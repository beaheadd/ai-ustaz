"""База знаний «Спросить AI Ustaz»: проверка записей (чистые функции), хэш содержания, номера аятов.

Владелец 20.11.2026: «Мы загрузим базу знаний, хадисы, Коран, тафсиры … Только с нашей базы данных, в интернете не будет
искать … чтобы достоверная информация была». Формат и порядок проверки — docs/база-знаний.md; таблицы — миграция 004.

Контракт:
  разобрать_запись(данные: dict) -> Запись         — проверка одной строки JSONL; ОшибкаЗаписи(текст) при нарушении
  разобрать_jsonl(текст) -> list[Запись]           — все строки; ОшибкаБазы со списком всех ошибок (ничего не грузим)
  хэш_записи(запись) -> str                        — sha256 содержания (вид, ссылка, источник, арабский, степень,
                                                     кто_оценил, тексты); статус и кто проверил в хэш не входят
  проверить_ссылку_корана(ссылка) -> bool          — «N:M» или «N:M-K» в пределах 114 сур и числа аятов
  есть_арабское(текст) -> bool                     — арабское письмо (U+0600–06FF, 0750–077F, 08A0–08FF, FB50–FDFF, FE70–FEFF)
Жёсткие правила (CLAUDE.md):
  1 — текст Корана в базе не храним: у вида «коран» только ссылка «сура:аят» и перевод смыслов с изданием; арабского
      письма нет ни в одном заголовке и тексте (Коран показывает приложение из проверенной копии Tanzil);
  2 — хадис только со сборником, номером, степенью достоверности и тем, кто её дал; арабский — дословно из базы;
  11 — статус «черновик» до проверки устазом; «утверждено» — только с «кто_проверил» и датой; публикация — версия и хэш.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from datetime import date

ВИДЫ = ('коран', 'хадис', 'тафсир', 'статья', 'справка')
ЯЗЫКИ = ('ru', 'kk', 'uz', 'en')  # en — с 20.11.2026 (миграция 006: тексты en — в kb_texts_en)
СТАТУСЫ = ('черновик', 'утверждено')
ПОЛЯ = frozenset({'id', 'вид', 'тексты', 'ссылка', 'источник', 'арабский', 'сборник', 'номер', 'степень', 'кто_оценил',
                  'статус', 'кто_проверил', 'когда', 'версия'})

# Число аятов в каждой из 114 сур (Tanzil Uthmani v1.1; сверено с app/public/quran/index.*.json — тест test_kb.py), всего 6236.
АЯТЫ_СУР = (
    7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110, 98, 135, 112, 78, 118, 64, 77, 227,
    93, 88, 69, 60, 34, 30, 73, 54, 45, 83, 182, 88, 75, 85, 54, 53, 89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96,
    29, 22, 24, 13, 14, 11, 11, 18, 12, 12, 30, 52, 52, 44, 28, 28, 20, 56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17,
    19, 26, 30, 20, 15, 21, 11, 8, 8, 19, 5, 8, 8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
)
assert len(АЯТЫ_СУР) == 114 and sum(АЯТЫ_СУР) == 6236

АРАБСКОЕ = re.compile('[؀-ۿݐ-ݿࢠ-ࣿﭐ-﷿ﹰ-﻿]')
_ID = re.compile(r'^[a-z0-9][a-z0-9._-]{1,79}$')
_ССЫЛКА_КОРАНА = re.compile(r'^(\d{1,3}):(\d{1,3})(?:-(\d{1,3}))?$')
_ДАТА = re.compile(r'^\d{4}-\d{2}-\d{2}$')
МАКС_ЗАГОЛОВОК = 200
МАКС_ТЕКСТ = 8000


class ОшибкаЗаписи(ValueError):
    pass


class ОшибкаБазы(ValueError):
    def __init__(self, ошибки: list[str]) -> None:
        super().__init__('; '.join(ошибки))
        self.ошибки = ошибки


@dataclass(frozen=True)
class Запись:
    id: str
    вид: str
    тексты: dict  # {'ru': {'заголовок', 'текст'}, 'kk': …}
    ссылка: str | None
    источник: str
    арабский: str | None
    степень: str | None
    кто_оценил: str | None
    статус: str
    кто_проверил: str | None
    когда: str | None
    версия: int
    sha: str = field(default='')


def есть_арабское(текст: str | None) -> bool:
    return bool(текст) and bool(АРАБСКОЕ.search(текст))


def проверить_ссылку_корана(ссылка: object) -> bool:
    if not isinstance(ссылка, str):
        return False
    м = _ССЫЛКА_КОРАНА.match(ссылка.strip())
    if not м:
        return False
    сура, аят = int(м.group(1)), int(м.group(2))
    if not 1 <= сура <= 114 or not 1 <= аят <= АЯТЫ_СУР[сура - 1]:
        return False
    if м.group(3) is not None:
        конец = int(м.group(3))
        return аят < конец <= АЯТЫ_СУР[сура - 1]
    return True


def _строка(данные: dict, ключ: str, *, нужно: bool, макс: int = 300) -> str | None:
    з = данные.get(ключ)
    if з is None or (isinstance(з, str) and not з.strip()):
        if нужно:
            raise ОшибкаЗаписи(f'нет поля «{ключ}»')
        return None
    if not isinstance(з, str):
        raise ОшибкаЗаписи(f'«{ключ}» — не строка')
    з = з.strip()
    if len(з) > макс:
        raise ОшибкаЗаписи(f'«{ключ}» длиннее {макс} символов')
    return з


def хэш_записи(з: Запись) -> str:
    содержание = {'вид': з.вид, 'ссылка': з.ссылка, 'источник': з.источник, 'арабский': з.арабский, 'степень': з.степень,
                  'кто_оценил': з.кто_оценил, 'тексты': з.тексты}
    сырое = json.dumps(содержание, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(сырое.encode('utf-8')).hexdigest()


def разобрать_запись(данные: object) -> Запись:
    if not isinstance(данные, dict):
        raise ОшибкаЗаписи('строка — не объект JSON')
    лишние = set(данные) - ПОЛЯ
    if лишние:
        raise ОшибкаЗаписи('лишние поля: ' + ', '.join(sorted(лишние)))
    ид = данные.get('id')
    if not isinstance(ид, str) or not _ID.match(ид):
        raise ОшибкаЗаписи('id — латиница, цифры, «.-_», 2–80 символов')
    вид = данные.get('вид')
    if вид not in ВИДЫ:
        raise ОшибкаЗаписи('вид — один из: ' + ', '.join(ВИДЫ))

    тексты_сырые = данные.get('тексты')
    if not isinstance(тексты_сырые, dict) or 'ru' not in тексты_сырые:
        raise ОшибкаЗаписи('нет «тексты» с языком ru')
    тексты: dict = {}
    for язык, т in тексты_сырые.items():
        if язык not in ЯЗЫКИ:
            raise ОшибкаЗаписи(f'язык «{язык}» — не из ru, kk, uz, en')
        if not isinstance(т, dict) or set(т) - {'заголовок', 'текст'}:
            raise ОшибкаЗаписи(f'тексты.{язык} — только {{заголовок, текст}}')
        заголовок = _строка(т, 'заголовок', нужно=True, макс=МАКС_ЗАГОЛОВОК)
        текст = _строка(т, 'текст', нужно=вид != 'коран', макс=МАКС_ТЕКСТ) or ''
        if есть_арабское(заголовок) or есть_арабское(текст):
            # правило 1: арабский текст (аяты) в заголовках и текстах не храним; у хадиса арабский — в поле «арабский»
            raise ОшибкаЗаписи(f'тексты.{язык}: арабское письмо в заголовке или тексте (Коран не храним, правило 1)')
        тексты[язык] = {'заголовок': заголовок, 'текст': текст}

    источник = _строка(данные, 'источник', нужно=True)
    арабский = _строка(данные, 'арабский', нужно=False, макс=МАКС_ТЕКСТ)
    if арабский is not None and вид != 'хадис':
        raise ОшибкаЗаписи(f'«арабский» у вида «{вид}» не храним (правило 1: аят показывает приложение из Tanzil)')
    if арабский is not None and not есть_арабское(арабский):
        raise ОшибкаЗаписи('«арабский» без арабского письма')
    ссылка = _строка(данные, 'ссылка', нужно=False, макс=120)
    сборник = _строка(данные, 'сборник', нужно=вид == 'хадис', макс=100)
    номер = _строка(данные, 'номер', нужно=вид == 'хадис', макс=20)
    степень = _строка(данные, 'степень', нужно=вид == 'хадис', макс=100)
    кто_оценил = _строка(данные, 'кто_оценил', нужно=вид == 'хадис', макс=200)
    if вид == 'хадис':
        if not re.search(r'\d', номер or ''):
            raise ОшибкаЗаписи('номер хадиса — с цифрой')
        ожидаемая = f'{сборник}, {номер}'
        if ссылка is not None and ссылка != ожидаемая:
            raise ОшибкаЗаписи(f'ссылка хадиса — «{ожидаемая}» (сборник, номер) или пусто')
        ссылка = ожидаемая
    else:
        for ключ, з in (('сборник', сборник), ('номер', номер), ('степень', степень), ('кто_оценил', кто_оценил)):
            if з is not None:
                raise ОшибкаЗаписи(f'«{ключ}» — только у хадиса')
    if вид in ('коран', 'тафсир') and not проверить_ссылку_корана(ссылка):
        raise ОшибкаЗаписи('ссылка — «сура:аят» или «сура:аят-аят» в пределах 114 сур и числа аятов')

    статус = данные.get('статус')
    if статус not in СТАТУСЫ:
        raise ОшибкаЗаписи('статус — «черновик» или «утверждено»')
    кто_проверил = _строка(данные, 'кто_проверил', нужно=статус == 'утверждено', макс=200)
    когда = _строка(данные, 'когда', нужно=статус == 'утверждено', макс=10)
    if когда is not None:
        if not _ДАТА.match(когда):
            raise ОшибкаЗаписи('«когда» — ГГГГ-ММ-ДД')
        try:
            date.fromisoformat(когда)
        except ValueError as е:
            raise ОшибкаЗаписи('«когда» — несуществующая дата') from е
    версия = данные.get('версия')
    if not isinstance(версия, int) or isinstance(версия, bool) or not 1 <= версия <= 1_000_000:
        raise ОшибкаЗаписи('версия — целое ≥ 1')

    з = Запись(id=ид, вид=вид, тексты=тексты, ссылка=ссылка, источник=источник, арабский=арабский, степень=степень,
               кто_оценил=кто_оценил, статус=статус, кто_проверил=кто_проверил, когда=когда, версия=версия)
    return Запись(**{**з.__dict__, 'sha': хэш_записи(з)})


def разобрать_jsonl(текст: str) -> list[Запись]:
    записи: list[Запись] = []
    ошибки: list[str] = []
    видели: set[str] = set()
    for номер, строка in enumerate(текст.splitlines(), 1):
        if not строка.strip():
            continue
        try:
            данные = json.loads(строка)
        except ValueError:
            ошибки.append(f'строка {номер}: не JSON')
            continue
        ид = данные.get('id') if isinstance(данные, dict) else None
        try:
            з = разобрать_запись(данные)
        except ОшибкаЗаписи as е:
            ошибки.append(f'строка {номер} ({ид or "?"}): {е}')
            continue
        if з.id in видели:
            ошибки.append(f'строка {номер} ({з.id}): id повторяется')
            continue
        видели.add(з.id)
        записи.append(з)
    if not записи and not ошибки:
        ошибки.append('файл пуст')
    if ошибки:
        raise ОшибкаБазы(ошибки)
    return записи
