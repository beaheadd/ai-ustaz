"""Ссылки на аяты в вопросах чата и сопоставление распознанного с фото арабского текста с нашей копией Tanzil.

Владелец 27.11.2026: «как читается такой-то аят» — чат AI Ustaz; фото страницы мусхафа → «Это сура X, аят Y».
Данные — server/quran_ref.json (собирает tools/kb/build_server_quran.py из копии «показ» Tanzil Uthmani v1.1): имена сур
и «скелет» аятов (буквы без огласовок) — техническая производная. Текст Корана отсюда НИКУДА не отдаём: наружу уходит
только ссылка «сура:аят», аят показывает приложение из своей проверенной копии (CLAUDE.md, правило 1).

Контракт (чистые функции; данные грузятся один раз, лениво):
  ссылка_из_вопроса(вопрос: str) -> str | None
      «2:255», «сура 2 аят 255», «аят аль-Курси», «сура Ихлас», «сура аль-Фатиха аят 5», «Ikhlas surah», «Ихлас сүресі».
      Сура без номера аята → «N:1-K» (K = все аяты, если их ≤ 11, иначе «N:1»). Имя суры без слова «сура» понимаем только
      у «Фатиха» и «аят аль-Курси» (иначе «что такое ихлас» стало бы сурой 112).
  скелет(текст) -> str — как в сборке (огласовки прочь, формы алифа и хамзы — к основе).
  сопоставить(арабский_текст) -> {'ссылка': 'N:M' | 'N:M-K', 'доля': float} | None — по триграммам букв: лучший аят (или два-
      три подряд) с долей совпавших триграмм ≥ ПОРОГ_СОВПАДЕНИЯ и отрывом от второго места; иначе None («не уверен — не
      говорим»: правило 7).
"""
from __future__ import annotations

import json
import pathlib
import re
import threading

ПУТЬ = pathlib.Path(__file__).resolve().parent / 'quran_ref.json'
ПОРОГ_СОВПАДЕНИЯ = 0.55
ОТРЫВ = 0.08
МИН_БУКВ = 12

ЗНАКИ = re.compile('[ؐ-ًؚ-ٟۖ-ۭـ]')
ЗАМЕНЫ = str.maketrans({'ٱ': 'ا', 'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ى': 'ي', 'ی': 'ي', 'ة': 'ه', 'ؤ': 'و', 'ئ': 'ي',
                        'ک': 'ك', 'ء': '', 'ٰ': 'ا'})

_замок = threading.Lock()
_данные: dict | None = None
_триграммы: dict[str, frozenset] | None = None
_порядок: list[str] = []


def скелет(текст: str) -> str:
    т = ЗНАКИ.sub('', текст or '').translate(ЗАМЕНЫ)
    т = re.sub(r'[^ء-ي\s]', ' ', т)
    return re.sub(r'\s+', ' ', т).strip()


def _загрузить() -> dict:
    global _данные, _триграммы, _порядок
    with _замок:
        if _данные is None:
            _данные = json.loads(ПУТЬ.read_text(encoding='utf-8'))
            _порядок = list(_данные['скелет'])
            _триграммы = {к: _триграммы_текста(в) for к, в in _данные['скелет'].items()}
    return _данные


def _триграммы_текста(т: str) -> frozenset:
    с = т.replace(' ', '')
    return frozenset(с[i:i + 3] for i in range(max(0, len(с) - 2)))


# ───────────── ссылки в вопросе ─────────────
def _имя(т: str) -> str:
    т = т.lower().replace('ё', 'е')
    т = re.sub(r"['’‘ʻʼ`]", '', т)
    return т


БЕЗ_СЛОВА_СУРА = frozenset({'фатиха', 'fatiha', 'fatihah', 'faatiha', 'fotiha'})
_СЛОВО_СУРА = r'(?:сур[аеыуой]\w*|сүре\w*|surah?|sura\w*|surasi|сураси)'
_КУРСИ = re.compile(r'\b(?:аят\w*|ayat\w*|ayah|oyat\w*)[\s-]*(?:(?:аль|ал|ul|al|ul)[\s-]*)?(?:курси|күрси|kursi|kursiy)\b')
_ЧИСЛО_АЯТА = re.compile(r'^\W{0,3}(?:(?:аят\w*|ayat\w*|ayah|verse|oyat\w*)\s*(?:№\s*)?)?[:,]?\s*(\d{1,3})\b')
_ССЫЛКА_N_M = re.compile(r'\b(\d{1,3})\s*[:：]\s*(\d{1,3})\b')


def _вся_сура(н: int, аятов: int) -> str:
    return f'{н}:1-{аятов}' if аятов <= 11 else f'{н}:1'


def ссылка_из_вопроса(вопрос: str) -> str | None:
    т = _имя(вопрос)
    if _КУРСИ.search(т):
        return '2:255'
    данные = _загрузить()
    суры = данные['суры']
    м = _ССЫЛКА_N_M.search(т)
    if м:
        н, а = int(м.group(1)), int(м.group(2))
        if 1 <= н <= 114 and 1 <= а <= суры[н - 1]['аятов']:
            return f'{н}:{а}'
    # имя суры: «сура <имя>» / «<имя> сүресі» / «surah <name>»; для «Фатиха» слово «сура» не нужно
    лучшее: tuple[int, int, int] | None = None  # (длина имени, номер суры, конец совпадения)
    for с in суры:
        for и in с['имена']:
            образец = re.escape(и).replace(r'\ ', r'[\s-]*')
            if и.endswith('а') and len(и) >= 5:
                образец = образец[:-1] + '[аыуеиой]'  # падежи: «Фатиху», «Фатихи»
            for мм in re.finditer(r'(?<![\w])(?:(?:аль|ал|ас|аш|ан|ат|ад|ар|аз|al|an|as|ash|at|ad|ar|az)[\s-]*)?' + образец + r'(?![\w])', т):
                рядом = т[max(0, мм.start() - 20):мм.end() + 20]
                if not re.search(_СЛОВО_СУРА, рядом) and и not in БЕЗ_СЛОВА_СУРА:
                    continue
                if лучшее is None or len(и) > лучшее[0]:
                    лучшее = (len(и), с['n'], мм.end())
    if лучшее is None:
        м = re.search(_СЛОВО_СУРА + r'\s*(?:№\s*)?(\d{1,3})\b', т) or re.search(r'\b(\d{1,3})[\s-]*(?:я|й|ая|ші|шы|inchi)?\s*' + _СЛОВО_СУРА, т)
        if not м:
            return None
        н = int(м.group(1))
        if not 1 <= н <= 114:
            return None
        лучшее = (0, н, м.end())
    _, н, конец = лучшее
    аятов = суры[н - 1]['аятов']
    хвост = re.sub(_СЛОВО_СУРА, ' ', т[конец:])
    м = _ЧИСЛО_АЯТА.search(хвост) or re.search(r'\b(\d{1,3})\s*-?\s*(?:аят\w*|oyat\w*|ayat\w*)', т)
    if м and 1 <= int(м.group(1)) <= аятов:
        return f'{н}:{int(м.group(1))}'
    м = re.search(r'(?:аят\w*|ayat\w*|ayah|verse|oyat\w*)\s*(?:№\s*)?(\d{1,3})', т)
    if м and 1 <= int(м.group(1)) <= аятов:
        return f'{н}:{int(м.group(1))}'
    return _вся_сура(н, аятов)


# ───────────── фото: распознанный арабский → аят ─────────────
def сопоставить(арабский: str) -> dict | None:
    с = скелет(арабский)
    if len(с.replace(' ', '')) < МИН_БУКВ:
        return None
    _загрузить()
    assert _триграммы is not None
    нужно = _триграммы_текста(с)
    if not нужно:
        return None
    # окно — 1–3 аята подряд одной суры; оценка — F1: доля триграмм фото в окне × доля окна на фото
    оценки: list[tuple[float, str, int]] = []
    for и, к in enumerate(_порядок):
        окно: frozenset = frozenset()
        сура = к.split(':')[0]
        for шаг in range(3):
            if и + шаг >= len(_порядок) or _порядок[и + шаг].split(':')[0] != сура:
                break
            окно = окно | _триграммы[_порядок[и + шаг]]
            общих = len(нужно & окно)
            if not общих:
                break
            точность, полнота = общих / len(нужно), общих / len(окно)
            оценки.append((2 * точность * полнота / (точность + полнота), к, шаг))
    if not оценки:
        return None
    оценки.sort(key=lambda о: (-о[0], о[2]))
    лучшая, ключ, шаг = оценки[0]
    сура, аят = map(int, ключ.split(':'))
    вторая = next((о[0] for о in оценки[1:] if о[1].split(':')[0] != str(сура) or abs(int(о[1].split(':')[1]) - аят) > 2), 0.0)
    if лучшая < ПОРОГ_СОВПАДЕНИЯ or лучшая - вторая < ОТРЫВ:
        return None
    return {'ссылка': f'{сура}:{аят}' + (f'-{аят + шаг}' if шаг else ''), 'доля': round(лучшая, 3)}
