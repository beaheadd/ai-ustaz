def test_о_чём_здесь_говорит_аллах_после_аята():
    """Случай владельца: «Как читается аят 2:255?» → «О чем здесь говорит Аллах?» дал хадис про «Амин»."""
    к, б = клиент()
    д = спросить_с(к, 'О чем здесь говорит Аллах?', {'вид': 'аят', 'сура': 2, 'аят': 255})
    assert д['намерение'] == 'тафсир' and all(и['вид'] in ('тафсир', 'коран') for и in д['источники'])
    assert not any(и['вид'] == 'хадис' for и in д['источники'])
    д = спросить_с(к, 'О чем здесь говорит Аллах?', {'вид': 'аят', 'сура': 3, 'аят': 7})
    assert д['намерение'] == 'тафсир' and [и['ссылка'] for и in д['источники']] == ['3:7']
    assert д['текст'].startswith('Толкования (тафсира) AI Ustaz не даёт') and 'перевод смыслов' in д['текст']
    # без контекста — тоже не хадис: честный шаблон без ссылки
    д = спросить_с(к, 'О чем здесь говорит Аллах?')
    assert д['намерение'] == 'тафсир' and д['источники'] == []
    for вопрос in ('Что означает этот аят?', 'Смысл этого аята', 'Переведи это', 'Бұл аят не туралы?', "Bu oyat nima haqida?",
                   'What does this ayah mean?'):
        assert спросить_с(к, вопрос, {'вид': 'аят', 'сура': 3, 'аят': 7})['намерение'] == 'тафсир', вопрос
    assert б.не_нашли == 0


