def test_ии_ответ_проходит_валидатор():
    ии = ПодставнойИИ({'вид': 'ответ', 'текст': 'Закят платят с имущества сверх нисаба после года; доля — 1/40.',
                       'источники': ['zakat-nisab']})
    к, б = клиент(ии=ии)
    д = спросить(к, 'Меня зовут Айгуль, почта a@b.kz. Сколько закята с 1000000 тенге и какой нисаб?').json()
    assert д['вид'] == 'ответ' and д['режим'] == 'ии' and [и['id'] for и in д['источники']] == ['zakat-nisab']
    assert д['текст'].startswith('Закят платят')
    вопрос, язык, записи = ии.вызовы[0]
    assert 'Айгуль' not in вопрос and 'a@b.kz' not in вопрос and '1000000' in вопрос and язык == 'ru'
    assert all(set(з) == {'id', 'вид', 'заголовок', 'ссылка', 'текст'} for з in записи)   # ни арабского, ни черновиков
    assert б.ask_журнал[-1] == ('ответ', 'ии', None, 1)


