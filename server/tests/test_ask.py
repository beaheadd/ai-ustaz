class ПодставнаяБаза(ПодставноеХранилище):
    def __init__(self, записи=None) -> None:
        super().__init__()
        self.записи = list(БАЗА if записи is None else записи)
        self.ask_журнал: list[tuple] = []
        self.не_нашли = 0
        self.сломана = False

    def _выдача(self, з, язык):
        т = з['тексты'].get(язык) or з['тексты']['ru']
        поля = {к: в for к, в in з.items() if к != 'тексты'}
        return {**поля, 'заголовок': т['заголовок'], 'текст': т['текст']}

    def _видны(self, черновые):
        if self.сломана:
            raise RuntimeError('база недоступна')
        return [з for з in self.записи if черновые or not з['черновик']]

    def kb_число(self, черновые):
        return len(self._видны(черновые))

    def kb_найти(self, термы, язык, черновые, предел=5):
        итог = []
        for з in self._видны(черновые):
            в = self._выдача(з, язык)
            текст = ask.нормализовать(в['заголовок'] + ' ' + в['текст'])
            совпало = sum(1 for т in термы if т.removesuffix(':*')[:5] in текст)
            if совпало:
                итог.append({**в, 'совпало': совпало, 'всего': len(термы)})
        return sorted(итог, key=lambda з: -з['совпало'])[:предел]

    def kb_по_ссылке(self, вид, ссылка, язык, черновые, предел=3):
        return [self._выдача(з, язык) for з in self._видны(черновые) if з['вид'] == вид and з['ссылка'] == ссылка][:предел]

    def ask_записать(self, вид, режим, причина, источников):
        self.ask_журнал.append((вид, режим, причина, источников))

    def ask_не_нашли(self, сейчас):
        self.не_нашли += 1


class ПодставнойИИ:
    def __init__(self, ответ=None, причина=None) -> None:
        self.ответ, self.причина, self.вызовы = ответ, причина, []

    def __call__(self, вопрос, язык, записи):
        self.вызовы.append((вопрос, язык, ask.записи_для_ии(записи)))
        return (self.ответ(записи) if callable(self.ответ) else self.ответ), self.причина


def клиент(база=None, ии=None, черновые=True, часы=None):
    app = FastAPI()
    б = база if база is not None else ПодставнаяБаза()
    время = часы or {'t': СЕЙЧАС / 1000}
    ask.register(app, хранилище=б, ключ_лимита=lambda з: 'ip:test', ии=ии, черновые=черновые, часы=lambda: время['t'])
    return TestClient(app), б


def спросить(к, q, lang='ru', **заголовки):
    return к.post('/api/ask/v1', json={'q': q, 'lang': lang}, headers=заголовки)


