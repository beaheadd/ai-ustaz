def test_лимит_сутки_по_алматы():
    часы = {'t': СЕЙЧАС / 1000}            # 20.11.2026 09:00 Алматы
    к, _ = клиент(часы=часы)
    for i in range(100):
        часы['t'] = СЕЙЧАС / 1000 + i * 60  # каждую минуту — минутный лимит не мешает
        assert спросить(к, 'Что такое закят?').status_code == 200
    часы['t'] = СЕЙЧАС / 1000 + 100 * 60
    assert спросить(к, 'Что такое закят?').json() == {'ошибка': 'rate'}
    часы['t'] = СЕЙЧАС / 1000 + 14 * 3600 + 60  # 23:01 Алматы — те же сутки
    assert спросить(к, 'Что такое закят?').status_code == 429
    часы['t'] = СЕЙЧАС / 1000 + 15 * 3600 + 60  # 00:01 Алматы 21.11 — новые сутки
    assert спросить(к, 'Что такое закят?').status_code == 200


