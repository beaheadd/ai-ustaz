    return {'id': ид, 'вид': вид, 'тексты': тексты, 'ссылка': поля.get('ссылка'), 'арабский': поля.get('арабский'),
            'источник': поля.get('источник', 'Издание'), 'степень': поля.get('степень'), 'кто_оценил': поля.get('кто_оценил'),
            'черновик': поля.get('черновик', True), 'версия': поля.get('версия', '1.0123abcd')}


