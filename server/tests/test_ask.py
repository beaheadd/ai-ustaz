    assert к.post('/api/ask/v1', content=b'{"q": "' + b'a' * 9000 + b'"}', headers={'content-type': 'application/json'}).status_code == 413
    assert к.post('/api/ask/v1', content=b'not json').json() == {'ошибка': 'question'}
    р = спросить(к, 'Что такое закят?', origin='https://evil.example')
    assert р.status_code == 403 and р.json() == {'ошибка': 'origin'}
    assert спросить(к, 'Что такое закят?', origin='https://aiustaz.pro').status_code == 200
    пустой, _ = клиент(ПодставнаяБаза([]))
    assert спросить(пустой, 'Что такое закят?').json() == {'ошибка': 'kb'}
    б.сломана = True
    р = спросить(к, 'Что такое закят?')
    assert р.status_code == 503 and р.json() == {'ошибка': 'kb'}


