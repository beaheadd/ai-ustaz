def test_клиент_ии_запрос_и_ошибки():
    anthropic = pytest.importorskip('anthropic')
    httpx2 = pytest.importorskip('httpx2')
    ии = ask.КлиентИИ('sk-test-не-настоящий')
    запросы = []
    ответ = {'v': None}

    def создать(**параметры):
        запросы.append(параметры)
        if isinstance(ответ['v'], Exception):
            raise ответ['v']
        return ответ['v']

    ии._клиент = types.SimpleNamespace(beta=types.SimpleNamespace(messages=types.SimpleNamespace(create=создать)))
    блок = types.SimpleNamespace(type='text', text=json.dumps({'вид': 'ответ', 'текст': 'т', 'источники': ['zakat-nisab']}))
    ответ['v'] = types.SimpleNamespace(stop_reason='end_turn', content=[types.SimpleNamespace(type='thinking'), блок])
    данные, причина = ии('Сколько закята?', 'ru', [dict(НАЙДЕНО[0], арабский='x', черновик=True)])
    assert причина is None and данные['источники'] == ['zakat-nisab']
    п = запросы[0]
    assert п['model'] == 'claude-opus-5-5' and 'thinking' not in п and 'tool_choice' not in п
    assert п['output_config']['effort'] == 'low' and п['output_config']['format']['schema'] == ask.СХЕМА_ОТВЕТА
    assert п['betas'] == ['server-side-fallback-2026-07-01'] and п['fallbacks'] == 'default'
    assert п['messages'][-1]['role'] == 'user' and п['system'][0]['text'] == ask.СИСТЕМНЫЙ_ПРОМПТ
    отправлено = json.loads(п['messages'][0]['content'])
    assert set(отправлено) == {'язык', 'записи', 'вопрос'} and 'арабский' not in отправлено['записи'][0]

    ответ['v'] = types.SimpleNamespace(stop_reason='refusal', content=[])
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_refusal')
    ответ['v'] = types.SimpleNamespace(stop_reason='end_turn', content=[types.SimpleNamespace(type='text', text='не json')])
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_json')
    запрос = httpx2.Request('POST', 'https://api.anthropic.com/v1/messages')
    ответ['v'] = anthropic.RateLimitError('rate', response=httpx2.Response(429, request=запрос), body=None)
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_rate')
    ответ['v'] = anthropic.InternalServerError('x', response=httpx2.Response(500, request=запрос), body=None)
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_http_500')
    ответ['v'] = anthropic.APITimeoutError(request=запрос)
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_timeout')
    ответ['v'] = anthropic.APIConnectionError(request=запрос)
    assert ии('в', 'ru', НАЙДЕНО) == (None, 'llm_net')


