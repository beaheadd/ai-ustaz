    (хороший(), None),
    (хороший(текст='Как сказано в базе: «Закят выплачивают с имущества сверх нисаба, прошедшего год».'), None),
    ({'вид': 'нет-в-базе', 'текст': '', 'источники': []}, None),
    (хороший(текст='Сказано: «Закят обязателен для каждого, у кого есть машина и дом».'), 'quote'),   # выдуманная цитата
    (хороший(текст='Сказано: "Пророк говорил платить закят с каждой машины ежемесячно".'), 'quote'),
    (хороший(текст='Закят — это زكاة, доля 1/40.'), 'arabic'),
    (хороший(текст='Аят: ﷽'), 'arabic'),
    (хороший(источники=['zakat-nisab', 'hadith-fake-1']), 'foreign_id'),
    (хороший(источники=[]), 'no_source'),
    (хороший(текст='Ваш намаз недействителен, перечитайте.'), 'fatwa'),
    (хороший(текст='Вы обязаны заплатить закят с машины.'), 'fatwa'),
    (хороший(текст='Намазыңыз жарамсыз.'), 'fatwa'),
    (хороший(текст='Namozingiz haqiqiy emas.'), 'fatwa'),
