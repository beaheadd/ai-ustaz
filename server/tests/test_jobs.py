"""Цикл отправки (server/jobs.py) на подставном хранилище: наступившие, опоздание, 410, напоминание обновить, без повторов."""
from __future__ import annotations

import jobs
import push
from conftest import АДРЕС_FCM, СЕЙЧАС, момент, пункт, тело

МИН = 60_000


def подписать(хранилище, пункты, адрес=АДРЕС_FCM, язык='ru', далеко=True):
    # далеко — последний пункт расписания через 25 дней (как у настоящего клиента): «обновите время» не нужно
    пункты = пункты + ([пункт('2026-12-15', '14:39')] if далеко else [])
    з = push.разобрать_подписку(тело(пункты, адрес=адрес, язык=язык), СЕЙЧАС)
    хранилище.сохранить(з, СЕЙЧАС)
    return з


def отправитель(код=201):
    журнал = []

    def отправить(подписка, данные, ttl, срочность):
        журнал.append((подписка['хэш'], данные, ttl, срочность))
        return код(данные) if callable(код) else код

    return отправить, журнал


def test_отправляет_наступившее_один_раз(хранилище):
    подписать(хранилище, [пункт('2026-11-20', '14:39'), пункт('2026-11-20', '14:39', заранее=10), пункт('2026-11-20', '16:28', 'maghrib', след=('isha', '17:59'))])
    отправить, журнал = отправитель()
    assert jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:28'), потоков=1)['отправлено'] == 0
    счёт = jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:29'), потоков=1)
    assert счёт['отправлено'] == 1 and журнал[-1][1]['title'] == 'Через 10 мин — Аср (14:39)' and журнал[-1][2] == 600
    счёт = jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:39') + 20_000, потоков=1)
    assert счёт['отправлено'] == 1 and журнал[-1][1]['title'] == 'Аср · 14:39' and журнал[-1][3] == 'high'
    # тот же момент ещё раз — уже взято, повтора нет
    assert jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:40'), потоков=1)['отправлено'] == 0
    assert len(журнал) == 2


def test_опоздание_больше_10_мин_не_шлём(хранилище):
    подписать(хранилище, [пункт('2026-11-20', '14:39')])
    отправить, журнал = отправитель()
    счёт = jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:50'), потоков=1)
    assert счёт['поздно'] == 1 and not журнал
    assert any(з[1] == 'late' for з in хранилище.журнал)


def test_410_удаляет_подписку_и_остальное_не_шлёт(хранилище):
    подписать(хранилище, [пункт('2026-11-20', '14:39'), пункт('2026-11-20', '14:39', заранее=5)])
    отправить, журнал = отправитель(410)
    счёт = jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:40'), потоков=1)
    assert счёт['удалено'] == 1 and len(журнал) == 1 and not хранилище.подписки


def test_ошибка_сервиса_не_удаляет(хранилище):
    подписать(хранилище, [пункт('2026-11-20', '14:39')])
    отправить, _ = отправитель(503)
    assert jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:39'), потоков=1)['ошибка'] == 1
    assert хранилище.подписки


def test_тихое_напоминание_обновить_один_раз(хранилище):
    подписать(хранилище, [пункт('2026-11-22', '14:39')], далеко=False)  # расписание кончается через 2 дня
    отправить, журнал = отправитель()
    счёт = jobs.шаг(хранилище, отправить, СЕЙЧАС, потоков=1)
    assert счёт['обновить'] == 1
    _, данные, ttl, срочность = журнал[0]
    assert данные['silent'] is True and данные['kind'] == 'refresh' and срочность == 'low' and ttl == 86_400
    assert jobs.шаг(хранилище, отправить, СЕЙЧАС + МИН, потоков=1)['обновить'] == 0
    # новое расписание (человек открыл приложение) — флаг сброшен, но до конца далеко: не шлём
    подписать(хранилище, [пункт('2026-12-15', '14:39')])
    assert jobs.шаг(хранилище, отправить, СЕЙЧАС + 2 * МИН, потоков=1)['обновить'] == 0


def test_много_подписок_параллельно(хранилище):
    for i in range(20):
        подписать(хранилище, [пункт('2026-11-20', '14:39')], адрес=f'https://fcm.googleapis.com/fcm/send/n{i:03d}', язык='kk' if i % 2 else 'ru')
    отправить, журнал = отправитель()
    assert jobs.шаг(хранилище, отправить, момент('2026-11-20', '14:39'), потоков=8)['отправлено'] == 20
    assert len({з[0] for з in журнал}) == 20
    assert {з[1]['title'] for з in журнал} == {'Аср · 14:39', 'Екінті · 14:39'}


