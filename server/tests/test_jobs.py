def test_настоящее_шифрование_и_vapid(monkeypatch):
    """Полный путь pywebpush без сети: запрос перехвачен, тело расшифровано ключом «браузера» (aes128gcm), VAPID подписан."""
    import base64
    import json

    import http_ece
    import requests
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec

    def b64(б):
        return base64.urlsafe_b64encode(б).decode().rstrip('=')

    vapid_ключ = ec.generate_private_key(ec.SECP256R1())
    приватный = b64(vapid_ключ.private_numbers().private_value.to_bytes(32, 'big'))
    браузер = ec.generate_private_key(ec.SECP256R1())
    p256dh = b64(браузер.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
    auth_байты = b'\x07' * 16
    перехват = {}

    class Ответ:
        status_code = 201
        reason = 'Created'
        headers: dict = {}
        text = ''

    def post(self, адрес, data=None, headers=None, timeout=None, **_):
        перехват.update(адрес=адрес, тело=data, заголовки=headers, таймаут=timeout)
        return Ответ()

    monkeypatch.setattr(requests.Session, 'post', post)
    отправить = jobs.создать_отправителя(приватный, 'https://aiustaz.pro')
    подписка = {'endpoint': АДРЕС_FCM, 'p256dh': p256dh, 'auth': b64(auth_байты)}
    данные = push.уведомление(push.Пункт(момент('2026-11-20', '14:39'), 'asr', '14:39', 0, 'maghrib', '16:28'), 'kk', 'Алматы')
    assert отправить(подписка, данные, 600, 'high') == 201
    з = перехват['заголовки']
    assert перехват['адрес'] == АДРЕС_FCM and з['ttl'] == '600' and з['Urgency'] == 'high' and з['content-encoding'] == 'aes128gcm'
    assert з['Authorization'].startswith('vapid t=') and ',k=' in з['Authorization']
    открыто = http_ece.decrypt(перехват['тело'], private_key=браузер, auth_secret=auth_байты, version='aes128gcm')
    assert json.loads(открыто) == данные and 'Екінті · 14:39' in открыто.decode()
