class ОшибкаЗапроса(ValueError):
    """Тело запроса не прошло проверку. код — короткая латиница для ответа 400 (без эха присланных данных)."""

    def __init__(self, код: str) -> None:
        super().__init__(код)
        self.код = код


@dataclass(frozen=True)
class Пункт:
    момент: int  # мс UTC, кратно минуте
    ключ: str
    время: str  # местное время намаза «14:39»
    заранее: int = 0  # 0 — в момент намаза; N — напоминание за N минут
    след_ключ: str | None = None
    след_время: str | None = None
    смещение: int = СМЕЩЕНИЕ_РК  # минуты к востоку от UTC: местное время места в момент намаза


@dataclass(frozen=True)
class Запрос:
    адрес: str
    p256dh: str
    auth: str
    язык: str
    город: str
    пункты: tuple[Пункт, ...] = field(default_factory=tuple)

    @property
    def хэш(self) -> str:
        return хэш_адреса(self.адрес)

    @property
    def конец(self) -> int:
        return max((п.момент for п in self.пункты), default=0)


# ───────────────────────── местное время места ─────────────────────────

def _местное(момент_мс: int, смещение: int = СМЕЩЕНИЕ_РК) -> datetime:
    return datetime.fromtimestamp(момент_мс / 1000, tz=timezone.utc) + timedelta(minutes=смещение)


def чч_мм(момент_мс: int, смещение: int = СМЕЩЕНИЕ_РК) -> str:
    return _местное(момент_мс, смещение).strftime('%H:%M')


def день_рк(момент_мс: int, смещение: int = СМЕЩЕНИЕ_РК) -> str:
    return _местное(момент_мс, смещение).strftime('%Y-%m-%d')


def пятница(момент_мс: int, смещение: int = СМЕЩЕНИЕ_РК) -> bool:
    return _местное(момент_мс, смещение).weekday() == 4


# ───────────────────────── проверка запроса ─────────────────────────

def хэш_адреса(адрес: str) -> str:
    return hashlib.sha256(адрес.encode('utf-8')).hexdigest()[:32]


def хост_разрешён(хост: str) -> bool:
    х = (хост or '').lower().rstrip('.')
    return х in ХОСТЫ_ТОЧНО or bool(ХОСТ_WINDOWS.match(х))


def _адрес(значение: object) -> str:
    if not isinstance(значение, str) or not (10 <= len(значение) <= МАКС_ДЛИНА_АДРЕСА):
        raise ОшибкаЗапроса('endpoint')
    if УПРАВЛЯЮЩИЕ.search(значение) or ' ' in значение:
        raise ОшибкаЗапроса('endpoint')
    try:
        ч = urlsplit(значение)
        порт = ч.port
    except ValueError as е:
        raise ОшибкаЗапроса('endpoint') from е
    if ч.scheme != 'https' or ч.username or ч.password or порт not in (None, 443) or not хост_разрешён(ч.hostname or ''):
        raise ОшибкаЗапроса('endpoint')
    if ч.fragment:
        raise ОшибкаЗапроса('endpoint')
    return значение


def _b64(значение: object, длина: int, код: str) -> str:
    if not isinstance(значение, str) or len(значение) > 200 or not B64URL.match(значение):
        raise ОшибкаЗапроса(код)
    try:
        сырое = base64.urlsafe_b64decode(значение.rstrip('=') + '=' * (-len(значение.rstrip('=')) % 4))
    except (binascii.Error, ValueError) as е:
        raise ОшибкаЗапроса(код) from е
    if len(сырое) != длина:
        raise ОшибкаЗапроса(код)
    if код == 'p256dh' and сырое[0] != 4:  # несжатая точка P-256
        raise ОшибкаЗапроса(код)
    return значение


def _город(значение: object) -> str:
    if not isinstance(значение, str):
        raise ОшибкаЗапроса('city')
    г = УПРАВЛЯЮЩИЕ.sub('', значение).strip()
    if not (1 <= len(г) <= МАКС_ДЛИНА_ГОРОДА) or any(с in г for с in '<>{}\\'):
        raise ОшибкаЗапроса('city')
    return г


def разобрать_адрес(тело: object) -> str:
    if not isinstance(тело, dict):
        raise ОшибкаЗапроса('body')
    return _адрес(тело.get('endpoint'))


def _пункт(сырой: object) -> Пункт:
    if not isinstance(сырой, dict) or set(сырой) - {'at', 'key', 'time', 'before', 'next', 'off'}:
        raise ОшибкаЗапроса('item')
    момент, ключ, время, заранее = сырой.get('at'), сырой.get('key'), сырой.get('time'), сырой.get('before', 0)
    смещение = сырой.get('off', СМЕЩЕНИЕ_РК)
    if (isinstance(смещение, bool) or not isinstance(смещение, int) or смещение % 15
            or not СМЕЩЕНИЕ_МИН <= смещение <= СМЕЩЕНИЕ_МАКС):
        raise ОшибкаЗапроса('item.off')
    if isinstance(момент, bool) or not isinstance(момент, int) or момент % МИНУТА_МС:
        raise ОшибкаЗапроса('item.at')
    if ключ not in КЛЮЧИ:
        raise ОшибкаЗапроса('item.key')
    if isinstance(заранее, bool) or заранее not in ЗАРАНЕЕ:
        raise ОшибкаЗапроса('item.before')
    if not isinstance(время, str) or not ЧЧ_ММ.match(время) or время != чч_мм(момент + заранее * МИНУТА_МС, смещение):
        raise ОшибкаЗапроса('item.time')
    след_ключ = след_время = None
    след = сырой.get('next')
    if след is not None:
        if not isinstance(след, dict) or set(след) - {'key', 'time'}:
            raise ОшибкаЗапроса('item.next')
        след_ключ, след_время = след.get('key'), след.get('time')
        if след_ключ not in НАМАЗЫ or not isinstance(след_время, str) or not ЧЧ_ММ.match(след_время):
            raise ОшибкаЗапроса('item.next')
    return Пункт(момент, ключ, время, заранее, след_ключ, след_время, смещение)


def разобрать_подписку(тело: object, сейчас_мс: int) -> Запрос:
    """Проверка тела подписки. Прошедшие пункты (часы телефона, сеть) молча отбрасываются; дальше 31 дня — ошибка."""
    if not isinstance(тело, dict):
        raise ОшибкаЗапроса('body')
    if set(тело) - ПОЛЯ_ЗАПРОСА:
        raise ОшибкаЗапроса('fields')  # лишнего (координаты, имя, телефон…) не принимаем и не храним
    подписка = тело.get('subscription')
    if not isinstance(подписка, dict) or set(подписка) - ПОЛЯ_ПОДПИСКИ:
        raise ОшибкаЗапроса('subscription')
    ключи = подписка.get('keys')
    if not isinstance(ключи, dict):
        raise ОшибкаЗапроса('keys')
    адрес = _адрес(подписка.get('endpoint'))
    p256dh = _b64(ключи.get('p256dh'), 65, 'p256dh')
    auth = _b64(ключи.get('auth'), 16, 'auth')
    язык = тело.get('lang')
    if язык not in ЯЗЫКИ:
        raise ОшибкаЗапроса('lang')
    город = _город(тело.get('city'))
    сырые = тело.get('items')
    if not isinstance(сырые, list) or len(сырые) > МАКС_ПУНКТОВ:
        raise ОшибкаЗапроса('items')
    пункты: dict[tuple[int, str, int], Пункт] = {}
    в_сутки: dict[str, int] = {}
    предел = сейчас_мс + МАКС_ДНЕЙ * ДЕНЬ_МС
    for сырой in сырые:
        п = _пункт(сырой)
        if п.момент > предел:
            raise ОшибкаЗапроса('items.range')
        if п.момент <= сейчас_мс:
            continue
        ключ = (п.момент, п.ключ, п.заранее)
        if ключ in пункты:
            continue  # повтор — один раз
        день = день_рк(п.момент + п.заранее * МИНУТА_МС, п.смещение)
        в_сутки[день] = в_сутки.get(день, 0) + 1
        if в_сутки[день] > МАКС_В_СУТКИ:
            raise ОшибкаЗапроса('items.per_day')
        пункты[ключ] = п
    if not пункты:
        raise ОшибкаЗапроса('items.empty')  # пустое расписание — это «выключено», а не подписка
    return Запрос(адрес, p256dh, auth, язык, город, tuple(sorted(пункты.values(), key=lambda п: (п.момент, п.заранее))))


# ───────────────────────── текст уведомления ─────────────────────────

def _название(ключ: str, язык: str, момент_намаза: int, смещение: int = СМЕЩЕНИЕ_РК) -> str:
    if ключ == 'dhuhr' and пятница(момент_намаза, смещение):
        return ДЖУМА[язык]
    return НАЗВАНИЯ[язык][ключ]


def _кнопки(язык: str) -> list[dict]:
    т = ТЕКСТЫ[язык]
    return [{'action': 'prayer', 'title': т['кнопка_намаз']}, {'action': 'qibla', 'title': т['кнопка_кибла']}]


def уведомление(пункт: Пункт, язык: str, город: str) -> dict:
    """Полезная нагрузка для service worker (app/public/push-sw.js). Тег — по намазу и дню: повтор заменяет прежнее."""
    т = ТЕКСТЫ[язык]
    момент_намаза = пункт.момент + пункт.заранее * МИНУТА_МС
    название = _название(пункт.ключ, язык, момент_намаза, пункт.смещение)
    день = день_рк(момент_намаза, пункт.смещение)
    if пункт.заранее:
        заголовок = т['напоминание'].format(мин=пункт.заранее, намаз=название, время=пункт.время)
        текст = город
        тег = f'aiustaz-soon-{пункт.ключ}-{день}'
    else:
        заголовок = f'{название} · {пункт.время}'
        текст = т['восход' if пункт.ключ == 'sunrise' else 'наступило'].format(город=город)
        if пункт.след_ключ and пункт.след_время:
            след_момент = момент_намаза if пункт.ключ != 'isha' else момент_намаза + ДЕНЬ_МС  # пятница — по дню следующего
            текст += '. ' + т['следующий'].format(намаз=_название(пункт.след_ключ, язык, след_момент, пункт.смещение),
                                                 время=пункт.след_время)
        тег = f'aiustaz-{пункт.ключ}-{день}'
    return {
        'v': 1,
        'kind': 'soon' if пункт.заранее else 'prayer',
        'title': заголовок,
        'body': текст,
        'tag': тег,
        'url': '#/prayer',
        'actions': _кнопки(язык),
        'silent': False,
        'lang': язык,
        'ts': момент_намаза,
    }


def уведомление_обновить(язык: str, сейчас_мс: int) -> dict:
    т = ТЕКСТЫ[язык]
    return {'v': 1, 'kind': 'refresh', 'title': т['обновить_заголовок'], 'body': т['обновить'], 'tag': 'aiustaz-refresh',
            'url': '#/notifications', 'actions': [], 'silent': True, 'lang': язык, 'ts': сейчас_мс}


def уведомление_проверка(язык: str, город: str, сейчас_мс: int) -> dict:
    т = ТЕКСТЫ[язык]
    return {'v': 1, 'kind': 'test', 'title': т['проверка_заголовок'], 'body': т['проверка'].format(город=город),
            'tag': 'aiustaz-test', 'url': '#/notifications', 'actions': _кнопки(язык), 'silent': False, 'lang': язык,
            'ts': сейчас_мс}


# ───────────────────────── когда отправлять ─────────────────────────

def решение(момент_мс: int, сейчас_мс: int) -> str:
    if момент_мс > сейчас_мс:
        return 'рано'
    if сейчас_мс - момент_мс > МАКС_ОПОЗДАНИЕ_МС:
        return 'поздно'
    return 'отправить'


def срок_жизни(пункт: Пункт) -> tuple[int, str]:
    """TTL (с) и Urgency: телефон без сети не должен получить «Наступило время Аср» через час."""
    if пункт.заранее:
        return max(60, пункт.заранее * 60), 'high'
    return 600, 'high'


def нужно_напомнить_обновить(конец_мс: int, сейчас_мс: int, отправлено: bool) -> bool:
    return not отправлено and конец_мс - сейчас_мс < ПОРОГ_ОБНОВЛЕНИЯ_МС
