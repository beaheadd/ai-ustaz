"""Загрузчик базы знаний «Спросить AI Ustaz»: JSONL → таблицы kb_entries / kb_texts (миграция 004). Всё или ничего.

Владелец 20.11.2026: «Мы загрузим базу знаний, хадисы, Коран, тафсиры … Только с нашей базы данных». Формат строки,
обязательные поля по виду и кто проверяет (правило 11) — docs/база-знаний.md.

Запуск (из папки server/, база — MUGALIM_DATABASE_URL, страж boot.py):
  python -m kb_load ../content/kb/spravka.jsonl            — проверить и загрузить (upsert по id)
  python -m kb_load --check ../content/kb/spravka.jsonl    — только проверить файл, в базу не ходить
Код выхода: 0 — загружено (или проверено); 1 — ошибки в файле или версиях: ничего не записано; 2 — нет файла / аргументов.
Правила загрузки:
  - каждая строка проверяется kb.разобрать_запись (хадис без сборника, номера, степени, кто_оценил — отказ; коран — ссылка
    «сура:аят» в пределах 114 сур и числа аятов, арабский у корана — отказ; арабское письмо в текстах — отказ);
  - sha256 содержания считается сам; изменилось содержание — версия в файле должна вырасти, иначе отказ всего файла;
  - тот же sha и та же версия, но другой статус / кто проверил — обновляется только статус;
  - записи, которых нет в файле, не трогаем (файлов может быть несколько).
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import kb


def загрузить(путь: pathlib.Path, хранилище=None, *, только_проверить: bool = False, вывод=print) -> int:
    try:
        текст = путь.read_text(encoding='utf-8')
    except OSError as е:
        вывод(f'нет файла {путь}: {е.strerror}')
        return 2
    try:
        записи = kb.разобрать_jsonl(текст)
    except kb.ОшибкаБазы as е:
        вывод(f'ОТКАЗ: {len(е.ошибки)} ошибок, ничего не записано:')
        for о in е.ошибки:
            вывод('  ' + о)
        return 1
    по_видам: dict[str, int] = {}
    for з in записи:
        по_видам[з.вид] = по_видам.get(з.вид, 0) + 1
    черновых = sum(з.статус == 'черновик' for з in записи)
    вывод(f'файл {путь.name}: {len(записи)} записей ({", ".join(f"{в} {ч}" for в, ч in sorted(по_видам.items()))}); '
          f'черновиков {черновых}, утверждено {len(записи) - черновых}')
    if только_проверить:
        вывод('проверено, в базу не писали (--check)')
        return 0
    if хранилище is None:
        import boot
        from db import Хранилище

        адрес = boot.адрес_базы()
        boot.остановить_если_чужая(адрес)
        хранилище = Хранилище(адрес)
        хранилище.применить_миграции()
    try:
        итог = хранилище.kb_загрузить(записи)
    except kb.ОшибкаБазы as е:
        вывод(f'ОТКАЗ: {len(е.ошибки)} ошибок версий, ничего не записано:')
        for о in е.ошибки:
            вывод('  ' + о)
        return 1
    вывод(f'загружено: новых {итог["новых"]}, изменено {итог["изменено"]}, статус обновлён {итог["статус"]}, '
          f'без изменений {итог["без_изменений"]}')
    return 0


def main(argv: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(prog='python -m kb_load', description='Загрузка базы знаний «Спросить AI Ustaz» (JSONL)')
    разбор.add_argument('файл', type=pathlib.Path)
    разбор.add_argument('--check', action='store_true', help='только проверить файл, в базу не писать')
    аргументы = разбор.parse_args(argv)
    return загрузить(аргументы.файл, только_проверить=аргументы.check)


if __name__ == '__main__':
    sys.exit(main())
