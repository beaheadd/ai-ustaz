КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
УРОК0 = 'أَ إِ أُ'
АРАБСКИЕ = range(0x0600, 0x0700)


class Ядро:
    """Подставное ядро: слышит заданные фонемы; гипотеза, равная услышанному, на 10 вероятнее остальных."""

    def __init__(self, услышано: str | None = None, замена: tuple[str, str] | None = None, какое: int = 1):
        self.услышано, self.замена, self.какое = услышано, замена, какое
        self.эталон = None

    def распознать(self, волна, эталон):
        import torch
        from aiustaz_speech.core import Распознано
        self.эталон = эталон.фонемы
        фон = self.услышано
        if фон is None:
            фон = эталон.фонемы
            if self.замена:
                было, стало = self.замена
                п = -1
                for _ in range(self.какое):
                    п = фон.index(было, п + 1)
                фон = фон[:п] + стало + фон[п + len(было):]
        return Распознано(фонемы=фон, вероятности=[0.9] * len(фон), сифаты=[], лог_вероятности=torch.zeros(10, 5),
                          длительность_сек=len(волна) / 16000)

    def оценить_гипотезы(self, распознано, гипотезы):
        # уверенно — любая гипотеза-подмена (не эталон): место из нескольких одинаковых подмен тоже уверенное
        return [0.0 if г == self.эталон else 10.0 for г in гипотезы]


def _разобрать(эталон, **ядро):
    я = Ядро(**ядро)
    return разобрать(я, эталон, я.распознать(np.zeros(16000, dtype=np.float32), эталон))


def wav(сек=1.0):
    t = np.arange(int(сек * 16000)) / 16000
    буфер = io.BytesIO()
    sf.write(буфер, (0.1 * np.sin(2 * np.pi * 220 * t)).astype(np.float32), 16000, format='WAV', subtype='PCM_16')
    return буфер.getvalue()


def _api(ядро, **поля):
    from fastapi.testclient import TestClient
    from aiustaz_speech.app import создать
    with TestClient(создать(ядро)) as клиент:
        return клиент.post('/v1/proverka', files={'audio': ('a.wav', wav(2.0), 'audio/wav')},
                           data={к: str(з) for к, з in поля.items()}).json()


# ───────────────────────── слоги, звуки, буквы ─────────────────────────

def test_слоги():
    assert [УРОК0[с.нач:с.кон] for с in слоги(УРОК0)] == ['أَ', 'إِ', 'أُ']
    assert [(с.номер, с.слово) for с in слоги('كَتَبَ بَا')] == [(1, 1), (2, 1), (3, 1), (4, 2)]
    т = 'ٱلْحَمْدُ لِلَّهِ'
    assert [т[с.нач:с.кон] for с in слоги(т)] == ['ٱلْحَمْ', 'دُ', 'لِ', 'لَّ', 'هِ']   # ٱ без огласовки — к слогу
    т = 'بَا بِي أَبْ'
    assert [т[с.нач:с.кон] for с in слоги(т)] == ['بَا', 'بِي', 'أَبْ']         # мадд и сукун — в слоге


def test_звуки():
    assert звуки('ءِ') == [{'вид': 'согласный', 'буква': 'ء', 'id': 'hamza'}, {'вид': 'гласный', 'гласный': 'и', 'счёт': 1}]
    assert звуки('بِۦۦ')[1] == {'вид': 'гласный', 'гласный': 'и', 'счёт': 2}     # мадд табии — 2 счёта
    assert звуки('بَاا')[1]['счёт'] == 2 and звуки('ءُ')[1]['счёт'] == 1
    assert звуки('ۦۦ') == [{'вид': 'продление', 'гласный': 'и', 'счёт': 2}]
    assert звуки('لِلل')[2] == {'вид': 'согласный', 'буква': 'ل', 'id': 'lam', 'удвоен': True}
    assert звуки('بڇ') == [{'вид': 'согласный', 'буква': 'ب', 'id': 'ba', 'калькаля': True}]


@pytest.mark.skipif(not os.path.exists(os.path.join(КОРЕНЬ, 'content', 'letters.json')), reason='нет content/letters.json')
def test_таблица_букв_совпадает_с_letters_json():
    буквы = {б['id']: б for б in json.load(open(os.path.join(КОРЕНЬ, 'content', 'letters.json'), encoding='utf-8'))}
    for знак, ид in БУКВЫ.items():
        assert ид in буквы, (знак, ид)
        б = буквы[ид]
        assert знак == б['знак'] or знак in (б.get('носители') or []) or (ид == 'hamza' and знак == 'ٔ'), (знак, ид)
    assert {б for б in буквы if буквы[б]['вид'] == 'буква' and б != 'lam-alif'} <= set(БУКВЫ.values())


