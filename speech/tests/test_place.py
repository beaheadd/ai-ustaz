"""Место и звук замечания — поля для конкретных подсказок (владелец 20.11.2026, снимок урока 0 на aiustaz.pro:
«Проверьте себя: в одном месте прозвучал лишний звук» → «Нужно нам доработать проверку таджвида, именно где нам нужно
говорить, какая буква, где неправильно произнесли»).

Причина «в одном месте»: у вставки (лишний звук) пакет даёт ПУСТОЙ диапазон в тексте эталона, а при чтении ×3
позиции были в утроенном тексте, которого нет на экране. Теперь: позиция и фрагмент — непустой кусок ОДНОКРАТНОГО
текста, номер чтения — повтор; слог, слово, буква (id letters.json), огласовка, звук ожидался/услышан — описанием.

Без модели: «услышано» = эталон с подменой; гипотеза-подмена вероятнее эталона на 10 (уверенно).
Запуск: cd speech && python -m pytest tests -q
"""
