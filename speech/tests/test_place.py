def test_api_аят_без_услышанных_фонем():
    ответ = _api(Ядро(замена=('حَ', 'خَ')), sura=1, aya=2)
    assert ответ['статус'] == 'ок' and 'фонемы' not in ответ['услышано']
    [з] = ответ['замечания']
    assert з['услышано'] is None and з['слово'] == 1 and з['буква']['id'] == 'hha'
    for поле in ('услышано', 'звук_услышан'):
        текст = json.dumps(з[поле], ensure_ascii=False)
        арабских = [с for с in текст if ord(с) in АРАБСКИЕ]
        assert len(арабских) <= 1, (поле, текст)      # самое большее — знак одной буквы в описании звука
