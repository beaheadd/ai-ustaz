"""HTTP-сервис проверки чтения (порт 8032, только 127.0.0.1 — снаружи через nginx своего домена).

Контракт API (v1):
- GET  /v1/zdorovye -> {ок, модель, версия_пакета, потоков}
- POST /v1/proverka (multipart, имена полей латиницей): audio — WAV 16 кГц моно (клиент пересчитывает сам),
    до MUGALIM_SPEECH_MAX_SEC с; эталон: text=<учебный слог/слово> ИЛИ sura=<1..114>&aya=<n> и, если читают часть аята,
    uthmani_from=<номер uthmani-слова с 1>[&uthmani_words=<сколько; нет — до конца аята>] (новые поля, 19.11.2026;
    нумерация клиента — слова копии для показа без знаков, app/src/quran/text.ts) либо старые word_from=<imlaey с 0>
    [&words=] (совместимость). Диапазон — только внутри аята, иначе 400.
    kinds=мадд,буква,C1.табии,… (необязательно: что ученик уже прошёл — виды или коды; правило 7 «не ругать за
    непройденное», explain.py).
  -> {статус: 'ок'|'плохой_звук', причина? ('коротко'|'длинно'|'тихо'|'перегруз'|'испорчено'|'не_то' — прочитано другое),
      эталон:{текст, фонемы[, повторов][, слово_с, слов — uthmani-слова с 1 по всему аяту]},
      услышано:{фонемы (не для аята — правило 8), уверенность_ср},
      замечания:[…explain.разобрать…, у аята — с номером uthmani-слова «слово»], длительность_сек, время_мс}
    Учебный текст, прочитанный 2–3 раза подряд: эталон.текст — ОДНОКРАТНЫЙ, эталон.повторов — сколько раз прочитано,
    позиции замечаний — в однократном тексте, номер чтения — замечание.повтор (20.11.2026, explain.py).
Приватность (CLAUDE.md «Данные и приватность»): запись не пишется на диск и в журнал, удаляется сразу после разбора;
в журнал — только длительность и время ответа. Аудио во внешние сервисы не уходит.
Нагрузка: одна запись за раз (замок в ядре) + очередь не длиннее MUGALIM_SPEECH_QUEUE — иначе 503.
"""
from __future__ import annotations

from difflib import SequenceMatcher
import logging
import os
import time
from contextlib import asynccontextmanager

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.concurrency import run_in_threadpool

from . import audio
from .core import РечевоеЯдро
from .envnum import строка_из_окружения, число_из_окружения, целое_из_окружения
from .explain import не_то_прочитано, отобрать, разобрать
from .reference import эталон_аята, эталон_повтора, эталон_текста

журнал = logging.getLogger('mugalim.speech')

ПУТЬ_МОДЕЛИ = строка_из_окружения('MUGALIM_SPEECH_MODEL_DIR', '')
ПОТОКОВ = целое_из_окружения('MUGALIM_SPEECH_THREADS', 2, 1, 64)
МАКС_СЕК = число_из_окружения('MUGALIM_SPEECH_MAX_SEC', 20.0, 1.0, 120.0)
МАКС_ОЧЕРЕДЬ = целое_из_окружения('MUGALIM_SPEECH_QUEUE', 4, 1, 100)
МАКС_БАЙТ = целое_из_окружения('MUGALIM_SPEECH_MAX_BYTES', 2_000_000, 10_000, 50_000_000)
МАКС_ЗАМЕЧАНИЙ = целое_из_окружения('MUGALIM_SPEECH_MAX_HINTS', 3, 1, 50)

_состояние: dict = {'ядро': None, 'очередь': 0}


def прогреть(ядро: РечевоеЯдро) -> None:
    """Прогрев при запуске: первая проверка в свежем процессе шла дольше 20 с (таймаут клиента) — 19.11.2026,
    aiustaz.pro. Один холостой разбор 1 с тона против учебного слога; запись не нужна, ничего не сохраняется."""
    try:
        import numpy as np
        волна = (0.05 * np.sin(2 * np.pi * 220 * np.arange(16000) / 16000)).astype(np.float32)
        ядро.распознать(волна, эталон_текста('أَ إِ أُ'))
        журнал.info('прогрев модели: готово')
    except Exception as е:  # прогрев — не повод не запускаться
        журнал.warning('прогрев модели не удался: %s', type(е).__name__)


def создать(ядро: РечевоеЯдро | None = None) -> FastAPI:
    @asynccontextmanager
    async def жизнь(приложение: FastAPI):
        if ядро is not None:
            _состояние['ядро'] = ядро
        elif _состояние['ядро'] is None:
            if not ПУТЬ_МОДЕЛИ or not os.path.isdir(ПУТЬ_МОДЕЛИ):
                raise RuntimeError('MUGALIM_SPEECH_MODEL_DIR не задан или нет папки модели')
            _состояние['ядро'] = РечевоеЯдро(ПУТЬ_МОДЕЛИ, ПОТОКОВ)
            прогреть(_состояние['ядро'])
        yield

    приложение = FastAPI(title='AI Ustaz — речевой сервис', docs_url=None, redoc_url=None, lifespan=жизнь)

    @приложение.get('/v1/zdorovye')
    def здоровье():
        from importlib.metadata import version
        return {'ок': _состояние['ядро'] is not None, 'модель': os.path.basename(ПУТЬ_МОДЕЛИ.rstrip('/')) or 'внешнее',
                'версия_пакета': version('quran-muaalem'), 'потоков': ПОТОКОВ}

    @приложение.post('/v1/proverka')
    async def проверка(
        запись: UploadFile = File(..., alias='audio'),
        текст: str | None = Form(None, alias='text'),
        сура: int | None = Form(None, alias='sura'),
        аят: int | None = Form(None, alias='aya'),
        слово_с: int | None = Form(None, alias='word_from'),
        слов: int | None = Form(None, alias='words'),
        uthmani_с: int | None = Form(None, alias='uthmani_from'),
        uthmani_слов: int | None = Form(None, alias='uthmani_words'),
        виды: str | None = Form(None, alias='kinds'),
    ):
        начало = time.perf_counter()
        байты = await запись.read(МАКС_БАЙТ + 1)
        if len(байты) > МАКС_БАЙТ:
            raise HTTPException(413, 'запись слишком большая')
        try:
            if сура is not None or аят is not None:
                эталон = эталон_аята(сура, аят, слово_с, слов, uthmani_с=uthmani_с, uthmani_слов=uthmani_слов)
            else:
                эталон = эталон_текста(текст or '')
        except Exception as е:
            raise HTTPException(400, f'неверный эталон: {type(е).__name__}') from None
        try:
            волна, _ = audio.прочитать_запись(байты)
        except audio.ОшибкаЗаписи as е:
            raise HTTPException(400, str(е)) from None
        finally:
            del байты
        причина = audio.оценить_звук(волна, макс_сек=МАКС_СЕК)
        if причина:
            return {'статус': 'плохой_звук', 'причина': причина, 'длительность_сек': round(audio.длительность_сек(волна), 2)}
        if _состояние['очередь'] >= МАКС_ОЧЕРЕДЬ:
            raise HTTPException(503, 'сервис занят, повторите через несколько секунд')
        _состояние['очередь'] += 1
        try:
            ядро = _состояние['ядро']
            распознано = await run_in_threadpool(ядро.распознать, волна, эталон)
            набор_видов = {в.strip() for в in виды.split(',') if в.strip()} if виды else None
            if текст and not (сура and аят):
                # Учебный текст читают несколько раз подряд (урок 0: «а — и — у» три раза) — 19.11.2026 на aiustaz.pro
                # тройное чтение считалось «прочитано не то». Берём эталон ×1, ×2 или ×3 — какой ближе к услышанному.
                def сходство(а: str, б: str) -> float:
                    return SequenceMatcher(None, а, б, autojunk=False).ratio()
                лучший, лучшая = эталон, сходство(эталон.фонемы, распознано.фонемы)
                for раз in (2, 3):
                    повтор = эталон_повтора(текст, раз)
                    с = сходство(повтор.фонемы, распознано.фонемы)
                    if с > лучшая + 0.05:
                        лучший, лучшая = повтор, с
                if лучший is not эталон:
                    эталон = лучший
                    распознано = await run_in_threadpool(ядро.распознать, волна, эталон)
            if не_то_прочитано(эталон.фонемы, распознано.фонемы):
                return {'статус': 'плохой_звук', 'причина': 'не_то', 'длительность_сек': round(распознано.длительность_сек, 2),
                        'эталон': {'фонемы': эталон.фонемы},
                        'услышано': {} if эталон.вид == 'аят' else {'фонемы': распознано.фонемы}}
            замечания = await run_in_threadpool(разобрать, ядро, эталон, распознано, набор_видов)
            замечания = отобрать(замечания, МАКС_ЗАМЕЧАНИЙ)
        finally:
            _состояние['очередь'] -= 1
            del волна
        вер = распознано.вероятности
        # Чтение ×2/×3: текст эталона в ответе — ОДНОКРАТНЫЙ (как на экране), позиции замечаний — в нём же;
        # фонемы — того, с чем сверяли (×K). Аят (правило 8): услышанные фонемы арабицей не возвращаем.
        один = ' '.join(текст.split()) if эталон.повторов > 1 and текст else эталон.текст
        ответ = {
            'статус': 'ок',
            'эталон': {'текст': один, 'фонемы': эталон.фонемы,
                       **({'повторов': эталон.повторов} if эталон.повторов > 1 else {}),
                       **({'слово_с': эталон.слово_с, 'слов': эталон.слов} if эталон.вид == 'аят' else {})},
            'услышано': {**({} if эталон.вид == 'аят' else {'фонемы': распознано.фонемы}),
                         'уверенность_ср': round(sum(вер) / len(вер), 3) if вер else 0.0},
            'замечания': замечания,
            'длительность_сек': round(распознано.длительность_сек, 2),
            'время_мс': int((time.perf_counter() - начало) * 1000),
        }
        журнал.info('проверка: %.1f с, %d мс, замечаний %d', распознано.длительность_сек, ответ['время_мс'], len(замечания))
        return ответ

    return приложение


app = создать()
