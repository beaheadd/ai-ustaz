"""Место и звук замечания — поля для шаблонов подсказок (владелец 20.11.2026: «Нужно нам доработать проверку таджвида,
именно где нам нужно говорить, какая буква, где неправильно произнесли»).

Контракт (чистые функции, без модели):
- слоги(текст) -> [Слог(номер, слово, нач, кон)] — слоги текста эталона (номер и слово — с 1). Слог начинается
  с буквы с огласовкой (фатха, кясра, дамма, танвин); буквы без своей огласовки (сукун, буква мадда, ـٰ) идут
  к предыдущему слогу; буква без огласовки в начале слова (ٱ) — к следующему.
- группа(текст, позиция) -> (нач, кон) — буква с её знаками (огласовка, шадда, сукун, малые знаки).
- место(эталон, ошибка) -> dict — поля замечания: позиция/фрагмент (в ОДНОКРАТНОМ тексте при чтении ×2/×3),
  повтор, слог, слово_в_тексте, буква {знак, id}, огласовка {id, знак, шадда}, вставка, звук_ожидался, звук_услышан.
- звуки(фонемы) -> [звук] — фонемы QPS (quran-transcript) → описание без арабского текста слов:
    {вид:'гласный', гласный:'а'|'и'|'у', счёт:n}       — краткий (1) или долгий (2+, мадд) гласный;
    {вид:'продление', гласный, счёт:n}                  — только протяжка: n букв мадда без своего гласного
                                                          (после краткого гласного это долгий на n счётов);
    {вид:'согласный', буква:'ح', id:'hha'|None, удвоен?, калькаля?} — согласный звук (id — content/letters.json);
    {вид:'гунна', буква:'ن'|'م'}                       — скрытый нун/мим (ихфа);
    {вид:'калькаля'} | {вид:'особый', знак}.
  Клиент (app/src/speech/hints.ts) превращает это в «краткое „и“», «долгое „и“», «звук „х“ (خ)» по-русски
  и по-казахски. Текст объяснения здесь не пишется (CLAUDE.md, правило 4).
- Правило 8: для аята «услышанное» не возвращается арабским текстом — только описанием звука (app.py, explain.py).
- БУКВЫ — знак → id из content/letters.json, только где буква однозначна (ة, ى, ٱ, آ — нет: читаются по-разному).
  Тест сверяет таблицу с content/letters.json.
"""
from __future__ import annotations

from dataclasses import dataclass
import unicodedata

ФАТХА, КЯСРА, ДАММА = 'َ', 'ِ', 'ُ'
СУКУН = ('ْ', 'ۡ')
ШАДДА = 'ّ'
ТАНВИН = {'ً': 'tanwin-fath', 'ٍ': 'tanwin-kasr', 'ٌ': 'tanwin-damm', 'ࣰ': 'tanwin-fath', 'ࣱ': 'tanwin-damm', 'ࣲ': 'tanwin-kasr'}
ОГЛАСОВКИ = {ФАТХА: 'fatha', КЯСРА: 'kasra', ДАММА: 'damma', **ТАНВИН}
БУКВЫ_МАДДА = set('اوىيٰـ')  # без своей огласовки — продолжение слога (ـٰ — малый алиф на татвиле)

# Знак буквы → id в content/letters.json (одна буква — один звук). Хамза — на любом носителе.
БУКВЫ = {
    'ء': 'hamza', 'أ': 'hamza', 'إ': 'hamza', 'ؤ': 'hamza', 'ئ': 'hamza', 'ٔ': 'hamza',
    'ا': 'alif', 'ب': 'ba', 'ت': 'ta', 'ث': 'tha', 'ج': 'jim', 'ح': 'hha', 'خ': 'kha', 'د': 'dal', 'ذ': 'dhal',
    'ر': 'ra', 'ز': 'zay', 'س': 'sin', 'ش': 'shin', 'ص': 'sad', 'ض': 'dad', 'ط': 'tta', 'ظ': 'zza', 'ع': 'ain',
    'غ': 'ghain', 'ف': 'fa', 'ق': 'qaf', 'ك': 'kaf', 'ل': 'lam', 'م': 'mim', 'ن': 'nun', 'ه': 'ha', 'و': 'waw',
    'ي': 'ya',
}

# Фонемы QPS (quran_transcript.alphabet.phonetics)
_ГЛАСНЫЕ_QPS = {ФАТХА: 'а', КЯСРА: 'и', ДАММА: 'у', '۪': 'а', 'ؙ': 'у'}
_МАДД_QPS = {'ا': 'а', 'ۦ': 'и', 'ۥ': 'у'}
_КАЛЬКАЛЯ_QPS = 'ڇ'
_СКРЫТЫЕ_QPS = {'ں': 'ن', '۾': 'م'}


def _знак(с: str) -> bool:
    """Огласовка и малые знаки (Mn) — часть буквы, не отдельная буква."""
    return unicodedata.category(с) == 'Mn'


def группа(текст: str, позиция: int) -> tuple[int, int]:
    """[нач, кон) буквы с её знаками, в которую попадает символ позиции (знак — к своей букве)."""
    if not текст:
        return 0, 0
    п = max(0, min(int(позиция), len(текст) - 1))
    нач = п
    while нач > 0 and _знак(текст[нач]):
        нач -= 1
    кон = нач + 1
    while кон < len(текст) and _знак(текст[кон]):
        кон += 1
    return нач, кон


def _группы_слова(текст: str, нач: int, кон: int) -> list[tuple[int, int]]:
    группы, п = [], нач
    while п < кон:
        с, по = группа(текст, п)
        группы.append((с, по))
        п = по
    return группы


def _есть_гласный(текст: str, с: int, по: int) -> bool:
    return any(з in ОГЛАСОВКИ for з in текст[с + 1:по])


@dataclass
class Слог:
    номер: int   # с 1, по всему тексту
    слово: int   # с 1
    нач: int
    кон: int


def слоги(текст: str) -> list[Слог]:
    итог: list[Слог] = []
    слово, п = 0, 0
    while п < len(текст):
        if текст[п] == ' ':
            п += 1
            continue
        конец = текст.find(' ', п)
        конец = len(текст) if конец < 0 else конец
        слово += 1
        текущие: list[list[int]] = []
        висит: int | None = None   # буквы без огласовки в начале слова (ٱ) — к первому слогу
        for с, по in _группы_слова(текст, п, конец):
            if _есть_гласный(текст, с, по):
                текущие.append([с if висит is None else висит, по])
                висит = None
            elif текущие:
                текущие[-1][1] = по
            elif висит is None:
                висит = с
        if not текущие:
            текущие = [[п, конец]]
        for с, по in текущие:
            итог.append(Слог(len(итог) + 1, слово, с, по))
        п = конец
    return итог


def звуки(фонемы: str) -> list[dict]:
    """Фонемы QPS → список звуков для описания (см. шапку). Ничего не теряет: незнакомое — {вид:'особый'}."""
    итог: list[dict] = []
    п = 0
    while п < len(фонемы):
        з = фонемы[п]
        if з in _ГЛАСНЫЕ_QPS:
            # QPS: краткий гласный — один знак; долгий — знак и по букве мадда на каждый счёт («بَاا» — 2 счёта)
            гласный = _ГЛАСНЫЕ_QPS[з]
            мадд, п = 0, п + 1
            while п < len(фонемы) and _МАДД_QPS.get(фонемы[п]) == гласный:
                мадд, п = мадд + 1, п + 1
            итог.append({'вид': 'гласный', 'гласный': гласный, 'счёт': max(1, мадд)})
            continue
        if з in _МАДД_QPS:
            гласный, счёт = _МАДД_QPS[з], 0
            while п < len(фонемы) and фонемы[п] == з:
                счёт, п = счёт + 1, п + 1
            итог.append({'вид': 'продление', 'гласный': гласный, 'счёт': счёт})
            continue
        if з == _КАЛЬКАЛЯ_QPS:
            if итог and итог[-1]['вид'] == 'согласный':
                итог[-1]['калькаля'] = True
            else:
                итог.append({'вид': 'калькаля'})
            п += 1
            continue
        if з in _СКРЫТЫЕ_QPS:
            итог.append({'вид': 'гунна', 'буква': _СКРЫТЫЕ_QPS[з]})
            while п < len(фонемы) and фонемы[п] == з:
                п += 1
            continue
        if з in БУКВЫ and з not in 'اأإؤئٔ':
            звук = {'вид': 'согласный', 'буква': з, 'id': БУКВЫ[з]}
            п += 1
            if п < len(фонемы) and фонемы[п] == з:   # удвоенный согласный (шадда)
                звук['удвоен'] = True
                while п < len(фонемы) and фонемы[п] == з:
                    п += 1
            итог.append(звук)
            continue
        итог.append({'вид': 'особый', 'знак': з})
        п += 1
    return итог


def _буква_группы(текст: str, с: int, по: int) -> dict | None:
    знак = текст[с]
    if знак == 'ـ' or знак not in БУКВЫ:
        return {'знак': знак, 'id': None} if знак.strip() and знак != 'ـ' else None
    return {'знак': знак, 'id': БУКВЫ[знак]}


def _огласовка_группы(текст: str, с: int, по: int) -> dict | None:
    знаки = текст[с + 1:по]
    шадда = ШАДДА in знаки
    for з in знаки:
        if з in ОГЛАСОВКИ:
            return {'id': ОГЛАСОВКИ[з], 'знак': з, 'шадда': шадда}
    for з in знаки:
        if з in СУКУН:
            return {'id': 'sukun', 'знак': з, 'шадда': шадда}
    return {'id': 'shadda', 'знак': ШАДДА, 'шадда': True} if шадда else None


def _символ_перед_вставкой(карта: list, ph: int) -> int | None:
    """Символ текста, чья фонема стоит прямо перед местом вставки (последний с pos[1] == ph)."""
    найден = None
    for и, мп in enumerate(карта):
        с, по = мп.pos
        if not getattr(мп, 'deleted', False) and по > с and по == ph:
            найден = и
    return найден


def _период(текст: str, повторов: int) -> int:
    """Длина одного чтения + пробел: текст ×K = ' '.join([t] * K)."""
    if повторов <= 1:
        return len(текст) + 1
    return (len(текст) + 1) // повторов


def место(эталон, ошибка) -> dict:
    """Поля «где и что» одного расхождения (ReciterError пакета) — см. шапку модуля."""
    текст_полный = эталон.текст
    повторов = max(1, int(getattr(эталон, 'повторов', 1) or 1))
    период = _период(текст_полный, повторов)
    один = текст_полный[:период - 1] if повторов > 1 else текст_полный

    с, по = (int(x) for x in ошибка.uthmani_pos)
    вставка = None
    if ошибка.speech_error_type == 'insert' and по <= с:
        ph = int(ошибка.ph_pos[0])
        перед = _символ_перед_вставкой(эталон.карта, ph)
        if перед is None:
            с, по = группа(текст_полный, с)
            вставка = 'в_начале'
        else:
            с, по = группа(текст_полный, перед)
            предыдущая = эталон.фонемы[ph - 1] if ph > 0 else ''
            вставка = 'после_гласного' if предыдущая in _ГЛАСНЫЕ_QPS or предыдущая in _МАДД_QPS else 'после_согласного'
    if по <= с:
        с, по = группа(текст_полный, с)
    # пробелы по краям — не часть места
    while с < по and текст_полный[с] == ' ':
        с += 1
    while по > с and текст_полный[по - 1] == ' ':
        по -= 1

    повтор = с // период + 1
    с1 = с - (повтор - 1) * период
    по1 = min(по - (повтор - 1) * период, len(один))
    if по1 <= с1:
        с1, по1 = группа(один, с1)

    все_слоги = слоги(один)
    слог = next((сл for сл in все_слоги if сл.нач <= с1 < сл.кон), None)
    # буква: первая буква места; буква мадда без своей огласовки — к букве слога с гласным, который она тянет
    гс, гпо = группа(один, с1)
    if один[гс] in БУКВЫ_МАДДА and not _есть_гласный(один, гс, гпо) and слог:
        for нс, нпо in _группы_слова(один, слог.нач, гс):
            if _есть_гласный(один, нс, нпо):
                гс, гпо = нс, нпо
    return {
        'позиция': [с1, по1],
        'фрагмент': один[с1:по1],
        'повтор': повтор if повторов > 1 else None,
        'повторов': повторов,
        'слог': слог.номер if слог else None,
        'слогов': len(все_слоги),
        'слог_позиция': [слог.нач, слог.кон] if слог else None,
        'слог_текст': один[слог.нач:слог.кон] if слог else None,
        'слово_в_тексте': слог.слово if слог else один.count(' ', 0, с1) + 1,
        'слов_в_тексте': len(один.split()),
        'буква': _буква_группы(один, гс, гпо),
        'огласовка': _огласовка_группы(один, гс, гпо),
        'вставка': вставка,
        'звук_ожидался': звуки(ошибка.expected_ph or ''),
        'звук_услышан': звуки(ошибка.preditected_ph or ''),
    }
