"""Факты для объяснения: расхождения «эталон ↔ услышано» → замечания с кодами каталога ошибок.

Контракт: разобрать(ядро, эталон, распознано, виды=None) -> list[dict] замечаний. Каждое замечание:
  {код, вид, уровень, позиция:[начало, конец) в тексте эталона, фрагмент, слово, ожидалось, услышано,
   счёт_ожидался, счёт_услышан, правила:[{ar, en}], уверенность}
- слово — номер uthmani-слова (с 1, по ВСЕМУ аяту) для эталона-аята, иначе None. Клиент подсвечивает слово копии
  для показа по этому номеру (app/src/quran/text.ts, разборАята): позиция и фрагмент — в фонетической копии
  (с татвилем и малыми мимами), и в тексте на экране их часто нет (docs/дизайн/05, §2.4).
- виды (поле kinds) — что ученик уже прошёл: замечание остаётся, если его вид ИЛИ код есть в наборе
  ('мадд' — все мадды; 'C1.табии' — только табии). Пустой набор/None — без фильтра (правило 7: клиент для аятов
  всегда шлёт набор по прогрессу, app/src/quran-check/kinds.ts).
- Текст объяснения здесь НЕ пишется: его собирает клиент по шаблонам каталога (CLAUDE.md, правило 4).
- Уровень (правило 7, решение владельца 18.11.2026): на старте только «проверьте». «Ошибка» включается
  код за кодом после замера; сервис её пока не выдаёт.
- Уверенность — проверка двух гипотез: лог-правдоподобие CTC «как услышано» минус «как в эталоне».
  Ниже ПОРОГ_УВЕРЕННОСТИ — тишина («не уверен — не ругаем»).
- Допустимые варианты не замечание: ‘арид и лин — 2/4/6, муттасиль — 4–6, мунфасиль — 4–5;
  мунфасиль на 2 — мягкая подсказка без штрафа (решение D3, без «Тайибы»).
"""
from __future__ import annotations

from difflib import SequenceMatcher

from quran_transcript.phonetics.error_explainer import explain_error

from .envnum import число_из_окружения
from .reference import номер_слова

ПОРОГ_УВЕРЕННОСТИ = число_из_окружения('MUGALIM_SPEECH_MIN_LLR', 2.0, 0.0, 50.0)

_ДОПУСТИМЫЕ_СЧЁТА = {
    'AaredMaddRule': {2, 4, 6},
    'LeenMaddRule': {2, 4, 6},
    'MottaselMaddRule': {4, 5, 6},
    'MottaselMaddPauseRule': {4, 5, 6},
    'MonfaselMaddRule': {4, 5},
}
_КОД_МАДДА = {
    'NormalMaddRule': 'C1.табии',
    'MonfaselMaddRule': 'C1.мунфасиль',
    'MottaselMaddRule': 'C1.муттасиль',
    'MottaselMaddPauseRule': 'C1.муттасиль',
    'LazemMaddRule': 'C1.лязим',
    'AaredMaddRule': 'C1.арид',
    'LeenMaddRule': 'C1.лин',
}


def _имя_правила(правило) -> dict:
    имя = getattr(правило, 'name', None)
    return {'ar': getattr(имя, 'ar', ''), 'en': getattr(имя, 'en', type(правило).__name__)}


def _классифицировать(ошибка) -> tuple[str, str, str]:
    """-> (код, вид, уровень) по типу расхождения и правилам таджвида эталона."""
    правила = list(ошибка.ref_tajweed_rules or []) + list(ошибка.missing_tajweed_rules or [])
    классы = [type(п).__name__ for п in правила]
    if ошибка.error_type == 'tajweed':
        for к in классы:
            if к in _КОД_МАДДА:
                ожид, усл = ошибка.expected_len, ошибка.predicted_len
                if усл is not None and усл in _ДОПУСТИМЫЕ_СЧЁТА.get(к, set()):
                    return '', 'допустимо', 'нет'
                if к == 'MonfaselMaddRule' and усл == 2:
                    return 'C1.мунфасиль', 'мадд', 'подсказка'
                if ожид is not None and усл is not None and усл > ожид:
                    return 'C2', 'мадд', 'проверьте'
                return _КОД_МАДДА[к], 'мадд', 'проверьте'
        if 'Qalqalah' in классы or 'ڇ' in (ошибка.expected_ph or '') + (ошибка.preditected_ph or ''):
            return ('F1' if ошибка.speech_error_type != 'insert' else 'F3'), 'калькаля', 'проверьте'
        if 'Ghonnah' in классы or 'MoshaddadOrModghamNoonRule' in классы:
            return 'D2', 'гунна', 'проверьте'
        if 'IdghamKamel' in классы:
            return 'E1', 'идгам', 'проверьте'
        return 'T', 'таджвид', 'проверьте'
    if ошибка.error_type == 'tashkeel':
        return 'B1', 'огласовка', 'проверьте'
    return {'delete': 'A2', 'insert': 'A3'}.get(ошибка.speech_error_type, 'A1'), 'буква', 'проверьте'


def разобрать(ядро, эталон, распознано, виды: set[str] | None = None) -> list[dict]:
    ошибки = explain_error(эталон.текст, эталон.фонемы, распознано.фонемы, эталон.карта)
    if not ошибки:
        return []
    база = ядро.оценить_гипотезы(распознано, [эталон.фонемы])[0]
    замечания = []
    for о in ошибки:
        код, вид, уровень = _классифицировать(о)
        if уровень == 'нет' or (виды and вид not in виды and код not in виды):
            continue
        начало, конец = о.ph_pos
        вариант = эталон.фонемы[:начало] + (о.preditected_ph or '') + эталон.фонемы[конец:]
        try:
            уверенность = ядро.оценить_гипотезы(распознано, [вариант])[0] - база
        except ValueError:
            уверенность = 0.0
        if уверенность < ПОРОГ_УВЕРЕННОСТИ:
            continue  # не уверены — молчим
        с, по = о.uthmani_pos
        замечания.append({
            'код': код,
            'вид': вид,
            'уровень': уровень,
            'позиция': [int(с), int(по)],
            'фрагмент': эталон.текст[с:по],
            'слово': номер_слова(эталон.текст, с, эталон.слово_с) if getattr(эталон, 'слово_с', None) else None,
            'ожидалось': о.expected_ph,
            'услышано': о.preditected_ph,
            'счёт_ожидался': о.expected_len,
            'счёт_услышан': о.predicted_len,
            'правила': [_имя_правила(п) for п in (о.ref_tajweed_rules or [])],
            'уверенность': round(float(уверенность), 2),
        })
    return замечания


def не_то_прочитано(эталон: str, услышано: str, порог: float = 0.5) -> bool:
    """Прочитано другое (не тот слог или аят): не разбираем по буквам, а просим повторить задание."""
    if not услышано:
        return True
    return SequenceMatcher(None, эталон, услышано, autojunk=False).ratio() < порог


def отобрать(замечания: list[dict], сколько: int) -> list[dict]:
    """Не больше N подсказок за раз — самые уверенные, в порядке текста (новичка не заваливаем)."""
    лучшие = sorted(замечания, key=lambda з: -з['уверенность'])[:сколько]
    return sorted(лучшие, key=lambda з: з['позиция'][0])
