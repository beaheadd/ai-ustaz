"""Общие функции инструментов контента AI Ustaz (tools/build_content.py, tools/check_content.py).

Назначение: разбор учебного арабского на буквы и знаки, транскрипция кириллицей
по схеме каталога ошибок §10.1, слоги и лестница, чтение Tanzil Uthmani v1.1 из XML.
Запуск инструментов — только `python3 -I` (изолированный режим), без сторонних пакетов.

Контракт:
  единицы(строка) -> [(буква, знаки)]               — буква + комбинирующие знаки (Mn)
  транскрипция(строка) -> str                        — «ра ри ру», «қуль», «х̣асан»
  слоги(слово) -> [str]; лестница(слово) -> [str]    — ступени начинаются с огласованной буквы
  прочитать_tanzil(путь) -> ({(сура, аят): текст}, шапка, sha256 файла)
  путь_tanzil(аргументы) — путь к XML: аргумент --tanzil, иначе MUGALIM_TANZIL_XML, иначе копия для показа
    content/quran/quran-uthmani-marks.xml (Tanzil Uthmani v1.1 со знаками; с 19.11.2026).
Текст Корана здесь не меняется и не нормализуется: строки берутся из XML как есть.
"""
import hashlib
import os
import pathlib
import re
import unicodedata
import xml.etree.ElementTree as ET

ФАТХА, КЯСРА, ДАММА, СУКУН, ШАДДА = 'َ', 'ِ', 'ُ', 'ْ', 'ّ'
ТАНВИНЫ = ('ً', 'ٌ', 'ٍ')
ТАТВИЛЬ = 'ـ'
ГЛАСНЫЕ = {ФАТХА: 'а', КЯСРА: 'и', ДАММА: 'у'}
ХАМЗЫ = set('ءأإؤئ')

# Схема транскрипции каталога ошибок §10.1 (общая для ru и kk).
СОГЛАСНЫЕ = {
    'ب': 'б', 'ت': 'т', 'ث': 'с̱', 'ج': 'дж', 'ح': 'х̣', 'خ': 'х', 'د': 'д', 'ذ': 'з̱',
    'ر': 'р', 'ز': 'з', 'س': 'с', 'ش': 'ш', 'ص': 'с̣', 'ض': 'д̣', 'ط': 'т̣', 'ظ': 'з̣',
    'ع': '‘', 'غ': 'ғ', 'ف': 'ф', 'ق': 'қ', 'ك': 'к', 'ل': 'л', 'م': 'м', 'ن': 'н',
    'ه': 'һ', 'و': 'в', 'ي': 'й',
}

# Копия Tanzil Uthmani v1.1 ДЛЯ ПОКАЗА — со знаками остановки, саджды и руб‘ аль-хизба, лежит в репозитории
# (загружена с tanzil.net 19.11.2026, sha256 — в content/sources.json). Фонетическая копия без знаков
# (quran-transcript) — только речевому сервису для фонетики и выравнивания; здесь не используется.
ПУТЬ_TANZIL_ПО_УМОЛЧАНИЮ = str(
    pathlib.Path(__file__).resolve().parent.parent / 'content' / 'quran' / 'quran-uthmani-marks.xml')
АРАБСКИЙ_ОТРЕЗОК = re.compile('[؀-ۿݐ-ݿࢠ-ࣿ]+')


def путь_tanzil(аргументы):
    """--tanzil ПУТЬ в аргументах, иначе переменная MUGALIM_TANZIL_XML, иначе путь по умолчанию."""
    if '--tanzil' in аргументы:
        return аргументы[аргументы.index('--tanzil') + 1]
    return os.environ.get('MUGALIM_TANZIL_XML') or ПУТЬ_TANZIL_ПО_УМОЛЧАНИЮ


def sha256_строки(строка):
    return hashlib.sha256(строка.encode('utf-8')).hexdigest()


def sha256_файла(путь):
    with open(путь, 'rb') as ф:
        return hashlib.sha256(ф.read()).hexdigest()


def прочитать_tanzil(путь):
    """Возвращает ({(сура, аят): текст}, шапка-комментарий дословно, sha256 файла)."""
    with open(путь, 'r', encoding='utf-8') as ф:
        сырой = ф.read()
    шапка = сырой[сырой.index('<!--') + 4:сырой.index('-->')]
    корень = ET.fromstring(сырой.encode('utf-8'))
    аяты = {}
    for сура in корень.iter('sura'):
        for аят in сура.iter('aya'):
            аяты[(int(сура.get('index')), int(аят.get('index')))] = аят.get('text')
    return аяты, шапка, sha256_файла(путь)


def единицы(строка):
    """Разбивает строку на [(буква, знаки)]; пробелы и знаки препинания — отдельными единицами без знаков."""
    результат = []
    for символ in строка:
        if unicodedata.category(символ) == 'Mn' and результат:
            буква, знаки = результат[-1]
            результат[-1] = (буква, знаки + символ)
        else:
            результат.append((символ, ''))
    return результат


def буквы(строка):
    """Только буквы (без татвиля, пробелов, знаков препинания)."""
    return [б for б, _ in единицы(строка) if unicodedata.category(б) == 'Lo' and б != ТАТВИЛЬ]


def огласовка(знаки):
    for з in знаки:
        if з in ГЛАСНЫЕ:
            return з
    return СУКУН if СУКУН in знаки else None


def транскрипция(строка):
    """Учебная транскрипция кириллицей (каталог §10.1). Только для учебных слогов и слов уровня 1."""
    слова_ = []
    for слово in re.split(r'[\s،]+', строка.strip()):
        if not слово:
            continue
        выход, прежний_гласный = [], None
        ед = [(б, з) for б, з in единицы(слово) if б != ТАТВИЛЬ]
        for и, (б, з) in enumerate(ед):
            гл = огласовка(з)
            if б in ХАМЗЫ:
                согл = '' if и == 0 else '’'
            elif б == 'ا':
                if гл is None:
                    raise ValueError(f'алиф без знака в учебной строке: {строка!r}')
                согл = ''
            elif б == 'و' and гл == СУКУН and прежний_гласный == 'а':
                согл = 'у'
            elif б == 'ل' and гл == СУКУН:
                согл = 'ль'
            elif б in СОГЛАСНЫЕ:
                согл = СОГЛАСНЫЕ[б]
            else:
                raise ValueError(f'нет транскрипции для {б!r} в {строка!r}')
            if ШАДДА in з or any(т in з for т in ТАНВИНЫ):
                raise ValueError(f'шадда/танвин на уровне 1 не транскрибируются: {строка!r}')
            гласный = ГЛАСНЫЕ.get(гл, '') if гл else ''
            выход.append(согл + гласный)
            прежний_гласный = гласный or None
        слова_.append(''.join(выход))
    return ' '.join(слова_)


def слоги(слово):
    """Слоги учебного слова: каждый начинается с огласованной буквы, буквы с сукуном замыкают слог."""
    результат = []
    for б, з in единицы(слово):
        гл = огласовка(з)
        if гл in ГЛАСНЫЕ:
            результат.append(б + з)
        elif гл == СУКУН and результат:
            результат[-1] += б + з
        else:
            raise ValueError(f'слог не может начаться с {б + з!r} в {слово!r}')
    return результат


def лестница(слово):
    """Ступени «Муаллим сани»: открытый слог → закрытый слог → закрытые основы → слово целиком."""
    с = слоги(слово)
    первая = единицы(с[0])
    ступени = [первая[0][0] + первая[0][1]]
    if len(первая) > 1:
        ступени.append(с[0])
    накоплено = с[0]
    for слог in с[1:-1]:
        накоплено += слог
        if огласовка(единицы(слог)[-1][1]) == СУКУН:
            ступени.append(накоплено)
    if ступени[-1] != слово:
        ступени.append(слово)
    return ступени
