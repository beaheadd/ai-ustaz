def контур(d, n=24):
    """Точки пути (абсолютные M L C Q Z), n точек на сегмент."""
    т = re.findall(r'[MLCQZ]|-?\d+(?:\.\d+)?', d)
    i, команда, cur, start, pts = 0, None, None, None, []

    def ч():
        nonlocal i
        i += 2
        return float(т[i - 2]), float(т[i - 1])
    while i < len(т):
        if т[i] in 'MLCQZ':
            команда = т[i]
            i += 1
            if команда == 'Z':
                pts.append(start)
                cur = start
                continue
        if команда == 'M':
            cur = start = ч()
            pts.append(cur)
            команда = 'L'
            continue
        опорные = [cur] + [ч() for _ in range({'L': 1, 'Q': 2, 'C': 3}[команда])]
        for k in range(1, n + 1):
            t = k / n
            pp = опорные
            while len(pp) > 1:   # де Кастельжо
                pp = [(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t) for a, b in zip(pp, pp[1:])]
            pts.append(pp[0])
        cur = опорные[-1]
    return pts


def вдоль(d, рамка, центр, сдвиг):
    """Линия по поверхности органа d внутри рамки (x0, y0, x1, y1), сдвинутая на «сдвиг» внутрь органа (к центру)."""
    return 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in точки_вдоль(d, рамка, центр, сдвиг))


def полоска(d, рамка, центр, толщина):
    """Залитая полоска по поверхности органа внутрь на «толщину» (кромка зуба — «куда»)."""
    снаружи = точки_вдоль(d, рамка, центр, 0)
    внутри = точки_вдоль(d, рамка, центр, толщина)[::-1]
    return 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in снаружи + внутри) + 'Z'


def точки_вдоль(d, рамка, центр, сдвиг):
    """Точки линии вдоль() (не больше 8)."""
    x0, y0, x1, y1 = рамка
    pts = контур(d)
    куски, кусок = [], []
    for p in pts:
        if x0 <= p[0] <= x1 and y0 <= p[1] <= y1:
            кусок.append(p)
        elif кусок:
            куски.append(кусок)
            кусок = []
    куски.append(кусок)
    кусок = max(куски, key=len)
    if len(кусок) < 2:
        raise ValueError(f'нет поверхности в рамке {рамка}')
    итог = []
    for j, (x, y) in enumerate(кусок):
        a, b = кусок[max(0, j - 1)], кусок[min(len(кусок) - 1, j + 1)]
        nx, ny = -(b[1] - a[1]), b[0] - a[0]
        длина = math.hypot(nx, ny) or 1
        nx, ny = nx / длина, ny / длина
        if nx * (центр[0] - x) + ny * (центр[1] - y) < 0:
            nx, ny = -nx, -ny
        итог.append((x + nx * сдвиг, y + ny * сдвиг))
    шаг = max(1, len(итог) // 6)
    return итог[::шаг] + ([итог[-1]] if (len(итог) - 1) % шаг else [])


