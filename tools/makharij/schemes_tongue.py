def схема_lam_nun_ra(н, активный=None):
    """Ревью 19.11 (по бейтам «وَاللَّامُ أَدْنَاهَا لِمُنْتَهَاهَا … وَالنُّونُ مِنْ طَرَفِهِ تَحْتُ … وَالرَّا يُدَانِيهِ لِظَهْرٍ أَدْخَلُ»):
    10 ن — сам кончик у десны резцов, ниже всех; 11 ر — кончик вместе со спинкой у кончика, к десне чуть глубже;
    9 ل — кончик и передняя часть языка у десны резцов и альвеол (по средней линии — там же, где ن и ر, не глубже по
    нёбу); боковые края ل видны только сверху (mx-lam-top). На общей схеме линии ل — внутренний ряд (глубже в языке
    и в десне), чтобы не сливаться с ن и ر."""
    я = ЯЗЫК['кончик-вверх']
    сл = 1.6 if активный == н['lam'] else 4.2   # в варианте ل — по поверхности, на общей схеме — внутренний ряд
    зоны = {
        'lam': о.зона(н['lam'], о.путь(вдоль(я, (59.5, 113, 72, 130), ЦЕНТР_ЯЗЫКА, сл), 'a'),
                      о.путь(вдоль(НЁБО, (58.5, 112, 71, 122), ЦЕНТР_НЁБА, сл), 'p'),
                      о.номер(9, 66, 100.5, (65, 115.5 - сл), Т)),
        'nun': о.зона(н['nun'], о.путь(вдоль(я, (59.5, 121, 62.5, 130), ЦЕНТР_ЯЗЫКА, 1.6), 'a'),
                      о.путь(вдоль(НЁБО, (58.5, 117.5, 61.5, 122), ЦЕНТР_НЁБА, 1.6), 'p'),
                      о.номер(10, 54, 100.5, (59.6, 119.8), Т)),
        'ra': о.зона(н['ra'], о.путь(вдоль(я, (60.5, 114, 73, 124), ЦЕНТР_ЯЗЫКА, 1.6), 'a'),
                     о.путь(вдоль(НЁБО, (62.5, 110, 72, 117.5), ЦЕНТР_НЁБА, 1.6), 'p'),
                     о.номер(11, 78, 100.5, (70.5, 113.2), Т)),
    }
    # выделенный махрадж рисуем последним — поверх бледных соседей
    порядок = sorted(зоны, key=lambda к: н[к] == активный)
    return о.разрез(я) + ''.join(зоны[к] for к in порядок)


def схема_nitiyya(н, активный=None):
    """12 ط د ت — кончик языка у оснований верхних резцов: на стыке зуба и десны (ниже места ن, которое на десне)."""
    я = ЯЗЫК['кончик-к-корням']
    return о.разрез(я) + о.зона(
        н['nitiyya'], о.путь(вдоль(о.П['резец_верх'], (56, 121.5, 60, 129.5), ЦЕНТР_РЕЗЦА_ВЕРХ, 1.6), 'p'),
        о.путь(вдоль(я, (56.5, 126, 63, 137), ЦЕНТР_ЯЗЫКА, 1.6), 'a'), о.номер(12, 54, 100.5, (58.2, 125.5), Т))


def схема_asaliyya(н, активный=None):
    """13 ص س ز — кончик языка над нижними резцами; узкая щель — путь воздуха (свист)."""
    я = ЯЗЫК['кончик-вниз']
    # Зубы почти сомкнуты, губы чуть разведены: воздух идёт по желобку языка, через щель у краёв резцов — наружу.
    низ = 3
    резец_низ = сд(о.П['резец_низ'], 0, низ)
    воздух = 'M108,112C92,114 80,120 72,128C66,135 60,143 54,151C50,156 46,160 40,161L22,161'
    return о.разрез(я, губа_низ=сд(о.ГУБА_НИЗ['покой'], 0, 7), сдвиг_низа=низ) + о.зона(
        н['asaliyya'], о.путь(вдоль(резец_низ, (52, 146 + низ, 58.5, 158 + низ), ЦЕНТР_РЕЗЦА_НИЗ, 1.6), 'p'),
        о.путь(вдоль(я, (57, 143, 65, 160), ЦЕНТР_ЯЗЫКА, 1.6), 'a'),
        о.путь(воздух, 'w'), о.стрелка(18, 161, 180, Р), о.номер(13, 73, 151, (63, 151), Р))


def схема_lithawiyya(н, активный=None):
    """14 ظ ذ ث — кончик языка между резцами, у кромки верхних; рот приоткрыт чуть-чуть: нижняя губа почти касается
    кончика языка (ревью 19.11)."""
    я = ЯЗЫК['кончик-между-зубов']
    return о.разрез(я, губа_низ=сд(о.ГУБА_НИЗ['покой'], 0, 10), сдвиг_низа=10) + о.зона(
        н['lithawiyya'], о.путь(КРОМКА_РЕЗЦА, 'pf'),
        о.путь(вдоль(я, (36, 157, 50, 161), ЦЕНТР_ЯЗЫКА, 1.6), 'a'), о.номер(14, 20, 156, (37, 161), Р))


