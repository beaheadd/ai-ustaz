def точка_дуги(угол, отступ=0.0):
    """Угол от середины переда, со знаком: минус — левая сторона говорящего (слева на рисунке)."""
    р = math.radians(abs(угол))
    x = ДУГА['cx'] + (ДУГА['a'] - отступ) * math.sin(р)
    y = ДУГА['cy'] - (ДУГА['b'] - отступ) * math.cos(р)
    return (2 * ДУГА['cx'] - x if угол < 0 else x), y


def раскладка_зубов():
    """[(название, угол_начала, угол_центра, угол_конца, ширина, глубина)] для правой стороны (углы > 0)."""
    углы, длины, всего = [0.0], [0.0], 0.0
    x0, y0 = точка_дуги(0)
    у = 0.0
    while у < УГОЛ_КОНЦА:
        у = min(УГОЛ_КОНЦА, у + 0.25)
        x1, y1 = точка_дуги(у)
        всего += math.hypot(x1 - x0, y1 - y0)
        углы.append(у)
        длины.append(всего)
        x0, y0 = x1, y1

    def угол(s):
        for i in range(1, len(длины)):
            if длины[i] >= s:
                k = (s - длины[i - 1]) / (длины[i] - длины[i - 1])
                return углы[i - 1] + k * (углы[i] - углы[i - 1])
        return углы[-1]
    сумма = sum(w for _, w, _ in ЗУБЫ)
    итог, s = [], 0.0
    for имя, w, глубина in ЗУБЫ:
        ширина = всего * w / сумма
        итог.append((имя, угол(s), угол(s + ширина / 2), угол(s + ширина), ширина, глубина))
        s += ширина
    return итог


def углы_зуба(имя):
    return next(з[1:4] for з in раскладка_зубов() if з[0] == имя)


def зуб(уц, ширина, глубина, сторона, класс):
    x, y = точка_дуги(уц * сторона, глубина / 2 - 2)
    р = math.radians(уц)
    наклон = math.degrees(math.atan2(ДУГА['b'] * math.sin(р), ДУГА['a'] * math.cos(р))) * сторона
    return (f'<rect class="{класс}" x="{x - ширина / 2 + 1:.0f}" y="{y - глубина / 2:.0f}" width="{ширина - 2:.0f}" '
            f'height="{глубина}" rx="{min(5, глубина / 2.6):.0f}" transform="rotate({наклон:.0f} {x:.0f} {y:.0f})"/>')


def кривая(у0, у1, отступ, шаг=4.0):
    """Ломаная вдоль дуги от угла у0 до у1 (градусы со знаком)."""
    n = max(2, int(abs(у1 - у0) / шаг) + 1)
    return 'M' + 'L'.join('%.0f,%.0f' % точка_дуги(у0 + (у1 - у0) * i / n, отступ) for i in range(n + 1))


def вид_сверху(залить=(), бледно=()):
    """Зубной ряд сверху; залить / бледно — множества (сторона, зуб): «куда» — залитые зубы; бледно — вторая, тоже
    допустимая сторона (та же заливка, прозрачнее; ревью 19.11: пунктир в схемах значит только воздух)."""
    внутр = [точка_дуги(у, ОТСТУП_ДЕСНЫ) for у in range(-УГОЛ_КОНЦА, УГОЛ_КОНЦА + 1, 7)]
    нёбо = 'M' + 'L'.join(f'{x:.0f},{y:.0f}' for x, y in внутр) + f'L{внутр[-1][0]:.0f},330L{внутр[0][0]:.0f},330Z'
    край = [точка_дуги(у, ОТСТУП_ЯЗЫКА) for у in range(-100, 101, 5)]
    язык = 'M' + 'L'.join(f'{x:.0f},{y:.0f}' for x, y in край) + f'L{край[-1][0]:.0f},330L{край[0][0]:.0f},330Z'
    # знак «вперёд, к губам» — треугольник над резцами (без губ и лица); нёбо — ткань внутри ряда; язык — «сквозь» нёбо
    s = '<path class="d" d="M160,48L169,62L151,62Z"/>'
    s += f'<path class="t" d="{нёбо}"/><path class="g" d="{язык}"/>'
    s += '<path class="h" d="M160,%.0fL160,318"/>' % (точка_дуги(0, ОТСТУП_ЯЗЫКА)[1] + 16)  # срединная борозда языка
    for имя, _, уц, _, ширина, глубина in раскладка_зубов():
        for сторона in (-1, 1):
            класс = 'pf' if (сторона, имя) in залить else 'pf o' if (сторона, имя) in бледно else 'd'
            s += зуб(уц, ширина, глубина, сторона, класс)
    return s


def точка(угол, отступ):
    x, y = точка_дуги(угол, отступ)
    return round(x), round(y)


