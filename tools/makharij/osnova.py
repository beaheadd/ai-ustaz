def _лупа(рисунок, cx, cy, r, масштаб, откуда):
    ox, oy = откуда
    # содержимое: та же разметка, увеличенная вокруг точки «откуда» и перенесённая в центр лупы
    tx, ty = cx - ox * масштаб, cy - oy * масштаб
    содержимое = рисунок.replace('id="cy"', 'id="cy2"').replace('url(#cy)', 'url(#cy2)')
    return (f'<clipPath id="cl"><circle cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r)}"/></clipPath>'
            f'<path class="лл" d="M{пт((ox, oy))}L{пт((cx, cy))}"/>'
            f'<circle class="лп" cx="{ч(ox)}" cy="{ч(oy)}" r="{ч(r / масштаб)}"/>'
            f'<circle cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r + 2)}" fill="#fbf7ee"/>'
            f'<g clip-path="url(#cl)"><g transform="translate({ч(tx)} {ч(ty)}) scale({масштаб})">{содержимое}</g></g>'
            f'<circle class="лп" cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r)}" style="stroke-width:1.6"/>')


