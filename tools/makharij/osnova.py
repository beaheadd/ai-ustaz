def _лупа(cx, cy, r, масштаб, откуда):
    """Круглая лупа: группа #a (анатомия + подсветка), увеличенная вокруг точки «откуда»."""
    ox, oy = откуда
    tx, ty = cx - ox * масштаб, cy - oy * масштаб
    rs = r / масштаб
    dx, dy = cx - ox, cy - oy
    L = math.hypot(dx, dy)
    ux, uy = dx / L, dy / L
    return (f'<clipPath id="cl"><circle cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r)}"/></clipPath>'
            f'<path class="лл" d="M{пт((ox + ux * rs, oy + uy * rs))}L{пт((cx - ux * r, cy - uy * r))}"/>'
            f'<circle class="лп" cx="{ч(ox)}" cy="{ч(oy)}" r="{ч(rs)}" style="stroke-width:.9"/>'
            f'<circle cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r + 2.5)}" style="fill:#fbf7ee;stroke:#d9cdb6"/>'
            f'<g clip-path="url(#cl)"><use href="#a" transform="translate({ч(tx)} {ч(ty)}) scale({ч(масштаб)})"/></g>'
            f'<circle class="лп" cx="{ч(cx)}" cy="{ч(cy)}" r="{ч(r)}" style="stroke-width:1.5"/>')


def в_лупе(лупа, p):
    """Координаты точки рисунка внутри лупы."""
    cx, cy, r, м, (ox, oy) = лупа
    return (cx + (p[0] - ox) * м, cy + (p[1] - oy) * м)


