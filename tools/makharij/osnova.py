"""Общая основа схем махраджей: разрез речевого тракта 320×320 без лица и примитивы подсветки.

Назначение: одна геометрия для всех схем-разрезов (губы слева, гортань справа внизу, нёбо сверху), чтобы схемы
разных групп совпадали линия в линию. Геометрия — tools/makharij/geometry.json (точки, зоны горла, пути органов),
описание — tools/makharij/_основа-описание.md.
Контракт:
  ГЕО — содержимое geometry.json; П — пути органов (ГЕО['пути']);
  ВИД, ВИД_КРУПНО, ВИД_КОНЧИК, ВИД_РЕЗЦЫ — (x, y, w, h) окна viewBox: весь разрез; губы ×2; кончик языка у дёсен ×5;
    кромки резцов и губы ×5; ПИКСЕЛИ — (ширина, высота) атрибутов <svg>; КРУПНО, КОНЧИК, РЕЗЦЫ — масштабы окон;
  разрез(язык=путь_или_имя, губа_верх=, губа_низ=, нос=False, сдвиг_низа=0, полость='') → разметка
    анатомии без подсветки (слои — ГЕО['слои']); язык и губы — имя позы из ЯЗЫК/ГУБА_ВЕРХ/ГУБА_НИЗ или готовый путь;
    сдвиг_низа — рот приоткрыт: нижняя челюсть (дно рта + нижний резец) поворачивается вокруг шарнира так, что
    резец опускается на сдвиг_низа (ревью 19.11: раньше опускался только резец, «утопая» в десне);
  путь(d, класс, стиль=''), зона, номер, стрелка — те же примитивы, что в build_makharij.py (классы стиля — build_makharij.стиль()).
Решение владельца 19.11.2026: «картинка произношения каждой буквы»; рисуем свои схемы с нуля (рисунки «Көрнекі тәжуид»
не копируем и не обводим). Правило 9: без лица — нет контура лица, глаз, носа, подбородка; полость носа только на
схеме гунны и только как внутренняя полость.
"""
import json
