def воздух(точки):
    """Путь воздуха: светлая подложка + голубой пунктир + стрелка на конце."""
    d = сплайн(точки)
    (x1, y1), (x2, y2) = точки[-2], точки[-1]
    а = math.atan2(y2 - y1, x2 - x1)
    к = [(x2 + 5 * math.cos(а), y2 + 5 * math.sin(а)),
         (x2 + 4.5 * math.cos(а + 2.5), y2 + 4.5 * math.sin(а + 2.5)),
         (x2 + 4.5 * math.cos(а - 2.5), y2 + 4.5 * math.sin(а - 2.5))]
    return (путь(d, 'wф') + путь(d, 'w')
            + f'<path class="wс" d="M{пт(к[0])}L{пт(к[1])}L{пт(к[2])}Z"/>')


def номер(x, y, n, к=None):
    """Кружок с номером махраджа; к=(x, y) — тонкая выноска к месту."""
