def зуб(край, верх, профиль):
    """Контур зуба по оси: край (режущий край), верх (верхушка корня); профиль — [(t, губная, язычная)] —
    полуширины вдоль оси (t=0 — край, t=1 — верхушка). → (губная сторона, язычная сторона)."""
    ex, ey = край
    ax, ay = верх
    dx, dy = ax - ex, ay - ey
    L = math.hypot(dx, dy)
    ux, uy = dx / L, dy / L
    # нормаль к губам: для верхнего зуба (ось вверх) — влево, для нижнего (ось вниз) — тоже влево
    nx, ny = (uy, -ux) if dy < 0 else (-uy, ux)
    губ = [(ex + ux * L * t + nx * w, ey + uy * L * t + ny * w) for t, w, _ in профиль]
    яз = [(ex + ux * L * t - nx * w, ey + uy * L * t - ny * w) for t, _, w in профиль]
    return губ, яз


