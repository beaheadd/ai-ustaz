ГУБА_НИЗ = {
    'покой': П['губа_низ_покой'],
    'сомкнута': 'M42,152C35,152 27,152 21,155C16,162 16,175 20,184C25,193 37,196 47,193L47,160Z',
    # ف: губа поднята и чуть подтянута назад, её внутренняя кромка — под краем верхних резцов
    'под-резцами': 'M47,163C46,159 44,157 40,157C32,156 23,159 20,166C17,175 19,185 25,191C31,196 40,197 47,193Z',
    # джауф: рот приоткрыт
    'открыта': 'M47,172C39,169 29,169 23,174C17,181 17,193 21,201C26,209 37,212 47,209Z',
}


def путь(d, класс, стиль=''):
    return f'<path class="{класс}"' + (f' style="{стиль}"' if стиль else '') + f' d="{d}"/>'


def зона(якорь, *части):
    return f'<g id="{якорь}" class="z">' + ''.join(части) + '</g>'


def номер(n, x, y, к_точке=None, м=1):
    """Кружок с номером махраджа; к_точке=(x, y) — выноска с точкой на конце; м — увеличение схемы."""
    s = ''
    r = 12 / м   # ревью 19.11: кружок ≈ 21 px и цифра ≈ 11 px на карточке 280 px
    if к_точке:
        tx, ty = к_точке
        длина = math.hypot(tx - x, ty - y)
        if длина > r + 1:
            sx, sy = x + (tx - x) * r / длина, y + (ty - y) * r / длина
            s += (f'<path class="l" d="M{sx:.1f},{sy:.1f}L{tx},{ty}"/>'
                  f'<circle class="ld" cx="{tx}" cy="{ty}" r="{2.2 / м:g}"/>')
    return s + f'<circle class="k" cx="{x}" cy="{y}" r="{r:g}"/><text class="kt" x="{x}" y="{y}" dy=".36em">{n}</text>'


def стрелка(x, y, угол, м=1):
    """Наконечник пути воздуха в точке (x, y); угол — направление в градусах (0 — вправо, 90 — вниз)."""
    р = math.radians(угол)

    def т(dx, dy):
        dx, dy = dx / м, dy / м
        return x + dx * math.cos(р) - dy * math.sin(р), y + dx * math.sin(р) + dy * math.cos(р)
    точки = [т(0, 0), т(-9, -5), т(-9, 5)]
    return '<path class="wh" d="M' + 'L'.join(f'{a:.1f},{b:.1f}' for a, b in точки) + 'Z"/>'


def _поза(значение, словарь):
    return словарь.get(значение, значение)


def разрез(язык='покой', губа_верх='покой', губа_низ='покой', нос=False, сдвиг_низа=0, полость=''):
    """Анатомия разреза без подсветки. нос=True — мягкое нёбо опущено, видна полость носа (только гунна);
    сдвиг_низа — рот приоткрыт (поворот нижней челюсти); полость — разметка поверх полости носа (подсветка зоны)."""
    s = ''
    if нос:
        # заливка полости без обводки (низ полости — открытый проход в горло), обводка — только свод
        s += (путь(П['полость_носа'], 'c', 'stroke:none') + полость + путь(П['свод_носа'], 't', 'fill:none')
              + путь(П['раковины_носа'], 'h'))
    s += путь(П['резец_верх'], 'd') + путь(П['пульпа_резец_верх'], 'h')
    s += путь(П['ткань_верх_нос'], 't') + путь(П['стенка_нос'], 't') if нос else путь(П['ткань_верх'], 't')
    челюсть = путь(П['резец_низ'], 'd') + путь(П['пульпа_резец_низ'], 'h') + путь(П['дно_рта'], 't')
    if сдвиг_низа:
        # поворот вокруг шарнира (против часовой на экране): резец (x ≈ 52) опускается на сдвиг_низа
        угол = -math.degrees(сдвиг_низа / (ШАРНИР[0] - 52))
        челюсть = f'<g transform="rotate({угол:.2f} {ШАРНИР[0]} {ШАРНИР[1]})">{челюсть}</g>'
    s += челюсть + ''.join(путь(П[к], 't') for к in ('гортань_перёд', 'связки'))
    s += путь(_поза(язык, ЯЗЫК), 'g') + путь(П['надгортанник'], 't')
    s += путь(_поза(губа_верх, ГУБА_ВЕРХ), 'g') + путь(_поза(губа_низ, ГУБА_НИЗ), 'g')
    return s
