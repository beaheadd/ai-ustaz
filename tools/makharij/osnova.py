# ─────────────────────────── геометрия ───────────────────────────
def ч(x):
    """Число для SVG: одна цифра после точки, без лишних нулей."""
    с = f'{x:.1f}'
    if с.endswith('.0'):
        с = с[:-2]
    return '0' if с == '-0' else с


def пт(p):
    return f'{ч(p[0])},{ч(p[1])}'


def сплайн(точки, замкнуть=False, натяжение=1.0):
    """Гладкая кривая Катмулла — Рома через точки → путь из кубических Безье."""
    п = [tuple(t) for t in точки]
    n = len(п)
    if n < 2:
        return ''
    d = [f'M{пт(п[0])}']
    рёбра = n if замкнуть else n - 1
    for i in range(рёбра):
        p0 = п[(i - 1) % n] if (замкнуть or i > 0) else п[0]
        p1 = п[i]
        p2 = п[(i + 1) % n]
        p3 = п[(i + 2) % n] if (замкнуть or i + 2 < n) else п[-1]
        k = натяжение / 6
        c1 = (p1[0] + (p2[0] - p0[0]) * k, p1[1] + (p2[1] - p0[1]) * k)
        c2 = (p2[0] - (p3[0] - p1[0]) * k, p2[1] - (p3[1] - p1[1]) * k)
        d.append(f'C{пт(c1)} {пт(c2)} {пт(p2)}')
    if замкнуть:
        d.append('Z')
    return ''.join(d)


def поворот(p, угол, центр=ШАРНИР, вес=1.0):
    """Поворот точки вокруг центра на угол (градусы, + — челюсть вниз) с весом 0..1."""
    а = math.radians(-угол * вес)
    x, y = p[0] - центр[0], p[1] - центр[1]
    return (центр[0] + x * math.cos(а) - y * math.sin(а), центр[1] + x * math.sin(а) + y * math.cos(а))


def челюсть(точки, угол, затухание=None):
    """Точки нижней челюсти и того, что с ней движется. затухание=(x0, x1): вес 1 левее x0, 0 правее x1."""
    итог = []
    for p in точки:
        вес = 1.0
        if затухание:
            x0, x1 = затухание
            вес = max(0.0, min(1.0, (x1 - p[0]) / (x1 - x0)))
        итог.append(поворот(p, угол, вес=вес))
    return итог


def смесь(а, б, t):
    return [(x1 + (x2 - x1) * t, y1 + (y2 - y1) * t) for (x1, y1), (x2, y2) in zip(а, б)]


def путь(d, кл='', стиль='', доп=''):
    return (f'<path' + (f' class="{кл}"' if кл else '') + (f' style="{стиль}"' if стиль else '') + доп
            + f' d="{d}"/>')


