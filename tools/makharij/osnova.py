def нарисовать_зуб(край, верх, профиль, эмаль_t):
    губ, яз = зуб(край, верх, профиль)
    весь = губ + list(reversed(яз))
    n = sum(1 for t, *_ in профиль if t <= эмаль_t)
    коронка = губ[:n] + list(reversed(яз[:n]))
    ex, ey = край
    ax, ay = верх
    по_оси = [(ex + (ax - ex) * t, ey + (ay - ey) * t) for t in (.2, .38, .6, .8, .95)]
    ширина = [.9, 2.0, 1.5, .9, .3]
    L = math.hypot(ax - ex, ay - ey)
    nx, ny = (ay - ey) / L, -(ax - ex) / L
    п1 = [(x + nx * w, y + ny * w) for (x, y), w in zip(по_оси, ширина)]
    п2 = [(x - nx * w, y - ny * w) for (x, y), w in zip(по_оси, ширина)]
    return (путь(сплайн(весь, True, .7), 'кр') + путь(сплайн(п1 + list(reversed(п2)), True), 'пл')
            + путь(сплайн(коронка, True, .7), 'зб'))


def волокна(спинка, начало, n=20, изгиб=9):
    """Веер подбородочно-язычной мышцы: от подбородочной ости к точкам спинки, чуть выгнутые наружу."""
    дл = [0.0]
    for a, b in zip(спинка, спинка[1:]):
        дл.append(дл[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    всего = дл[-1]
    итог = []
    for i in range(n):
        s = всего * (0.04 + 0.93 * i / (n - 1))
        j = max(k for k in range(len(дл) - 1) if дл[k] <= s)
        t = (s - дл[j]) / max(1e-6, дл[j + 1] - дл[j])
        a, b = спинка[j], спинка[j + 1]
        x, y = a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t
        mx, my = (начало[0] + x) / 2, (начало[1] + y) / 2
        dx, dy = x - начало[0], y - начало[1]
        L = math.hypot(dx, dy) or 1
        к = изгиб * (0.5 - i / (n - 1)) * 2
        cx, cy = mx + dy / L * к, my - dx / L * к
        итог.append(f'M{пт(начало)}Q{пт((cx, cy))} {пт((x, y))}')
    return ''.join(итог)


def смещение(точки, d):
    """Кривая, смещённая на d вправо от направления обхода (для спинки от корня к кончику — внутрь языка)."""
    итог = []
    for i, p in enumerate(точки):
        a = точки[max(0, i - 1)]
        b = точки[min(len(точки) - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dy) or 1
        итог.append((p[0] - dy / L * d, p[1] + dx / L * d))
    return итог


