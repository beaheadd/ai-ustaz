АРАБСКИЙ = re.compile(r'[؀-ۿ]')
ОБЛАСТИ = ['area-jawf', 'area-halq', 'area-lisan', 'area-shafatan', 'area-khayshum']
МАДД = {'alif', 'waw', 'ya'}
ПРОБЫ_МАДДА = {'alif': 'آ', 'waw': 'أُو', 'ya': 'إِي', 'lam-alif': 'لَا'}
ПРОБЫ_ГУННЫ = {'nun': 'أَنَّ', 'mim': 'أَمَّ'}
ФАТХА, СУКУН, ШАДДА = 'َ', 'ْ', 'ّ'
ЛИН = {'waw', 'ya'}
SVG = '{http://www.w3.org/2000/svg}'

ошибки = []


def ошибка(т):
    ошибки.append(т)


def обойти_ru_kk(узел, путь_='$'):
    if isinstance(узел, dict):
        if 'ru' in узел or 'kk' in узел:
            for язык in ('ru', 'kk'):
                if not (isinstance(узел.get(язык), str) and узел[язык].strip()):
                    ошибка(f'{путь_}: нет непустого «{язык}» рядом с другим языком')
        for ключ, знач in узел.items():
            обойти_ru_kk(знач, f'{путь_}.{ключ}')
    elif isinstance(узел, list):
        for i, знач in enumerate(узел):
            обойти_ru_kk(знач, f'{путь_}[{i}]')


def имена_записей(б, з):
    """Имена файлов записи кари для буквы: <id>-<форма>.m4a (docs/записи-кари-буквы.md)."""
    if б in ('alif', 'lam-alif'):
        return [f'{б}-madd.m4a']
    формы = ['shadda', 'lin'] if б in ЛИН else ['sukun']
    формы += ['fatha', 'kasra', 'damma']
    if 'мадд' in з:
        формы.append('madd')
    if 'гунна' in з:
        формы.append('ghunna')
    return [f'{б}-{ф}.m4a' for ф in формы]


def проверить_шапку(д):
    if д.get('утверждено') is None and д.get('статус') != 'черновик':
        ошибка('статус должен быть «черновик», пока утверждено = null (правило 11: проверяет устаз)')
    if д.get('утверждено') is not None and not isinstance(д['утверждено'], dict):
        ошибка('утверждено: null или {кто, дата, версия}')
    if 'Джазари' not in д.get('источник', ''):
        ошибка('источник: нужен «Ибн аль-Джазари, аль-Мукаддима…»')
    бейты = д.get('мукаддима', {}).get('бейты', [])
    if len(бейты) != 11 or any(len(б) != 2 or not all(АРАБСКИЙ.search(п) for п in б) for б in бейты):
        ошибка('мукаддима.бейты: 11 бейтов главы о махраджах, по два полустишия')


def проверить_махраджи(д):
    махраджи = д['махраджи']
    if [м['номер'] for м in махраджи] != list(range(1, 18)):
        ошибка(f'номера махраджей должны идти 1–17 по порядку: {[м["номер"] for м in махраджи]}')
    ид = [м['id'] for м in махраджи]
    if len(set(ид)) != len(ид):
        ошибка('повторяются id махраджей')
    if [о['id'] for о in д['области']] != ОБЛАСТИ:
        ошибка(f'области — ровно {ОБЛАСТИ} по порядку')
    в_областях = [м for о in д['области'] for м in о['махраджи']]
    if sorted(в_областях) != sorted(ид):
        ошибка('каждый махрадж — ровно в одной области')
    по_области = {м: о['id'] for о in д['области'] for м in о['махраджи']}
    for м in махраджи:
        где = f'махрадж {м["номер"]} ({м["id"]})'
        if по_области.get(м['id']) != м['область']:
            ошибка(f'{где}: область {м["область"]} ≠ списку области')
        ар = м.get('арабский', {})
        for поле in ('название', 'описание', 'стих'):
            if not АРАБСКИЙ.search(ар.get(поле, '')):
                ошибка(f'{где}: нет арабского «{поле}»')
        for поле in ('название', 'описание'):
            if not isinstance(м.get(поле), dict):
                ошибка(f'{где}: нет «{поле}» {{ru, kk}}')
        п = м.get('подсветка', {})
        if п.get('якорь') != f'm{м["номер"]}':
            ошибка(f'{где}: якорь подсветки должен быть m{м["номер"]}')
        if not isinstance(п.get('что'), dict):
            ошибка(f'{где}: подсветка.что {{ru, kk}}')
        if 'куда' not in п:
            ошибка(f'{где}: подсветка.куда — {{ru, kk}} или null')
    # Порядок областей = порядок номеров (от глубины к губам, затем хайшум).
    порядок = [ОБЛАСТИ.index(м['область']) for м in махраджи]
    if порядок != sorted(порядок):
        ошибка('номера махраджей должны идти по областям: джауф → горло → язык → губы → хайшум')


def проверить_буквы(д):
    буквы_json = json.loads(к.ПУТЬ_БУКВ.read_text(encoding='utf-8'))
    знаки = {б['id']: б['знак'] for б in буквы_json}
    виды = {б['id']: б['вид'] for б in буквы_json}
    карта = д['буквы']
    махраджи = {м['id']: м for м in д['махраджи']}
    if set(карта) != set(знаки):
        ошибка(f'буквы: нет записи для {sorted(set(знаки) - set(карта))}, лишние {sorted(set(карта) - set(знаки))}')
    for м in д['махраджи']:
        for б in м['буквы']:
            if б not in знаки:
                ошибка(f'махрадж {м["id"]}: неизвестная буква {б}')
            elif виды[б] == 'лигатура':
                ошибка(f'махрадж {м["id"]}: лигатура {б} — не в списке букв махраджа (только в «буквы» с «состав»)')
    for б, вид in виды.items():
        if вид == 'лигатура':
            continue
        где = {м for м, з in махраджи.items() if б in з['буквы']}
        без_джауфа = где - {'jawf'}
        if б in МАДД:
            if 'jawf' not in где:
                ошибка(f'буква {б}: буква мадда — должна быть и в jawf')
            if б == 'alif' and без_джауфа:
                ошибка(f'буква alif — только в jawf, а есть ещё в {sorted(без_джауфа)}')
            if б != 'alif' and len(без_джауфа) != 1:
                ошибка(f'буква {б}: кроме jawf — ровно один махрадж, есть {sorted(без_джауфа)}')
        else:
            if 'jawf' in где:
                ошибка(f'буква {б}: не буква мадда, а стоит в jawf')
            if len(без_джауфа) != 1:
                ошибка(f'буква {б}: должна быть ровно в одном махрадже, есть {sorted(без_джауфа)}')
    носители = set(махраджи['khayshum'].get('гунна', {}).get('носители', []))
    for б, з in карта.items():
        м = з.get('махрадж')
        if м not in махраджи:
            ошибка(f'буквы.{б}: неизвестный махрадж {м}')
            continue
        if виды.get(б) == 'лигатура':
            состав = з.get('состав', [])
            if not состав or any(с not in знаки for с in состав):
                ошибка(f'буквы.{б}: «состав» из букв letters.json')
            elif карта[состав[0]]['махрадж'] != м:
                ошибка(f'буквы.{б}: махрадж = махраджу первой буквы состава ({состав[0]})')
        elif б not in махраджи[м]['буквы']:
            ошибка(f'буквы.{б}: махрадж {м}, но буквы нет в его списке')
        elif б in МАДД and б != 'alif' and м == 'jawf':
            ошибка(f'буквы.{б}: основной махрадж — согласной буквы, мадд — в поле «мадд»')
        if (б in МАДД - {'alif'} or б == 'lam-alif') != ('мадд' in з):
            ошибка(f'буквы.{б}: поле «мадд» — только у و, ي и лям-алифа')
        if 'мадд' in з and з['мадд'].get('махрадж') != 'jawf':
            ошибка(f'буквы.{б}.мадд: махрадж jawf')
        if ('гунна' in з) != (б in носители):
            ошибка(f'буквы.{б}: поле «гунна» — ровно у носителей гунны хайшума {sorted(носители)}')
        if 'гунна' in з and з['гунна'].get('махрадж') != 'khayshum':
            ошибка(f'буквы.{б}.гунна: махрадж khayshum')
        # Пробы.
        проба = з.get('проба', '')
        if б in ПРОБЫ_МАДДА and б not in ЛИН:
            нужно = ПРОБЫ_МАДДА[б]
        elif б in ЛИН:
            нужно = 'أ' + ФАТХА + знаки[б] + ФАТХА + ШАДДА
        else:
            нужно = 'أ' + ФАТХА + знаки[б] + СУКУН
        if проба != нужно:
            ошибка(f'буквы.{б}: проба «{проба}», ожидается «{нужно}»')
        if (б in ЛИН) != ('лин' in з):
            ошибка(f'буквы.{б}: поле «лин» — только у و и ي')
        if 'лин' in з:
            if з['лин'].get('проба') != 'أ' + ФАТХА + знаки[б] + СУКУН:
                ошибка(f'буквы.{б}.лин: проба «хамза с фатхой + буква с сукуном»')
            if з['лин'].get('махрадж') != м or not isinstance(з['лин'].get('примечание'), dict):
                ошибка(f'буквы.{б}.лин: махрадж как у буквы и примечание {{ru, kk}} о разногласии')
        if 'мадд' in з and з['мадд'].get('проба') != ПРОБЫ_МАДДА[б]:
            ошибка(f'буквы.{б}.мадд: проба «{з["мадд"].get("проба")}», ожидается «{ПРОБЫ_МАДДА[б]}»')
        if 'гунна' in з and з['гунна'].get('проба') != ПРОБЫ_ГУННЫ.get(б):
            ошибка(f'буквы.{б}.гунна: проба «{з["гунна"].get("проба")}», ожидается «{ПРОБЫ_ГУННЫ.get(б)}»')
    # Список для записи кари.
    if not к.ПУТЬ_ЗАПИСЕЙ.exists():
        ошибка(f'нет {к.ПУТЬ_ЗАПИСЕЙ.relative_to(к.КОРЕНЬ)}')
    else:
        текст = к.ПУТЬ_ЗАПИСЕЙ.read_text(encoding='utf-8')
        пробы = {з['проба'] for з in карта.values()}
        пробы |= {з[доп]['проба'] for з in карта.values() for доп in сборка.ДОП_ЗАПИСИ if доп in з}
        for п in sorted(пробы):
            if п not in текст:
                ошибка(f'проба «{п}» не попала в {к.ПУТЬ_ЗАПИСЕЙ.name}')
        for б, з in карта.items():
            for имя in имена_записей(б, з):
                if f'`{имя}`' not in текст:
                    ошибка(f'буква {б}: нет имени файла записи `{имя}` в {к.ПУТЬ_ЗАПИСЕЙ.name}')


def проверить_svg(имя, байты, якоря_нужны):
    где = f'схема {имя}'
    текст = байты.decode('utf-8')
    for u in re.findall(r'https?://[^\s"\'<>)]+', текст):
        if u != 'http://www.w3.org/2000/svg':
            ошибка(f'{где}: внешний URL {u}')
    if re.search(r'url\((?!#)', текст):
        ошибка(f'{где}: url(...) не на внутренний id')
    try:
        корень = ET.fromstring(байты)
    except ET.ParseError as е:
        ошибка(f'{где}: не XML — {е}')
        return
    if корень.tag != SVG + 'svg' or not корень.get('viewBox'):
        ошибка(f'{где}: корень — <svg viewBox>')
    if корень.get('class') != 'mx':
        ошибка(f'{где}: у корня class="mx" (тема и подсветка)')
    стиль_ = ''.join(эл.text or '' for эл in корень.iter(SVG + 'style'))
    for правило in re.findall(r'([^{}]+)\{[^{}]*stroke-dasharray', стиль_):
        if правило.strip() != '.w':
            ошибка(f'{где}: пунктир у «{правило.strip()}» — пунктир только у воздуха (.w)')
    if 'stroke-dasharray' in re.sub(r'<style>.*?</style>', '', текст, flags=re.S):
        ошибка(f'{где}: stroke-dasharray вне стиля — пунктир только у воздуха (.w)')
    заголовок = корень.find(SVG + 'title')
    if заголовок is None or not (заголовок.text or '').strip():
        ошибка(f'{где}: нет <title>')
    ид = set()
    ссылки = []
    for эл in корень.iter():
        тег = эл.tag.replace(SVG, '')
        if тег in ('script', 'foreignObject', 'image', 'a', 'iframe', 'feImage'):
            ошибка(f'{где}: запрещённый элемент <{тег}>')
        for атр, знач in эл.attrib.items():
            if атр.lower().startswith('on'):
                ошибка(f'{где}: запрещённый атрибут {атр}')
            elif атр.endswith('href'):
                if тег == 'use' and атр == 'href' and re.fullmatch(r'#[A-Za-z][\w-]*', знач):
                    ссылки.append(знач[1:])
                else:
                    ошибка(f'{где}: атрибут {атр}="{знач}" — href только у <use> на свой id')
        if тег == 'text' and not re.fullmatch(r'\d{1,2}', (эл.text or '').strip()):
            ошибка(f'{где}: текст «{эл.text}» — в схеме только номера махраджей')
        if эл.get('id'):
            ид.add(эл.get('id'))
    for я in якоря_нужны:
        if я not in ид:
            ошибка(f'{где}: нет группы подсветки id="{я}"')
    for с in ссылки:
        if с not in ид:
            ошибка(f'{где}: <use href="#{с}"> — нет такого id в файле')


def проверить_схемы(д):
    папка = к.ПАПКА_ВЫХОДА
    по_номеру = {м['id']: м for м in д['махраджи']}
    разрезов = {м: 0 for м in по_номеру}
    файлы = set()
    всего = сжато = 0
    файл_по = {}

    def файл_на_месте(где, запись, основа):
        nonlocal всего, сжато
        имя = запись.get('файл', '')
        м_имени = к.ИМЯ_ФАЙЛА.match(имя)
        if not м_имени or f'{м_имени.group(1)}' + (f'-{м_имени.group(2)}' if м_имени.group(2) else '') != основа:
            ошибка(f'{где}: имя файла «{имя}» — нужно {основа}.<sha256[:20]>.svg')
            return None
        путь_ = папка / имя
        if not путь_.exists():
            ошибка(f'{где}: нет файла {путь_.relative_to(к.КОРЕНЬ)} (python3 -I -B tools/makharij/build_makharij.py)')
            return None
        байты = путь_.read_bytes()
        sha = hashlib.sha256(байты).hexdigest()
        if sha != запись.get('sha256') or not sha.startswith(м_имени.group(3)) or len(байты) != запись.get('байт'):
            ошибка(f'{где}: sha256/размер файла не совпадают с makharij.json или с именем')
        файлы.add(имя)
        if len(байты) / 1024 > к.БЮДЖЕТ_ФАЙЛА_КБ:
            ошибка(f'{где}: {имя} {len(байты) / 1024:.1f} КБ больше бюджета файла {к.БЮДЖЕТ_ФАЙЛА_КБ} КБ')
        всего += len(байты)
        сжато += len(gzip.compress(байты, 9, mtime=0))
        return байты
    for с in д['схемы']:
        где = f'схема {с["id"]}'
        if с['id'] not in сборка.СХЕМЫ:
            ошибка(f'{где}: нет рисунка в build_makharij.py')
        if с.get('вид') not in ('разрез', 'сверху'):
            ошибка(f'{где}: вид «разрез» или «сверху»')
        if not isinstance(с.get('подпись'), dict):
            ошибка(f'{где}: подпись {{ru, kk}} (alt для приложения)')
        for м in с['махраджи']:
            if м not in по_номеру:
                ошибка(f'{где}: неизвестный махрадж {м}')
            elif с.get('вид') == 'разрез':
                разрезов[м] += 1
        байты = файл_на_месте(где, с, с['id'])
        if байты is not None:
            проверить_svg(с['файл'], байты, [по_номеру[м]['подсветка']['якорь'] for м in с['махраджи'] if м in по_номеру])
        if len(с['махраджи']) != 1:
            ошибка(f'{где}: у схемы ровно один махрадж (своя схема у каждого), есть {с["махраджи"]}')
            файл_по[с['id'], None] = с['файл']
        нужны = сборка.якоря_вариантов(с, по_номеру)
        if sorted(с.get('варианты', {})) != sorted(нужны):
            ошибка(f'{где}: варианты {sorted(с.get("варианты", {}))}, нужны {sorted(нужны)}')
        for я, вариант in с.get('варианты', {}).items():
            байты = файл_на_месте(f'{где} #{я}', вариант, f'{с["id"]}-{я}')
            if байты is not None:
                проверить_svg(вариант['файл'], байты, [я])
                файл_по[с['id'], я] = вариант['файл']
    for м, n in разрезов.items():
        if n != 1:
            ошибка(f'махрадж {м}: схем-разрезов {n}, нужна ровно одна')
    if папка.exists():
        лишние = sorted(п.name for п in папка.iterdir() if п.name not in файлы)
        if лишние:
            ошибка(f'лишние файлы в {папка.relative_to(к.КОРЕНЬ)}: {лишние}')
    if всего / 1024 > к.БЮДЖЕТ_ПАПКИ_КБ:
        ошибка(f'схемы {всего / 1024:.1f} КБ больше бюджета папки {к.БЮДЖЕТ_ПАПКИ_КБ} КБ')
    # Свежесть: сборка из текущих данных даёт те же файлы и поля.
    файлы_сборки, данные_сборки = сборка.собрать(к.прочитать())
    for имя, б in файлы_сборки.items():
        if not (папка / имя).exists() or (папка / имя).read_bytes() != б:
            ошибка(f'схема {имя} устарела — python3 -I -B tools/makharij/build_makharij.py')
    if к.в_текст(данные_сборки) != к.в_текст(д):
        ошибка('поля сборки в makharij.json устарели — python3 -I -B tools/makharij/build_makharij.py')
    # Карточка буквы: файл, где выделен махрадж буквы по её якорю (без :target в URL).
    разрез_махраджа = {м: next(с['id'] for с in д['схемы'] if м in с['махраджи'] and с['вид'] == 'разрез')
                       for м in по_номеру}
    for б, з in д['буквы'].items():
        for запись, где in [(з, f'буквы.{б}')] + [(з[доп], f'буквы.{б}.{доп}') for доп in сборка.ДОП_ЗАПИСИ if доп in з]:
            сид = разрез_махраджа.get(запись.get('махрадж'))
            нужно = файл_по.get((сид, запись.get('якорь')), файл_по.get((сид, None)))
            if запись.get('схема') != нужно:
                ошибка(f'{где}: схема {запись.get("схема")} ≠ файлу с выделенным махраджем ({нужно})')
    return всего, сжато


def проверить_цвета():
    цвета = к.цвета()
    рисунок = (osnova.CSS + osnova.DEFS + pathlib.Path(pozy.__file__).read_text(encoding='utf-8')).lower()
    for роль, hex_ in к.ЦВЕТА_СХЕМ.items():
        if hex_.lower() not in рисунок:
            ошибка(f'цвет «{роль}» {hex_} не встречается в рисунке (osnova.py / pozy.py) — ЦВЕТА_СХЕМ устарели')
    for класс, роль in (('.k', 'номер'), ('.kt', 'цифра')):
        м = re.search(re.escape(класс) + r'\{fill:(#[0-9A-Fa-f]{6})', osnova.CSS)
        if not м or м.group(1).upper() != цвета[роль]:
            ошибка(f'номер махраджа: {класс} должен быть цвета токена «{к.ТОКЕНЫ_НОМЕРА[роль]}» {цвета[роль]}')
    for роль, на, порог in к.ПАРЫ_КОНТРАСТА_СХЕМ:
        к_ = к.контраст(цвета[роль], цвета[на])
        if к_ < порог:
            ошибка(f'контраст {роль} на {на}: {к_:.2f} < {порог}')
    return len(к.ПАРЫ_КОНТРАСТА_СХЕМ)


