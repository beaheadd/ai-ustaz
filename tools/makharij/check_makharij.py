"""Проверка карты махраджей: content/makharij.json, схемы app/public/makharij/*.svg и список записей кари.

Запуск:  python3 -I -B tools/makharij/check_makharij.py   (код 1 при любой ошибке; без сети и сторонних пакетов)
Проверяет:
  1. Шапка: статус «черновик», пока утверждено = null (правило 11); источник указан.
  2. 17 махраджей с номерами 1–17 по порядку, 5 областей (الجوف، الحلق، اللسان، الشفتان، الخيشوم) — каждый махрадж
     ровно в одной области; у каждого — арабские название, описание и стих, ru и kk, подсветка с якорем «m<номер>».
  3. Везде, где есть ru, есть непустой kk (и наоборот).
  4. Буквы content/letters.json: у каждой есть запись в «буквы»; каждая буква (кроме лигатуры) — ровно в одном махрадже,
     а буквы мадда (ا و ي) — ещё и в الجوف (ا — только там); буквы[id].махрадж с этим согласован; гунна — только у ن и م
     и совпадает с «носителями» хайшума; лигатура лям-алиф — из ل + мадд ا.
  5. Пробы: у согласной — «хамза с фатхой + буква с сукуном» (أَبْ…); у و и ي-согласных — удвоенная подвижная
     (أَوَّ، أَيَّ; ревью 19.11: лин — слабая форма), лин — отдельной записью (أَوْ، أَيْ); у мадда — آ / أُو / إِي;
     у гунны — أَنَّ / أَمَّ; каждая проба есть в docs/записи-кари-буквы.md вместе с именем файла записи.
  6. Схемы: по одной схеме-разрезу на махрадж (+ виды сверху ض и ل); у каждой — рисунок в pozy.py, файл
     <id>.<sha256[:20]>.svg и варианты <id>-m<N>w.<sha256[:20]>.svg (у губ — поза و) на месте, sha256 и размер
     совпадают, в папке нет лишних файлов; буквы[].схема — файл, где выделен махрадж буквы (её якорь);
     схемы и поля сборки не устарели (свежая сборка побайтно та же).
  7. Безопасность SVG: корень <svg viewBox>, есть <title>; нет script/foreignObject/image/a, атрибутов on*; href —
     только у <use> и только на свой id («#a» — лупа); внешних URL нет (кроме пространства имён SVG — check-dist
     п. 4); текст — только номера махраджей (без подписей и арабского: буквы рисует приложение шрифтом Amiri Quran);
     у схемы — группа подсветки id="m<номер>". Пунктир (stroke-dasharray) — только у воздуха (.w).
  8. Цвета: каждый цвет ЦВЕТА_СХЕМ есть в рисунке (osnova.py), номер — цвет токенов «акцент»/«акцентТекст»;
     контраст пар ПАРЫ_КОНТРАСТА_СХЕМ; бюджет: файл ≤ БЮДЖЕТ_ФАЙЛА_КБ, все ≤ БЮДЖЕТ_ПАПКИ_КБ (сырые байты).
Решение владельца 19.11.2026 — см. шапку build_makharij.py.
"""
