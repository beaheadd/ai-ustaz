"""Сборка своих схем махраджей (SVG) и имён файлов в content/makharij.json.

Запуск:  python3 -I -B tools/makharij/build_makharij.py [--check] [--витрина ПАПКА] [--тёмный-набор ПАПКА]
  (без сети и сторонних пакетов)
Читает:  content/makharij.json (тексты, махраджи, состав схем), цвета — app/src/theme/tokens.ts (makharij_common.палитры).
Пишет:   app/public/makharij/<id>.<sha256[:20]>.svg — 14 схем (все махраджи схемы равно яркие) и
         <id>-m<N>.<sha256[:20]>.svg — 9 вариантов общих схем с одним выделенным махраджем (горло 2/3/4, ق/ك, ل/ن/ر,
         губы для و); старые *.svg с другим хэшем удаляет (чужих файлов в папке быть не должно);
         в content/makharij.json — только поля сборки: схемы[].файл/sha256/байт/варианты, махраджи[].схема/схемаСверху,
         буквы[].схема/схемаСверху/якорь (и то же в «лин»/«мадд»/«гунна»). Тексты не трогает.
--check:   ничего не пишет; код 1, если схемы или поля сборки на диске не совпадают со свежей сборкой.
--витрина: дополнительно пишет ПАПКА/index.html — все схемы и варианты в светлой и тёмной теме (не в репозиторий).
--тёмный-набор: пишет в ПАПКА те же файлы только с тёмной палитрой (без prefers-color-scheme) — запасной путь, если
           в WebKit `color-scheme` на <img> не доходит до SVG (docs/дизайн/06 §4.2); в сборку не идёт.

Контракт схемы (для приложения; подключение к урокам — следующий шаг, docs/дизайн/06 §5):
  — путь в сборке: /aiustaz/makharij/<файл> (Expo копирует public/ в dist/ как есть); показывать настоящим <img>
    (не RN <Image>: там фон-картинка), на карточке буквы — файл буквы[id].схема (махрадж уже выделен, без якоря в URL:
    `:target` в SVG-картинке в WebKit не проверен, а в нативной сборке его нет вовсе);
  — alt = подпись схемы + «выделено: №N — что → куда» из махраджи[].подсветка[язык] (docs/дизайн/06 §4.1);
  — тема: светлая по умолчанию, тёмная по prefers-color-scheme; ручной выбор темы приложения — стилем
    `color-scheme: light|dark` на <img> (в Chromium проверено, 19.11.2026); у схемы своя подложка;
  — смысл не только цветом: «что работает» — сплошная линия, «куда» — точки или залитая кромка зуба, воздух —
    единственный пунктир (со стрелкой); у каждой подсветки — кружок с номером;
  — нет текста, кроме номеров махраджей; нет внешних ссылок (check-dist п. 4); нет лиц (правило 9).
Решение владельца 19.11.2026: «добавить картинку произношения каждой буквы. Картинка, звук, видео…». Рисуем свои схемы
с нуля по описаниям Ибн аль-Джазари; рисунки «Көрнекі тәжуид» не копируем и не обводим (права — у д-ра Сувайда
и Dar al-Ghouthani, разрешения нет). Геометрия и рисунки — osnova.py, shemy_gorlo_guby.py, schemes_tongue.py.
"""
import gzip
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import makharij_common as к  # noqa: E402
import schemes_tongue  # noqa: E402
