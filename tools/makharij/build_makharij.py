# ─────────────────────────── стиль ───────────────────────────
РОЛИ_CSS = ('bg', 'edge', 'line', 'tis', 'tng', 'tth', 'cav', 'act', 'pas', 'pasf', 'air', 'mk', 'mkt')


def стиль(палитры, м=1, активный=None, тема=None):
    """CSS схемы. м — увеличение окна (толщины и пунктиры делим на м, на экране они те же);
    активный — якорь «mN» варианта с одним выделенным махраджем (остальные бледнеют до 28 %);
    тема=None — светлая палитра и тёмная по prefers-color-scheme (переменные тёмной темы — один раз), 'тёмная' — только
    тёмная палитра (запасной набор)."""
    def перем(т):
        return ';'.join(f'--{р}:{палитры[т][р]}' for р in РОЛИ_CSS)

    def ч(x):
        return f'{x / м:.3g}'
    if тема == 'тёмная':
        цвета = f'.mx{{{перем("тёмная")}}}'
    else:
        цвета = f'.mx{{{перем("светлая")}}}@media(prefers-color-scheme:dark){{.mx{{{перем("тёмная")}}}}}'
    css = (
        цвета
        + '.b{fill:var(--bg);stroke:var(--edge)}'
        f'.t,.g,.d,.c{{stroke:var(--line);stroke-width:{ч(1.5)};stroke-linejoin:round}}'
        '.t{fill:var(--tis)}.g{fill:var(--tng)}.d{fill:var(--tth)}.c{fill:var(--cav)}'
        f'.h{{fill:none;stroke:var(--line);stroke-width:{ч(1.2)};opacity:.45}}'
        '.a,.p,.l,.w,.ab{fill:none;stroke-linecap:round;stroke-linejoin:round}'
        f'.a{{stroke:var(--act);stroke-width:{ч(5)}}}'
        f'.p{{stroke:var(--pas);stroke-width:{ч(5)};stroke-dasharray:0 {ч(8)}}}'
        f'.pf{{fill:var(--pasf);stroke:var(--pas);stroke-width:{ч(2)}}}'
        '.o{opacity:.45}'
        f'.zf{{fill:var(--act);fill-opacity:.16;stroke:var(--act);stroke-width:{ч(2)}}}'
        f'.ab{{stroke:var(--act);stroke-opacity:.16;stroke-width:{ч(16)}}}'
        f'.w{{stroke:var(--air);stroke-width:{ч(2)};stroke-dasharray:{ч(5)} {ч(4)}}}.wh{{fill:var(--air)}}'
        f'.l{{stroke:var(--act);stroke-width:{ч(1.2)}}}.ld{{fill:var(--act)}}'
        f'.k{{fill:var(--mk)}}.kt{{fill:var(--mkt);font:600 {ч(13)}px system-ui,sans-serif;text-anchor:middle}}'
    )
    if активный:
        css += (f'.z{{opacity:.28}}#{активный}{{opacity:1}}'
                f'#{активный} .a,#{активный} .p{{stroke-width:{ч(6.5)}}}')
    return css


# ─────────────────────────── рисунки ───────────────────────────
# id схемы → (рисунок(якоря, активный), вид (x, y, w, h), пиксели (ш, в)); якоря — {id махраджа: 'mN'}.
СХЕМЫ = {}
СХЕМЫ.update(shemy_gorlo_guby.СХЕМЫ)
СХЕМЫ.update(schemes_tongue.СХЕМЫ)


def экранировать(т):
    return т.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def нарисовать(схема, якоря, палитры, активный=None, тема=None):
    """SVG одной схемы: якоря — {id махраджа: 'mN'}; активный — якорь варианта (или None — все равно яркие)."""
    рисовать, (x, y, w, h), (ш, в) = СХЕМЫ[схема['id']]
    м = ш / w
    карточка = f' x="{x + 0.5 / м:g}" y="{y + 0.5 / м:g}" width="{w - 1 / м:g}" height="{h - 1 / м:g}" rx="{16 / м:g}"'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" class="mx" viewBox="{x} {y} {w} {h}" width="{ш}" height="{в}" role="img">'
        f'<title>{экранировать(схема["подпись"]["ru"])}</title><style>{стиль(палитры, м, активный, тема)}</style>'
        f'<clipPath id="k"><rect{карточка}/></clipPath><rect class="b"{карточка}/>'
        f'<g clip-path="url(#k)">{рисовать(якоря, активный)}</g><rect class="b" style="fill:none"{карточка}/></svg>\n'
    ).encode('utf-8')


def якоря_вариантов(схема, по_id):
    """Якоря, для которых у схемы есть вариант с одним выделенным махраджем: все якоря общей схемы (2+ махраджа)
    и дополнительные (якорьВав у губ: другая поза губ для و)."""
    махраджи = [по_id[м] for м in схема['махраджи']]
    итог = [м['подсветка']['якорь'] for м in махраджи] if len(махраджи) > 1 else []
    итог += [м['подсветка']['якорьВав'] for м in махраджи if 'якорьВав' in м['подсветка']]
    return итог


# ─────────────────────────── сборка ───────────────────────────
ДОП_ЗАПИСИ = ('лин', 'мадд', 'гунна')   # вложенные записи буквы со своим махраджем, схемой и пробой


def собрать(данные, тема=None):
    """→ (файлы {имя: байты}, новые данные с полями сборки)."""
    палитры = к.палитры()
    по_id = {м['id']: м for м in данные['махраджи']}
    якоря = {м['id']: м['подсветка']['якорь'] for м in данные['махраджи']}
    файлы = {}
    файл_по = {}   # (id схемы, якорь или None) → имя файла

    def записать_файл(основа, байты):
        sha = hashlib.sha256(байты).hexdigest()
        имя = f'{основа}.{sha[:20]}.svg'
        файлы[имя] = байты
        return {'файл': имя, 'sha256': sha, 'байт': len(байты)}
    for схема in данные['схемы']:
        if схема['id'] not in СХЕМЫ:
            raise SystemExit(f'Нет рисунка для схемы «{схема["id"]}» (СХЕМЫ в build_makharij.py)')
        схема.update(записать_файл(схема['id'], нарисовать(схема, якоря, палитры, тема=тема)))
        файл_по[схема['id'], None] = схема['файл']
        варианты = {}
        for я in якоря_вариантов(схема, по_id):
            варианты[я] = записать_файл(f'{схема["id"]}-{я}', нарисовать(схема, якоря, палитры, я, тема))
            файл_по[схема['id'], я] = варианты[я]['файл']
        if варианты:
            схема['варианты'] = варианты
        else:
            схема.pop('варианты', None)
    вид = {с['id']: с['вид'] for с in данные['схемы']}

    def схемы_махраджа(мид):
        своих = [с['id'] for с in данные['схемы'] if мид in с['махраджи']]
        разрезы = [с for с in своих if вид[с] == 'разрез']
        сверху = [с for с in своих if вид[с] == 'сверху']
        if len(разрезы) != 1:
            raise SystemExit(f'У махраджа {мид} должна быть ровно одна схема-разрез, есть: {разрезы}')
        return разрезы[0], (сверху[0] if сверху else None)

    def файл(сид, якорь):
        return файл_по.get((сид, якорь), файл_по[сид, None])
    for м in данные['махраджи']:
        разрез, сверху = схемы_махраджа(м['id'])
        м['схема'] = файл(разрез, м['подсветка']['якорь'])
        if сверху:
            м['схемаСверху'] = файл(сверху, м['подсветка']['якорь'])
        else:
            м.pop('схемаСверху', None)

    def поля(запись):
        м = по_id[запись['махрадж']]
        запись['якорь'] = запись.get('якорь') if запись.get('якорь') in якоря_махраджа(м) else м['подсветка']['якорь']
        разрез, сверху = схемы_махраджа(м['id'])
        запись['схема'] = файл(разрез, запись['якорь'])
        if сверху:
            запись['схемаСверху'] = файл(сверху, запись['якорь'])
        else:
            запись.pop('схемаСверху', None)
    for запись in данные['буквы'].values():
        поля(запись)
        for доп in ДОП_ЗАПИСИ:
            if доп in запись:
                поля(запись[доп])
    return файлы, данные


def якоря_махраджа(м):
    return [м['подсветка']['якорь']] + ([м['подсветка']['якорьВав']] if 'якорьВав' in м['подсветка'] else [])


def размер_gzip(файлы):
    return sum(len(gzip.compress(б, 9, mtime=0)) for б in файлы.values())


def витрина(папка, данные, файлы_светлые, файлы_тёмные):
    """HTML для глаз: каждая схема и её варианты — в светлой и тёмной теме (тёмная — запасной набор без media)."""
    папка = pathlib.Path(папка)
    for под, файлы in (('makharij', файлы_светлые), ('makharij-d', файлы_тёмные)):
        (папка / под).mkdir(parents=True, exist_ok=True)
        for имя, байты in файлы.items():
            (папка / под / имя).write_bytes(байты)
    _, тёмные = собрать(к.прочитать(), 'тёмная')
    строки = []
    for тема, под, схемы in (('светлая', 'makharij', данные['схемы']), ('тёмная', 'makharij-d', тёмные['схемы'])):
        строки.append(f'<h1 class="{тема}">Тема: {тема}</h1>')
        for с in схемы:
            картинки = [('все', с['файл'])] + [(я, в['файл']) for я, в in с.get('варианты', {}).items()]
            строки.append(f'<section class="{тема}"><h2>{с["id"]} — {экранировать(с["подпись"]["ru"])}</h2>' + ''.join(
                f'<figure><img src="{под}/{ф}" width="280"><figcaption>{я}</figcaption></figure>' for я, ф in картинки)
                + '</section>')
    html = ('<!doctype html><meta charset="utf-8"><title>Махраджи — витрина</title><style>'
            'body{font:14px system-ui,sans-serif;margin:0}.светлая{background:#F7F2E8;color:#1B2623}'
            '.тёмная{background:#0C1715;color:#EDE6D6}h1{margin:0;padding:12px 16px;font-size:18px}'
            'section{display:flex;flex-wrap:wrap;gap:12px;padding:8px 16px}h2{width:100%;font-size:15px;margin:8px 0 0}'
            'figure{margin:0}figcaption{font-size:12px;opacity:.7}</style>' + ''.join(строки))
    (папка / 'index.html').write_text(html, encoding='utf-8')
    return папка / 'index.html'


def аргумент(имя):
    return sys.argv[sys.argv.index(имя) + 1] if имя in sys.argv else None


def main():
    исходные = к.прочитать()
    файлы, данные = собрать(к.прочитать())
    папка = к.ПАПКА_ВЫХОДА
    есть = {п.name for п in папка.glob('*')} if папка.exists() else set()
    чужие = sorted(и for и in есть if not к.ИМЯ_ФАЙЛА.match(и))
    if чужие:
        print(f'В {папка} чужие файлы: {", ".join(чужие)} — уберите их (папка только для схем махраджей).')
        return 1
    всего = sum(len(б) for б in файлы.values())
    сжато = размер_gzip(файлы)
    if '--check' in sys.argv:
        разные = [и for и, б in файлы.items() if not (папка / и).exists() or (папка / и).read_bytes() != б]
        лишние = sorted(есть - set(файлы))
        json_другой = к.в_текст(исходные) != к.в_текст(данные)
        if разные or лишние or json_другой:
            print(f'Схемы махраджей устарели: разных {len(разные)}, лишних {len(лишние)}, '
                  f'поля сборки в makharij.json {"другие" if json_другой else "те же"}. '
                  'Запустите python3 -I -B tools/makharij/build_makharij.py')
            return 1
        print(f'Схемы махраджей совпадают со свежей сборкой ({len(файлы)} файлов, {всего / 1024:.1f} КБ, '
              f'gzip {сжато / 1024:.1f} КБ).')
        return 0
    папка.mkdir(parents=True, exist_ok=True)
    for имя in sorted(есть - set(файлы)):
        (папка / имя).unlink()
    for имя, байты in файлы.items():
        if not (папка / имя).exists() or (папка / имя).read_bytes() != байты:
            (папка / имя).write_bytes(байты)
    к.записать(данные)
    print(f'Готово: {len(файлы)} файлов в {папка.relative_to(к.КОРЕНЬ)} ({всего / 1024:.1f} КБ, gzip {сжато / 1024:.1f} КБ); '
          f'удалено старых: {len(есть - set(файлы))}; поля сборки — в {к.ПУТЬ_ДАННЫХ.relative_to(к.КОРЕНЬ)}.')
    тёмные = собрать(к.прочитать(), 'тёмная')[0] if (аргумент('--тёмный-набор') or аргумент('--витрина')) else {}
    if аргумент('--тёмный-набор'):
        п = pathlib.Path(аргумент('--тёмный-набор'))
        п.mkdir(parents=True, exist_ok=True)
        for имя, байты in тёмные.items():
            (п / имя).write_bytes(байты)
        print(f'Тёмный набор: {len(тёмные)} файлов в {п} ({sum(map(len, тёмные.values())) / 1024:.1f} КБ) — не в сборку.')
    if аргумент('--витрина'):
        print('Витрина:', витрина(аргумент('--витрина'), данные, файлы, тёмные))
    return 0


if __name__ == '__main__':
    sys.exit(main())
