"""Сборка своих схем махраджей (SVG) и имён файлов в content/makharij.json.

Запуск:  python3 -I -B tools/makharij/build_makharij.py [--check] [--витрина ПАПКА]   (без сети и сторонних пакетов)
Читает:  content/makharij.json (тексты, махраджи, состав схем); рисунки — tools/makharij/pozy.py на основе osnova.py.
Пишет:   app/public/makharij/<id>.<sha256[:20]>.svg — по одной схеме на махрадж (17 разрезов) + 2 вида сверху (ض, ل)
         и вариант губ для و (<id>-m16w.<sha256[:20]>.svg); старые *.svg с другим хэшем удаляет (чужих файлов в папке
         быть не должно); в content/makharij.json — только поля сборки: схемы[].файл/sha256/байт/варианты,
         махраджи[].схема/схемаСверху, буквы[].схема/схемаСверху/якорь (и то же в «лин»/«мадд»/«гунна»). Тексты не трогает.
--check:   ничего не пишет; код 1, если схемы или поля сборки на диске не совпадают со свежей сборкой.
--витрина: дополнительно пишет ПАПКА/index.html — все схемы на светлом и тёмном фоне приложения (не в репозиторий).

Контракт схемы (для приложения; подключение к урокам — следующий шаг, docs/дизайн/06 §5):
  — путь в сборке: /aiustaz/makharij/<файл> (Expo копирует public/ в dist/ как есть); показывать настоящим <img>;
    на карточке буквы — файл буквы[id].схема (махрадж уже выделен — своя схема у каждого махраджа);
  — alt = подпись схемы + «выделено: №N — что → куда» из махраджи[].подсветка[язык] (docs/дизайн/06 §4.1);
  — тема: рисунок в «природных» цветах на своей светлой карточке в обеих темах; рамка карточки — по
    prefers-color-scheme (решение владельца 19.11.2026, docs/дизайн/06 §4.2);
  — смысл не только цветом: место касания — оранжевая линия органа + жёлтая линия места + свечение; воздух —
    единственный пунктир (со стрелкой); у каждой подсветки — кружок с номером;
  — передний отдел рта (ل ن ر, ط د ت, ص س ز, ظ ذ ث, ف, губы) — ещё и в круглой лупе: <use href="#a"> на группу
    рисунка той же схемы (внутренняя ссылка, без внешних);
  — нет текста, кроме номеров махраджей; нет внешних ссылок и растров (check-dist п. 4).
Решения владельца 19.11.2026: «добавить картинку произношения каждой буквы»; «Эти картинки нормально рисуй, как
реальный рот человека» — реалистичный сагиттальный разрез (образец манеры — «Көрнекі тәжуид»; его рисунки не копируем
и не обводим: права у д-ра Сувайда и Dar al-Ghouthani). Правило 9 уточнено владельцем: разрез от уровня носа и ниже,
без глаз, бровей, лба, ушей; профиль носа, губ и подбородка — допустим.
"""
import gzip
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import makharij_common as к  # noqa: E402
import osnova  # noqa: E402
import pozy  # noqa: E402

СХЕМЫ = pozy.СХЕМЫ


def экранировать(т):
    return т.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def нарисовать(схема, якоря, активный=None):
    """SVG одной схемы: якорь — махраджа схемы ('mN'); активный — якорь варианта (у губ — 'm16w', поза و)."""
    якорь = якоря[схема['махраджи'][0]]
    внутри = СХЕМЫ[схема['id']](якорь, активный)
    return osnova.svg(внутри, экранировать(схема['подпись']['ru'])).encode('utf-8')


def якоря_вариантов(схема, по_id):
    """Якоря, для которых у схемы есть вариант: дополнительные позы махраджа (якорьВав у губ: поза و)."""
    return [по_id[м]['подсветка']['якорьВав'] for м in схема['махраджи'] if 'якорьВав' in по_id[м]['подсветка']]


# ─────────────────────────── сборка ───────────────────────────
ДОП_ЗАПИСИ = ('лин', 'мадд', 'гунна')   # вложенные записи буквы со своим махраджем, схемой и пробой


def собрать(данные):
    """→ (файлы {имя: байты}, новые данные с полями сборки)."""
    по_id = {м['id']: м for м in данные['махраджи']}
    якоря = {м['id']: м['подсветка']['якорь'] for м in данные['махраджи']}
    файлы = {}
    файл_по = {}   # (id схемы, якорь или None) → имя файла

    def записать_файл(основа, байты):
        sha = hashlib.sha256(байты).hexdigest()
        имя = f'{основа}.{sha[:20]}.svg'
        файлы[имя] = байты
        return {'файл': имя, 'sha256': sha, 'байт': len(байты)}
    for схема in данные['схемы']:
        if схема['id'] not in СХЕМЫ:
            raise SystemExit(f'Нет рисунка для схемы «{схема["id"]}» (СХЕМЫ в tools/makharij/pozy.py)')
        схема.update(записать_файл(схема['id'], нарисовать(схема, якоря)))
        файл_по[схема['id'], None] = схема['файл']
        варианты = {}
        for я in якоря_вариантов(схема, по_id):
            варианты[я] = записать_файл(f'{схема["id"]}-{я}', нарисовать(схема, якоря, я))
            файл_по[схема['id'], я] = варианты[я]['файл']
        if варианты:
            схема['варианты'] = варианты
        else:
            схема.pop('варианты', None)
    вид = {с['id']: с['вид'] for с in данные['схемы']}

    def схемы_махраджа(мид):
        своих = [с['id'] for с in данные['схемы'] if мид in с['махраджи']]
        разрезы = [с for с in своих if вид[с] == 'разрез']
        сверху = [с for с in своих if вид[с] == 'сверху']
        if len(разрезы) != 1:
            raise SystemExit(f'У махраджа {мид} должна быть ровно одна схема-разрез, есть: {разрезы}')
        return разрезы[0], (сверху[0] if сверху else None)

    def файл(сид, якорь):
        return файл_по.get((сид, якорь), файл_по[сид, None])
    for м in данные['махраджи']:
        разрез, сверху = схемы_махраджа(м['id'])
        м['схема'] = файл(разрез, м['подсветка']['якорь'])
        if сверху:
            м['схемаСверху'] = файл(сверху, м['подсветка']['якорь'])
        else:
            м.pop('схемаСверху', None)

    def поля(запись):
        м = по_id[запись['махрадж']]
        запись['якорь'] = запись.get('якорь') if запись.get('якорь') in якоря_махраджа(м) else м['подсветка']['якорь']
        разрез, сверху = схемы_махраджа(м['id'])
        запись['схема'] = файл(разрез, запись['якорь'])
        if сверху:
            запись['схемаСверху'] = файл(сверху, запись['якорь'])
        else:
            запись.pop('схемаСверху', None)
    for запись in данные['буквы'].values():
        поля(запись)
        for доп in ДОП_ЗАПИСИ:
            if доп in запись:
                поля(запись[доп])
    return файлы, данные


def якоря_махраджа(м):
    return [м['подсветка']['якорь']] + ([м['подсветка']['якорьВав']] if 'якорьВав' in м['подсветка'] else [])


def размер_gzip(файлы):
    return sum(len(gzip.compress(б, 9, mtime=0)) for б in файлы.values())


def витрина(папка, данные, файлы):
    """HTML для глаз: каждая схема и её варианты — на светлом и тёмном фоне приложения."""
    папка = pathlib.Path(папка)
    (папка / 'makharij').mkdir(parents=True, exist_ok=True)
    for имя, байты in файлы.items():
        (папка / 'makharij' / имя).write_bytes(байты)
    строки = []
    for тема in ('светлая', 'тёмная'):
        строки.append(f'<h1 class="{тема}">Фон приложения: {тема}</h1><section class="{тема}">')
        for с in данные['схемы']:
            картинки = [(с['id'], с['файл'])] + [(f'{с["id"]}-{я}', в['файл']) for я, в in с.get('варианты', {}).items()]
            строки.extend(f'<figure><img src="makharij/{ф}" width="300"><figcaption>{экранировать(и)}</figcaption>'
                          f'</figure>' for и, ф in картинки)
        строки.append('</section>')
    html = ('<!doctype html><meta charset="utf-8"><title>Махраджи — витрина</title><style>'
            'body{font:14px system-ui,sans-serif;margin:0}.светлая{background:#F7F2E8;color:#1B2623}'
            '.тёмная{background:#0C1715;color:#EDE6D6}h1{margin:0;padding:12px 16px;font-size:18px}'
            'section{display:flex;flex-wrap:wrap;gap:12px;padding:8px 16px}'
            'figure{margin:0}figcaption{font-size:12px;opacity:.7}</style>' + ''.join(строки))
    (папка / 'index.html').write_text(html, encoding='utf-8')
    return папка / 'index.html'


def аргумент(имя):
    return sys.argv[sys.argv.index(имя) + 1] if имя in sys.argv else None


def main():
    исходные = к.прочитать()
    файлы, данные = собрать(к.прочитать())
    папка = к.ПАПКА_ВЫХОДА
    есть = {п.name for п in папка.glob('*')} if папка.exists() else set()
    чужие = sorted(и for и in есть if not к.ИМЯ_ФАЙЛА.match(и))
    if чужие:
        print(f'В {папка} чужие файлы: {", ".join(чужие)} — уберите их (папка только для схем махраджей).')
        return 1
    всего = sum(len(б) for б in файлы.values())
    сжато = размер_gzip(файлы)
    if '--check' in sys.argv:
        разные = [и for и, б in файлы.items() if not (папка / и).exists() or (папка / и).read_bytes() != б]
        лишние = sorted(есть - set(файлы))
        json_другой = к.в_текст(исходные) != к.в_текст(данные)
        if разные or лишние or json_другой:
            print(f'Схемы махраджей устарели: разных {len(разные)}, лишних {len(лишние)}, '
                  f'поля сборки в makharij.json {"другие" if json_другой else "те же"}. '
                  'Запустите python3 -I -B tools/makharij/build_makharij.py')
            return 1
        print(f'Схемы махраджей совпадают со свежей сборкой ({len(файлы)} файлов, {всего / 1024:.1f} КБ, '
              f'gzip {сжато / 1024:.1f} КБ).')
        return 0
    папка.mkdir(parents=True, exist_ok=True)
    for имя in sorted(есть - set(файлы)):
        (папка / имя).unlink()
    for имя, байты in файлы.items():
        if not (папка / имя).exists() or (папка / имя).read_bytes() != байты:
            (папка / имя).write_bytes(байты)
    к.записать(данные)
    print(f'Готово: {len(файлы)} файлов в {папка.relative_to(к.КОРЕНЬ)} ({всего / 1024:.1f} КБ, gzip {сжато / 1024:.1f} КБ); '
          f'удалено старых: {len(есть - set(файлы))}; поля сборки — в {к.ПУТЬ_ДАННЫХ.relative_to(к.КОРЕНЬ)}.')
    if аргумент('--витрина'):
        print('Витрина:', витрина(аргумент('--витрина'), данные, файлы))
    return 0


if __name__ == '__main__':
    sys.exit(main())
