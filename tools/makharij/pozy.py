def г(якорь, *части):
    return f'<g id="{якорь}">' + ''.join(части) + '</g>'


def пассив(точки):
    """Куда касается: жёлтая линия по нёбу, дёснам, зубам."""
    return путь(сплайн(точки), 'кп')


def номер_у(место, n, где=None, л=None, угол=-38):
    """Номер махраджа: у места (где — позиция кружка) или, если есть лупа, — на ободе лупы с выноской к месту."""
    if л:
        cx, cy, r, *_ = л
        а = math.radians(угол)
        где = (cx + (r + 3) * math.cos(а), cy + (r + 3) * math.sin(а))
        место = о.в_лупе(л, место)
    return номер(*где, n, к=место)


def касание(акт, пас, свет, n, где_номер, якорь, поза, л=None, под=''):
    """Свечение + оранжевая линия органа + жёлтая линия места; номер — у места или на ободе лупы."""
    cx, cy, rx, ry = свет
    п = г(якорь, пятно(cx, cy, rx, ry), пассив(пас) if пас else '', линия_касания(акт) if акт else '')
    return о.разрез(поза, п, лупа=л, под_подсветкой=под, номера=номер_у((cx, cy), n, где_номер, л))


