# ─────────────────────────── вид сверху ───────────────────────────
# Верхний зубной ряд «сквозь» нёбо: перёд (резцы) — вверху; левая сторона говорящего — слева на рисунке.
ДУГА = [(200, 66), (226, 71), (250, 86), (268, 108), (281, 138), (290, 172), (296, 210), (300, 250), (303, 292),
        (305, 332)]
ЗУБЫ = [('i1', 8.5, 7), ('i2', 6.5, 6.5), ('c', 7.5, 8), ('p1', 7, 9), ('p2', 6.5, 9), ('m1', 10, 11),
        ('m2', 9, 10.5), ('m3', 8.5, 10)]
МАСШТАБ_ЗУБОВ = 4.0   # единиц на мм


def _по_дуге(s):
    """Точка и касательная на дуге (правая половина) на расстоянии s от середины."""
    дл = 0.0
    for a, b in zip(ДУГА, ДУГА[1:]):
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        if дл + L >= s:
            t = (s - дл) / L
            return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t), ((b[0] - a[0]) / L, (b[1] - a[1]) / L)
        дл += L
    a, b = ДУГА[-2], ДУГА[-1]
    L = math.hypot(b[0] - a[0], b[1] - a[1])
    return b, ((b[0] - a[0]) / L, (b[1] - a[1]) / L)


def места_зубов():
    """{(сторона, имя): (центр, касательная, ширина, глубина)}; сторона +1 — правая половина рисунка."""
    итог = {}
    s = 0.0
    for имя, ш, гл in ЗУБЫ:
        w = ш * МАСШТАБ_ЗУБОВ
        (x, y), (tx, ty) = _по_дуге(s + w / 2)
        for сторона in (1, -1):
            итог[сторона, имя] = ((200 + (x - 200) * сторона, y), (tx * сторона, ty), w, гл * МАСШТАБ_ЗУБОВ)
        s += w + 1.2
    return итог


def _зуб_сверху(центр, кас, w, гл, имя):
    (x, y), (tx, ty) = центр, кас
    nx, ny = -ty, tx    # нормаль
    # наружу от середины нёба
    if (x - 200) * nx + (y - 200) * ny < 0:
        nx, ny = -nx, -ny
    угол = math.degrees(math.atan2(ty, tx))
    if имя.startswith('i'):
        форма = f'<rect x="{ч(-w / 2)}" y="{ч(-гл / 2)}" width="{ч(w)}" height="{ч(гл)}" rx="{ч(гл / 2.2)}"/>'
        бороздки = f'<path d="M{ч(-w / 2 + 3)},{ч(-гл / 2 + 2.5)}Q0,{ч(-гл / 2)} {ч(w / 2 - 3)},{ч(-гл / 2 + 2.5)}"/>'
    elif имя == 'c':
        форма = f'<ellipse rx="{ч(w / 2)}" ry="{ч(гл / 2)}"/>'
        бороздки = f'<path d="M{ч(-w / 2 + 3)},0L0,{ч(-гл / 4)}L{ч(w / 2 - 3)},0"/>'
    elif имя.startswith('p'):
        форма = f'<rect x="{ч(-w / 2)}" y="{ч(-гл / 2)}" width="{ч(w)}" height="{ч(гл)}" rx="{ч(w / 2.1)}"/>'
        бороздки = f'<path d="M{ч(-w / 2 + 4)},0L{ч(w / 2 - 4)},0"/>'
    else:
        форма = f'<rect x="{ч(-w / 2)}" y="{ч(-гл / 2)}" width="{ч(w)}" height="{ч(гл)}" rx="{ч(w / 3)}"/>'
        бороздки = (f'<path d="M{ч(-w / 2 + 4)},{ч(-1)}L{ч(w / 2 - 4)},1M{ч(-2)},{ч(-гл / 2 + 4)}'
                    f'L1,{ч(гл / 2 - 4)}"/>')
    # губная/щёчная сторона — наружу (нормаль); поворачиваем так, чтобы ось x шла по дуге
    return (f'<g transform="translate({ч(x)} {ч(y)}) rotate({ч(угол)})">'
            f'<g class="зб">{форма}</g><g style="fill:none;stroke:#cdbf9f;stroke-width:1.1">{бороздки}</g></g>')


