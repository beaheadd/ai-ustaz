"""Лёгкий индекс махраджей для приложения: content/makharij.json + content/letters.json →
app/public/makharij-index/makharij.<sha256[:20]>.json и app/src/makharij/manifest.generated.ts.

Зачем: схемы махраджей (app/public/makharij/*.svg, tools/makharij/build_makharij.py) нарисованы 19.11.2026, но ни
один экран их не показывал — makharij.json целиком в бандле стоил бы +68 КБ JS при бюджете на пределе. Индекс —
статический файл; экраны «Как произносить буквы» (#/makharij, #/makharij/letter?n=) грузят его fetch'ем общим
загрузчиком (src/quran/data.ts: sha256, кэш, «нет связи»).
Решения владельца: 19.11.2026 — «добавить картинку произношения каждой буквы»; 26.11.2026 — «Тот раз ты же рисовал
картинки произношения букв. Почему их нету в нашем приложении? Не выкатывал?».

Тексты НЕ меняются — переносятся из content/makharij.json как есть (ru, kk; uz и en в нём нет — экран показывает
русский с пометкой). Арабский (названия, лакаб, бейты Ибн аль-Джазари) — только из данных, дословно. Статус данных —
«черновик» (правило 11): экран показывает плашку, пока устаз не проверил.

Запуск (из корня, без сети):
  python3 -I -B tools/makharij/build_index.py           собрать
  python3 -I -B tools/makharij/build_index.py --check   ничего не пишет; код 1, если файлы ≠ свежей сборке
Контракт выхода (формат 1):
  {формат, версия, статус, автор (бейтов), сверить (ru),
   области: [{id, арабский, название{ru,kk}, махраджи: [id]}],
   махраджи: [{id, номер, область, арабский{название, стих?}, лакаб?, название, описание, условие?, гунна?,
               подсветка{что, куда?}, схема, подпись, схемаСверху?, подписьСверху?, буквы: [id]}],
   буквы: [{id, номер, знак, название{ru,kk,uz,en}, махрадж, проба, схема, схемаСверху?, примечание?, состав?,
            лин?|мадд?|гунна?: {махрадж, проба, схема, схемаСверху?, примечание?}}]}
  все {ru,kk} — тексты makharij.json; схемы — имена файлов в /aiustaz/makharij/ (их sha256 — в makharij.json).
  Манифест: МАНИФЕСТ_МАХРАДЖЕЙ = {файл, sha256, буквы: [id по порядку]} — номер буквы в адресе = позиция + 1;
  порядок букв — по махраджам (от горла к губам), лам-алиф — в конце.
"""
import hashlib
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import makharij_common as к  # noqa: E402

ПАПКА_ИНДЕКСА = к.КОРЕНЬ / 'app' / 'public' / 'makharij-index'
ПУТЬ_МАНИФЕСТА = к.КОРЕНЬ / 'app' / 'src' / 'makharij' / 'manifest.generated.ts'
ИМЯ_ИНДЕКСА = re.compile(r'^makharij\.([0-9a-f]{20})\.json$')
ЯЗЫКИ_ДАННЫХ = ('ru', 'kk')
ДОП = ('лин', 'мадд', 'гунна')


class ОшибкаИндекса(Exception):
    pass


def тексты(з, где):
    if not isinstance(з, dict) or not all(isinstance(з.get(я), str) and з[я].strip() for я in ЯЗЫКИ_ДАННЫХ):
        raise ОшибкаИндекса(f'{где}: нужны непустые ru и kk')
    return {я: з[я] for я in ЯЗЫКИ_ДАННЫХ}


def собрать():
    данные = к.прочитать()
    буквы_уроков = json.loads(к.ПУТЬ_БУКВ.read_text(encoding='utf-8'))
    подписи = {}
    for с in данные['схемы']:
        подписи[с['файл']] = (с['вид'], с['подпись'])
        for в in с.get('варианты', {}).values():
            подписи[в['файл']] = (с['вид'], с['подпись'])
    есть_файлы = {п.name for п in к.ПАПКА_ВЫХОДА.glob('*.svg')}

    def схема(имя, где):
        if имя not in подписи or имя not in есть_файлы:
            raise ОшибкаИндекса(f'{где}: схемы {имя} нет в app/public/makharij или в makharij.json')
        return имя

    махраджи = []
    for м in данные['махраджи']:
        з = {'id': м['id'], 'номер': м['номер'], 'область': м['область'],
             'арабский': {'название': м['арабский']['название'], **({'стих': м['арабский']['стих']} if м['арабский'].get('стих') else {})}}
        if м.get('лакаб'):
            з['лакаб'] = м['лакаб']
        з['название'] = тексты(м['название'], м['id'])
        з['описание'] = тексты(м['описание'], м['id'])
        if м.get('условие'):
            з['условие'] = тексты(м['условие'], м['id'])
        if м.get('гунна'):
            з['гунна'] = тексты(м['гунна'], м['id'] + '.гунна')
        # «куда» нет у полости и носа: звук ни к чему не прижимается.
        з['подсветка'] = {'что': тексты(м['подсветка']['что'], м['id']),
                          **({'куда': тексты(м['подсветка']['куда'], м['id'])} if м['подсветка'].get('куда') else {})}
        з['схема'] = схема(м['схема'], м['id'])
        з['подпись'] = тексты(подписи[м['схема']][1], м['схема'])
        if м.get('схемаСверху'):
            з['схемаСверху'] = схема(м['схемаСверху'], м['id'])
            з['подписьСверху'] = тексты(подписи[м['схемаСверху']][1], м['схемаСверху'])
        з['буквы'] = list(м['буквы'])
        махраджи.append(з)
    ид_махраджей = {м['id'] for м in махраджи}

    def запись_буквы(з, где):
        if з['махрадж'] not in ид_махраджей:
            raise ОшибкаИндекса(f'{где}: махрадж {з["махрадж"]}')
        итог = {'махрадж': з['махрадж'], 'проба': з['проба'], 'схема': схема(з['схема'], где)}
        if з.get('схемаСверху'):
            итог['схемаСверху'] = схема(з['схемаСверху'], где)
        if з.get('примечание'):
            итог['примечание'] = тексты(з['примечание'], где)
        return итог

    # Порядок букв — по махраджам (№1…17, внутри — как в махрадже), потом буквы без своего махраджа (лам-алиф):
    # «пред./след.» на карточке идут от горла к губам.
    номер_м = {м['id']: м['номер'] for м in махраджи}
    место = {м['id']: {б: i for i, б in enumerate(м['буквы'])} for м in махраджи}

    def ключ(б):
        з = данные['буквы'].get(б['id'], {})
        мид = з.get('махрадж')
        if 'состав' in з or мид not in номер_м:
            return (99, 0)
        return (номер_м[мид], место[мид].get(б['id'], 50))
    буквы = []
    for н, б in enumerate(sorted(буквы_уроков, key=ключ), 1):
        з = данные['буквы'].get(б['id'])
        if not з:
            raise ОшибкаИндекса(f'буква {б["id"]} из letters.json — нет в makharij.json')
        итог = {'id': б['id'], 'номер': н, 'знак': б['знак'],
                'название': {я: б['название'][я] for я in ('ru', 'kk', 'uz', 'en')}}
        итог.update(запись_буквы(з, б['id']))
        if з.get('состав'):
            итог['состав'] = list(з['состав'])
        for доп in ДОП:
            if доп in з:
                итог[доп] = запись_буквы(з[доп], f'{б["id"]}.{доп}')
        буквы.append(итог)
    if len(буквы) != len(данные['буквы']):
        raise ОшибкаИндекса('в makharij.json есть буквы, которых нет в letters.json')
    м = данные['мукаддима']
    индекс = {'формат': 1, 'версия': данные['версия'], 'статус': данные['статус'], 'автор': м['автор'],
              'сверить': м['сверить'],
              'области': [{'id': о['id'], 'арабский': о['арабский'], 'название': тексты(о['название'], о['id']),
                           'махраджи': list(о['махраджи'])} for о in данные['области']],
              'махраджи': махраджи, 'буквы': буквы}
    байты = (json.dumps(индекс, ensure_ascii=False, separators=(',', ':')) + '\n').encode('utf-8')
    sha = hashlib.sha256(байты).hexdigest()
    имя = f'makharij.{sha[:20]}.json'
    ids = ', '.join(f"'{б['id']}'" for б in буквы)
    манифест = ('// Создано tools/makharij/build_index.py — не править руками.\n'
                '// Махраджи (владелец 19.11 и 26.11.2026): индекс — fetch makharij-index/, схемы — makharij/*.svg.\n'
                f"export const МАНИФЕСТ_МАХРАДЖЕЙ = {{ файл: 'makharij-index/{имя}', sha256: '{sha}', буквы: [{ids}] }} as const;\n")
    return {имя: байты}, манифест.encode('utf-8'), индекс


def проверить():
    """Для tools/check_content.py: (ошибки, счёт). Файлы индекса и манифест = свежей сборке."""
    try:
        файлы, манифест, индекс = собрать()
    except (ОшибкаИндекса, KeyError) as е:
        return [f'makharij-index: {е}'], {}
    ошибки = []
    есть = {п.name for п in ПАПКА_ИНДЕКСА.glob('*')} if ПАПКА_ИНДЕКСА.exists() else set()
    if есть != set(файлы):
        ошибки.append(f'makharij-index: в папке {sorted(есть)}, нужен {sorted(файлы)} (python3 -I -B tools/makharij/build_index.py)')
    for имя, байты in файлы.items():
        if (ПАПКА_ИНДЕКСА / имя).exists() and (ПАПКА_ИНДЕКСА / имя).read_bytes() != байты:
            ошибки.append(f'makharij-index: {имя} ≠ свежей сборке')
    if not ПУТЬ_МАНИФЕСТА.exists() or ПУТЬ_МАНИФЕСТА.read_bytes() != манифест:
        ошибки.append('makharij-index: app/src/makharij/manifest.generated.ts ≠ свежей сборке')
    return ошибки, {'махраджи: в индексе приложения': len(индекс['махраджи']), 'махраджи: букв в индексе': len(индекс['буквы'])}


def main():
    try:
        файлы, манифест, индекс = собрать()
    except (ОшибкаИндекса, KeyError) as е:
        print(f'Ошибка индекса махраджей: {е}')
        return 1
    if '--check' in sys.argv[1:]:
        ошибки, _ = проверить()
        for о in ошибки:
            print('Ошибка:', о)
        print(f'Индекс махраджей: {len(индекс["махраджи"])} махраджей, {len(индекс["буквы"])} букв — '
              f'{"не совпадает" if ошибки else "совпадает"} со свежей сборкой.')
        return 1 if ошибки else 0
    ПАПКА_ИНДЕКСА.mkdir(parents=True, exist_ok=True)
    for п in ПАПКА_ИНДЕКСА.glob('*'):
        if п.name not in файлы:
            п.unlink()
    for имя, байты in файлы.items():
        (ПАПКА_ИНДЕКСА / имя).write_bytes(байты)
    ПУТЬ_МАНИФЕСТА.parent.mkdir(parents=True, exist_ok=True)
    ПУТЬ_МАНИФЕСТА.write_bytes(манифест)
    имя, байты = next(iter(файлы.items()))
    print(f'Индекс махраджей: app/public/makharij-index/{имя} ({len(байты) / 1024:.1f} КБ), '
          f'{len(индекс["махраджи"])} махраджей, {len(индекс["буквы"])} букв.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
