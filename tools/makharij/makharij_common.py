"""Общее для карты махраджей: пути, цвета схем из токенов дизайн-системы, чтение и запись данных.

Назначение: content/makharij.json (17 махраджей по Ибн аль-Джазари, буквы → махрадж, схемы) и свои SVG-схемы
в app/public/makharij/ — их собирает build_makharij.py, проверяет check_makharij.py.
Контракт:
  ПУТЬ_ДАННЫХ, ПАПКА_ВЫХОДА, ИМЯ_ФАЙЛА — где лежат данные и схемы; имя схемы `<id>.<sha256[:20]>.svg`
    (check-dist п. 2: у каждого файла сборки хэш в имени — service worker batr.kz кэширует по URL навсегда);
  палитры() → {'светлая': {роль: '#hex'}, 'тёмная': {...}} — цвета схем по ролям, взяты из app/src/theme/tokens.ts
    по именам токенов (РОЛИ_ЦВЕТА); своих hex в схемах нет;
  ПАРЫ_КОНТРАСТА_СХЕМ — пары ролей с порогом WCAG (проверка — check_makharij.py);
  прочитать() / записать(данные) — JSON с отступом 2, ensure_ascii=False, перевод строки в конце (как build_content.py).
Решения владельца: 19.11.2026 — «картинка произношения каждой буквы. Картинка, звук, видео…»; рисуем свои схемы с нуля
(иллюстрации «Көрнекі тәжуид» принадлежат д-ру Сувайду и Dar al-Ghouthani и пока не разрешены).
Правила CLAUDE.md: 9 — люди без лиц (схема тракта без контура лица, глаз и носа); 11 — черновик до проверки устазом.
"""
import json
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ_ДАННЫХ = КОРЕНЬ / 'content' / 'makharij.json'
ПУТЬ_БУКВ = КОРЕНЬ / 'content' / 'letters.json'
ПУТЬ_ТОКЕНОВ = КОРЕНЬ / 'app' / 'src' / 'theme' / 'tokens.ts'
ПАПКА_ВЫХОДА = КОРЕНЬ / 'app' / 'public' / 'makharij'
ПУТЬ_ЗАПИСЕЙ = КОРЕНЬ / 'docs' / 'записи-кари-буквы.md'
ИМЯ_ФАЙЛА = re.compile(r'^([a-z][a-z-]*)(?:-(m\d{1,2}w?))?\.([0-9a-f]{20})\.svg$')
# Бюджет: схемы — статические файлы (не JS), но входят в бюджет «всего» сборки (check-dist п. 6, сырые байты).
# Свой бюджет папки — по gzip -9: 23 файла (14 схем + 9 вариантов с одним выделенным махраджем) ≈ 45 КБ в gzip.
БЮДЖЕТ_ПАПКИ_КБ = 56

# Роль цвета в схеме → токен палитры: одно имя на обе темы или пара (светлая, тёмная).
# Тёмная тема (ревью 19.11): подложка — самый тёмный «фон», ткани светлее её («поверхность»), иначе полость рта
# выглядит светлее плоти; язык — «плашкаФон» (≥ 1,3 : 1 к подложке); «куда» — «золотоДекор», чтобы по яркости
# отличаться от «что работает» (≥ 1,5 : 1), а не только оттенком.
РОЛИ_ЦВЕТА = {
    'bg': ('поверхность', 'фон'),   # подложка карточки схемы
    'edge': 'граница',          # рамка карточки (декор)
    'line': 'текстВторой',      # контуры органов
    'tis': ('фон', 'поверхность'),  # ткани: нёбо, челюсть, стенка горла
    'tng': ('песок', 'плашкаФон'),  # язык и губы
    'tth': 'выбрано',           # зубы
    'cav': 'поверхностьАкцент', # полость носа (только схема гунны)
    'act': 'акцент',            # что работает: часть языка, губа, зона горла (сплошная линия)
    'pas': ('золотоЗначок', 'золотоДекор'),  # куда: нёбо, зубы, дёсны (точечная линия, залитая кромка зуба)
    'pasf': 'следующийФон',     # заливка места касания
    'air': 'бирюза',            # путь воздуха (пунктир со стрелкой)
    'mk': 'акцент',             # кружок номера махраджа
    'mkt': 'акцентТекст',       # цифра в кружке
}

# [роль, на роли, порог]: «что работает» и «куда» видны на всех поверхностях (≥ 3:1, как значки);
# цифра в кружке — текст (≥ 4,5:1); контуры — ≥ 3:1; «что» и «куда» различаются и по яркости (≥ 1,5:1),
# язык отделяется от подложки заливкой (≥ 1,25:1, держится и контуром).
ПАРЫ_КОНТРАСТА_СХЕМ = [
    ('act', 'pas', 1.5), ('tng', 'bg', 1.25),
    ('line', 'bg', 3), ('line', 'tis', 3), ('line', 'tng', 3),
    ('act', 'bg', 3), ('act', 'tis', 3), ('act', 'tng', 3), ('act', 'tth', 3), ('act', 'cav', 3),
    ('pas', 'bg', 3), ('pas', 'tis', 3), ('pas', 'tng', 3), ('pas', 'tth', 3),
    ('air', 'bg', 3), ('air', 'tis', 3),
    ('mkt', 'mk', 4.5),
]


def палитры():
    """Цвета ролей из app/src/theme/tokens.ts (светлая и тёмная палитры)."""
    текст = ПУТЬ_ТОКЕНОВ.read_text(encoding='utf-8')
    итог = {}
    for тема in ('светлая', 'тёмная'):
        м = re.search(r'export const ' + тема + r': Палитра = \{(.*?)\n\};', текст, re.S)
        if not м:
            raise SystemExit(f'В {ПУТЬ_ТОКЕНОВ} нет палитры «{тема}»')
        токены = dict(re.findall(r"^\s*([^\s:]+): '(#[0-9A-Fa-f]{6})',", м.group(1), re.M))
        итог[тема] = {}
        for роль, токены_роли in РОЛИ_ЦВЕТА.items():
            токен = токены_роли if isinstance(токены_роли, str) else токены_роли[тема == 'тёмная']
            if токен not in токены:
                raise SystemExit(f'Нет токена «{токен}» в палитре «{тема}» ({ПУТЬ_ТОКЕНОВ})')
            итог[тема][роль] = токены[токен].upper()
    return итог


def яркость(hex_):
    к = [int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    к = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in к]
    return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2]


def контраст(а, б):
    я1, я2 = sorted((яркость(а), яркость(б)), reverse=True)
    return (я1 + 0.05) / (я2 + 0.05)


def прочитать(путь=ПУТЬ_ДАННЫХ):
    return json.loads(путь.read_text(encoding='utf-8'))


def в_текст(данные):
    return json.dumps(данные, ensure_ascii=False, indent=2) + '\n'


def записать(данные, путь=ПУТЬ_ДАННЫХ):
    путь.write_text(в_текст(данные), encoding='utf-8')
