"""Общее для карты махраджей: пути, цвета схем, бюджеты, чтение и запись данных.

Назначение: content/makharij.json (17 махраджей по Ибн аль-Джазари, буквы → махрадж, схемы) и свои SVG-схемы
в app/public/makharij/ — их собирает build_makharij.py (рисунки — pozy.py на основе osnova.py), проверяет
check_makharij.py.
Контракт:
  ПУТЬ_ДАННЫХ, ПАПКА_ВЫХОДА, ИМЯ_ФАЙЛА — где лежат данные и схемы; имя схемы `<id>.<sha256[:20]>.svg`
    (check-dist п. 2: у каждого файла сборки хэш в имени — service worker batr.kz кэширует по URL навсегда);
  ЦВЕТА_СХЕМ — «природные» цвета рисунка и цвета подсветки (роль → '#hex'; каждый должен встречаться в osnova.py);
    номер махраджа — токен «акцент» / «акцентТекст» дизайн-системы (токены() читает app/src/theme/tokens.ts);
  ПАРЫ_КОНТРАСТА_СХЕМ — пары ролей с порогом WCAG (проверка — check_makharij.py);
  БЮДЖЕТ_ФАЙЛА_КБ, БЮДЖЕТ_ПАПКИ_КБ — сырые байты (без gzip): файл ≤ 40 КБ, папка ≤ 500 КБ;
  прочитать() / записать(данные) — JSON с отступом 2, ensure_ascii=False, перевод строки в конце (как build_content.py).
Решения владельца 19.11.2026: «картинка произношения каждой буквы…»; «Эти картинки нормально рисуй, как реальный рот
человека» — реалистичный разрез в природных цветах на своей светлой карточке (в тёмной теме карточка остаётся светлой).
Рисунки «Көрнекі тәжуид» (д-р Сувайд, Dar al-Ghouthani) не копируем и не обводим. Правило 9 (уточнено владельцем
19.11.2026): разрез от уровня носа и ниже — без глаз, бровей, лба, причёски, ушей. Правило 11 — черновик до устаза.
"""
import json
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ_ДАННЫХ = КОРЕНЬ / 'content' / 'makharij.json'
ПУТЬ_БУКВ = КОРЕНЬ / 'content' / 'letters.json'
ПУТЬ_ТОКЕНОВ = КОРЕНЬ / 'app' / 'src' / 'theme' / 'tokens.ts'
ПАПКА_ВЫХОДА = КОРЕНЬ / 'app' / 'public' / 'makharij'
ПУТЬ_ЗАПИСЕЙ = КОРЕНЬ / 'docs' / 'записи-кари-буквы.md'
ИМЯ_ФАЙЛА = re.compile(r'^([a-z][a-z-]*)(?:-(m\d{1,2}w?))?\.([0-9a-f]{20})\.svg$')
# Бюджет (задание 19.11.2026): каждый SVG ≤ 40 КБ, все ≤ 500 КБ — сырые байты; входят в бюджет сборки «всего»
# (check-dist п. 6).
БЮДЖЕТ_ФАЙЛА_КБ = 40
БЮДЖЕТ_ПАПКИ_КБ = 500

# Роль → цвет рисунка (osnova.CSS / DEFS). Номер махраджа — токены дизайн-системы (ТОКЕНЫ_НОМЕРА).
ЦВЕТА_СХЕМ = {
    'карточка': '#FBF7EE',   # подложка карточки (в обеих темах)
    'полость': '#B86F72',    # воздух в глубине (средний тон градиента)
    'язык': '#D06E67',       # язык (средний тон градиента)
    'десна': '#E9908C',      # десна на виде сверху
    'касание': '#F07800',    # что работает: оранжевая линия органа
    'место': '#FFD23F',      # куда: жёлтая линия места; касание без давления на виде сверху
    'опора': '#1F4FA8',      # вид сверху: опора с давлением
    'воздух': '#1593C9',     # пунктир воздуха
    'обводка': '#FFFFFF',    # светлая подложка пунктира и обводка номера
}
ТОКЕНЫ_НОМЕРА = {'номер': 'акцент', 'цифра': 'акцентТекст'}

# [роль, на роли, порог]: цифра в кружке — текст (≥ 4,5:1); номер виден на карточке; пунктир — на своей светлой
# подложке, подложка — на полости; «куда» (жёлтое) — на языке и в полости; «что» и «куда» различаются по яркости;
# синие бусины — на десне и рядом с жёлтыми.
ПАРЫ_КОНТРАСТА_СХЕМ = [
    ('цифра', 'номер', 4.5), ('номер', 'карточка', 4.5),
    ('воздух', 'обводка', 3), ('обводка', 'полость', 3),
    ('место', 'язык', 2), ('место', 'полость', 2), ('касание', 'место', 1.5),
    ('опора', 'десна', 3), ('место', 'опора', 3),
]


def токены():
    """Светлая палитра app/src/theme/tokens.ts: {имя токена: '#HEX'}."""
    текст = ПУТЬ_ТОКЕНОВ.read_text(encoding='utf-8')
    м = re.search(r'export const светлая: Палитра = \{(.*?)\n\};', текст, re.S)
    if not м:
        raise SystemExit(f'В {ПУТЬ_ТОКЕНОВ} нет светлой палитры')
    return {к: v.upper() for к, v in re.findall(r"^\s*([^\s:]+): '(#[0-9A-Fa-f]{6})',", м.group(1), re.M)}


def цвета():
    """ЦВЕТА_СХЕМ + цвета номера из токенов."""
    т = токены()
    итог = dict(ЦВЕТА_СХЕМ)
    for роль, токен in ТОКЕНЫ_НОМЕРА.items():
        if токен not in т:
            raise SystemExit(f'Нет токена «{токен}» в {ПУТЬ_ТОКЕНОВ}')
        итог[роль] = т[токен]
    return итог


def яркость(hex_):
    к = [int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    к = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in к]
    return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2]


def контраст(а, б):
    я1, я2 = sorted((яркость(а), яркость(б)), reverse=True)
    return (я1 + 0.05) / (я2 + 0.05)


def прочитать(путь=ПУТЬ_ДАННЫХ):
    return json.loads(путь.read_text(encoding='utf-8'))


def в_текст(данные):
    return json.dumps(данные, ensure_ascii=False, indent=2) + '\n'


def записать(данные, путь=ПУТЬ_ДАННЫХ):
    путь.write_text(в_текст(данные), encoding='utf-8')
