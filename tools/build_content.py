    def пара(self, a, b):
        """Минимальная пара: показ одного слова, выбор буквы, которой оно отличается."""
        ба, бб = об.буквы(a), об.буквы(b)
        if len(ба) != len(бб):
            return False
        разн = [i for i in range(len(ба)) if ба[i] != бб[i]]
        if len(разн) != 1:
            return False
        показ, другое = (a, b) if self.случай.random() < 0.5 else (b, a)
        i = разн[0]
        буква_показ, буква_другая = об.буквы(показ)[i], об.буквы(другое)[i]
        if буква_другая in об.буквы(показ):
            return False
        варианты, верный = self.варианты({'арабский': буква_показ}, [{'арабский': буква_другая}])
        з = {'тип': 'выбор', 'вид': 'пара', 'вопрос': т('Какая из этих букв есть в слове?', 'Сөзде осы әріптердің қайсысы бар?'),
             'показ': показ, 'варианты': варианты, 'верный': верный}
