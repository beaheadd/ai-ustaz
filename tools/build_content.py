        все = [с_огласовкой(б['знак'], г) for г in (об.ФАТХА, об.КЯСРА, об.ДАММА)]
        верный_слог = с_огласовкой(б['знак'], гл)
        варианты, верный = self.варианты({'арабский': верный_слог},
                                         [{'арабский': x} for x in все if x != верный_слог])
        ru, kk = ИМЯ_ОГЛАСОВКИ[гл]
        имя = self.имя(б)
