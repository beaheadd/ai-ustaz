def урок_уровня1(номер, буквы_, практика, курс_пункт):
    сб = Сборщик(f'L{номер:02d}', буквы_, f'L{номер:02d}')
    новые = [б for б in буквы_ if б['урок'] == номер and б['вид'] in ('буква', 'хамза')]
    изученные = [б for б in буквы_ if б['урок'] <= номер and б['вид'] in ('буква', 'хамза')]
    п = практика[номер]

    if номер == 1:
        сб.теория(т('Справа налево', 'Оңнан солға'),
                  т('Арабский текст читают справа налево. Первая буква слова — справа.',
                    'Араб мәтіні оңнан солға қарай оқылады. Сөздің бірінші әрпі — оң жақта.'),
                  примеры=['أَ', 'إِ', 'أُ'])
        сб.теория(т('Огласовки: фатха, кясра, дамма', 'Харакаттар: фатха, кәсра, дамма'),
                  т('Фатха — черта над буквой: «а». Кясра — черта под буквой: «и». Дамма — петелька над буквой: «у».',
                    'Фатха — әріптің үстіндегі сызық: «а». Кәсра — әріптің астындағы сызық: «и». Дамма — әріптің үстіндегі ілмек: «у».'),
                  примеры=['أَ', 'إِ', 'أُ'])
        сб.теория(т('Сукун', 'Сукун'),
                  т('Сукун — маленький кружок над буквой. Слог закрыт: после буквы гласного нет.',
                    'Сукун — әріптің үстіндегі кішкентай дөңгелек. Буын жабық: әріптен кейін дауысты жоқ.'),
                  примеры=['أَرْ', 'إِرْ', 'أُرْ'])

    for б in новые:
        сб.знакомство(б)
        if номер == 1 and б['id'] == 'alif':
            сб.теория(т('Алиф и хамза', 'Алиф пен хамза'),
                      т('Хамза (ء) — короткая смычка в горле, как перерыв в «а-а!». В начале слова она пишется на алифе: أَ إِ أُ.',
                        'Хамза (ء) — тамақтағы қысқа тоқтау, «а-а!» дегендегі үзіліс сияқты. Сөз басында ол алифтің үстіне жазылады: أَ إِ أُ.'),
                      примеры=['أَ', 'إِ', 'أُ'])
        if б['id'] == 'alif':
            continue
        # По три задания «выбор» на букву: найти по названию, огласовка, форма (у несоединяющихся — «собери»).
        сб.найди_букву(б, изученные)
        сб.огласовка_задание(б, закрытый=б['id'] != 'hamza' and (б['порядок'] or 0) % 2 == 0)
        if б['соединяетсяСлева'] and б['вид'] == 'буква':
            сб.форма(б)
        else:
            сб.собери(б)

    # Слоги: из программы (уроки 1–3) или по формату книги «буква + фатха, кясра, дамма» и закрытый слог.
    строки_слогов = list(п['слоги'])
    знаки_в_программе = {об.буквы(с[0])[-1] for с in строки_слогов}
    for б in новые:
        if б['id'] in ('alif',) or б['знак'] in знаки_в_программе:
            continue
        if б['id'] == 'hamza':
            continue
        строки_слогов.append([с_огласовкой(б['знак'], г) for г in (об.ФАТХА, об.КЯСРА, об.ДАММА)])
        строки_слогов.append([н + б['знак'] + об.СУКУН for н in открывающие_закрытого(б)])
    for и in range(0, len(строки_слогов), 2):
        сб.прочитай([с for строка in строки_слогов[и:и + 2] for с in строка])
    сб.запись([с for строка in строки_слогов[:2] for с in строка])

    if номер == 4:
        сб.теория(т('Дифтонг «ай»', '«Ай» дифтонгы'),
                  т('Если на ي сукун, а перед ней фатха, звучит «ай».', 'ي әрпінде сукун, ал алдында фатха болса, «ай» естіледі.'),
                  примеры=['بَيْتَ', 'بَيْنَ'])
    if номер == 6:
        сб.теория(т('Дифтонг «ау»', '«Ау» дифтонгы'),
                  т('Если на و сукун, а перед ней фатха, звучит «ау».', 'و әрпінде сукун, ал алдында фатха болса, «ау» естіледі.'),
                  примеры=['يَوْمَ', 'لَوْ'])
    if номер == 10:
        сб.теория(т('Тяжёлые буквы (исти‘ля)', 'Жуан әріптер (истиғла)'),
                  т('Семь букв читаются «тяжело»: задняя часть языка поднята, звук полный; гласный после них темнее, но не «о».',
                    'Жеті әріп «жуан» оқылады: тілдің арты көтеріледі, дыбыс толық; кейінгі дауысты жуандайды, бірақ «о» емес.'),
                  примеры=['خ', 'ص', 'ض', 'غ', 'ط', 'ق', 'ظ'])
    if номер in СРАВНЕНИЯ:
        карточка_сравнения(сб, СРАВНЕНИЯ[номер])
    if номер == 15:
        сб.теория(т('ض и ظ проверяет устаз', 'ض пен ظ әріптерін ұстаз тексереді'),
                  т('Различие ض и ظ ИИ не оценивает — только устаз.', 'ض пен ظ айырмасын ЖИ бағаламайды — тек ұстаз.'),
                  примеры=['ضَ', 'ظَ'])

    пары = п['пары']
    for a, b in пары[:5]:
        сб.пара(a, b)
    if пары:
        сб.прочитай([x for пара_ in пары for x in пара_][:8], ПОДСКАЗКА_ПАРЫ)

    слова = п['слова']
    for гр in группы(слова, 5):
        сб.прочитай(гр)
    if слова:
        сб.запись(слова[:3])
    if номер in ЛЕСТНИЦА_В_УРОКАХ:
        кандидаты = [с for с in слова + [x for пара_ in пары for x in пара_] if len(об.слоги(с)) >= 2]
        if кандидаты:
            сб.лестница(max(кандидаты, key=lambda с: len(об.слоги(с))))

    return {'номер': номер, 'id': f'L{номер:02d}', 'уровень': 1, 'название': курс_пункт['название'],
            'цель': курс_пункт['цель'], 'новое': [б['знак'] for б in новые] or [],
            'задания': сб.задания, 'критерий': {'доляВерных': ПОРОГ}, 'версия': ВЕРСИЯ, 'статус': СТАТУС,
            'утверждено': УТВЕРЖДЕНО}


def все_слова(практика, до):
    return [с for н in range(1, до + 1) for с in практика[н]['слова']]


