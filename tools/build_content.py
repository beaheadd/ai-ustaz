# ---------------------------------------------------------------- программа курса: практика уроков 1–15
def практика_программы():
    """{номер: {'слоги': [[...]], 'слова': [...], 'пары': [(a, b)]}} — дословно из таблицы §5.2."""
    текст = (ДОКИ / 'программа-курса.md').read_text(encoding='utf-8')
    раздел = текст[текст.index('### 5.2.'):текст.index('## 6. Уровень 2')]
    результат = {}
    for строка in раздел.splitlines():
        м = re.match(r'^\| (\d+) \| (.*?) \| (.*?) \|', строка)
        if not м or not 1 <= int(м.group(1)) <= 15:
            continue
        номер, ячейка = int(м.group(1)), м.group(3)
        данные = {'слоги': [], 'слова': [], 'пары': []}
        for сегмент in ячейка.split(' · '):
            if '–' in сегмент:
                for пара in re.findall(r'(\S+)–(\S+?)(?:[،\s*]|$)', сегмент.replace('**', ' ')):
                    a, b = (об.АРАБСКИЙ_ОТРЕЗОК.fullmatch(x.strip('،')) for x in пара)
                    if a and b:
                        данные['пары'].append((a.group(0), b.group(0)))
                continue
            лексемы = об.АРАБСКИЙ_ОТРЕЗОК.findall(сегмент.replace('،', ' '))
            if all(слог_ли(л) for л in лексемы):
                данные['слоги'].append(лексемы)
            else:
                данные['слова'].extend(лексемы)
        результат[номер] = данные
    return результат


