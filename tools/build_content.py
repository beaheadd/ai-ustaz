    соед = [б for б in изученные if б['вид'] == 'буква' and б['соединяетсяСлева']]
    for б in сб.случай.sample(соед, 4):
        сб.форма(б)
    пары = [p for н in range(1, 16) for p in практика[н]['пары']]
    сделано = 0
    for a, b in сб.случай.sample(пары, len(пары)):
        if сделано == 4:
            break
        сделано += сб.пара(a, b)
    слова = [с for с in все_слова(практика, 15)]
    for с in сб.случай.sample([x for x in слова if len(об.буквы(x)) >= 3], 2):
        сб.в_слове(с, изученные)
    выборка = сб.случай.sample(слова, 20)
    for гр in группы(выборка, 5):
        сб.прочитай(гр)
    сб.запись(выборка[:3])
    сб.запись(выборка[3:6])
    return {'номер': 101, 'id': 'K1', 'уровень': 1, 'название': курс_пункт['название'], 'цель': курс_пункт['цель'],
            'новое': [], 'задания': сб.задания, 'критерий': {'доляВерных': ПОРОГ}, 'версия': ВЕРСИЯ,
            'статус': СТАТУС, 'утверждено': УТВЕРЖДЕНО,
            'примечание': т('Тренировочный вариант без проверки голосом. Контрольной К1 он не засчитывается.',
                            'Дауыспен тексерусіз жаттығу нұсқасы. Ол Б1 бақылауы ретінде есептелмейді.')}


