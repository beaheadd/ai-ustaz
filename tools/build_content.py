def подсказки_каталога():
    """Таблица каталога ошибок §8: буква → (ru, kk), дословно."""
    текст = (ДОКИ / 'каталог-ошибок.md').read_text(encoding='utf-8')
    раздел = текст[текст.index('## 8. Подсказки по артикуляции'):текст.index('## 9. Микро-упражнения')]
    результат = {}
    for строка in раздел.splitlines():
        if not строка.startswith('| ') or строка.startswith('| Буква') or строка.startswith('|---'):
            continue
        ячейки = [я.strip() for я in строка.strip('|').split('|')]
        ключ, ru, kk = ячейки[0], ячейки[1], ячейки[2]
        if ключ == 'ب, د (на конце)':
            for б in ('ب', 'د'):
                результат[б] = (ru, kk)
        else:
            результат[ключ] = (ru, kk)
    for знак, (ru, kk, было_ru) in ПОПРАВКИ_ПОДСКАЗОК.items():
        if результат.get(знак, (None,))[0] != было_ru:
            raise SystemExit(f'Подсказка каталога §8 для {знак} изменилась — пересмотрите ПОПРАВКИ_ПОДСКАЗОК')
        результат[знак] = (ru, kk)
    return результат


