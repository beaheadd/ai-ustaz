def тексты_примера(каталог, номер, метки):
    начало = каталог.index(f'**Пример {номер}. ')
    конец = каталог.index('**Пример', начало + 10)
    блок = каталог[начало:конец].splitlines()
    результат = []
    for метка in метки:
        строка = next(с for с in блок if с.startswith(метка))
        результат.append(строка[строка.index(': «') + 3:строка.rindex('»')])
    return результат


def имена_букв_из_глоссария(текст, имена):
    """«буква ха (ح)» → «буква х̣а (ح)»: слот {буква_рус} (каталог §10.1) берёт имя из глоссария letters.json,
    а не из текста примера (в §13, пример 1, у ح стоит имя буквы خ)."""
    def замена(м):
        имя = имена.get(м.group(2))
        return f'буква {имя} ({м.group(2)})' if имя else м.group(0)
    return re.sub(r'буква (\S+) \(([\u0600-\u06FF])\)', замена, текст)


def имена_букв_kk(текст):
    """Казахский текст каталога: «әліп» → «алиф», как в глоссарии letters.json (одно имя у буквы, пока ДУМК
    не утвердит термин — программа §16, вопрос 9). Окончания совпадают: обе основы мягкие и на глухой согласный."""
    return re.sub(r'(?<![а-яәіңғүұқөһ])([Әә])ліп(?!пе)', lambda м: 'Алиф' if м.group(1) == 'Ә' else 'алиф', текст)


def лестница_из_текста(текст):
    for маркер in ('Повторите: ', 'Қайталаңыз: '):
        if маркер in текст:
            хвост = текст[текст.index(маркер) + len(маркер):]
            хвост = хвост.split('.')[0]
            return [ступень.strip() for ступень in хвост.split(' — ')]
    return []


