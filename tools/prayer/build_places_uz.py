ИСКЛЮЧИТЬ = {1512506}

# Шахимардан — эксклав Узбекистана в Киргизии: GeoNames даёт пояс Asia/Bishkek, но время там узбекское (UTC+5).


def км(а, б):
    р = math.pi / 180
    дш = (б['latitude'] - а['latitude']) * р
    дд = (б['longitude'] - а['longitude']) * р
    х = math.sin(дш / 2) ** 2 + math.cos(а['latitude'] * р) * math.cos(б['latitude'] * р) * math.sin(дд / 2) ** 2
    return 12742 * math.asin(math.sqrt(х))


def выбрать(города):
    уз = sorted((в for в in города.values() if в['countrycode'] == 'UZ'), key=lambda в: (-в['population'], в['geonameid']))
    взяты = []
    for в in уз:
        if в['geonameid'] in ИСКЛЮЧИТЬ:
            continue
        if в['admin1code'] == '13' and в['geonameid'] != СТОЛИЦА:
            continue
        if any(км(в, к) < 6 for к in взяты):
            continue
        взяты.append(в)
    return взяты


def склонения(точки):
    вход = json.dumps({'точки': точки})
    р = subprocess.run(['node', СКЛОНЕНИЕ], input=вход, capture_output=True, text=True, check=True)
    return json.loads(р.stdout)['склонение']


def ид(uz):
    с = uz.lower().replace('ʻ', '').replace(' ', '-')
    return re.sub(r'[^a-z-]', '', с)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    данные = sys.argv[1]
    выход = sys.argv[2] if len(sys.argv) > 2 else ВЫХОД
    with open(os.path.join(данные, 'cities1000.json'), encoding='utf-8') as ф:
        города = json.load(ф)
    взяты = выбрать(города)
    ошибки = []
    нет = [в['geonameid'] for в in взяты if в['geonameid'] not in НАЗВАНИЯ]
    if нет:
        ошибки.append('нет названий для geonameid: ' + ', '.join(map(str, нет)))
    лишние = set(НАЗВАНИЯ) - {в['geonameid'] for в in взяты}
    if лишние:
        ошибки.append('в таблице названий есть пункты не из выгрузки: ' + ', '.join(map(str, sorted(лишние))))
    if ошибки:
        raise SystemExit('\n'.join(ошибки))
    области = sorted({в['admin1code'] for в in взяты})
    коды = list(ВИЛОЯТЫ)
    if set(области) - set(коды):
        raise SystemExit('неизвестные вилояты: ' + ', '.join(sorted(set(области) - set(коды))))
    виды = ['столица', 'центр вилоята', 'город', '']
    взяты.sort(key=lambda в: (коды.index(в['admin1code']), 0 if в['geonameid'] in ЦЕНТРЫ or в['geonameid'] == СТОЛИЦА else 1,
                              -в['population'], в['geonameid']))
    скл = склонения([[в['latitude'], в['longitude']] for в in взяты])
    места = []
    ids = set()
    пары = set()
    for в, с in zip(взяты, скл):
        ru, uz = НАЗВАНИЯ[в['geonameid']]
        ш, д = в['latitude'], в['longitude']
        if not (ГРАНИЦЫ[0] <= ш <= ГРАНИЦЫ[1] and ГРАНИЦЫ[2] <= д <= ГРАНИЦЫ[3]):
            ошибки.append(f'вне Узбекистана: {ru} {ш} {д}')
        if not ru or not uz:
            ошибки.append(f'нет ru или uz: {в["geonameid"]}')
        if re.search(r"['’‘`]", uz):
            ошибки.append(f'в uz апостроф вместо U+02BB: {uz}')
        if re.search(r'[A-Za-z]', ru):
            ошибки.append(f'в ru латиница: {ru}')
        и = ид(uz)
        if и in ids:
            и = f'{и}-{в["admin1code"]}'
        if и in ids:
            ошибки.append(f'дубль id: {и}')
        ids.add(и)
        пара = (ru, в['admin1code'])
        if пара in пары:
            ошибки.append(f'дубль названия в вилояте: {ru}')
        пары.add(пара)
        if в['geonameid'] == СТОЛИЦА:
            вид = 0
        elif в['geonameid'] in ЦЕНТРЫ:
            вид = 1
        elif в['population'] >= 10000:
            вид = 2
        else:
            вид = 3
        места.append([и, ru, ru, uz, коды.index(в['admin1code']), вид, round(ш, 5), round(д, 5), с, в['geonameid']])
    if len({в['geonameid'] for в in взяты} & (ЦЕНТРЫ | {СТОЛИЦА})) != 14:
        ошибки.append('нет всех 14 центров (Ташкент и 13 вилоятов)')
    if ошибки:
        raise SystemExit('\n'.join(ошибки))
    итог = {
        'версия': 1,
        'описание': f'Места Узбекистана для времени намаза и киблы (AI Ustaz): {len(места)} — Ташкент, 13 центров вилоятов '
                    'и Каракалпакстана, города и посёлки GeoNames cities1000. Собрано tools/prayer/build_places_uz.py — '
                    'руками не править. Названия ru и uz — вручную (таблица в скрипте); kk = ru (черновик для редактора-носителя).',
        'источники': 'Координаты: GeoNames (geonames.org), CC BY 4.0 — выгрузка cities1000 из пакета geonamescache 3.0.2. '
                     'Склонение — модель WMM2025 (NOAA NCEI / NGA, общественное достояние) на 01.01.2027, градусы к востоку.',
        'страна': 'UZ',
        'поУмолчанию': 'toshkent',
        'области': [{'ru': ВИЛОЯТЫ[к][0], 'uz': ВИЛОЯТЫ[к][1], 'kk': ВИЛОЯТЫ[к][2]} for к in коды],
        'виды': виды,
        'поля': ['id', 'kk', 'ru', 'uz', 'область', 'вид', 'широта', 'долгота', 'склонение', 'geonameid'],
        'места': места,
    }
    with open(выход, 'w', encoding='utf-8') as ф:
        json.dump(итог, ф, ensure_ascii=False, indent=1)
        ф.write('\n')
    print(f'{выход}: {len(места)} мест')


if __name__ == '__main__':
    main()
