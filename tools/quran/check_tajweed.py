"""Проверка разметки таджвида и страниц мусхафа (её вызывает tools/check_content.py; отдельно — python3 -I -B tools/quran/check_tajweed.py).

Без сети. Любое расхождение — ошибка:
  (а) content/quran/quran-data.js: sha256 = внешнему якорю build_tajweed.ЭТАЛОН_SHA256_МЕТАДАННЫХ = записи
      «tanzil-metadata» в content/sources.json; страниц 604, джузов 30, четвертей хизба 240, всё по порядку
      «сура:аят», номера аятов существуют, страница 1 — 1:1, страница 2 — 2:1, начало каждого джуза — начало четверти;
  (б) манифест app/src/quran/tajweedManifest.generated.ts → индекс tajweed/index.<хэш>.json (sha256, хэш в имени,
      коды правил, sha256 XML-источника);
  (в) каждый файл сур tajweed/NNN: sha256 = индексу и началу имени; sha256Текста = sha256 файла суры в индексе
      Корана; длины = длинам аятов XML; разметка раскодируется, отрезки по порядку, не пересекаются, внутри строки,
      без пробелов, не режут букву и её знаки (начало — не знак, после конца — не знак); склейка кусков = аяту
      побайтно (для всех 6236 аятов и бисмилл); разметка = свежему расчёту правил tools/quran/tajweed_rules.py;
  (г) в app/public/quran/tajweed нет лишних файлов, файлы = свежей сборке build_tajweed.py;
  (д) явные ожидания tools/quran/test_tajweed.py (аль-Фатиха, 2:1–5, 112–114, примеры уроков 32–40) совпадают.
Контракт: проверить(sha_в_sources) -> (ошибки: list[str], счёт: dict[str, int]).
"""
import json
import pathlib
import re
import sys
import unicodedata

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_tajweed as б  # noqa: E402
import quran_common as к  # noqa: E402
import tajweed_rules as п  # noqa: E402
import test_tajweed  # noqa: E402


def куски(текст, отрезки):
    """Текст аята → куски [(подстрока, код|None)] по отрезкам; склейка = текст."""
    р, поз = [], 0
    for с, по, ч in отрезки:
        if с > поз:
            р.append((текст[поз:с], None))
        р.append((текст[с:по], ч))
        поз = по
    if поз < len(текст):
        р.append((текст[поз:], None))
    return р


def знак(ч):
    return unicodedata.category(ч) == 'Mn'


def проверить_отрезки(текст, отрезки):
    """Список нарушений (пустой — всё верно)."""
    плохо, конец = [], 0
    for с, по, ч in отрезки:
        if ч not in п.КОДЫ:
            плохо.append(f'код {ч}')
        if с < конец or по <= с or по > len(текст):
            плохо.append(f'отрезок {с}–{по} вне порядка или строки')
            continue
        if ' ' in текст[с:по]:
            плохо.append(f'отрезок {с}–{по} с пробелом')
        if знак(текст[с]):
            плохо.append(f'отрезок {с}–{по} начинается со знака')
        if по < len(текст) and знак(текст[по]):
            плохо.append(f'отрезок {с}–{по} отрывает знак после себя')
        конец = по
    if ''.join(т for т, _ in куски(текст, отрезки)) != текст:
        плохо.append('склейка кусков ≠ аяту')
    return плохо


def проверить(sha_в_sources):
    ошибки, счёт = [], {}

    def ош(где, что):
        ошибки.append(f'tajweed: {где}: {что}')

    def плюс(ключ, н=1):
        счёт[ключ] = счёт.get(ключ, 0) + н

    # (а) метаданные
    if not б.ПУТЬ_МЕТАДАННЫХ.exists():
        ош('quran-data.js', 'нет файла метаданных Tanzil')
        return ошибки, счёт
    sha_м = к.sha256_байтов(б.ПУТЬ_МЕТАДАННЫХ.read_bytes())
    if sha_м != б.ЭТАЛОН_SHA256_МЕТАДАННЫХ:
        ош('quran-data.js', f'sha256 {sha_м} ≠ эталону загрузки ({б.МЕТАДАННЫЕ_ЗАГРУЖЕНЫ}) {б.ЭТАЛОН_SHA256_МЕТАДАННЫХ}')
    if sha_в_sources != б.ЭТАЛОН_SHA256_МЕТАДАННЫХ:
        ош('sources.json', f'sha256 tanzil-metadata {sha_в_sources} ≠ эталону')
    копия = к.прочитать_xml(к.ПУТЬ_XML)
    аятов = {с.номер: len(с.аяты) for с in копия.суры}
    страницы, джузы, четверти = б.метаданные()

    def по_порядку(список, имя, сколько):
        if len(список) != сколько:
            ош('quran-data.js', f'{имя}: {len(список)}, нужно {сколько}')
        for (с1, а1), (с2, а2) in zip(список, список[1:]):
            if (с2, а2) <= (с1, а1):
                ош('quran-data.js', f'{имя}: не по порядку {с1}:{а1} → {с2}:{а2}')
        for с, а in список:
            if с not in аятов or not 1 <= а <= аятов[с]:
                ош('quran-data.js', f'{имя}: нет аята {с}:{а}')

    по_порядку(страницы, 'страницы', б.СТРАНИЦ)
    по_порядку(джузы, 'джузы', б.ДЖУЗОВ)
    по_порядку(четверти, 'четверти', б.ЧЕТВЕРТЕЙ)
    if страницы[:2] != [[1, 1], [2, 1]]:
        ош('quran-data.js', 'страница 1 — не 1:1 или страница 2 — не 2:1')
    if not all(д in четверти for д in джузы):
        ош('quran-data.js', 'начало джуза не совпадает с началом четверти хизба')
    плюс('Мусхаф: страниц (Tanzil Metadata)', len(страницы))

    # (б) манифест → индекс
    if not б.ПУТЬ_МАНИФЕСТА.exists():
        ош('tajweedManifest.generated.ts', 'нет манифеста — запустите tools/quran/build_tajweed.py')
        return ошибки, счёт
    манифест = б.ПУТЬ_МАНИФЕСТА.read_text(encoding='utf-8')
    м_и = re.search(r"индекс: '([^']+)'", манифест)
    м_sha = re.search(r"sha256Индекса: '([0-9a-f]{64})'", манифест)
    if not (м_и and м_sha):
        ош('tajweedManifest.generated.ts', 'не разобрать индекс/sha256')
        return ошибки, счёт

    def файл(отн, sha, где):
        if not отн.startswith(б.ПОДПАПКА + '/'):
            ош(где, f'файл «{отн}» не в {б.ПОДПАПКА}/')
            return None
        путь = б.ПАПКА / отн.rsplit('/', 1)[1]
        if not путь.exists():
            ош(где, f'нет файла {отн}')
            return None
        байты = путь.read_bytes()
        с = к.sha256_байтов(байты)
        if с != sha:
            ош(где, f'sha256 {отн} не совпадает')
        м = б.ИМЯ_ФАЙЛА.match(путь.name)
        if not м or м.group(2) != с[:к.ДЛИНА_ХЭША]:
            ош(где, f'хэш в имени {отн} ≠ началу sha256')
        return json.loads(байты.decode('utf-8'))

    индекс = файл(м_и.group(1), м_sha.group(1), 'manifest → index')
    if индекс is None:
        return ошибки, счёт
    if индекс.get('коды') != п.КОДЫ or индекс.get('правила') != б.ВЕРСИЯ_ПРАВИЛ:
        ош('index', 'коды или версия правил не те')
    if индекс.get('sha256Источника') != копия.sha256:
        ош('index', 'sha256 XML-источника не тот')
    if [индекс.get('страницы'), индекс.get('джузы'), индекс.get('четверти')] != [страницы, джузы, четверти]:
        ош('index', 'страницы/джузы/четверти ≠ quran-data.js')
    if (индекс.get('метаданные') or {}).get('sha256') != sha_м:
        ош('index', 'sha256 метаданных не тот')
    индекс_корана = б.индекс_корана()
    нужные = {м_и.group(1).rsplit('/', 1)[1]}
    сверено = отрезков = 0
    по_номеру = {с.номер: с for с in копия.суры}
    записи = индекс.get('суры') or []
    if [з.get('сура') for з in записи] != list(range(1, к.СУР + 1)):
        ош('index', 'записи сур не 1…114')
    for з in записи:
        н = з.get('сура')
        с = по_номеру.get(н)
        if not с:
            continue
        где = f'сура {н}'
        if з.get('sha256Текста') != индекс_корана['суры'][н - 1]['sha256']:
            ош(где, 'sha256Текста ≠ файлу суры в индексе Корана')
        д = файл(з.get('файл') or '', з.get('sha256'), где)
        if д is None:
            continue
        нужные.add(з['файл'].rsplit('/', 1)[1])
        if д.get('sha256Текста') != з.get('sha256Текста') or д.get('сура') != н:
            ош(где, 'номер суры или sha256Текста в файле ≠ индексу')
        if д.get('длины') != [len(т) for _, т in с.аяты] or len(д.get('аяты') or []) != len(с.аяты):
            ош(где, 'длины аятов или число разметок ≠ XML')
            continue
        пары = list(zip([т for _, т in с.аяты], д['аяты'], [f'{н}:{а}' for а, _ in с.аяты]))
        if с.бисмилла:
            if д.get('длиныБисмиллы') != len(с.бисмилла) or not isinstance(д.get('бисмилла'), str):
                ош(где, 'бисмилла: длина или разметка')
            else:
                пары.append((с.бисмилла, д['бисмилла'], f'{н}:бисмилла'))
        elif д.get('бисмилла') is not None:
            ош(где, 'бисмилла есть в разметке, а в XML нет')
        for текст, строка, имя in пары:
            try:
                отр = п.раскодировать(строка)
            except ValueError as е:
                ош(имя, str(е))
                continue
            плохо = проверить_отрезки(текст, отр)
            if плохо:
                ош(имя, '; '.join(плохо[:3]))
            if строка != п.закодировать(п.разметить(текст)):
                ош(имя, 'разметка ≠ свежему расчёту правил')
            сверено += 1
            отрезков += len(отр)
    плюс('Таджвид: аятов и бисмилл — склейка кусков = тексту Tanzil, отрезки по границам букв', сверено)
    плюс('Таджвид: отрезков разметки', отрезков)
    if сверено != к.АЯТОВ + 112:
        ош('разметка', f'сверено {сверено}, нужно {к.АЯТОВ} аятов + 112 бисмилл')

    # (д) смысл правил на известных аятах (tools/quran/test_tajweed.py: аль-Фатиха, 2:1–5, 112–114, уроки 32–40)
    for е in test_tajweed.провалы_ожиданий(копия):
        ош('ожидания test_tajweed', е)
    плюс('Таджвид: аятов с явными ожиданиями (test_tajweed)', len(test_tajweed.ОЖИДАНИЯ))

    # (г) лишние и свежесть
    for путь in sorted(б.ПАПКА.glob('*')):
        if путь.name not in нужные:
            ош('app/public/quran/tajweed', f'лишний файл {путь.name}')
    свежие, свежий_манифест = б.собрать()
    устарели = [о for о, бб in свежие.items()
                if not (б.ПАПКА / о.rsplit('/', 1)[1]).exists() or (б.ПАПКА / о.rsplit('/', 1)[1]).read_bytes() != бб]
    if устарели or свежий_манифест != манифест:
        ош('разметка', f'не совпадает со свежей сборкой ({len(устарели)} файлов) — tools/quran/build_tajweed.py')
    return ошибки, счёт


if __name__ == '__main__':
    источники = json.loads((к.КОРЕНЬ / 'content' / 'sources.json').read_text(encoding='utf-8'))
    мета = next((и for и in источники['источники'] if и['id'] == 'tanzil-metadata'), {})
    ошибки, счёт = проверить(мета.get('sha256Файла'))
    for кл, в in счёт.items():
        print(f'  {кл}: {в}')
    for е in ошибки:
        print('  - ' + е)
    print('Итог: ' + ('ошибок нет.' if not ошибки else f'ОШИБКИ: {len(ошибки)}'))
    sys.exit(1 if ошибки else 0)
