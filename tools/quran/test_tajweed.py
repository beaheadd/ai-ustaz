def провалы_ожиданий(копия):
    """Список расхождений с ОЖИДАНИЯ (пустой — всё совпало)."""
    аяты = {(с.номер, н): т for с in копия.суры for н, т in с.аяты}
    р = []
    for ключ, ожидание in ОЖИДАНИЯ.items():
        текст = аяты[ключ]
        вышло = ' '.join(f'{ч}:{текст[с:по]}' for с, по, ч in п.разметить(текст))
        if вышло != ожидание:
            р.append(f'{ключ[0]}:{ключ[1]}\n    ждали: {ожидание}\n    вышло: {вышло}')
    return р


def main():
    копия = к.прочитать_xml(к.ПУТЬ_XML)
    провалы = провалы_ожиданий(копия)
    # Кодирование туда и обратно — на всех 6236 аятах (длинные отрезки кодируются частями ≤ 35).
    for _, текст in ((н, т) for с in копия.суры for н, т in с.аяты):
        отр = п.разметить(текст)
        if п.раскодировать(п.закодировать(отр)) != _дробить(отр):
            провалы.append('кодирование туда-обратно: ' + текст[:30])
            break
    проверок = len(ОЖИДАНИЯ) + 1
    for е in провалы:
        print('  ✗ ' + е)
    print(f'Правила таджвида: {проверок - len(провалы)} из {проверок} проверок ({len(ОЖИДАНИЯ)} аятов с ожиданиями).')
    return 1 if провалы else 0


def _дробить(отр):
    """Отрезки длиннее 35 кодируются частями — так их и раскодируем."""
    р = []
    for с, по, ч in отр:
        while по - с > 35:
            р.append((с, с + 35, ч))
            с += 35
        р.append((с, по, ч))
    return р


if __name__ == '__main__':
    sys.exit(main())
