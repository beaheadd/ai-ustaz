@dataclass
class Сура:
    номер: int
    имя: str
    бисмилла: str | None
    аяты: list = field(default_factory=list)   # [(номер аята, текст)] — дословно из XML


@dataclass
class КопияКорана:
    суры: list
    копирайт: str      # блок копирайта Tanzil дословно (между <!-- и -->)
    sha256: str        # sha256 файла XML


def sha256_байтов(байты):
    return hashlib.sha256(байты).hexdigest()


def прочитать_xml(путь=ПУТЬ_XML):
    байты = pathlib.Path(путь).read_bytes()
    сырой = байты.decode('utf-8')
    копирайт = сырой[сырой.index('<!--') + 4:сырой.index('-->')]
    корень = ET.fromstring(байты)
    суры = []
    for с in корень.iter('sura'):
        сура = Сура(int(с.get('index')), с.get('name'), None)
        for а in с.iter('aya'):
            if а.get('bismillah') is not None:
                if int(а.get('index')) != 1 or сура.бисмилла is not None:
                    raise ValueError(f'бисмилла не у первого аята суры {сура.номер}')
                сура.бисмилла = а.get('bismillah')
            сура.аяты.append((int(а.get('index')), а.get('text')))
        суры.append(сура)
    return КопияКорана(суры, копирайт, sha256_байтов(байты))


def _json(данные):
    # Компактно (без отступов): ≈ 1,5 МБ на весь Коран; текст аятов — как есть (ensure_ascii=False, без экранирования).
    return (json.dumps(данные, ensure_ascii=False, separators=(',', ':')) + '\n').encode('utf-8')


def _имя(основа, байты):
    return f'{основа}.{sha256_байтов(байты)[:ДЛИНА_ХЭША]}.json'


def хэш_в_имени(имя):
    м = ИМЯ_ФАЙЛА.match(имя)
    return м.group(2) if м else None


def собрать(путь_xml=ПУТЬ_XML, имя_xml=None):
    """Все производные: ({'quran/<имя>': байты}, текст manifest.generated.ts). Детерминированно."""
    копия = прочитать_xml(путь_xml)
    if len(копия.суры) != СУР or sum(len(с.аяты) for с in копия.суры) != АЯТОВ:
        raise ValueError('в XML не 114 сур / 6236 аятов')
    имя_xml = имя_xml or pathlib.Path(путь_xml).name
    общее = {'формат': ФОРМАТ, 'источник': ИСТОЧНИК, 'копия': КОПИЯ, 'файлИсточника': имя_xml,
             'sha256Источника': копия.sha256}
    файлы, записи = {}, []
    for с in копия.суры:
        данные = {**общее, 'сура': с.номер, 'имя': с.имя, 'аятов': len(с.аяты), 'бисмилла': с.бисмилла,
                  'аяты': [{'аят': н, 'текст': т} for н, т in с.аяты], 'копирайт': копия.копирайт}
        байты = _json(данные)
        имя = _имя(f'{с.номер:03d}', байты)
        файлы[f'{ПОДПАПКА}/{имя}'] = байты
        записи.append({'сура': с.номер, 'имя': с.имя, 'аятов': len(с.аяты), 'файл': f'{ПОДПАПКА}/{имя}',
                       'sha256': sha256_байтов(байты),
                       'транслит': {'ru': ТРАНСЛИТ_RU[с.номер - 1], 'kk': None},
                       'синонимы': [ТРАНСЛИТ_LAT[с.номер - 1], *СИНОНИМЫ.get(с.номер, ())]})
    индекс = {**общее, 'сур': СУР, 'аятов': АЯТОВ,
              'статусТранслита': 'черновик',
              'транслитПримечание': 'Транслитерация арабского имени суры, не перевод смыслов. ru — черновик для '
                                    'проверки устазом и редактором; kk пока нет (показывать номер и арабское имя).',
              'суры': записи, 'копирайт': копия.копирайт}
    байты_индекса = _json(индекс)
    имя_индекса = _имя('index', байты_индекса)
    файлы[f'{ПОДПАПКА}/{имя_индекса}'] = байты_индекса
    манифест = (
        '/**\n'
        ' * СГЕНЕРИРОВАНО tools/quran/build_quran.py — руками не править (python3 -I -B tools/quran/build_quran.py).\n'
        ' * Где лежит индекс сур Корана для показа (статический файл сборки: app/public/quran → dist/quran).\n'
        ' * Текста Корана здесь нет: только имя файла индекса и его sha256 (src/quran/data.ts сверяет при загрузке).\n'
        ' */\n'
        'export const МАНИФЕСТ_КОРАНА = {\n'
        f'  формат: {ФОРМАТ},\n'
        f"  индекс: '{ПОДПАПКА}/{имя_индекса}',\n"
        f"  sha256Индекса: '{sha256_байтов(байты_индекса)}',\n"
        f'  сур: {СУР},\n'
        f'  аятов: {АЯТОВ},\n'
        f"  источник: '{ИСТОЧНИК}',\n"
        f"  файлИсточника: '{имя_xml}',\n"
        f"  sha256Источника: '{копия.sha256}',\n"
        '} as const;\n'
    )
    return файлы, манифест
