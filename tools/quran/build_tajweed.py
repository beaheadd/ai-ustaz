"""Сборка разметки таджвида и страниц мусхафа для видов чтения «Страница мусхафа», «Мусхаф + цвета таджвида», «Ночной».

Запуск:  python3 -I -B tools/quran/build_tajweed.py [--check]   (без сети и сторонних пакетов)
Читает:  content/quran/quran-uthmani-marks.xml (Tanzil Uthmani v1.1, копия ДЛЯ ПОКАЗА — тот же текст, что в app/public/quran),
         content/quran/quran-data.js (Tanzil Quran Metadata 1.0, CC BY 3.0: страницы мединского мусхафа (604), джузы,
         четверти хизба — только номера «сура:аят», текста Корана в нём нет), app/public/quran/index.<хэш>.json (sha256
         файлов сур — привязка разметки к тексту).
Пишет:   app/public/quran/tajweed/NNN.<хэш>.json (114) — разметка аятов и бисмиллы;
         app/public/quran/tajweed/index.<хэш>.json — страницы, джузы, четверти, файлы разметки и sha256 текста сур;
         app/src/quran/tajweedManifest.generated.ts — имя и sha256 индекса (в бандле ни разметки, ни текста).
--check: ничего не пишет; код 1, если файлы на диске не совпадают со свежей сборкой.
Проверка — tools/quran/check_tajweed.py (из tools/check_content.py); тесты правил — tools/quran/test_tajweed.py.

Формат разметки аята — строка «<пропуск><КОД><длина>» подряд: пропуск — число символов от конца прошлого отрезка
(десятичное), КОД — заглавная буква кода (tajweed_rules.КОДЫ), длина — один знак base36 (1…z). Индексы — в строке
аята Tanzil как есть (UTF-16 = кодовые точки: всё в BMP). Текст Корана в файлах разметки НЕ хранится: только
отрезки, длины аятов и sha256 файла суры — разметка годится только к тому же тексту (правило 1 CLAUDE.md).
Решение владельца 20.11.2026: «Коран нужно нам сделать разные дизайны … 3–4 варианта».
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import quran_common as к  # noqa: E402
import tajweed_rules as п  # noqa: E402

ПУТЬ_МЕТАДАННЫХ = к.КОРЕНЬ / 'content' / 'quran' / 'quran-data.js'
# Внешний якорь метаданных: sha256 файла tanzil.net/res/text/metadata/quran-data.js при загрузке 20.11.2026.
ЭТАЛОН_SHA256_МЕТАДАННЫХ = '9e9930c592aaa34b5c7a79ff4e99ffdc782263a266090bfe2c49e4ed4bac4ca4'
МЕТАДАННЫЕ_ЗАГРУЖЕНЫ = '2026-11-20'
АТРИБУЦИЯ_МЕТАДАННЫХ = 'Tanzil Quran Metadata (ver 1.0). Copyright (C) 2008-2009 Tanzil.info. License: Creative Commons Attribution 3.0. tanzil.net'
ПАПКА = к.ПАПКА_ВЫХОДА / 'tajweed'
ПОДПАПКА = 'quran/tajweed'
ПУТЬ_МАНИФЕСТА = к.КОРЕНЬ / 'app' / 'src' / 'quran' / 'tajweedManifest.generated.ts'
ФОРМАТ = 1
ВЕРСИЯ_ПРАВИЛ = 'aiustaz-tajweed-1'
ИМЯ_ФАЙЛА = re.compile(r'^(index|\d{3})\.([0-9a-f]{20})\.json$')
СТРАНИЦ, ДЖУЗОВ, ЧЕТВЕРТЕЙ = 604, 30, 240


def метаданные(путь=ПУТЬ_МЕТАДАННЫХ):
    """Страницы, джузы, четверти хизба из quran-data.js: списки [сура, аят] начала (без пустой первой записи и без
    завершающей [115, 1]). Разбор регулярками — JS не исполняется."""
    сырой = pathlib.Path(путь).read_text(encoding='utf-8')

    def массив(имя):
        м = re.search(r'QuranData\.' + имя + r'\s*=\s*\[(.*?)\n\];', сырой, re.S)
        if not м:
            raise ValueError(f'в quran-data.js нет QuranData.{имя}')
        пары = [[int(а), int(б)] for а, б in re.findall(r'\[\s*(\d+)\s*,\s*(\d+)\s*\]', м.group(1))]
        if not пары or пары[-1] != [115, 1]:
            raise ValueError(f'QuranData.{имя}: нет завершающей [115, 1]')
        return пары[:-1]

    return массив('Page'), массив('Juz'), массив('HizbQaurter')


def _json(данные):
    return (json.dumps(данные, ensure_ascii=False, separators=(',', ':')) + '\n').encode('utf-8')


def _имя(основа, байты):
    return f'{основа}.{к.sha256_байтов(байты)[:к.ДЛИНА_ХЭША]}.json'


def индекс_корана():
    """Записи сур из текущего индекса Корана (app/public/quran) — sha256 файлов сур для привязки."""
    манифест = к.ПУТЬ_МАНИФЕСТА.read_text(encoding='utf-8')
    имя = re.search(r"индекс: '([^']+)'", манифест).group(1)
    return json.loads((к.ПАПКА_ВЫХОДА / имя.split('/', 1)[1]).read_text(encoding='utf-8'))


def собрать():
    """({'quran/tajweed/<имя>': байты}, текст манифеста). Детерминированно."""
    копия = к.прочитать_xml(к.ПУТЬ_XML)
    байты_мета = ПУТЬ_МЕТАДАННЫХ.read_bytes()
    sha_мета = к.sha256_байтов(байты_мета)
    if sha_мета != ЭТАЛОН_SHA256_МЕТАДАННЫХ:
        raise ValueError(f'sha256 quran-data.js {sha_мета} ≠ эталону загрузки с tanzil.net {ЭТАЛОН_SHA256_МЕТАДАННЫХ}')
    страницы, джузы, четверти = метаданные()
    if (len(страницы), len(джузы), len(четверти)) != (СТРАНИЦ, ДЖУЗОВ, ЧЕТВЕРТЕЙ):
        raise ValueError(f'страниц {len(страницы)}, джузов {len(джузы)}, четвертей {len(четверти)}')
    индекс = индекс_корана()
    if индекс.get('sha256Источника') != копия.sha256:
        raise ValueError('индекс Корана собран из другого XML — сначала tools/quran/build_quran.py')
    файлы, записи = {}, []
    for с in копия.суры:
        запись_корана = индекс['суры'][с.номер - 1]
        разметка = [п.закодировать(п.разметить(т)) for _, т in с.аяты]
        данные = {'формат': ФОРМАТ, 'правила': ВЕРСИЯ_ПРАВИЛ, 'сура': с.номер,
                  'файлТекста': запись_корана['файл'], 'sha256Текста': запись_корана['sha256'],
                  'бисмилла': п.закодировать(п.разметить(с.бисмилла)) if с.бисмилла else None,
                  'длиныБисмиллы': len(с.бисмилла) if с.бисмилла else None,
                  'длины': [len(т) for _, т in с.аяты], 'аяты': разметка}
        байты = _json(данные)
        имя = _имя(f'{с.номер:03d}', байты)
        файлы[f'{ПОДПАПКА}/{имя}'] = байты
        записи.append({'сура': с.номер, 'файл': f'{ПОДПАПКА}/{имя}', 'sha256': к.sha256_байтов(байты),
                       'sha256Текста': запись_корана['sha256']})
    индекс_т = {
        'формат': ФОРМАТ,
        'правила': ВЕРСИЯ_ПРАВИЛ,
        'статусПравил': 'черновик',
        'линия': 'Хафс от ‘Асыма через аш-Шатибийю',
        'коды': п.КОДЫ,
        'источник': к.ИСТОЧНИК, 'sha256Источника': копия.sha256,
        'метаданные': {'источник': 'Tanzil Quran Metadata 1.0', 'файл': ПУТЬ_МЕТАДАННЫХ.name, 'sha256': sha_мета,
                       'лицензия': 'CC BY 3.0', 'атрибуция': АТРИБУЦИЯ_МЕТАДАННЫХ,
                       'мусхаф': 'страницы мединского мусхафа (604); переносы строк — по ширине экрана'},
        'страницы': страницы, 'джузы': джузы, 'четверти': четверти,
        'суры': записи,
    }
    байты_и = _json(индекс_т)
    имя_и = _имя('index', байты_и)
    файлы[f'{ПОДПАПКА}/{имя_и}'] = байты_и
    манифест = (
        '/**\n'
        ' * СГЕНЕРИРОВАНО tools/quran/build_tajweed.py — руками не править (python3 -I -B tools/quran/build_tajweed.py).\n'
        ' * Где лежит индекс видов чтения: страницы мединского мусхафа (Tanzil Metadata, CC BY 3.0) и файлы разметки\n'
        ' * таджвида по сурам (app/public/quran/tajweed → dist/quran/tajweed). Ни текста Корана, ни разметки здесь нет.\n'
        ' */\n'
        'export const МАНИФЕСТ_ТАДЖВИДА = {\n'
        f'  формат: {ФОРМАТ},\n'
        f"  индекс: '{ПОДПАПКА}/{имя_и}',\n"
        f"  sha256Индекса: '{к.sha256_байтов(байты_и)}',\n"
        f"  правила: '{ВЕРСИЯ_ПРАВИЛ}',\n"
        f"  коды: '{п.КОДЫ}',\n"
        f'  страниц: {СТРАНИЦ},\n'
        '} as const;\n'
    )
    return файлы, манифест


def main():
    файлы, манифест = собрать()
    нужные = {о.rsplit('/', 1)[1] for о in файлы}
    есть = {ф.name for ф in ПАПКА.glob('*')} if ПАПКА.exists() else set()
    чужие = sorted(и for и in есть if not ИМЯ_ФАЙЛА.match(и))
    if чужие:
        print(f'В {ПАПКА} чужие файлы: {", ".join(чужие)}')
        return 1
    if '--check' in sys.argv:
        разные = [о for о, б in файлы.items() if not (ПАПКА / о.rsplit('/', 1)[1]).exists()
                  or (ПАПКА / о.rsplit('/', 1)[1]).read_bytes() != б]
        старый = ПУТЬ_МАНИФЕСТА.read_text(encoding='utf-8') if ПУТЬ_МАНИФЕСТА.exists() else ''
        if разные or (есть - нужные) or старый != манифест:
            print(f'Разметка устарела: разных {len(разные)}, лишних {len(есть - нужные)}, манифест '
                  f'{"другой" if старый != манифест else "тот же"}. Запустите python3 -I -B tools/quran/build_tajweed.py')
            return 1
        print('Разметка таджвида и страницы совпадают со свежей сборкой.')
        return 0
    ПАПКА.mkdir(parents=True, exist_ok=True)
    for имя in sorted(есть - нужные):
        (ПАПКА / имя).unlink()
    for о, б in файлы.items():
        цель = ПАПКА / о.rsplit('/', 1)[1]
        if not цель.exists() or цель.read_bytes() != б:
            цель.write_bytes(б)
    ПУТЬ_МАНИФЕСТА.write_text(манифест, encoding='utf-8')
    print(f'Готово: {len(файлы)} файлов в {ПАПКА.relative_to(к.КОРЕНЬ)} ({sum(len(б) for б in файлы.values()) / 1024:.0f} КБ), '
          f'манифест {ПУТЬ_МАНИФЕСТА.relative_to(к.КОРЕНЬ)}; удалено старых: {len(есть - нужные)}.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
