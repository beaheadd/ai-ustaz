"""Проверка производных Корана для показа (её вызывает tools/check_content.py; отдельно — python3 -I -B tools/quran/check_quran.py).

Без сети и сторонних пакетов. Что сверяется (любое расхождение — ошибка):
  (а) sha256 XML копии для показа (content/quran/quran-uthmani-marks.xml) = записи «tanzil» в content/sources.json,
      имя файла = её «файл»; в XML 114 сур подряд и 6236 аятов, у каждой суры аяты 1…n подряд;
  (б) манифест app/src/quran/manifest.generated.ts → индекс app/public/quran/index.<хэш>.json: sha256 содержимого =
      манифесту, хэш в имени = началу sha256; индекс: 114 записей 1…114, имя и число аятов = XML, файл суры есть,
      его sha256 = индексу и началу sha256 в имени, транслитерация ru заполнена (kk — строка или null);
  (в) каждая сура: номер, имя, число аятов, бисмилла = атрибуту XML, номера аятов 1…n, КАЖДЫЙ аят побайтно = XML,
      блок копирайта Tanzil дословно = XML (условие Tanzil — в каждом производном файле), sha256 источника = XML;
  (г) в app/public/quran нет лишних файлов; файлы на диске = свежей сборке tools/quran/build_quran.py побайтно.
Контракт: проверить(sha_источника_из_sources, файл_из_sources) -> (ошибки: list[str], счёт: dict[str, int]).
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import quran_common as к  # noqa: E402


def проверить(sha_в_sources, файл_в_sources):
    ошибки, счёт = [], {}

    def ош(где, что):
        ошибки.append(f'quran: {где}: {что}')

    def плюс(ключ, н=1):
        счёт[ключ] = счёт.get(ключ, 0) + н

    if not к.ПУТЬ_XML.exists():
        ош(str(к.ПУТЬ_XML.relative_to(к.КОРЕНЬ)), 'нет копии Tanzil для показа')
        return ошибки, счёт
    копия = к.прочитать_xml(к.ПУТЬ_XML)
    if копия.sha256 != sha_в_sources:
        ош('sources.json', f'sha256 копии для показа {копия.sha256} не совпадает с записанным {sha_в_sources}')
    if файл_в_sources != к.ПУТЬ_XML.name:
        ош('sources.json', f'файл копии для показа «{файл_в_sources}», а лежит «{к.ПУТЬ_XML.name}»')
    if [с.номер for с in копия.суры] != list(range(1, к.СУР + 1)):
        ош('XML', 'суры не 1…114 подряд')
    for с in копия.суры:
        if [н for н, _ in с.аяты] != list(range(1, len(с.аяты) + 1)):
            ош('XML', f'сура {с.номер}: аяты не 1…n подряд')
    if sum(len(с.аяты) for с in копия.суры) != к.АЯТОВ:
        ош('XML', f'аятов {sum(len(с.аяты) for с in копия.суры)}, нужно {к.АЯТОВ}')
    плюс('Коран: сур в копии для показа', len(копия.суры))
    по_номеру = {с.номер: с for с in копия.суры}

    # (б) манифест → индекс
    if not к.ПУТЬ_МАНИФЕСТА.exists():
        ош('manifest.generated.ts', 'нет манифеста — запустите tools/quran/build_quran.py')
        return ошибки, счёт
    манифест = к.ПУТЬ_МАНИФЕСТА.read_text(encoding='utf-8')
    м_индекс = re.search(r"индекс: '([^']+)'", манифест)
    м_sha = re.search(r"sha256Индекса: '([0-9a-f]{64})'", манифест)
    м_ист = re.search(r"sha256Источника: '([0-9a-f]{64})'", манифест)
    if not (м_индекс and м_sha and м_ист):
        ош('manifest.generated.ts', 'не разобрать индекс/sha256')
        return ошибки, счёт
    if м_ист.group(1) != копия.sha256:
        ош('manifest.generated.ts', 'sha256 источника не совпадает с XML')
    папка = к.ПАПКА_ВЫХОДА

    def файл_с_хэшем(отн, ожидаемый_sha, где):
        """Байты файла, если он есть, его sha256 = ожидаемому и хэш в имени = началу sha256; иначе None."""
        if not отн.startswith(к.ПОДПАПКА + '/'):
            ош(где, f'файл «{отн}» не в {к.ПОДПАПКА}/')
            return None
        путь = папка / отн.split('/', 1)[1]
        if not путь.exists():
            ош(где, f'нет файла {отн}')
            return None
        байты = путь.read_bytes()
        sha = к.sha256_байтов(байты)
        if sha != ожидаемый_sha:
            ош(где, f'sha256 {отн} не совпадает')
        if к.хэш_в_имени(путь.name) != sha[:к.ДЛИНА_ХЭША]:
            ош(где, f'хэш в имени {отн} ≠ началу sha256 содержимого')
        return байты

    байты_индекса = файл_с_хэшем(м_индекс.group(1), м_sha.group(1), 'manifest → index')
    if байты_индекса is None:
        return ошибки, счёт
    индекс = json.loads(байты_индекса.decode('utf-8'))
    if индекс.get('формат') != к.ФОРМАТ or индекс.get('источник') != к.ИСТОЧНИК or индекс.get('копия') != к.КОПИЯ:
        ош('index', 'формат/источник/копия не те')
    if индекс.get('sha256Источника') != копия.sha256 or индекс.get('файлИсточника') != к.ПУТЬ_XML.name:
        ош('index', 'файл/sha256 источника не те')
    if индекс.get('сур') != к.СУР or индекс.get('аятов') != к.АЯТОВ:
        ош('index', 'сур/аятов не 114/6236')
    if индекс.get('копирайт') != копия.копирайт:
        ош('index', 'блок копирайта Tanzil изменён или отсутствует')
    записи = индекс.get('суры') or []
    if [з.get('сура') for з in записи] != list(range(1, к.СУР + 1)):
        ош('index', 'записи сур не 1…114 подряд')
    нужные_имена = {папка / м_индекс.group(1).split('/', 1)[1]}
    аятов_сверено = 0
    for з in записи:
        н = з.get('сура')
        с = по_номеру.get(н)
        где = f'сура {н}'
        if not с:
            continue
        if з.get('имя') != с.имя or з.get('аятов') != len(с.аяты):
            ош(где, 'имя или число аятов в индексе ≠ XML')
        тр = з.get('транслит') or {}
        if not isinstance(тр.get('ru'), str) or not тр['ru'].strip() or not (тр.get('kk') is None or isinstance(тр.get('kk'), str)):
            ош(где, 'транслитерация: ru — непустая строка, kk — строка или null')
        отн = з.get('файл') or ''
        байты = файл_с_хэшем(отн, з.get('sha256'), где)
        if байты is None:
            continue
        нужные_имена.add(папка / отн.split('/', 1)[1])
        if not re.match(rf'^{к.ПОДПАПКА}/{н:03d}\.', отн):
            ош(где, f'имя файла {отн} не по номеру суры')
        д = json.loads(байты.decode('utf-8'))
        if д.get('сура') != н or д.get('имя') != с.имя or д.get('аятов') != len(с.аяты):
            ош(где, 'номер, имя или число аятов в файле ≠ XML')
        if д.get('бисмилла') != с.бисмилла:
            ош(где, 'бисмилла ≠ атрибуту XML')
        if д.get('копирайт') != копия.копирайт:
            ош(где, 'блок копирайта Tanzil изменён или отсутствует')
        if д.get('источник') != к.ИСТОЧНИК or д.get('sha256Источника') != копия.sha256 or д.get('копия') != к.КОПИЯ:
            ош(где, 'источник/копия/sha256 источника не те')
        аяты = д.get('аяты') or []
        if len(аяты) != len(с.аяты):
            ош(где, f'аятов в файле {len(аяты)}, в XML {len(с.аяты)}')
        for (номер, текст), а in zip(с.аяты, аяты):
            if а.get('аят') != номер:
                ош(где, f'номер аята {а.get("аят")} вместо {номер}')
            elif not isinstance(а.get('текст'), str) or а['текст'].encode('utf-8') != текст.encode('utf-8'):
                ош(где, f'аят {н}:{номер} не совпадает с XML побайтно')
            else:
                аятов_сверено += 1
        плюс('Коран: файлов сур сверено')
    плюс('Коран: аятов производных сверено с XML побайтно', аятов_сверено)
    if аятов_сверено != к.АЯТОВ:
        ош('производные', f'сверено аятов {аятов_сверено}, нужно {к.АЯТОВ}')

    # (г) лишние файлы и совпадение со свежей сборкой
    for путь in sorted(папка.glob('*')):
        if путь not in нужные_имена:
            ош('app/public/quran', f'лишний файл {путь.name}')
    свежие, свежий_манифест = к.собрать(к.ПУТЬ_XML)
    устарели = [о for о, б in свежие.items()
                if not (папка / о.split('/', 1)[1]).exists() or (папка / о.split('/', 1)[1]).read_bytes() != б]
    if устарели or свежий_манифест != манифест:
        ош('производные', f'не совпадают со свежей сборкой ({len(устарели)} файлов, манифест '
                          f'{"другой" if свежий_манифест != манифест else "тот же"}) — tools/quran/build_quran.py')
    return ошибки, счёт


if __name__ == '__main__':
    источники = json.loads((к.КОРЕНЬ / 'content' / 'sources.json').read_text(encoding='utf-8'))
    tanzil = next(и for и in источники['источники'] if и['id'] == 'tanzil')
    ошибки, счёт = проверить(tanzil.get('sha256Файла'), tanzil.get('файл'))
    for кл, в in счёт.items():
        print(f'  {кл}: {в}')
    for е in ошибки:
        print('  - ' + е)
    print('Итог: ' + ('ошибок нет.' if not ошибки else f'ОШИБКИ: {len(ошибки)}'))
    sys.exit(1 if ошибки else 0)
