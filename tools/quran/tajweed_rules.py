"""Правила раскраски таджвида (цветной мусхаф) — детерминированно, по буквам и огласовкам копии Tanzil для показа.

Назначение: для каждого аята (и бисмиллы) найти места правил таджвида и вернуть отрезки [начало, конец, код] — индексы
в строке аята Tanzil как есть (Python str = кодовые точки; весь текст — в BMP, поэтому = индексам UTF-16 в JS).
Текст НЕ меняется (правило 1 CLAUDE.md): раскраска — разметка поверх неизменной строки; склейка кусков = аяту.
Без ИИ и без чужой разметки: только эти правила (их проверяет устаз — «Цвета таджвида — черновик»).

Линия чтения — Хафс от ‘Асыма через аш-Шатибийю (CLAUDE.md, правило 6). Чтение по умолчанию — слитно внутри аята
(васл), остановка — в конце аята. Знаки остановки внутри аята не прерывают правило (как в цветных мусхафах).

Отрезок всегда покрывает целые «кластеры»: основа (буква, татвиль, малые ۥ ۦ) + все её знаки. Знак никогда не
отделяется от своей буквы — так раскраска не рвёт арабскую связность и огласовки (см. docs/дизайн/05, «Виды чтения»).

Коды (одна латинская буква — компактно в JSON; названия и цвета — в приложении, app/src/quran/tajweed.ts):
  g  гунна: ن и م с шаддой (2 счёта)                                         — урок 21
  n  идгам с гунной: нун без огласовки/танвин перед ي ن م و (буква нуна/танвина и следующая ي/و); мим перед мّ  — 33, 36
  b  идгам без гунны: нун/танвин перед ل ر (буква нуна/танвина)              — урок 33
  k  ихфа: нун/танвин перед 15 буквами ихфы; ихфа шафави — мим перед ب      — уроки 35, 36
  q  икляб: нун/танвин перед ب (в тексте — малый мим ۢ/ۭ)                   — урок 34
  c  калькаля: ق ط ب ج د с сукуном и в конце аята (при остановке)            — урок 37
  t  мадд табии (2): ا после фатхи, و после даммы, ي/ى после касры, надстрочный алиф ٰ, малые ۥ ۦ — уроки 17, 18, 24
  m  мадд муттасиль (4–5): знак мадда ٓ и хамза в том же слове             — уроки 23, 38
  f  мадд мунфасиль (4–5): знак мадда ٓ в конце слова, следующее слово с хамзы (и يَٰٓ / هَٰٓ перед хамзой) — урок 38
  l  мадд лязим (6): знак мадда ٓ перед шаддой/сукуном; буквы мукатта‘ат со знаком мадда — уроки 31, 40
  s  непроизносимое: хамзат-васль ٱ, буква с ۟, алиф с ۠, буква без огласовки перед шаддой (лям шамсийя,
     идгам мислейн/мутаджанисейн)                                           — уроки 25, 26
Приоритет (у кластера один код): s(ٱ ۟ ۠) → нун/танвин/мим → s(перед шаддой) → g → мадды → c.

Контракт:
  КОДЫ — строка кодов по порядку легенды; разметить(текст) -> list[(начало, конец, код)] — по порядку, без
  пересечений, внутри слов (без пробелов), на границах кластеров; кластеры(текст) — разбор для тестов.
Решение владельца 20.11.2026: «Коран нужно нам сделать разные дизайны … реальная страница, где выделены буквы
разными цветами».
"""

КОДЫ = 'gnbkqctmfls'

ФАТХА, ДАММА, КАСРА = '\u064E', '\u064F', '\u0650'
ТАНВИНЫ = set('\u064B\u064C\u064D')
ШАДДА, СУКУН, МАДДА, ХАМЗА_НАД = '\u0651', '\u0652', '\u0653', '\u0654'
АЛИФ_НАД = '\u0670'                 # надстрочный (малый) алиф
НОЛЬ_КРУГЛЫЙ = '\u06DF'             # ۟ — буква не читается
НОЛЬ_ПРЯМОЙ = '\u06E0'              # ۠ — алиф не читается при слитном чтении (أَنَا۠)
МИМ_ВЫСОКИЙ, МИМ_НИЗКИЙ = '\u06E2', '\u06ED'   # малый мим: икляб; после танвина — «последовательный» танвин
ТАТВИЛЬ = '\u0640'
МАЛЫЙ_ЙА_НАД = '\u06E7'            # ـۧ — малая йа над татвилем (إِبْرَٰهِـۧمَ, ٱلنَّبِيِّـۧنَ)
ДВА_СЧЁТА_МУКАТТААТ = set('\u062D\u064A\u0637\u0647\u0631')   # حي طهر — в мукатта‘ат тянутся на 2
МАЛЫЙ_ВАВ, МАЛЫЙ_ЙА = '\u06E5', '\u06E6'
ВАСЛЬ = '\u0671'
ХАМЗЫ = set('\u0621\u0623\u0624\u0625\u0626')
# Знаки-токены (через пробел между словами): остановки, ۞, ۩ — не слова.
ЗНАКИ_ТОКЕНЫ = set('\u06D6\u06D7\u06D8\u06D9\u06DA\u06DB\u06DC\u06DE\u06E9')
ГЛАСНЫЕ = {ФАТХА, ДАММА, КАСРА} | ТАНВИНЫ
БУКВЫ_МАДДА = set('\u0627\u0648\u064A\u0649') | {ТАТВИЛЬ, МАЛЫЙ_ВАВ, МАЛЫЙ_ЙА}
КАЛЬКАЛЯ = set('\u0642\u0637\u0628\u062C\u062F')        # ق ط ب ج د
ИХФА = set('\u062A\u062B\u062C\u062F\u0630\u0632\u0633\u0634\u0635\u0636\u0637\u0638\u0641\u0642\u0643')
ИДГАМ_ГУННА = set('\u064A\u0646\u0645\u0648')           # ي ن م و
ИДГАМ_БЕЗ = set('\u0644\u0631')                           # ل ر
НУН, МИМ, БА, ЛЯМ, АЛИФ, ВАВ, ЙА, АЛИФ_М = '\u0646', '\u0645', '\u0628', '\u0644', '\u0627', '\u0648', '\u064A', '\u0649'
ХА, ЙА_Б = '\u0647', '\u064A'


def основа(ч):
    """Основа кластера: буквы, татвиль, малые ۥ ۦ, хамзат-васль. Знаки — всё остальное (огласовки, малые знаки)."""
    return ('\u0621' <= ч <= '\u064A') or ч in (ТАТВИЛЬ, МАЛЫЙ_ВАВ, МАЛЫЙ_ЙА, ВАСЛЬ)


class Кластер:
    __slots__ = ('с', 'по', 'буква', 'знаки', 'слово', 'вСлове')

    def __init__(self, с, буква, слово, в_слове):
        self.с, self.по, self.буква, self.знаки, self.слово, self.вСлове = с, с + 1, буква, '', слово, в_слове

    def есть(self, *знаки):
        return any(з in self.знаки for з in знаки)

    @property
    def голый(self):
        """Без огласовки, сукуна, шадды и танвина."""
        return not any(з in ГЛАСНЫЕ or з in (ШАДДА, СУКУН) for з in self.знаки)

    @property
    def танвин(self):
        return any(з in ТАНВИНЫ for з in self.знаки)

    @property
    def хамза(self):
        return self.буква in ХАМЗЫ or ХАМЗА_НАД in self.знаки


def кластеры(текст):
    """Слова аята → кластеры. Возвращает список слов; слово — список кластеров (знаки-токены пропущены)."""
    слова, поз = [], 0
    for кусок in текст.split(' '):
        if len(кусок) == 1 and кусок in ЗНАКИ_ТОКЕНЫ:
            поз += 2
            continue
        слово = []
        for i, ч in enumerate(кусок):
            if основа(ч) or not слово:
                if not основа(ч):
                    raise ValueError(f'знак без буквы в начале слова: U+{ord(ч):04X}')
                слово.append(Кластер(поз + i, ч, len(слова), len(слово)))
            else:
                слово[-1].знаки += ч
                слово[-1].по = поз + i + 1
        слова.append(слово)
        поз += len(кусок) + 1
    return слова


def разметить(текст):
    """Отрезки (начало, конец, код) по порядку. Соседние кластеры одного слова с одним кодом — один отрезок."""
    if any(ord(ч) > 0xFFFF for ч in текст):
        raise ValueError('символ вне BMP — индексы Python ≠ UTF-16')
    слова = кластеры(текст)
    плоско = [к for с in слова for к in с]
    код = {}

    def след(к):
        """Следующий кластер (в слове или первый кластер следующего слова)."""
        с = слова[к.слово]
        if к.вСлове + 1 < len(с):
            return с[к.вСлове + 1]
        return слова[к.слово + 1][0] if к.слово + 1 < len(слова) else None

    def первый_след_слова(к):
        return слова[к.слово + 1][0] if к.слово + 1 < len(слова) else None

    def поставить(к, ч):
        if к is not None and id(к) not in код:
            код[id(к)] = ч

    # 1. Непроизносимое: хамзат-васль, буква с ۟, алиф с ۠.
    for к in плоско:
        if к.буква == ВАСЛЬ or к.есть(НОЛЬ_КРУГЛЫЙ) or (к.буква == АЛИФ and к.есть(НОЛЬ_ПРЯМОЙ)):
            поставить(к, 's')

    # 2. Нун без огласовки / с малым мимом, танвин «последовательный» (с малым мимом), мим без огласовки.
    for к in плоско:
        if id(к) in код:
            continue
        нун = к.буква == НУН and (к.голый or к.есть(МИМ_ВЫСОКИЙ)) and not к.есть(АЛИФ_НАД, МАДДА)
        танвин = к.танвин and к.есть(МИМ_ВЫСОКИЙ, МИМ_НИЗКИЙ)
        if нун or танвин:
            # У танвина следующая буква — первая буква следующего слова (ا/ى после танвина не читаются).
            н = первый_след_слова(к) if танвин else след(к)
            if н is None:
                continue
            if н.буква == БА:
                поставить(к, 'q')
            elif н.буква in ИДГАМ_ГУННА:
                поставить(к, 'n')
                if н.буква in (ЙА, ВАВ) and н.есть(ШАДДА):
                    поставить(н, 'n')
            elif н.буква in ИДГАМ_БЕЗ:
                поставить(к, 'b')
            elif н.буква in ИХФА:
                поставить(к, 'k')
        elif к.буква == МИМ and к.голый and not к.есть(АЛИФ_НАД, МАДДА):
            н = след(к)
            if н is None:
                continue
            if н.буква == БА:
                поставить(к, 'k')
            elif н.буква == МИМ and н.есть(ШАДДА):
                поставить(к, 'n')

    # 3. Буква без огласовки перед буквой с шаддой — не читается (лям шамсийя ٱلرَّ, ٱلَّذِى; идгам: قَد تَّبَيَّنَ).
    for к in плоско:
        if id(к) in код or not к.голый or к.буква in БУКВЫ_МАДДА or к.буква in (НУН, МИМ, ВАСЛЬ) or к.знаки:
            continue
        н = след(к)
        if н is not None and н.есть(ШАДДА):
            поставить(к, 's')

    # 4. Гунна: ن и م с шаддой.
    for к in плоско:
        if к.буква in (НУН, МИМ) and к.есть(ШАДДА):
            поставить(к, 'g')

    # 5. Мадды.
    def значимые_после(к):
        """Кластеры слова после к, кроме непроизносимых (۟)."""
        с = слова[к.слово]
        return [х for х in с[к.вСлове + 1:] if not х.есть(НОЛЬ_КРУГЛЫЙ)]

    def конец_слова(к):
        return not значимые_после(к)

    def выпадает(к):
        """Долгая буква в конце слова перед хамзат-васлем — в слитном чтении не тянется (فِى ٱلْأَرْضِ)."""
        н = первый_след_слова(к)
        return конец_слова(к) and н is not None and н.буква == ВАСЛЬ

    def мукаттаат(н):
        """Слово из букв мукатта‘ат: ни одной огласовки, сукуна, шадды и танвина (الٓمٓ, طه, كٓهيعٓصٓ)."""
        с = слова[н]
        return len(с) >= 2 and all(х.голый and х.буква != ВАСЛЬ for х in с)

    for к in плоско:
        if id(к) in код:
            continue
        if к.есть(МАДДА):
            if к.буква not in БУКВЫ_МАДДА and not к.есть(АЛИФ_НАД):
                поставить(к, 'l')            # буква мукатта‘ат (الٓمٓ, قٓ, نٓ)
                continue
            после = значимые_после(к)
            if после:
                ф = после[0]
                с = слова[к.слово]
                if ф.хамза:
                    # يَٰٓأَيُّهَا, هَٰٓأَنتُمْ, هَٰٓؤُلَآءِ, يَٰٓـَٔادَمُ — призыв/указание + отдельное слово: мунфасиль.
                    звательное = к.вСлове == 1 and с[0].буква in (ЙА_Б, ХА) and с[0].есть(ФАТХА) and к.буква == ТАТВИЛЬ
                    поставить(к, 'f' if звательное else 'm')
                elif ф.есть(ШАДДА, СУКУН):
                    поставить(к, 'l')
                else:
                    поставить(к, 'm' if any(х.хамза for х in после) else 'l')
            else:
                н = первый_след_слова(к)
                if н is not None and н.хамза:
                    поставить(к, 'f')
                elif н is None:
                    # Знак мадда в конце аята: следующий аят начинается с хамзы — мунфасиль при слитном чтении аятов.
                    поставить(к, 'f')
            continue
        пред = слова[к.слово][к.вСлове - 1] if к.вСлове > 0 else None
        долгий = False
        if к.есть(АЛИФ_НАД, МАЛЫЙ_ЙА_НАД) or к.буква in (МАЛЫЙ_ВАВ, МАЛЫЙ_ЙА):
            долгий = True                    # надстрочный алиф, сыля (بِهِۦ, لَهُۥ), ـۧ (إِبْرَٰهِـۧمَ) — 2 счёта
        elif мукаттаат(к.слово) and к.буква in ДВА_СЧЁТА_МУКАТТААТ and not к.знаки:
            долгий = True                    # буквы حي طهر в мукатта‘ат (طه, يسٓ, حمٓ, الٓر) — 2 счёта
        elif not к.знаки and пред is not None:
            if к.буква == АЛИФ and пред.есть(ФАТХА):
                долгий = True
            elif к.буква == ВАВ and пред.есть(ДАММА):
                долгий = True
            elif к.буква in (ЙА, АЛИФ_М) and пред.есть(КАСРА):
                долгий = True
        # Сыля в самом конце аята (يَرَهُۥ) при остановке не читается.
        if к.буква in (МАЛЫЙ_ВАВ, МАЛЫЙ_ЙА) and к is плоско[-1]:
            долгий = False
        if долгий and not выпадает(к):
            поставить(к, 't')

    # 6. Калькаля: буква قطبجد с сукуном; последняя буква аята (остановка).
    for к in плоско:
        if к.буква in КАЛЬКАЛЯ and к.есть(СУКУН):
            поставить(к, 'c')
    if плоско:
        последний = next((к for к in reversed(плоско) if not к.есть(НОЛЬ_КРУГЛЫЙ) and к.буква not in (АЛИФ, АЛИФ_М)), None)
        # С фатхатаном в конце — при остановке алиф ‘ивада (عَذَابَا): буква с огласовкой, калькали нет.
        if последний is not None and последний.буква in КАЛЬКАЛЯ and not последний.есть('\u064B'):
            поставить(последний, 'c')

    # Отрезки: по порядку, соседние кластеры слова с тем же кодом — вместе.
    отрезки = []
    for слово in слова:
        for к in слово:
            ч = код.get(id(к))
            if ч is None:
                continue
            if отрезки and отрезки[-1][2] == ч and отрезки[-1][1] == к.с and отрезки[-1][3] == к.слово:
                отрезки[-1][1] = к.по
            else:
                отрезки.append([к.с, к.по, ч, к.слово])
    return [(с, по, ч) for с, по, ч, _ in отрезки]


def закодировать(отрезки):
    """Отрезки → компактная строка: «<пропуск><КОД><длина base36 одним знаком>» подряд (длинные — частями ≤ 35)."""
    части, конец = [], 0
    for с, по, ч in отрезки:
        while по - с > 0:
            д = min(35, по - с)
            части.append(f'{с - конец}{ч.upper()}{"0123456789abcdefghijklmnopqrstuvwxyz"[д]}')
            конец = с + д
            с = конец
    return ''.join(части)


def раскодировать(строка):
    import re
    отрезки, конец = [], 0
    if not re.fullmatch(r'(?:\d+[A-Z][1-9a-z])*', строка):
        raise ValueError('разметка: неверный формат')
    for м in re.finditer(r'(\d+)([A-Z])([1-9a-z])', строка):
        с = конец + int(м.group(1))
        д = int(м.group(3), 36)
        отрезки.append((с, с + д, м.group(2).lower()))
        конец = с + д
    return отрезки
