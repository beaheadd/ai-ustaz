"""Сборка раздела «Учимся намазу»: content/namaz/namaz.json → app/public/namaz/namaz.<хэш>.json + app/src/namaz/manifest.generated.ts.

Решение владельца 27.11.2026: «Учимся намазу нужно собрать по ханафи». Линия — ханафитский мазхаб, ДУМК (CLAUDE.md, 6).

Правила (CLAUDE.md 1, 2, 5, 11):
  - арабский текст НЕ набирается руками — те же функции, что у зикров (tools/dhikr/build_dhikr.py): фрагмент хадиса
    HadeethEnc вырезается посимвольно по тексту без огласовок (сырьё — content/hadith/raw, sha256 = якорю), аяты — из
    Tanzil Uthmani v1.1 (sha256 = ЭТАЛОН_SHA256_ПОКАЗА); степень и такхридж — из той же записи HadeethEnc;
  - фикх (шаги, парызы, ракааты, блок для женщин), произношение и перевод — наш черновик на kk/ru/uz/en (проверяет
    устаз; чек-лист — docs/дизайн/11-намаз.md); в наших текстах арабских букв быть не должно (ошибка сборки);
  - чего нет в источниках (таауз в принятой формуле, кунут) — не набираем: «ждут_устаза».

Запуск (из корня, без сторонних пакетов):
  python3 -I -B tools/namaz/build_namaz.py           собрать (нужно сырьё HadeethEnc: build_hadith.py --download)
  python3 -I -B tools/namaz/build_namaz.py --check   ничего не пишет; файлы = свежей сборке, иначе код 1
Контракт выхода (app/public/namaz/namaz.<20 hex>.json):
  {"формат": 1, "версия",
   "тексты": {id: {"вид": "хадис"|"коран", "ar": [абзацы], "название"|"произношение"|"перевод"|"примечание"?: {kk,ru,uz,en},
                   "источник": {"коран"?, "hadeethenc"?, "степень_ar"?, "степень"?, "передали_ar"?, "передали"?}}},
   "разделы": [{"id", "название", "вступление"?, "группы"?: [{"заголовок"?, "пункты": [{4 языка}], "примечание"?}],
                "таблица"?: {"колонки": [{4}], "строки": [{"намаз": {4}, "числа": [до, фард, после, витр]}]},
                "шаги"?: [{"заголовок", "текст", "тексты"?: [id], "раз"?, "примечание"?}], "ждёт_устаза"?: {4}}],
   "итог": {4}}
"""
import hashlib
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / 'tools' / 'dhikr'))
import build_dhikr as з  # noqa: E402

ВХОД = КОРЕНЬ / 'content' / 'namaz' / 'namaz.json'
ПАПКА_ВЫХОДА = КОРЕНЬ / 'app' / 'public' / 'namaz'
ПУТЬ_МАНИФЕСТА = КОРЕНЬ / 'app' / 'src' / 'namaz' / 'manifest.generated.ts'
ЯЗЫКИ = з.ЯЗЫКИ
ДЛИНА_ХЭША = 20
ИМЯ_ФАЙЛА = re.compile(r'^namaz\.([0-9a-f]{20})\.json$')
АРАБСКИЕ = re.compile('[؀-ۿ]')
ОшибкаСборки = з.ОшибкаСборки


def четыре(значение, где, обязательно=True):
    if значение is None and not обязательно:
        return None
    if not isinstance(значение, dict) or set(значение) != set(ЯЗЫКИ) or not all(
            isinstance(значение[я], str) and значение[я].strip() for я in ЯЗЫКИ):
        raise ОшибкаСборки(f'{где}: нужны непустые kk, ru, uz, en')
    if any(АРАБСКИЕ.search(значение[я]) for я in ЯЗЫКИ):
        raise ОшибкаСборки(f'{где}: арабские буквы в нашем тексте — арабский только из источника')
    return {я: значение[я].strip() for я in ЯЗЫКИ}


def собрать_текст(т, хадисы, аяты):
    id_ = т['id']
    ист = т['источник']
    if 'hadeethenc' in ист:
        hid = ист['hadeethenc']
        хадис = хадисы.get(hid)
        if not хадис:
            raise ОшибкаСборки(f'{id_}: хадиса HadeethEnc №{hid} нет в выгрузке')
        ar, начало = [], 0
        for фрагмент in ист['фрагменты']:
            строка, начало = з.вырезать(хадис['hadeeth'], фрагмент, начало)
            ar.append(строка)
        степень = хадис['grade'].strip()
        if степень not in з.СТЕПЕНИ:
            raise ОшибкаСборки(f'{id_}: незнакомая степень «{степень}»')
        вид = 'хадис'
        выход_ист = {'hadeethenc': hid, 'степень_ar': степень, 'степень': з.СТЕПЕНИ[степень],
                     'передали_ar': хадис['attribution'].strip(), 'передали': з.передали(хадис['attribution'])}
    elif 'коран' in ист:
        м = re.fullmatch(r'(\d{1,3}):(\d{1,3})(?:-(\d{1,3}))?', ист['коран'])
        if not м:
            raise ОшибкаСборки(f'{id_}: ссылка «{ист["коран"]}»')
        сура, от, до = int(м[1]), int(м[2]), int(м[3] or м[2])
        ar = []
        for аят in range(от, до + 1):
            if (сура, аят) not in аяты:
                raise ОшибкаСборки(f'{id_}: нет аята {сура}:{аят}')
            ar.append(аяты[(сура, аят)])
        вид = 'коран'
        выход_ист = {'коран': ист['коран']}
    else:
        raise ОшибкаСборки(f'{id_}: источник — «hadeethenc» или «коран»')
    выход = {'вид': вид, 'ar': ar}
    for поле in ('название', 'произношение', 'перевод'):
        выход[поле] = четыре(т.get(поле), f'{id_}.{поле}')
    прим = четыре(т.get('примечание'), f'{id_}.примечание', обязательно=False)
    if прим:
        выход['примечание'] = прим
    выход['источник'] = выход_ист
    return выход


def собрать():
    вход = json.loads(ВХОД.read_text(encoding='utf-8'))
    хадисы = з.арабская_выгрузка()
    аяты = з.tanzil()
    тексты = {}
    for т in вход['тексты']:
        if not re.fullmatch(r'[a-z0-9-]{1,40}', т['id']) or т['id'] in тексты:
            raise ОшибкаСборки(f'id текста «{т["id"]}»')
        тексты[т['id']] = собрать_текст(т, хадисы, аяты)
    разделы, ids = [], set()
    for р in вход['разделы']:
        id_ = р['id']
        if not re.fullmatch(r'[a-z0-9-]{1,40}', id_) or id_ in ids:
            raise ОшибкаСборки(f'id раздела «{id_}»')
        ids.add(id_)
        выход = {'id': id_, 'название': четыре(р.get('название'), f'{id_}.название')}
        вст = четыре(р.get('вступление'), f'{id_}.вступление', обязательно=False)
        if вст:
            выход['вступление'] = вст
        if 'группы' in р:
            группы = []
            for н, г in enumerate(р['группы']):
                гр = {}
                заг = четыре(г.get('заголовок'), f'{id_}.группы[{н}].заголовок', обязательно=False)
                if заг:
                    гр['заголовок'] = заг
                if not г.get('пункты'):
                    raise ОшибкаСборки(f'{id_}.группы[{н}]: пустой список пунктов')
                гр['пункты'] = [четыре(п, f'{id_}.группы[{н}].пункты[{к}]') for к, п in enumerate(г['пункты'])]
                прим = четыре(г.get('примечание'), f'{id_}.группы[{н}].примечание', обязательно=False)
                if прим:
                    гр['примечание'] = прим
                группы.append(гр)
            выход['группы'] = группы
        if 'таблица' in р:
            т = р['таблица']
            колонки = [четыре(к, f'{id_}.колонки') for к in т['колонки']]
            строки = []
            for с in т['строки']:
                числа = с['числа']
                if len(числа) != len(колонки) - 1 or not all(isinstance(ч, int) and 0 <= ч <= 4 for ч in числа):
                    raise ОшибкаСборки(f'{id_}: числа строки таблицы')
                строки.append({'намаз': четыре(с['намаз'], f'{id_}.строки'), 'числа': числа})
            выход['таблица'] = {'колонки': колонки, 'строки': строки}
        if 'шаги' in р:
            шаги = []
            for н, ш in enumerate(р['шаги'], 1):
                шаг = {'заголовок': четыре(ш.get('заголовок'), f'{id_}.шаг {н}.заголовок'),
                       'текст': четыре(ш.get('текст'), f'{id_}.шаг {н}.текст')}
                if ш.get('тексты'):
                    for ид in ш['тексты']:
                        if ид not in тексты:
                            raise ОшибкаСборки(f'{id_}.шаг {н}: нет текста «{ид}»')
                    шаг['тексты'] = list(ш['тексты'])
                if 'раз' in ш:
                    if not isinstance(ш['раз'], int) or not 1 <= ш['раз'] <= 33:
                        raise ОшибкаСборки(f'{id_}.шаг {н}: «раз»')
                    шаг['раз'] = ш['раз']
                прим = четыре(ш.get('примечание'), f'{id_}.шаг {н}.примечание', обязательно=False)
                if прим:
                    шаг['примечание'] = прим
                шаги.append(шаг)
            выход['шаги'] = шаги
        ждёт = четыре(р.get('ждёт_устаза'), f'{id_}.ждёт_устаза', обязательно=False)
        if ждёт:
            выход['ждёт_устаза'] = ждёт
        if not any(к in выход for к in ('группы', 'таблица', 'шаги')):
            raise ОшибкаСборки(f'{id_}: пустой раздел')
        разделы.append(выход)
    данные = {'формат': 1, 'версия': вход['версия'], 'тексты': тексты, 'разделы': разделы,
              'итог': четыре(вход.get('итог'), 'итог')}
    байты = (json.dumps(данные, ensure_ascii=False, separators=(',', ':')) + '\n').encode('utf-8')
    хэш = hashlib.sha256(байты).hexdigest()
    имя = f'namaz.{хэш[:ДЛИНА_ХЭША]}.json'
    манифест = ('// Создано tools/namaz/build_namaz.py — не править руками.\n'
                '// Учимся намазу (владелец 27.11.2026): арабский — дословно из HadeethEnc и Tanzil, текст — fetch namaz/.\n'
                f"export const МАНИФЕСТ_НАМАЗА = {{ файл: 'namaz/{имя}', sha256: '{хэш}', разделов: {len(разделы)} }} as const;\n")
    return {имя: байты}, манифест.encode('utf-8'), данные


def проверить():
    """Для tools/check_content.py: (ошибки, счёт, предупреждения). Целостность всегда; дословность — если есть сырьё."""
    ошибки, предупреждения = [], []
    if not ПУТЬ_МАНИФЕСТА.exists():
        return ['namaz: нет app/src/namaz/manifest.generated.ts'], {}, []
    м = re.search(r"файл: 'namaz/([^']+)', sha256: '([0-9a-f]{64})', разделов: (\d+)", ПУТЬ_МАНИФЕСТА.read_text('utf-8'))
    if not м:
        return ['namaz: манифест не разобран'], {}, []
    имя, хэш, разделов = м[1], м[2], int(м[3])
    есть = sorted(п.name for п in ПАПКА_ВЫХОДА.glob('*'))
    if есть != [имя]:
        ошибки.append(f'namaz: в app/public/namaz {есть}, нужен ровно {имя}')
    путь = ПАПКА_ВЫХОДА / имя
    if not путь.exists():
        return ошибки + [f'namaz: нет {имя}'], {}, []
    байты = путь.read_bytes()
    if hashlib.sha256(байты).hexdigest() != хэш or ИМЯ_ФАЙЛА.match(имя)[1] != хэш[:ДЛИНА_ХЭША]:
        ошибки.append(f'namaz: sha256 {имя} ≠ манифесту')
    данные = json.loads(байты)
    if len(данные.get('разделы', [])) != разделов:
        ошибки.append('namaz: число разделов ≠ манифесту')
    аяты = з.tanzil()
    for id_, т in данные.get('тексты', {}).items():
        if т.get('вид') == 'коран':
            м2 = re.fullmatch(r'(\d+):(\d+)(?:-(\d+))?', т['источник']['коран'])
            целые = [аяты[(int(м2[1]), а)] for а in range(int(м2[2]), int(м2[3] or м2[2]) + 1)]
            if т['ar'] != целые:
                ошибки.append(f'namaz {id_}: текст ≠ Tanzil {т["источник"]["коран"]}')
    if (з.х.ПАПКА_СЫРЫХ / 'ar.sqlite.zip').exists():
        try:
            файлы, манифест, _ = собрать()
            if файлы != {имя: байты} or манифест != ПУТЬ_МАНИФЕСТА.read_bytes():
                ошибки.append('namaz: файлы ≠ свежей сборке (python3 -I -B tools/namaz/build_namaz.py)')
        except ОшибкаСборки as е:
            ошибки.append(f'namaz: {е}')
    else:
        предупреждения.append('намаз: сырьё HadeethEnc не скачано — дословность хадисных фрагментов не сверена')
    return ошибки, {'намаз: разделов': len(данные.get('разделы', [])), 'намаз: текстов': len(данные.get('тексты', {}))}, предупреждения


def main():
    try:
        файлы, манифест, данные = собрать()
    except ОшибкаСборки as е:
        print(f'Ошибка сборки намаза: {е}')
        return 1
    if '--check' in sys.argv[1:]:
        ош = []
        есть = {п.name for п in ПАПКА_ВЫХОДА.glob('*')} if ПАПКА_ВЫХОДА.exists() else set()
        if есть != set(файлы):
            ош.append(f'app/public/namaz: {sorted(есть)} ≠ {sorted(файлы)}')
        for имя, байты in файлы.items():
            п = ПАПКА_ВЫХОДА / имя
            if п.exists() and п.read_bytes() != байты:
                ош.append(f'{имя} ≠ свежей сборке')
        if not ПУТЬ_МАНИФЕСТА.exists() or ПУТЬ_МАНИФЕСТА.read_bytes() != манифест:
            ош.append('manifest.generated.ts ≠ свежей сборке')
        for о in ош:
            print('Ошибка:', о)
        print(f'Намаз: разделов {len(данные["разделы"])}, проверка {"не пройдена" if ош else "пройдена"}.')
        return 1 if ош else 0
    ПАПКА_ВЫХОДА.mkdir(parents=True, exist_ok=True)
    for п in ПАПКА_ВЫХОДА.glob('*'):
        if п.name not in файлы:
            п.unlink()
    for имя, байты in файлы.items():
        (ПАПКА_ВЫХОДА / имя).write_bytes(байты)
    ПУТЬ_МАНИФЕСТА.parent.mkdir(parents=True, exist_ok=True)
    ПУТЬ_МАНИФЕСТА.write_bytes(манифест)
    print(f'Намаз: разделов {len(данные["разделы"])}, текстов {len(данные["тексты"])} → app/public/namaz/{next(iter(файлы))}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
