"""Проверка раздела «Хадисы» (хадисы аль-Бухари из HadeethEnc.com): вызывает tools/check_content.py и
python3 -I -B tools/hadith/build_hadith.py --check (там сырьё обязательно). Без сети.

Решение владельца 21.11.2026: «Добавь хадисы Аль-Бухари ещё перевод!». Условия HadeethEnc: без изменений, добавлений
и удалений; ссылка на источник. Правила 1, 2, 5, 6, 11 CLAUDE.md. Контракт данных — tools/hadith/hadith_common.py.

Что сверяется (любое расхождение — ошибка):
  (а) целостность (всегда): манифест app/src/hadith/manifest.generated.ts → индекс app/public/hadith (sha256 = манифесту,
      хэш в имени = началу sha256) → файлы заголовков и порций (sha256 и хэш в имени = индексу); лишних файлов нет;
      номера 1…N подряд, id не повторяются; в порции языка — ровно хадисы этой порции с этим переводом;
  (б) у каждого показанного хадиса есть русский перевод: title, hadeeth, explanation, grade, attribution непустые
      (kk показывает русский); есть ссылка на страницу HadeethEnc (https://hadeethenc.com/<язык>/browse/hadith/<id>);
  (в) ни один хадис из content/hadith/на-проверку-устаза.json (акыда, джихад, худуд, шариатская политика, цитата
      Корана) не опубликован, если его нет в content/hadith/одобрено.json; одобренные — в индексе «одобрено»;
  (г) дословность (если сырьё скачано; требовать_сырьё=True — обязательно): sha256 сырых выгрузок = sources.json и
      якорю ЭТАЛОНЫ; КАЖДОЕ поле каждой записи каждой порции и каждого файла заголовков посимвольно = полю выгрузки
      (SQLite; link — CSV того же языка; hints и words_meanings — тот же список строк); арабский текст перевода
      другой редакции (hadeeth_ar) лежит рядом ровно тогда, когда он отличается; категории = связям выгрузки;
  (д) файлы на диске = свежей сборке tools/hadith/build_hadith.py побайтно (порции, заголовки, индекс, манифест,
      на-проверку-устаза.json).
Контракт: проверить(требовать_сырьё=False) -> (ошибки: list[str], счёт: dict[str, int], предупреждения: list[str]).
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hadith_common as х  # noqa: E402

ССЫЛКА = re.compile(r'^https://hadeethenc\.com/(ar|ru|en|uz)/browse/hadith/(\d+)$')
ОБЯЗАТЕЛЬНЫЕ_RU = ('title', 'hadeeth', 'explanation', 'grade', 'attribution')


def проверить(требовать_сырьё=False):
    ошибки, счёт, предупреждения = [], {}, []

    def ош(где, что):
        ошибки.append(f'hadith: {где}: {что}')

    def плюс(ключ, н=1):
        счёт[ключ] = счёт.get(ключ, 0) + н

    папка = х.ПАПКА_ВЫХОДА
    if not х.ПУТЬ_МАНИФЕСТА.exists() or not папка.exists():
        ош('app/public/hadith', 'нет манифеста или папки (python3 -I -B tools/hadith/build_hadith.py)')
        return ошибки, счёт, предупреждения
    манифест = х.ПУТЬ_МАНИФЕСТА.read_text(encoding='utf-8')
    м_индекс = re.search(r"индекс: '([^']+)'", манифест)
    м_sha = re.search(r"sha256Индекса: '([0-9a-f]{64})'", манифест)
    if not м_индекс or not м_sha:
        ош('manifest.generated.ts', 'нет индекса или sha256')
        return ошибки, счёт, предупреждения

    def прочитать(отн):
        return (папка / отн.split('/', 1)[1]).read_bytes()

    нужные = {м_индекс.group(1)}
    try:
        б_индекса = прочитать(м_индекс.group(1))
    except FileNotFoundError:
        ош(м_индекс.group(1), 'нет файла индекса')
        return ошибки, счёт, предупреждения
    if х.sha256_байтов(б_индекса) != м_sha.group(1):
        ош(м_индекс.group(1), 'sha256 ≠ манифесту')
    индекс = json.loads(б_индекса)
    if индекс.get('источник') != х.ИСТОЧНИК or индекс.get('формат') != х.ФОРМАТ or индекс.get('условия') != х.УСЛОВИЯ:
        ош('индекс', 'источник, формат или условия HadeethEnc не те')
    хадисы = индекс.get('хадисы') or []
    if [з.get('n') for з in хадисы] != list(range(1, len(хадисы) + 1)):
        ош('индекс', 'номера хадисов не 1…N подряд')
    ids = [з.get('id') for з in хадисы]
    if len(set(ids)) != len(ids):
        ош('индекс', 'id повторяются')
    if индекс.get('хадисов') != len(хадисы) or f'хадисов: {len(хадисы)},' not in манифест:
        ош('индекс', 'число хадисов ≠ индексу/манифесту')
    плюс('хадисы: показано', len(хадисы))
    по_id = {з['id']: з for з in хадисы}
    категории = {к['id'] for к in индекс.get('категории') or []}
    for з in хадисы:
        if 'ru' not in з.get('языки', []):
            ош(f'#{з["id"]}', 'нет русского перевода')
        if any(к not in категории for к in з.get('категории', [])):
            ош(f'#{з["id"]}', 'категория не из индекса')
        if з.get('порция') != (з['n'] - 1) // х.ПОРЦИЯ:
            ош(f'#{з["id"]}', 'не та порция')

    def файл_по_записи(з, где):
        if not з or not isinstance(з.get('файл'), str):
            ош(где, 'нет записи файла')
            return None
        нужные.add(з['файл'])
        if f'.{z_sha(з)[:20]}.' not in з['файл']:
            ош(з['файл'], 'хэш в имени ≠ началу sha256')
        try:
            б = прочитать(з['файл'])
        except FileNotFoundError:
            ош(з['файл'], 'нет файла')
            return None
        if х.sha256_байтов(б) != з.get('sha256'):
            ош(з['файл'], 'sha256 ≠ индексу')
        return json.loads(б)

    # Заголовки
    заголовки = {}
    for я in х.ПЕРЕВОДЫ:
        д = файл_по_записи((индекс.get('заголовки') or {}).get(я), f'заголовки {я}')
        if not д:
            continue
        if д.get('язык') != я:
            ош(f'заголовки {я}', 'не тот язык')
        ожидаемые = [з['id'] for з in хадисы if я in з.get('языки', [])]
        if [с[0] for с in д.get('заголовки', [])] != ожидаемые:
            ош(f'заголовки {я}', 'список id ≠ индексу')
        заголовки[я] = {с[0]: с for с in д.get('заголовки', [])}

    # Порции
    порции = {}
    for я in х.ЯЗЫКИ:
        список = (индекс.get('порции') or {}).get(я) or []
        if len(список) != (len(хадисы) + х.ПОРЦИЯ - 1) // х.ПОРЦИЯ:
            ош(f'порции {я}', 'число порций ≠ числу хадисов / 50')
        for ч, з in enumerate(список):
            ожидаемые = [х_['id'] for х_ in хадисы[ч * х.ПОРЦИЯ:(ч + 1) * х.ПОРЦИЯ] if я == 'ar' or я in х_.get('языки', [])]
            if з is None:
                if ожидаемые:
                    ош(f'порция {я}/{ч}', 'нет файла, а хадисы с этим переводом есть')
                continue
            д = файл_по_записи(з, f'порция {я}/{ч}')
            if not д:
                continue
            if д.get('язык') != я or д.get('порция') != ч or д.get('источник') != х.ИСТОЧНИК:
                ош(з['файл'], 'язык, номер порции или источник не те')
            if [р.get('id') for р in д.get('хадисы', [])] != ожидаемые:
                ош(з['файл'], 'хадисы порции ≠ индексу')
            for р in д.get('хадисы', []):
                порции[(я, р.get('id'))] = р
                м = ССЫЛКА.match(р.get('link') or '')
                if not м or м.group(1) != я or int(м.group(2)) != р.get('id'):
                    ош(z_файл(з), f'#{р.get("id")}: ссылка на HadeethEnc «{р.get("link")}» не на страницу хадиса')
            плюс(f'хадисы: порций {я}')

    for з in хадисы:
        р = порции.get(('ru', з['id']))
        if not р or not all(isinstance(р.get(п), str) and р[п].strip() for п in ОБЯЗАТЕЛЬНЫЕ_RU):
            ош(f'#{з["id"]}', 'пустой или неполный русский перевод')
        else:
            плюс('хадисы: русский перевод полный (title, hadeeth, explanation, grade, attribution)')

    есть = {'hadith/' + str(п.relative_to(папка)) for п in папка.rglob('*') if п.is_file()}
    for лишний in sorted(есть - нужные):
        ош(лишний, 'лишний файл в app/public/hadith')

    # (в) скрытые до одобрения
    try:
        одобрено = х.прочитать_одобрено()
    except ValueError as е:
        ош('одобрено.json', str(е))
        одобрено = {}
    if х.ПУТЬ_НА_ПРОВЕРКУ.exists():
        на_проверку = json.loads(х.ПУТЬ_НА_ПРОВЕРКУ.read_text(encoding='utf-8'))
        скрытые = [з['id'] for з in на_проверку.get('хадисы', [])]
        if на_проверку.get('всего') != len(скрытые):
            ош('на-проверку-устаза.json', '«всего» ≠ числу записей')
        for id_ in скрытые:
            if id_ in по_id and id_ not in одобрено:
                ош(f'#{id_}', 'опубликован, хотя ждёт устаза (на-проверку-устаза.json) и не одобрен')
        плюс('хадисы: ждут устаза (не опубликованы)', len([i for i in скрытые if i not in по_id]))
        if (индекс.get('скрыто') or {}).get('хадисов') != len(скрытые):
            ош('индекс', '«скрыто» ≠ на-проверку-устаза.json')
    else:
        ош('content/hadith', 'нет на-проверку-устаза.json')
    if {int(к) for к in (индекс.get('одобрено') or {})} != {i for i in одобрено if i in по_id}:
        ош('индекс', '«одобрено» ≠ content/hadith/одобрено.json')

    # (г), (д) — по сырью
    запись = х.запись_источника()
    try:
        выгрузки = х.прочитать_выгрузки(запись)
    except FileNotFoundError as е:
        if требовать_сырьё:
            ош('сырьё', f'нет {е} — python3 -I -B tools/hadith/build_hadith.py --download')
        else:
            предупреждения.append('хадисы: сырые выгрузки HadeethEnc не скачаны — дословность не сверялась '
                                  '(python3 -I -B tools/hadith/build_hadith.py --download, затем --check)')
        return ошибки, счёт, предупреждения
    except ValueError as е:
        ош('сырьё', str(е))
        return ошибки, счёт, предупреждения
    плюс('хадисы: сырых выгрузок, sha256 = sources.json и якорю', len(выгрузки.файлы))
    ar = выгрузки.по_языку['ar']
    for (я, id_), р in порции.items():
        в = выгрузки.по_языку[я]
        исходник = в.хадисы.get(id_)
        if not исходник:
            ош(f'{я} #{id_}', 'нет в выгрузке')
            continue
        if р.get('link') != в.ссылки.get(id_):
            ош(f'{я} #{id_}', 'link ≠ CSV')
        if я == 'ar':
            поля = ('version', 'hadeeth', 'grade', 'attribution', 'reference')
            сравнить = [(п, р.get(п), исходник[п]) for п in поля]
            сравнить.append(('words_meanings', р.get('words_meanings'), х._список_json(исходник['words_meanings'])))
        else:
            сравнить = [(п, р.get(п), исходник[п]) for п in х.ПОЛЯ_ПЕРЕВОДА + ('ar_version',)]
            сравнить.append(('hints', р.get('hints'), х._список_json(исходник['hints']) or []))
            другой = исходник['hadeeth_ar'] != ar.хадисы[id_]['hadeeth']
            if другой:
                сравнить.append(('hadeeth_ar', р.get('hadeeth_ar'), исходник['hadeeth_ar']))
            elif 'hadeeth_ar' in р:
                ош(f'{я} #{id_}', 'hadeeth_ar лежит, хотя совпадает с арабской выгрузкой')
        for поле, наше, их in сравнить:
            if наше != их or type(наше) is not type(их):
                ош(f'{я} #{id_}', f'поле {поле} не совпадает с выгрузкой посимвольно')
            else:
                плюс('хадисы: полей сверено посимвольно с выгрузкой')
                плюс('хадисы: знаков сверено', len(json.dumps(их, ensure_ascii=False)) if not isinstance(их, str) else len(их))
    for я, словарь in заголовки.items():
        в = выгрузки.по_языку[я]
        for id_, (_, заголовок, степень) in словарь.items():
            if заголовок != в.хадисы[id_]['title'] or степень != в.хадисы[id_]['grade']:
                ош(f'заголовки {я} #{id_}', 'title/grade ≠ выгрузке')
            else:
                плюс('хадисы: заголовков сверено')
    for з in хадисы:
        if з['категории'] != [к for к in ar.связи.get(з['id'], []) if к in категории]:
            ош(f'#{з["id"]}', 'категории ≠ выгрузке')

    try:
        сборка = х.собрать(выгрузки, одобрено)
    except ValueError as е:
        ош('сборка', str(е))
        return ошибки, счёт, предупреждения
    for отн, б in сборка.файлы.items():
        try:
            if прочитать(отн) != б:
                ош(отн, 'не совпадает со свежей сборкой')
        except FileNotFoundError:
            ош(отн, 'нет файла свежей сборки — запустите build_hadith.py')
    if сборка.манифест != манифест:
        ош('manifest.generated.ts', 'не совпадает со свежей сборкой')
    if not х.ПУТЬ_НА_ПРОВЕРКУ.exists() or х.ПУТЬ_НА_ПРОВЕРКУ.read_bytes() != сборка.на_проверку:
        ош('на-проверку-устаза.json', 'не совпадает со свежей сборкой')
    плюс('хадисы: файлов = свежей сборке', len(сборка.файлы))
    return ошибки, счёт, предупреждения


def z_sha(з):
    return str(з.get('sha256') or '')


def z_файл(з):
    return str(з.get('файл') or '')


if __name__ == '__main__':
    требовать = '--raw' in sys.argv
    е, с, п = проверить(требовать)
    for к, в in с.items():
        print(f'  {к}: {в}')
    for пп in п:
        print('ПРЕДУПРЕЖДЕНИЕ: ' + пп)
    for ее in е[:200]:
        print('  - ' + ее)
    sys.exit(1 if е else 0)
