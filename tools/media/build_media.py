def прочитать(путь):
    return json.loads(путь.read_text(encoding='utf-8'))


def номер_урока(название, источник):
    """Номер урока/выпуска из названия видео; None — номера нет."""
    if источник == АЛИЖОН:
        м = re.search(r'(\d+)-dars|Урок (\d+)', название)
        return int(м.group(1) or м.group(2)) if м else None
    if источник == СУВАЙД:
        м = re.search(r'الحلقة \( (\d+) \)', название)
        return int(м.group(1)) if м else None
    м = re.search(r'- (\d+) сабақ', название)
    return int(м.group(1)) if м else None


def найти(плейлисты, источник, ключ, слово):
    видео = плейлисты[источник]['видео']
    if isinstance(ключ, int):
        найдено = [в for в in видео if номер_урока(в['название'], источник) == ключ]
    else:
        найдено = [в for в in видео if ключ in в['название']]
    if len(найдено) != 1:
        raise SystemExit(f'{источник} {ключ!r}: найдено {len(найдено)} видео, нужно ровно одно')
    if слово not in найдено[0]['название']:
        raise SystemExit(f'{источник} {ключ!r}: в названии «{найдено[0]["название"]}» нет «{слово}»')
    return найдено[0]


def запись_видео(источник, в, роль):
    return {'источник': источник, 'youtube_id': в['id'], 'название': в['название'], 'роль': роль,
            'ссылка': ССЫЛКА + в['id'], 'файл_видео': None, 'показывать': False}


def буквы_урока(путь):
    урок = прочитать(путь)
    return [з['знак'] for з in урок['задания'] if з['тип'] == 'знакомство']


