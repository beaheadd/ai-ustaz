"""Тест сборки пословных таймингов (tools/quran_words/build_words.py). Без сети.
Запуск: python3 -I -B tools/quran_words/test_build_words.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_words as б  # noqa: E402

n = fails = 0


def ok(cond, what):
    global n, fails
    n += 1
    if not cond:
        fails += 1
    print(('  ✓ ' if cond else '  ✗ ') + what)


ok(б.токены_аята('ذَٰلِكَ ٱلْكِتَـٰبُ لَا رَيْبَ ۛ فِيهِ ۛ هُدًۭى') == ['слово'] * 4 + ['знак', 'слово', 'знак', 'слово'],
   'токены: знаки остановки — отдельно, как text.ts')
т = ['слово', 'слово', 'знак', 'слово']
слова, оц = б.слова_аята([[0, 1, 0, 400], [1, 2, 420, 800], [2, 3, 820, 1200]], т, 'без-знаков')
ok(слова == [(0, 400), (420, 800), (820, 1200)] and оц == 0, 'счёт без знаков: номера — наши слова')
слова, _ = б.слова_аята([[0, 1, 0, 400], [1, 2, 420, 800], [3, 4, 820, 1200]], т, 'со-знаками')
ok(слова == [(0, 400), (420, 800), (820, 1200)], 'счёт со знаками: знак пропускается, номера переводятся')
слова, оц = б.слова_аята([[0, 2, 0, 800], [2, 3, 820, 1200]], т, 'без-знаков')
ok(слова == [(0, 400), (400, 800), (820, 1200)] and оц == 2, 'сегмент на два слова — поровну, слова отмечены как оценка')
слова, оц = б.слова_аята([[0, 1, 0, 400], [2, 3, 900, 1200]], т, 'без-знаков')
ok(слова == [(0, 400), (400, 900), (900, 1200)] and оц == 1, 'пропущенное слово — промежуток между соседями')
ok(б.слова_аята([[1, 3, 100, 900]], т, 'без-знаков') == (None, 0), 'нет первого слова — аят без таймингов')
ok(б.слова_аята([[0, 5, 0, 900]], т, 'без-знаков') == (None, 0), 'номер слова за пределом — аят без таймингов')
ok(б.слова_аята(None, т, 'без-знаков') == (None, 0), 'нет сегментов — без таймингов')
сж = б.сжать([(0, 400), (420, 800), (820, 1200)])
ok(сж == [0, 40, 2, 38, 2, 38] and б.развернуть(сж) == [(0, 40), (42, 80), (82, 120)], 'сжатие в сантисекунды и обратно')
ok(б.сжать([(0, 400)], сдвиг_мс=3000) == [300, 40], 'сдвиг на бисмиллу')
ok(б.сжать([(0, 500), (450, 800)]) == [0, 50, 0, 30], 'перекрытие слов — начало не раньше конца предыдущего')
записи = [{'surah': 2, 'ayah': 2, 'segments': [[0, 1, 0, 1], [5, 6, 2, 3]]}]
копия = {(2, 2): ['слово'] * 4 + ['знак', 'слово']}
ok(б.счёт_данных(записи, копия)[0] == 'со-знаками', 'счёт данных определяется по аятам со знаками')

print(f'\n{n - fails}/{n} проверок')
raise SystemExit(1 if fails else 0)
