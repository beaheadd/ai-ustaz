/**
 * Калькулятор закята — чистые функции (без React, без сети). Экран — screens/ZakatScreen.tsx, тест — scripts/test-zakat.mjs.
 *
 * Владелец 28.11.2026: «Нужно добавить калькулятор закята. Назвать нужно „Закят“». Раздел — черновик: правила счёта
 * проверяет устаз (правило 11 CLAUDE.md); без фетв — итог «по введённым данным», личные вопросы — к имаму или в ДУМК.
 *
 * Контракт:
 *   НИСАБ_ЗОЛОТО_Г = 85, НИСАБ_СЕРЕБРО_Г = 595 — нисаб в граммах (20 мискалей золота, 200 дирхамов серебра).
 *     Нисаба в тенге и цен в коде нет: цену грамма подставляет zakat/prices.ts с сервера (НБ РК; владелец 28.11.2026)
 *     или вводит человек (ДУМК ежегодно объявляет нисаб — muftyat.kz).
 *   разобратьСумму('1 234 567,5') → 1234567.5 | null — ввод человека: пробелы (в т. ч. неразрывные) — разделители
 *     разрядов, «,» или «.» — дробная часть (до 2 знаков для тенге, до 3 для граммов — обрезает экран); пусто → 0;
 *     мусор, минус, больше МАКС_СУММА → null.
 *   очиститьВвод(строка, знаков) → строка для поля: только цифры и одна дробная часть, разряды через пробел.
 *   форматТенге(1234567) → '1 234 567 ₸' (разряды — неразрывный пробел U+00A0, перед ₸ — тоже).
 *   посчитатьЗакят(ввод) → Итог (ниже) — суммы в тенге; внутри — тиыны (целые), чтобы не было ошибок дробей.
 *   Валюта (владелец 28.11.2026: «Должен быть выбор валюты всего мира»): счёт от валюты не зависит — «тенге» и «тиыны» в
 *   именах значат «единицы выбранной валюты» и «их сотые доли»; формат и пересчёт — zakat/currency.ts и zakat/rates.ts.
 * Правила счёта (черновик для устаза):
 *   имущество = наличные + карты и счета + золото (г × цена) + серебро (г × цена) + товары для продажи + уверенные долги вам;
 *   чистое = max(0, имущество − ваши долги, которые нужно отдать сейчас);
 *   нисаб = 595 г × цена серебра (по умолчанию: ханафиты берут меньший нисаб — так полезнее бедным) или 85 г × цена золота;
 *   закят обязателен по введённым данным, если чистое ≥ нисаба И прошёл лунный год (хауль);
 *   закят = чистое / 40 (2,5 %), с округлением вверх до тенге.
 */

export const НИСАБ_ЗОЛОТО_Г = 85;
export const НИСАБ_СЕРЕБРО_Г = 595;
/** Доля закята: 1/40 = 2,5 %. */
export const ДОЛЯ_ЗАКЯТА = 40;
/** Предел одного поля: 13 цифр (поле больше не берёт) — для валют с мелкой единицей (IRR, VND, IDR) с запасом; сотые доли
 *  остаются точными целыми: 6 полей × 10¹³ × 100 < 2^53 (владелец 28.11.2026: «выбор валюты всего мира»). */
export const МАКС_СУММА = 9_999_999_999_999;

export type МеталлНисаба = 'серебро' | 'золото';

export type ВводЗакята = {
  наличные: number;
  счета: number;
  золотоГ: number;
  ценаЗолота: number;
  сереброГ: number;
  ценаСеребра: number;
  товары: number;
  долгиВам: number;
  вашиДолги: number;
  нисабПо: МеталлНисаба;
  хауль: boolean;
};

/**
 * Почему такой итог:
 *   'нет-цены'    — не введена цена грамма металла выбранного нисаба (сравнить не с чем);
 *   'пусто'       — имущества нет (всё по нулям или долги больше);
 *   'ниже-нисаба' — чистое меньше нисаба;
 *   'нет-хауля'   — нисаб достигнут, но лунный год не отмечен;
 *   'закят'       — по введённым данным закят есть.
 */
export type ПричинаИтога = 'нет-цены' | 'пусто' | 'ниже-нисаба' | 'нет-хауля' | 'закят';

export type ИтогЗакята = {
  золотоТг: number;
  сереброТг: number;
  /** Всё имущество до вычета долгов. */
  имущество: number;
  /** Вычтенные долги (не больше имущества). */
  вычет: number;
  /** Имущество для закята: имущество − долги, не меньше 0. */
  чистое: number;
  /** Нисаб по золоту и по серебру в тенге; null — цена грамма не введена. */
  нисабЗолотоТг: number | null;
  нисабСереброТг: number | null;
  /** Нисаб выбранного металла в тенге (null — нет цены). */
  нисабТг: number | null;
  нисабДостигнут: boolean;
  /** Сумма закята в тенге (0, если не обязателен по введённым данным). */
  закят: number;
  причина: ПричинаИтога;
  /** Граммы золота или серебра введены, а цена грамма — нет: металл не посчитан. */
  нетЦеныЗолота: boolean;
  нетЦеныСеребра: boolean;
};

export const ПУСТОЙ_ВВОД: ВводЗакята = {
  наличные: 0,
  счета: 0,
  золотоГ: 0,
  ценаЗолота: 0,
  сереброГ: 0,
  ценаСеребра: 0,
  товары: 0,
  долгиВам: 0,
  вашиДолги: 0,
  нисабПо: 'серебро',
  хауль: false,
};

/** Тенге → тиыны (целые). Отрицательное и не число — 0. */
function вТиыны(тенге: number): number {
  return Number.isFinite(тенге) && тенге > 0 ? Math.round(тенге * 100) : 0;
}

/** Граммы × цена грамма → тиыны (целые). */
function стоимостьТиын(граммы: number, цена: number): number {
  if (!Number.isFinite(граммы) || !Number.isFinite(цена) || граммы <= 0 || цена <= 0) return 0;
  return Math.round(граммы * цена * 100);
}

/** Тиыны → тенге, вверх до целого (для нисаба и закята: не занижаем). */
const вТенгеВверх = (тиын: number) => Math.ceil(тиын / 100);
/** Тиыны → тенге с копейками (для сумм имущества — как есть, 2 знака). */
const вТенге = (тиын: number) => тиын / 100;

export function посчитатьЗакят(ввод: ВводЗакята): ИтогЗакята {
  const золото = стоимостьТиын(ввод.золотоГ, ввод.ценаЗолота);
  const серебро = стоимостьТиын(ввод.сереброГ, ввод.ценаСеребра);
  const имущество = вТиыны(ввод.наличные) + вТиыны(ввод.счета) + золото + серебро + вТиыны(ввод.товары) + вТиыны(ввод.долгиВам);
  const вычет = Math.min(имущество, вТиыны(ввод.вашиДолги));
  const чистое = имущество - вычет;
  const нисабЗолото = ввод.ценаЗолота > 0 ? стоимостьТиын(НИСАБ_ЗОЛОТО_Г, ввод.ценаЗолота) : null;
  const нисабСеребро = ввод.ценаСеребра > 0 ? стоимостьТиын(НИСАБ_СЕРЕБРО_Г, ввод.ценаСеребра) : null;
  const нисаб = ввод.нисабПо === 'золото' ? нисабЗолото : нисабСеребро;
  const нисабДостигнут = нисаб !== null && чистое > 0 && чистое >= нисаб;
  const причина: ПричинаИтога =
    нисаб === null ? 'нет-цены' : чистое === 0 ? 'пусто' : !нисабДостигнут ? 'ниже-нисаба' : !ввод.хауль ? 'нет-хауля' : 'закят';
  // 1/40 с округлением вверх до тенге: тиыны / 40 / 100 = тиыны / 4000 (целое деление точно: чистое < 2^53).
  const закят = причина === 'закят' ? Math.ceil(чистое / (ДОЛЯ_ЗАКЯТА * 100)) : 0;
  return {
    золотоТг: вТенге(золото),
    сереброТг: вТенге(серебро),
    имущество: вТенге(имущество),
    вычет: вТенге(вычет),
    чистое: вТенге(чистое),
    нисабЗолотоТг: нисабЗолото === null ? null : вТенгеВверх(нисабЗолото),
    нисабСереброТг: нисабСеребро === null ? null : вТенгеВверх(нисабСеребро),
    нисабТг: нисаб === null ? null : вТенгеВверх(нисаб),
    нисабДостигнут,
    закят,
    причина,
    нетЦеныЗолота: ввод.золотоГ > 0 && !(ввод.ценаЗолота > 0),
    нетЦеныСеребра: ввод.сереброГ > 0 && !(ввод.ценаСеребра > 0),
  };
}

/** Пробелы любых видов (обычный, неразрывный, узкий неразрывный, тонкий). */
const ПРОБЕЛЫ = /[\s   ]/g;

/** Ввод человека → число; пусто → 0; кривое, отрицательное, больше МАКС_СУММА → null. */
export function разобратьСумму(строка: string): number | null {
  const с = строка.replace(ПРОБЕЛЫ, '').replace(',', '.');
  if (с === '') return 0;
  if (!/^\d+(\.\d*)?$|^\.\d+$/.test(с)) return null;
  const ч = Number(с);
  if (!Number.isFinite(ч) || ч < 0 || ч > МАКС_СУММА) return null;
  return ч;
}

/** Целая часть с разрядами через пробел: '1234567' → '1 234 567'. */
function разряды(цифры: string, пробел: string): string {
  return цифры.replace(/\B(?=(\d{3})+(?!\d))/g, пробел);
}

/**
 * Строка для поля ввода: оставить цифры и одну дробную часть (не больше `знаков`), убрать ведущие нули, разряды —
 * обычным пробелом (поле переносит строку редко, а неразрывный пробел мешает копированию в калькулятор телефона).
 * '1234567,891' (знаков 2) → '1 234 567,89'; 'abc' → ''; '007' → '7'.
 */
export function очиститьВвод(строка: string, знаков: number): string {
  const с = строка.replace(ПРОБЕЛЫ, '').replace(/\./g, ',');
  const позиция = с.indexOf(',');
  const цел = (позиция < 0 ? с : с.slice(0, позиция)).replace(/\D/g, '').replace(/^0+(?=\d)/, '').slice(0, 13);
  if (позиция < 0 || знаков <= 0) return разряды(цел, ' ');
  const дробь = с.slice(позиция + 1).replace(/\D/g, '').slice(0, знаков);
  return разряды(цел === '' ? '0' : цел, ' ') + ',' + дробь;
}

/** 1234567 → '1 234 567 ₸' (неразрывные пробелы); дробные тенге — с запятой: 12,5 → '12,50 ₸'. */
export function форматТенге(тенге: number): string {
  const тиын = Math.round(Math.max(0, тенге) * 100);
  const цел = разряды(String(Math.floor(тиын / 100)), ' ');
  const остаток = тиын % 100;
  return (остаток ? цел + ',' + String(остаток).padStart(2, '0') : цел) + ' ₸';
}

/** Граммы для подписи: 85 → '85', 12.5 → '12,5'. */
export function форматГраммы(г: number): string {
  return String(г).replace('.', ',');
}
