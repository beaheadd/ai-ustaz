/**
 * Запись и проверка ЛЮБОГО аята — точка входа для экранов (#/quran/check, docs/дизайн/05 §2.4).
 *
 * Контракт:
 *   частиАята(текст) → ЧастьЗаписи[] — части аята для записи (parts.ts; текст — дословно из копии для показа,
 *     СураКорана.аяты[i].текст). Номер части с 1 = параметр p маршрута.
 *   эталонЧасти(сура, аят, часть, всегоСлов) → ЭталонПроверки (speech/check.ts): весь аят — { сура, аят };
 *     часть — { сура, аят, словоС, слов } (uthmani-слова с 1 → поля uthmani_from / uthmani_words сервиса).
 *   проверкаЧасти(сура, аят, текст, часть, виды) → проп `проверка` для <ПанельЗаписи>: эталон, текстПоказа (аят на
 *     экране), словаПоказа (слова копии для показа без знаков — подсказка называет слово ТОЛЬКО отсюда, по номеру из
 *     ответа сервиса), виды.
 *   видыПоПрогрессу(прогресс.уроки) → kinds (kinds.ts); ЦЕЛЬ_СЕК, ПРЕДЕЛ_СЕРВИСА_СЕК — parts.ts.
 * Компонент: <ПанельЧтенияАята> (components/quran/RecitePanel.tsx).
 * Правила: текст Корана не меняется и не режется (правило 1); на экране — только целый аят с подсветкой части
 * (правило 8); проверка — только на своём домене (speech/flag.ts), подсказки — «Проверьте себя»/«Подсказка» (правило 7).
 * Решение владельца 19.11.2026: «заходишь и читаешь любой аят, и записываешь голос и проверяешь, где ошибки».
 */
import { разборАята, словаАята, частиПоОстановкам } from '../quran/text';
import type { ЭталонПроверки } from '../speech/fields';
import { частиДляЗаписи, эталонЧасти, type ЧастьЗаписи } from './parts';

export { видыПоПрогрессу, БАЗОВЫЕ_ВИДЫ, ВИДЫ_ПО_УРОКАМ } from './kinds';
export { ЦЕЛЬ_СЕК, ПРЕДЕЛ_СЕРВИСА_СЕК, ПОРОГ_ВЫНУЖДЕННОЙ_СЕК, оценкаСекунд, эталонЧасти, type ЧастьЗаписи, type КонецЧасти } from './parts';

export function частиАята(текст: string): ЧастьЗаписи[] {
  return частиДляЗаписи(разборАята(текст), частиПоОстановкам(текст));
}

export type ПроверкаЧасти = {
  эталон: ЭталонПроверки;
  текстПоказа: string;
  словаПоказа: readonly string[];
  виды: readonly string[];
};

export function проверкаЧасти(сура: number, аят: number, текст: string, часть: ЧастьЗаписи, виды: readonly string[]): ПроверкаЧасти {
  const слова = словаАята(текст);
  return { эталон: эталонЧасти(сура, аят, часть, слова.length), текстПоказа: текст, словаПоказа: слова, виды };
}
