/** Виды сервиса: 'буква' (A1–A3), 'огласовка' (B1), 'мадд' (C1.*, C2), 'гунна' (D2), 'идгам' (E1), 'калькаля' (F1, F3), 'таджвид' (T). */
export const БАЗОВЫЕ_ВИДЫ: readonly string[] = ['буква', 'огласовка'];

export const ВИДЫ_ПО_УРОКАМ: ReadonlyArray<{ урок: number; виды: readonly string[] }> = [
  { урок: 17, виды: ['C1.табии', 'C2'] }, // мадд через ا — 2 счёта; «распевание» (C2) — там же
  { урок: 18, виды: ['C1.лин'] }, // мадд через ي и و; лин
  { урок: 21, виды: ['гунна'] }, // нун и мим с шаддой — гунна 2 счёта
  { урок: 23, виды: ['C1.муттасиль', 'C1.мунфасиль'] }, // знак мадда ٓ — не меньше 4 (мунфасиль на 2 — подсказка S5)
  { урок: 29, виды: ['C1.арид'] }, // мадд ‘арид при остановке (2, 4 или 6)
  { урок: 31, виды: ['C1.лязим'] }, // мадд лязим — 6 счётов
  { урок: 33, виды: ['идгам'] }, // идгам с гунной и без
  { урок: 37, виды: ['калькаля'] }, // калькаля, без ложной калькали
  { урок: 42, виды: ['таджвид'] }, // общий «таджвид» (T) — только после всего блока таджвида (уроки 32–42)
];

export function видыПоПрогрессу(уроки: Readonly<Record<string, { пройден?: boolean } | undefined>> | null | undefined): string[] {
  const виды = [...БАЗОВЫЕ_ВИДЫ];
  for (const { урок, виды: новые } of ВИДЫ_ПО_УРОКАМ) {
    if (уроки?.[String(урок)]?.пройден === true) for (const в of новые) if (!виды.includes(в)) виды.push(в);
  }
  return виды;
}
