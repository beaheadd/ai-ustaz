/**
 * Части аята для записи и проверки голосом — ЧИСТЫЕ функции (только `import type`: тест в node, scripts/test-speech.mjs).
 *
 * Зачем: речевой сервис принимает запись до 20 с (speech/README.md), а аяты бывают длинными (2:282 — 128 слов).
 * Поэтому аят делится на части ДЕТЕРМИНИРОВАННО — по знакам остановки копии Tanzil ДЛЯ ПОКАЗА. Текст Корана не
 * меняется и не режется: часть — это диапазон uthmani-слов (с 1) и индексы токенов разборАята (src/quran/text.ts)
 * для подсветки в ЦЕЛОМ аяте (правило 1 и 8 CLAUDE.md — обрезок как «аят» не показывается).
 *
 * Как делим (ЧЕРНОВИК ПОЛИТИКИ — утверждает устаз, docs/дизайн/05 §3 вопрос 3):
 * 1. Базовые части — частиПоОстановкам (text.ts): места, где МОЖНО остановиться, — ۘ ۗ ۖ ۚ. Не делим по ۙ (остановка
 *    нежелательна), ۛ (муанака: останавливаются только на одном из пары), ۜ (сакта: пауза без вдоха), ۞ и ۩.
 * 2. Соседние базовые части объединяем, пока оценка ≤ ЦЕЛЬ_СЕК (меньше частей; при равенстве — ровнее). Через ۘ
 *    (лязим — остановка обязательна) не объединяем никогда: после ۘ всегда новая часть. Аят, который помещается
 *    целиком и не содержит ۘ, — одна часть.
 * 3. Базовая часть длиннее ЦЕЛЬ_СЕК без знаков внутри — «вынужденная остановка» (как учат устазы: остановиться, где
 *    кончилось дыхание, и начать снова с того же слова): режем на отрезки ≤ ЦЕЛЬ_СЕК, следующий отрезок начинается со
 *    слова, на котором остановились (ВОЗВРАТ_СЛОВ = 1). Такие части помечены конец: 'вынужденная' / сВозвратом:
 *    экран обязан это сказать.
 * Оценка длительности — тоже черновик: по буквам слова (откалибровано по записям 5:109 в qdat_bench: 8 слов
 * ≈ 8–9 с, speech/EVAL.md) с запасом для неторопливого ученика: ЦЕЛЬ_СЕК = 15 при жёстком пределе сервиса 20 с.
 * Уточнить по записям своих кари и учеников.
 *
 * Контракт:
 *   частиДляЗаписи(токены: Токен[] (разборАята), базовые: ЧастьАята[] (частиПоОстановкам), настройки?) → ЧастьЗаписи[]
 *     номера частей с 1; части покрывают все слова аята по порядку (с перекрытием в одно слово только у вынужденных).
 *   оценкаСекунд(слова: string[]) → секунды чтения (черновик); буквСлова(слово) → число «звучащих» знаков.
 *   эталонЧасти(сура, аят, часть, всегоСлов) → ЭталонПроверки (speech/fields.ts): весь аят — { сура, аят };
 *     часть — { сура, аят, словоС, слов } (→ uthmani_from / uthmani_words сервиса).
 * Решение владельца 19.11.2026: «заходишь и читаешь любой аят, и записываешь голос и проверяешь, где ошибки».
 */
import type { ВидЗнака, ЧастьАята, Токен } from '../quran/text';
import type { ЭталонПроверки } from '../speech/fields';

export type КонецЧасти = 'аят' | 'остановка' | 'вынужденная';

export type ЧастьЗаписи = {
  /** С 1 — параметр p маршрута #/quran/check. */
  номер: number;
  /** Первое uthmani-слово части (с 1, по всему аяту) — поле uthmani_from сервиса. */
  словоС: number;
  /** Сколько слов — поле uthmani_words. */
  слов: number;
  /** Индексы токенов разборАята (включительно) — подсветка части в целом аяте; знак остановки в конце входит. */
  токенС: number;
  токенПо: number;
  /** Чем кончается часть: концом аята, знаком остановки (знакВКонце) или вынужденной остановкой без знака. */
  конец: КонецЧасти;
  знакВКонце: ВидЗнака | null;
  /** Часть начинается со слова, на котором кончилась предыдущая (возврат после вынужденной остановки). */
  сВозвратом: boolean;
  /** Оценка длительности чтения, с (черновик). */
  оценкаСек: number;
};

export type НастройкиЧастей = { цельСек?: number; возвратСлов?: number };

export const ЦЕЛЬ_СЕК = 15;
export const ПРЕДЕЛ_СЕРВИСА_СЕК = 20;
export const ВОЗВРАТ_СЛОВ = 1;
/** Черновик калибровки: секунд на «звучащий» знак, добавка на знак мадда ٓ (4–6 счётов) и на вдох/паузы по краям. */
export const СЕК_НА_БУКВУ = 0.24;
export const СЕК_НА_МАДД = 0.5;
export const СЕК_НА_КРАЯ = 0.8;

const ЗНАК_МАДДА = 0x0653; // ٓ

/** «Звучащие» знаки слова: буквы, надстрочный алиф ٰ, малые вав/йа ۥ ۦ ۧ (татвиль и огласовки — нет). */
export function буквСлова(слово: string): number {
  let н = 0;
  for (const с of слово) {
    const к = с.codePointAt(0) ?? 0;
    if ((к >= 0x0621 && к <= 0x063a) || (к >= 0x0641 && к <= 0x064a) || (к >= 0x0671 && к <= 0x06d3)) н += 1;
    else if (к === 0x0670 || к === 0x06e5 || к === 0x06e6 || к === 0x06e7) н += 1;
  }
  return н;
}

function секундСлова(слово: string): number {
  let мадд = 0;
  for (const с of слово) if (с.codePointAt(0) === ЗНАК_МАДДА) мадд += 1;
  return буквСлова(слово) * СЕК_НА_БУКВУ + мадд * СЕК_НА_МАДД;
}

export function оценкаСекунд(слова: readonly string[]): number {
  return слова.length === 0 ? 0 : СЕК_НА_КРАЯ + слова.reduce((с, с2) => с + секундСлова(с2), 0);
}

const округлить = (x: number) => Math.round(x * 10) / 10;

type Кусок = { словоС: number; слов: number; токенС: number; токенПо: number; знакВКонце: ВидЗнака | null };

/** Лучшее разбиение последовательности на отрезки: меньше отрезков, затем меньше самый длинный (детерминированно). */
function лучшееРазбиение(
  n: number,
  можно: (i: number, j: number) => boolean, // отрезок [i, j) допустим
  стоимость: (i: number, j: number) => number,
  шаг: (j: number) => number, // откуда начинается следующий отрезок после [i, j)
): Array<[number, number]> | null {
  const лучшее: Array<{ число: number; макс: number; от: number } | null> = new Array(n + 1).fill(null);
  лучшее[0] = { число: 0, макс: 0, от: -1 };
  // Состояние — начало очередного отрезка; цель — n.
  const откуда: Array<[number, number] | null> = new Array(n + 1).fill(null);
  for (let i = 0; i < n; i++) {
    const б = лучшее[i];
    if (!б) continue;
    for (let j = i + 1; j <= n; j++) {
      if (!можно(i, j)) continue;
      const следующий = j === n ? n : шаг(j);
      if (следующий <= i) continue;
      const кандидат = { число: б.число + 1, макс: Math.max(б.макс, стоимость(i, j)), от: i };
      const было = лучшее[следующий];
      if (!было || кандидат.число < было.число || (кандидат.число === было.число && кандидат.макс < было.макс - 1e-9)) {
        лучшее[следующий] = кандидат;
        откуда[следующий] = [i, j];
      }
    }
  }
  if (!лучшее[n]) return null;
  const путь: Array<[number, number]> = [];
  for (let к = n; к > 0; ) {
    const о = откуда[к];
    if (!о) return null;
    путь.unshift(о);
    к = о[0];
  }
  return путь;
}

export function частиДляЗаписи(
  токены: readonly Токен[],
  базовые: readonly ЧастьАята[],
  настройки: НастройкиЧастей = {},
): ЧастьЗаписи[] {
  const цель = настройки.цельСек ?? ЦЕЛЬ_СЕК;
  const возврат = Math.max(0, Math.floor(настройки.возвратСлов ?? ВОЗВРАТ_СЛОВ));
  const слова: string[] = [];
  const токенСлова: number[] = []; // индекс токена слова с номером (i + 1)
  токены.forEach((т, i) => {
    if (т.вид === 'слово') {
      слова.push(т.текст);
      токенСлова.push(i);
    }
  });
  if (слова.length === 0 || базовые.length === 0) return [];
  const оценка = (с: number, слов: number) => оценкаСекунд(слова.slice(с - 1, с - 1 + слов));

  // 2. Объединение соседних базовых частей (не через ۘ).
  const б = базовые;
  const объединение = лучшееРазбиение(
    б.length,
    (i, j) => {
      for (let к = i; к < j - 1; к++) if (б[к].знакВКонце === 'лязим') return false;
      if (j - i === 1) return true; // одна базовая часть допустима всегда (длинную режем ниже)
      const послед = б[j - 1];
      return оценка(б[i].словоС, послед.словоС + послед.слов - б[i].словоС) <= цель;
    },
    (i, j) => оценка(б[i].словоС, б[j - 1].словоС + б[j - 1].слов - б[i].словоС),
    (j) => j,
  ) ?? б.map((_, i) => [i, i + 1] as [number, number]);
  const куски: Кусок[] = объединение.map(([i, j]) => ({
    словоС: б[i].словоС,
    слов: б[j - 1].словоС + б[j - 1].слов - б[i].словоС,
    токенС: б[i].токенС,
    токенПо: б[j - 1].токенПо,
    знакВКонце: б[j - 1].знакВКонце,
  }));

  // 3. Вынужденные остановки внутри длинных кусков без знаков.
  const итог: ЧастьЗаписи[] = [];
  for (const к of куски) {
    const весь = оценка(к.словоС, к.слов);
    const отрезки =
      весь <= цель || к.слов < 2
        ? null
        : лучшееРазбиение(
            к.слов,
            // Отрезок ≤ цели (два слова — всегда: иначе не сдвинуться). Продвижение вперёд проверяет лучшееРазбиение:
            // следующий отрезок начинается с j − возврат и должен быть правее начала текущего.
            (i, j) => оценка(к.словоС + i, j - i) <= цель || j - i <= 2,
            (i, j) => оценка(к.словоС + i, j - i),
            (j) => j - возврат,
          );
    if (!отрезки || отрезки.length < 2) {
      итог.push({
        номер: итог.length + 1,
        словоС: к.словоС,
        слов: к.слов,
        токенС: к.токенС,
        токенПо: к.токенПо,
        конец: к.знакВКонце ? 'остановка' : 'аят',
        знакВКонце: к.знакВКонце,
        сВозвратом: false,
        оценкаСек: округлить(весь),
      });
      continue;
    }
    отрезки.forEach(([i, j], н) => {
      const последний = н === отрезки.length - 1;
      const словоС = к.словоС + i;
      итог.push({
        номер: итог.length + 1,
        словоС,
        слов: j - i,
        токенС: н === 0 ? к.токенС : токенСлова[словоС - 1],
        токенПо: последний ? к.токенПо : токенСлова[к.словоС + j - 2],
        конец: последний ? (к.знакВКонце ? 'остановка' : 'аят') : 'вынужденная',
        знакВКонце: последний ? к.знакВКонце : null,
        сВозвратом: н > 0 && возврат > 0,
        оценкаСек: округлить(оценка(словоС, j - i)),
      });
    });
  }
  return итог;
}

export function эталонЧасти(сура: number, аят: number, часть: Pick<ЧастьЗаписи, 'словоС' | 'слов'>, всегоСлов: number): ЭталонПроверки {
  if (часть.словоС === 1 && часть.слов === всегоСлов) return { сура, аят };
  return { сура, аят, словоС: часть.словоС, слов: часть.слов };
}
