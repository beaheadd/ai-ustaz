/**
 * Поля формы запроса к речевому сервису — ЧИСТЫЕ функции (только `import type`: тест в node, scripts/test-speech.mjs).
 *
 * Контракт:
 *   ЭталонПроверки = { текст } (учебный слог/слово) | { сура, аят, словоС?, слов? } — словоС/слов — UTHMANI-слова с 1
 *     (номерСлова в quran/text.ts: слова копии для показа без знаков-токенов = слова фонетической копии сервиса).
 *   поляЭталона(эталон, виды?) → [имя, значение][] — text | sura, aya[, uthmani_from[, uthmani_words]]; kinds.
 *     С 19.11.2026 диапазон слов уходит в uthmani_from / uthmani_words: старое поле word_from сервис понимает как
 *     imlaey-слово с 0 («يَـٰٓأَيُّهَا» — два imlaey-слова) — это была скрытая ошибка (docs/дизайн/05 §2.4).
 *   текстДляСервиса(текст) — учебный текст без запятых, пробелы схлопнуты (техническая производная).
 *   диапазонОтвета(эталон, словаПоказа?) → ОпцииРазбора | undefined — для аята: слова показа и проверенный диапазон
 *     (answer.ts сверяет эхо сервиса и номера слов замечаний).
 */
import type { ОпцииРазбора } from './answer';

export type ЭталонПроверки = { текст: string } | { сура: number; аят: number; словоС?: number; слов?: number };

/** Учебный текст для сервиса: без арабских и латинских запятых, пробелы схлопнуты (техническая производная). */
export function текстДляСервиса(текст: string): string {
  return текст.replace(/[،,]/g, ' ').split(/\s+/).filter(Boolean).join(' ');
}

export function поляЭталона(эталон: ЭталонПроверки, виды?: readonly string[]): Array<[string, string]> {
  const поля: Array<[string, string]> = [];
  if ('текст' in эталон) {
    поля.push(['text', текстДляСервиса(эталон.текст)]);
  } else {
    поля.push(['sura', String(эталон.сура)], ['aya', String(эталон.аят)]);
    if (эталон.словоС != null) {
      поля.push(['uthmani_from', String(эталон.словоС)]);
      if (эталон.слов != null) поля.push(['uthmani_words', String(эталон.слов)]);
    }
  }
  if (виды && виды.length > 0) поля.push(['kinds', виды.join(',')]);
  return поля;
}

export function диапазонОтвета(эталон: ЭталонПроверки, словаПоказа?: readonly string[] | null): ОпцииРазбора | undefined {
  if ('текст' in эталон || !словаПоказа || словаПоказа.length === 0) return undefined;
  const словоС = эталон.словоС ?? 1;
  return { словаПоказа, словоС, слов: эталон.слов ?? словаПоказа.length - словоС + 1 };
}
