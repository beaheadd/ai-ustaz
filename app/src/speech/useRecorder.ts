/**
 * Хук записи голоса для экранов: создаёт ЗаписьГолоса при монтировании и освобождает
 * её при размонтировании (запись удаляется при уходе с упражнения).
 *
 * Контракт:
 *   const з = useЗаписьГолоса({ максДлительностьМс?: number });
 *   з.снимок     — { состояние, ошибка, длительностьМс, естьЗапись } (см. speech/record.ts);
 *   з.уровень    — громкость 0..1, обновляется ~12 раз в секунду только во время записи;
 *   з.поддерживается — платформа умеет записывать;
 *   з.начать() / з.остановить() / з.воспроизвести() / з.остановитьВоспроизведение() / з.удалить().
 * Вердикта по голосу нет и не будет до речевого сервиса (этап 0) — только «Записали! Послушайте себя».
 */
import { useCallback, useEffect, useState, useSyncExternalStore } from 'react';
import { записьПоддерживается, создатьЗаписьГолоса, type ЗаписьГолоса, type НастройкиЗаписи, type СнимокЗаписи } from './record';

const ПУСТОЙ_СНИМОК: СнимокЗаписи = { состояние: 'ожидание', ошибка: null, длительностьМс: 0, естьЗапись: false };
const ШАГ_УРОВНЯ_МС = 80;

export type УправлениеЗаписью = {
  снимок: СнимокЗаписи;
  уровень: number;
  поддерживается: boolean;
  начать: () => Promise<void>;
  остановить: () => void;
  воспроизвести: () => Promise<void>;
  остановитьВоспроизведение: () => void;
  удалить: () => void;
};

export function useЗаписьГолоса(настройки?: НастройкиЗаписи): УправлениеЗаписью {
  const максМс = настройки?.максДлительностьМс;
  const [запись, установитьЗапись] = useState<ЗаписьГолоса | null>(null);

  useEffect(() => {
    const новая = создатьЗаписьГолоса({ максДлительностьМс: максМс });
    установитьЗапись(новая);
    return () => {
      новая.освободить();
    };
  }, [максМс]);

  const подписаться = useCallback((обновить: () => void) => (запись ? запись.подписаться(обновить) : () => {}), [запись]);
  const получить = useCallback(() => (запись ? запись.снимок() : ПУСТОЙ_СНИМОК), [запись]);
  const снимок = useSyncExternalStore(подписаться, получить, получить);

  const [уровень, установитьУровень] = useState(0);
  useEffect(() => {
    if (!запись || снимок.состояние !== 'запись') {
      установитьУровень(0);
      return;
    }
    const таймер = setInterval(() => установитьУровень(запись.уровень()), ШАГ_УРОВНЯ_МС);
    return () => clearInterval(таймер);
  }, [запись, снимок.состояние]);

  const начать = useCallback(async () => {
    await запись?.начать();
  }, [запись]);
  const остановить = useCallback(() => запись?.остановить(), [запись]);
  const воспроизвести = useCallback(async () => {
    await запись?.воспроизвести();
  }, [запись]);
  const остановитьВоспроизведение = useCallback(() => запись?.остановитьВоспроизведение(), [запись]);
  const удалить = useCallback(() => запись?.удалить(), [запись]);

  return {
    снимок,
    уровень,
    поддерживается: записьПоддерживается(),
    начать,
    остановить,
    воспроизвести,
    остановитьВоспроизведение,
    удалить,
  };
}
