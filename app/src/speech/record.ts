/**
 * Запись голоса — ИНТЕРФЕЙС (общий для платформ). Реализации:
 *   record.web.ts    — браузер, MediaRecorder + AnalyserNode (работает сейчас);
 *   record.native.ts — Android/iOS, заглушка (TODO: expo-audio).
 * Metro сам подставляет нужный файл по расширению; TypeScript видит этот.
 * Импортировать так: import { создатьЗаписьГолоса } from '../speech/record';
 * В экранах удобнее хук useЗаписьГолоса() (speech/useRecorder.ts) или компонент
 * <ПанельЗаписи> (components/RecordPanel.tsx).
 *
 * Правила (CLAUDE.md «Данные и приватность», решение по прототипу 18.11.2026):
 * - запись начинается только по нажатию; перед первым запросом микрофона показываем
 *   пояснение (<ПояснениеМикрофона>);
 * - запись живёт только в памяти страницы и не сохраняется; удаляется при уходе с упражнения
 *   (освободить() при размонтировании). Отправить её можно только явно: данные() → speech/check.ts
 *   по нажатию «Проверить» (проверка голосом — только на своём домене, speech/flag.ts; на batr.kz её нет);
 * - микрофон освобождается сразу после остановки записи;
 * - вердикта «верно/ошибка» по записи нет: проверка голосом (если включена) даёт только мягкие подсказки.
 */

export type СостояниеЗаписи = 'ожидание' | 'запрос' | 'запись' | 'записано' | 'воспроизведение';

export type ОшибкаЗаписи = 'нет-доступа' | 'нет-микрофона' | 'не-поддерживается' | 'небезопасно' | 'занят' | 'неизвестно';

export type СнимокЗаписи = {
  состояние: СостояниеЗаписи;
  /** Последняя ошибка (сбрасывается при следующем начать()). */
  ошибка: ОшибкаЗаписи | null;
  /** Длительность текущей (идущей) или готовой записи, мс. */
  длительностьМс: number;
  /** Есть готовая запись, которую можно послушать. */
  естьЗапись: boolean;
};

export type НастройкиЗаписи = {
  /** Автостоп, мс. По умолчанию 30 000. */
  максДлительностьМс?: number;
};

export interface ЗаписьГолоса {
  /** Платформа умеет записывать (без запроса доступа). */
  поддерживается(): boolean;
  /** Текущий снимок (тот же объект, пока ничего не изменилось). */
  снимок(): СнимокЗаписи;
  /** Подписка на изменения снимка; возвращает отписку. */
  подписаться(слушатель: (снимок: СнимокЗаписи) => void): () => void;
  /** Запросить микрофон (если нужно) и начать запись. Прежняя запись удаляется. Ошибки — в снимке. */
  начать(): Promise<void>;
  /** Остановить запись: запись готова, микрофон освобождён. */
  остановить(): void;
  /** Воспроизвести готовую запись. */
  воспроизвести(): Promise<void>;
  остановитьВоспроизведение(): void;
  /** Стереть запись из памяти. */
  удалить(): void;
  /** Готовая запись (Blob в памяти) — только для проверки по нажатию «Проверить»; иначе null. */
  данные(): Blob | null;
  /** Текущая громкость 0..1 (только во время записи; иначе 0) — для индикатора. */
  уровень(): number;
  /** Остановить всё, освободить микрофон и память. После вызова объект не использовать. */
  освободить(): void;
}

export declare function записьПоддерживается(): boolean;
export declare function создатьЗаписьГолоса(настройки?: НастройкиЗаписи): ЗаписьГолоса;
