/**
 * Клиент речевого сервиса AI Ustaz: проверка чтения одной записи.
 *
 * Контракт:
 *   проверитьЧтение(запись: Blob, эталон: ЭталонПроверки, виды?: string[], опции?) → Promise<ИтогПроверки>
 *     эталон: { текст } — учебный слог/слово (арабский с огласовками), или { сура, аят, словоС?, слов? } —
 *       словоС/слов — UTHMANI-слова с 1 (как номерСлова в quran/text.ts: слова копии для показа без знаков-токенов;
 *       совпадают со словами фонетической копии сервиса) → поля uthmani_from / uthmani_words (19.11.2026; раньше
 *       слали word_from — у сервиса это imlaey-слова с 0, скрытая ошибка, docs/дизайн/05 §2.4);
 *     виды — какие виды правил ученик уже прошёл (поле kinds: виды или коды; для аята — quran-check/kinds.ts);
 *     опции.сигнал — AbortSignal (уход с упражнения → итог { вид:'ошибка', ошибка:'отменено' });
 *     опции.текстПоказа — текст, который ученик видит на экране: фрагменты подсказок берутся только из него
 *       (по умолчанию — эталон.текст; для аята — передать текст Tanzil, иначе фрагменты не показываются);
 *     опции.словаПоказа — для аята: слова копии для показа (quran/text.ts, словаАята). Тогда слово подсказки берётся
 *       ТОЛЬКО отсюда по номеру uthmani-слова из ответа (замечание.слово), а ответ без подтверждённого диапазона
 *       (эталон.слово_с/слов ≠ запрошенным — старый сервис проверил бы не ту часть) → «недоступно» (answer.ts).
 *   Исключений не бросает: всё — в ИтогПроверки (speech/answer.ts).
 *   эталонЗадания(читать) → { эталон, текстПоказа } — из поля «читать» задания (учебный или Коран).
 *
 * Сервис: POST /api/speech/v1/proverka — ОТНОСИТЕЛЬНЫЙ адрес, только свой домен (CSP connect-src 'self');
 *   multipart: audio (WAV 16 кГц моно PCM16, speech/wav.web.ts), text | sura+aya(+uthmani_from, uthmani_words), kinds
 *   — поля собирает speech/fields.ts (поляЭталона; чистая функция, тест в node).
 *   Таймаут 20 с. 503 — сервис занят; 413 — запись велика; 400 — запись или эталон не разобраны.
 *
 * Правила (CLAUDE.md «Данные и приватность», правило 7; решение владельца: только свой домен, не batr.kz):
 * - вызывается ТОЛЬКО по нажатию «Проверить» и только при проверкаГолосомВключена() (повторная защита здесь);
 * - запись уходит только на свой сервер в РК; без cookie и Referer; ответ не сохраняется;
 * - запись длиннее 20 с не отправляем: сервис её не примет («плохой звук: длинно», это не ошибка).
 */
import type { ФрагментКорана } from '../content/types';
import { разобратьОтвет, type ИтогПроверки } from './answer';
import { диапазонОтвета, поляЭталона, текстДляСервиса, type ЭталонПроверки } from './fields';
import { проверкаГолосомВключена } from './flag';
import { вWav16кГц } from './wav';

export type { ЭталонПроверки } from './fields';
export { текстДляСервиса };

export const АДРЕС_ПРОВЕРКИ = '/api/speech/v1/proverka';
export const ТАЙМАУТ_ПРОВЕРКИ_МС = 20_000;
export const МАКС_СЕК_ПРОВЕРКИ = 20;

export function эталонЗадания(читать: { учебный: string } | { коран: ФрагментКорана }): { эталон: ЭталонПроверки; текстПоказа: string } {
  if ('коран' in читать) {
    const ф = читать.коран;
    const эталон: ЭталонПроверки = ф.слова
      ? // ф.слова — номера по split(' ') строки аята; = uthmani-словам, пока внутри аята нет знаков-токенов
        // (в аль-Фатихе их нет). Для аятов со знаками — брать номера по разборАята (docs/дизайн/05 §2.2).
        { сура: ф.сура, аят: ф.аят, словоС: ф.слова.с, слов: ф.слова.по - ф.слова.с + 1 }
      : { сура: ф.сура, аят: ф.аят };
    return { эталон, текстПоказа: ф.текст };
  }
  return { эталон: { текст: читать.учебный }, текстПоказа: читать.учебный };
}

function видОшибкиСети(ошибка: unknown): 'нет-сети' | 'недоступно' {
  if (typeof navigator !== 'undefined' && navigator.onLine === false) return 'нет-сети';
  return (ошибка as { name?: string } | null)?.name === 'TypeError' ? 'нет-сети' : 'недоступно';
}

export async function проверитьЧтение(
  запись: Blob,
  эталон: ЭталонПроверки,
  виды?: readonly string[],
  опции: { сигнал?: AbortSignal; текстПоказа?: string | null; словаПоказа?: readonly string[] | null } = {},
): Promise<ИтогПроверки> {
  if (!проверкаГолосомВключена()) return { вид: 'ошибка', ошибка: 'недоступно' };
  const { сигнал } = опции;
  const текстПоказа = опции.текстПоказа !== undefined ? опции.текстПоказа : 'текст' in эталон ? эталон.текст : null;

  let wav: Blob;
  try {
    const готовый = await вWav16кГц(запись);
    if (готовый.длительностьСек > МАКС_СЕК_ПРОВЕРКИ) return { вид: 'плохой-звук', причина: 'длинно' };
    wav = готовый.wav;
  } catch {
    return { вид: 'ошибка', ошибка: 'запись' };
  }
  if (сигнал?.aborted) return { вид: 'ошибка', ошибка: 'отменено' };

  const форма = new FormData();
  форма.append('audio', wav, 'zapis.wav');
  for (const [имя, значение] of поляЭталона(эталон, виды)) форма.append(имя, значение);

  const управление = new AbortController();
  let вышлоВремя = false;
  const таймер = setTimeout(() => {
    вышлоВремя = true;
    управление.abort();
  }, ТАЙМАУТ_ПРОВЕРКИ_МС);
  const отменить = () => управление.abort();
  сигнал?.addEventListener('abort', отменить);
  try {
    const ответ = await fetch(АДРЕС_ПРОВЕРКИ, {
      method: 'POST',
      body: форма,
      signal: управление.signal,
      credentials: 'omit',
      cache: 'no-store',
      referrerPolicy: 'no-referrer',
    });
    if (ответ.status === 503) return { вид: 'ошибка', ошибка: 'занят' };
    if (ответ.status === 413) return { вид: 'ошибка', ошибка: 'большая' };
    if (ответ.status === 400) return { вид: 'ошибка', ошибка: 'запись' };
    if (!ответ.ok) return { вид: 'ошибка', ошибка: 'недоступно' };
    let данные: unknown;
    try {
      данные = await ответ.json();
    } catch {
      return { вид: 'ошибка', ошибка: 'недоступно' };
    }
    return разобратьОтвет(данные, текстПоказа, диапазонОтвета(эталон, опции.словаПоказа));
  } catch (е) {
    if (вышлоВремя) return { вид: 'ошибка', ошибка: 'таймаут' };
    if (сигнал?.aborted) return { вид: 'ошибка', ошибка: 'отменено' };
    return { вид: 'ошибка', ошибка: видОшибкиСети(е) };
  } finally {
    clearTimeout(таймер);
    сигнал?.removeEventListener('abort', отменить);
  }
}
