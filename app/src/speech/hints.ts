/** Подпись к выделенному на экране месту (видна под текстом и читается диктором): «Выделено: второй слог «إِ»». */
export function подписьПодсветки(з: Замечание, язык: ЯзыкПодсказок): string | null {
  if (!з.фрагмент) return null;
  if (язык === 'uz') {
    const уровень = з.уровень === 'подсказка' ? 'maslahat' : 'oʻzingizni tekshiring';
    if (з.слог && з.слогТекст) {
      const п = ПОРЯДКОВЫЕ_UZ[з.слог - 1];
      return `Belgilandi: ${п ? п + ' ' : ''}«${з.слогТекст}» boʻgʻini — ${уровень}`;
    }
    return `Belgilandi: «${з.фрагмент}» — ${уровень}`;
  }
  const kk = язык === 'kk';
  const уровень = з.уровень === 'подсказка' ? (kk ? 'кеңес' : 'подсказка') : kk ? 'өзіңізді тексеріңіз' : 'проверьте себя';
  if (з.слог && з.слогТекст) {
    const п = (kk ? ПОРЯДКОВЫЕ_KK : ИМЕНИТ_RU)[з.слог - 1];
    const что = kk ? `${п ? п + ' ' : ''}буын «${з.слогТекст}»` : `${п ? п + ' ' : ''}слог «${з.слогТекст}»`;
    return kk ? `Белгіленді: ${что} — ${уровень}` : `Выделено: ${что} — ${уровень}`;
  }
  return kk ? `Белгіленді: «${з.фрагмент}» — ${уровень}` : `Выделено: «${з.фрагмент}» — ${уровень}`;
}

