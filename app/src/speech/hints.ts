function ключШаблона(з: Замечание): string | null {
  if (з.код === 'C1.мунфасиль' && з.уровень === 'подсказка') return 'C1.мунфасиль/подсказка';
  if (з.код === 'C2') return 'C2';
  if (з.код.startsWith('C1') || (з.вид === 'мадд' && !з.код)) return 'мадд';
  if (з.код in ТЕЛА) return з.код;
  if (з.вид === 'огласовка') return 'B1';
  if (з.вид === 'буква') return 'A1';
  if (з.вид === 'калькаля') return 'F1';
  if (з.вид === 'гунна') return 'D2';
  if (з.вид === 'идгам') return 'E1';
  return null;
}

