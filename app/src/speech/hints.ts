/** 1 счёт, 2 счёта, 5 счётов (21 счёт, 12 счётов). */
export function счётаRu(n: number): string {
  const д = n % 100;
  const е = n % 10;
  if (д >= 11 && д <= 14) return `${n} счётов`;
  if (е === 1) return `${n} счёт`;
  if (е >= 2 && е <= 4) return `${n} счёта`;
  return `${n} счётов`;
}

