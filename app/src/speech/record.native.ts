import type * as Интерфейс from './record';
import type { СнимокЗаписи } from './record';

// Типы взяты из интерфейса — расхождение с record.ts ломает typecheck.
export const записьПоддерживается: typeof Интерфейс.записьПоддерживается = () => false;

export const создатьЗаписьГолоса: typeof Интерфейс.создатьЗаписьГолоса = () => {
  let снимок: СнимокЗаписи = { состояние: 'ожидание', ошибка: null, длительностьМс: 0, естьЗапись: false };
  const слушатели = new Set<(с: СнимокЗаписи) => void>();
  return {
    поддерживается: () => false,
    снимок: () => снимок,
    подписаться(слушатель) {
      слушатели.add(слушатель);
      return () => слушатели.delete(слушатель);
    },
    async начать() {
      снимок = { ...снимок, ошибка: 'не-поддерживается' };
      слушатели.forEach((с) => с(снимок));
    },
    остановить() {},
    async воспроизвести() {},
    остановитьВоспроизведение() {},
    удалить() {},
    данные: () => null,
    уровень: () => 0,
    освободить() {
      слушатели.clear();
    },
  };
};
