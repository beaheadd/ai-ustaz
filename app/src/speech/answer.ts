/**
 * Ответ речевого сервиса → итог проверки для экрана — ЧИСТЫЕ функции и типы (без импортов: тест в node,
 * scripts/test-speech.mjs).
 *
 * Сервис (speech/aiustaz_speech/app.py, POST /v1/proverka) отвечает:
 *   { статус: 'ок'|'плохой_звук', причина?, эталон:{текст, фонемы[, слово_с, слов]}, услышано:{фонемы, уверенность_ср},
 *     замечания:[{код, вид, уровень, позиция:[нач,кон], фрагмент, слово?, ожидалось, услышано, счёт_ожидался,
 *                 счёт_услышан, правила, уверенность}] }
 *   (слово — номер uthmani-слова с 1 по всему аяту; эталон.слово_с/слов — какие слова аята проверялись)
 *   С 20.11.2026 (владелец: «говорить, какая буква, где неправильно произнесли») у замечания ещё поля для шаблонов:
 *     повтор, повторы, повторов (учебный текст ×2/×3: эталон.текст — однократный, позиции — в нём), слог, слогов,
 *     слог_текст, слово_в_тексте, буква:{знак, id}, огласовка:{id, знак, шадда}, вставка, звук_ожидался, звук_услышан
 *     (описание звуков, speech/aiustaz_speech/describe.py). Всё проверяется здесь: незнакомое → null.
 *
 * Что делаем с ответом (CLAUDE.md, правила 1, 4, 7, 8):
 * - уровень только 'проверьте' или 'подсказка'; всё прочее (в т.ч. будущая «ошибка») → 'проверьте':
 *   на старте «Ошибку» не показываем никогда;
 * - фонемы (ожидалось/услышано, эталон.фонемы) НЕ передаём дальше: на экран они не попадают;
 * - фрагмент показываем, только если он ровно эталон.текст[нач:кон] ответа И дословно входит в текст,
 *   который ученик видит на экране (учебный слог/слово или аят из Tanzil). Иначе фрагмент = null —
 *   шаблон скажет «в одном месте». Так на экран не попадёт ни текст из чужой копии Корана, ни искажённый;
 * - АЯТ (опции.словаПоказа — слова копии Tanzil для показа без знаков, quran/text.ts): фрагмент сервиса (он из
 *   фонетической копии, с татвилем и малыми мимами) НЕ используется; слово подсказки — словаПоказа[слово − 1]
 *   дословно, только если номер слова целый и внутри проверенного диапазона [словоС, словоС + слов − 1];
 *   иначе слово = null и фрагмент = null («в одном месте»). Ответ «ок», где эталон.слово_с/слов не равны
 *   запрошенным (старый сервис не понял uthmani_from и проверил бы другую часть), → «недоступно»;
 * - «услышанное» (фонемы, ожидалось/услышано) на экран не попадает никогда: неверный вариант аята не показываем
 *   (правило 8) — в подсказке только слово эталона и счёта;
 * - не больше МАКС_ЗАМЕЧАНИЙ, по порядку в тексте (и по номеру чтения);
 * - поля для шаблонов (20.11.2026): буква — только из таблицы БУКВЫ (знак ↔ id content/letters.json), огласовка — только
 *   из ОГЛАСОВКИ, звуки — только знакомые виды; слог_текст — только если дословно есть в тексте на экране (учебный текст;
 *   для аята слог не показываем — там слово копии для показа). диапазон — где на экране подсветить: [нач, кон) в
 *   ТЕКСТЕ ПОКАЗА (учебный текст; позиции сервиса — в текстДляСервиса, переводим обратно по карте символов).
 *
 * Контракт: разобратьОтвет(данные: unknown, текстПоказа: string | null, опции?: ОпцииРазбора) → ИтогПроверки.
 */

export type УровеньЗамечания = 'проверьте' | 'подсказка';

/** Звук для описания (сервис: describe.звуки) — без арабского текста слов; буква — один знак из таблицы БУКВЫ. */
export type Звук =
  | { вид: 'гласный' | 'продление'; гласный: 'а' | 'и' | 'у'; счёт: number }
  | { вид: 'согласный'; буква: string; id: string; удвоен: boolean; калькаля: boolean }
  | { вид: 'гунна'; буква: string }
  | { вид: 'калькаля' | 'особый' };

export type Вставка = 'после_гласного' | 'после_согласного' | 'в_начале';

export type Замечание = {
  код: string;
  вид: string;
  уровень: УровеньЗамечания;
  /** Кусок эталона (учебный слог/слово или слово аята) — дословно из текста на экране, или null. */
  фрагмент: string | null;
  /** Номер uthmani-слова аята (с 1) — только при опции словаПоказа и внутри проверенного диапазона; иначе null. */
  слово: number | null;
  счётОжидался: number | null;
  счётУслышан: number | null;
  /** Учебный текст: номер слога (с 1) и сколько слогов в тексте; текст слога — дословно с экрана. Аят — null. */
  слог: number | null;
  слогов: number | null;
  слогТекст: string | null;
  /** Чтение ×2/×3: в каких чтениях (с 1) и сколько всего; одно чтение — null и 1. */
  повторы: number[] | null;
  повторов: number;
  буква: { знак: string; id: string } | null;
  огласовка: { id: string; шадда: boolean } | null;
  вставка: Вставка | null;
  звукОжидался: Звук[];
  звукУслышан: Звук[];
  /** Где подсветить на экране: [нач, кон) в тексте показа (учебный текст); аят — по слову, здесь null. */
  диапазон: [number, number] | null;
};

export type ПричинаПлохогоЗвука = 'коротко' | 'длинно' | 'тихо' | 'перегруз' | 'испорчено' | 'не_то' | 'другое';

export type ОшибкаПроверки =
  | 'нет-сети' // fetch не дошёл до сервера
  | 'занят' // 503: очередь сервиса полна
  | 'таймаут' // нет ответа за 20 с
  | 'запись' // браузер не смог подготовить запись (WAV) или сервер её не разобрал (400)
  | 'большая' // 413
  | 'недоступно' // другое: сервис не отвечает как надо, проверка выключена
  | 'отменено'; // ушли с упражнения — показывать нечего

export type ИтогПроверки =
  | { вид: 'ответ'; замечания: Замечание[] }
  | { вид: 'плохой-звук'; причина: ПричинаПлохогоЗвука }
  | { вид: 'ошибка'; ошибка: ОшибкаПроверки };

/** Для аята: слова копии для показа (словаПоказа[0] — слово 1) и проверенный диапазон uthmani-слов с 1. */
export type ОпцииРазбора = { словаПоказа: readonly string[]; словоС: number; слов: number };

export const МАКС_ЗАМЕЧАНИЙ = 3;
const МАКС_ДЛИНА_ФРАГМЕНТА = 40;

/** Знак буквы → id в content/letters.json (как БУКВЫ в speech/aiustaz_speech/describe.py; тест сверяет). */
export const БУКВЫ: Readonly<Record<string, string>> = {
  ء: 'hamza', أ: 'hamza', إ: 'hamza', ؤ: 'hamza', ئ: 'hamza',
  ا: 'alif', ب: 'ba', ت: 'ta', ث: 'tha', ج: 'jim', ح: 'hha', خ: 'kha', د: 'dal', ذ: 'dhal', ر: 'ra', ز: 'zay', س: 'sin',
  ش: 'shin', ص: 'sad', ض: 'dad', ط: 'tta', ظ: 'zza', ع: 'ain', غ: 'ghain', ف: 'fa', ق: 'qaf', ك: 'kaf', ل: 'lam', م: 'mim',
  ن: 'nun', ه: 'ha', و: 'waw', ي: 'ya',
};
/** id огласовок — как в content/harakat.json. */
export const ОГЛАСОВКИ: readonly string[] = ['fatha', 'kasra', 'damma', 'sukun', 'shadda', 'tanwin-fath', 'tanwin-kasr', 'tanwin-damm'];
const ГЛАСНЫЕ = ['а', 'и', 'у'];
const ВСТАВКИ: readonly Вставка[] = ['после_гласного', 'после_согласного', 'в_начале'];
const ПРИЧИНЫ: readonly ПричинаПлохогоЗвука[] = ['коротко', 'длинно', 'тихо', 'перегруз', 'испорчено', 'не_то'];

function число(x: unknown): number | null {
  return typeof x === 'number' && Number.isFinite(x) && x >= 0 && x < 100 ? Math.round(x) : null;
}

function строка(x: unknown): string {
  return typeof x === 'string' ? x : '';
}

function проверенныйФрагмент(з: Record<string, unknown>, текстЭталона: string, текстПоказа: string | null): string | null {
  if (!текстПоказа) return null;
  const фрагмент = строка(з['фрагмент']).trim();
  if (!фрагмент || фрагмент.length > МАКС_ДЛИНА_ФРАГМЕНТА) return null;
  const поз = з['позиция'];
  if (!Array.isArray(поз) || поз.length !== 2 || !поз.every((п) => Number.isInteger(п) && п >= 0)) return null;
  const [нач, кон] = поз as [number, number];
  if (кон <= нач || текстЭталона.slice(нач, кон).trim() !== фрагмент) return null;
  return текстПоказа.includes(фрагмент) ? фрагмент : null;
}

function словоАята(з: Record<string, unknown>, опции: ОпцииРазбора): number | null {
  const н = з['слово'];
  if (typeof н !== 'number' || !Number.isInteger(н)) return null;
  if (н < опции.словоС || н > опции.словоС + опции.слов - 1 || н > опции.словаПоказа.length) return null;
  return н;
}

function номер(x: unknown, макс = 999): number | null {
  return typeof x === 'number' && Number.isInteger(x) && x >= 1 && x <= макс ? x : null;
}

function буква(x: unknown): { знак: string; id: string } | null {
  if (!x || typeof x !== 'object') return null;
  const б = x as Record<string, unknown>;
  const знак = строка(б['знак']);
  return БУКВЫ[знак] && БУКВЫ[знак] === б['id'] ? { знак, id: БУКВЫ[знак] } : null;
}

function огласовка(x: unknown): { id: string; шадда: boolean } | null {
  if (!x || typeof x !== 'object') return null;
  const о = x as Record<string, unknown>;
  const id = строка(о['id']);
  return ОГЛАСОВКИ.includes(id) ? { id, шадда: о['шадда'] === true || id === 'shadda' } : null;
}

/** Звуки из ответа: только знакомые виды и значения; что-то не так — пустой список (шаблон скажет общими словами). */
function звуки(x: unknown): Звук[] {
  if (!Array.isArray(x) || x.length > 12) return [];
  const итог: Звук[] = [];
  for (const сырое of x) {
    if (!сырое || typeof сырое !== 'object') return [];
    const з = сырое as Record<string, unknown>;
    const вид = з['вид'];
    if (вид === 'гласный' || вид === 'продление') {
      const г = строка(з['гласный']);
      const счёт = номер(з['счёт'], 12);
      if (!ГЛАСНЫЕ.includes(г) || !счёт) return [];
      итог.push({ вид, гласный: г as 'а' | 'и' | 'у', счёт });
    } else if (вид === 'согласный') {
      const б = строка(з['буква']);
      if (!БУКВЫ[б] || БУКВЫ[б] !== з['id']) return [];
      итог.push({ вид, буква: б, id: БУКВЫ[б], удвоен: з['удвоен'] === true, калькаля: з['калькаля'] === true });
    } else if (вид === 'гунна') {
      const б = строка(з['буква']);
      if (б !== 'ن' && б !== 'م') return [];
      итог.push({ вид, буква: б });
    } else if (вид === 'калькаля' || вид === 'особый') {
      итог.push({ вид });
    } else return [];
  }
  return итог;
}

/** Текст для сервиса (fields.ts, текстДляСервиса) с картой: символ нормализованного текста → индекс в тексте показа. */
export function картаНормализации(текстПоказа: string): { текст: string; индексы: number[] } {
  let текст = '';
  const индексы: number[] = [];
  let пробел = false;
  for (let i = 0; i < текстПоказа.length; i++) {
    const с = текстПоказа[i];
    if (/[\s،,]/.test(с)) {
      пробел = текст.length > 0;
      continue;
    }
    if (пробел) {
      текст += ' ';
      индексы.push(i - 1);
      пробел = false;
    }
    текст += с;
    индексы.push(i);
  }
  return { текст, индексы };
}

/** [нач, кон) фрагмента в тексте показа: позиция сервиса — в нормализованном тексте; дословная сверка обоих. */
function диапазонПоказа(з: Record<string, unknown>, фрагмент: string, текстПоказа: string): [number, number] | null {
  const поз = з['позиция'];
  if (!Array.isArray(поз) || поз.length !== 2 || !поз.every((п) => Number.isInteger(п) && п >= 0)) return null;
  const { текст, индексы } = картаНормализации(текстПоказа);
  const [нач, кон] = поз as [number, number];
  if (кон > индексы.length || текст.slice(нач, кон) !== фрагмент) return null;
  const д: [number, number] = [индексы[нач], индексы[кон - 1] + 1];
  return текстПоказа.slice(д[0], д[1]) === фрагмент ? д : null;
}

export function разобратьОтвет(данные: unknown, текстПоказа: string | null, опции?: ОпцииРазбора): ИтогПроверки {
  if (!данные || typeof данные !== 'object') return { вид: 'ошибка', ошибка: 'недоступно' };
  const д = данные as Record<string, unknown>;
  if (д['статус'] === 'плохой_звук') {
    const п = строка(д['причина']) as ПричинаПлохогоЗвука;
    return { вид: 'плохой-звук', причина: ПРИЧИНЫ.includes(п) ? п : 'другое' };
  }
  if (д['статус'] !== 'ок' || !Array.isArray(д['замечания'])) return { вид: 'ошибка', ошибка: 'недоступно' };
  const эталон = (д['эталон'] && typeof д['эталон'] === 'object' ? д['эталон'] : {}) as Record<string, unknown>;
  const текстЭталона = строка(эталон['текст']);
  if (опции && (эталон['слово_с'] !== опции.словоС || эталон['слов'] !== опции.слов)) return { вид: 'ошибка', ошибка: 'недоступно' };
  const сПозицией: Array<[number, Замечание]> = [];
  for (const сырое of д['замечания'] as unknown[]) {
    if (!сырое || typeof сырое !== 'object') continue;
    const з = сырое as Record<string, unknown>;
    const код = строка(з['код']).slice(0, 32);
    const вид = строка(з['вид']).slice(0, 32);
    if (!код && !вид) continue;
    const слово = опции ? словоАята(з, опции) : null;
    const поз = Array.isArray(з['позиция']) && Number.isInteger(з['позиция'][0]) ? (з['позиция'][0] as number) : 1e9;
    const фрагмент = опции ? (слово ? опции.словаПоказа[слово - 1] : null) : проверенныйФрагмент(з, текстЭталона, текстПоказа);
    const повторов = номер(з['повторов'], 3) ?? 1;
    const повторы = Array.isArray(з['повторы'])
      ? [...new Set((з['повторы'] as unknown[]).filter((п): п is number => номер(п, повторов) !== null))].sort((а, б) => а - б)
      : номер(з['повтор'], повторов)
        ? [з['повтор'] as number]
        : [];
    // Слог — только для учебного текста и только дословно с экрана (для аята «слог» фонетической копии не показываем).
    const слогТекст = !опции && текстПоказа ? строка(з['слог_текст']).trim() : '';
    const слогЕсть = !!слогТекст && слогТекст.length <= МАКС_ДЛИНА_ФРАГМЕНТА && !!текстПоказа?.includes(слогТекст);
    const вставка = строка(з['вставка']) as Вставка;
    сПозицией.push([
      (повторы[0] ?? 1) * 1e6 + поз,
      {
        код,
        вид,
        уровень: з['уровень'] === 'подсказка' ? 'подсказка' : 'проверьте',
        фрагмент,
        слово,
        счётОжидался: число(з['счёт_ожидался']),
        счётУслышан: число(з['счёт_услышан']),
        слог: слогЕсть ? номер(з['слог']) : null,
        слогов: слогЕсть ? номер(з['слогов']) : null,
        слогТекст: слогЕсть ? слогТекст : null,
        повторы: повторов > 1 && повторы.length > 0 ? повторы : null,
        повторов,
        буква: буква(з['буква']),
        огласовка: огласовка(з['огласовка']),
        вставка: ВСТАВКИ.includes(вставка) ? вставка : null,
        звукОжидался: звуки(з['звук_ожидался']),
        звукУслышан: звуки(з['звук_услышан']),
        диапазон: !опции && фрагмент && текстПоказа ? диапазонПоказа(з, фрагмент, текстПоказа) : null,
      },
    ]);
  }
  сПозицией.sort((а, б) => а[0] - б[0]);
  return { вид: 'ответ', замечания: сПозицией.slice(0, МАКС_ЗАМЕЧАНИЙ).map(([, з]) => з) };
}
