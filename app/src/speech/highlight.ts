/**
 * Подсветка места подсказки в учебном тексте на экране — ЧИСТЫЕ функции (только `import type`: тест в node,
 * scripts/test-speech.mjs). Владелец 20.11.2026: «говорить, какая буква, где неправильно произнесли».
 *
 * Контракт:
 *   подсветкаИзИтога(итог) → МестоПодсветки[] — места замечаний с диапазоном в тексте показа (answer.ts, диапазон),
 *     одно место — один раз (уровень «проверьте» сильнее «подсказки»), не больше МАКС_ЗАМЕЧАНИЙ.
 *   разметкаПодсветки(текст, места) → Кусок[] — текст, разрезанный на куски; выделенный кусок — ЦЕЛОЕ слово
 *     (токен между пробелами и запятыми), в которое попадает место: внутри слова арабские буквы не разрываем
 *     (связность букв), а сам слог называет подсказка. Склейка кусков = текст дословно (ничего не меняем).
 * Правило 7: цвет подсказки (янтарь «проверьте себя», акцент «подсказка»), не красный; слов «ошибка» нет.
 */
import type { ИтогПроверки, УровеньЗамечания, Замечание } from './answer';

export type МестоПодсветки = { нач: number; кон: number; уровень: УровеньЗамечания; замечание: Замечание };
export type Кусок = { текст: string; уровень: УровеньЗамечания | null; место: МестоПодсветки | null };

const ГРАНИЦА = /[\s،,]/;

export function подсветкаИзИтога(итог: ИтогПроверки | null): МестоПодсветки[] {
  if (!итог || итог.вид !== 'ответ') return [];
  const места: МестоПодсветки[] = [];
  for (const з of итог.замечания) {
    if (!з.диапазон) continue;
    const [нач, кон] = з.диапазон;
    const было = места.find((м) => м.нач === нач && м.кон === кон);
    if (было) {
      if (з.уровень === 'проверьте') было.уровень = 'проверьте';
      continue;
    }
    места.push({ нач, кон, уровень: з.уровень, замечание: з });
  }
  return места;
}

export function разметкаПодсветки(текст: string, места: readonly МестоПодсветки[]): Кусок[] {
  // Расширяем каждое место до целых слов; пересекающиеся — сливаем («проверьте» сильнее).
  const отрезки: Array<{ нач: number; кон: number; уровень: УровеньЗамечания; место: МестоПодсветки }> = [];
  for (const м of места) {
    if (!(м.нач >= 0 && м.кон > м.нач && м.кон <= текст.length)) continue;
    let нач = м.нач;
    let кон = м.кон;
    while (нач > 0 && !ГРАНИЦА.test(текст[нач - 1])) нач--;
    while (кон < текст.length && !ГРАНИЦА.test(текст[кон])) кон++;
    const пересёк = отрезки.find((о) => нач < о.кон && о.нач < кон);
    if (пересёк) {
      пересёк.нач = Math.min(пересёк.нач, нач);
      пересёк.кон = Math.max(пересёк.кон, кон);
      if (м.уровень === 'проверьте') пересёк.уровень = 'проверьте';
    } else отрезки.push({ нач, кон, уровень: м.уровень, место: м });
  }
  отрезки.sort((а, б) => а.нач - б.нач);
  const куски: Кусок[] = [];
  let п = 0;
  for (const о of отрезки) {
    if (о.нач > п) куски.push({ текст: текст.slice(п, о.нач), уровень: null, место: null });
    куски.push({ текст: текст.slice(о.нач, о.кон), уровень: о.уровень, место: о.место });
    п = о.кон;
  }
  if (п < текст.length || куски.length === 0) куски.push({ текст: текст.slice(п), уровень: null, место: null });
  return куски;
}
