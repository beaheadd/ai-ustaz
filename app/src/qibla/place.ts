/**
 * Место для киблы: тот же город, что у времени намаза (координаты и магнитное склонение).
 *
 * Контракт:
 *   МестоКиблы — { id, вид, ru, kk, широта, долгота, склонение } — подмножество prayer/places.ts «Место»
 *     (вид: 'место' — город из списка, кибла от его центра; 'точка' — своя точка по геолокации, ≈ 1 км)
 *     (список мест РК places-kz.json; склонение — WMM2025, ° к востоку).
 *   useМестоКиблы() → МестоКиблы — выбранное место из хранилища выбора города (prayer/store.ts,
 *     useМестоНамаза; хранится только на устройстве), по умолчанию — Астана. Экран киблы читает место
 *     только через этот хук; сменить город — экран 'городНамаза' (#/prayer-city).
 * Кибла и склонение — по центру выбранного места (сдвиг на 50 км меняет киблу на ~0,5°, компас телефона
 * ошибается на ±5–15°). Своя точка по геолокации — координаты, округлённые до ≈ 1 км (prayer/places.ts).
 */
import { useМестоНамаза } from '../prayer/store';

export type МестоКиблы = {
  id: string;
  /** 'место' — город из списка (кибла от центра города); 'точка' — своя точка по геолокации (≈ 1 км). */
  вид: 'место' | 'точка';
  ru: string;
  /** kk — черновик для редактора-носителя. */
  kk: string;
  широта: number;
  долгота: number;
  /** Магнитное склонение, ° к востоку (плюс). */
  склонение: number;
};

export function useМестоКиблы(): МестоКиблы {
  return useМестоНамаза().место;
}
