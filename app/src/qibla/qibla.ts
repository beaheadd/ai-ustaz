/** Окно браузера — только то, что читают функции кибли (тестам хватает простого объекта). */
export type ОкноОриентации = {
  screen?: { orientation?: { angle?: number } };
  orientation?: number | string;
};

/** Поворот экрана: screen.orientation.angle (Chrome, Safari 16.4+), иначе window.orientation (старый iOS), иначе 0. */
export function уголЭкрана(окно?: ОкноОриентации | null): number {
  const а = окно?.screen?.orientation?.angle;
  if (typeof а === 'number') return норм360(а);
  const о = окно?.orientation;
  return typeof о === 'number' ? норм360(о) : 0;
}

/** Матрица поворота устройство → Земля (x — восток, y — север, z — вверх) по углам W3C (Z-X'-Y''). Строки подряд. */
export function матрицаИзУглов(alpha: number, beta: number, gamma: number): number[] {
  const cA = Math.cos(рад(alpha));
  const sA = Math.sin(рад(alpha));
  const cB = Math.cos(рад(beta));
  const sB = Math.sin(рад(beta));
  const cG = Math.cos(рад(gamma));
  const sG = Math.sin(рад(gamma));
  return [
    cA * cG - sA * sB * sG, -sA * cB, cA * sG + sA * sB * cG,
    sA * cG + cA * sB * sG, cA * cB, sA * sG - cA * sB * cG,
    -cB * sG, sB, cB * cG,
  ];
}

/** Поля события ориентации, которые мы читаем (DeviceOrientationEvent + iOS webkitCompass*). */
export type СобытиеОриентации = {
  alpha?: number | null;
  beta?: number | null;
  gamma?: number | null;
  absolute?: boolean;
  webkitCompassHeading?: number;
  webkitCompassAccuracy?: number;
};

export type ИсточникКурса = 'ios' | 'android';
export type КурсТелефона = { курс: number; точность: number | null; источник: ИсточникКурса; вертикально: boolean };

/**
 * Курс верха экрана (магнитный) из события ориентации.
 * - iOS: webkitCompassHeading — курс верха устройства в портретной ориентации (по часовой), + поворот экрана;
 *   webkitCompassAccuracy < 0 — не откалиброван (точность null).
 * - Android (deviceorientationabsolute или deviceorientation с absolute === true): по полной матрице —
 *   верно при любом наклоне; если верх экрана смотрит почти вертикально (телефон стоит) — направление
 *   задней камеры и флаг «вертикально».
 * - Иначе (относительная ориентация Chrome, нет данных) — null: это не компас.
 */
export function курсИзСобытия(е: СобытиеОриентации | null | undefined, уголЭкранаГрад = 0): КурсТелефона | null {
  if (!е) return null;
  if (typeof е.webkitCompassHeading === 'number' && !Number.isNaN(е.webkitCompassHeading)) {
    const точность = typeof е.webkitCompassAccuracy === 'number' && е.webkitCompassAccuracy >= 0 ? е.webkitCompassAccuracy : null;
    return { курс: норм360(е.webkitCompassHeading + уголЭкранаГрад), точность, источник: 'ios', вертикально: Math.abs(е.beta ?? 0) > 60 };
  }
  if (е.absolute !== true || е.alpha == null || Number.isNaN(е.alpha)) return null;
  const R = матрицаИзУглов(е.alpha, е.beta ?? 0, е.gamma ?? 0);
  const θ = рад(уголЭкранаГрад);
  const u = [Math.sin(θ), Math.cos(θ)]; // верх экрана в осях устройства
  const восток = R[0] * u[0] + R[1] * u[1];
  const север = R[3] * u[0] + R[4] * u[1];
  if (Math.hypot(восток, север) > 0.5) {
    return { курс: норм360(град(Math.atan2(восток, север))), точность: null, источник: 'android', вертикально: false };
  }
  // телефон стоит: направление задней камеры (−z устройства)
  return { курс: норм360(град(Math.atan2(-R[2], -R[5]))), точность: null, источник: 'android', вертикально: true };
}

export const истинныйКурс = (магнитный: number, склонение: number) => норм360(магнитный + склонение);
export const уголСтрелки = (кибла: number, курсИстинный: number) => норм360(кибла - курсИстинный);

export type Поворот = { градусы: number; сторона: 'вправо' | 'влево' | 'прямо' };

/** На сколько и куда повернуться, чтобы с направления «от» встать на «к» (по часовой — вправо). */
export function поворот(от: number, к: number): Поворот {
  const р = норм180(к - от);
  const градусы = Math.round(Math.abs(р));
  return { градусы, сторона: градусы === 0 ? 'прямо' : р > 0 ? 'вправо' : 'влево' };
}

export function совпадает(кибла: number, курсИстинный: number): boolean {
  return Math.abs(норм180(кибла - курсИстинный)) <= ПОРОГ_СОВПАДЕНИЯ;
}

/** Опора для схемы без компаса: юг (его показывает солнце в истинный полдень), если кибла южнее линии восток–запад. */
export function опораДляПоворота(кибла: number): 0 | 180 {
  const к = норм360(кибла);
  return к > 90 && к < 270 ? 180 : 0;
}

export type Сглаживатель = { добавить: (курс: number) => number; разброс: () => number };

/** Сглаживание курса по единичному вектору (без скачка 359° → 0°) и разброс последних значений. */
export function новыйСглаживатель(доля = 0.25, окно = 20): Сглаживатель {
  let x: number | null = null;
  let y = 0;
  const последние: number[] = [];
  return {
    добавить(курс) {
      const cx = Math.cos(рад(курс));
      const cy = Math.sin(рад(курс));
      if (x === null) {
        x = cx;
        y = cy;
      } else {
        x += доля * (cx - x);
        y += доля * (cy - y);
      }
      последние.push(курс);
      if (последние.length > окно) последние.shift();
      return норм360(град(Math.atan2(y, x)));
    },
    разброс() {
      if (последние.length < 2) return 0;
      let sx = 0;
      let sy = 0;
      for (const к of последние) {
        sx += Math.cos(рад(к));
        sy += Math.sin(рад(к));
      }
      const R = Math.min(1, Math.hypot(sx, sy) / последние.length);
      return град(Math.sqrt(-2 * Math.log(Math.max(R, 1e-12)))); // круговое СКО
    },
  };
}

export type ПоложениеСолнца = { азимут: number; высота: number; склонениеСолнца: number; подсолнечнаяДолгота: number };

/** Склонение солнца (°) и уравнение времени (мин) на момент — уравнения NOAA General Solar Position. */
function координатыСолнца(момент: Date): { δ: number; уравнениеВремени: number } {
  const jd = момент.getTime() / 86400000 + 2440587.5;
  const T = (jd - 2451545) / 36525;
  const L0 = норм360(280.46646 + T * (36000.76983 + 0.0003032 * T));
  const M = 357.52911 + T * (35999.05029 - 0.0001537 * T);
  const e = 0.016708634 - T * (0.000042037 + 0.0000001267 * T);
  const C =
    Math.sin(рад(M)) * (1.914602 - T * (0.004817 + 0.000014 * T)) + Math.sin(рад(2 * M)) * (0.019993 - 0.000101 * T) + Math.sin(рад(3 * M)) * 0.000289;
  const Ω = 125.04 - 1934.136 * T;
  const λ = L0 + C - 0.00569 - 0.00478 * Math.sin(рад(Ω));
  const ε0 = 23 + (26 + (21.448 - T * (46.815 + T * (0.00059 - T * 0.001813))) / 60) / 60;
  const ε = ε0 + 0.00256 * Math.cos(рад(Ω));
  const δ = град(Math.asin(Math.sin(рад(ε)) * Math.sin(рад(λ))));
  const yy = Math.tan(рад(ε / 2)) ** 2;
  const уравнениеВремени =
    4 *
    град(
      yy * Math.sin(2 * рад(L0)) -
        2 * e * Math.sin(рад(M)) +
        4 * e * yy * Math.sin(рад(M)) * Math.cos(2 * рад(L0)) -
        0.5 * yy * yy * Math.sin(4 * рад(L0)) -
        1.25 * e * e * Math.sin(2 * рад(M)),
    );
  return { δ, уравнениеВремени };
}

/** Положение солнца (NOAA General Solar Position). Азимут — от севера по часовой. Без рефракции. */
export function положениеСолнца(широта: number, долгота: number, момент: Date): ПоложениеСолнца {
  const { δ, уравнениеВремени } = координатыСолнца(момент);
  const минутUTC = (((момент.getTime() % 86400000) + 86400000) % 86400000) / 60000;
  const H = (минутUTC + уравнениеВремени + 4 * долгота) / 4 - 180; // часовой угол, °
  const φ = рад(широта);
  const cosZ = Math.sin(φ) * Math.sin(рад(δ)) + Math.cos(φ) * Math.cos(рад(δ)) * Math.cos(рад(H));
  const z = Math.acos(Math.max(-1, Math.min(1, cosZ)));
  const аз = град(Math.atan2(Math.sin(рад(H)), Math.cos(рад(H)) * Math.sin(φ) - Math.tan(рад(δ)) * Math.cos(φ))) + 180;
  return { азимут: норм360(аз), высота: 90 - град(z), склонениеСолнца: δ, подсолнечнаяДолгота: норм180(-(минутUTC + уравнениеВремени) / 4 + 180) };
}

/** День по времени РК (UTC+5): 'ГГГГ-ММ-ДД'. */
export function деньРК(момент: Date): string {
  return new Date(момент.getTime() + СДВИГ_РК_МС).toISOString().slice(0, 10);
}

/** Время по РК: '14:18' (24 ч, секунды отброшены). */
export function чч_ммРК(момент: Date): string {
  return new Date(момент.getTime() + СДВИГ_РК_МС).toISOString().slice(11, 16);
}

/**
 * Истинный полдень дня РК в точке: солнце точно на юге (азимут 180°; в РК широта > 23,4° — всегда юг).
 * Часовой угол H = (минутUTC + УВ + 4·долгота)/4 − 180 = 0 ⇒ минутUTC = 720 − 4·долгота − УВ;
 * две итерации по уравнению времени — точность лучше секунды. Широта на полдень не влияет (параметр — для единообразия).
 */
export function истинныйПолдень(широта: number, долгота: number, деньРК: string): Date {
  const [г, м, ч] = деньРК.split('-').map(Number);
  const полночьUTC = Date.UTC(г, м - 1, ч); // в РК (UTC+5) полдень всегда в ту же дату UTC
  let t = полночьUTC + (720 - 4 * долгота) * 60000;
  for (let i = 0; i < 2; i++) t = полночьUTC + (720 - 4 * долгота - координатыСолнца(new Date(t)).уравнениеВремени) * 60000;
  return new Date(Math.round(t / 1000) * 1000);
}

/**
 * Момент после истинного полудня, когда азимут солнца равен кибле (в РК кибла 200–250°, солнце туда
 * приходит после полудня). null — если солнце садится раньше (зимой на севере) или кибла не к югу.
 * Возвращает и высоту солнца в этот момент: экран показывает подсказку, только если солнце видно (≥ 5°).
 */
export function солнцеВСторонеКиблы(широта: number, долгота: number, кибла: number, деньРК: string): { момент: Date; высота: number } | null {
  const к = норм360(кибла);
  if (к <= 180 || к >= 360) return null;
  const полдень = истинныйПолдень(широта, долгота, деньРК).getTime();
  // после полудня азимут растёт монотонно от 180° — перебор по минутам до заката (не дольше 10 ч)
  let прежний = полдень;
  for (let t = полдень + 60000; t <= полдень + 10 * 3600_000; t += 60000) {
    const п = положениеСолнца(широта, долгота, new Date(t));
    if (п.высота < -1) return null;
    if (п.азимут >= к) {
      const до = положениеСолнца(широта, долгота, new Date(прежний)).азимут;
      const доля = п.азимут === до ? 0 : (к - до) / (п.азимут - до);
      const момент = new Date(Math.round((прежний + доля * (t - прежний)) / 60000) * 60000);
      return { момент, высота: положениеСолнца(широта, долгота, момент).высота };
    }
    прежний = t;
  }
  return null;
}

/**
 * «Солнце над Каабой»: подсолнечная точка ближе всего к Каабе (≈ 28.05 и 15/16.07). В эти минуты тень
 * вертикального предмета везде, где видно солнце, указывает ПРОТИВ киблы. Перебор по минутам в окнах ±3 дня.
 */
export function солнцеНадКаабой(год: number): Date[] {
  const итог: Date[] = [];
  for (const [месяц, число] of [[4, 28], [6, 16]] as const) {
    let лучший: { момент: number; угол: number } | null = null;
    for (let t = Date.UTC(год, месяц, число - 3); t <= Date.UTC(год, месяц, число + 3); t += 60_000) {
      const { склонениеСолнца, подсолнечнаяДолгота } = положениеСолнца(0, 0, new Date(t));
      const dφ = рад(склонениеСолнца - КААБА.широта);
      const dλ = рад(подсолнечнаяДолгота - КААБА.долгота);
      const a = Math.sin(dφ / 2) ** 2 + Math.cos(рад(склонениеСолнца)) * Math.cos(рад(КААБА.широта)) * Math.sin(dλ / 2) ** 2;
      const угол = 2 * Math.asin(Math.sqrt(a));
      if (!лучший || угол < лучший.угол) лучший = { момент: t, угол };
    }
    if (лучший) итог.push(new Date(лучший.момент));
  }
  return итог;
}

/** Ближайшее «солнце над Каабой» в пределах «дней» суток от момента (включая сегодня), иначе null. Считает только у дат. */
export function ближайшееСолнцеНадКаабой(момент: Date, дней = 7): Date | null {
  const год = Number(деньРК(момент).slice(0, 4));
  const сейчас = момент.getTime();
  const окно = (дней + 4) * 86400_000; // грубый фильтр по датам, чтобы не считать перебор зря
  const грубые = [Date.UTC(год, 4, 28, 9), Date.UTC(год, 6, 16, 9)];
  if (!грубые.some((t) => t - сейчас < окно && t - сейчас > -2 * 86400_000)) return null;
  for (const t of солнцеНадКаабой(год)) {
    const до = t.getTime() - сейчас;
    if (до >= 0 && до <= дней * 86400_000) return t;
  }
  return null;
}
