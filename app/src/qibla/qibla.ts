/**
 * Кибла: чистые функции — направление на Каабу, курс телефона из события ориентации, склонение,
 * сглаживание, положение солнца и ориентиры без компаса. Без импортов: node ≥ 22.18 снимает типы сам
 * (тест — scripts/test-qibla.mjs, npm run test:qibla).
 *
 * Контракт:
 *   КААБА                                   { широта: 21.422487, долгота: 39.826206 }
 *   направлениеКиблы(ш, д)                  → ° [0, 360) по часовой от ИСТИННОГО севера (начальный азимут большого круга)
 *   расстояниеДоКаабыКм(ш, д)               → км по большому кругу (R = 6371,0088)
 *   румб(°, язык)                           → 'юго-запад' / 'оңтүстік-батыс' / 'janubi-gʻarb' / 'southwest' (16 румбов; kk, uz, en — черновики)
 *   уголЭкрана(окно)                        → поворот экрана 0 | 90 | 180 | 270
 *   курсИзСобытия(событие, уголЭкрана)      → { курс (МАГНИТНЫЙ), точность (° | null), источник, вертикально } | null
 *   истинныйКурс(магнитный, склонение)      → магнитный + склонение (к востоку — плюс)
 *   уголСтрелки(кибла, курсИстинный)        → на сколько ° по часовой от верха экрана указывает кибла
 *   поворот(от, к)                          → { градусы (0..180, целые), сторона: 'вправо' | 'влево' | 'прямо' }
 *   совпадает(кибла, курс)                  → |отклонение| ≤ ПОРОГ_СОВПАДЕНИЯ (5°)
 *   новыйСглаживатель(доля, окно)           → { добавить(курс) → сглаженный, разброс() → ° (круговое СКО) }
 *   положениеСолнца(ш, д, момент)           → { азимут, высота } (°; NOAA, ~0,1°)
 *   истинныйПолдень(ш, д, деньРК)           → момент, когда солнце точно на юге (азимут 180° — в РК всегда)
 *   солнцеВСторонеКиблы(ш, д, кибла, деньРК) → момент после полудня, когда азимут солнца = кибла | null
 *   солнцеНадКаабой(год)                    → два момента (≈ 28.05 и 15/16.07), когда солнце в зените над Каабой
 *   ближайшееСолнцеНадКаабой(момент, дней)  → такой момент в ближайшие «дней» суток | null
 *   опораДляПоворота(кибла)                 → 180 (юг) для киблы на юг от линии восток–запад, иначе 0 (север)
 *   чч_ммРК(момент), деньРК(момент)         → '14:18', '2026-05-28' по времени РК (UTC+5)
 *
 * Решения (19.11.2026, исследование prayer-proto/README.md §4–5):
 * - кибла — по большому кругу (как Qibla() в adhan-js; от эллипсоида WGS84 отличается на ~0,1°, а компас
 *   телефона ошибается на ±5–15°): Алматы 246,7°, Астана 231,5°;
 * - компас в браузере даёт МАГНИТНЫЙ курс и на iOS (WebKit: magneticHeading), и на Android
 *   (deviceorientationabsolute) — склонение места прибавляем всегда (в РК +4…+13°, WMM2025);
 * - курс верха экрана — по полной матрице поворота W3C (Z-X'-Y''), а не 360 − alpha: верен при наклоне;
 * - про «допустимое отклонение» и действительность намаза ничего не пишем — это фикх (к имаму).
 * Только расчёт: ничего не отправляет и не хранит.
 */

export const КААБА = { широта: 21.422487, долгота: 39.826206 } as const;
/** Совпадение стрелки с верхом экрана, ° (бриф §6.3): подсветка без звука и вибрации. */
export const ПОРОГ_СОВПАДЕНИЯ = 5;
/** Пояс РК — UTC+5 (вся страна с 01.03.2024). */
const СДВИГ_РК_МС = 5 * 3600_000;

const рад = (г: number) => (г * Math.PI) / 180;
const град = (р: number) => (р * 180) / Math.PI;
export const норм360 = (г: number) => ((г % 360) + 360) % 360;
export const норм180 = (г: number) => {
  const x = норм360(г);
  return x > 180 ? x - 360 : x;
};

/** Начальный азимут большого круга на Каабу, ° от истинного севера по часовой. */
export function направлениеКиблы(широта: number, долгота: number): number {
  const φ1 = рад(широта);
  const φ2 = рад(КААБА.широта);
  const Δλ = рад(КААБА.долгота - долгота);
  const y = Math.sin(Δλ) * Math.cos(φ2);
  const x = Math.cos(φ1) * Math.sin(φ2) - Math.sin(φ1) * Math.cos(φ2) * Math.cos(Δλ);
  return норм360(град(Math.atan2(y, x)));
}

/** Расстояние по большому кругу (гаверсинус), км. */
export function расстояниеДоКаабыКм(широта: number, долгота: number): number {
  const φ1 = рад(широта);
  const φ2 = рад(КААБА.широта);
  const Δφ = φ2 - φ1;
  const Δλ = рад(КААБА.долгота - долгота);
  const a = Math.sin(Δφ / 2) ** 2 + Math.cos(φ1) * Math.cos(φ2) * Math.sin(Δλ / 2) ** 2;
  return 2 * 6371.0088 * Math.asin(Math.min(1, Math.sqrt(a)));
}

