/**
 * Хук компаса для экрана киблы: состояние датчика и курс (истинный, со склонением), без лишних перерисовок.
 *
 * Контракт:
 *   const { состояние, включить } = useКомпас(склонение);
 *   состояние.вид:
 *     'нужно-разрешение' — сенсорный экран и есть requestPermission (iOS 13+, новые Chrome): кнопка «Включить
 *                          компас»; включить() — ПРЯМО в приНажатии (iOS иначе отказывает молча);
 *     'ищем'             — слушаем, ждём первый абсолютный курс (до 3 с);
 *     'есть'             — { курс (истинный, °), точность (° на iOS | null), разброс (°), вертикально, источник };
 *     'нет'              — компаса нет (ноутбук, нет событий, нативная сборка) — экран показывает схему;
 *     'отказ'            — доступ не дан (Safari помнит отказ до перезагрузки страницы).
 * Слушаем сразу, ещё до нажатия: где разрешение не нужно (Android Chrome), курс приходит сам и кнопка исчезает;
 * на iOS события до разрешения не приходят — кнопка остаётся. Подписка — только пока экран открыт и вкладка
 * видна (visibilitychange); уход с экрана отписывает. Перерисовка — не чаще кадра (requestAnimationFrame) и только
 * когда видимое изменилось: курс округляется до 1°, точность и разброс — до 5°; если округлённое состояние то же,
 * объект не меняется и React не перерисовывает экран (неподвижный телефон — 0–2 перерисовки в секунду, а не 60).
 * Без звука и вибрации. Ничего не сохраняет и не отправляет.
 */
import { useCallback, useEffect, useState } from 'react';
import { Platform } from 'react-native';
import { естьСобытияОриентации, запроситьДоступКомпаса, нуженЗапросРазрешения, слушатьКомпас, type ДанныеКомпаса, type ОкноКомпаса } from './compass';
import type { ИсточникКурса } from './qibla';

export type СостояниеКомпаса =
  | { вид: 'нужно-разрешение' }
  | { вид: 'ищем' }
  | { вид: 'есть'; курс: number; точность: number | null; разброс: number; вертикально: boolean; источник: ИсточникКурса }
  | { вид: 'нет' }
  | { вид: 'отказ' };

function окноБраузера(): ОкноКомпаса | null {
  if (Platform.OS !== 'web' || typeof window === 'undefined') return null;
  return window as unknown as ОкноКомпаса;
}

/** Округлить то, что видно на экране: курс — до 1°, точность и разброс — до 5°. Чистая функция. */
export function округлитьКомпас(д: { курсИстинный: number; точность: number | null; разброс: number; вертикально: boolean; источник: ИсточникКурса }): СостояниеКомпаса {
  return {
    вид: 'есть',
    курс: Math.round(д.курсИстинный) % 360,
    точность: д.точность === null ? null : Math.round(д.точность / 5) * 5,
    разброс: Math.round(д.разброс / 5) * 5,
    вертикально: д.вертикально,
    источник: д.источник,
  };
}

/** То же видимое состояние — тот же объект (без перерисовки). */
function одинаково(а: СостояниеКомпаса, б: СостояниеКомпаса): boolean {
  if (а.вид !== 'есть' || б.вид !== 'есть') return а.вид === б.вид && а.вид !== 'есть';
  return а.курс === б.курс && а.точность === б.точность && а.разброс === б.разброс && а.вертикально === б.вертикально && а.источник === б.источник;
}

function начальное(): СостояниеКомпаса {
  const окно = окноБраузера();
  if (!окно || !естьСобытияОриентации(окно)) return { вид: 'нет' };
  return нуженЗапросРазрешения(окно) ? { вид: 'нужно-разрешение' } : { вид: 'ищем' };
}

export function useКомпас(склонение: number): { состояние: СостояниеКомпаса; включить: () => void } {
  const [состояние, установить] = useState<СостояниеКомпаса>(начальное);
  /** Номер подписки: после разрешения подписываемся заново (новый таймаут «компаса нет»). */
  const [попытка, установитьПопытку] = useState(0);
  const [видно, установитьВидно] = useState(true);

  useEffect(() => {
    if (typeof document === 'undefined') return;
    const обновить = () => установитьВидно(document.visibilityState !== 'hidden');
    обновить();
    document.addEventListener('visibilitychange', обновить);
    return () => document.removeEventListener('visibilitychange', обновить);
  }, []);

  useEffect(() => {
    const окно = окноБраузера();
    if (!окно || !естьСобытияОриентации(окно) || !видно) return;
    let кадр: number | null = null;
    let последнее: ДанныеКомпаса | null = null;
    const применить = () => {
      кадр = null;
      const д = последнее;
      if (!д) return;
      if (д.состояние === 'нет-компаса') {
        // кнопку разрешения не прячем: на iOS курс придёт только после нажатия
        установить((с) => (с.вид === 'ищем' ? { вид: 'нет' } : с));
        return;
      }
      const новое = округлитьКомпас(д);
      установить((с) => (одинаково(с, новое) ? с : новое));
    };
    const стоп = слушатьКомпас(
      окно,
      (д) => {
        последнее = д;
        if (кадр === null) кадр = requestAnimationFrame(применить);
      },
      { склонение },
    );
    return () => {
      стоп();
      if (кадр !== null) cancelAnimationFrame(кадр);
    };
  }, [видно, склонение, попытка]);

  const включить = useCallback(() => {
    // requestPermission вызывается синхронно внутри нажатия (до первого await) — иначе iOS откажет молча
    void запроситьДоступКомпаса(окноБраузера()).then((итог) => {
      if (итог === 'разрешено') {
        установить((с) => (с.вид === 'есть' ? с : { вид: 'ищем' }));
        установитьПопытку((п) => п + 1);
      } else {
        установить({ вид: итог === 'отказ' ? 'отказ' : 'нет' });
      }
    });
  }, []);

  return { состояние, включить };
}
