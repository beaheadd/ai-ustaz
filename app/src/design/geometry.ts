/**
 * Геометрия дизайн-системы AI Ustaz — чистые функции и данные (SVG), без импортов.
 *
 * Назначение: форма арки михраба и плитки орнамента — для компонентов (react-native-svg) и витрины ds.html.
 * Контракт:
 *   путьАрки(ширина, высота, подъём, радиусНиза): d — замкнутый контур карточки со стрельчатым
 *     (килевидным) верхом: боковые стороны, скруглённые «плечи», к середине — пологий подъём и острая вершина;
 *     подъём — высота вершины над плечами (бриф §2.3: 20–24 px для карточек, до ~40 для «героя»).
 *   путьЗвезды(cx, cy, R): d — восьмиконечная звезда хатам из двух квадратов (контур, без круга в центре).
 *   ПЛИТКИ: { хатам, гирих, решётка } — плитка узора { размер, d } (только линии), ПОЛОСА — полоса-разделитель.
 * Правила (бриф §2.2–2.5): узор — тонкие линии 4–6 % непрозрачности, только по краям и пустым местам,
 * не под временем намаза, мелким текстом и арабским текстом; без надписей и без текста Корана.
 */

const к = (ч: number) => Math.round(ч * 100) / 100;

/**
 * Контур карточки-арки. Начало — левый нижний угол, по часовой стрелке.
 * Плечо: от вертикали (0, подъём) к точке (0,1·ш; 0,3·подъёма); дальше пологая дуга к вершине (ш/2, 0),
 * у вершины чуть вогнутая — «килевидная» острая вершина.
 */
export function путьАрки(ширина: number, высота: number, подъём: number, радиусНиза = 18): string {
  const ш = Math.max(ширина, 1);
  const в = Math.max(высота, подъём + 1);
  const п = Math.max(0, Math.min(подъём, в - 1));
  const р = Math.max(0, Math.min(радиусНиза, (в - п) / 2, ш / 2));
  const плечоX = Math.min(ш * 0.1, 36);
  const плечоY = п * 0.3;
  const с = ш / 2;
  const части = [
    `M0 ${к(в - р)}`,
    `V${к(п)}`,
    // плечо: от вертикали к пологому подъёму
    `C0 ${к(п * 0.55)} ${к(плечоX * 0.35)} ${к(плечоY + (п - плечоY) * 0.2)} ${к(плечоX)} ${к(плечоY)}`,
    // к вершине: сначала полого, у вершины круче (острая вершина)
    `C${к(с * 0.55)} ${к(плечоY * 0.62)} ${к(с * 0.86)} ${к(плечоY * 0.4)} ${к(с)} 0`,
    `C${к(ш - с * 0.86)} ${к(плечоY * 0.4)} ${к(ш - с * 0.55)} ${к(плечоY * 0.62)} ${к(ш - плечоX)} ${к(плечоY)}`,
    `C${к(ш - плечоX * 0.35)} ${к(плечоY + (п - плечоY) * 0.2)} ${к(ш)} ${к(п * 0.55)} ${к(ш)} ${к(п)}`,
    `V${к(в - р)}`,
    р > 0 ? `A${к(р)} ${к(р)} 0 0 1 ${к(ш - р)} ${к(в)}` : '',
    `H${к(р)}`,
    р > 0 ? `A${к(р)} ${к(р)} 0 0 1 0 ${к(в - р)}` : '',
    'Z',
  ];
  return части.filter(Boolean).join('');
}

/** Восьмиконечная звезда хатам (два квадрата), контур из 16 вершин. R — радиус вершин. */
export function путьЗвезды(cx: number, cy: number, R: number): string {
  const а = R / Math.SQRT2; // полусторона квадрата
  const и = R - а; // «внутренний» выступ на стороне квадрата
  const точки: [number, number][] = [
    [R, 0], [а, и], [а, а], [и, а], [0, R], [-и, а], [-а, а], [-а, и],
    [-R, 0], [-а, -и], [-а, -а], [-и, -а], [0, -R], [и, -а], [а, -а], [а, -и],
  ];
  return точки.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${к(cx + x)} ${к(cy + y)}`).join('') + 'Z';
}

export type Плитка = { размер: number; d: string };

/** Восьмиугольник в плитке s×s (усечённая квадратная мозаика: восьмиугольники и ромбы между ними). */
function восьмиугольник(s: number): string {
  const т = s / (2 + Math.SQRT2); // срез угла
  return `M${к(т)} 0H${к(s - т)}L${s} ${к(т)}V${к(s - т)}L${к(s - т)} ${s}H${к(т)}L0 ${к(s - т)}V${к(т)}Z`;
}

