/** Семейство шрифта Amiri Quran (OFL-1.1). Ключ совпадает с картой useFonts в App.tsx. */
export const ШРИФТ_АРАБСКИЙ = 'AmiriQuran';
export const ШИРИНА_КОЛОНКИ = 480;

export type Тема = {
  тёмная: boolean;
  цвет: Палитра;
  отступ: typeof отступ;
  радиус: typeof радиус;
  шрифт: typeof шрифт;
};

export function useТема(): Тема {
  const схема = useColorScheme();
  const тёмнаяТема = схема === 'dark';
  return { тёмная: тёмнаяТема, цвет: тёмнаяТема ? тёмная : светлая, отступ, радиус, шрифт };
}
