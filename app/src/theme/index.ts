/**
 * Тема AI Ustaz: токены дизайн-системы, светлая/тёмная тема, поверхность «герой», шрифты, движение.
 *
 * Контракт:
 *   useТема(): Тема — { тёмная, цвет, отступ, радиус, шрифт, типографика, тень(уровень), поверхность }.
 *     Внутри <Карточка вид="герой"> (поверхность «герой») — те же ключи, но цвет.текст/текстВторой/акцент
 *     и др. переопределены под тёмно-изумрудную шапку (см. ЦВЕТ_ГЕРОЯ). Цвета — только из темы.
 *   <ПоставщикТемы> — в App.tsx над всем; режим «как в системе» | «светлая» | «тёмная», хранится локально
 *     (ключ aiustaz:theme.v1, только настройка). Без поставщика useТема() следует системе.
 *   useНастройкаТемы(): { режим, установитьРежим } — для <ПереключательТемы>.
 *   <ПоверхностьГероя> — контекст «текст на тёмной шапке» (ставит Карточка вид="герой").
 *   useУменьшитьДвижение(): boolean — системная настройка «уменьшить движение» (prefers-reduced-motion).
 *   Веб: ПоставщикТемы ставит общий стиль кольца фокуса клавиатуры (:focus-visible — только с клавиатуры, не от
 *     касания): 2 px цвета «фокус» с отступом 2 px, на поверхности «герой» (data-surface="hero") — светлое кольцо
 *     геройТекст; у пунктов нижнего меню (data-focus="inside") — внутри пункта, offset −3 px. Цвета берутся из
 *     токенов текущей темы (WCAG 2.4.7; контраст ≥ 3:1 проверяет test-theme).
 *   Константы и шкалы — из tokens.ts (реэкспорт), шрифты — из fonts(.web).ts.
 *   <ПоставщикАрабскогоШрифта готов> / useАрабскийШрифтГотов() — загружен ли Amiri Quran (ставит App.tsx).
 *     Экраны не ждут шрифтов (на вебе у Inter font-display: swap); <АрабскийТекст> до загрузки Amiri держит
 *     место прозрачным, чтобы текст Корана и буквы не мелькнули системным шрифтом. Без поставщика — true.
 *
 * Дизайн (CLAUDE.md, правило 9; docs/дизайн/03-дизайн-система.md): спокойно, без лиц, без маскота,
 * без «наград»; изумруд + слоновая кость + песок, золото — только акцентом. Контраст текста ≥ 4,5:1
 * (проверяет scripts/test-theme.mjs). Решение: дизайн-система 19.11.2026.
 */
import { createContext, createElement, useCallback, useContext, useEffect, useMemo, useState, type ReactNode } from 'react';
import { AccessibilityInfo, Platform, useColorScheme, type ViewStyle } from 'react-native';
import { записатьJSON, прочитатьJSON, приВнешнемИзменении } from '../engine/storage';
import { ТЕНЬ, ТИПОГРАФИКА, отступ, радиус, светлая, тёмная, шрифт, type Палитра } from './tokens';

export * from './tokens';
export { МЕЖСТРОЧНЫЙ_УРДУ, СЕМЕЙСТВО_ИНТЕРФЕЙСА, ШРИФТ_АРАБСКИЙ, ШРИФТ_ИНТЕРФЕЙСА, ШРИФТ_УРДУ, ШРИФТЫ_ИНТЕРФЕЙСА, ШРИФТЫ_ПРИЛОЖЕНИЯ } from './fonts';

export type РежимТемы = 'система' | 'светлая' | 'тёмная';
export type Поверхность = 'обычная' | 'герой';
export type УровеньТени = 0 | 1 | 2;

export type Тема = {
  тёмная: boolean;
  цвет: Палитра;
  отступ: typeof отступ;
  радиус: typeof радиус;
  шрифт: typeof шрифт;
  типографика: typeof ТИПОГРАФИКА;
  /** Стиль тени уровня 0–2 (boxShadow; в тёмной теме — слабее). */
  тень: (уровень: УровеньТени) => ViewStyle;
  /** «обычная» или «герой» (тёмная изумрудная шапка). */
  поверхность: Поверхность;
};

/** На поверхности «герой» текст и действия — светлые; остальное — как в теме. */
function цветГероя(п: Палитра): Палитра {
  return {
    ...п,
    фон: п.геройФон,
    поверхность: п.геройФон,
    текст: п.геройТекст,
    текстВторой: п.геройВторой,
    текстПрошедший: п.геройВторой,
    акцент: п.геройТекст,
    акцентТекст: п.геройФон,
    акцентМягкий: п.геройЛиния,
    граница: п.геройЛиния,
    границаЭлемента: п.геройВторой,
    арабский: п.геройТекст,
    фокус: п.геройТекст,
  };
}

/** Веб: общий стиль кольца фокуса из токенов текущей темы (один <style> на страницу). */
function СтильФокуса() {
  const { цвет } = useТема();
  useEffect(() => {
    if (Platform.OS !== 'web' || typeof document === 'undefined') return;
    let стиль = document.getElementById('aiustaz-focus') as HTMLStyleElement | null;
    if (!стиль) {
      стиль = document.createElement('style');
      стиль.id = 'aiustaz-focus';
      document.head.appendChild(стиль);
    }
    стиль.textContent =
      // Поля ввода показывают фокус своей рамкой (ВыборГорода) — кольцо им не ставим.
      `:focus-visible:not(input):not(textarea){outline:2px solid ${цвет.фокус}!important;outline-offset:2px}` +
      `[data-surface="hero"] :focus-visible:not(input):not(textarea){outline-color:${цвет.геройТекст}!important}` +
      // Пункты нижнего меню: кольцо внутри (у края окна снаружи оно обрезалось бы).
      `[data-focus="inside"]:focus-visible{outline-offset:-3px}` +
      // Заголовок экрана получает фокус программно (смена экрана, для диктора) — это не элемент управления.
      `[data-focus="heading"]:focus{outline:none!important}`;
  }, [цвет.фокус, цвет.геройТекст]);
  return null;
}

const КЛЮЧ = 'theme.v1';
type Сохранённое = { версия: 1; режим: РежимТемы };
const РЕЖИМЫ: РежимТемы[] = ['система', 'светлая', 'тёмная'];

/** Веб: прочитать режим сразу (localStorage синхронный) — без вспышки светлой темы. */
// По умолчанию — СВЕТЛАЯ (владелец 26.11.2026: «По умолчанию поставь светлый фон»); тёмная и «как в системе» — только
// явным выбором в «Ещё» → «Тема» (сохранённый выбор не меняется).
const ПО_УМОЛЧАНИЮ: РежимТемы = 'светлая';

function режимСразу(): РежимТемы {
  if (Platform.OS !== 'web') return ПО_УМОЛЧАНИЮ;
  try {
    const строка = globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ);
    const з = строка ? (JSON.parse(строка) as Partial<Сохранённое>) : null;
    return з && РЕЖИМЫ.includes(з.режим as РежимТемы) ? (з.режим as РежимТемы) : ПО_УМОЛЧАНИЮ;
  } catch {
    return ПО_УМОЛЧАНИЮ;
  }
}

type НастройкаТемы = { режим: РежимТемы; установитьРежим: (режим: РежимТемы) => void };
const КонтекстТемы = createContext<НастройкаТемы>({ режим: 'светлая', установитьРежим: () => {} });
const КонтекстПоверхности = createContext<Поверхность>('обычная');
const КонтекстАрабскогоШрифта = createContext<boolean>(true);

/** Готов ли шрифт Amiri Quran (App.tsx: useFonts); пока нет — арабский текст прозрачен (место держит). */
export function ПоставщикАрабскогоШрифта({ готов, children }: { готов: boolean; children?: ReactNode }) {
  return createElement(КонтекстАрабскогоШрифта.Provider, { value: готов }, children);
}

export function useАрабскийШрифтГотов(): boolean {
  return useContext(КонтекстАрабскогоШрифта);
}

/** Поставщик темы: режим (система/светлая/тёмная), сохранение локально. */
export function ПоставщикТемы({ children }: { children?: ReactNode }) {
  const [режим, установить] = useState<РежимТемы>(режимСразу);
  useEffect(() => {
    if (Platform.OS === 'web') return;
    let живой = true;
    прочитатьJSON<Сохранённое | null>(КЛЮЧ, null).then((з) => {
      if (живой && з && РЕЖИМЫ.includes(з.режим)) установить(з.режим);
    });
    return () => {
      живой = false;
    };
  }, []);
  // Аккаунт (владелец 28.11.2026): тема пришла с другого устройства.
  useEffect(() => приВнешнемИзменении(КЛЮЧ, () => установить(режимСразу())), []);
  const установитьРежим = useCallback((новый: РежимТемы) => {
    установить(новый);
    void записатьJSON(КЛЮЧ, { версия: 1, режим: новый } satisfies Сохранённое);
  }, []);
  const значение = useMemo(() => ({ режим, установитьРежим }), [режим, установитьРежим]);
  return createElement(КонтекстТемы.Provider, { value: значение }, createElement(СтильФокуса), children);
}

/** Поверхность «герой»: текст, значки и кнопки внутри берут светлые цвета шапки. */
export function ПоверхностьГероя({ children }: { children?: ReactNode }) {
  return createElement(КонтекстПоверхности.Provider, { value: 'герой' }, children);
}

export function useНастройкаТемы(): НастройкаТемы {
  return useContext(КонтекстТемы);
}

function тени(тёмнаяТема: boolean, цвет: string): (уровень: УровеньТени) => ViewStyle {
  return (уровень) => {
    const т = ТЕНЬ[уровень];
    if (т.непрозрачность === 0) return {};
    const непрозрачность = тёмнаяТема ? Math.min(0.5, т.непрозрачность * 3) : т.непрозрачность;
    const hex = Math.round(непрозрачность * 255)
      .toString(16)
      .padStart(2, '0');
    return { boxShadow: `0px ${т.смещение}px ${т.размытие}px ${цвет}${hex}` };
  };
}

export function useТема(): Тема {
  const { режим } = useContext(КонтекстТемы);
  const поверхность = useContext(КонтекстПоверхности);
  const схема = useColorScheme();
  const тёмнаяТема = режим === 'система' ? схема === 'dark' : режим === 'тёмная';
  return useMemo(() => {
    const база = тёмнаяТема ? тёмная : светлая;
    return {
      тёмная: тёмнаяТема,
      цвет: поверхность === 'герой' ? цветГероя(база) : база,
      отступ,
      радиус,
      шрифт,
      типографика: ТИПОГРАФИКА,
      тень: тени(тёмнаяТема, база.тень),
      поверхность,
    };
  }, [тёмнаяТема, поверхность]);
}

/** Системная настройка «уменьшить движение». Пока неизвестно — считаем, что включена (без анимации). */
export function useУменьшитьДвижение(): boolean {
  const [уменьшить, установить] = useState(true);
  useEffect(() => {
    let живой = true;
    AccessibilityInfo.isReduceMotionEnabled()
      .then((в) => живой && установить(в))
      .catch(() => живой && установить(false));
    const подписка = AccessibilityInfo.addEventListener('reduceMotionChanged', (в: boolean) => установить(в));
    return () => {
      живой = false;
      подписка?.remove?.();
    };
  }, []);
  return уменьшить;
}
