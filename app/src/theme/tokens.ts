/**
 * Токены дизайн-системы AI Ustaz — чистые данные, без импортов.
 *
 * Назначение: единый источник цветов, шкал и констант. Их читают тема приложения (theme/index.ts),
 * проверка контраста (scripts/test-theme.mjs, node снимает типы сам) и витрина дизайн-системы
 * (статический ds.html). Описание — docs/дизайн/03-дизайн-система.md.
 *
 * Контракт:
 *   светлая, тёмная: Палитра — цвета по назначению (ключи одинаковые, typecheck проверяет).
 *   ПАРЫ_КОНТРАСТА — пары «текст/значок на фоне» с порогом WCAG (тест не пропустит ниже).
 *   отступ, радиус, шрифт, ТИПОГРАФИКА, ТЕНЬ, ДВИЖЕНИЕ, ОРНАМЕНТ, ГОРИЗОНТ — шкалы и константы.
 * Правила (CLAUDE.md, правило 9; бриф §2): спокойно; золото — только акцент (≤ 5 % площади);
 * красный не используем для ошибок чтения (в таджвидном мусхафе красный — мадд); цвет никогда
 * не единственный носитель смысла.
 * Решение: дизайн-система 19.11.2026 (задача владельца: «мощный дизайн для мусульманской аудитории»).
 */

export type Палитра = {
  /** Фон экрана. */
  фон: string;
  /** Карточки, листы, поля. */
  поверхность: string;
  /** Мягкий изумрудный фон: пояснения, «акцентная» карточка. */
  поверхностьАкцент: string;
  /** Выбранный сегмент вкладок / переключателя (на дорожке поверхностьВторая). */
  выбрано: string;
  /** Утопленная поверхность: дорожка вкладок, подложка полей. */
  поверхностьВторая: string;
  /** Основной текст. */
  текст: string;
  /** Пояснения, подписи. */
  текстВторой: string;
  /** Прошедшее (время намаза, пройденный шаг) — тише второго, но ≥ 4,5:1. */
  текстПрошедший: string;
  /** Главный цвет: кнопки, ссылки, значки действий. */
  акцент: string;
  /** Текст и значки на акценте. */
  акцентТекст: string;
  /** Вторичная кнопка, выделенная строка. */
  акцентМягкий: string;
  /** Нажатая основная кнопка. */
  акцентНажат: string;
  /** Вторичные ссылки, кольцо фокуса. */
  бирюза: string;
  /** Песок: блок восхода, подложки. */
  песок: string;
  /** Текст на песке. */
  песокТекст: string;
  /** Золото для линий и орнамента. НЕ для текста и не для смысла. */
  золотоДекор: string;
  /** Золото для значков (≥ 3:1 на поверхности). */
  золотоЗначок: string;
  /** Золото для редких подписей (≥ 4,5:1). */
  золотоТекст: string;
  /** Шапка «герой» (арка дня): фон, текст, второй текст, тонкие линии. */
  геройФон: string;
  геройТекст: string;
  геройВторой: string;
  геройЛиния: string;
  /** Рамка блока «Восход» на герое (это не намаз: песочная пунктирная рамка, без золота). */
  геройВосход: string;
  /** Выделение «следующий» (следующий намаз, текущий шаг): мягкое золото. */
  следующийФон: string;
  следующийТекст: string;
  /** Декоративные разделители (не несут смысла). */
  граница: string;
  /** Рамки полей и вторичных кнопок (≥ 3:1). */
  границаЭлемента: string;
  /** Кольцо фокуса клавиатуры. */
  фокус: string;
  /** Плашки «Прототип», «Черновик». */
  плашкаФон: string;
  плашкаТекст: string;
  /** Статусы. «опасность» — только для системного (удалить запись), не для чтения. */
  успех: string;
  успехФон: string;
  внимание: string;
  вниманиеФон: string;
  опасность: string;
  /** Арабский текст (Коран, буквы). */
  арабский: string;
  /** Эмблема AI Ustaz (фонарь-шырақ): свет окна, сияние, «молчу». */
  свет: string;
  сияние: string;
  тихо: string;
  /** Бумага пузыря эмблемы. */
  бумага: string;
  /** Затемнение под листами и диалогами. */
  наложение: string;
  /** Цвет тени (прозрачность — в ТЕНЬ). */
  тень: string;
};

