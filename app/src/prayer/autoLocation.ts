/**
 * Место «по геолокации» обновляется само.
 *
 * Решение владельца 26.11.2026: «Нужно получить один раз разрешение, а потом постоянно его местоположение держать у
 * себя, чтобы если он передвигается туда-сюда, обновлять — чтобы он не нажимал постоянно „обновить местоположение“.
 * Мы должны постоянно обновлять местоположение за него».
 *
 * Как работает:
 *   - режим «авто» включается, когда человек сам определил место по геолокации в выборе города (CityPicker:
 *     разрешение спрашивает браузер — по нажатию человека, после нашего пояснения); выбор города из списка вручную
 *     режим выключает;
 *   - при запуске приложения и при возвращении во вкладку (visibilitychange → visible), не чаще раза в 10 мин, если
 *     разрешение уже ДАНО (navigator.permissions.query → 'granted'), берём позицию тихо (низкая точность, свежая —
 *     без кэша браузера, таймаут 10 с). Разрешения нет, отозвано или браузер не умеет его проверить — ничего не спрашиваем,
 *     остаётся последнее место;
 *   - сместились больше чем на 3 км — ищем ближайшее место (свои списки КЗ и УЗ и плитки мира, как в выборе города):
 *     до 5 км — этот город, дальше — «своя точка» (≈ 1 км) с поясом ближайшего города (дальше 100 км — пояс телефона).
 * Координаты — только на этом устройстве (ключ aiustaz:prayer-auto.v1 = { версия: 1, вкл, точка (0,01°), время });
 * в сеть уходят только номера плиток мира, как при ручном определении. Уведомления о намазе — без координат.
 *
 * Контракт:
 *   запомнитьТочку(точка) — позиция, которую только что дал браузер в выборе города (в памяти);
 *   включитьАвто() / выключитьАвто() — режим; useАвтоМесто() → включён ли;
 *   нужноСпросить(авто, сейчас), сместился(было, стало) — чистые функции (ИНТЕРВАЛ_МС, ПОРОГ_КМ);
 *   обновитьМестоСамо(сейчас?) → Promise<'выключено' | 'рано' | 'нет-разрешения' | 'не-удалось' | 'то-же' | 'обновлено'>;
 *   запуститьАвтообновление() → отписаться() — раз при запуске и при каждом возвращении во вкладку.
 */
import { useSyncExternalStore } from 'react';
import { Platform } from 'react-native';
import { записатьJSON } from '../engine/storage';
import { ближайшееМесто, расстояниеКм, своёМесто, type Место } from './places';
import { ближайшееВМире, выбратьМесто, загрузитьМеста } from './store';

export const ИНТЕРВАЛ_МС = 10 * 60_000;
export const ПОРОГ_КМ = 3;
const КЛЮЧ = 'prayer-auto.v1';

type Точка = { широта: number; долгота: number };
export type Авто = { версия: 1; вкл: boolean; точка?: Точка; время?: number };

const округлить = (т: Точка): Точка => ({ широта: Math.round(т.широта * 100) / 100, долгота: Math.round(т.долгота * 100) / 100 });

function этоТочка(з: unknown): з is Точка {
  const т = з as Partial<Точка> | null;
  return !!т && Number.isFinite(т.широта) && Number.isFinite(т.долгота);
}

function прочитатьСразу(): Авто {
  if (Platform.OS !== 'web') return { версия: 1, вкл: false };
  try {
    const з = JSON.parse(globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ) ?? 'null') as Partial<Авто> | null;
    if (!з || з.версия !== 1) return { версия: 1, вкл: false };
    return { версия: 1, вкл: з.вкл === true, ...(этоТочка(з.точка) ? { точка: з.точка } : {}), ...(Number.isFinite(з.время) ? { время: з.время } : {}) };
  } catch {
    return { версия: 1, вкл: false };
  }
}

let авто: Авто = прочитатьСразу();
let последняя: { точка: Точка; время: number } | null = null;
const слушатели = new Set<() => void>();

function сохранить(новое: Авто) {
  авто = новое;
  for (const с of слушатели) с();
  void записатьJSON(КЛЮЧ, новое);
}

export function текущееАвто(): Авто {
  return авто;
}

export function запомнитьТочку(точка: Точка, время = Date.now()): void {
  последняя = { точка: округлить(точка), время };
}

export function включитьАвто(): void {
  сохранить({ версия: 1, вкл: true, ...(последняя ? { точка: последняя.точка, время: последняя.время } : авто.точка ? { точка: авто.точка, время: авто.время } : {}) });
}

export function выключитьАвто(): void {
  if (авто.вкл) сохранить({ версия: 1, вкл: false });
}

export function useАвтоМесто(): boolean {
  return useSyncExternalStore(
    (с: () => void) => {
      слушатели.add(с);
      return () => {
        слушатели.delete(с);
      };
    },
    () => авто.вкл,
    () => авто.вкл,
  );
}

/** Пора ли тихо спросить позицию: режим включён и с прошлого раза прошло не меньше ИНТЕРВАЛ_МС. */
export function нужноСпросить(а: Авто, сейчас: number): boolean {
  return а.вкл && (а.время === undefined || сейчас - а.время >= ИНТЕРВАЛ_МС);
}

/** Сместился ли человек дальше ПОРОГ_КМ (нет прошлой точки — да). */
export function сместился(было: Точка | undefined, стало: Точка): boolean {
  return !было || расстояниеКм(было, стало) > ПОРОГ_КМ;
}

/** Разрешение на геолокацию уже дано? Без Permissions API — считаем, что нет (иначе браузер мог бы спросить сам). */
async function разрешеноУже(): Promise<boolean> {
  try {
    const п = globalThis.navigator?.permissions;
    if (!п?.query) return false;
    const с = await п.query({ name: 'geolocation' as PermissionName });
    return с.state === 'granted';
  } catch {
    return false;
  }
}

function позиция(): Promise<Точка | null> {
  const гл = globalThis.navigator?.geolocation;
  if (!гл) return Promise.resolve(null);
  return new Promise((готово) =>
    гл.getCurrentPosition(
      (п) => готово({ широта: п.coords.latitude, долгота: п.coords.longitude }),
      () => готово(null),
      // Свежая позиция (кэш браузера мог остаться от прошлого места); низкая точность — сеть/вышки, без GPS.
      { enableHighAccuracy: false, maximumAge: 0, timeout: 10_000 },
    ),
  );
}

/** Место для точки: ближайший город до 5 км, иначе своя точка (пояс — города; дальше 100 км — пояс телефона). */
async function местоДляТочки(точка: Точка): Promise<Место | null> {
  const [список, вМире] = await Promise.all([загрузитьМеста().catch(() => null), ближайшееВМире(точка).catch(() => null)]);
  const свой = список?.length ? ближайшееМесто(список, точка) : null;
  const ближ = свой && (!вМире || свой.км <= вМире.км) ? свой : вМире;
  if (!ближ) return null;
  if (ближ.км <= 5) return ближ.место;
  let пояс: string | undefined;
  if (ближ.км > 100) {
    try {
      пояс = Intl.DateTimeFormat().resolvedOptions().timeZone || undefined;
    } catch {
      пояс = undefined;
    }
  }
  return своёМесто(точка, ближ, пояс);
}

let идёт: Promise<string> | null = null;

export function обновитьМестоСамо(сейчас = Date.now()): Promise<'выключено' | 'рано' | 'нет-разрешения' | 'не-удалось' | 'то-же' | 'обновлено'> {
  if (!авто.вкл) return Promise.resolve('выключено');
  if (!нужноСпросить(авто, сейчас)) return Promise.resolve('рано');
  if (идёт) return идёт as Promise<'то-же'>;
  const задача = (async () => {
    if (!(await разрешеноУже())) return 'нет-разрешения' as const;
    const точка = await позиция();
    if (!точка || !авто.вкл) return 'не-удалось' as const;
    const было = авто.точка;
    if (!сместился(было, точка)) {
      сохранить({ ...авто, время: сейчас });
      return 'то-же' as const;
    }
    const место = await местоДляТочки(точка);
    if (!место || !авто.вкл) return 'не-удалось' as const;
    await выбратьМесто(место);
    сохранить({ версия: 1, вкл: true, точка: округлить(точка), время: сейчас });
    return 'обновлено' as const;
  })().finally(() => {
    идёт = null;
  });
  идёт = задача;
  return задача;
}

/** Раз при запуске и при каждом возвращении во вкладку (только веб). */
export function запуститьАвтообновление(): () => void {
  if (Platform.OS !== 'web' || typeof document === 'undefined') return () => undefined;
  const проверить = () => {
    if (document.visibilityState === 'visible') void обновитьМестоСамо();
  };
  проверить();
  document.addEventListener('visibilitychange', проверить);
  return () => document.removeEventListener('visibilitychange', проверить);
}
