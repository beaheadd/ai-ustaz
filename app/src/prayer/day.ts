export const ЭТО_НАМАЗ: Record<КлючВремени, boolean> = { fajr: true, sunrise: false, dhuhr: true, asr: true, maghrib: true, isha: true };

/** Фаза дня → ключ ГОРИЗОНТ (theme/tokens.ts) и знак фазы. */
export const ФАЗА_ГОРИЗОНТА = { fajr: 'фаджр', sunrise: 'восход', dhuhr: 'зухр', asr: 'аср', maghrib: 'магриб', isha: 'иша' } as const;

const НАМАЗЫ: readonly КлючВремени[] = ['fajr', 'dhuhr', 'asr', 'maghrib', 'isha'];
const ПОРЯДОК: readonly КлючВремени[] = ['fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha'];

export type ВидБлока = 'прошёл' | 'сейчас' | 'следующий' | 'впереди';

export type СостояниеДня = {
  /** Времена, которые показывает сетка: сегодня, а после начала құптан — завтра. */
  сетка: ВременаДня;
  /** Сетка показывает завтрашний день. */
  завтра: boolean;
  /** Следующий намаз (восход следующим не бывает). */
  следующий: { ключ: КлючВремени; момент: number; завтра: boolean };
  /** Чьё время идёт сейчас, если этот блок есть в сетке (восход–бесін и до таң — null). */
  текущий: КлючВремени | null;
  /** Между таң и восходом — момент восхода (им заканчивается время таң). */
  восход: number | null;
  /** Фаза дня для знака и полосы горизонта: последнее наступившее время (до таң — құптан). */
  фаза: КлючВремени;
  /** После начала құптан (сетка уже завтрашняя) — сегодняшнее начало құптан: «Сейчас — Иша (с 17:59)». */
  иша: number | null;
  /** Вид каждого блока сетки. */
  виды: Record<КлючВремени, ВидБлока>;
};

/**
 * Что показать сейчас. сегодня — времена дня деньРК(сейчас), завтра — следующего дня.
 * До таң: следующий — таң, текущего блока нет (құптан вчерашний). Таң…восход: текущий — таң, следующий — бесін,
 * плюс момент восхода. Восход…бесін: текущего нет (восход — не намаз). После начала құптан: сетка — завтра,
 * следующий — завтрашний таң.
 */
/** Фаза дня: последнее наступившее сегодня время (до таң — құптан). Чистая функция. */
export function фазаДня(сейчас: number, сегодня: ВременаДня): КлючВремени {
  const наступили = ПОРЯДОК.filter((к) => сегодня[к] <= сейчас);
  return наступили.length ? наступили[наступили.length - 1] : 'isha';
}

export function состояниеДня(сейчас: number, сегодня: ВременаДня, завтра: ВременаДня): СостояниеДня {
  const наступили = ПОРЯДОК.filter((к) => сегодня[к] <= сейчас);
  const фаза = фазаДня(сейчас, сегодня);
  if (сегодня.isha <= сейчас) {
    const виды = Object.fromEntries(ПОРЯДОК.map((к) => [к, к === 'fajr' ? 'следующий' : 'впереди'])) as Record<КлючВремени, ВидБлока>;
    return { сетка: завтра, завтра: true, следующий: { ключ: 'fajr', момент: завтра.fajr, завтра: true }, текущий: null, восход: null, фаза, иша: сегодня.isha, виды };
  }
  const ключСледующего = НАМАЗЫ.find((к) => сегодня[к] > сейчас) ?? 'isha';
  const текущий: КлючВремени | null = фаза === 'sunrise' || наступили.length === 0 ? null : фаза;
  const виды = {} as Record<КлючВремени, ВидБлока>;
  for (const к of ПОРЯДОК) {
    виды[к] = к === ключСледующего ? 'следующий' : к === текущий ? 'сейчас' : сегодня[к] <= сейчас ? 'прошёл' : 'впереди';
  }
  return {
    сетка: сегодня,
    завтра: false,
    следующий: { ключ: ключСледующего, момент: сегодня[ключСледующего], завтра: false },
    текущий,
    восход: фаза === 'fajr' ? сегодня.sunrise : null,
    фаза,
    иша: null,
    виды,
  };
}

/** Обратный отсчёт до момента: вверх до минуты (не показываем «0 мин», пока время не наступило). */
export function обратныйОтсчёт(мс: number, язык: Язык): string {
  const всего = Math.max(1, Math.ceil(мс / МИНУТА));
  const ч = Math.floor(всего / 60);
  const м = всего % 60;
  if (язык === 'kk') return ч > 0 ? `${ч} сағ ${String(м).padStart(2, '0')} мин қалды` : `${м} мин қалды`;
  if (язык === 'uz') return ч > 0 ? `${ч} soat ${String(м).padStart(2, '0')} daq. qoldi` : `${м} daq. qoldi`;
  return ч > 0 ? `через ${ч} ч ${String(м).padStart(2, '0')} мин` : `через ${м} мин`;
}

/** То же для экранного диктора, без сокращений. */
export function обратныйОтсчётПолностью(мс: number, язык: Язык): string {
  const всего = Math.max(1, Math.ceil(мс / МИНУТА));
  const ч = Math.floor(всего / 60);
  const м = всего % 60;
  if (язык === 'kk') return [ч ? `${ч} сағат` : '', м ? `${м} минут` : ''].filter(Boolean).join(' ') + ' қалды';
  if (язык === 'uz') return [ч ? `${ч} soat` : '', м ? `${м} daqiqa` : ''].filter(Boolean).join(' ') + ' qoldi';
  const формаЧ = склонение(ч, ['час', 'часа', 'часов']);
  const формаМ = склонение(м, ['минуту', 'минуты', 'минут']);
  return 'через ' + [ч ? `${ч} ${формаЧ}` : '', м ? `${м} ${формаМ}` : ''].filter(Boolean).join(' ');
}

function склонение(n: number, [одна, две, пять]: [string, string, string]): string {
  const д = n % 100;
  if (д >= 11 && д <= 14) return пять;
  const е = n % 10;
  return е === 1 ? одна : е >= 2 && е <= 4 ? две : пять;
}

export type Приглашение = { ключ: КлючВремени; начало: number; прошлоМин: number };

/**
 * «Урок после намаза»: если с начала времени намаза (не восхода) прошло от сМин до окноМин минут и следующее
 * время ещё не наступило — мягкое «5 минут урока?». В первые минуты времени (до сМин) не зовём: человек,
 * возможно, ещё не молился (docs/дизайн/02-образ-устаза.md, реплика №3: «через 10–40 мин после начала»).
 * Без упрёков и без слов о совершении намаза.
 */
export function приглашениеПослеНамаза(сейчас: number, сегодня: ВременаДня, окноМин = 40, сМин = 10): Приглашение | null {
  for (const к of НАМАЗЫ) {
    const начало = сегодня[к];
    const прошло = сейчас - начало;
    if (прошло < сМин * МИНУТА || прошло > окноМин * МИНУТА) continue;
    const после = ПОРЯДОК.slice(ПОРЯДОК.indexOf(к) + 1).find((д) => сегодня[д] <= сейчас);
    if (после) continue;
    return { ключ: к, начало, прошлоМин: Math.floor(прошло / МИНУТА) };
  }
  return null;
}

const МЕСЯЦЫ: Record<Язык, string[]> = {
  ru: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
  kk: ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'],
  uz: ['yanvar', 'fevral', 'mart', 'aprel', 'may', 'iyun', 'iyul', 'avgust', 'sentyabr', 'oktyabr', 'noyabr', 'dekabr'],
};
const ДНИ_НЕДЕЛИ: Record<Язык, string[]> = {
  // getUTCDay: 0 — воскресенье
  ru: ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'],
  kk: ['жс', 'дс', 'сс', 'ср', 'бс', 'жм', 'сб'], // kk — черновик (сокращения как в календарях: Дс, Сс, Ср, Бс, Жм, Сб, Жс)
  uz: ['ya', 'du', 'se', 'ch', 'pa', 'ju', 'sh'], // uz — черновик (Yakshanba, Dushanba, Seshanba, Chorshanba, Payshanba, Juma, Shanba)
};

/** '20 ноября' / '20 қараша' / '20-noyabr' (узбекская запись даты — через дефис). */
export function датаДня(день: ДеньРК, язык: Язык): string {
  const [, м, ч] = день.split('-').map(Number);
  return язык === 'uz' ? `${ч}-${МЕСЯЦЫ.uz[м - 1]}` : `${ч} ${МЕСЯЦЫ[язык][м - 1]}`;
}

/** 'Сегодня, 19 ноября' / 'Завтра, 20 ноября' / '21 ноября' (kk: 'Бүгін, 19 қараша'). */
export function подписьДня(день: ДеньРК, язык: Язык, сегодня: ДеньРК): string {
  const дата = датаДня(день, язык);
  if (день === сегодня) return { ru: 'Сегодня, ', kk: 'Бүгін, ', uz: 'Bugun, ' }[язык] + дата;
  if (день === сдвигДня(сегодня, 1)) return { ru: 'Завтра, ', kk: 'Ертең, ', uz: 'Ertaga, ' }[язык] + дата;
  return дата;
}

/** Короткая подпись дня для таблицы недели: { деньНедели: 'пт', число: '20', дата: '20.11' }. */
export function короткийДень(день: ДеньРК, язык: Язык): { деньНедели: string; число: string; дата: string } {
  const [г, м, ч] = день.split('-').map(Number);
  const дн = new Date(Date.UTC(г, м - 1, ч)).getUTCDay();
  return { деньНедели: ДНИ_НЕДЕЛИ[язык][дн], число: String(ч), дата: `${String(ч).padStart(2, '0')}.${String(м).padStart(2, '0')}` };
}
