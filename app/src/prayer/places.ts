/**
 * Области, где наш расчёт может расходиться с таблицами ДУМК больше чем на минуту. Пусто: прежние «до 3 мин»
 * в Кызылорде оказались разовым сбоем ответа api.muftyat.kz (сверка 19.11.2026: три скачивания, 2025–2027 годы
 * и 6 мест области — ≤ 1 мин). Вернуть «Кызылординская область», если расхождение повторится.
 */
export const ОБЛАСТИ_С_ОГОВОРКОЙ: readonly string[] = [];

export function оговоркаТочности(место: Место, области: readonly string[] = ОБЛАСТИ_С_ОГОВОРКОЙ): 'до3мин' | null {
  return место.область && области.includes(место.область.ru) ? 'до3мин' : null;
}

export const КРУПНЫЕ: readonly string[] = ['республиканского значения', 'областной центр'];

type СырыеМеста = {
  области?: { kk?: unknown; ru?: unknown }[];
  виды?: unknown[];
  поля?: unknown[];
  места?: unknown[][];
};

const ЧИСЛО = (з: unknown): з is number => typeof з === 'number' && Number.isFinite(з);
const СТРОКА = (з: unknown): з is string => typeof з === 'string' && з.length > 0;

export function разобратьМеста(данные: unknown): Место[] {
  const д = (данные ?? {}) as СырыеМеста;
  const поля = Array.isArray(д.поля) ? д.поля : [];
  const и = (имя: string) => поля.indexOf(имя);
  const области = Array.isArray(д.области) ? д.области : [];
  const виды = Array.isArray(д.виды) ? д.виды : [];
  const итог: Место[] = [];
  const ids = new Set<string>();
  for (const з of Array.isArray(д.места) ? д.места : []) {
    if (!Array.isArray(з)) continue;
    const id = з[и('id')];
    const kk = з[и('kk')];
    const ru = з[и('ru')];
    const ш = з[и('широта')];
    const дл = з[и('долгота')];
    const скл = з[и('склонение')];
    const обл = области[з[и('область')] as number];
    const тип = виды[з[и('вид')] as number];
    if (!СТРОКА(id) || !СТРОКА(kk) || !СТРОКА(ru) || !ЧИСЛО(ш) || !ЧИСЛО(дл) || !ЧИСЛО(скл) || ids.has(id)) continue;
    if (Math.abs(ш) > 90 || Math.abs(дл) > 180) continue;
    ids.add(id);
    итог.push({
      id,
      вид: 'место',
      kk,
      ru,
      область: обл && СТРОКА(обл.kk) && СТРОКА(обл.ru) ? { kk: обл.kk, ru: обл.ru } : null,
      тип: СТРОКА(тип) ? тип : '',
      широта: ш,
      долгота: дл,
      склонение: скл,
    });
  }
  return итог;
}

/** Строка для поиска: нижний регистр, ё→е, казахские буквы → близкие русские. */
export function нормализовать(с: string): string {
  return с
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[әа]/g, 'а')
    .replace(/[қк]/g, 'к')
    .replace(/[өо]/g, 'о')
    .replace(/[ұүу]/g, 'у')
    .replace(/[ғг]/g, 'г')
    .replace(/[ңн]/g, 'н')
    .replace(/[һх]/g, 'х')
    .replace(/[іи]/g, 'и')
    .replace(/[-‐–—]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function найтиМеста(места: readonly Место[], запрос: string, язык: Язык, предел = 30): Место[] {
  const з = нормализовать(запрос);
  if (!з) return [];
  const оценки: { м: Место; о: number }[] = [];
  for (const м of места) {
    const имена = [нормализовать(м[язык]), нормализовать(язык === 'kk' ? м.ru : м.kk), м.id.replace(/-/g, ' ')];
    let о = -1;
    for (const имя of имена) {
      if (имя.startsWith(з)) о = Math.max(о, 3);
      else if (имя.split(' ').some((слово) => слово.startsWith(з))) о = Math.max(о, 2);
      else if (имя.includes(з)) о = Math.max(о, 1);
    }
    if (о >= 0) оценки.push({ м, о: о + (КРУПНЫЕ.includes(м.тип) ? 0.5 : 0) });
  }
  оценки.sort((а, б) => б.о - а.о || а.м[язык].localeCompare(б.м[язык], язык));
  return оценки.slice(0, предел).map((х) => х.м);
}

export function расстояниеКм(а: { широта: number; долгота: number }, б: { широта: number; долгота: number }): number {
  const р = Math.PI / 180;
  const дш = (б.широта - а.широта) * р;
  const дд = (б.долгота - а.долгота) * р;
  const х = Math.sin(дш / 2) ** 2 + Math.cos(а.широта * р) * Math.cos(б.широта * р) * Math.sin(дд / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(х)));
}

export function ближайшееМесто(места: readonly Место[], точка: { широта: number; долгота: number }): { место: Место; км: number } | null {
  let лучшее: { место: Место; км: number } | null = null;
  for (const м of места) {
    const км = расстояниеКм(точка, м);
    if (!лучшее || км < лучшее.км) лучшее = { место: м, км };
  }
  return лучшее;
}

/** Грубая проверка «в Казахстане»: прямоугольник РК и не дальше 150 км от места из списка. */
export function вКазахстане(точка: { широта: number; долгота: number }, кмДоБлижайшего: number): boolean {
  return точка.широта >= 40.4 && точка.широта <= 55.6 && точка.долгота >= 46.4 && точка.долгота <= 87.4 && кмДоБлижайшего <= 150;
}

export function своёМесто(точка: { широта: number; долгота: number }, ближайшее: { место: Место; км: number }): Место {
  const округлить = (х: number) => Math.round(х * 100) / 100;
  return {
    id: 'точка',
    вид: 'точка',
    kk: '≈ ' + ближайшее.место.kk,
    ru: '≈ ' + ближайшее.место.ru,
    область: ближайшее.место.область,
    тип: '',
    широта: округлить(точка.широта),
    долгота: округлить(точка.долгота),
    склонение: ближайшее.место.склонение,
    ближайшее: { id: ближайшее.место.id, км: Math.round(ближайшее.км) },
  };
}

/** Проверка сохранённого места (localStorage мог испортиться). */
export function этоМесто(з: unknown): з is Место {
  const м = з as Partial<Место> | null;
  return (
    !!м &&
    СТРОКА(м.id) &&
    (м.вид === 'место' || м.вид === 'точка') &&
    СТРОКА(м.kk) &&
    СТРОКА(м.ru) &&
    ЧИСЛО(м.широта) &&
    ЧИСЛО(м.долгота) &&
    ЧИСЛО(м.склонение) &&
    м.широта >= 40 &&
    м.широта <= 56 &&
    м.долгота >= 46 &&
    м.долгота <= 88
  );
}
