/**
 * Места РК для времени намаза и киблы: типы, разбор списка, поиск, ближайшее место — чистые функции.
 *
 * Контракт:
 *   type Место — город или районный центр из списка (вид 'место') либо своя точка по геолокации (вид 'точка').
 *   МЕСТО_ПО_УМОЛЧАНИЮ — Астана (как у ДУМК); есть сразу, без загрузки списка.
 *   разобратьМеста(данные) → Место[] — из places-kz.json (компактные строки «поля»); кривые записи отбрасывает.
 *   найтиМеста(места, запрос, язык, предел?) → Место[] — поиск по kk, ru и латинскому id; без учёта регистра,
 *     ё/е и казахских букв (қ→к, ә→а, ө→о, ұ/ү→у, ғ→г, ң→н, һ→х, і→и); сначала — совпадение с начала слова.
 *   расстояниеКм(а, б) — по большому кругу (гаверсинус, R = 6371 км).
 *   ближайшееМесто(места, точка) → { место, км } | null.
 *   вКазахстане(точка, км до ближайшего) — грубо: прямоугольник РК и ≤ 150 км до места из списка.
 *   своёМесто(точка, ближайшее) → Место вида 'точка': координаты округлены до 0,01° (≈ 1 км), склонение — как
 *     у ближайшего места (меняется медленно), подпись — «≈ <город>».
 *   оговоркаТочности(место) → текстовый ключ оговорки или null (ОБЛАСТИ_С_ОГОВОРКОЙ).
 *   КРУПНЫЕ — виды «республиканского значения» и «областной центр» (список без запроса).
 *
 * Данные — places-kz.json рядом (168 мест; GeoNames CC BY 4.0, 6 точек — из общедоступного списка мест ДУМК;
 * склонение WMM2025). Таблицы ДУМК в бандл не кладём. Геолокация не покидает устройство: сохраняется
 * только выбранное место (для своей точки — координаты с точностью ≈ 1 км, локально).
 * Модуль без импортов своих файлов (node снимает типы сам — scripts/test-prayer.mjs).
 */

type Язык = 'ru' | 'kk';

export type Место = {
  id: string;
  /** 'место' — из списка; 'точка' — своя точка по геолокации. */
  вид: 'место' | 'точка';
  kk: string;
  ru: string;
  область: { kk: string; ru: string } | null;
  /** 'республиканского значения' | 'областной центр' | 'город' | 'районный центр' | '' (точка). */
  тип: string;
  широта: number;
  долгота: number;
  /** Магнитное склонение, ° к востоку (для компаса киблы). */
  склонение: number;
  /** Для своей точки — ближайшее место списка и расстояние до него. */
  ближайшее?: { id: string; км: number };
};

