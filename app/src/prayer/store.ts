import type { Мазхаб } from './methods';
import { МЕСТО_ПО_УМОЛЧАНИЮ, ПОЯС_СТРАНЫ, разобратьМеста, этоМесто, type Место } from './places';
import { ФАЙЛЫ_МЕСТ } from './world.generated';
import { ближайшееВПлитках, найтиВМире, плиткиВокруг, разобратьИндекс, разобратьШард, расстояние, type ИндексМира, type Шард } from './world';

const КЛЮЧ = 'prayer-place.v1';
type Сохранённое = { версия: 1; место: Место };

type Состояние = { место: Место; выбрано: boolean; загружено: boolean };

function изСохранённого(з: unknown): Место | null {
  const с = з as Partial<Сохранённое> | null;
  if (!с || с.версия !== 1 || !этоМесто(с.место)) return null;
  const м = с.место as Место;
  // До 20.11.2026 сохранялись только места РК (без страны и пояса).
  const страна = м.страна ?? 'KZ';
  return { ...м, страна, пояс: м.пояс ?? ПОЯС_СТРАНЫ[страна] ?? ПОЯС_СТРАНЫ.KZ };
}

/** Веб: прочитать сразу (localStorage синхронный) — без вспышки Астаны вместо выбранного города. */
function прочитатьСразу(): Состояние {
  if (Platform.OS !== 'web') return { место: МЕСТО_ПО_УМОЛЧАНИЮ, выбрано: false, загружено: false };
  try {
    const строка = globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ);
    const место = строка ? изСохранённого(JSON.parse(строка)) : null;
    return { место: место ?? МЕСТО_ПО_УМОЛЧАНИЮ, выбрано: !!место, загружено: true };
  } catch {
    return { место: МЕСТО_ПО_УМОЛЧАНИЮ, выбрано: false, загружено: true };
  }
}

let состояние: Состояние = прочитатьСразу();
const слушатели = new Set<() => void>();

function разослать(новое: Состояние) {
  состояние = новое;
  for (const с of слушатели) с();
}

if (!состояние.загружено) {
  прочитатьJSON<unknown>(КЛЮЧ, null).then((з) => {
    const место = изСохранённого(з);
    разослать({ место: место ?? состояние.место, выбрано: !!место || состояние.выбрано, загружено: true });
  });
}

// Аккаунт (владелец 28.11.2026): синхронизация записала данные другого устройства — перечитать.
приВнешнемИзменении(КЛЮЧ, () => {
  void прочитатьJSON<unknown>(КЛЮЧ, null).then((з) => {
    const место = изСохранённого(з);
    if (место) разослать({ место, выбрано: true, загружено: true });
  });
});

export function текущееМесто(): Место {
  return состояние.место;
}

export async function выбратьМесто(место: Место): Promise<boolean> {
  разослать({ место, выбрано: true, загружено: true });
  return записатьJSON(КЛЮЧ, { версия: 1, место } satisfies Сохранённое);
}

function подписаться(с: () => void) {
  слушатели.add(с);
  return () => {
    слушатели.delete(с);
  };
}

export function useМестоНамаза(): Состояние & { выбрать: (место: Место) => Promise<boolean> } {
  const с = useSyncExternalStore(подписаться, () => состояние, () => состояние);
  return { ...с, выбрать: выбратьМесто };
}

// ───────────── правило асра ─────────────
const КЛЮЧ_АСРА = 'prayer-asr.v1';
type СохранённыйМазхаб = { версия: 1; мазхаб: Мазхаб };
const этоМазхаб = (з: unknown): з is Мазхаб => з === 'hanafi' || з === 'shafi';

function мазхабСразу(): { мазхаб: Мазхаб; загружено: boolean } {
  if (Platform.OS !== 'web') return { мазхаб: 'hanafi', загружено: false };
  try {
    const строка = globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ_АСРА);
    const з = строка ? (JSON.parse(строка) as Partial<СохранённыйМазхаб>) : null;
    return { мазхаб: з && з.версия === 1 && этоМазхаб(з.мазхаб) ? з.мазхаб : 'hanafi', загружено: true };
  } catch {
    return { мазхаб: 'hanafi', загружено: true };
  }
}

let аср = мазхабСразу();
const слушателиАсра = new Set<() => void>();
function разослатьАср(мазхаб: Мазхаб) {
  аср = { мазхаб, загружено: true };
  for (const с of слушателиАсра) с();
}
if (!аср.загружено) {
  прочитатьJSON<unknown>(КЛЮЧ_АСРА, null).then((з) => {
    const с = з as Partial<СохранённыйМазхаб> | null;
    разослатьАср(с && с.версия === 1 && этоМазхаб(с.мазхаб) ? с.мазхаб : аср.мазхаб);
  });
}

приВнешнемИзменении(КЛЮЧ_АСРА, () => {
  void прочитатьJSON<unknown>(КЛЮЧ_АСРА, null).then((з) => {
    const с = з as Partial<СохранённыйМазхаб> | null;
    if (с && с.версия === 1 && этоМазхаб(с.мазхаб)) разослатьАср(с.мазхаб);
  });
});

export function текущийМазхаб(): Мазхаб {
  return аср.мазхаб;
}

export async function выбратьМазхаб(мазхаб: Мазхаб): Promise<boolean> {
  разослатьАср(мазхаб);
  return записатьJSON(КЛЮЧ_АСРА, { версия: 1, мазхаб } satisfies СохранённыйМазхаб);
}

export function useМазхаб(): { мазхаб: Мазхаб; выбрать: (мазхаб: Мазхаб) => Promise<boolean> } {
  const с = useSyncExternalStore(
    (с: () => void) => {
      слушателиАсра.add(с);
      return () => {
        слушателиАсра.delete(с);
      };
    },
    () => аср,
    () => аср,
  );
  return { мазхаб: с.мазхаб, выбрать: выбратьМазхаб };
}

// ───────────── загрузка списков мест (статические файлы public/prayer) ─────────────
const ТАЙМАУТ_МС = 20000;

/** baseUrl сборки ('/aiustaz'): Expo подставляет process.env.EXPO_BASE_URL при сборке (как quran/data.ts). */
function базаСборки(): string {
  try {
    const б = process.env.EXPO_BASE_URL;
    if (typeof б === 'string') return б.replace(/\/+$/, '');
  } catch {
    // нет process — ниже значение по умолчанию
  }
  return '/aiustaz';
}

async function получитьJSON(файл: string): Promise<unknown> {
  const стоп = typeof AbortController === 'function' ? new AbortController() : null;
  const таймер = стоп ? setTimeout(() => стоп.abort(), ТАЙМАУТ_МС) : null;
  try {
    const ответ = await fetch(базаСборки() + '/' + файл, { credentials: 'omit', referrerPolicy: 'no-referrer', signal: стоп?.signal });
    if (!ответ.ok) throw new Error('места: ' + ответ.status);
    return await ответ.json();
  } finally {
    if (таймер) clearTimeout(таймер);
  }
}

/** Промис с кэшем: неудача не кэшируется (следующий вызов пробует снова). */
function сКэшем<Т>(загрузить: () => Promise<Т>): () => Promise<Т> {
  let кэш: Promise<Т> | null = null;
  return () => {
    кэш ??= загрузить().catch((ошибка: unknown) => {
      кэш = null;
      throw ошибка;
    });
    return кэш;
  };
}

export const загрузитьМеста = сКэшем(async () => {
  const [kz, uz] = await Promise.all([получитьJSON(ФАЙЛЫ_МЕСТ.kz), получитьJSON(ФАЙЛЫ_МЕСТ.uz)]);
  const места = [...разобратьМеста(kz), ...разобратьМеста(uz)];
  if (!места.length) throw new Error('места: пустой список');
  return места;
});

export const загрузитьИндексМира = сКэшем(async () => {
  const индекс = разобратьИндекс(await получитьJSON(ФАЙЛЫ_МЕСТ.мир));
  if (!индекс) throw new Error('места мира: кривой индекс');
  return индекс;
});

const шарды = new Map<string, Шард>();
const грузятся = new Map<string, Promise<void>>();

async function загрузитьШард(индекс: ИндексМира, п: string): Promise<void> {
  if (шарды.has(п) || !индекс.шарды[п]) return;
  if (!грузятся.has(п)) {
    грузятся.set(
      п,
      получитьJSON('prayer/' + индекс.шарды[п])
        .then((сырое) => {
          шарды.set(п, разобратьШард(индекс, п, сырое));
        })
        .finally(() => грузятся.delete(п)),
    );
  }
  await грузятся.get(п);
}

/** Поиск по миру: шард по первым двум буквам запроса и шарды, куда ведут ключи других имён (не больше 6). */
export async function искатьВМире(запрос: string, предел = 20): Promise<Место[]> {
  const индекс = await загрузитьИндексМира();
  for (let шаг = 0; шаг < 3; шаг++) {
    const р = найтиВМире(индекс, запрос, (п) => шарды.get(п) ?? null, предел);
    if (!р.нужныШарды.length) return р.места;
    await Promise.all(р.нужныШарды.slice(0, 6).map((п) => загрузитьШард(индекс, п)));
  }
  return найтиВМире(индекс, запрос, (п) => шарды.get(п) ?? null, предел).места;
}

const плитки = new Map<string, unknown>();

/** Ближайшее место мира (без KZ и UZ — их ищут в своих списках): плитки 3×3 вокруг точки. */
export async function ближайшееВМире(точка: { широта: number; долгота: number }): Promise<{ место: Место; км: number } | null> {
  const индекс = await загрузитьИндексМира();
  const нужны = плиткиВокруг(точка).filter((к) => индекс.плитки[к]);
  await Promise.all(
    нужны
      .filter((к) => !плитки.has(к))
      .map(async (к) => {
        плитки.set(к, await получитьJSON('prayer/' + индекс.плитки[к]));
      }),
  );
  const б = ближайшееВПлитках(точка, Object.fromEntries(нужны.map((к) => [к, плитки.get(к)])));
  if (!б) return null;
  await загрузитьШард(индекс, б.шард);
  const место = шарды.get(б.шард)?.места[б.номер];
  return место ? { место, км: расстояние(точка, место) } : null;
}
