/**
 * Выбранное место для времени намаза и киблы, правило асра и загрузка списков мест — только на устройстве.
 *
 * Контракт:
 *   useМестоНамаза() → { место, выбрано, загружено, выбрать(место) }
 *     место — выбранное или Астана по умолчанию (сразу, без ожидания хранилища: на вебе localStorage читается
 *     синхронно); выбрано — человек выбирал место сам (иначе на карточке «по умолчанию · изменить»).
 *   выбратьМесто(место) — сохранить и разослать подписчикам (все экраны видят сразу).
 *   текущееМесто() — то же без React (для экрана киблы и тестов).
 *   useМазхаб() → { мазхаб, выбрать(мазхаб) } — правило асра: 'hanafi' (по умолчанию, линия проекта) | 'shafi';
 *     текущийМазхаб() — без React. Ключ aiustaz:prayer-asr.v1 = { версия: 1, мазхаб }.
 *   загрузитьМеста() → Promise<Место[]> — свои списки КЗ (168) и УЗ (176): статические файлы public/prayer
 *     (имена — world.generated.ts), кэш на страницу. Не загрузилось (нет сети) — промис отклоняется (а не пустой
 *     список: «Все места (0)» было бы неправдой); следующий вызов пробует снова. Главная подгружает список в простое.
 *   загрузитьИндексМира() → Promise<ИндексМира>; искатьВМире(запрос, предел?) → Promise<Место[]> — шарды по запросу
 *     (кэш); ближайшееВМире(точка) → Promise<{ место, км } | null> — плитки 3×3 вокруг точки.
 * Хранение: ключ aiustaz:prayer-place.v1 = { версия: 1, место }. Только выбранное место: для своей точки —
 * координаты, округлённые до 0,01° (≈ 1 км). Никуда не отправляется (CLAUDE.md, «Данные и приватность»).
 * У мест, сохранённых до 20.11.2026, нет страны и пояса — это места РК: KZ, UTC+5.
 * Запросы — только на свой адрес (CSP connect-src 'self'), без cookie. Нативно относительного адреса нет — как у
 * Корана (quran/data.ts): TODO — адрес своего домена или файлы в пакете приложения.
 */
