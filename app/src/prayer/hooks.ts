/**
 * React-хуки времени намаза: общие «часы» с шагом в минуту и времена дня для выбранного места.
 *
 * Контракт:
 *   useСейчас(заданное?) → мс, округлённые вниз до минуты. Один общий таймер на всё приложение (а не по таймеру
 *     на компонент): срабатывает на границе минуты (+20 мс) и при возврате в приложение (AppState: вкладка или
 *     телефон спали, часы сменились); работает, только пока есть подписчики. Моменты намаза стоят на целых
 *     минутах, а отсчёт округляется вверх до минуты, поэтому шаг в 30 с не давал бы нового текста.
 *     заданное — для тестов и предпросмотра (без таймеров).
 *   useЧасы(выбор, заданное?) → выбор(сейчас) — подписка на те же часы, но компонент перерисовывается, только
 *     когда меняется результат выбора (строка, число, boolean — сравнение Object.is). Пример: фаза дня для
 *     реплики главной — меняется несколько раз в сутки, а не каждую минуту. выбор — чистая функция.
 *   временаДняКэш(место, день) → ВременаДня | null — расчёт с кэшем (несколько дней и мест; ошибка — null).
 *   useДеньНамаза(место, сейчас) → { день: { сегодня, завтра, состояние } | null, ошибка } — пересчёт времён только
 *     при смене места или суток РК (полночь UTC+5), состояния — при смене «сейчас».
 * Отсчёт на экране — в минутах (вверх), секунд и мигания нет (бриф §9: слабые телефоны).
 */
import { useMemo, useSyncExternalStore } from 'react';
import { AppState } from 'react-native';
import { деньРК, состояниеДня, сдвигДня, type СостояниеДня } from './day';
import type { Место } from './places';
import { временаДня, type ВременаДня } from './times';

const ШАГ = 60_000;
const округлить = (мс: number) => Math.floor(мс / ШАГ) * ШАГ;

// ───────────── общие часы ─────────────
let текущее = округлить(Date.now());
const подписчики = new Set<() => void>();
let таймер: ReturnType<typeof setTimeout> | undefined;
let подпискаПриложения: { remove: () => void } | undefined;

function обновить() {
  const новое = округлить(Date.now());
  if (новое === текущее) return;
  текущее = новое;
  for (const п of подписчики) п();
}

function запланировать() {
  clearTimeout(таймер);
  таймер = setTimeout(() => {
    обновить();
    запланировать();
  }, ШАГ - (Date.now() % ШАГ) + 20);
}

function подписаться(п: () => void) {
  подписчики.add(п);
  if (подписчики.size === 1) {
    обновить();
    запланировать();
    подпискаПриложения = AppState.addEventListener('change', (с) => {
      if (с === 'active') {
        обновить();
        запланировать();
      }
    });
  }
  return () => {
    подписчики.delete(п);
    if (подписчики.size === 0) {
      clearTimeout(таймер);
      подпискаПриложения?.remove();
      подпискаПриложения = undefined;
    }
  };
}

const снимокЧасов = () => текущее;

export function useСейчас(заданное?: number): number {
  const сейчас = useSyncExternalStore(подписаться, снимокЧасов, снимокЧасов);
  return заданное ?? сейчас;
}

export function useЧасы<Т extends string | number | boolean | null>(выбор: (сейчас: number) => Т, заданное?: number): Т {
  const снимок = () => выбор(заданное ?? текущее);
  return useSyncExternalStore(подписаться, снимок, снимок);
}

// ───────────── времена дня ─────────────
const кэш = new Map<string, ВременаДня | null>();

export function временаДняКэш(место: Pick<Место, 'широта' | 'долгота'>, день: string): ВременаДня | null {
  const ключ = `${место.широта},${место.долгота},${день}`;
  if (!кэш.has(ключ)) {
    let в: ВременаДня | null = null;
    try {
      в = временаДня({ широта: место.широта, долгота: место.долгота }, день);
    } catch {
      в = null;
    }
    if (кэш.size > 32) кэш.clear();
    кэш.set(ключ, в);
  }
  return кэш.get(ключ) ?? null;
}

export type ДеньНамаза = { сегодня: ВременаДня; завтра: ВременаДня; состояние: СостояниеДня } | null;

export function useДеньНамаза(место: Место, сейчас: number): { день: ДеньНамаза; ошибка: boolean } {
  const день = деньРК(сейчас);
  const { широта, долгота } = место;
  const пара = useMemo(() => {
    const сегодня = временаДняКэш({ широта, долгота }, день);
    const завтра = временаДняКэш({ широта, долгота }, сдвигДня(день, 1));
    return сегодня && завтра ? { сегодня, завтра } : null;
  }, [широта, долгота, день]);
  const состояние = useMemo(() => (пара ? состояниеДня(сейчас, пара.сегодня, пара.завтра) : null), [пара, сейчас]);
  return { день: пара && состояние ? { ...пара, состояние } : null, ошибка: !пара };
}
