/**
 * React-хуки времени намаза: общие «часы» с шагом в минуту и времена дня для выбранного места.
 *
 * Контракт:
 *   useСейчас(заданное?) → мс, округлённые вниз до минуты. Один общий таймер на всё приложение (а не по таймеру
 *     на компонент): срабатывает на границе минуты (+20 мс) и при возврате в приложение (AppState: вкладка или
 *     телефон спали, часы сменились); работает, только пока есть подписчики. Моменты намаза стоят на целых
 *     минутах, а отсчёт округляется вверх до минуты, поэтому шаг в 30 с не давал бы нового текста.
 *     заданное — для тестов и предпросмотра (без таймеров).
 *   useЧасы(выбор, заданное?) → выбор(сейчас) — подписка на те же часы, но компонент перерисовывается, только
 *     когда меняется результат выбора (строка, число, boolean — сравнение Object.is). Пример: фаза дня для
 *     реплики главной — меняется несколько раз в сутки, а не каждую минуту. выбор — чистая функция.
 *   временаДняКэш(место, день, мазхаб?) → ВременаДня | null — для мест Казахстана и Узбекистана при ханафитском асре —
 *     из официальной таблицы ДУМК/УМУз, если она уже на телефоне (prayer/officialStore.ts; владелец 20.11.2026: «один в
 *     один с местными»); иначе — расчёт по методу страны места (prayer/methods.ts). Кэш — несколько дней и мест;
 *     ошибка — null. мазхаб по умолчанию — выбранный (prayer/store.ts).
 *   источникДня(место, день, мазхаб?) → { src, обновлено, точка, метод } | null — откуда время этого дня (null — расчёт).
 *   useДеньНамаза(место, сейчас) → { день: { сегодня, завтра, состояние } | null, ошибка, источник } — пересчёт времён
 *     только при смене места, правила асра, суток места (полночь в поясе места) или пришедшей таблицы, состояния — при
 *     смене «сейчас». Сам просит официальную таблицу (подготовитьОфициальное) — только id пункта, без координат.
 * Отсчёт на экране — в минутах (вверх), секунд и мигания нет (бриф §9: слабые телефоны).
 */
import { useEffect, useMemo, useSyncExternalStore } from 'react';
import { AppState } from 'react-native';
import { деньРК, состояниеДня, сдвигДня, type СостояниеДня } from './day';
import type { Мазхаб } from './methods';
import { пунктОфициальный, временаИзТаблицы, type ТаблицаОфициальная } from './official';
import { подготовитьОфициальное, таблицаОфициальная, версияОфициальных, useВерсияОфициальных } from './officialStore';
import type { Место } from './places';
import { текущийМазхаб, useМазхаб } from './store';
import { временаДня, type ВременаДня } from './times';

const ШАГ = 60_000;
const округлить = (мс: number) => Math.floor(мс / ШАГ) * ШАГ;

// ───────────── общие часы ─────────────
let текущее = округлить(Date.now());
const подписчики = new Set<() => void>();
let таймер: ReturnType<typeof setTimeout> | undefined;
let подпискаПриложения: { remove: () => void } | undefined;

function обновить() {
  const новое = округлить(Date.now());
  if (новое === текущее) return;
  текущее = новое;
  for (const п of подписчики) п();
}

function запланировать() {
  clearTimeout(таймер);
  таймер = setTimeout(() => {
    обновить();
    запланировать();
  }, ШАГ - (Date.now() % ШАГ) + 20);
}

function подписаться(п: () => void) {
  подписчики.add(п);
  if (подписчики.size === 1) {
    обновить();
    запланировать();
    подпискаПриложения = AppState.addEventListener('change', (с) => {
      if (с === 'active') {
        обновить();
        запланировать();
      }
    });
  }
  return () => {
    подписчики.delete(п);
    if (подписчики.size === 0) {
      clearTimeout(таймер);
      подпискаПриложения?.remove();
      подпискаПриложения = undefined;
    }
  };
}

const снимокЧасов = () => текущее;

export function useСейчас(заданное?: number): number {
  const сейчас = useSyncExternalStore(подписаться, снимокЧасов, снимокЧасов);
  return заданное ?? сейчас;
}

export function useЧасы<Т extends string | number | boolean | null>(выбор: (сейчас: number) => Т, заданное?: number): Т {
  const снимок = () => выбор(заданное ?? текущее);
  return useSyncExternalStore(подписаться, снимок, снимок);
}

// ───────────── времена дня ─────────────
const кэш = new Map<string, ВременаДня | null>();

type МестоДляВремени = Pick<Место, 'широта' | 'долгота'> & Partial<Pick<Место, 'страна' | 'id' | 'вид' | 'ближайшее'>>;

/** Официальная таблица для дня места (только ханафитский аср: так считают и ДУМК, и УМУз). */
function таблицаДня(место: МестоДляВремени, день: string, мазхаб: Мазхаб): ТаблицаОфициальная | null {
  if (мазхаб !== 'hanafi' || !место.id || !место.вид) return null;
  const п = пунктОфициальный({ id: место.id, вид: место.вид, страна: место.страна ?? 'KZ', ближайшее: место.ближайшее });
  return п ? таблицаОфициальная(п.src, п.id, Number(день.slice(0, 4))) : null;
}

export function источникДня(
  место: МестоДляВремени,
  день: string,
  мазхаб: Мазхаб = текущийМазхаб(),
): { src: ТаблицаОфициальная['src']; обновлено: string; точка: ТаблицаОфициальная['точка']; метод: ТаблицаОфициальная['метод'] } | null {
  const т = таблицаДня(место, день, мазхаб);
  return т && временаИзТаблицы(т, день) ? { src: т.src, обновлено: т.обновлено, точка: т.точка, метод: т.метод } : null;
}

export function временаДняКэш(место: МестоДляВремени, день: string, мазхаб: Мазхаб = текущийМазхаб()): ВременаДня | null {
  const страна = место.страна ?? 'KZ';
  const т = таблицаДня(место, день, мазхаб);
  if (т) {
    const в = временаИзТаблицы(т, день);
    if (в) return в;
  }
  const ключ = `${место.широта},${место.долгота},${страна},${мазхаб},${день}`;
  if (!кэш.has(ключ)) {
    let в: ВременаДня | null = null;
    try {
      в = временаДня({ широта: место.широта, долгота: место.долгота }, день, { страна, мазхаб });
    } catch {
      в = null;
    }
    if (кэш.size > 32) кэш.clear();
    кэш.set(ключ, в);
  }
  return кэш.get(ключ) ?? null;
}

export type ДеньНамаза = { сегодня: ВременаДня; завтра: ВременаДня; состояние: СостояниеДня } | null;
export type ИсточникДня = ReturnType<typeof источникДня>;

export function useДеньНамаза(место: Место, сейчас: number): { день: ДеньНамаза; ошибка: boolean; источник: ИсточникДня } {
  const { мазхаб } = useМазхаб();
  const версия = useВерсияОфициальных();
  const день = деньРК(сейчас, место.пояс);
  const { широта, долгота, страна, id, вид, ближайшее } = место;
  const ближайшееId = ближайшее?.id;
  const ближайшееКм = ближайшее?.км;
  useEffect(() => {
    подготовитьОфициальное({ id, вид, страна, ближайшее: ближайшееId ? { id: ближайшееId, км: ближайшееКм ?? Infinity } : undefined }, день);
  }, [id, вид, страна, ближайшееId, ближайшееКм, день]);
  const пара = useMemo(() => {
    const м = { широта, долгота, страна, id, вид, ближайшее: ближайшееId ? { id: ближайшееId, км: ближайшееКм ?? Infinity } : undefined };
    const сегодня = временаДняКэш(м, день, мазхаб);
    const завтра = временаДняКэш(м, сдвигДня(день, 1), мазхаб);
    return сегодня && завтра ? { сегодня, завтра, источник: источникДня(м, день, мазхаб) } : null;
    // версия — пришла официальная таблица: пересчитать
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [широта, долгота, страна, id, вид, ближайшееId, ближайшееКм, мазхаб, день, версия]);
  const состояние = useMemo(() => (пара ? состояниеДня(сейчас, пара.сегодня, пара.завтра) : null), [пара, сейчас]);
  return {
    день: пара && состояние ? { сегодня: пара.сегодня, завтра: пара.завтра, состояние } : null,
    ошибка: !пара,
    источник: пара?.источник ?? null,
  };
}

