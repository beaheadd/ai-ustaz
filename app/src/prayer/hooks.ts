/**
 * React-хуки времени намаза: «сейчас» с шагом 30 с и времена дня для выбранного места.
 *
 * Контракт:
 *   useСейчас(заданное?) → мс, округлённые вниз до 30 с. Обновляется на границе :00/:30 (setTimeout до неё,
 *     не setInterval(1000)) и при возврате в приложение (AppState: вкладка/телефон спали, часы сменились).
 *     Одинаковое значение не перерисовывает экран. заданное — для тестов/предпросмотра (без таймеров).
 *   useДеньНамаза(место, сейчас) → { сегодня, завтра, состояние, ошибка } — пересчёт только при смене места
 *     или суток РК (полночь UTC+5), не каждые 30 с. ошибка — расчёт не удался (такого в РК не бывает).
 * Отсчёт на экране — в минутах (вверх), секунд и мигания нет (бриф §9: слабые телефоны).
 */
import { useEffect, useMemo, useState } from 'react';
import { AppState } from 'react-native';
import { деньРК, состояниеДня, сдвигДня, type СостояниеДня } from './day';
import type { Место } from './places';
import { временаДня, type ВременаДня } from './times';

const ШАГ = 30_000;
const округлить = (мс: number) => Math.floor(мс / ШАГ) * ШАГ;

export function useСейчас(заданное?: number): number {
  const [сейчас, установить] = useState(() => заданное ?? округлить(Date.now()));
  useEffect(() => {
    if (заданное !== undefined) return;
    let таймер: ReturnType<typeof setTimeout> | undefined;
    const обновить = () => установить(округлить(Date.now()));
    const запланировать = () => {
      clearTimeout(таймер);
      таймер = setTimeout(() => {
        обновить();
        запланировать();
      }, ШАГ - (Date.now() % ШАГ) + 20);
    };
    обновить();
    запланировать();
    const подписка = AppState.addEventListener('change', (с) => {
      if (с === 'active') {
        обновить();
        запланировать();
      }
    });
    return () => {
      clearTimeout(таймер);
      подписка.remove();
    };
  }, [заданное]);
  return заданное ?? сейчас;
}

export type ДеньНамаза = { сегодня: ВременаДня; завтра: ВременаДня; состояние: СостояниеДня } | null;

export function useДеньНамаза(место: Место, сейчас: number): { день: ДеньНамаза; ошибка: boolean } {
  const день = деньРК(сейчас);
  const { широта, долгота } = место;
  const пара = useMemo(() => {
    try {
      return { сегодня: временаДня({ широта, долгота }, день), завтра: временаДня({ широта, долгота }, сдвигДня(день, 1)) };
    } catch {
      return null;
    }
  }, [широта, долгота, день]);
  const состояние = useMemo(() => (пара ? состояниеДня(сейчас, пара.сегодня, пара.завтра) : null), [пара, сейчас]);
  return { день: пара && состояние ? { ...пара, состояние } : null, ошибка: !пара };
}
