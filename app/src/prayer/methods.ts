export function методСтраны(страна: string | undefined): Метод {
  return МЕТОДЫ[(страна && МЕТОД_СТРАНЫ[страна]) || 'mwl'];
}

export function поправкиМетода(метод: Метод, широта: number): Record<Ключ, number> {
  if (метод.поправки === 'думк') return поправкиДУМК(широта);
  return { fajr: 0, sunrise: 0, dhuhr: 0, asr: 0, maghrib: 0, isha: 0, ...метод.поправки };
}

/**
 * Подпись под временем: «Расчёт по методу ДУМК (±1 мин)», «Расчёт по методу Управления мусульман Узбекистана
 * (уточняется)», «Расчёт по стандарту Центральной Азии (15°/15°)»; если аср считаем не так, как ведомство, —
 * «· аср — ханафитский». kk — черновик для редактора-носителя.
 */
export function подписьМетода(метод: Метод, мазхаб: Мазхаб, язык: 'ru' | 'kk' | 'uz'): string {
  const в = метод.ведомство[язык];
  const стандарт = в.startsWith('стандарт') || в.includes('стандарты') || в.includes('standarti');
  const хвост =
    метод.статус === 'сверено' && метод.точность
      ? ` (±${метод.точность} ${язык === 'uz' ? 'daq.' : 'мин'})`
      : метод.статус === 'оценка'
        ? { ru: ' (уточняется)', kk: ' (нақтыланады)', uz: ' (aniqlanmoqda)' }[язык]
        : '';
  const основа =
    язык === 'kk'
      ? `${в} ${стандарт ? 'бойынша' : 'әдісімен'} есептелді${хвост}`
      : язык === 'uz'
        ? `${в} ${стандарт ? 'boʻyicha' : 'usuli boʻyicha'} hisoblangan${хвост}`
        : `Расчёт по ${стандарт ? '' : 'методу '}${в}${хвост}`;
  if (мазхаб === метод.мазхаб) return основа;
  const аср = {
    ru: мазхаб === 'hanafi' ? 'аср — ханафитский' : 'аср — шафиитский',
    kk: мазхаб === 'hanafi' ? 'екінті — ханафи' : 'екінті — шафиғи',
    uz: мазхаб === 'hanafi' ? 'asr — hanafiy' : 'asr — shofeʼiy',
  }[язык];
  return `${основа} · ${аср}`;
}
