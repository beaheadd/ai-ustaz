/**
 * Время намаза для любой точки мира — расчёт на устройстве (чистые функции, без сети).
 *
 * Назначение: шесть времён календарного дня места (фаджр, восход, зухр, аср, магриб, иша) по методу страны места
 * (prayer/methods.ts: KZ — ДУМК, UZ — УМУз, TR — Диянет, SA — Умм аль-Кура, … остальной мир — MWL) и выбранному
 * правилу асра (по умолчанию — ханафитский).
 * Метод ДУМК подтверждён исходником muftyat.kz (praytimes.js) и сверкой с таблицами api.muftyat.kz за 2026 г.
 * (docs/исследование/13-время-намаза-думк.md): 15°/15°, аср ханафи, TwilightAngle, поправки ±3/±5 к округлённым минутам.
 * Остальные методы и сверка — docs/исследование/15-время-намаза-мир.md.
 * Округление — до ближайшей минуты (≥ 30 с — вверх), как у ДУМК и adhan-js.
 *
 * Контракт:
 *   временаДня(точка, день, опции?) → ВременаДня: моменты UTC (мс), кратные минуте; день — 'ГГГГ-ММ-ДД' — календарный
 *     день МЕСТА (в его часовом поясе: prayer/day.ts деньРК(мс, пояс)).
 *     опции: { страна?: 'KZ' (по умолчанию), мазхаб?: 'hanafi' (по умолчанию) }.
 *   поправкиДУМК(широта) → поправки ДУМК в минутах (реэкспорт из methods.ts).
 *   КЛЮЧИ_ВРЕМЁН — порядок дня: fajr, sunrise, dhuhr, asr, maghrib, isha.
 * Бросает ошибку на неверной строке дня или если расчёт не дал времени (полярный день/ночь: солнце не садится или
 * не встаёт — экран показывает «не удалось посчитать»).
 *
 * Решения: считаем сами — письменного разрешения ДУМК на их таблицы нет (19.11.2026); подпись «Расчёт по методу …»,
 * не «по данным …». Зависимость: adhan@4.4.6 (MIT), без изменений. Модуль импортирует только methods.ts (node снимает
 * типы сам — scripts/test-prayer.mjs).
 * Владелец 20.11.2026: «Мы мировое приложение. У нас должно быть все времени намаза в мире.»
 */
import { CalculationParameters, Coordinates, HighLatitudeRule, Madhab, PrayerTimes, Rounding } from 'adhan';
import { методСтраны, поправкиДУМК, поправкиМетода, ГРАНИЦА_ШИРОТЫ_ДУМК, type Мазхаб, type Метод } from './methods.ts';

export { поправкиДУМК };

export type КлючВремени = 'fajr' | 'sunrise' | 'dhuhr' | 'asr' | 'maghrib' | 'isha';

/** Порядок дня — как в таблицах ДУМК и в мечети (восход — после фаджра: им заканчивается время фаджра). */
export const КЛЮЧИ_ВРЕМЁН: readonly КлючВремени[] = ['fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha'];

/** Календарный день места: 'ГГГГ-ММ-ДД' (имя осталось от РК; для мира — день в поясе места). */
export type ДеньРК = string;

export type Точка = { широта: number; долгота: number };

/** Шесть моментов (UTC, мс от эпохи, ровно на минуте) и день, на который они посчитаны. */
export type ВременаДня = { день: ДеньРК } & Record<КлючВремени, number>;

export type ОпцииРасчёта = { страна?: string; мазхаб?: Мазхаб };

/** Широта, с которой ДУМК берёт поправки ±5 вместо ±3. */
export const ГРАНИЦА_ШИРОТЫ = ГРАНИЦА_ШИРОТЫ_ДУМК;

const ПРАВИЛО: Record<Exclude<Метод['высокиеШироты'], 'recommended'>, 'middleofthenight' | 'seventhofthenight' | 'twilightangle'> = {
  twilightAngle: HighLatitudeRule.TwilightAngle,
  seventh: HighLatitudeRule.SeventhOfTheNight,
  middle: HighLatitudeRule.MiddleOfTheNight,
};

function параметры(метод: Метод, точка: Точка, мазхаб: Мазхаб): CalculationParameters {
  // 'Other' — без методических поправок adhan: все поправки метода — в таблице methods.ts.
  const иша = метод.иша;
  const п =
    typeof иша === 'number'
      ? new CalculationParameters('Other', метод.фаджр, иша, 0, метод.магрибУгол ?? 0)
      : new CalculationParameters('Other', метод.фаджр, 0, иша.минут, метод.магрибУгол ?? 0);
  п.madhab = мазхаб === 'shafi' ? Madhab.Shafi : Madhab.Hanafi;
  п.highLatitudeRule =
    метод.высокиеШироты === 'recommended'
      ? HighLatitudeRule.recommended(new Coordinates(точка.широта, точка.долгота))
      : ПРАВИЛО[метод.высокиеШироты];
  п.rounding = Rounding.Nearest;
  п.adjustments = поправкиМетода(метод, точка.широта);
  return п;
}

const ДЕНЬ = /^(\d{4})-(\d{2})-(\d{2})$/;
const МИНУТА = 60_000;

/**
 * Шесть времён на календарный день места. adhan-js берёт дату из ЛОКАЛЬНЫХ полей Date устройства, поэтому дата
 * строится в поясе устройства на полдень: поля совпадают с днём места при любом поясе телефона.
 * После правила высоких широт у моментов остаются доли секунды — отбрасываем до минуты.
 */
export function временаДня(точка: Точка, день: ДеньРК, опции: ОпцииРасчёта = {}): ВременаДня {
  const р = ДЕНЬ.exec(день);
  if (!р) throw new Error('день: ожидается ГГГГ-ММ-ДД');
  const дата = new Date(Number(р[1]), Number(р[2]) - 1, Number(р[3]), 12, 0, 0);
  const метод = методСтраны(опции.страна ?? 'KZ');
  const в = new PrayerTimes(new Coordinates(точка.широта, точка.долгота), дата, параметры(метод, точка, опции.мазхаб ?? 'hanafi'));
  const итог = { день } as ВременаДня;
  for (const к of КЛЮЧИ_ВРЕМЁН) {
    const м = в[к];
    const мс = м instanceof Date ? м.getTime() : NaN;
    if (!Number.isFinite(мс)) throw new Error(`нет времени ${к}: ${точка.широта}, ${точка.долгота}, ${день}`);
    итог[к] = Math.floor(мс / МИНУТА) * МИНУТА;
  }
  return итог;
}
