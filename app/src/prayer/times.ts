/**
 * Время намаза по методу ДУМК — расчёт на устройстве (чистые функции, без сети).
 *
 * Назначение: шесть времён календарного дня РК (таң, восход, бесін, екінті, ақшам, құптан) для точки.
 * Метод ДУМК подтверждён исходником muftyat.kz (praytimes.js, calculateTimes) и сверкой с таблицами
 * api.muftyat.kz за все дни 2026 г.: docs/исследование/13-время-намаза-думк.md.
 *   - фаджр и иша — 15° (ISNA), аср — ханафи, высокие широты — TwilightAngle (= AngleBased, доля ночи 15/60);
 *   - поправки к округлённым минутам: восход −3, зухр/аср/магриб +3 южнее 48° с. ш.; −5/+5 на 48° и севернее;
 *   - пояс — UTC+5 (вся РК с 01.03.2024); округление до ближайшей минуты (≥ 30 с — вверх).
 * Точность: adhan-js с этими параметрами расходится с таблицами ДУМК не больше чем на 1 мин (сверка
 * прототипа 19.11.2026: 163 места × 365 дней); отсюда подпись «Расчёт по методу ДУМК (±1 мин)».
 * Эталон для теста — Python-версия tools/prayer/compare_dumk.py (adhanpy): scripts/test-prayer.mjs
 * сверяет с её фикстурой (scripts/fixtures/prayer-reference.json, свои расчёты, НЕ таблицы ДУМК).
 *
 * Контракт:
 *   временаДня(точка, день) → ВременаДня: моменты UTC (мс), кратные минуте; день — 'ГГГГ-ММ-ДД' (сутки РК).
 *   поправкиДУМК(широта)    → поправки в минутах по ключам.
 *   КЛЮЧИ_ВРЕМЁН            — порядок дня: fajr, sunrise, dhuhr, asr, maghrib, isha.
 * Бросает ошибку только на неверной строке дня или если расчёт не дал времени (вне РК — не вызываем).
 *
 * Решения: считаем сами — письменного разрешения ДУМК на их таблицы нет (19.11.2026); подпись
 * «Расчёт по методу ДУМК», не «по данным ДУМК». Зависимость: adhan@4.4.6 (MIT), без изменений.
 * Модуль без импортов своих файлов (node снимает типы сам — scripts/test-prayer.mjs).
 */
import { CalculationParameters, Coordinates, HighLatitudeRule, Madhab, PrayerTimes, Rounding } from 'adhan';

export type КлючВремени = 'fajr' | 'sunrise' | 'dhuhr' | 'asr' | 'maghrib' | 'isha';

/** Порядок дня — как в таблицах ДУМК и в мечети (восход — после таң: им заканчивается время таң). */
export const КЛЮЧИ_ВРЕМЁН: readonly КлючВремени[] = ['fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha'];

/** Календарный день РК: 'ГГГГ-ММ-ДД'. */
export type ДеньРК = string;

export type Точка = { широта: number; долгота: number };

/** Шесть моментов (UTC, мс от эпохи, ровно на минуте) и день, на который они посчитаны. */
export type ВременаДня = { день: ДеньРК } & Record<КлючВремени, number>;

/** Широта, с которой ДУМК берёт поправки ±5 вместо ±3. */
export const ГРАНИЦА_ШИРОТЫ = 48;

/** Поправки ДУМК в минутах (к округлённому времени). Таң и құптан — без поправок. */
export function поправкиДУМК(широта: number): Record<КлючВремени, number> {
  const п = широта >= ГРАНИЦА_ШИРОТЫ ? 5 : 3;
  return { fajr: 0, sunrise: -п, dhuhr: п, asr: п, maghrib: п, isha: 0 };
}

function параметрыДУМК(широта: number): CalculationParameters {
  // 'Other' 15°/15° — как ISNA, но без методической поправки +1 мин к зухру (её у ДУМК нет).
  const п = new CalculationParameters('Other', 15, 15);
  п.madhab = Madhab.Hanafi;
  п.highLatitudeRule = HighLatitudeRule.TwilightAngle;
  п.rounding = Rounding.Nearest;
  п.adjustments = поправкиДУМК(широта);
  return п;
}

const ДЕНЬ = /^(\d{4})-(\d{2})-(\d{2})$/;
const МИНУТА = 60_000;

/**
 * Шесть времён на календарный день РК. adhan-js берёт дату из ЛОКАЛЬНЫХ полей Date устройства, поэтому
 * дата строится в поясе устройства на полдень: поля совпадают с днём РК при любом поясе телефона.
 * После правила высоких широт у моментов остаются доли секунды — отбрасываем до минуты.
 */
export function временаДня(точка: Точка, день: ДеньРК): ВременаДня {
  const р = ДЕНЬ.exec(день);
  if (!р) throw new Error('день: ожидается ГГГГ-ММ-ДД');
  const дата = new Date(Number(р[1]), Number(р[2]) - 1, Number(р[3]), 12, 0, 0);
  const в = new PrayerTimes(new Coordinates(точка.широта, точка.долгота), дата, параметрыДУМК(точка.широта));
  const итог = { день } as ВременаДня;
  for (const к of КЛЮЧИ_ВРЕМЁН) {
    const м = в[к];
    const мс = м instanceof Date ? м.getTime() : NaN;
    if (!Number.isFinite(мс)) throw new Error(`нет времени ${к}: ${точка.широта}, ${точка.долгота}, ${день}`);
    итог[к] = Math.floor(мс / МИНУТА) * МИНУТА;
  }
  return итог;
}
