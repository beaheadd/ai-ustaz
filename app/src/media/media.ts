/**
 * Видео и аудио учителей-партнёров к урокам: проверка формы /content/media.json и правила показа.
 *
 * Решение владельца 19.11.2026: в каждом уроке — видео, аудио и объяснение. Видео и аудио — от учителей-
 * партнёров (шейх Алижон кари, Еркінбек Шоқай, д-р Айман Сувайд). Разрешений авторов пока нет — договор
 * ведёт владелец. Поэтому ученик видит видео и аудио источника, ТОЛЬКО если в данных «разрешено: true»
 * (content/media.json → источники.<id>.разрешено). Предпросмотр для владельца (флаг сборки
 * EXPO_PUBLIC_MEDIA_PREVIEW=1, media/flag.ts) показывает и неразрешённое — с красной плашкой.
 *
 * Контракт (чистые функции, без React и без импортов кода — проверяются в node):
 *   проверитьМедиа(сырые) → МедиаДанные | null   — форма; кривые записи отбрасываются, не показываются
 *   материалыУрока(медиа, номер, предпросмотр) → { видео: ПоказВидео[], аудио: ПоказАудио[] }
 *       только то, что можно показать: разрешено (или предпросмотр); видео — основное, потом дополнительное
 *   клипыКари(материалы) → Map<текст, ПоказАудио>  — для кнопки «Послушать кари» в упражнениях
 *   ЭТО_ССЫЛКА_YOUTUBE, ЭТО_СВОЙ_ФАЙЛ_ВИДЕО, ЭТО_СВОЙ_ФАЙЛ_АУДИО — образцы допустимых адресов
 *
 * Без встраивания YouTube (iframe — реклама и метки Google, CLAUDE.md «без рекламы и трекинга»):
 * видео без своего файла открывается ссылкой youtube.com/watch во внешнем приложении/вкладке.
 * Свои файлы — только относительные пути media/… (CSP media-src 'self'). Синтеза голоса нет.
 */
import type { АудиоКлип, ВидеоУрока, ИсточникМедиа, ЛокализованныйТекст, МедиаДанные, МедиаУрока, СтатусКонтента } from '../content/types';

export const ЭТО_ССЫЛКА_YOUTUBE = /^https:\/\/www\.youtube\.com\/watch\?v=([A-Za-z0-9_-]{11})$/;
export const ЭТО_СВОЙ_ФАЙЛ_ВИДЕО = /^media\/(?!.*\.\.)(?!.*\/\/)[A-Za-z0-9_./-]+\.(mp4|webm)$/;
export const ЭТО_СВОЙ_ФАЙЛ_АУДИО = /^media\/(?!.*\.\.)(?!.*\/\/)[A-Za-z0-9_./-]+\.(m4a|mp3|ogg|opus|webm)$/;

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
function строка(з: unknown): з is string {
  return typeof з === 'string' && з.length > 0;
}
function локализованный(з: unknown): з is ЛокализованныйТекст {
  const т = объект(з);
  return !!т && typeof т.ru === 'string' && typeof т.kk === 'string' && (т.ru.length > 0 || т.kk.length > 0);
}

function проверитьИсточник(id: string, з: unknown): ИсточникМедиа | null {
  const и = объект(з);
  if (!и || !локализованный(и.имя) || !локализованный(и.атрибуция)) return null;
  return {
    id,
    имя: и.имя,
    канал: строка(и.канал) ? и.канал : '',
    ссылкаКанала: строка(и.ссылка_канала) && !и.ссылка_канала.includes('://') ? и.ссылка_канала : '',
    курс: строка(и.курс) ? и.курс : '',
    язык: строка(и.язык) ? и.язык : '',
    // Строго true: всё остальное (нет поля, строка «true», 1) — нет разрешения.
    разрешено: и.разрешено === true,
    датаРазрешения: строка(и.дата_разрешения) ? и.дата_разрешения : null,
    условия: строка(и.условия) ? и.условия : '',
    атрибуция: и.атрибуция,
  };
}

function проверитьВидео(з: unknown, источники: Record<string, ИсточникМедиа>): ВидеоУрока | null {
  const в = объект(з);
  if (!в || !строка(в.источник) || !источники[в.источник] || !строка(в.youtube_id) || !строка(в.ссылка)) return null;
  const м = ЭТО_ССЫЛКА_YOUTUBE.exec(в.ссылка);
  if (!м || м[1] !== в.youtube_id) return null;
  if (в.роль !== 'основное' && в.роль !== 'дополнительно') return null;
  return {
    источник: в.источник,
    youtubeId: в.youtube_id,
    название: строка(в.название) ? в.название : '',
    роль: в.роль,
    ссылка: в.ссылка,
    файлВидео: строка(в.файл_видео) && ЭТО_СВОЙ_ФАЙЛ_ВИДЕО.test(в.файл_видео) ? в.файл_видео : null,
    показывать: в.показывать === true,
  };
}

function проверитьКлип(з: unknown, источники: Record<string, ИсточникМедиа>): АудиоКлип | null {
  const а = объект(з);
  if (!а || !строка(а.текст) || !строка(а.файл) || !ЭТО_СВОЙ_ФАЙЛ_АУДИО.test(а.файл)) return null;
  if (!строка(а.источник) || !источники[а.источник]) return null;
  return { текст: а.текст, файл: а.файл, источник: а.источник };
}

export function проверитьМедиа(сырые: unknown): МедиаДанные | null {
  const д = объект(сырые);
  const сырыеИсточники = объект(д?.источники);
  if (!д || !сырыеИсточники || !Array.isArray(д.уроки)) return null;
  const источники: Record<string, ИсточникМедиа> = {};
  for (const [id, з] of Object.entries(сырыеИсточники)) {
    const и = проверитьИсточник(id, з);
    if (и) источники[id] = и;
  }
  const уроки: МедиаУрока[] = [];
  for (const з of д.уроки as unknown[]) {
    const у = объект(з);
    if (!у || typeof у.номер !== 'number' || !Number.isInteger(у.номер)) continue;
    уроки.push({
      номер: у.номер,
      id: строка(у.id) ? у.id : String(у.номер),
      уровень: typeof у.уровень === 'number' ? у.уровень : 0,
      видео: Array.isArray(у.видео) ? у.видео.map((в) => проверитьВидео(в, источники)).filter((в): в is ВидеоУрока => в != null) : [],
      аудио: Array.isArray(у.аудио) ? у.аудио.map((а) => проверитьКлип(а, источники)).filter((а): а is АудиоКлип => а != null) : [],
    });
  }
  const статусы: readonly СтатусКонтента[] = ['черновик', 'проверен-устазом', 'подписан-советом'];
  return {
    версия: строка(д.версия) ? д.версия : '—',
    статус: (статусы as readonly unknown[]).includes(д.статус) ? (д.статус as СтатусКонтента) : 'черновик',
    источники,
    уроки,
  };
}

/** Видео, готовое к показу: с источником и пометкой «без разрешения» (только в предпросмотре). */
export type ПоказВидео = ВидеоУрока & { автор: ИсточникМедиа; безРазрешения: boolean };
export type ПоказАудио = АудиоКлип & { автор: ИсточникМедиа; безРазрешения: boolean };
export type МатериалыМедиа = { видео: ПоказВидео[]; аудио: ПоказАудио[] };

/** Разрешено ли показать ученику: автор разрешил (и генератор отметил видео показываемым). */
function разрешеноВидео(в: ВидеоУрока, и: ИсточникМедиа): boolean {
  return и.разрешено === true && в.показывать === true;
}

export function материалыУрока(медиа: МедиаДанные | null, номер: number, предпросмотр: boolean): МатериалыМедиа {
  const урок = медиа?.уроки.find((у) => у.номер === номер);
  if (!медиа || !урок) return { видео: [], аудио: [] };
  const видео: ПоказВидео[] = [];
  for (const роль of ['основное', 'дополнительно'] as const) {
    for (const в of урок.видео) {
      const автор = медиа.источники[в.источник];
      if (в.роль !== роль || !автор) continue;
      const можно = разрешеноВидео(в, автор);
      if (можно || предпросмотр) видео.push({ ...в, автор, безРазрешения: !можно });
    }
  }
  const аудио: ПоказАудио[] = [];
  for (const а of урок.аудио) {
    const автор = медиа.источники[а.источник];
    if (!автор) continue;
    if (автор.разрешено || предпросмотр) аудио.push({ ...а, автор, безРазрешения: !автор.разрешено });
  }
  return { видео, аудио };
}

/** Клип кари по точному тексту буквы/слога (первый по порядку данных). */
export function клипыКари(материалы: МатериалыМедиа): Map<string, ПоказАудио> {
  const карта = new Map<string, ПоказАудио>();
  for (const а of материалы.аудио) if (!карта.has(а.текст)) карта.set(а.текст, а);
  return карта;
}
