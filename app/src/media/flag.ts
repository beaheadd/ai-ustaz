/**
 * Предпросмотр видео и аудио партнёров для владельца. ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ.
 *
 * Решение владельца 19.11.2026: видео и аудио учителей-партнёров ученики видят только с разрешением автора
 * (content/media.json → источники.<id>.разрешено). Чтобы владелец увидел, как это будет выглядеть, есть
 * отдельная сборка с флагом EXPO_PUBLIC_MEDIA_PREVIEW=1: блоки видео и аудио видны и без разрешения,
 * с красной плашкой «Предпросмотр: нет разрешения автора — ученики этого не видят».
 * Обычная сборка (для batr.kz) — без флага; scripts/after-export.mjs ставит метку aiustaz-media-preview,
 * а check-dist не пропускает «on» без MUGALIM_TARGET=preview.
 *
 * Контракт: предпросмотрМедиа() → boolean; предпросмотрПоФлагу(флаг) — чистая функция (тест).
 * Без импортов: файл проверяется в node.
 */

export function предпросмотрПоФлагу(флаг: string | undefined): boolean {
  return флаг === '1';
}

/** Обращение — строго `process.env.EXPO_PUBLIC_MEDIA_PREVIEW`: Expo заменяет при сборке именно это выражение. */
function флагСборки(): string | undefined {
  try {
    return process.env.EXPO_PUBLIC_MEDIA_PREVIEW;
  } catch {
    return undefined;
  }
}

export function предпросмотрМедиа(): boolean {
  return предпросмотрПоФлагу(флагСборки());
}
