/**
 * Можно ли здесь включить уведомления о времени намаза и что объяснить, если нельзя — чистая функция (без импортов,
 * кроме типов; тест — scripts/test-notify.mjs).
 *
 * Решение ведущего 20.11.2026 (по образцу проверки голосом, speech/flag.ts): уведомления — ТОЛЬКО на своём домене
 * aiustaz.pro; на batr.kz их нет (там свой service worker со scope «/», реклама и чужие скрипты вокруг) — пояснение
 * «уведомления — на aiustaz.pro». Прочие адреса (localhost, тест) — как batr.kz.
 *
 * Контракт:
 *   поддержкаУведомлений(среда, есть) → ПоддержкаУведомлений:
 *     'можно'          — aiustaz.pro и в браузере есть service worker, PushManager и Notification;
 *     'batr'           — batr.kz (и другие адреса): объяснить, что уведомления — на aiustaz.pro;
 *     'ios-домой'      — iPhone/iPad, страница открыта НЕ с экрана «Домой»: Web Push в iOS (16.4+) работает только у
 *                        приложения на экране «Домой» — объяснить и дать ссылку на #/install;
 *     'ios-старый'     — iOS ниже 16.4 (даже с экрана «Домой» уведомлений нет);
 *     'нет-поддержки'  — браузер без Push (встроенные браузеры соцсетей, старые) — «откройте в Chrome/Safari».
 *   есть — { sw: 'serviceWorker' in navigator, push: 'PushManager' in window, уведомления: 'Notification' in window }.
 */
import type { Среда } from '../install/platform';

export type ПоддержкаУведомлений = 'можно' | 'batr' | 'ios-домой' | 'ios-старый' | 'нет-поддержки';

export type ЕстьВБраузере = { sw: boolean; push: boolean; уведомления: boolean };

export function поддержкаУведомлений(среда: Pick<Среда, 'хост' | 'ос' | 'версияIOS' | 'установлено' | 'встроенный'>, есть: ЕстьВБраузере): ПоддержкаУведомлений {
  if (среда.хост !== 'свой') return 'batr';
  const всё = есть.sw && есть.push && есть.уведомления;
  if (среда.ос === 'ios') {
    const в = среда.версияIOS; // нет версии в userAgent — не гадаем, что iOS старая
    if (в && (в[0] < 16 || (в[0] === 16 && в[1] < 4))) return 'ios-старый';
    if (!среда.установлено) return 'ios-домой';
    return всё ? 'можно' : 'нет-поддержки';
  }
  if (среда.встроенный) return 'нет-поддержки';
  return всё ? 'можно' : 'нет-поддержки';
}
