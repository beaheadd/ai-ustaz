/**
 * Расписание уведомлений о времени намаза на 30 дней — чистые функции (без React, без сети, без часов).
 *
 * Владелец 20.11.2026 (скрин уведомлений Muslim Pro): «Нам тоже нужно добавить уведомления, чтобы правильные, красивые
 * уведомления время намаза приходило к клиенту.» Дизайн и приватность — docs/дизайн/07-уведомления.md.
 *
 * Приватность (решение ведущего 20.11.2026): время намаза считает ТЕЛЕФОН (prayer/times.ts, метод ДУМК), на сервер уходят
 * только моменты (UTC), ключ намаза, местное время строкой, ключ «следующего» — и НИКАКИХ координат. Сервер
 * (server/push.py) проверяет то же: местное время = момент по Алматы (UTC+5), не больше 12 пунктов в сутки и 31 дня.
 *
 * Контракт:
 *   собратьРасписание({ сейчас, времена, намазы, заранее, дней? }) → ПунктРасписания[] по возрастанию at:
 *     времена(день 'ГГГГ-ММ-ДД') → ВременаДня | null — расчёт для выбранного места (prayer/hooks.ts временаДняКэш);
 *     для каждого выбранного времени — пункт в момент начала (с next — следующий НАМАЗ: восход следующим не бывает,
 *     после иши — фаджр завтра) и, если заранее > 0, напоминание at = момент − заранее мин (без next);
 *     только at в (сейчас; сейчас + дней × 24 ч] — прошедшее не шлём.
 *   концаРасписания(пункты) → мс последнего пункта или null.
 *   НастройкиУведомлений, ПО_УМОЛЧАНИЮ, разобратьНастройки(сырое) — сохранённые настройки (notify/store.ts): кривое —
 *     значения по умолчанию (выключено, восход выключен, без напоминания).
 *   ВАРИАНТЫ_ЗАРАНЕЕ, НАМАЗЫ_ПО_УМОЛЧАНИЮ (восход выключен), ДНЕЙ_РАСПИСАНИЯ = 30, ключ дня деньРК/чч_мм (UTC+5).
 * В РК нет перехода на летнее время (вся РК — UTC+5 с 01.03.2024): граница DST не нужна.
 * Модуль без импортов своих файлов, кроме типов (node снимает типы сам — scripts/test-notify.mjs).
 */
import type { ВременаДня, КлючВремени } from '../prayer/times';

export type Заранее = 0 | 5 | 10 | 15 | 30;
export const ВАРИАНТЫ_ЗАРАНЕЕ: readonly Заранее[] = [0, 5, 10, 15, 30];
export type ВыборНамазов = Record<КлючВремени, boolean>;
/** Восход по умолчанию выключен: это не намаз (им заканчивается время фаджра). */
export const НАМАЗЫ_ПО_УМОЛЧАНИЮ: Readonly<ВыборНамазов> = { fajr: true, sunrise: false, dhuhr: true, asr: true, maghrib: true, isha: true };
export const ДНЕЙ_РАСПИСАНИЯ = 30;
export const ПОРЯДОК: readonly КлючВремени[] = ['fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha'];

export type ПунктРасписания = {
  /** Момент показа, мс UTC (ровно на минуте). */
  at: number;
  key: КлючВремени;
  /** Местное время НАМАЗА «14:39» (у напоминания — тоже время намаза, не момент показа). */
  time: string;
  before: Заранее;
  next?: { key: КлючВремени; time: string };
};

const МИНУТА = 60_000;
const ДЕНЬ = 86_400_000;
const СДВИГ_РК = 5 * 60 * 60_000;

export function деньРК(мс: number): string {
  return new Date(мс + СДВИГ_РК).toISOString().slice(0, 10);
}

export function чч_мм(мс: number): string {
  return new Date(мс + СДВИГ_РК).toISOString().slice(11, 16);
}

export function сдвигДня(день: string, n: number): string {
  const [г, м, ч] = день.split('-').map(Number);
  return new Date(Date.UTC(г, м - 1, ч + n)).toISOString().slice(0, 10);
}

/** Следующий намаз после ключа (восход пропускаем; после иши — фаджр завтра). */
function следующий(ключ: КлючВремени, сегодня: ВременаДня, завтра: ВременаДня | null): { key: КлючВремени; time: string } | undefined {
  const намазы: КлючВремени[] = ['fajr', 'dhuhr', 'asr', 'maghrib', 'isha'];
  if (ключ === 'isha') return завтра ? { key: 'fajr', time: чч_мм(завтра.fajr) } : undefined;
  const после = намазы.find((к) => ПОРЯДОК.indexOf(к) > ПОРЯДОК.indexOf(ключ));
  return после ? { key: после, time: чч_мм(сегодня[после]) } : undefined;
}

export function собратьРасписание({
  сейчас,
  времена,
  намазы,
  заранее,
  дней = ДНЕЙ_РАСПИСАНИЯ,
}: {
  сейчас: number;
  времена: (день: string) => ВременаДня | null;
  намазы: Readonly<ВыборНамазов>;
  заранее: Заранее;
  дней?: number;
}): ПунктРасписания[] {
  const предел = сейчас + дней * ДЕНЬ;
  const начало = деньРК(сейчас);
  const кэш = new Map<string, ВременаДня | null>();
  const день = (д: string) => {
    if (!кэш.has(д)) кэш.set(д, времена(д));
    return кэш.get(д) ?? null;
  };
  const пункты: ПунктРасписания[] = [];
  for (let i = 0; i <= дней; i++) {
    const д = сдвигДня(начало, i);
    const в = день(д);
    if (!в) continue;
    for (const ключ of ПОРЯДОК) {
      if (!намазы[ключ]) continue;
      const момент = в[ключ];
      const время = чч_мм(момент);
      if (момент > сейчас && момент <= предел) {
        const след = следующий(ключ, в, ключ === 'isha' ? день(сдвигДня(д, 1)) : null);
        пункты.push(след ? { at: момент, key: ключ, time: время, before: 0, next: след } : { at: момент, key: ключ, time: время, before: 0 });
      }
      if (заранее > 0) {
        const заранееМ = момент - заранее * МИНУТА;
        if (заранееМ > сейчас && заранееМ <= предел) пункты.push({ at: заранееМ, key: ключ, time: время, before: заранее });
      }
    }
  }
  return пункты.sort((а, б) => а.at - б.at || б.before - а.before);
}

export function концаРасписания(пункты: readonly ПунктРасписания[]): number | null {
  return пункты.length ? Math.max(...пункты.map((п) => п.at)) : null;
}

// ───────────── сохранённые настройки (aiustaz:notify.v1; хранит notify/store.ts) ─────────────

export type НастройкиУведомлений = {
  версия: 1;
  включено: boolean;
  намазы: ВыборНамазов;
  заранее: Заранее;
  /** Когда сервер последний раз принял расписание (мс) и до какого момента оно. */
  отправлено: number | null;
  до: number | null;
};

export const ПО_УМОЛЧАНИЮ: НастройкиУведомлений = { версия: 1, включено: false, намазы: { ...НАМАЗЫ_ПО_УМОЛЧАНИЮ }, заранее: 0, отправлено: null, до: null };

export function разобратьНастройки(сырое: unknown): НастройкиУведомлений {
  const с = (сырое ?? {}) as Partial<НастройкиУведомлений>;
  if (с.версия !== 1) return { ...ПО_УМОЛЧАНИЮ, намазы: { ...НАМАЗЫ_ПО_УМОЛЧАНИЮ } };
  const намазы = { ...НАМАЗЫ_ПО_УМОЛЧАНИЮ };
  for (const к of ПОРЯДОК) if (typeof с.намазы?.[к] === 'boolean') намазы[к] = с.намазы[к];
  const число = (х: unknown) => (typeof х === 'number' && Number.isFinite(х) ? х : null);
  return {
    версия: 1,
    включено: с.включено === true,
    намазы,
    заранее: ВАРИАНТЫ_ЗАРАНЕЕ.includes(с.заранее as Заранее) ? (с.заранее as Заранее) : 0,
    отправлено: число(с.отправлено),
    до: число(с.до),
  };
}
