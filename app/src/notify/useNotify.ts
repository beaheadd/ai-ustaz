/**
 * Хуки уведомлений о времени намаза: поддержка здесь, данные расписания, фоновая синхронизация при открытии приложения.
 *
 * Контракт:
 *   useПоддержкаУведомлений() → ПоддержкаУведомлений (notify/support.ts) по среде (install/) и возможностям браузера.
 *   данныеРасписания(место, язык, настройки, сейчас) → ДанныеРасписания — 30 дней вперёд тем же расчётом, что карточка
 *     намаза (prayer/times.ts временаДня, метод ДУМК; общий кэш карточки не трогаем); город — строкой (место[язык]); координаты НЕ попадают в данные.
 *   ключСинхронизации(место, язык, настройки) / отметитьОтправку(ключ) — что уже отправлено за этот запуск страницы.
 *   <СинхронизацияУведомлений /> — в App.tsx: при каждом открытии приложения и при смене города, языка, намазов или
 *     «напомнить заранее» отправляет новое расписание (раз на изменение, через 1,5 с), если уведомления включены,
 *     разрешение дано и это aiustaz.pro. Ничего не рисует.
 */
import { useEffect, useMemo } from 'react';
import { useПеревод } from '../i18n';
import { useУстановка } from '../install/useInstall';
import type { Место } from '../prayer/places';
import { useМестоНамаза } from '../prayer/store';
import { временаДня } from '../prayer/times';
import { естьВБраузере, обновить, разрешение, type ДанныеРасписания } from './push';
import { концаРасписания, собратьРасписание } from './schedule';
import { изменитьНастройки, useНастройкиУведомлений, type НастройкиУведомлений } from './store';
import { поддержкаУведомлений, type ПоддержкаУведомлений } from './support';

export function useПоддержкаУведомлений(): ПоддержкаУведомлений {
  const { среда } = useУстановка();
  return useMemo(() => поддержкаУведомлений(среда, естьВБраузере()), [среда]);
}

export function данныеРасписания(место: Место, язык: 'ru' | 'kk', настройки: НастройкиУведомлений, сейчас: number): ДанныеРасписания {
  const пункты = собратьРасписание({
    сейчас,
    времена: (день) => {
      try {
        return временаДня({ широта: место.широта, долгота: место.долгота }, день);
      } catch {
        return null;
      }
    },
    намазы: настройки.намазы,
    заранее: настройки.заранее,
  });
  return { язык, город: место[язык].slice(0, 60), пункты };
}

export function ключСинхронизации(место: Место, язык: string, настройки: НастройкиУведомлений): string {
  return JSON.stringify([место.id, место.широта, место.долгота, язык, настройки.намазы, настройки.заранее]);
}

let отправлено = '';

export function отметитьОтправку(ключ: string): void {
  отправлено = ключ;
}

export function СинхронизацияУведомлений() {
  const { настройки, загружено } = useНастройкиУведомлений();
  const { место } = useМестоНамаза();
  const { язык } = useПеревод();
  const поддержка = useПоддержкаУведомлений();
  const ключ = ключСинхронизации(место, язык, настройки);
  const включено = загружено && настройки.включено && поддержка === 'можно';

  useEffect(() => {
    if (!включено || ключ === отправлено || разрешение() !== 'granted') return;
    const таймер = setTimeout(() => {
      отправлено = ключ;
      const сейчас = Date.now();
      const данные = данныеРасписания(место, язык, настройки, сейчас);
      if (!данные.пункты.length) return;
      void обновить(данные).then((итог) => {
        if (итог === 'включено') void изменитьНастройки({ отправлено: сейчас, до: концаРасписания(данные.пункты) });
        else if (отправлено === ключ) отправлено = ''; // не вышло (нет сети) — попробуем при следующем открытии или изменении
      });
    }, 1500);
    return () => clearTimeout(таймер);
    // ключ уже включает место, язык и настройки
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [включено, ключ]);
  return null;
}
