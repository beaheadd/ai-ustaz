/**
 * Настройки уведомлений о времени намаза — только на устройстве (ключ aiustaz:notify.v1).
 *
 * Контракт:
 *   useНастройкиУведомлений() → { настройки, загружено, изменить(часть) } — общий снимок для экрана, главной и синхронизации.
 *   текущиеНастройки(), изменитьНастройки(часть) — то же без React.
 *   разобратьНастройки(сырое) → НастройкиУведомлений — чистая функция (кривое — значения по умолчанию).
 * Хранится: включено, выбор намазов (восход выключен по умолчанию), «напомнить заранее», когда последний раз
 * отправили расписание и до какого момента оно (для строки состояния). Адреса подписки, координат и личных данных нет:
 * подписку хранит сам браузер (PushManager), место — prayer/store.ts.
 */
import { useSyncExternalStore } from 'react';
import { Platform } from 'react-native';
import { записатьJSON, прочитатьJSON } from '../engine/storage';
import { ПО_УМОЛЧАНИЮ, разобратьНастройки, type НастройкиУведомлений } from './schedule';

const КЛЮЧ = 'notify.v1';

export type { НастройкиУведомлений };
export { ПО_УМОЛЧАНИЮ, разобратьНастройки };

type Состояние = { настройки: НастройкиУведомлений; загружено: boolean };

function прочитатьСразу(): Состояние {
  if (Platform.OS !== 'web') return { настройки: ПО_УМОЛЧАНИЮ, загружено: false };
  try {
    const строка = globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ);
    return { настройки: разобратьНастройки(строка ? JSON.parse(строка) : null), загружено: true };
  } catch {
    return { настройки: ПО_УМОЛЧАНИЮ, загружено: true };
  }
}

let состояние: Состояние = прочитатьСразу();
const слушатели = new Set<() => void>();

function разослать(новое: Состояние) {
  состояние = новое;
  for (const с of слушатели) с();
}

if (!состояние.загружено) {
  void прочитатьJSON<unknown>(КЛЮЧ, null).then((з) => разослать({ настройки: разобратьНастройки(з), загружено: true }));
}

export function текущиеНастройки(): НастройкиУведомлений {
  return состояние.настройки;
}

export function изменитьНастройки(часть: Partial<Omit<НастройкиУведомлений, 'версия'>>): Promise<boolean> {
  const настройки = { ...состояние.настройки, ...часть, версия: 1 as const };
  разослать({ настройки, загружено: true });
  return записатьJSON(КЛЮЧ, настройки);
}

function подписаться(с: () => void) {
  слушатели.add(с);
  return () => {
    слушатели.delete(с);
  };
}

export function useНастройкиУведомлений(): Состояние & { изменить: typeof изменитьНастройки } {
  const с = useSyncExternalStore(подписаться, () => состояние, () => состояние);
  return { ...с, изменить: изменитьНастройки };
}
