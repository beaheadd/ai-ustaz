/**
 * Типы контента уроков. Данные — JSON в /content (корень репозитория), импорт по алиасу:
 *   import урок1 from '@content/lessons/01.json';   // пример пути; раскладку задаёт автор контента
 * Здесь ТОЛЬКО типы (данные и реестр уроков заполняет другой агент).
 *
 * Жёсткие правила (CLAUDE.md):
 * - Коран — только ФрагментКорана: дословно из Tanzil Uthmani v1.1
 *   (quran-uthmani-without-pause-sajda-hizb-marks.xml), строки извлекаются программно, не руками;
 *   не «исправлять», не нормализовать. Неверный вариант аята не показывать никогда.
 * - Неправильные варианты ответа — только буквы, слоги и учебные слова (УчебныйАрабский).
 * - Любой текст урока — черновик, пока не подписан устазом и советом (статус, утверждено).
 * - Проверки голоса ИИ в прототипе нет: задания с записью — без вердикта.
 * Схема — по docs/программа-курса.md §3.3 и §14 (упрощена под прототип).
 */

/** Строка интерфейса на двух языках; kk — черновик для редактора-носителя. */
export type ЛокализованныйТекст = { ru: string; kk: string };

/** Учебный арабский: буква, слог или учебное слово с огласовками. НЕ текст Корана. */
export type УчебныйАрабский = string;

/** Ссылка «сура:аят» (1–114, 1–286). */
export type СсылкаНаАят = { сура: number; аят: number };

/** Фрагмент Корана — дословно из Tanzil Uthmani v1.1, по ссылке. */
export type ФрагментКорана = СсылкаНаАят & {
  /** Текст ровно как в XML Tanzil (весь аят или слова с…по). */
  текст: string;
  /** Если фрагмент — часть аята: номера слов (с 1, включительно) по разбиению Tanzil по пробелам. */
  слова?: { с: number; по: number };
  источник: 'tanzil-uthmani-1.1';
  /** sha256 (hex) поля текст в UTF-8 — для проверки при сборке контента. */
  хеш: string;
};

/** Статус проверки (CLAUDE.md, правило 11): без подписи совета — только черновик за флагом. */
export type СтатусКонтента = 'черновик' | 'проверен-устазом' | 'подписан-советом';

export type Утверждение = { кем: string | null; дата: string | null };

/** Эталонный голос кари: в прототипе всегда null (записи появятся на этапе 0б). Синтез запрещён. */
export type ГолосКари = { файл: string; кари: string; лицензия: string } | null;

/** Вариант ответа в задании «выбор»: арабский (буква/слог/учебное слово) или текст на языке интерфейса. */
export type ВариантОтвета = { арабский: УчебныйАрабский } | { текст: ЛокализованныйТекст };

/** Карточка объяснения (без проверки). */
export type ЗаданиеТеория = {
  тип: 'теория';
  заголовок: ЛокализованныйТекст;
  текст: ЛокализованныйТекст;
  /** Крупные учебные примеры (буквы, слоги), справа налево. */
  примеры?: УчебныйАрабский[];
};

/** Выбор с одним верным ответом (тап). Заменяет «узнай», «форма», «собери» прототипа. */
export type ЗаданиеВыбор = {
  тип: 'выбор';
  вопрос: ЛокализованныйТекст;
  /** Что показать крупно над вариантами (буква, слог). */
  показ?: УчебныйАрабский;
  варианты: ВариантОтвета[];
  /** Индекс верного варианта в «варианты». */
  верный: number;
  /** Короткое пояснение после ответа — из утверждённой базы правил (каталог ошибок), не LLM. */
  пояснение?: ЛокализованныйТекст;
};

/** Прочитать вслух и записать себя (эхо/скажи). Без вердикта: «Записали! Послушайте себя». */
export type ЗаданиеЗапись = {
  тип: 'запись';
  подсказка: ЛокализованныйТекст;
  /** Что читать: учебный арабский или фрагмент Корана (только по ссылке). */
  читать: { учебный: УчебныйАрабский } | { коран: ФрагментКорана };
  /** Слоги для подсказки под словом: ['اَلْ', 'حَمْ', 'دُ'] (только для учебного текста). */
  слоги?: УчебныйАрабский[];
  голосКари: ГолосКари;
};

/** Лестница «Муаллим сани»: слог → слово → фраза; каждую ступень — записать себя. */
export type ЗаданиеЛестница = {
  тип: 'лестница';
  подсказка: ЛокализованныйТекст;
  ступени: Array<{ учебный: УчебныйАрабский } | { коран: ФрагментКорана }>;
  голосКари: ГолосКари;
};

export type Задание = ЗаданиеТеория | ЗаданиеВыбор | ЗаданиеЗапись | ЗаданиеЛестница;

export type Урок = {
  /** Номер в курсе: 0 — «Вход», 1…16 — уровень 1 (программа курса §5). */
  номер: number;
  /** 'L01' и т. п. (программа курса §14). */
  id: string;
  уровень: number;
  название: ЛокализованныйТекст;
  цель: ЛокализованныйТекст;
  /** Новые буквы и знаки урока. */
  новое: УчебныйАрабский[];
  задания: Задание[];
  /** Порог прохождения по заданиям «выбор» (доля верных, 0..1). Голос не оценивается. */
  критерий: { доляВерных: number };
  версия: string;
  статус: СтатусКонтента;
  утверждено: Утверждение;
};

/** Краткая запись урока для карты курса (без заданий). */
export type ОписаниеУрока = Pick<Урок, 'номер' | 'id' | 'уровень' | 'название' | 'статус'> & {
  /** Есть ли урок в прототипе (иначе — «скоро»). */
  доступен: boolean;
};

/** Версия набора контента (/content/version.json). */
export type ВерсияКонтента = {
  версия: string;
  статус: СтатусКонтента;
  утверждено: Утверждение;
};
