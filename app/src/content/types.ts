// Решение владельца 19.11.2026: в каждом уроке — видео, аудио и объяснение. Видео и аудио — от учителей-
// партнёров; ученикам показываются, ТОЛЬКО если у источника «разрешено: true» (договор ведёт владелец).
// Данные собирает tools/media/build_media.py, проверяет tools/media/check_media.py.

/** Автор (канал) видео и аудио. */
export type ИсточникМедиа = {
  id: string;
  имя: ЛокализованныйТекст;
  канал: string;
  /** Текст без схемы (youtube.com/channel/…): в бандле нет внешних URL, кроме ссылок youtube.com/watch. */
  ссылкаКанала: string;
  курс: string;
  /** Язык видео: uz, kk, ar. */
  язык: string;
  /** Разрешение автора (договор). false — ученики видео и аудио этого источника не видят. */
  разрешено: boolean;
  датаРазрешения: string | null;
  условия: string;
  /** «Видео: …. Используется с разрешения автора.» — на экране рядом с каждым видео. */
  атрибуция: ЛокализованныйТекст;
};

export type РольВидео = 'основное' | 'дополнительно';

export type ВидеоУрока = {
  источник: string;
  youtubeId: string;
  название: string;
  роль: РольВидео;
  /** Ровно https://www.youtube.com/watch?v=<id> — открывается во внешнем приложении, НЕ встраивается. */
  ссылка: string;
  /** Файл на своём сервере (относительный путь media/….mp4|webm), когда автор передаст файлы; иначе null. */
  файлВидео: string | null;
  /** = разрешено источника (пересчитывает генератор). */
  показывать: boolean;
};

/** Клип кари: буква или слог → запись на своём сервере (относительный путь media/…). Синтеза нет. */
export type АудиоКлип = { текст: УчебныйАрабский; файл: string; источник: string };

export type МедиаУрока = { номер: number; id: string; уровень: number; видео: ВидеоУрока[]; аудио: АудиоКлип[] };

export type МедиаДанные = {
  версия: string;
  статус: СтатусКонтента;
  источники: Record<string, ИсточникМедиа>;
  уроки: МедиаУрока[];
};
