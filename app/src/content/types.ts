  /** Код из каталога ошибок: 'A1.ح>х', 'A2', 'A1.эмф'… */
  код: string;
  описание: ЛокализованныйТекст;
  /** Кому важнее; null — в документах не указано. */
  кому: ЛокализованныйТекст | null;
  /** true — по документам это гипотеза [Г]. */
  гипотеза: boolean;
