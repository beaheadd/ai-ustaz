const КЛЮЧ_ИНДЕКСА = 'хадисы:индекс';

export function загрузитьИндекс(): Promise<Результат<ИндексХадисов>> {
  // Отметки из админки (владелец 27.11.2026): «проверено устазом» снимает плашку «Черновик»; скрытые — ниже
  // (content/remoteConfig.ts; текст хадисов — только из сборки).
  return загрузитьФайл(КЛЮЧ_ИНДЕКСА, М.индекс, М.sha256Индекса, (с) => {
    const и = проверитьИндекс(с, М);
    return и ? применитьКХадисам(и) : null;
  });
}

export async function загрузитьЗаголовки(язык: ЯзыкПеревода): Promise<Результат<Заголовки>> {
  const и = await загрузитьИндекс();
  if (!и.ок) return и;
  const ф = и.данные.заголовки[язык];
  return загрузитьФайл('хадисы:заголовки-' + язык, ф.файл, ф.sha256, (с) => проверитьЗаголовки(с, язык, и.данные));
}

function порция(индекс: ИндексХадисов, язык: 'ar' | ЯзыкПеревода, ч: number) {
  const ф = индекс.порции[язык][ч];
  if (!ф) return Promise.resolve<Результат<Map<number, ЗаписьАр | ЗаписьПеревода>>>({ ок: false, причина: 'нет-файла' });
  return загрузитьФайл(`хадисы:${язык}-${ч}`, ф.файл, ф.sha256, (с) => проверитьПорцию(с, язык, ч, индекс));
}

export type ХадисДляПоказа = {
  запись: ЗаписьХадиса;
  ar: ЗаписьАр;
  перевод: ЗаписьПеревода;
  /** Язык показанного перевода и то, что он запасной (kk; en/uz без своего перевода — русский). */
  языкПеревода: ЯзыкПеревода;
  запасной: boolean;
  /** Одобрил устаз (без плашки «Черновик»), иначе null. */
  одобрено: { кто: string; когда: string } | null;
  индекс: ИндексХадисов;
};

export async function загрузитьХадис(id: number, языкИнтерфейса: string): Promise<Результат<ХадисДляПоказа | null>> {
  const и = await загрузитьИндекс();
  if (!и.ок) return и;
  const запись = и.данные.хадисы.find((х) => х.id === id);
  if (!запись || скрытХадис(id)) return { ок: true, данные: null };
  const { язык, запасной } = языкПеревода(языкИнтерфейса, запись.языки);
  const [ar, пер] = await Promise.all([порция(и.данные, 'ar', запись.порция), порция(и.данные, язык, запись.порция)]);
  if (!ar.ок) return ar;
  if (!пер.ок) return пер;
  const а = ar.данные.get(id) as ЗаписьАр | undefined;
  const п = пер.данные.get(id) as ЗаписьПеревода | undefined;
  if (!а || !п) return { ок: false, причина: 'не-прошло-сверку' };
  return {
    ок: true,
    данные: { запись, ar: а, перевод: п, языкПеревода: язык, запасной, одобрено: и.данные.одобрено[String(id)] ?? null, индекс: и.данные },
  };
}

/** Скрытые в админке хадисы не показываются в разделах и поиске (владелец 27.11.2026: «убирали, отключали»). */
export function хадисыКатегории(индекс: ИндексХадисов, id: number): ЗаписьХадиса[] {
  return всеКатегории(индекс, id).filter((х) => !скрытХадис(х.id));
}

export function найти(...а: Parameters<typeof найтиВсе>): ЗаписьХадиса[] {
  return найтиВсе(...а).filter((х) => !скрытХадис(х.id));
}

export function useИндексХадисов() {
  return useЗагрузка<ИндексХадисов>('индекс-хадисов', изКэша<ИндексХадисов>(КЛЮЧ_ИНДЕКСА), загрузитьИндекс);
}

export function useЗаголовки(язык: ЯзыкПеревода) {
  return useЗагрузка<Заголовки>('заголовки-' + язык, изКэша<Заголовки>('хадисы:заголовки-' + язык), () => загрузитьЗаголовки(язык));
}

export function useХадис(id: number | null, языкИнтерфейса: string) {
  return useЗагрузка<ХадисДляПоказа | null>(id === null ? null : `хадис-${id}-${языкИнтерфейса}`, null, () =>
    id === null ? Promise.resolve({ ок: true as const, данные: null }) : загрузитьХадис(id, языкИнтерфейса),
  );
}
