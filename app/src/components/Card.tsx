/**
 * Карточка — блок контента на поверхности.
 *
 * Контракт:
 *   <Карточка вид?="обычная|акцент|песок|арка|герой" заголовок? приНажатии? подъём? орнамент?
 *             акцент? стиль? testID?>…</Карточка>
 * - обычная — поверхность, тонкая рамка, тень 1 (по умолчанию);
 *   акцент — мягкий изумрудный фон (пояснения, важные блоки); старый проп акцент={true} = вид «акцент»;
 *   песок — тёплый песочный фон (восход, подложки);
 *   арка — верх в форме арки михраба (главное на экране: карточка буквы, вступление урока);
 *   герой — арка тёмного изумруда со светлым текстом, тонкой золотой линией и узором хатам в верхней
 *     части (шапка «Арка дня» на главной). Внутри — поверхность «герой»: <Текст>, <Значок>, <Кнопка>,
 *     <Плашка>, <ЭмблемаУстаза> сами берут светлые цвета.
 * - подъём — высота вершины арки над плечами, px (арка — 24, герой — 32); содержимое начинается ниже.
 * - орнамент — узор в арке героя (по умолчанию true; false — без узора).
 * - приНажатии: вся карточка — кнопка (accessibilityRole="button").
 * Правила: арку ставить только на «главное на экране» (одна-две на экран), не на кнопки и мелочи;
 * узор — не под текстом: только в вершине арки над содержимым (высота подъём + отступ.m), 5 % (ОРНАМЕНТ.фонГерой).
 * На вебе у героя — data-surface="hero": кольцо фокуса клавиатуры там светлое (theme/index.ts, стиль фокуса).
 */
import { useState, type ReactNode } from 'react';
import { Platform, Pressable, View, type LayoutChangeEvent, type StyleProp, type ViewStyle } from 'react-native';
import { Path, Svg } from './primitives/svg';
import { путьАрки } from '../design/geometry';
import { ОРНАМЕНТ, ПоверхностьГероя, useТема } from '../theme';
import { Орнамент } from './Ornament';
import { Текст } from './Text';

export type ВидКарточки = 'обычная' | 'акцент' | 'песок' | 'арка' | 'герой';

export type СвойстваКарточки = {
  children?: ReactNode;
  вид?: ВидКарточки;
  заголовок?: string;
  приНажатии?: () => void;
  /** Совместимость: акцент={true} — то же, что вид="акцент". */
  акцент?: boolean;
  подъём?: number;
  орнамент?: boolean;
  стиль?: StyleProp<ViewStyle>;
  testID?: string;
};

export function Карточка({ children, вид: вид_, заголовок, приНажатии, акцент = false, подъём: подъём_, орнамент = true, стиль, testID }: СвойстваКарточки) {
  const { цвет, радиус, отступ, тень } = useТема();
  const вид: ВидКарточки = вид_ ?? (акцент ? 'акцент' : 'обычная');
  const арочная = вид === 'арка' || вид === 'герой';
  const подъём = подъём_ ?? (вид === 'герой' ? 32 : 24);
  const [размер, установитьРазмер] = useState<{ ш: number; в: number } | null>(null);

  const фон = вид === 'акцент' ? цвет.поверхностьАкцент : вид === 'песок' ? цвет.песок : вид === 'герой' ? цвет.геройФон : цвет.поверхность;
  const рамка = вид === 'акцент' ? цвет.поверхностьАкцент : вид === 'песок' ? цвет.песок : цвет.граница;

  const оформление: ViewStyle = арочная
    ? {
        // Фон и рамку рисует SVG-арка; до первой раскладки — обычный прямоугольник (без вспышки пустоты).
        backgroundColor: размер ? 'transparent' : фон,
        borderRadius: размер ? 0 : радиус.l,
        padding: отступ.l,
        paddingTop: подъём + (вид === 'герой' ? отступ.m : отступ.s),
        gap: отступ.s,
      }
    : {
        backgroundColor: фон,
        borderRadius: радиус.l,
        borderWidth: 1,
        borderColor: рамка,
        padding: отступ.l,
        gap: отступ.s,
        ...(вид === 'обычная' ? тень(1) : null),
      };

  const приРаскладке = арочная
    ? (е: LayoutChangeEvent) => {
        const { width: ш, height: в } = е.nativeEvent.layout;
        if (!размер || Math.abs(размер.ш - ш) > 0.5 || Math.abs(размер.в - в) > 0.5) установитьРазмер({ ш, в });
      }
    : undefined;

  const арка =
    арочная && размер ? (
      <View style={{ position: 'absolute', left: 0, top: 0, width: размер.ш, height: размер.в, pointerEvents: 'none' }} aria-hidden>
        <Svg width={размер.ш} height={размер.в}>
          <Path d={путьАрки(размер.ш, размер.в, подъём, радиус.l)} fill={фон} stroke={вид === 'герой' ? 'none' : рамка} strokeWidth={1} />
        </Svg>
        {вид === 'герой' && орнамент ? (
          // Узор — только в вершине арки, выше содержимого (оно начинается с подъём + отступ.m): не под городом,
          // мелким текстом и временем намаза (бриф §2.2, 4–6 %).
          <View style={{ position: 'absolute', left: 0, top: 0, right: 0, height: Math.min(размер.в, подъём + отступ.m), overflow: 'hidden' }}>
            <Орнамент вид="хатам" цвет={цвет.геройТекст} прозрачность={ОРНАМЕНТ.фонГерой} контур={путьАрки(размер.ш, размер.в, подъём, радиус.l)} />
          </View>
        ) : null}
        {вид === 'герой' ? (
          <Svg width={размер.ш} height={размер.в} style={{ position: 'absolute', left: 0, top: 0 }}>
            <Path
              d={путьАрки(размер.ш - 12, размер.в - 12, Math.max(0, подъём - 3), радиус.l - 5)}
              transform="translate(6 6)"
              fill="none"
              stroke={цвет.золотоДекор}
              strokeWidth={1}
              opacity={0.85}
            />
          </Svg>
        ) : null}
      </View>
    ) : null;

  const содержимое = (
    <>
      {арка}
      {заголовок ? <Текст вид="подзаголовок">{заголовок}</Текст> : null}
      {children}
    </>
  );
  const обёрнуто = вид === 'герой' ? <ПоверхностьГероя>{содержимое}</ПоверхностьГероя> : содержимое;

  // Веб: метка поверхности для стиля фокуса (на тёмной шапке кольцо светлое).
  const метка = вид === 'герой' && Platform.OS === 'web' ? ({ dataSet: { surface: 'hero' } } as object) : null;
  if (приНажатии) {
    return (
      <Pressable accessibilityRole="button" onPress={приНажатии} testID={testID} onLayout={приРаскладке} {...метка} style={({ pressed }) => [оформление, { opacity: pressed ? 0.85 : 1 }, стиль]}>
        {обёрнуто}
      </Pressable>
    );
  }
  return (
    <View testID={testID} onLayout={приРаскладке} {...метка} style={[оформление, стиль]}>
      {обёрнуто}
    </View>
  );
}
