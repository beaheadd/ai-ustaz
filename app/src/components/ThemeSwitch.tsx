/**
 * Переключатель темы: «Системная · Светлая · Тёмная» (короткая подпись: «Как в системе» не помещалась на 390 px).
 *
 * Контракт: <ПереключательТемы /> — меняет тему сразу и сохраняет выбор локально (aiustaz:theme.v1).
 * testID вкладок: тема-система, тема-светлая, тема-тёмная.
 */
import { создатьСловарь, useСловарь } from '../i18n';
import { useНастройкаТемы, type РежимТемы } from '../theme';
import { Вкладки } from './Tabs';

const СЛОВАРЬ = создатьСловарь({
  ru: { группа: 'Тема оформления', система: 'Системная', светлая: 'Светлая', тёмная: 'Тёмная' },
  kk: { группа: 'Безендіру тақырыбы', система: 'Жүйелік', светлая: 'Ашық', тёмная: 'Қараңғы' },
});

export function ПереключательТемы() {
  const т = useСловарь(СЛОВАРЬ);
  const { режим, установитьРежим } = useНастройкаТемы();
  const режимы: РежимТемы[] = ['система', 'светлая', 'тёмная'];
  return (
    <Вкладки
      подпись={т('группа')}
      вкладки={режимы.map((р) => ({ ключ: р, надпись: т(р), значок: р === 'система' ? 'тема' : р === 'светлая' ? 'солнце' : 'луна', testID: 'тема-' + р }))}
      выбрана={режим}
      приВыборе={(к) => установитьРежим(к as РежимТемы)}
    />
  );
}
