/**
 * ЭмблемаУстаза — образ ИИ-наставника AI Ustaz: фонарь-шырақ, «свет знания» (концепция C).
 *
 * Контракт:
 *   <ЭмблемаУстаза размер?={48} состояние?="покой|слушаю|объясняю|молчу" вариант?="авто|полный|значок"
 *                  подпись? testID? />
 * - размер — сторона квадрата, px. Вариант «авто»: ≤ 40 px — «значок» (силуэт и звезда-свет), больше — «полный».
 *   Рекомендуемые размеры: 24 (шапка, строка), 40 (реплика), 48 (подсказки), 120 (вступление, пустые
 *   состояния), 240 (приветствие). Поле вокруг — не меньше 1/8 размера (его даёт родитель).
 * - состояние (docs/дизайн/02-образ-устаза.md §5):
 *     покой    — ровный свет (главная, вступление, «без замечаний»);
 *     слушаю   — только пока идёт запись: кольцо света, сияние «дышит» (2,4 с), окно мерцает; без звука;
 *     объясняю — показана подсказка: рядом маленький пузырь (в интерфейсе текст — в <РепликаУстаза>);
 *     молчу    — не уверен / плохой звук / нет сети / перерыв: свет приглушён, без красного.
 *   При «уменьшить движение» — без анимации, свет ровно яркий.
 * - Цвета — из темы: основа = акцент (на «герое» — светлый текст), тон = поверхностьАкцент, свет, сияние, тихо, бумага.
 * - подпись — для экранного диктора (по умолчанию «AI Ustaz, ИИ-наставник»; в «слушаю» — «… идёт запись»).
 * Правила: не человек и не персонаж — без лица, глаз, рук и эмоций; не «растёт», не получает звёзд;
 * не ставить внутрь текста аята и поверх мусхафа; не использовать как награду.
 */
import { useId, type ReactNode } from 'react';
import { View, type StyleProp, type ViewStyle } from 'react-native';
import {
  ГРАДИЕНТЫ,
  НЕПРОЗРАЧНОСТЬ_ПОГАШЕННОГО,
  ПОРОГ_ЗНАЧКА,
  СДВИГ_ТЕЛА_ПОЛНОГО,
  СОСТОЯНИЯ,
  ЭМБЛЕМА,
  type ГрадиентЭмблемы,
  type РольЭмблемы,
  type СлойЭмблемы,
  type СостояниеЭмблемы,
  type ФигураЭмблемы,
} from '../design/emblem';
import { создатьСловарь, useСловарь } from '../i18n';
import { useТема, useУменьшитьДвижение } from '../theme';
import { СлойДыхания } from './primitives/Breath';
import { Circle, Defs, G, Path, RadialGradient, Rect, Stop, Svg } from './primitives/svg';

export type { СостояниеЭмблемы } from '../design/emblem';
export type ВариантЭмблемы = 'авто' | 'полный' | 'значок';

export type СвойстваЭмблемы = {
  размер?: number;
  состояние?: СостояниеЭмблемы;
  вариант?: ВариантЭмблемы;
  подпись?: string;
  стиль?: StyleProp<ViewStyle>;
  testID?: string;
};

const СЛОВАРЬ = создатьСловарь({
  ru: { подпись: 'AI Ustaz, ИИ-наставник', запись: 'AI Ustaz, ИИ-наставник: идёт запись' },
  kk: { подпись: 'AI Ustaz, ЖИ-тәлімгер', запись: 'AI Ustaz, ЖИ-тәлімгер: жазылып жатыр' },
  uz: { подпись: 'AI Ustaz, SI-murabbiy', запись: 'AI Ustaz, SI-murabbiy: yozib olinmoqda' },
});

export function ЭмблемаУстаза({ размер = 48, состояние = 'покой', вариант = 'авто', подпись, стиль, testID }: СвойстваЭмблемы) {
  const { цвет, поверхность } = useТема();
  const т = useСловарь(СЛОВАРЬ);
  const уменьшить = useУменьшитьДвижение();
  const ид = useId().replace(/[^a-zA-Z0-9_-]/g, '');
  const вид = вариант === 'авто' ? (размер <= ПОРОГ_ЗНАЧКА ? 'значок' : 'полный') : вариант;
  const с = СОСТОЯНИЯ[состояние];
  const анимировать = с.дышит && !уменьшить;

  const роли: Record<РольЭмблемы, string> = {
    основа: поверхность === 'герой' ? цвет.геройТекст : цвет.акцент,
    тон: поверхность === 'герой' ? цвет.геройФон : цвет.поверхностьАкцент,
    бумага: цвет.бумага,
    свет: с.погашен ? цвет.тихо : цвет.свет,
    сияние: цвет.сияние,
    тихо: цвет.тихо,
  };

  const фигуры = ЭМБЛЕМА[вид];
  const градиенты = ГРАДИЕНТЫ[вид];
  const сдвиг = вид === 'полный' ? СДВИГ_ТЕЛА_ПОЛНОГО : 0;
  const слой = (имя: СлойЭмблемы) => фигуры.filter((ф) => ф.слой === имя);

  const заливка = (з: ФигураЭмблемы['заливка']) =>
    !з ? 'none' : з === 'url:сияние' ? `url(#${ид}-сияние)` : з === 'url:стекло' ? `url(#${ид}-стекло)` : роли[з];
  const нарисовать = (ф: ФигураЭмблемы, i: number) => {
    const общее = {
      fill: заливка(ф.заливка),
      stroke: ф.обводка ? роли[ф.обводка] : undefined,
      strokeWidth: ф.толщина,
      strokeLinecap: 'round' as const,
      strokeLinejoin: 'round' as const,
      opacity: ф.прозрачность,
    };
    if (ф.вид === 'круг') return <Circle key={i} cx={ф.cx} cy={ф.cy} r={ф.r} {...общее} />;
    if (ф.вид === 'прямоугольник') return <Rect key={i} x={ф.x} y={ф.y} width={ф.ширина} height={ф.высота} rx={ф.rx} {...общее} />;
    return <Path key={i} d={ф.d} {...общее} />;
  };
  const градиент = (имя: string, г: ГрадиентЭмблемы) => (
    <RadialGradient id={`${ид}-${имя}`} gradientUnits="userSpaceOnUse" cx={г.cx} cy={г.cy} r={г.r} fx={г.cx} fy={г.cy}>
      {г.остановки.map(([смещение, роль, непрозрачность], i) => (
        <Stop key={i} offset={смещение} stopColor={роли[роль]} stopOpacity={роль === 'сияние' && с.погашен ? НЕПРОЗРАЧНОСТЬ_ПОГАШЕННОГО : непрозрачность} />
      ))}
    </RadialGradient>
  );

  const svg = (содержимое: ReactNode, определения?: ReactNode) => (
    <Svg width={размер} height={размер} viewBox="0 0 120 120">
      {определения ? <Defs>{определения}</Defs> : null}
      {содержимое}
    </Svg>
  );

  const абсолютно: ViewStyle = { position: 'absolute', left: 0, top: 0, width: размер, height: размер };
  // При «уменьшить движение» в «слушаю» — ровно ярко (как в эскизе): сияние 1, масштаб 1,06.
  const покойСияния = с.дышит ? { непрозрачность: 1, масштаб: 1.06 } : { непрозрачность: с.сияние, масштаб: 1 };

  return (
    <View
      testID={testID}
      accessible
      accessibilityRole="image"
      accessibilityLabel={подпись ?? (состояние === 'слушаю' ? т('запись') : т('подпись'))}
      style={[{ width: размер, height: размер, pointerEvents: 'none' }, стиль]}
    >
      {/* Сияние — отдельный слой: «дышит» прозрачностью и масштабом. */}
      <СлойДыхания вид="сияние" активен={анимировать} покой={покойСияния} размер={размер}>
        {svg(<G>{слой('сияние').map(нарисовать)}</G>, градиент('сияние', градиенты.сияние))}
      </СлойДыхания>
      {/* Тело фонаря (и пузырь «объясняю»). */}
      <View style={абсолютно}>
        {svg(
          <>
            <G transform={`translate(0 ${сдвиг})`}>{слой('тело').map(нарисовать)}</G>
            {с.пузырь ? <G>{слой('пузырь').map(нарисовать)}</G> : null}
          </>,
          градиент('стекло', градиенты.стекло),
        )}
      </View>
      {/* Окно-звезда и кольцо «слушаю» — мерцают вместе. */}
      <СлойДыхания вид="мерцание" активен={анимировать} покой={{ непрозрачность: 1 }} размер={размер}>
        {svg(
          <>
            {с.кольцо ? <G>{слой('кольцо').map(нарисовать)}</G> : null}
            <G transform={`translate(0 ${сдвиг})`}>{слой('свет').map(нарисовать)}</G>
          </>,
        )}
      </СлойДыхания>
    </View>
  );
}
