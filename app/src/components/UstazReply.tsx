/**
 * РепликаУстаза — пузырь с репликой ИИ-наставника: эмблема слева, подпись «AI Ustaz · ИИ-наставник», текст.
 *
 * Контракт:
 *   <РепликаУстаза состояние?="объясняю" предупреждение? подпись? компактная? testID?>
 *     текст или <СмешанныйТекст>…
 *   </РепликаУстаза>
 * - состояние — состояние эмблемы (по умолчанию «объясняю»; «молчу» — «не уверен», «плохо слышно»;
 *   «слушаю» — только пока идёт запись; «покой» — приветствие).
 * - предупреждение — строка «Проверка ИИ может ошибаться и не заменяет устаза» под текстом
 *   (обязательна рядом с каждым итогом проверки голосом).
 * - подпись — заменить подпись над текстом (по умолчанию «AI Ustaz · ИИ-наставник» / «ЖИ-тәлімгер»).
 * - компактная — пузырь на всю ширину, малая эмблема (20 px) — в строке подписи «AI Ustaz · ИИ-наставник», поля 8/12
 *   (главная под картой намаза, 19.11.2026; ревью: так короткая реплика влезает в одну строку на 360–412 px, −24 px);
 *   подпись ИИ остаётся.
 * Голос (02-образ-устаза §8): на «вы», коротко, от «мы» или безлично, без «я» и без чувств; сначала что
 * получилось, потом одно действие; «не уверен — не ругаем». Объяснения ошибок — только из шаблонов
 * каталога ошибок (правило 4), реплика их лишь подаёт. Живой устаз оформляется иначе (без эмблемы).
 */
import type { ReactNode } from 'react';
import { View } from 'react-native';
import { создатьСловарь, useСловарь } from '../i18n';
import { useТема } from '../theme';
import { Текст } from './Text';
import { ЭмблемаУстаза, type СостояниеЭмблемы } from './UstazEmblem';

const СЛОВАРЬ = создатьСловарь({
  ru: { подпись: 'AI Ustaz · ИИ-наставник', предупреждение: 'Проверка ИИ может ошибаться и не заменяет устаза.' },
  kk: { подпись: 'AI Ustaz · ЖИ-тәлімгер', предупреждение: 'ЖИ тексеруі қателесуі мүмкін және ұстазды алмастырмайды.' },
  uz: { подпись: 'AI Ustaz · SI-murabbiy', предупреждение: 'SI tekshiruvi xato qilishi mumkin va ustozning oʻrnini bosmaydi.' },
});

export type СвойстваРеплики = {
  children?: ReactNode;
  состояние?: СостояниеЭмблемы;
  предупреждение?: boolean;
  подпись?: string;
  компактная?: boolean;
  testID?: string;
};

export function РепликаУстаза({ children, состояние = 'объясняю', предупреждение = false, подпись, компактная = false, testID }: СвойстваРеплики) {
  const { цвет, отступ, радиус } = useТема();
  const т = useСловарь(СЛОВАРЬ);
  const метка = (
    <Текст вид="метка" цвет={цвет.акцент}>
      {подпись ?? т('подпись')}
    </Текст>
  );
  return (
    <View testID={testID} style={{ flexDirection: 'row', alignItems: 'flex-start', gap: отступ.s }}>
      {компактная ? null : (
        <View style={{ paddingTop: 2 }}>
          <ЭмблемаУстаза размер={40} состояние={состояние} />
        </View>
      )}
      <View
        style={{
          flex: 1,
          gap: отступ.xs,
          paddingVertical: компактная ? отступ.s : отступ.m,
          paddingHorizontal: компактная ? отступ.m : отступ.l,
          backgroundColor: цвет.поверхность,
          borderWidth: 1,
          borderColor: цвет.граница,
          borderRadius: радиус.l,
          borderTopLeftRadius: радиус.s / 2,
        }}
      >
        {компактная ? (
          <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
            <ЭмблемаУстаза размер={20} состояние={состояние} />
            {метка}
          </View>
        ) : (
          метка
        )}
        {typeof children === 'string' ? <Текст>{children}</Текст> : children}
        {предупреждение ? (
          <Текст вид="мелкий" testID={testID ? testID + '-предупреждение' : undefined}>
            {т('предупреждение')}
          </Текст>
        ) : null}
      </View>
    </View>
  );
}
