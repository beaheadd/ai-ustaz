/**
 * Плашка прототипа — небольшая постоянная полоса под шапкой.
 *
 * Контракт: <ПлашкаПрототипа вид="урок|общая" />
 *   урок  — «Прототип. Черновик урока — проходит проверку устаза» (на КАЖДОМ экране урока);
 *   общая — «Прототип: проверки голоса ИИ пока нет».
 * Обычно не вставляется руками: <Экран плашка="урок"> рисует её сам.
 */
import { View } from 'react-native';
import { useПеревод } from '../i18n';
import { useТема } from '../theme';
import { Текст } from './Text';

export type ВидПлашки = 'урок' | 'общая';

export function ПлашкаПрототипа({ вид = 'урок' }: { вид?: ВидПлашки }) {
  const { t } = useПеревод();
  const { цвет, отступ } = useТема();
  return (
    <View
      accessibilityRole="text"
      testID="плашка-прототипа"
      style={{ backgroundColor: цвет.плашкаФон, paddingVertical: отступ.xs + 2, paddingHorizontal: отступ.l }}
    >
      <Текст вид="мелкий" стиль={{ color: цвет.плашкаТекст, textAlign: 'center' }}>
        {t(вид === 'урок' ? 'плашка.урок' : 'плашка.общая')}
      </Текст>
    </View>
  );
}
