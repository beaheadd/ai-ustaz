export type СвойстваПроверкиГолосом = {
  эталон: ЭталонПроверки;
  текстПоказа: string;
  виды?: readonly string[];
  словаПоказа?: readonly string[];
  приИтоге?: (итог: ИтогПроверки | null) => void;
  естьЗапись: boolean;
  заняты: boolean;
  получитьЗапись: () => Blob | null;
};

export function ПроверкаГолосом(свойства: СвойстваПроверкиГолосом) {
  // Флаг не меняется за время жизни страницы: на batr.kz ничего не рисуем и хуков проверки не держим.
  const [включена] = useState(проверкаГолосомВключена);
  return включена ? <ПроверкаГолосомВнутри {...свойства} /> : null;
}

function ПроверкаГолосомВнутри({ эталон, текстПоказа, виды, словаПоказа, приИтоге, естьЗапись, заняты, получитьЗапись }: СвойстваПроверкиГолосом) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { отступ, цвет } = useТема();
  const { прогресс, изменить } = useПрогресс();
  const { вКонец } = useПрокрутка();
  const [режим, установитьРежим] = useState<'покой' | 'согласие' | 'идёт'>('покой');
  const [итог, установитьИтогСостояние] = useState<ИтогПроверки | null>(null);
  const управление = useRef<AbortController | null>(null);
  const приИтогеСсылка = useRef(приИтоге);
  приИтогеСсылка.current = приИтоге;
  const установитьИтог = (новый: ИтогПроверки | null) => {
    установитьИтогСостояние(новый);
    приИтогеСсылка.current?.(новый);
  };

  // Новая запись, удаление или уход с упражнения — прежний итог и незаконченная проверка не нужны.
  useEffect(() => {
    if (естьЗапись && !заняты) return;
    управление.current?.abort();
    управление.current = null;
    установитьИтог(null);
    установитьРежим('покой');
  }, [естьЗапись, заняты]);
  useEffect(() => () => управление.current?.abort(), []);

  async function проверить() {
    const запись = получитьЗапись();
    if (!запись) return;
    управление.current?.abort();
    const у = new AbortController();
    управление.current = у;
    установитьИтог(null);
    установитьРежим('идёт');
    const ответ = await проверитьЧтение(запись, эталон, виды, { сигнал: у.signal, текстПоказа, словаПоказа });
    if (у.signal.aborted || управление.current !== у) return;
    управление.current = null;
    установитьРежим('покой');
    if (ответ.вид === 'ошибка' && ответ.ошибка === 'отменено') return;
    установитьИтог(ответ);
    вКонец();
  }

  function нажатьПроверить() {
    if (!прогресс.согласиеПроверкиГолосом || !прогресс.предупреждениеПоказано) {
      установитьРежим('согласие');
      вКонец();
      return;
    }
    void проверить();
  }

  if (!естьЗапись || заняты) return null;

  if (режим === 'согласие') {
    return (
      <View style={{ gap: отступ.m }}>
        {!прогресс.предупреждениеПоказано ? <ПредупреждениеИИИзКонтента testID="предупреждение-ии-проверка" /> : null}
        <Карточка вид="акцент" testID="согласие-проверки">
          <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
            <Значок имя="замок" размер={20} цвет={цвет.акцент} толщина={2} />
            <Текст вид="подзаголовок" стиль={{ flex: 1 }}>
              {т('согласие.заголовок')}
            </Текст>
          </View>
          <Текст>{т('согласие.сервер')}</Текст>
          <Текст>{т('согласие.никому')}</Текст>
          <Текст вид="мелкий">{т('предупреждение')}</Текст>
          <View style={{ gap: отступ.s, marginTop: отступ.s }}>
            <Кнопка
              надпись={т('согласие.да')}
              приНажатии={() => {
                изменить((п) => ({ ...п, согласиеПроверкиГолосом: true, предупреждениеПоказано: true }));
                void проверить();
              }}
              testID="согласие-проверки-да"
            />
            <Кнопка надпись={т('согласие.нет')} вид="тихая" приНажатии={() => установитьРежим('покой')} testID="согласие-проверки-нет" />
          </View>
        </Карточка>
      </View>
    );
  }

  const идёт = режим === 'идёт';
  return (
    <View style={{ gap: отступ.s }}>
      <Кнопка
        надпись={итог ? т('ещё') : т('проверить')}
        вид={итог ? 'вторичная' : 'основная'}
        отключена={идёт}
        приНажатии={нажатьПроверить}
        testID="проверить-запись"
      />
      {идёт ? (
        <Текст вид="второй" testID="проверка-идёт" accessibilityLiveRegion="polite">
          {т('идёт')}
        </Текст>
      ) : null}
      {итог ? (
        <View testID="итог-проверки" accessibilityLiveRegion="polite">
          <РепликаУстаза состояние={состояниеЭмблемы(итог)}>
            <View style={{ gap: отступ.s }}>
              {итог.вид === 'ответ' && итог.замечания.length > 0
                ? итог.замечания.map((з, i) => (
                    <View key={i} style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'flex-start' }}>
                      <Значок имя="нукта" размер={16} цвет={з.уровень === 'подсказка' ? цвет.акцент : цвет.внимание} стиль={{ marginTop: 4 }} />
                      <СмешанныйТекст testID="подсказка-проверки" стиль={{ flex: 1 }}>
                        {текстЗамечания(з, язык)}
                      </СмешанныйТекст>
                    </View>
                  ))
                : null}
              {итог.вид === 'ответ' && итог.замечания.length === 0 ? <Текст testID="проверка-без-замечаний">{текстБезЗамечаний(язык)}</Текст> : null}
              {итог.вид === 'плохой-звук' ? <Текст testID="проверка-плохой-звук">{текстПлохогоЗвука(итог.причина, язык)}</Текст> : null}
              {итог.вид === 'ошибка' ? (
                <Текст вид="второй" testID="проверка-недоступна">
                  {текстОшибкиПроверки(итог.ошибка, язык)}
                </Текст>
              ) : null}
              {итог.вид === 'ответ' && итог.замечания.length > 0 ? <Текст вид="мелкий">{т('черновик')}</Текст> : null}
            </View>
          </РепликаУстаза>
        </View>
      ) : null}
      <Текст вид="мелкий" testID="проверка-ии-предупреждение">
        {т('предупреждение')}
      </Текст>
    </View>
  );
}

/** Состояние эмблемы по итогу: замечания — «объясняю», без замечаний — «покой», плохой звук и сбой — «молчу». */
function состояниеЭмблемы(итог: ИтогПроверки): СостояниеЭмблемы {
  if (итог.вид === 'ответ') return итог.замечания.length > 0 ? 'объясняю' : 'покой';
  return 'молчу';
}
