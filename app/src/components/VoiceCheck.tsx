/**
 * Проверка голосом — кнопка «Проверить» под готовой записью и мягкий итог. Показывается ТОЛЬКО если
 * проверкаГолосомВключена() (speech/flag.ts): сборка с EXPO_PUBLIC_SPEECH_CHECK=1 и страница НЕ на batr.kz.
 * На batr.kz/aiustaz компонент ничего не рисует.
 *
 * Контракт: <ПроверкаГолосом эталон текстПоказа виды? словаПоказа? приИтоге? естьЗапись заняты получитьЗапись />
 *   эталон / текстПоказа — speech/check.ts (эталонЗадания); виды — из данных задания, если есть;
 *   словаПоказа — для аята (quran-check, 19.11.2026): слова копии для показа, слово подсказки — только отсюда;
 *   приИтоге(итог | null) — экран подсвечивает слова замечаний в аяте (null — итог сброшен);
 *   естьЗапись — готовая запись есть; заняты — идёт запись/запрос микрофона (итог сбрасывается);
 *   получитьЗапись — Blob записи (useЗаписьГолоса().получитьЗапись).
 * testID: проверить-запись, согласие-проверки (+ -да / -нет), проверка-идёт, итог-проверки,
 *         подсказка-проверки, проверка-ии-предупреждение.
 *
 * Правила (CLAUDE.md, правила 4, 7, 11, 12; «Данные и приватность»):
 * - запись уходит на сервер только по нажатию «Проверить»; перед первой отправкой — пояснение
 *   «уйдёт на сервер AI Ustaz в Казахстане, удалится сразу после проверки» (согласие — в прогрессе,
 *   локально); если ИИ-предупреждение QML ещё не показано — оно здесь же, до первого использования;
 * - итог — только «Проверьте себя: …» / «Подсказка: …» по шаблонам (speech/hints.ts, черновик),
 *   без «Ошибка», «неправильно», «верно»; нет замечаний — «Мы не услышали расхождений. Проверка ИИ
 *   может ошибаться»; плохой звук — «Плохо слышно… это не ошибка»;
 * - рядом всегда «Проверка ИИ — может ошибаться, не заменяет устаза»; фонемы не показываем.
 * Вид (дизайн-система 19.11.2026): итог — реплика ИИ-наставника (<РепликаУстаза>): замечания — эмблема
 * «объясняю», каждое замечание с нуктой (указатель места; «Проверьте себя» — янтарь, «Подсказка» — акцент);
 * без замечаний — «покой»; плохой звук и сервис недоступен — «молчу» (не уверен — не ругаем).
 * Тексты внутри — только из шаблонов speech/hints.ts.
 */
