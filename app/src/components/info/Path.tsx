/**
 * Путь: узлы и вертикальная линия «этапов пути» (карта курса, «что есть / что будет», шаги онбординга),
 * и нукта — маленький ромб-указатель (пункты списка, дни занятий).
 *
 * Контракт:
 *   <ШагПути узел={<УзелПути …/>} первый? последний? линия?="сплошная|тихая" верхУзла?={12} ширина?={44}
 *            testID?>…содержимое справа…</ШагПути>
 *     — строка пути: слева колонка с узлом и тонкой линией (золотоДекор — только декор), справа содержимое.
 *       Строки ставятся подряд без зазора (отступ снизу — внутри строки), тогда линия непрерывна.
 *       первый — линия начинается от узла; последний — заканчивается на узле; линия «тихая» — участок после
 *       узла бледнее (впереди то, что ещё не вышло).
 *   <УзелПути вид="пройден|текущий|доступен|скоро" метка? значок? размер?={36} форма?="круг|квадрат" подложка? />
 *     — кружок с меткой («1», «К1») или значком. пройден — изумруд; текущий — мягкое золото с тонким
 *       золотым кольцом (текущий шаг); доступен — контур изумрудом; скоро — утопленный, тише.
 *       Декоративный (скрыт от диктора): смысл несёт текст рядом («Пройден», «Скоро»).
 *       подложка — цвет под кольцом текущего узла (по умолчанию цвет.фон; на карточке — цвет.поверхность).
 *   <Нукта размер?={8} цвет? контур? /> — ромб 45° (нукта из образа устаза): указатель пункта, отметка дня.
 * Правила (docs/дизайн/03-дизайн-система.md §2.3, §7): звезда хатам — не награда; пройденное — круг
 * с изумрудом, без звёзд, блеска и анимации; золото — только линия и «текущий шаг».
 */
import type { ReactNode } from 'react';
import { View } from 'react-native';
import { ОРНАМЕНТ, useТема } from '../../theme';
import { Значок, type ИмяЗначка } from '../Icon';
import { Текст } from '../Text';

export type ВидУзла = 'пройден' | 'текущий' | 'доступен' | 'скоро';

export function УзелПути({
  вид,
  метка,
  значок,
  размер = 36,
  форма = 'круг',
  подложка,
}: {
  вид: ВидУзла;
  метка?: string;
  значок?: ИмяЗначка;
  размер?: number;
  форма?: 'круг' | 'квадрат';
  подложка?: string;
}) {
  const { цвет, радиус } = useТема();
  const [фон, текст, рамка] =
    вид === 'пройден'
      ? [цвет.акцент, цвет.акцентТекст, цвет.акцент]
      : вид === 'текущий'
        ? [цвет.следующийФон, цвет.следующийТекст, цвет.следующийФон]
        : вид === 'доступен'
          ? [цвет.поверхность, цвет.акцент, цвет.акцент]
          : [цвет.поверхностьВторая, цвет.текстВторой, цвет.граница];
  const скругление = форма === 'круг' ? радиус.круг : радиус.s;
  const длинная = (метка?.length ?? 0) > 2;
  const внутри = (
    <View
      style={{
        minWidth: размер,
        height: размер,
        paddingHorizontal: длинная ? 6 : 0,
        borderRadius: скругление,
        borderWidth: вид === 'доступен' ? 1.5 : 1,
        borderColor: рамка,
        backgroundColor: фон,
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      {значок ? (
        <Значок имя={значок} размер={Math.round(размер * 0.55)} цвет={текст} толщина={2} />
      ) : метка ? (
        <Текст вид="метка" цвет={текст} табличные стиль={размер >= 40 ? { fontSize: 15, lineHeight: 20 } : null}>
          {метка}
        </Текст>
      ) : null}
    </View>
  );
  return (
    <View accessibilityElementsHidden importantForAccessibility="no-hide-descendants" style={{ pointerEvents: 'none' }}>
      {вид === 'текущий' ? (
        // Текущий шаг: тонкое золотое кольцо вокруг (фон экрана в зазоре закрывает линию пути).
        <View style={{ padding: 3, borderRadius: скругление, borderWidth: 1.5, borderColor: цвет.золотоДекор, backgroundColor: подложка ?? цвет.фон }}>{внутри}</View>
      ) : (
        внутри
      )}
    </View>
  );
}

export function ШагПути({
  узел,
  children,
  первый = false,
  последний = false,
  линия = 'сплошная',
  верхУзла = 12,
  ширина = 44,
  testID,
}: {
  узел: ReactNode;
  children?: ReactNode;
  первый?: boolean;
  последний?: boolean;
  линия?: 'сплошная' | 'тихая';
  верхУзла?: number;
  ширина?: number;
  testID?: string;
}) {
  const { цвет, отступ } = useТема();
  // Центр узла по вертикали: верхУзла + половина типичного узла (36 + кольцо).
  const центр = верхУзла + 20;
  const прозрачность = ОРНАМЕНТ.полоса;
  return (
    <View testID={testID} style={{ flexDirection: 'row', gap: отступ.m }}>
      <View style={{ width: ширина, alignItems: 'center' }} accessibilityElementsHidden importantForAccessibility="no-hide-descendants">
        {!первый ? (
          <View style={{ position: 'absolute', top: 0, height: центр, width: 2, borderRadius: 1, backgroundColor: цвет.золотоДекор, opacity: прозрачность }} />
        ) : null}
        {!последний ? (
          <View
            style={{
              position: 'absolute',
              top: центр,
              bottom: 0,
              width: 2,
              borderRadius: 1,
              backgroundColor: цвет.золотоДекор,
              opacity: линия === 'тихая' ? прозрачность * 0.45 : прозрачность,
            }}
          />
        ) : null}
        <View style={{ marginTop: верхУзла }}>{узел}</View>
      </View>
      <View style={{ flex: 1, minWidth: 0, paddingBottom: последний ? 0 : отступ.m }}>{children}</View>
    </View>
  );
}

export function Нукта({ размер = 8, цвет, контур = false }: { размер?: number; цвет?: string; контур?: boolean }) {
  const тема = useТема();
  const ц = цвет ?? тема.цвет.акцент;
  return (
    <View
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
      style={{
        width: размер,
        height: размер,
        borderRadius: 1,
        transform: [{ rotate: '45deg' }],
        backgroundColor: контур ? 'transparent' : ц,
        borderWidth: контур ? 1.25 : 0,
        borderColor: ц,
        pointerEvents: 'none',
      }}
    />
  );
}
