export function КарточкаПредупрежденияИИ({
  предупреждение,
  акцент = true,
  testID = 'предупреждение-ии',
}: {
  предупреждение: ПредупреждениеИИ;
  акцент?: boolean;
  testID?: string;
}) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет } = useТема();
  return (
    <Карточка вид={акцент ? 'акцент' : 'обычная'} testID={testID}>
      <View style={{ gap: отступ.m }}>
        {/* Шапка: эмблема ИИ-наставника — это предупреждение об ИИ, не слова живого устаза. */}
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
          <ЭмблемаУстаза размер={40} />
          <Текст вид="подзаголовок" accessibilityRole="header" уровень={2} стиль={{ flex: 1 }}>
            {т('заголовок')}
          </Текст>
        </View>
        <АрабскийТекст размер="малый" выравнивание="right" стиль={{ fontSize: 24, lineHeight: 46 }} testID="предупреждение-ar">
          {предупреждение.ar}
        </АрабскийТекст>
        <View style={{ height: 1, backgroundColor: акцент ? цвет.акцентМягкий : цвет.граница }} />
        <Текст testID="предупреждение-текст">{текстЯзыка(предупреждение, язык)}</Текст>
        {язык === 'kk' ? <Текст вид="мелкий">{т('казахский')}</Текст> : null}
        {язык === 'uz' && предупреждение.uz ? <Текст вид="мелкий">{т('узбекский')}</Текст> : null}
        {язык === 'en' && предупреждение.en ? <Текст вид="мелкий">{т('английский')}</Текст> : null}
        {предупреждение.прочитано ? <Текст вид="мелкий">{т('источник', { дата: предупреждение.прочитано })}</Текст> : null}
      </View>
    </Карточка>
  );
}

export function ПредупреждениеИИИзКонтента({ testID }: { testID?: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const { t } = useПеревод();
  const урок0 = useДанные('lesson0');
  if (урок0.состояние === 'загрузка') return <Текст вид="второй">{t('общее.загрузка')}</Текст>;
  if (урок0.состояние === 'нет' && урок0.нетСвязи) {
    return (
      <View style={{ gap: 8 }}>
        <Текст вид="второй">{t('общее.нетСвязи')}</Текст>
        <Кнопка вид="вторичная" значок="повтор" надпись={t('общее.повторить')} растянуть={false} приНажатии={урок0.повторить} testID={testID ? testID + '-повторить' : undefined} />
      </View>
    );
  }
  if (урок0.состояние === 'нет') return <Текст вид="второй">{т('нет')}</Текст>;
  return <КарточкаПредупрежденияИИ предупреждение={урок0.данные.предупреждениеИИ} testID={testID} />;
}
