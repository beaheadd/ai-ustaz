/**
 * ИИ-предупреждение QML (лицензия модели quran-muaalem; CLAUDE.md, правило 12; программа курса §5.1):
 * всегда на арабском и на языке интерфейса, не мельче обычного текста.
 * Тексты — только из /content/lesson0.json (ar и ru — официальные из NOTICE, kk — наш черновик).
 *
 * Контракт:
 *   <КарточкаПредупрежденияИИ предупреждение={ПредупреждениеИИ} акцент? testID? />
 *   <ПредупреждениеИИИзКонтента testID? /> — сам грузит lesson0.json (для «О проекте» и главной).
 */
import { View } from 'react-native';
import type { ПредупреждениеИИ } from '../../content/types';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { useДанные } from './data';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    заголовок: 'ИИ-предупреждение',
    казахский: '',
    источник: 'Официальный текст из файла NOTICE модели quran-muaalem (лицензия QML-1.0). Прочитано: {дата}.',
    нет: 'Текст предупреждения не загрузился. Обновите страницу.',
  },
  kk: {
    заголовок: 'ЖИ туралы ескерту',
    казахский: 'Қазақша мәтін — біздің аудармамыз, жоба: оны ана тілінде сөйлейтін аудармашы тексереді.',
    источник: 'Арабша мәтін — quran-muaalem моделінің NOTICE файлынан алынған ресми мәтін (QML-1.0 лицензиясы). Оқылған күні: {дата}.',
    нет: 'Ескерту мәтіні жүктелмеді. Бетті жаңартыңыз.',
  },
});

export function КарточкаПредупрежденияИИ({
  предупреждение,
  акцент = true,
  testID = 'предупреждение-ии',
}: {
  предупреждение: ПредупреждениеИИ;
  акцент?: boolean;
  testID?: string;
}) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет } = useТема();
  return (
    <Карточка акцент={акцент} заголовок={т('заголовок')} testID={testID}>
      <View style={{ gap: отступ.m }}>
        <АрабскийТекст размер="малый" выравнивание="right" стиль={{ fontSize: 24, lineHeight: 46 }} testID="предупреждение-ar">
          {предупреждение.ar}
        </АрабскийТекст>
        <View style={{ height: 1, backgroundColor: цвет.граница }} />
        <Текст testID="предупреждение-текст">{язык === 'kk' ? предупреждение.kk : предупреждение.ru}</Текст>
        {язык === 'kk' ? <Текст вид="мелкий">{т('казахский')}</Текст> : null}
        {предупреждение.прочитано ? <Текст вид="мелкий">{т('источник', { дата: предупреждение.прочитано })}</Текст> : null}
      </View>
    </Карточка>
  );
}

export function ПредупреждениеИИИзКонтента({ testID }: { testID?: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const { t } = useПеревод();
  const урок0 = useДанные('lesson0');
  if (урок0.состояние === 'загрузка') return <Текст вид="второй">{t('общее.загрузка')}</Текст>;
  if (урок0.состояние === 'нет') return <Текст вид="второй">{т('нет')}</Текст>;
  return <КарточкаПредупрежденияИИ предупреждение={урок0.данные.предупреждениеИИ} testID={testID} />;
}
