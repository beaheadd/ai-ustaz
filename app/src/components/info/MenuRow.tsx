/**
 * Строка меню: значок, надпись, пояснение и «›». Высота ≥ 56 px.
 * Обёртка над <СтрокаСписка> дизайн-системы (оставлена ради совместимости экранов).
 *
 * Контракт: <ПунктМеню надпись пояснение? значок? приНажатии раскрыт? testID? />
 *   значок — имя значка из набора ('карта', 'инфо', 'урок'…) или короткий символ (без лиц);
 *   раскрыт — для пунктов-раскрывашек (вместо «›» — «вниз/вверх», aria-expanded).
 */
import { СтрокаСписка } from '../ListRow';

export function ПунктМеню({
  надпись,
  пояснение,
  значок,
  приНажатии,
  раскрыт,
  testID,
}: {
  надпись: string;
  пояснение?: string;
  значок?: string;
  приНажатии: () => void;
  раскрыт?: boolean;
  testID?: string;
}) {
  return <СтрокаСписка заголовок={надпись} подпись={пояснение} значок={значок} приНажатии={приНажатии} раскрыт={раскрыт} testID={testID} />;
}
