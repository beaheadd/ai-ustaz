/**
 * Обзор пути обучения — общий для главной и карты курса (одни и те же числа на обоих экранах).
 *
 * Контракт:
 *   статусПункта(пункт, прогресс) → 'пройден' | 'начат' | 'доступен' | 'скоро' (чистая функция).
 *   статусыЭтапов(уровни, прогресс) → ВидУзла[] — пройден · текущий (первый непройденный с доступными) · доступен · скоро.
 *   сводкаПути(уровни, прогресс) → { этап, пройдено, всего, входПройден } | null — текущий этап (не вход) и сколько
 *     его пунктов пройдено; вход (урок 0) считается отдельно. Подпись на обоих экранах: «Этап 1: пройдено 1 из 17
 *     уроков» (kk: «1-кезең: 17 сабақтан 1 өтілді» — черновик) и отдельно «Вход (урок 0) — пройден».
 *   <ОбзорЭтапов уровни этапы названия подложка? testID?="карта-обзор" /> — узлы этапов на золотой линии.
 * Правила: без звёзд-наград, рейтингов и «серий»; линия — только декор (aria-hidden), смысл — в подписях.
 * Решение: дизайн-система 19.11.2026; общий счётчик — замечание рецензента 19.11.2026 (разные числа на главной и карте).
 */
import { View } from 'react-native';
import type { УровеньКурса, ПунктКурса } from '../../content/types';
import type { Прогресс } from '../../engine/progress';
import { useТема } from '../../theme';
import { Текст } from '../Text';
import { УзелПути, type ВидУзла } from './Path';

export type Статус = 'пройден' | 'начат' | 'доступен' | 'скоро';

export function статусПункта(п: Pick<ПунктКурса, 'номер' | 'доступен'>, прогресс: Прогресс): Статус {
  const итог = прогресс.уроки[String(п.номер)];
  if (итог?.пройден) return 'пройден';
  if (!п.доступен) return 'скоро';
  return (итог?.попыток ?? 0) > 0 ? 'начат' : 'доступен';
}

/** Статус этапа: пройден (всё пройдено), текущий (первый непройденный с доступными), доступен, скоро. Чистая функция. */
export function статусыЭтапов(уровни: УровеньКурса[], прогресс: Прогресс): ВидУзла[] {
  let текущийНайден = false;
  return уровни.map((у) => {
    const статусы = у.пункты.map((п) => статусПункта(п, прогресс));
    if (статусы.length > 0 && статусы.every((с) => с === 'пройден')) return 'пройден';
    if (!статусы.some((с) => с !== 'скоро' && с !== 'пройден')) return 'скоро';
    if (!текущийНайден) {
      текущийНайден = true;
      return 'текущий';
    }
    return 'доступен';
  });
}


export type СводкаПути = { этап: УровеньКурса; пройдено: number; всего: number; входПройден: boolean };

/** Текущий этап (уровень ≥ 1) и сколько его пунктов пройдено; вход (уровень 0) — отдельно. Чистая функция. */
export function сводкаПути(уровни: УровеньКурса[], прогресс: Прогресс): СводкаПути | null {
  const этапы = статусыЭтапов(уровни, прогресс);
  const вход = уровни.find((у) => у.уровень === 0);
  const входПройден = !!вход && вход.пункты.length > 0 && вход.пункты.every((п) => статусПункта(п, прогресс) === 'пройден');
  let i = этапы.findIndex((в, к) => в === 'текущий' && уровни[к].уровень >= 1);
  if (i < 0) i = уровни.findIndex((у) => у.уровень >= 1);
  if (i < 0) return null;
  const этап = уровни[i];
  const пройдено = этап.пункты.filter((п) => статусПункта(п, прогресс) === 'пройден').length;
  return { этап, пройдено, всего: этап.пункты.length, входПройден };
}

/**
 * Обзор этапов: узлы по горизонтали на золотой линии (пройден · вы здесь · впереди), подпись под узлом.
 * Контракт: <ОбзорЭтапов уровни этапы={статусыЭтапов(…)} названия={['Вход', 'Этап 1', …]} подложка? testID?="карта-обзор" />
 * — общий для карты курса и главной (подложка — цвет под кольцом текущего узла, по умолчанию цвет.поверхность).
 */
export function ОбзорЭтапов({
  уровни,
  этапы,
  названия,
  подложка,
  testID = 'карта-обзор',
}: {
  уровни: Pick<УровеньКурса, 'уровень'>[];
  этапы: ВидУзла[];
  названия: string[];
  подложка?: string;
  testID?: string;
}) {
  const { цвет, отступ } = useТема();
  const ВЫСОТА = 44;
  // Линия — от центра первого узла до центра последнего (колонки равной ширины).
  const край = `${50 / уровни.length}%` as const;
  return (
    <View testID={testID} style={{ paddingTop: отступ.xs }}>
      <View
        aria-hidden
        style={{ position: 'absolute', top: ВЫСОТА / 2 - 1 + отступ.xs, left: край, right: край, height: 2, borderRadius: 1, backgroundColor: цвет.золотоДекор, opacity: 0.55 }}
      />
      <View style={{ flexDirection: 'row' }}>
        {уровни.map((у, i) => (
          <View key={у.уровень} style={{ flex: 1, alignItems: 'center', gap: 2 }}>
            <View style={{ height: ВЫСОТА, justifyContent: 'center' }}>
              <УзелПути
                вид={этапы[i]}
                размер={30}
                подложка={подложка ?? цвет.поверхность}
                значок={этапы[i] === 'пройден' ? 'галочка' : undefined}
                метка={этапы[i] === 'пройден' ? undefined : String(у.уровень)}
              />
            </View>
            <Текст
              вид={этапы[i] === 'текущий' ? 'метка' : 'мелкий'}
              цвет={этапы[i] === 'текущий' ? цвет.золотоТекст : undefined}
              стиль={{ textAlign: 'center' }}
              numberOfLines={1}
            >
              {названия[i]}
            </Текст>
          </View>
        ))}
      </View>
    </View>
  );
}

