export function ЧтоЕстьЧтоБудет({ testID = 'главная-что-будет' }: { testID?: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет } = useТема();
  const вехи: { заголовок: string; пункты: string[]; вид: ВидУзла }[] = [
    { заголовок: т('есть'), пункты: [т('есть1'), т('есть2'), т('есть3'), т('есть5'), т('есть4')], вид: 'пройден' },
    { заголовок: т('скоро'), пункты: [т('скоро1'), т('скоро2'), т('скоро3')], вид: 'текущий' },
    { заголовок: т('потом'), пункты: [т('потом1'), т('потом2'), т('потом3')], вид: 'скоро' },
  ];
  return (
    <Карточка testID={testID}>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
        <Значок имя="карта" размер={22} цвет={цвет.акцент} />
        <Текст вид="подзаголовок" стиль={{ flex: 1 }}>
          {т('заголовок')}
        </Текст>
      </View>
      <View style={{ paddingTop: отступ.xs }}>
        {вехи.map((в, i) => (
          <ШагПути
            key={в.заголовок}
            первый={i === 0}
            последний={i === вехи.length - 1}
            линия={i >= 1 ? 'тихая' : 'сплошная'}
            верхУзла={0}
            ширина={36}
            узел={<УзелПути вид={в.вид} размер={26} подложка={цвет.поверхность} значок={в.вид === 'пройден' ? 'галочка' : undefined} метка={в.вид === 'пройден' ? undefined : String(i + 1)} />}
          >
            <View style={{ gap: отступ.s, paddingTop: 2 }}>
              <Текст стиль={{ fontWeight: '600' }}>{в.заголовок}</Текст>
              <Пункты пункты={в.пункты} вид={в.вид === 'скоро' ? 'второй' : 'обычный'} />
            </View>
          </ШагПути>
        ))}
      </View>
      <Текст вид="мелкий">{т('сноска')}</Текст>
    </Карточка>
  );
}
