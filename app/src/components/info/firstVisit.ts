/**
 * Флаг «онбординг уже предлагали в этот заход на страницу» (только в памяти страницы).
 * Главная открывает онбординг при первом входе не больше одного раза за заход — иначе
 * «назад» из онбординга снова открыл бы его.
 *
 * Контракт: онбордингПредлагался() → boolean; отметитьОнбордингПредложен().
 */
let предложен = false;

export function онбордингПредлагался(): boolean {
  return предложен;
}

export function отметитьОнбордингПредложен(): void {
  предложен = true;
}
