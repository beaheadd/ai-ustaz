/**
 * Текст интерфейса со вставками арабского (например, объяснение «В слове ٱلْحَمْدُ буква ха (ح)…»).
 * Строку делит на куски: арабские куски рисует <АрабскийТекст встроенный> (Amiri Quran,
 * на вебе <span dir="rtl" lang="ar"> — браузер изолирует направление), остальное — как есть.
 * Сам текст не меняется: куски склеиваются обратно в исходную строку.
 *
 * Контракт: <СмешанныйТекст вид? стиль? testID? accessibilityRole?>{строка}</СмешанныйТекст>
 *   Кегль арабских вставок зависит от вида (заголовок — крупнее). Используется и в уроках (exercises).
 *   разбитьНаКуски(строка) → { арабский: boolean; текст: string }[] — чистая функция.
 */
import type { StyleProp, TextProps, TextStyle } from 'react-native';
import { АрабскийТекст } from '../ArabicText';
import { Текст, type ВидТекста } from '../Text';

const БУКВА = '\\u0600-\\u06FF\\u0750-\\u077F\\u08A0-\\u08FF\\uFB50-\\uFDFF\\uFE70-\\uFEFF';
/** Арабский кусок: от арабского символа до арабского символа; внутри — пробелы и ZWNJ/ZWJ. */
const КУСОК = new RegExp(`[${БУКВА}](?:[${БУКВА}\\u200C\\u200D ]*[${БУКВА}])?`, 'g');

export type Кусок = { арабский: boolean; текст: string };

export function разбитьНаКуски(строка: string): Кусок[] {
  const куски: Кусок[] = [];
  let позиция = 0;
  for (const н of строка.matchAll(КУСОК)) {
    const начало = н.index ?? 0;
    if (начало > позиция) куски.push({ арабский: false, текст: строка.slice(позиция, начало) });
    куски.push({ арабский: true, текст: н[0] });
    позиция = начало + н[0].length;
  }
  if (позиция < строка.length) куски.push({ арабский: false, текст: строка.slice(позиция) });
  return куски;
}

/** Кегль и интерлиньяж арабских вставок по виду текста: арабское письмо мельче кириллицы того же кегля. */
const АРАБСКИЙ_ПО_ВИДУ: Record<ВидТекста, { кегль: number; строка: number }> = {
  заголовок: { кегль: 34, строка: 50 },
  подзаголовок: { кегль: 26, строка: 40 },
  обычный: { кегль: 22, строка: 36 },
  второй: { кегль: 22, строка: 36 },
  мелкий: { кегль: 18, строка: 28 },
};

export function СмешанныйТекст({
  children,
  вид = 'обычный',
  стиль,
  testID,
  accessibilityRole,
}: {
  children: string;
  вид?: ВидТекста;
  стиль?: StyleProp<TextStyle>;
  testID?: string;
  accessibilityRole?: TextProps['accessibilityRole'];
}) {
  const куски = разбитьНаКуски(children);
  const естьАрабский = куски.some((к) => к.арабский);
  const размер = АРАБСКИЙ_ПО_ВИДУ[вид];
  return (
    <Текст
      вид={вид}
      testID={testID}
      accessibilityRole={accessibilityRole}
      стиль={[естьАрабский ? { lineHeight: размер.строка } : null, стиль]}
    >
      {куски.map((к, i) =>
        к.арабский ? (
          <АрабскийТекст key={i} встроенный размер="малый" стиль={{ fontSize: размер.кегль }}>
            {к.текст}
          </АрабскийТекст>
        ) : (
          к.текст
        ),
      )}
    </Текст>
  );
}
