/**
 * Карточка объяснения ошибки (ПЛАН §4.4, каталог ошибок §13): где → что прозвучало → как надо →
 * правило → что сделать. Всегда с пометкой «пример, не проверка вашего чтения» (проверки голоса нет).
 * Тексты — только из /content/fatiha-demo.json (утверждённая база шаблонов каталога), не LLM.
 * Слово — дословно из Tanzil (data.ts сверил его со словом аята по номеру).
 *
 * Контракт: <КарточкаОбъяснения пример={ПримерОбъяснения} пометка={ЛокализованныйТекст} testID? />
 */
import type { ReactNode } from 'react';
import { View } from 'react-native';
import type { ЛокализованныйТекст, ПримерОбъяснения } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { СмешанныйТекст } from './MixedText';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    где: 'Где',
    гдеТекст: 'Аят {сура}:{аят}, слово {слово}',
    буква: 'буква',
    прозвучало: 'Что прозвучало',
    надо: 'Как надо',
    правило: 'Правило',
    сделать: 'Что сделать',
    повторите: 'Повторите по ступеням:',
    текст: 'Так будет звучать объяснение',
    код: 'Код в каталоге ошибок: {код}',
    кари: 'Голос кари к упражнению появится после записи эталона.',
  },
  kk: {
    где: 'Қай жерде',
    гдеТекст: '{сура}:{аят} аят, {слово}-сөз',
    буква: 'әріп',
    прозвучало: 'Не естілді',
    надо: 'Қалай болуы керек',
    правило: 'Ереже',
    сделать: 'Не істеу керек',
    повторите: 'Сатылап қайталаңыз:',
    текст: 'Түсіндірме осылай естіледі',
    код: 'Қателер каталогындағы коды: {код}',
    кари: 'Жаттығуға арналған қари дауысы эталон жазылғаннан кейін қосылады.',
  },
});

export function ЧипУровня({ пример }: { пример: ПримерОбъяснения }) {
  const { язык } = useПеревод();
  const { цвет, радиус, отступ } = useТема();
  const ошибка = пример.уровень === 'Ошибка';
  return (
    <View
      style={{
        alignSelf: 'flex-start',
        borderRadius: радиус.круг,
        paddingHorizontal: отступ.m,
        paddingVertical: 2,
        borderWidth: 1,
        borderColor: ошибка ? цвет.внимание : цвет.акцент,
        backgroundColor: цвет.поверхность,
      }}
    >
      <Текст вид="мелкий" стиль={{ color: ошибка ? цвет.внимание : цвет.акцент, fontWeight: '600' }}>
        {локально(пример.названиеУровня, язык)}
      </Текст>
    </View>
  );
}

function Шаг({ номер, заголовок, children }: { номер: number; заголовок: string; children: ReactNode }) {
  const { цвет, отступ, радиус } = useТема();
  return (
    <View style={{ flexDirection: 'row', gap: отступ.m }}>
      <View
        style={{
          width: 26,
          height: 26,
          borderRadius: радиус.круг,
          backgroundColor: цвет.акцентМягкий,
          alignItems: 'center',
          justifyContent: 'center',
          marginTop: 1,
        }}
        accessibilityElementsHidden
        importantForAccessibility="no"
      >
        <Текст вид="мелкий" стиль={{ color: цвет.акцент, fontWeight: '700' }}>
          {String(номер)}
        </Текст>
      </View>
      <View style={{ flex: 1, gap: 2 }}>
        <Текст вид="мелкий" стиль={{ fontWeight: '600' }}>
          {заголовок}
        </Текст>
        {children}
      </View>
    </View>
  );
}

export function КарточкаОбъяснения({
  пример,
  пометка,
  testID = 'карточка-объяснения',
}: {
  пример: ПримерОбъяснения;
  пометка: ЛокализованныйТекст;
  testID?: string;
}) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const шаги: { заголовок: string; содержимое: ReactNode }[] = [
    {
      заголовок: т('где'),
      содержимое: (
        <Текст>
          {т('гдеТекст', { сура: пример.сура, аят: пример.аят, слово: пример.слово })}
          {пример.буква ? (
            <>
              {', ' + т('буква') + ' '}
              <АрабскийТекст встроенный размер="малый" стиль={{ fontSize: 22 }}>
                {пример.буква}
              </АрабскийТекст>
            </>
          ) : null}
        </Текст>
      ),
    },
    ...(пример.услышано ? [{ заголовок: т('прозвучало'), содержимое: <Текст>«{пример.услышано}»</Текст> }] : []),
    ...(пример.нужно ? [{ заголовок: т('надо'), содержимое: <Текст>«{пример.нужно}»</Текст> }] : []),
    { заголовок: т('правило'), содержимое: <СмешанныйТекст>{локально(пример.правило, язык)}</СмешанныйТекст> },
    {
      заголовок: т('сделать'),
      содержимое: (
        <View style={{ gap: отступ.xs }}>
          <СмешанныйТекст>{локально(пример.чтоСделать, язык)}</СмешанныйТекст>
          {пример.лестница.length > 0 ? (
            <>
              <Текст вид="второй">{т('повторите')}</Текст>
              <АрабскийТекст размер="средний" выравнивание="right" testID="объяснение-лестница">
                {пример.лестница.join(' — ')}
              </АрабскийТекст>
            </>
          ) : null}
        </View>
      ),
    },
  ];

  return (
    <Карточка testID={testID}>
      <View style={{ gap: отступ.m }}>
        <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between', gap: отступ.s, flexWrap: 'wrap' }}>
          <ЧипУровня пример={пример} />
          <СмешанныйТекст вид="мелкий">{т('код', { код: пример.код })}</СмешанныйТекст>
        </View>
        <АрабскийТекст размер="крупный" testID="объяснение-слово">
          {пример.текстСлова}
        </АрабскийТекст>
        {шаги.map((ш, i) => (
          <Шаг key={ш.заголовок} номер={i + 1} заголовок={ш.заголовок}>
            {ш.содержимое}
          </Шаг>
        ))}
        <View style={{ borderLeftWidth: 3, borderLeftColor: цвет.акцент, paddingLeft: отступ.m, gap: отступ.xs }}>
          <Текст вид="мелкий" стиль={{ fontWeight: '600' }}>
            {т('текст')}
          </Текст>
          <СмешанныйТекст вид="второй">{локально(пример.текст, язык)}</СмешанныйТекст>
        </View>
        {пример.примечание ? <СмешанныйТекст вид="мелкий">{локально(пример.примечание, язык)}</СмешанныйТекст> : null}
        <Текст вид="мелкий">{т('кари')}</Текст>
        <View
          style={{ backgroundColor: цвет.плашкаФон, borderRadius: радиус.s, paddingHorizontal: отступ.m, paddingVertical: отступ.s }}
          testID="объяснение-пометка"
        >
          <Текст вид="мелкий" стиль={{ color: цвет.плашкаТекст, fontWeight: '600' }}>
            {локально(пометка, язык)}
          </Текст>
        </View>
      </View>
    </Карточка>
  );
}
