export function проверитьИсточники(сырые: unknown): ИсточникиДанные | null {
  const о = объект(сырые);
  const список = Array.isArray(сырые) ? сырые : Array.isArray(о?.источники) ? (о.источники as unknown[]) : null;
  if (!список) return null;
  const поле = (з: unknown) => (строка(з) ? з.trim() || null : null);
  const источники = список.flatMap((з, i): ИсточникКонтента[] => {
    const и = объект(з);
    if (!и || !строка(и.название)) return [];
    return [
      {
        id: строка(и.id) ? и.id : String(i),
        название: и.название,
        что: поле(и.что),
        лицензия: поле(и.лицензия),
        ссылка: поле(и.ссылка),
        лицензияСсылка: поле(и.лицензияСсылка),
        атрибуция: поле(и.атрибуция),
        // Блок условий Tanzil показываем как есть (без правок): только обрезаем пустые края.
        условия: строка(и.условия) ? и.условия.replace(/^\s+|\s+$/g, '') || null : null,
        примечание: поле(и.примечание),
        прочитано: поле(и.прочитано),
      },
    ];
  });
  return { версия: строка(о?.версия) ? (о.версия as string) : null, источники };
}

// ───────────────────────── Загрузка ─────────────────────────

const ПРОВЕРКИ: { [И in ИмяДанных]: (сырые: unknown) => ДанныеПоИмени[И] | null } = {
  course: проверитьКурс,
  lesson0: проверитьУрок0,
  'fatiha-demo': проверитьДемо,
  sources: проверитьИсточники,
};

/** /content (корень репозитория), без подпапок; каждый файл — отдельный ленивый чанк. */
const КОНТЕНТ = require.context('../../../../content', false, /(^|\/)(course|lesson0|fatiha-demo|sources)\.json$/, 'lazy');

const кэш = new Map<ИмяДанных, Promise<unknown>>();

export function загрузитьДанные<И extends ИмяДанных>(имя: И): Promise<ДанныеПоИмени[И] | null> {
  let обещание = кэш.get(имя);
  if (!обещание) {
    обещание = (async () => {
      const ключ = КОНТЕНТ.keys().find((к) => к.endsWith('/' + имя + '.json'));
      if (!ключ) return null;
      try {
        const м = (await (КОНТЕНТ(ключ) as Promise<unknown> | unknown)) as unknown;
        const сырые = м && typeof м === 'object' && 'default' in м ? (м as { default: unknown }).default : м;
        return ПРОВЕРКИ[имя](сырые);
      } catch {
        return null;
      }
    })();
    кэш.set(имя, обещание);
  }
  return обещание as Promise<ДанныеПоИмени[И] | null>;
}

export type СостояниеДанных<Т> = { состояние: 'загрузка' } | { состояние: 'нет' } | { состояние: 'есть'; данные: Т };

export function useДанные<И extends ИмяДанных>(имя: И): СостояниеДанных<ДанныеПоИмени[И]> {
  const [с, установить] = useState<СостояниеДанных<ДанныеПоИмени[И]>>({ состояние: 'загрузка' });
  useEffect(() => {
    let живой = true;
    загрузитьДанные(имя).then((данные) => {
      if (живой) установить(данные ? { состояние: 'есть', данные } : { состояние: 'нет' });
    });
    return () => {
      живой = false;
    };
  }, [имя]);
  return с;
}
