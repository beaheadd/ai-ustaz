/**
 * Запись /content/sources.json. Поля, кроме «название», необязательны.
 * ссылка — текст вида 'tanzil.net' или 'github.com/… — файл NOTICE' (без схемы: в бандле не должно
 * быть внешних URL, scripts/check-dist.mjs); адрес для перехода собирает экран.
 */
export type ИсточникКонтента = {
  id: string;
  название: string;
  что: string | null;
  лицензия: string | null;
  ссылка: string | null;
  /** Адрес текста лицензии без схемы (CC BY 3.0, раздел 4(a): URI лицензии к каждой копии). */
  лицензияСсылка: string | null;
  атрибуция: string | null;
  условия: string | null;
  примечание: string | null;
  прочитано: string | null;
};

export type ИсточникиДанные = { версия: string | null; источники: ИсточникКонтента[] };

export type ДанныеПоИмени = {
  course: КартаКурсаДанные;
  lesson0: Урок0Данные;
  'fatiha-demo': ДемоФатихи;
  sources: ИсточникиДанные;
};
export type ИмяДанных = keyof ДанныеПоИмени;

// ───────────────────────── Мелкие проверки ─────────────────────────

const СТАТУСЫ: readonly СтатусКонтента[] = ['черновик', 'проверен-устазом', 'подписан-советом'];
const ОЧЕРЕДИ: readonly ОчередьВыпуска[] = ['сейчас', 'следующий выпуск', 'следующие выпуски', 'позже'];
const ВИДЫ_ПУНКТОВ: readonly ПунктКурса['вид'][] = ['вход', 'урок', 'контрольная', 'намаз', 'итог'];

function строка(з: unknown): з is string {
  return typeof з === 'string' && з.length > 0;
}
function целое(з: unknown, мин: number, макс: number): з is number {
  return typeof з === 'number' && Number.isInteger(з) && з >= мин && з <= макс;
}
function локализованный(з: unknown): з is ЛокализованныйТекст {
  if (!з || typeof з !== 'object') return false;
  const т = з as Record<string, unknown>;
  return typeof т.ru === 'string' && typeof т.kk === 'string' && (т.ru.length > 0 || т.kk.length > 0);
}
function статус(з: unknown): СтатусКонтента {
  return (СТАТУСЫ as readonly unknown[]).includes(з) ? (з as СтатусКонтента) : 'черновик';
}
function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
const ПУСТО: ЛокализованныйТекст = { ru: '', kk: '' };

/** Слова аята по разбиению Tanzil (по одному пробелу). Строку не меняет: words.join(' ') === текст. */
export function словаАята(текст: string): string[] {
  return текст.split(' ');
}

// ───────────────────────── course.json ─────────────────────────

function проверитьПункт(з: unknown): ПунктКурса | null {
  const п = объект(з);
  if (!п) return null;
  if (!целое(п.номер, 0, 999) || !строка(п.метка) || !локализованный(п.название)) return null;
  if (!(ВИДЫ_ПУНКТОВ as readonly unknown[]).includes(п.вид)) return null;
  return {
    номер: п.номер,
    id: строка(п.id) ? п.id : String(п.номер),
    уровень: целое(п.уровень, 0, 99) ? п.уровень : 0,
    метка: п.метка,
    вид: п.вид as ПунктКурса['вид'],
    название: п.название,
    цель: локализованный(п.цель) ? п.цель : ПУСТО,
    очередь: (ОЧЕРЕДИ as readonly unknown[]).includes(п.очередь) ? (п.очередь as ОчередьВыпуска) : 'позже',
    статус: статус(п.статус),
    доступен: п.доступен === true && строка(п.файл),
    файл: строка(п.файл) ? п.файл : null,
    ...(локализованный(п.примечание) ? { примечание: п.примечание } : {}),
  };
}

export function проверитьКурс(сырые: unknown): КартаКурсаДанные | null {
  const к = объект(сырые);
  if (!к || !Array.isArray(к.уровни)) return null;
  const уровни: УровеньКурса[] = [];
  for (const у of к.уровни) {
    const о = объект(у);
    if (!о || !целое(о.уровень, 0, 99) || !локализованный(о.название) || !Array.isArray(о.пункты)) continue;
    const пункты = о.пункты.map(проверитьПункт).filter((п): п is ПунктКурса => п != null);
    if (пункты.length > 0) уровни.push({ уровень: о.уровень, название: о.название, пункты });
  }
  if (уровни.length === 0) return null;
  уровни.sort((а, б) => а.уровень - б.уровень);
  const утв = объект(к.утверждено);
  return {
    версия: строка(к.версия) ? к.версия : '—',
    статус: статус(к.статус),
    утверждено: { кем: строка(утв?.кем) ? утв.кем : null, дата: строка(утв?.дата) ? утв.дата : null },
    источник: строка(к.источник) ? к.источник : '',
    уровни,
  };
}

// ───────────────────────── lesson0.json ─────────────────────────

function проверитьКуда(з: unknown): КудаВести | null {
  const к = объект(з);
  if (!к) return null;
  if (к.экран === 'урок' && целое(к.номер, 0, 999)) return { экран: 'урок', номер: к.номер };
  if (к.экран === 'картаКурса') return { экран: 'картаКурса' };
  if (к.экран === 'какОбъясняем') return { экран: 'какОбъясняем' };
  return null;
}

export function проверитьУрок0(сырые: unknown): Урок0Данные | null {
  const у = объект(сырые);
  if (!у) return null;
  const пр = объект(у.предупреждениеИИ);
  // ИИ-предупреждение QML обязательно: без него урок 0 не показываем.
  if (!пр || !строка(пр.ar) || !строка(пр.ru) || !строка(пр.kk)) return null;
  const задания = Array.isArray(у.задания) ? у.задания.map(проверитьЗадание).filter((з): з is Задание => з != null) : [];
  const м = объект(у.маршрут);
  const варианты = Array.isArray(м?.варианты)
    ? (м.варианты as unknown[]).flatMap((в) => {
        const о = объект(в);
        const куда = проверитьКуда(о?.куда);
        if (!о || !строка(о.id) || !локализованный(о.текст) || !куда) return [];
        return [{ id: о.id, текст: о.текст, куда, ...(локализованный(о.примечание) ? { примечание: о.примечание } : {}) }];
      })
    : [];
  const н = объект(у.намерение);
  const вариантыНамерения = Array.isArray(н?.варианты)
    ? (н.варианты as unknown[]).flatMap((в) => {
        const о = объект(в);
        return о && строка(о.id) && локализованный(о.текст) ? [{ id: о.id, текст: о.текст }] : [];
      })
    : [];
  const утв = объект(у.утверждено);
  return {
    номер: 0,
    id: 'L00',
    уровень: 0,
    название: локализованный(у.название) ? у.название : { ru: 'Вход', kk: 'Кіріспе' },
    цель: локализованный(у.цель) ? у.цель : ПУСТО,
    предупреждениеИИ: {
      id: строка(пр.id) ? пр.id : 'qml-notice',
      версия: строка(пр.версия) ? пр.версия : '',
      ar: пр.ar,
      ru: пр.ru,
      kk: пр.kk,
      источник: строка(пр.источник) ? пр.источник : '',
      ссылка: строка(пр.ссылка) ? пр.ссылка : '',
      прочитано: строка(пр.прочитано) ? пр.прочитано : '',
    },
    маршрут: { вопрос: локализованный(м?.вопрос) ? (м.вопрос as ЛокализованныйТекст) : ПУСТО, варианты },
    намерение: {
      вопрос: локализованный(н?.вопрос) ? (н.вопрос as ЛокализованныйТекст) : ПУСТО,
      варианты: вариантыНамерения,
      сохранять: false,
    },
    задания,
    версия: строка(у.версия) ? у.версия : '—',
    статус: статус(у.статус),
    утверждено: { кем: строка(утв?.кем) ? утв.кем : null, дата: строка(утв?.дата) ? утв.дата : null },
  };
}

// ───────────────────────── fatiha-demo.json ─────────────────────────

const УРОВНИ_ПОКАЗА: readonly ПримерОбъяснения['уровень'][] = ['Ошибка', 'Проверьте себя', 'Сравните'];

function проверитьПример(з: unknown, аяты: ФрагментКорана[]): ПримерОбъяснения | null {
  const п = объект(з);
  if (!п || !строка(п.id) || !целое(п.сура, 1, 114) || !целое(п.аят, 1, 286) || !целое(п.слово, 1, 1000)) return null;
  if (!строка(п.текстСлова) || !строка(п.код)) return null;
  if (!(УРОВНИ_ПОКАЗА as readonly unknown[]).includes(п.уровень)) return null;
  if (!локализованный(п.названиеУровня) || !локализованный(п.правило) || !локализованный(п.чтоСделать) || !локализованный(п.текст)) return null;
  // Слово примера — дословно то же, что в проверенном аяте под этим номером (подсветка по индексу).
  const аят = аяты.find((а) => а.сура === п.сура && а.аят === п.аят);
  if (!аят || словаАята(аят.текст)[(п.слово as number) - 1] !== п.текстСлова) return null;
  return {
    id: п.id,
    сура: п.сура,
    аят: п.аят,
    слово: п.слово,
    текстСлова: п.текстСлова,
    буква: строка(п.буква) ? п.буква : null,
    код: п.код,
    уровень: п.уровень as ПримерОбъяснения['уровень'],
    названиеУровня: п.названиеУровня,
    услышано: строка(п.услышано) ? п.услышано : null,
    нужно: строка(п.нужно) ? п.нужно : null,
    правило: п.правило,
    чтоСделать: п.чтоСделать,
    лестница: Array.isArray(п.лестница) ? п.лестница.filter(строка) : [],
    текст: п.текст,
    ...(локализованный(п.примечание) ? { примечание: п.примечание } : {}),
  };
}

export function проверитьДемо(сырые: unknown): ДемоФатихи | null {
  const д = объект(сырые);
  if (!д || !Array.isArray(д.аяты) || !Array.isArray(д.примеры)) return null;
  const аяты = д.аяты.map(проверитьФрагментКорана).filter((а): а is ФрагментКорана => а != null);
  if (аяты.length === 0) return null;
  аяты.sort((а, б) => а.сура - б.сура || а.аят - б.аят);
  const примеры = д.примеры.map((п) => проверитьПример(п, аяты)).filter((п): п is ПримерОбъяснения => п != null);
  const утв = объект(д.утверждено);
  const пометкаПоУмолчанию = {
    ru: 'Пример, не проверка вашего чтения.',
    kk: 'Бұл — мысал, сіздің оқуыңызды тексеру емес.',
  };
  return {
    id: строка(д.id) ? д.id : 'fatiha-demo',
    название: локализованный(д.название) ? д.название : ПУСТО,
    пометка: локализованный(д.пометка) ? д.пометка : пометкаПоУмолчанию,
    пометкаИИ: локализованный(д.пометкаИИ) ? д.пометкаИИ : ПУСТО,
    пометкаУровней: локализованный(д.пометкаУровней) ? д.пометкаУровней : ПУСТО,
    аяты,
    примеры,
    версия: строка(д.версия) ? д.версия : '—',
    статус: статус(д.статус),
    утверждено: { кем: строка(утв?.кем) ? утв.кем : null, дата: строка(утв?.дата) ? утв.дата : null },
  };
}

