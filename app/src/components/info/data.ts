/**
 * Данные информационных экранов из /content: карта курса, урок 0, пример объяснения на аль-Фатихе,
 * источники контента — с проверкой формы. То, что проверку не прошло, НЕ показывается.
 *
 * Контракт:
 *   useДанные('course' | 'lesson0' | 'fatiha-demo' | 'sources')
 *     → { состояние: 'загрузка' } | { состояние: 'нет' } | { состояние: 'есть'; данные }
 *   загрузитьДанные(имя) → Promise<данные | null> — то же без React (кэш на время страницы).
 *   Чистые проверки (для тестов): проверитьКурс, проверитьУрок0, проверитьДемо, проверитьИсточники,
 *   словаАята(текст) — разбиение текста Tanzil по пробелам (сам текст не меняется).
 *
 * Файлы грузятся лениво (require.context, режим lazy): каждый — свой чанк с хэшем в имени,
 * только когда экран его попросил. Внешних запросов нет — всё в бандле.
 *
 * Коран (CLAUDE.md, правило 1): аят показывается, только если источник — tanzil-uthmani-1.1 и
 * sha256 текста совпадает (проверитьФрагментКорана движка урока). Пример объяснения показывается,
 * только если слово по номеру в аяте дословно равно «текстСлова» — подсветка идёт строго по индексу.
 * Решение владельца 18.11.2026: первая версия — честный прототип v0 на batr.kz/aiustaz.
 */
