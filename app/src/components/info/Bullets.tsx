/**
 * Список с указателями (короткие пункты «что есть / чего нет»).
 *
 * Контракт: <Пункты пункты={(string | { текст, значок })[]} вид? значок? testID? />
 * - пункт — строка (может содержать арабские вставки) или { текст, значок } со своим значком;
 * - значок (для всех строк без своего): по умолчанию — нукта (ромб цвета акцент, дизайн-система §8:
 *   указатель места); имя значка из набора ('галочка', 'замок'…) — линейный значок; другой короткий
 *   символ ('✓') — как текст.
 */
import { View } from 'react-native';
import { useТема } from '../../theme';
import { Значок, этоЗначок, type ИмяЗначка } from '../Icon';
import { Текст, type ВидТекста } from '../Text';
import { СмешанныйТекст } from './MixedText';
import { Нукта } from './Path';

export type Пункт = string | { текст: string; значок: ИмяЗначка };

export function Пункты({ пункты, вид = 'обычный', значок, testID }: { пункты: Пункт[]; вид?: ВидТекста; значок?: string; testID?: string }) {
  const { отступ, цвет } = useТема();
  const мелкий = вид === 'мелкий' || вид === 'метка';
  // Высота первой строки текста — чтобы указатель стоял по её середине.
  const строка = мелкий ? 18 : 24;
  const указатель = (свой?: string) => {
    const з = свой ?? значок;
    if (з == null || з === '•') return <Нукта размер={мелкий ? 6 : 7} />;
    if (этоЗначок(з)) return <Значок имя={з} размер={мелкий ? 16 : 20} цвет={цвет.акцент} толщина={2} />;
    return (
      <Текст вид={вид} цвет={цвет.акцент}>
        {з}
      </Текст>
    );
  };
  return (
    <View style={{ gap: отступ.s }} testID={testID}>
      {пункты.map((пункт, i) => {
        const текст = typeof пункт === 'string' ? пункт : пункт.текст;
        const свой = typeof пункт === 'string' ? undefined : пункт.значок;
        return (
          <View key={i} style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start' }}>
            <View style={{ width: 20, minHeight: строка, alignItems: 'center', justifyContent: 'center' }} aria-hidden>
              {указатель(свой)}
            </View>
            <СмешанныйТекст вид={вид} стиль={{ flex: 1 }}>
              {текст}
            </СмешанныйТекст>
          </View>
        );
      })}
    </View>
  );
}
