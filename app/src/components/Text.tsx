/**
 * Текст интерфейса (не арабский — для него АрабскийТекст).
 *
 * Контракт: <Текст вид? цвет? табличные? стиль? …пропсы Text>…</Текст>
 * - вид — шкала дизайн-системы (theme/tokens.ts ТИПОГРАФИКА):
 *     обычный 16/24 · второй 16/24 (текстВторой) · заголовок 24/30 600 · подзаголовок 18/24 600 ·
 *     мелкий 13/18 (текстВторой) · метка 13/18 600 · кнопка 17/22 600 ·
 *     время 22/28 600 и времяКрупное 44/50 600 (табличные цифры — время намаза).
 * - цвет — переопределить цвет (только из темы: цвет.акцент, цвет.золотоТекст …).
 * - табличные — цифры одинаковой ширины (у «время*» включены всегда).
 * Шрифт — Inter (подмножество, OFL) с системным запасным; на поверхности «герой» цвета светлые сами.
 * Остальные свойства — как у Text из react-native (accessibilityRole, testID, numberOfLines…).
 * Веб: направление абзаца — всегда ltr (интерфейс ru/kk). Без этого react-native-web ставит dir="auto",
 * и строка, которая начинается с арабской буквы («ث және ص әріптері»), раскладывается справа налево.
 * Арабские вставки внутри — <АрабскийТекст встроенный> (span dir="rtl", изолирован).
 */
import type { ReactNode } from 'react';
import { Platform, Text, type StyleProp, type TextProps, type TextStyle } from 'react-native';
import { ТИПОГРАФИКА, ШРИФТ_ИНТЕРФЕЙСА, useТема, type ВидТипографики } from '../theme';

export type ВидТекста = ВидТипографики;

export type СвойстваТекста = Omit<TextProps, 'style'> & {
  вид?: ВидТекста;
  цвет?: string;
  табличные?: boolean;
  стиль?: StyleProp<TextStyle>;
  children?: ReactNode;
};

const ВЕСА = { обычное: '400', полужирное: '600' } as const;

/** Стиль текста по виду шкалы — для своих <Text> (например, в кнопке). Цвет не задаёт. */
export function стильТекста(вид: ВидТекста, табличные = false): TextStyle {
  const ш = ТИПОГРАФИКА[вид];
  return {
    fontFamily: ШРИФТ_ИНТЕРФЕЙСА,
    fontSize: ш.кегль,
    lineHeight: ш.строка,
    fontWeight: ВЕСА[ш.начертание],
    ...(табличные || ('цифрыТабличные' in ш && ш.цифрыТабличные) ? { fontVariant: ['tabular-nums'] as TextStyle['fontVariant'] } : null),
  };
}

export function Текст({ вид = 'обычный', цвет, табличные = false, стиль, children, ...остальное }: СвойстваТекста) {
  const тема = useТема();
  const цветВида = вид === 'второй' || вид === 'мелкий' ? тема.цвет.текстВторой : тема.цвет.текст;
  return (
    <Text
      {...(Platform.OS === 'web' ? ({ dir: 'ltr' } as object) : null)}
      {...остальное}
      accessibilityRole={остальное.accessibilityRole ?? (вид === 'заголовок' ? 'header' : undefined)}
      style={[стильТекста(вид, табличные), { color: цвет ?? цветВида }, стиль]}
    >
      {children}
    </Text>
  );
}
