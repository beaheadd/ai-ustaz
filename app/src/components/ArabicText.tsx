/**
 * Арабский текст: шрифт Amiri Quran (OFL-1.1), справа налево, крупно.
 *
 * Контракт:
 *   <АрабскийТекст размер="малый|средний|крупный|огромный" выравнивание="center|right"
 *                  встроенный? цвет? выбираемый? testID? коран?>
 *     {строка}
 *   </АрабскийТекст>
 * - Блочный (по умолчанию): отдельный абзац RTL внутри LTR-интерфейса.
 * - встроенный: внутри <Текст> русской/казахской строки (на вебе — <span dir="rtl" lang="ar">,
 *   браузер изолирует направление; нативно — writingDirection).
 * - подсветка (учебный текст, 20.11.2026) — места подсказок проверки голосом (speech/highlight.ts): слово с местом —
 *   цвет подсказки («Проверьте себя» — янтарь, «Подсказка» — акцент; не красный, правило 7) + подпись рядом, testID
 *   подсветка-места; строка режется на куски без изменений (склейка = исходная строка). Подпись — рядом (common.tsx).
 * - Строку выводит как есть: ничего не нормализует и не меняет. Текст Корана передавать
 *   только из ФрагментКорана (content/types.ts) — дословно из Tanzil.
 * - коран (владелец 28.11.2026: выбор шрифта Корана) — строка — текст Корана (ФрагментКорана): шрифт — выбор человека
 *   (components/quran/QuranFont.tsx; «Мединский мусхаф» — с подстройкой показа, исходный текст — в data-o). Без него —
 *   Amiri Quran (буквы, слоги, учебные слова, хадисы, дуа).
 * - Пока Amiri Quran не загружен (useАрабскийШрифтГотов), текст прозрачен и держит место: Коран и буквы не
 *   мелькают системным шрифтом (экраны больше не ждут шрифтов — App.tsx).
 */
import { Platform, Text, type StyleProp, type TextStyle } from 'react-native';
import { разметкаПодсветки, type МестоПодсветки } from '../speech/highlight';
import { useТема } from '../theme';
import { кусокКорана, useШрифтКорана } from './quran/QuranFont';

export type РазмерАрабского = 'малый' | 'средний' | 'крупный' | 'огромный';

const РАЗМЕРЫ: Record<РазмерАрабского, number> = { малый: 24, средний: 32, крупный: 46, огромный: 68 };
/** Amiri Quran высокий: огласовки сверху и снизу — межстрочный интервал щедрый. */
const МЕЖСТРОЧНЫЙ = 1.9;

export type СвойстваАрабского = {
  children: string;
  размер?: РазмерАрабского;
  выравнивание?: 'center' | 'right';
  встроенный?: boolean;
  цвет?: string;
  выбираемый?: boolean;
  testID?: string;
  стиль?: StyleProp<TextStyle>;
  подсветка?: readonly МестоПодсветки[];
  /** Строка — текст Корана: шрифт Корана по выбору человека. */
  коран?: boolean;
};

/** Атрибуты HTML для react-native-web (Text их поддерживает, в типах RN их нет). */
const ВЕБ_АТРИБУТЫ = (Platform.OS === 'web' ? { lang: 'ar', dir: 'rtl' } : {}) as object;

export function АрабскийТекст({
  children,
  размер = 'средний',
  выравнивание = 'center',
  встроенный = false,
  цвет,
  выбираемый = true,
  testID,
  стиль,
  подсветка,
  коран = false,
}: СвойстваАрабского) {
  const тема = useТема();
  const шрифт = useШрифтКорана(коран);
  const готов = шрифт.готов;
  const кегль = РАЗМЕРЫ[размер];
  const базовый: TextStyle = {
    fontFamily: шрифт.семейство,
    fontSize: кегль,
    color: цвет ?? тема.цвет.арабский,
    writingDirection: 'rtl',
  };
  const блочный: TextStyle = встроенный ? {} : { lineHeight: Math.round(кегль * МЕЖСТРОЧНЫЙ), textAlign: выравнивание };
  return (
    <Text
      {...ВЕБ_АТРИБУТЫ}
      accessibilityLanguage="ar"
      selectable={выбираемый}
      testID={testID}
      style={[базовый, блочный, стиль, готов ? null : { opacity: 0 }]}
    >
      {подсветка && подсветка.length > 0
        ? разметкаПодсветки(children, подсветка).map((к, i) =>
            к.уровень ? (
              <Text
                key={i}
                testID="подсветка-места"
                style={{
                  // Фон у Amiri Quran — во всю высоту шрифта (≈ 2,5 кегля), полоса через карточку; подчёркивание уходит
                  // под огласовки и не видно. Поэтому — цвет подсказки, а не только цветом место называет подпись под
                  // текстом (<ПодписиПодсветки>: «Выделено: второй слог «إِ»»).
                  color: к.уровень === 'подсказка' ? тема.цвет.акцент : тема.цвет.внимание,
                }}
              >
                {кусокКорана(шрифт, к.текст)}
              </Text>
            ) : (
              кусокКорана(шрифт, к.текст, i)
            ),
          )
        : кусокКорана(шрифт, children)}
    </Text>
  );
}
