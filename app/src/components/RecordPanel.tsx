/**
 * Панель записи голоса для заданий «запись»/«лестница»: пояснение о приватности
 * (один раз), кнопка «Записать/Стоп», индикатор громкости, «Послушать себя», «Удалить».
 *
 * Контракт: <ПанельЗаписи максДлительностьМс? testID? приЗаписи? проверка? запись? доп? строкаИнфо? />
 *   приЗаписи(длительностьМс) — вызывается, когда запись готова (например, чтобы открыть «Далее»).
 *   проверка — { эталон, текстПоказа, виды?, словаПоказа?, приИтоге? } (speech/check.ts, эталонЗадания; для аята —
 *     quran-check/index.ts, проверкаЧасти): под готовой записью кнопка «Проверить» и мягкий итог (<ПроверкаГолосом>).
 *     Только если проверкаГолосомВключена() — свой домен и сборка с флагом; на batr.kz кнопки нет, панель как раньше.
 *   Для чтения аята (19.11.2026, <ПанельЧтенияАята>), все необязательны — уроки работают как раньше:
 *     запись — внешний useЗаписьГолоса(): экран сам останавливает чтение кари, когда идёт запись или «Послушать себя»;
 *     доп — узел под кнопками записи и над «Проверить» («Сравнить с кари»);
 *     строкаИнфо — своя строка внизу вместо «Без оценки…» и «Голос кари…» (null — без строки).
 * Вердикта нет: после записи — «Записали! Послушайте себя.»; проверка — только «Проверьте себя»/«Подсказка».
 * Голоса кари нет — честная строка «появится после записи эталона».
 * Запись удаляется при размонтировании панели (уход с упражнения).
 * Клавиатура и диктор (ревью 19.11.2026): после «Записать» фокус — на «Стоп», после остановки — на «Послушать себя»
 * (кнопка, на которой стоял фокус, исчезает — фокус не теряется на body); «Запись идёт» объявляется один раз
 * (role=status), таймер секунд — не объявляется.
 *
 * Вид (дизайн-система 19.11.2026; docs/дизайн/02-образ-устаза.md §5): слева — эмблема AI Ustaz (фонарь)
 * в плитке с решёткой машрабии. Состояние эмблемы: «слушаю» — ТОЛЬКО пока идёт запись (свет «дышит»
 * 2,4 с; при «уменьшить движение» — ровно, это делает <ЭмблемаУстаза>), «молчу» — нет доступа к микрофону,
 * иначе «покой». Без звуков и вибрации. Справа — строка состояния; ниже — кнопки со значками набора.
 * testID: панель-записи, запись-идёт, индикатор-громкости, запись-готово, запись-ошибка, запись-начать,
 *         запись-стоп, запись-слушать, запись-удалить, запись-включить, панель-записи-эмблема, запись-инфо.
 */
