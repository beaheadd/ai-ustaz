const ТЕКСТ_ОШИБКИ: Record<ОшибкаЗаписи, КлючСтроки> = {
  'нет-доступа': 'запись.ошибка.нет-доступа',
  'нет-микрофона': 'запись.ошибка.нет-микрофона',
  'не-поддерживается': 'запись.ошибка.не-поддерживается',
  небезопасно: 'запись.ошибка.небезопасно',
  занят: 'запись.ошибка.занят',
  неизвестно: 'запись.ошибка.неизвестно',
};

const СЛОВАРЬ = создатьСловарь({
  ru: { нажмите: 'Нажмите «Записать» и прочитайте вслух — чтобы услышать себя.', идёт: 'Запись идёт' },
  kk: { нажмите: '«Жазу» түймесін басып, дауыстап оқыңыз — өзіңізді есту үшін.', идёт: 'Жазу жүріп жатыр' },
});

/** Веб: перевести фокус на кнопку панели, если он был на исчезнувшей кнопке (на body) или внутри панели. */
function фокусНа(панель: string, кнопка: string) {
  if (Platform.OS !== 'web' || typeof document === 'undefined') return;
  setTimeout(() => {
    const корень = document.querySelector(`[data-testid="${панель}"]`);
    const активный = document.activeElement;
    if (активный && активный !== document.body && !корень?.contains(активный)) return; // человек ушёл фокусом в другое место
    корень?.querySelector<HTMLElement>(`[data-testid="${кнопка}"]`)?.focus({ preventScroll: false });
  }, 0);
}

export type СвойстваПанелиЗаписи = {
  максДлительностьМс?: number;
  приЗаписи?: (длительностьМс: number) => void;
  /** Эталон для проверки голосом (если включена): учебный текст или ссылка на аят + текст на экране. */
  проверка?: {
    эталон: ЭталонПроверки;
    текстПоказа: string;
    виды?: readonly string[];
    словаПоказа?: readonly string[];
    приИтоге?: (итог: ИтогПроверки | null) => void;
  };
  /** Внешняя запись (useЗаписьГолоса) — если экрану нужно знать её состояние; иначе панель создаёт свою. */
  запись?: УправлениеЗаписью;
  доп?: ReactNode;
  строкаИнфо?: string | null;
  testID?: string;
};

/** Эмблема в плитке с решёткой машрабии (узор только вокруг эмблемы — не под текстом). */
function ПлиткаЭмблемы({ состояние }: { состояние: СостояниеЭмблемы }) {
  const { цвет, радиус } = useТема();
  return (
    <View
      testID="панель-записи-эмблема"
      style={{
        width: 64,
        height: 64,
        borderRadius: радиус.l,
        backgroundColor: цвет.поверхностьАкцент,
        alignItems: 'center',
        justifyContent: 'center',
        overflow: 'hidden',
      }}
    >
      <Орнамент вид="решётка" прозрачность={0.06} />
      <ЭмблемаУстаза размер={50} состояние={состояние} вариант="полный" />
    </View>
  );
}

export function ПанельЗаписи(свойства: СвойстваПанелиЗаписи) {
  return свойства.запись ? <ВидПанелиЗаписи {...свойства} з={свойства.запись} /> : <ПанельЗаписиСоСвоейЗаписью {...свойства} />;
}

function ПанельЗаписиСоСвоейЗаписью(свойства: СвойстваПанелиЗаписи) {
  const з = useЗаписьГолоса({ максДлительностьМс: свойства.максДлительностьМс });
  return <ВидПанелиЗаписи {...свойства} з={з} />;
}

function ВидПанелиЗаписи({ приЗаписи, проверка, доп, строкаИнфо, testID = 'панель-записи', з }: СвойстваПанелиЗаписи & { з: УправлениеЗаписью }) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const { прогресс, изменить } = useПрогресс();
  const [режим, установитьРежим] = useState<'обычный' | 'пояснение' | 'без-записи'>('обычный');
  const [проверкаВключена] = useState(проверкаГолосомВключена);
  const { состояние, ошибка, длительностьМс, естьЗапись } = з.снимок;

  const приЗаписиСсылка = useRef(приЗаписи);
  приЗаписиСсылка.current = приЗаписи;
  useEffect(() => {
    if (состояние === 'записано') приЗаписиСсылка.current?.(длительностьМс);
    // длительность намеренно не в зависимостях: сообщаем один раз на каждую готовую запись
  }, [состояние]);

  const былоСостояние = useRef(состояние);
  useEffect(() => {
    const было = былоСостояние.current;
    былоСостояние.current = состояние;
    if (состояние === 'запись' && было !== 'запись') фокусНа(testID, 'запись-стоп');
    else if (было === 'запись' && состояние === 'записано') фокусНа(testID, 'запись-слушать');
  }, [состояние, testID]);

  function нажатьЗаписать() {
    if (!прогресс.пояснениеМикрофонаПоказано) {
      установитьРежим('пояснение');
      return;
    }
    void з.начать();
  }

  if (режим === 'пояснение') {
    return (
      <ПояснениеМикрофона
        приСогласии={() => {
          изменить((п) => ({ ...п, пояснениеМикрофонаПоказано: true }));
          установитьРежим('обычный');
          void з.начать();
        }}
        приОтказе={() => установитьРежим('без-записи')}
      />
    );
  }

  if (режим === 'без-записи') {
    return (
      <Карточка testID={testID}>
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
          <ПлиткаЭмблемы состояние="молчу" />
          <Текст вид="второй" стиль={{ flex: 1 }}>
            {t('запись.безОценки')}
          </Текст>
        </View>
        <Кнопка надпись={t('запись.включить')} значок="микрофон" вид="вторичная" приНажатии={() => установитьРежим('пояснение')} testID="запись-включить" />
      </Карточка>
    );
  }

  const идёт = состояние === 'запись';
  const ждём = состояние === 'запрос';
  const играет = состояние === 'воспроизведение';
  const секунд = Math.floor(длительностьМс / 1000);
  const эмблема: СостояниеЭмблемы = идёт ? 'слушаю' : ошибка ? 'молчу' : 'покой';

  return (
    <Карточка testID={testID}>
      {/* Один раз для диктора: «Запись идёт» (регион есть всегда; таймер секунд не объявляется). */}
      <Текст
        accessibilityLiveRegion="polite"
        {...(Platform.OS === 'web' ? ({ role: 'status' } as object) : null)}
        стиль={{ position: 'absolute', width: 1, height: 1, overflow: 'hidden', opacity: 0 }}
        testID="запись-статус"
      >
        {идёт ? т('идёт') : ''}
      </Текст>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m, minHeight: 64 }}>
        <ПлиткаЭмблемы состояние={эмблема} />
        <View style={{ flex: 1, gap: отступ.s }}>
          {идёт ? (
            <>
              <Текст стиль={{ fontWeight: '600' }} табличные testID="запись-идёт">
                {t('запись.идёт', { секунд })}
              </Текст>

              <View
                accessibilityRole="progressbar"
                accessibilityLabel={t('запись.уровень')}
                accessibilityValue={{ min: 0, max: 100, now: Math.round(з.уровень * 100) }}
                style={{ height: 8, borderRadius: радиус.круг, backgroundColor: цвет.граница, overflow: 'hidden' }}
              >
                <View
                  testID="индикатор-громкости"
                  style={{ width: `${Math.round(з.уровень * 100)}%`, height: '100%', borderRadius: радиус.круг, backgroundColor: цвет.акцент }}
                />
              </View>
            </>
          ) : ошибка ? (
            <Текст цвет={цвет.внимание} testID="запись-ошибка" accessibilityLiveRegion="polite">
              {t(ТЕКСТ_ОШИБКИ[ошибка])}
            </Текст>
          ) : ждём ? (
            <Текст вид="второй">{t('запись.запрос')}</Текст>
          ) : естьЗапись ? (
            <Текст вид="подзаголовок" testID="запись-готово" accessibilityLiveRegion="polite">
              {t('запись.готово')}
            </Текст>
          ) : (
            <Текст вид="второй">{т('нажмите')}</Текст>
          )}
        </View>
      </View>

      <View style={{ gap: отступ.s, marginTop: отступ.xs }}>
        {идёт ? (
          <Кнопка надпись={t('запись.остановить')} значок="стоп" крупная приНажатии={з.остановить} testID="запись-стоп" />
        ) : естьЗапись ? (
          <>
            <Кнопка
              надпись={играет ? t('запись.остановитьВоспроизведение') : t('запись.слушать')}
              значок={играет ? 'стоп' : 'играть'}
              приНажатии={играет ? з.остановитьВоспроизведение : () => void з.воспроизвести()}
              testID="запись-слушать"
            />
            <Кнопка
              надпись={t('запись.ещё')}
              значок="повтор"
              вид="вторичная"
              отключена={ждём || играет}
              приНажатии={нажатьЗаписать}
              testID="запись-начать"
            />
            <Кнопка надпись={t('запись.удалить')} значок="удалить" вид="тихая" приНажатии={з.удалить} testID="запись-удалить" />
          </>
        ) : (
          <Кнопка
            надпись={t('запись.начать')}
            значок="микрофон"
            крупная
            отключена={ждём || играет}
            приНажатии={нажатьЗаписать}
            testID="запись-начать"
          />
        )}
      </View>

      {доп}

      {проверка ? (
        <ПроверкаГолосом
          эталон={проверка.эталон}
          текстПоказа={проверка.текстПоказа}
          виды={проверка.виды}
          словаПоказа={проверка.словаПоказа}
          приИтоге={проверка.приИтоге}
          естьЗапись={естьЗапись}
          заняты={идёт || ждём}
          получитьЗапись={з.получитьЗапись}
        />
      ) : null}

      {строкаИнфо === null ? null : (
        <СтрокаСоЗначком
          значок="инфо"
          вид="мелкий"
          testID="запись-инфо"
          текст={строкаИнфо ?? (проверка && проверкаВключена ? '' : t('запись.безОценки') + '\n') + t('запись.голосКари')}
        />
      )}
    </Карточка>
  );
}
