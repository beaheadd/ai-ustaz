/**
 * «Перевод на ваш язык готовится» — строка над содержимым, у которого нет перевода на язык интерфейса (ar, tr, id, ur:
 * владелец 28.11.2026). Уроки, «Учимся намазу», правила таджвида и описания махраджей религиозного содержания не
 * переводим машиной: показываем английский (или русский) текст и эту строку на языке человека.
 *
 * Контракт: <ПереводГотовится показать? testID? /> — по умолчанию показывается только для ar, tr, id, ur
 * (показать = false — не показывать; true — показать всегда, например когда своего поля нет и у старого языка).
 */
import { useПеревод, этоНовый } from '../i18n';
import { Текст } from './Text';

export function ПереводГотовится({ показать, testID = 'перевод-готовится' }: { показать?: boolean; testID?: string }) {
  const { t, язык } = useПеревод();
  if (!(показать ?? этоНовый(язык))) return null;
  return (
    <Текст вид="мелкий" testID={testID}>
      {t('перевод.готовится')}
    </Текст>
  );
}
