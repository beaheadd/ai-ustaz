/**
 * ВыборГорода — место для времени намаза и киблы: поиск по списку (kk/ru/латиница), крупные города сразу,
 * все 168 мест по областям, «Определить по геолокации» с пояснением о приватности.
 *
 * Контракт:
 *   <ВыборГорода приВыборе?(место) testID? />
 * - Выбор сохраняется сам (prayer/store.ts → aiustaz:prayer-place.v1, только на устройстве), потом приВыборе.
 * - Геолокация: сначала пояснение «координаты остаются на телефоне» (кнопки «Разрешить» / «Выбрать вручную»),
 *   только потом navigator.geolocation (низкая точность, кэш до 10 мин, таймаут 10 с). Координаты живут в
 *   памяти экрана; сохраняется выбранное: ближайший город или — по кнопке — своя точка, округлённая до ≈ 1 км.
 *   Дальше 30 км от города — предупреждение «время может отличаться на 1–2 мин». Вне РК — не считаем.
 *   Отказ — без повторных просьб; выбранный город остаётся.
 * - Нет связи и список не загрузился — «Нет связи — список мест не загрузился» и «Повторить»; геолокация тогда
 *   тоже честно говорит «нет связи», а не «вы не в Казахстане».
 * - Поле поиска в фокусе — рамка цветом фокуса толщиной 2 (WCAG 2.4.7; своя обводка браузера снята).
 * testID: выбор-города, город-текущий, город-гео, город-гео-пояснение, город-гео-разрешить, город-гео-вручную,
 *   город-гео-ищем, город-гео-итог, город-гео-выбрать, город-гео-точка, город-гео-далеко, город-гео-вне-рк,
 *   город-гео-ошибка, город-поиск, город-<id>, город-крупные, город-все, город-ничего, город-нет-связи,
 *   город-повторить.
 * Названия kk — черновик для редактора-носителя. Список — GeoNames (CC BY 4.0), см. «Лицензии».
 */
