type Гео =
  | { вид: 'покой' }
  | { вид: 'пояснение' }
  | { вид: 'ищем' }
  | { вид: 'итог'; точка: { широта: number; долгота: number }; ближайшее: { место: Место; км: number } }
  | { вид: 'ошибка'; причина: 'отказ' | 'неУдалось' | 'нетГео' | 'нетСписка' };

/** Пояснение показано в этом заходе — второй раз не спрашиваем «зачем». */
let пояснениеПоказано = false;

export type СвойстваВыбораГорода = { приВыборе?: (место: Место) => void; testID?: string };

export function ВыборГорода({ приВыборе, testID = 'выбор-города' }: СвойстваВыбораГорода) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const { место: текущее, выбрано, выбрать } = useМестоНамаза();
  const [места, установитьМеста] = useState<Место[] | null>(null);
  const [нетСвязи, установитьНетСвязи] = useState(false);
  const [попытка, установитьПопытку] = useState(0);
  const [запрос, установитьЗапрос] = useState('');
  const [вФокусе, установитьФокус] = useState(false);
  const [все, установитьВсе] = useState(false);
  const [гео, установитьГео] = useState<Гео>({ вид: 'покой' });
  const [мир, установитьМир] = useState<{ запрос: string; места: Место[] | null; нетСвязи: boolean }>({ запрос: '', места: null, нетСвязи: false });

  useEffect(() => {
    let живой = true;
    установитьНетСвязи(false);
    загрузитьМеста().then(
      (м) => живой && установитьМеста(м),
      () => живой && установитьНетСвязи(true),
    );
    return () => {
      живой = false;
    };
  }, [попытка]);

  // Связь вернулась — пробуем ещё раз сами.
  useEffect(() => {
    if (!нетСвязи || Platform.OS !== 'web' || typeof window === 'undefined') return;
    const снова = () => установитьПопытку((п) => п + 1);
    window.addEventListener('online', снова);
    return () => window.removeEventListener('online', снова);
  }, [нетСвязи]);

  const взять = (м: Место) => {
    void выбрать(м);
    приВыборе?.(м);
  };

  const найдено = useMemo(() => (места && запрос.trim() ? найтиМеста(места, запрос, язык, 15) : null), [места, запрос, язык]);
  const ключМира = свернуть(запрос);

  // Мир — с двух букв, через 250 мс после ввода; ответ на старый запрос не показываем.
  useEffect(() => {
    if (ключМира.length < 2) {
      установитьМир({ запрос: ключМира, места: [], нетСвязи: false });
      return;
    }
    let живой = true;
    установитьМир({ запрос: ключМира, места: null, нетСвязи: false });
    const таймер = setTimeout(() => {
      искатьВМире(ключМира, 20).then(
        (м) => живой && установитьМир({ запрос: ключМира, места: м, нетСвязи: false }),
        () => живой && установитьМир({ запрос: ключМира, места: [], нетСвязи: true }),
      );
    }, 250);
    return () => {
      живой = false;
      clearTimeout(таймер);
    };
  }, [ключМира, попытка]);
  const найденоВМире = мир.запрос === ключМира ? мир.места : null;
  // Крупные города — по странам (сначала страна выбранного места), внутри — столица, потом по алфавиту.
  const крупные = useMemo(() => {
    const порядок = (м: Место) => (КРУПНЫЕ.indexOf(м.тип) <= 1 ? 0 : 1);
    const группы = new Map<string, Место[]>();
    for (const м of места ?? []) if (КРУПНЫЕ.includes(м.тип)) группы.set(м.страна, [...(группы.get(м.страна) ?? []), м]);
    for (const список of группы.values()) список.sort((а, б) => порядок(а) - порядок(б) || а[язык].localeCompare(б[язык], язык));
    return [...группы.entries()].sort(([а], [б]) => (а === текущее.страна ? -1 : б === текущее.страна ? 1 : а.localeCompare(б)));
  }, [места, язык, текущее.страна]);

  const определить = () => {
    const гл = Platform.OS === 'web' ? globalThis.navigator?.geolocation : undefined;
    if (!гл || (Platform.OS === 'web' && globalThis.isSecureContext === false)) {
      установитьГео({ вид: 'ошибка', причина: 'нетГео' });
      return;
    }
    установитьГео({ вид: 'ищем' });
    гл.getCurrentPosition(
      async (п) => {
        const точка = { широта: п.coords.latitude, долгота: п.coords.longitude };
        const [список, вМире] = await Promise.all([
          места?.length ? Promise.resolve(места) : загрузитьМеста().catch(() => null),
          ближайшееВМире(точка).catch(() => null),
        ]);
        if (список && !места) установитьМеста(список);
        const свой = список?.length ? ближайшееМесто(список, точка) : null;
        const ближ = свой && (!вМире || свой.км <= вМире.км) ? свой : вМире;
        if (!ближ) {
          установитьГео({ вид: 'ошибка', причина: 'нетСписка' });
          return;
        }
        if (ближ.км <= 5) {
          установитьГео({ вид: 'покой' });
          взять(ближ.место);
        } else установитьГео({ вид: 'итог', точка, ближайшее: ближ });
      },
      (о) => установитьГео({ вид: 'ошибка', причина: о.code === 1 ? 'отказ' : 'неУдалось' }),
      // Кэш позиции — до 10 мин: в дороге старое место дало бы чужой город.
      { enableHighAccuracy: false, maximumAge: 600_000, timeout: 10_000 },
    );
  };

  const нажатьГео = () => {
    if (пояснениеПоказано) определить();
    else установитьГео({ вид: 'пояснение' });
  };

  const подписьМеста = (м: Место) => {
    const обл = м.область ? м.область[язык] : '';
    const вид = м.тип === 'районный центр' ? т('районный') : '';
    const uz = м.uz && м.uz !== м[язык] ? м.uz : '';
    const en = !uz && м.en && м.en !== м[язык] ? м.en : '';
    return [...new Set([uz || en, обл, вид, названиеСтраны(м.страна, язык)].filter(Boolean))].join(' · ');
  };

  const строка = (м: Место) => (
    <СтрокаСписка
      key={м.id}
      вид="плоская"
      заголовок={м[язык]}
      подпись={подписьМеста(м)}
      выбрана={текущее.вид === 'место' && текущее.id === м.id}
      приНажатии={() => взять(м)}
      testID={'город-' + м.id}
    />
  );

  // Все места: страна (сначала страна выбранного места) → область по алфавиту.
  const поОбластям = useMemo(() => {
    const группы = new Map<string, Место[]>();
    for (const м of места ?? []) {
      const к = м.страна + '\u0000' + (м.область ? м.область[язык] : '');
      группы.set(к, [...(группы.get(к) ?? []), м]);
    }
    const страна = (к: string) => к.split('\u0000')[0];
    return [...группы.entries()]
      .sort(([а], [б]) =>
        страна(а) === страна(б)
          ? а.localeCompare(б, язык)
          : страна(а) === текущее.страна
            ? -1
            : страна(б) === текущее.страна
              ? 1
              : страна(а).localeCompare(страна(б)),
      )
      .map(([к, список]) => [названиеСтраны(страна(к), язык) + ' · ' + к.split('\u0000')[1], список] as const);
  }, [места, язык, текущее.страна]);
  const выбратьПозицию = (точка: { широта: number; долгота: number }, ближайшее: { место: Место; км: number }) => {
    // Пояс своей точки — ближайшего города (база поясов места надёжнее телефона: Etc/GMT-5 для РК); город дальше
    // 100 км — пояс телефона (если телефон его знает).
    let пояс: string | undefined;
    if (ближайшее.км > 100) {
      try {
        пояс = Intl.DateTimeFormat().resolvedOptions().timeZone || undefined;
      } catch {
        пояс = undefined;
      }
    }
    взять(своёМесто(точка, ближайшее, пояс));
  };

  return (
    <View style={{ gap: отступ.l }} testID={testID}>
      <Текст вид="второй" testID="город-текущий">
        {выбрано ? т('текущий', { место: текущее[язык] }) : т('поУмолчанию', { место: текущее[язык] })}
        {текущее.вид === 'точка' && текущее.ближайшее ? ' (' + т('км', { км: текущее.ближайшее.км, город: текущее[язык].replace(/^≈ /, '') }) + ')' : ''}
      </Текст>

      {гео.вид === 'пояснение' ? (
        <Карточка вид="акцент" testID="город-гео-пояснение">
          <View style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start' }}>
            <Значок имя="замок" размер={22} цвет={цвет.акцент} />
            <Текст стиль={{ flex: 1 }}>{т('геоПояснение')}</Текст>
          </View>
          <Кнопка
            надпись={т('разрешить')}
            значок="геолокация"
            приНажатии={() => {
              пояснениеПоказано = true;
              определить();
            }}
            testID="город-гео-разрешить"
          />
          <Кнопка вид="тихая" надпись={т('вручную')} приНажатии={() => установитьГео({ вид: 'покой' })} testID="город-гео-вручную" />
        </Карточка>
      ) : (
        <Кнопка вид="вторичная" значок="геолокация" надпись={т('гео')} приНажатии={нажатьГео} отключена={гео.вид === 'ищем'} testID="город-гео" />
      )}

      {гео.вид === 'ищем' ? (
        <Текст вид="второй" testID="город-гео-ищем" accessibilityLiveRegion="polite">
          {т('ищем')}
        </Текст>
      ) : null}
      {гео.вид === 'итог' ? (
        <Карточка testID="город-гео-итог">
          <Текст accessibilityLiveRegion="polite">{т('ближайший', { город: гео.ближайшее.место[язык], км: Math.round(гео.ближайшее.км) })}</Текст>
          {гео.ближайшее.км > 30 ? (
            <Текст вид="второй" testID="город-гео-далеко">
              {т('далеко')}
            </Текст>
          ) : null}
          <Кнопка надпись={т('выбрать', { город: гео.ближайшее.место[язык] })} приНажатии={() => взять(гео.ближайшее.место)} testID="город-гео-выбрать" />
          <Кнопка
            вид="вторичная"
            надпись={т('точка')}
            значок="геолокация"
            приНажатии={() => выбратьПозицию(гео.точка, гео.ближайшее)}
            testID="город-гео-точка"
          />
          <Текст вид="мелкий">{т('точкаПояснение')}</Текст>
        </Карточка>
      ) : null}
      {гео.вид === 'ошибка' ? (
        <Текст вид="второй" testID="город-гео-ошибка" accessibilityLiveRegion="polite">
          {т(гео.причина)}
        </Текст>
      ) : null}

      <View
        style={{
          flexDirection: 'row',
          alignItems: 'center',
          gap: отступ.s,
          minHeight: 48,
          // Фокус: рамка 2 px цветом фокуса; отступ меньше на 1 px — поле не прыгает.
          paddingHorizontal: вФокусе ? отступ.m - 1 : отступ.m,
          borderRadius: радиус.m,
          borderWidth: вФокусе ? 2 : 1,
          borderColor: вФокусе ? цвет.фокус : цвет.границаЭлемента,
          backgroundColor: цвет.поверхность,
        }}
      >
        <Значок имя="поиск" размер={20} цвет={цвет.текстВторой} />
        <TextInput
          value={запрос}
          onChangeText={установитьЗапрос}
          onFocus={() => установитьФокус(true)}
          onBlur={() => установитьФокус(false)}
          placeholder={т('поиск')}
          placeholderTextColor={цвет.текстВторой}
          accessibilityLabel={т('поиск')}
          autoCorrect={false}
          autoCapitalize="words"
          inputMode="search"
          enterKeyHint="search"
          testID="город-поиск"
          style={{ flex: 1, minHeight: 46, fontFamily: ШРИФТ_ИНТЕРФЕЙСА, fontSize: 16, color: цвет.текст, ...(Platform.OS === 'web' ? ({ outlineStyle: 'none' } as object) : null) }}
        />
      </View>

      {!места && !нетСвязи ? <Текст вид="второй">{т('загрузка')}</Текст> : null}
      {!места && нетСвязи ? (
        <Карточка вид="песок" testID="город-нет-связи">
          <Текст цвет={цвет.песокТекст} accessibilityLiveRegion="polite">
            {т('нетСвязи')}
          </Текст>
          <Кнопка вид="вторичная" значок="повтор" надпись={т('повторить')} приНажатии={() => установитьПопытку((п) => п + 1)} testID="город-повторить" />
        </Карточка>
      ) : null}

      {запрос.trim() ? (
        <View style={{ gap: отступ.s }}>
          {найдено?.length ? <View>{найдено.map(строка)}</View> : null}
          {найденоВМире?.length ? (
            <View testID="город-мир">
              {найдено?.length ? (
                <Текст вид="метка" accessibilityRole="header">
                  {т('мир')}
                </Текст>
              ) : null}
              {найденоВМире.map(строка)}
            </View>
          ) : null}
          {ключМира.length >= 2 && найденоВМире === null ? (
            <Текст вид="второй" testID="город-мир-ищем" accessibilityLiveRegion="polite">
              {т('мирИщем')}
            </Текст>
          ) : null}
          {мир.нетСвязи && мир.запрос === ключМира ? (
            <Текст вид="второй" testID="город-мир-нет-связи">
              {т('мирНетСвязи')}
            </Текст>
          ) : null}
          {(найдено ?? []).length === 0 && найденоВМире !== null && найденоВМире.length === 0 && !мир.нетСвязи ? (
            <Текст вид="второй" testID="город-ничего">
              {т('ничего')}
            </Текст>
          ) : null}
        </View>
      ) : места ? (
        <View style={{ gap: отступ.s }}>
          {!все ? (
            <>
              <Текст вид="подзаголовок" accessibilityRole="header">
                {т('крупные')}
              </Текст>
              <View testID="город-крупные" style={{ gap: отступ.s }}>
                {крупные.map(([страна, список]) => (
                  <View key={страна} testID={'город-страна-' + страна}>
                    <Текст вид="метка" accessibilityRole="header">
                      {названиеСтраны(страна, язык)}
                    </Текст>
                    {список.map(строка)}
                  </View>
                ))}
              </View>
              <Текст вид="второй" testID="город-мир-подсказка">
                {т('мирПодсказка')}
              </Текст>
            </>
          ) : (
            поОбластям.map(([область, список]) => (
              <View key={область} style={{ gap: отступ.xs, marginBottom: отступ.m }}>
                <Текст вид="метка" accessibilityRole="header">
                  {область}
                </Текст>
                <View>{список.map(строка)}</View>
              </View>
            ))
          )}
          <Кнопка
            вид="тихая"
            надпись={все ? т('свернуть') : т('все', { число: места.length })}
            приНажатии={() => установитьВсе((в) => !в)}
            testID="город-все"
          />
        </View>
      ) : null}
    </View>
  );
}
