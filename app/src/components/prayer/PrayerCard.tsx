/** Высота ярлыка «следующий/сейчас» при обычном шрифте (12/16 + рамка); фактическую даёт замер. */
const ВЫСОТА_ЯРЛЫКА = 18;
/** Поля плитки: по бокам, снизу, сверху (сверху — не меньше половины ярлыка). */
const ПОЛЯ = { бок: 8, низ: 5, верх: 9 } as const;
const ПРОМЕЖУТОК = 8;
/** Ярлык стоит на верхней рамке плитки с отступом слева. */
const ЯРЛЫК_СЛЕВА = 6;

/** Ширины самых длинных подписей тем же шрифтом (скрытый замер): текст плитки, ярлык (и его высота), kk «Күн шығуы». */
type Замер = { текст: number; ярлык: number; высотаЯрлыка: number; восход: number };

/**
 * Число колонок сетки (чистая функция): 3, если плитка вмещает нужную ширину, иначе 2, иначе 1.
 * нужно — ширина плитки под самый длинный текст (с полями и рамкой).
 */
export function колонокСетки(ширинаСетки: number, нужно: number): 1 | 2 | 3 {
  for (const к of [3, 2] as const) if ((ширинаСетки - ПРОМЕЖУТОК * (к - 1)) / к >= нужно) return к;
  return 1;
}

