/** Цель касания колокольчика и зазор до текста. */
const КОЛОКОЛ = 48;
const ЗАЗОР_КОЛОКОЛА = 4;

type Отрезок = { x: number; y: number; ш: number; в: number };

/**
 * Где поставить колокольчик (чистая функция): строки ряда — по y отрезков; сначала первая строка, потом последняя;
 * справа нужно КОЛОКОЛ + ЗАЗОР свободных px. null — места нет (колокольчика не будет, высота карточки не меняется).
 */
export function местоКолокола(ширинаРяда: number, отрезки: readonly Отрезок[]): { верх: number } | null {
  if (!(ширинаРяда > 0) || !отрезки.length) return null;
  const строки = new Map<number, Отрезок[]>();
  for (const о of отрезки) {
    const ключ = [...строки.keys()].find((y) => Math.abs(y - о.y) < 6) ?? о.y;
    строки.set(ключ, [...(строки.get(ключ) ?? []), о]);
  }
  const ys = [...строки.keys()].sort((а, б) => а - б);
  for (const y of [ys[0], ys[ys.length - 1]]) {
    const строка = строки.get(y)!;
    const право = Math.max(...строка.map((о) => о.x + о.ш));
    const верх = Math.min(...строка.map((о) => о.y));
    const низ = Math.max(...строка.map((о) => о.y + о.в));
    if (ширинаРяда - право >= КОЛОКОЛ + ЗАЗОР_КОЛОКОЛА) return { верх: Math.round((верх + низ) / 2 - КОЛОКОЛ / 2) };
  }
  return null;
}

