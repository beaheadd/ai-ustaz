/**
 * КарточкаНамаза — «Арка дня» для главной и экрана «Время намаза»: шесть блоков времени намаза
 * (бриф docs/дизайн/01-бриф.md §5.2–5.4, вариант A), город, кибла, следующий намаз и обратный отсчёт.
 *
 * Контракт:
 *   <КарточкаНамаза перейтиКНамазу? перейтиККибле? выбратьГород? восходПоследним? арабские? сейчас? testID? />
 * - перейтиКНамазу — открыть экран «Время намаза» (неделя, метод); без него нижняя строка не нажимается.
 * - перейтиККибле — открыть экран киблы; без него кнопки «Кибла» нет.
 * - выбратьГород — открыть выбор города; по умолчанию перейти('городНамаза').
 * - восходПоследним — восход 6-м блоком (по умолчанию false: порядок дня, как у ДУМК и в мечети — восход после таң).
 * - арабские — мелкие арабские названия в блоках (по умолчанию true).
 * - сейчас — момент (мс) для тестов и предпросмотра; по умолчанию часы устройства (обновление раз в 30 с).
 * Место — useМестоНамаза() (prayer/store.ts): выбранное или Астана «по умолчанию · изменить».
 * testID: карточка-намаза, намаз-город, намаз-город-по-умолчанию, намаз-дата, намаз-следующий,
 *   намаз-следующий-время, намаз-отсчёт, намаз-до-восхода, намаз-сетка, намаз-блок-<ключ> (fajr…isha),
 *   намаз-время-<ключ>, намаз-метка-<ключ>, намаз-кибла, намаз-подпись, намаз-черновик, намаз-пояс,
 *   намаз-оговорка, намаз-ошибка.
 *
 * Оформление (дизайн-система): Карточка «герой» — арка тёмного изумруда; в вершине — знак фазы дня и полоса
 * горизонта (ГОРИЗОНТ, только декор). Блоки: прошедшее — тише (геройВторой); идущее сейчас — светлая рамка и
 * ярлык «сейчас»; следующий — мягкое золото и ярлык «следующий» (цвет не единственный носитель смысла);
 * восход — песочная пунктирная рамка, значок и ярлык «не намаз», золотым «следующим» не бывает.
 * Сетка 3×2; при крупном шрифте — 2×3, при очень крупном — столбец. Узора под временем нет.
 * Правила: время — расчёт на устройстве по методу ДУМК (prayer/times.ts), подпись «Расчёт по методу ДУМК
 * (±1 мин)», не «по данным ДУМК»; плашка «Черновик», пока устаз не посмотрел (CLAUDE.md, правило 11);
 * о действительности намаза — ничего; хиджры нет; без звука и анимаций.
 * Решение владельца 19.11.2026: главный экран — вверху 6 блоков времени намаза, 6-й — восход; ниже обучение.
 */
