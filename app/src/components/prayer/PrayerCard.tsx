/**
 * Полоса снизу карточки: «Фаджр» слева, «через 08:55:00» справа и колокольчик (как в Sajda; владелец 26.11.2026).
 * Название и отсчёт — одна ссылка на экран «Время намаза» (значок «вперёд» показывает, что открывается); колокольчик —
 * отдельная кнопка рядом. Слово при отсчёте — мелко: ru «через», en «in» перед цифрами; kk «қалды», uz «qoldi» после
 * (разбор удобства 26.11.2026: голые цифры читались как время намаза). Диктору — без секунд и без повтора слова.
 */
function ПолосаСледующего({
  следующий,
  колокол,
  т,
  язык,
  пояс,
  заданное,
  перейтиКНамазу,
}: {
  следующий: { ключ: КлючВремени; момент: number };
  колокол: boolean;
  т: Т;
  язык: Язык;
  пояс: string;
  заданное?: number;
  перейтиКНамазу?: () => void;
}) {
  const { цвет } = useТема();
  const { перейти } = useНавигация();
  const { настройки } = useНастройкиУведомлений();
  const поддержка = useПоддержкаУведомлений();
  const сейчас = useСекунды(заданное);
  const осталось = следующий.момент - сейчас;
  const название = НАЗВАНИЯ[следующий.ключ][язык];
  const вкл = настройки.включено;
  // Диктору — с точностью до минуты (секунды не зачитываем); слово «через/қалды» уже в обратныйОтсчётПолностью.
  const диктор = т('дикторПолоса', { намаз: название, время: чч_мм(следующий.момент, пояс), отсчёт: обратныйОтсчётПолностью(Math.max(осталось, 60000), язык) });
  // Порядок слов: ru, en — «через 08:55:00», «in 08:55:00»; kk, uz — «08:55:00 қалды», «08:55:00 qoldi».
  const словоПосле = язык === 'kk' || язык === 'uz';
  const перед = словоПосле ? '' : т('отсчётСлово');
  const после = словоПосле ? т('отсчётСлово') : '';
  const слово = { fontSize: 13, lineHeight: 18, opacity: 0.85 } as const;
  const естьКолокол = колокол && поддержка === 'можно';
  return (
    <View style={{ flexDirection: 'row', alignItems: 'center', backgroundColor: цвет.акцент, minHeight: 48 }} testID="намаз-следующий">
      <Pressable
        accessibilityRole="link"
        accessibilityLabel={диктор}
        accessibilityHint={т('открытьНамаз')}
        disabled={!перейтиКНамазу}
        onPress={перейтиКНамазу}
        testID="намаз-полоса"
        style={({ pressed }) => ({
          flex: 1,
          minHeight: 48,
          flexDirection: 'row',
          alignItems: 'center',
          gap: 6,
          paddingLeft: 16,
          paddingRight: естьКолокол ? 4 : 12,
          opacity: pressed ? 0.8 : 1,
        })}
      >
        <Текст вид="подзаголовок" цвет={цвет.акцентТекст} aria-hidden numberOfLines={1} testID="намаз-следующий-название" стиль={{ flexShrink: 1 }}>
          {название}
        </Текст>
        <View style={{ flex: 1 }} />
        <View aria-hidden style={{ flexDirection: 'row', alignItems: 'baseline', gap: 5 }}>
          {перед ? (
            <Текст вид="мелкий" цвет={цвет.акцентТекст} стиль={слово} testID="намаз-отсчёт-слово">
              {перед}
            </Текст>
          ) : null}
          <Текст вид="времяСреднее" цвет={цвет.акцентТекст} testID="намаз-отсчёт" стиль={{ fontSize: 22, lineHeight: 28, fontVariant: ['tabular-nums'] }}>
            {отсчётЧМС(осталось)}
          </Текст>
          {после ? (
            <Текст вид="мелкий" цвет={цвет.акцентТекст} стиль={слово} testID="намаз-отсчёт-слово">
              {после}
            </Текст>
          ) : null}
        </View>
        {перейтиКНамазу ? <Значок имя="вперёд" размер={16} цвет={цвет.акцентТекст} /> : null}
      </Pressable>
      {естьКолокол ? (
        <Pressable
          accessibilityRole="button"
          accessibilityLabel={т(вкл ? 'колоколВкл' : 'колоколВыкл')}
          onPress={() => перейти('уведомления')}
          testID="намаз-колокол"
          style={({ pressed }) => ({ width: 48, height: 48, alignItems: 'center', justifyContent: 'center', opacity: pressed ? 0.7 : 1 })}
        >
          <Значок имя={вкл ? 'колокол' : 'колоколВыкл'} размер={20} цвет={цвет.акцентТекст} />
        </Pressable>
      ) : null}
    </View>
  );
}
