/** Часы с секундами для полосы отсчёта: тик раз в секунду, только пока страница видна (visibilitychange). */
function useСекунды(заданное?: number): number {
  const [мс, установить] = useState(() => заданное ?? Date.now());
  useEffect(() => {
    if (заданное !== undefined) return;
    let таймер: ReturnType<typeof setInterval> | null = null;
    const видно = () => typeof document === 'undefined' || document.visibilityState !== 'hidden';
    const обновить = () => {
      if (видно()) {
        установить(Date.now());
        if (таймер === null) таймер = setInterval(() => установить(Date.now()), 1000);
      } else if (таймер !== null) {
        clearInterval(таймер);
        таймер = null;
      }
    };
    обновить();
    if (typeof document !== 'undefined') document.addEventListener('visibilitychange', обновить);
    return () => {
      if (таймер !== null) clearInterval(таймер);
      if (typeof document !== 'undefined') document.removeEventListener('visibilitychange', обновить);
    };
  }, [заданное]);
  return заданное ?? мс;
}

/** Отсчёт «ч:мм:сс» (как в Sajda: 08:08:03), не меньше нуля (чистая функция). */
export function отсчётЧМС(мс: number): string {
  const всего = Math.max(0, Math.floor(мс / 1000));
  const ч = Math.floor(всего / 3600);
  const м = Math.floor((всего % 3600) / 60);
  const с = всего % 60;
  return [ч, м, с].map((ч) => String(ч).padStart(2, '0')).join(':');
}

