/**
 * ПриглашениеПослеНамаза — «Урок после намаза»: мягкое «5 минут урока?» через 10–40 минут после начала времени
 * намаза (не восхода; docs/дизайн/02-образ-устаза.md, реплика №3). Ничего не говорит о самом намазе, без
 * упрёков и счётчиков. В первые 10 минут времени не зовём: человек, возможно, ещё не молился.
 *
 * Контракт:
 *   <ПриглашениеПослеНамаза продолжить надписьКнопки? видКнопки?="вторичная|основная" окноМин?={40} сейчас? testID? />
 * - продолжить — переход к продолжению урока (экран сам решает, к какому: обычно следующийШаг главной).
 * - видКнопки — «основная», если на экране нет другой основной кнопки (одна основная на экран).
 * - Вне окна — ничего не рисует. «Не сейчас» скрывает до следующего намаза (ключ aiustaz:prayer-invite.v1 —
 *   день и намаз, только на устройстве).
 * - Место и время — как у КарточкиНамаза (prayer/store.ts, prayer/hooks.ts).
 *   useПриглашениеПослеНамаза({ окноМин?, сейчас? }) → { приглашение: { ключ, названиеПосле } | null, скрыть() } —
 *     та же логика без карточки (главная встраивает приглашение в реплику карточки урока, «Не сейчас» — под
 *     кнопкой). Компонент перерисовывается, только когда окно открывается или закрывается (useЧасы).
 * testID: урок-после-намаза, урок-после-намаза-перейти, урок-после-намаза-скрыть.
 * Эмблема устаза — фонарь-шырақ в покое (образ ИИ-наставника, без лица). Тексты — черновик (kk — для редактора).
 * Где показываем: экран «Время намаза» (#/prayer). На главной отдельной карточки нет (одна мысль — одна карточка).
 */
import { useCallback, useState } from 'react';
import { Platform, View } from 'react-native';
import { записатьJSON } from '../../engine/storage';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { НАЗВАНИЯ, деньРК, приглашениеПослеНамаза } from '../../prayer/day';
import { useЧасы, временаДняКэш } from '../../prayer/hooks';
import { useМестоНамаза } from '../../prayer/store';
import type { КлючВремени } from '../../prayer/times';
import { useТема } from '../../theme';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { ЭмблемаУстаза } from '../UstazEmblem';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    заголовок: '5 минут урока?',
    текст: 'После {намаз} — продолжим с того места, где вы остановились.',
    перейти: 'К уроку',
    скрыть: 'Не сейчас',
  },
  kk: {
    заголовок: '5 минуттық сабақ?',
    текст: '{намаз} кейін — тоқтаған жерден жалғастырайық.',
    перейти: 'Сабаққа',
    скрыть: 'Қазір емес',
  },
  uz: {
    заголовок: '5 daqiqalik dars?',
    текст: '{намаз} keyin — toʻxtagan joyingizdan davom etamiz.',
    перейти: 'Darsga',
    скрыть: 'Hozir emas',
  },
});

const КЛЮЧ = 'prayer-invite.v1';

function скрытоСразу(): string {
  if (Platform.OS !== 'web') return '';
  try {
    const з = JSON.parse(globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ) ?? 'null') as { скрыто?: unknown } | null;
    return typeof з?.скрыто === 'string' ? з.скрыто : '';
  } catch {
    return '';
  }
}

export type Приглашение = { ключ: КлючВремени; названиеПосле: string };

/** Логика приглашения без карточки: окно 10–40 мин после начала намаза, «Не сейчас» — до следующего намаза. */
export function useПриглашениеПослеНамаза({ окноМин = 40, сейчас: заданное }: { окноМин?: number; сейчас?: number } = {}): {
  приглашение: Приглашение | null;
  скрыть: () => void;
} {
  const { язык } = useПеревод();
  const { место } = useМестоНамаза();
  const { пояс } = место;
  // Метка «день:намаз» или '' — компонент перерисуется, только когда окно откроется или закроется. Место целиком: для
  // КЗ/УЗ — официальная таблица, если она на телефоне (владелец 20.11.2026).
  const метка = useЧасы((мс) => {
    const сегодня = временаДняКэш(место, деньРК(мс, пояс));
    const п = сегодня ? приглашениеПослеНамаза(мс, сегодня, окноМин) : null;
    return п && сегодня ? `${сегодня.день}:${п.ключ}` : '';
  }, заданное);
  const [скрыто, установитьСкрыто] = useState(скрытоСразу);
  const скрыть = useCallback(() => {
    установитьСкрыто(метка);
    void записатьJSON(КЛЮЧ, { скрыто: метка });
  }, [метка]);
  if (!метка || скрыто === метка) return { приглашение: null, скрыть };
  const ключ = метка.slice(метка.indexOf(':') + 1) as КлючВремени;
  return { приглашение: { ключ, названиеПосле: язык === 'kk' ? НАЗВАНИЯ[ключ].послеKk : язык === 'uz' ? НАЗВАНИЯ[ключ].послеUz : НАЗВАНИЯ[ключ].послеRu }, скрыть };
}

export type СвойстваПриглашения = {
  продолжить: () => void;
  надписьКнопки?: string;
  видКнопки?: 'основная' | 'вторичная';
  окноМин?: number;
  сейчас?: number;
  testID?: string;
};

export function ПриглашениеПослеНамаза({ продолжить, надписьКнопки, видКнопки = 'вторичная', окноМин = 40, сейчас, testID = 'урок-после-намаза' }: СвойстваПриглашения) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const { приглашение, скрыть } = useПриглашениеПослеНамаза({ окноМин, сейчас });
  if (!приглашение) return null;
  return (
    <Карточка вид="акцент" testID={testID}>
      <View style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start' }}>
        <ЭмблемаУстаза размер={40} состояние="покой" />
        <View style={{ flex: 1, gap: отступ.xs }}>
          <Текст вид="подзаголовок">{т('заголовок')}</Текст>
          <Текст вид="второй">{т('текст', { намаз: приглашение.названиеПосле })}</Текст>
        </View>
      </View>
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
        <Кнопка вид={видКнопки} надпись={надписьКнопки ?? т('перейти')} значок="урок" растянуть={false} приНажатии={продолжить} testID={testID + '-перейти'} />
        <Кнопка вид="тихая" надпись={т('скрыть')} растянуть={false} приНажатии={скрыть} testID={testID + '-скрыть'} />
      </View>
    </Карточка>
  );
}
