/**
 * ПриглашениеПослеНамаза — «Урок после намаза»: мягкое «5 минут урока?», если с начала времени намаза
 * (не восхода) прошло не больше 40 минут. Ничего не говорит о самом намазе, без упрёков и счётчиков.
 *
 * Контракт:
 *   <ПриглашениеПослеНамаза продолжить надписьКнопки? видКнопки?="вторичная|основная" окноМин?={40} сейчас? testID? />
 * - продолжить — переход к продолжению урока (экран сам решает, к какому: обычно следующийШаг главной).
 * - видКнопки — «основная», если на экране нет другой основной кнопки (одна основная на экран).
 * - Вне окна — ничего не рисует. «Не сейчас» скрывает до следующего намаза (ключ aiustaz:prayer-invite.v1 —
 *   день и намаз, только на устройстве).
 * - Место и время — как у КарточкиНамаза (prayer/store.ts, prayer/hooks.ts).
 * testID: урок-после-намаза, урок-после-намаза-перейти, урок-после-намаза-скрыть.
 * Эмблема устаза — фонарь-шырақ в покое (образ ИИ-наставника, без лица). Тексты — черновик (kk — для редактора).
 */
import { useState } from 'react';
import { Platform, View } from 'react-native';
import { записатьJSON } from '../../engine/storage';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { НАЗВАНИЯ, приглашениеПослеНамаза } from '../../prayer/day';
import { useДеньНамаза, useСейчас } from '../../prayer/hooks';
import { useМестоНамаза } from '../../prayer/store';
import { useТема } from '../../theme';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { ЭмблемаУстаза } from '../UstazEmblem';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    заголовок: '5 минут урока?',
    текст: 'После {намаз} — продолжим с того места, где вы остановились.',
    перейти: 'К уроку',
    скрыть: 'Не сейчас',
  },
  kk: {
    заголовок: '5 минут сабақ?',
    текст: '{намаз} кейін — тоқтаған жерден жалғастырайық.',
    перейти: 'Сабаққа',
    скрыть: 'Қазір емес',
  },
});

const КЛЮЧ = 'prayer-invite.v1';

function скрытоСразу(): string {
  if (Platform.OS !== 'web') return '';
  try {
    const з = JSON.parse(globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ) ?? 'null') as { скрыто?: unknown } | null;
    return typeof з?.скрыто === 'string' ? з.скрыто : '';
  } catch {
    return '';
  }
}

export type СвойстваПриглашения = {
  продолжить: () => void;
  надписьКнопки?: string;
  видКнопки?: 'основная' | 'вторичная';
  окноМин?: number;
  сейчас?: number;
  testID?: string;
};

export function ПриглашениеПослеНамаза({ продолжить, надписьКнопки, видКнопки = 'вторичная', окноМин = 40, сейчас: заданное, testID = 'урок-после-намаза' }: СвойстваПриглашения) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const { место } = useМестоНамаза();
  const сейчас = useСейчас(заданное);
  const { день } = useДеньНамаза(место, сейчас);
  const [скрыто, установитьСкрыто] = useState(скрытоСразу);

  const п = день ? приглашениеПослеНамаза(сейчас, день.сегодня, окноМин) : null;
  if (!п || !день) return null;
  const метка = `${день.сегодня.день}:${п.ключ}`;
  if (скрыто === метка) return null;

  const названиеПосле = язык === 'kk' ? НАЗВАНИЯ[п.ключ].послеKk : НАЗВАНИЯ[п.ключ].послеRu;
  return (
    <Карточка вид="акцент" testID={testID}>
      <View style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start' }}>
        <ЭмблемаУстаза размер={40} состояние="покой" />
        <View style={{ flex: 1, gap: отступ.xs }}>
          <Текст вид="подзаголовок">{т('заголовок')}</Текст>
          <Текст вид="второй">{т('текст', { намаз: названиеПосле })}</Текст>
        </View>
      </View>
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
        <Кнопка вид={видКнопки} надпись={надписьКнопки ?? т('перейти')} значок="урок" растянуть={false} приНажатии={продолжить} testID={testID + '-перейти'} />
        <Кнопка
          вид="тихая"
          надпись={т('скрыть')}
          растянуть={false}
          приНажатии={() => {
            установитьСкрыто(метка);
            void записатьJSON(КЛЮЧ, { скрыто: метка });
          }}
          testID={testID + '-скрыть'}
        />
      </View>
    </Карточка>
  );
}
