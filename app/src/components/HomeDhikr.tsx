type Раздел = 'зикры' | 'дуа' | 'коран' | 'хадисы' | 'намаз' | 'таджвид' | 'закят' | 'время' | 'кибла';
const РАЗДЕЛЫ: readonly { id: Раздел; рисунок: ИмяИллюстрации }[] = [
  { id: 'зикры', рисунок: 'зикры' },
  { id: 'дуа', рисунок: 'дуа' },
  { id: 'коран', рисунок: 'коран' },
  { id: 'таджвид', рисунок: 'таджвид' },
  { id: 'намаз', рисунок: 'намаз' },
  { id: 'хадисы', рисунок: 'хадисы' },
  { id: 'время', рисунок: 'времяНамаза' },
  { id: 'кибла', рисунок: 'кибла' },
  { id: 'закят', рисунок: 'закят' },
];

/** Плиток в ряду. */
const В_РЯДУ = 3;
const РЯДЫ = Array.from({ length: Math.ceil(РАЗДЕЛЫ.length / В_РЯДУ) }, (_, i) => РАЗДЕЛЫ.slice(i * В_РЯДУ, (i + 1) * В_РЯДУ));

export function СеткаРазделов() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, тень } = useТема();
  const { перейти, перейтиВкладку } = useНавигация();

  const открыть = (id: Раздел) => {
    if (id === 'зикры') перейти('зикры');
    else if (id === 'дуа') перейти('дуа');
    else if (id === 'намаз') перейти('учимсяНамазу');
    else if (id === 'закят') перейти('закят');
    else if (id === 'время') перейти('намаз');
    else if (id === 'кибла') перейти('кибла');
    // Раздел не в нижнем меню (таджвид с 27.11.2026: в центре меню AI Ustaz) — открываем его экран с главной.
    else if (!ВКЛАДКИ.includes(id)) перейти(КОРЕНЬ_ВКЛАДКИ[id]);
    else перейтиВкладку(id);
  };

  return (
    <View style={{ gap: отступ.s }}>
      <View testID="главная-разделы" role="group" aria-label={т('разделы')} style={{ gap: отступ.m }}>
        {РЯДЫ.map((ряд, i) => (
          <View key={i} testID={'главная-разделы-ряд-' + (i + 1)} style={{ flexDirection: 'row', columnGap: отступ.s }}>
            {ряд.map((р) => (
              <Pressable
                key={р.id}
                accessibilityRole="button"
                accessibilityLabel={т(р.id)}
                onPress={() => открыть(р.id)}
                testID={'главная-раздел-' + р.id}
                style={({ pressed }) => ({
                  flex: 1,
                  minWidth: 0,
                  alignItems: 'center',
                  justifyContent: 'flex-start',
                  gap: 4,
                  paddingTop: 10,
                  paddingBottom: 10,
                  paddingHorizontal: 4,
                  borderRadius: 22,
                  backgroundColor: цвет.поверхность,
                  borderWidth: 1,
                  borderColor: цвет.граница,
                  opacity: pressed ? 0.75 : 1,
                  ...тень(1),
                })}
              >
                <ИллюстрацияРаздела имя={р.рисунок} размер={60} testID={'главная-рисунок-' + р.id} />
                {/* Подпись в 2 строки (на 320 px kk — до 3), кегль не сжимается: «Намаз оқып үйрену», «Namozni oʻrganish». */}
                <Текст вид="метка" numberOfLines={3} стиль={{ fontSize: 15, lineHeight: 20, textAlign: 'center' }}>
                  {т(р.id)}
                </Текст>
              </Pressable>
            ))}
            {/* Пустые места неполного ряда — та же ширина, что у плитки (седьмая плитка не растягивается). */}
            {Array.from({ length: В_РЯДУ - ряд.length }, (_, j) => (
              <View key={'пусто' + j} aria-hidden style={{ flex: 1 }} />
            ))}
          </View>
        ))}
      </View>
    </View>
  );
}
