type Раздел = 'зикры' | 'дуа' | 'коран' | 'хадисы' | 'намаз' | 'таджвид';
const РАЗДЕЛЫ: readonly { id: Раздел; значок: ИмяЗначка }[] = [
  { id: 'зикры', значок: 'тасбих' },
  { id: 'дуа', значок: 'дуа' },
  { id: 'коран', значок: 'коран' },
  { id: 'хадисы', значок: 'хадис' },
  { id: 'намаз', значок: 'намаз' },
  { id: 'таджвид', значок: 'таджвид' },
];

export function СеткаРазделов() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const { перейти, перейтиВкладку } = useНавигация();
  const [скоро, установитьСкоро] = useState(false);

  const открыть = (id: Раздел) => {
    if (id === 'зикры') перейти('зикры');
    else if (id === 'дуа') перейти('дуа');
    else if (id === 'намаз') установитьСкоро((б) => !б);
    // Хадисы — вкладка меню; когда в центре меню AI Ustaz (флаг), их вкладки нет — открываем экран.
    else if (id === 'хадисы' && !ВКЛАДКИ.includes('хадисы')) перейти('хадисы');
    else перейтиВкладку(id);
  };

  return (
    <View style={{ gap: отступ.s }}>
      <View testID="главная-разделы" role="group" aria-label={т('разделы')} style={{ flexDirection: 'row', flexWrap: 'wrap', rowGap: отступ.m, columnGap: отступ.s }}>
        {РАЗДЕЛЫ.map((р) => (
          <Pressable
            key={р.id}
            accessibilityRole="button"
            accessibilityLabel={р.id === 'намаз' ? `${т('намаз')}, ${т('скоро')}` : т(р.id)}
            {...(р.id === 'намаз' ? { accessibilityState: { expanded: скоро } } : null)}
            onPress={() => открыть(р.id)}
            testID={'главная-раздел-' + р.id}
            style={({ pressed }) => ({ width: '31.5%', flexGrow: 1, alignItems: 'center', gap: отступ.xs, opacity: pressed ? 0.75 : 1 })}
          >
            <View
              style={{ alignSelf: 'stretch', minHeight: 64, borderRadius: радиус.l, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.поверхность, borderWidth: 1, borderColor: цвет.граница }}
            >
              <Значок имя={р.значок} размер={34} цвет={цвет.акцент} />
              {р.id === 'намаз' ? (
                <View style={{ position: 'absolute', top: 4, right: 4, paddingHorizontal: 6, borderRadius: 8, backgroundColor: цвет.акцентМягкий }}>
                  <Текст вид="мелкий" цвет={цвет.акцент} стиль={{ fontSize: 11, lineHeight: 16 }}>
                    {т('скоро')}
                  </Текст>
                </View>
              ) : null}
            </View>
            <Текст вид="метка" numberOfLines={2} стиль={{ textAlign: 'center' }}>
              {т(р.id)}
            </Текст>
          </Pressable>
        ))}
      </View>
      {скоро ? (
        <Текст вид="мелкий" цвет={цвет.текстВторой} testID="главная-намаз-скоро" accessibilityLiveRegion="polite">
          {т('намазСкоро')}
        </Текст>
      ) : null}
    </View>
  );
}
