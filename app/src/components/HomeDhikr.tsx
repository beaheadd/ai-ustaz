/**
 * Главная: сетка разделов по 3 в ряд под аркой времени намаза (7 плиток: 3 + 3 + 1).
 *
 * Решение владельца 27.11.2026 (образец — HalalGuide): «На главный экран нужно добавить зикры как кнопочку — сами
 * зикры здесь выводить не нужно; поставь значок тасбиха. Потом добавить дуа (дұғалар). Потом Коран, хадисы, намаз оқып
 * үйрену — и значки соответствующие». Блок быстрых зикров со счётом (26.11.2026) убран.
 *
 * Контракт: <СеткаРазделов /> — 7 плиток: цветная иллюстрация (components/SectionArt.tsx) на мягкой плашке + подпись
 *   под ней (до 2 строк). 27.11.2026 владелец: «значки нужно отрисовать… Дуа — неприличный жест… Зикры — тасбих, как
 *   фото… намаз — другой значок» — линейные значки заменены своими цветными иллюстрациями.
 *   Зикры (тасбих) → #/dhikr; Дуа (ладони) → #/dua; Коран → вкладка «Коран»; Хадисы → вкладка «Хадисы»;
 *   Учимся намазу (коврик с михрабом) → #/namaz (владелец 27.11.2026: «Учимся намазу нужно собрать по ханафи»;
 *   раздел — черновик, проверяет устаз);
 *   Таджвид (продукт №1) → вкладка «Таджвид»;
 *   Закят (мешочек с монетами и полумесяцем) → #/zakat (владелец 28.11.2026: «Нужно добавить калькулятор закята.
 *   Назвать нужно „Закят“»; раздел — черновик, проверяет устаз).
 *   Сетка — ряды по 3 плитки одной ширины (flex: 1); в неполном последнем ряду — пустые места той же ширины, поэтому
 *   седьмая плитка стоит слева под первой колонкой и не растягивается на весь ряд (28.11.2026). 4 в ряд не взяли: на
 *   360 px плитка сжалась бы до ≈ 76 px (на 320 — до ≈ 66), а длинные подписи («Намаз оқып үйрену», «Namozni
 *   oʻrganish») рвались бы на три строки или посреди слова.
 *   Свои иллюстрации, без лиц и фигур (правило 9); 3D-картинки HalalGuide не копируем.
 * Без наград и счётчиков. kk — черновик для редактора-носителя.
 * testID: главная-разделы, главная-разделы-ряд-<1..3>, главная-раздел-<зикры|дуа|коран|хадисы|намаз|таджвид|закят>.
 */
import { Pressable, View } from 'react-native';
import { useНавигация } from '../engine/navigation';
import { ВКЛАДКИ, КОРЕНЬ_ВКЛАДКИ } from '../engine/routes';
import { создатьСловарь, useСловарь } from '../i18n';
import { useТема } from '../theme';
import { ИллюстрацияРаздела, type ИмяИллюстрации } from './SectionArt';
import { Текст } from './Text';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    разделы: 'Разделы',
    зикры: 'Зикры',
    дуа: 'Дуа',
    коран: 'Коран',
    хадисы: 'Хадисы',
    намаз: 'Учимся намазу',
    таджвид: 'Таджвид',
    закят: 'Закят',
  },
  kk: {
    разделы: 'Бөлімдер',
    зикры: 'Зікірлер',
    дуа: 'Дұғалар',
    коран: 'Құран',
    хадисы: 'Хадистер',
    намаз: 'Намаз оқып үйрену',
    таджвид: 'Тәжуид',
    закят: 'Зекет',
  },
  uz: {
    разделы: 'Boʻlimlar',
    зикры: 'Zikrlar',
    дуа: 'Duolar',
    коран: 'Qurʼon',
    хадисы: 'Hadislar',
    намаз: 'Namozni oʻrganish',
    таджвид: 'Tajvid',
    закят: 'Zakot',
  },
  en: {
    разделы: 'Sections',
    зикры: 'Dhikr',
    дуа: 'Duas',
    коран: 'Quran',
    хадисы: 'Hadith',
    намаз: 'Learn salah',
    таджвид: 'Tajweed',
    закят: 'Zakat',
  },
});

type Раздел = 'зикры' | 'дуа' | 'коран' | 'хадисы' | 'намаз' | 'таджвид' | 'закят';
const РАЗДЕЛЫ: readonly { id: Раздел; рисунок: ИмяИллюстрации }[] = [
  { id: 'зикры', рисунок: 'зикры' },
  { id: 'дуа', рисунок: 'дуа' },
  { id: 'коран', рисунок: 'коран' },
  { id: 'хадисы', рисунок: 'хадисы' },
  { id: 'намаз', рисунок: 'намаз' },
  { id: 'таджвид', рисунок: 'таджвид' },
  { id: 'закят', рисунок: 'закят' },
];

/** Плиток в ряду. */
const В_РЯДУ = 3;
const РЯДЫ = Array.from({ length: Math.ceil(РАЗДЕЛЫ.length / В_РЯДУ) }, (_, i) => РАЗДЕЛЫ.slice(i * В_РЯДУ, (i + 1) * В_РЯДУ));

export function СеткаРазделов() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const { перейти, перейтиВкладку } = useНавигация();

  const открыть = (id: Раздел) => {
    if (id === 'зикры') перейти('зикры');
    else if (id === 'дуа') перейти('дуа');
    else if (id === 'намаз') перейти('учимсяНамазу');
    else if (id === 'закят') перейти('закят');
    // Раздел не в нижнем меню (таджвид с 27.11.2026: в центре меню AI Ustaz) — открываем его экран с главной.
    else if (!ВКЛАДКИ.includes(id)) перейти(КОРЕНЬ_ВКЛАДКИ[id]);
    else перейтиВкладку(id);
  };

  return (
    <View style={{ gap: отступ.s }}>
      <View testID="главная-разделы" role="group" aria-label={т('разделы')} style={{ gap: отступ.m }}>
        {РЯДЫ.map((ряд, i) => (
          <View key={i} testID={'главная-разделы-ряд-' + (i + 1)} style={{ flexDirection: 'row', columnGap: отступ.s }}>
            {ряд.map((р) => (
              <Pressable
                key={р.id}
                accessibilityRole="button"
                accessibilityLabel={т(р.id)}
                onPress={() => открыть(р.id)}
                testID={'главная-раздел-' + р.id}
                style={({ pressed }) => ({ flex: 1, minWidth: 0, alignItems: 'center', gap: отступ.xs, opacity: pressed ? 0.75 : 1 })}
              >
                <View
                  style={{ alignSelf: 'stretch', minHeight: 76, paddingVertical: 6, borderRadius: радиус.l, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.поверхность, borderWidth: 1, borderColor: цвет.граница }}
                >
                  <ИллюстрацияРаздела имя={р.рисунок} размер={58} testID={'главная-рисунок-' + р.id} />
                </View>
                <Текст вид="метка" numberOfLines={2} стиль={{ textAlign: 'center' }}>
                  {т(р.id)}
                </Текст>
              </Pressable>
            ))}
            {/* Пустые места неполного ряда — та же ширина, что у плитки (седьмая плитка не растягивается). */}
            {Array.from({ length: В_РЯДУ - ряд.length }, (_, j) => (
              <View key={'пусто' + j} aria-hidden style={{ flex: 1 }} />
            ))}
          </View>
        ))}
      </View>
    </View>
  );
}
