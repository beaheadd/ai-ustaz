/** Быстрые зикры по умолчанию (id из content/dhikr/dhikr.json). */
export const ЗИКРЫ_ПО_УМОЛЧАНИЮ = ['subhanallah', 'alhamdulillah', 'takbir', 'tahlil'] as const;

/** До четырёх зикров для главной: избранное (по порядку), затем по умолчанию; без повторов; только те, что есть. */
export function быстрыеЗикры(все: readonly Зикр[], избранное: readonly string[], сколько = 4): Зикр[] {
  const поId = new Map(все.map((з) => [з.id, з]));
  const итог: Зикр[] = [];
  for (const id of [...избранное, ...ЗИКРЫ_ПО_УМОЛЧАНИЮ]) {
    const з = поId.get(id);
    if (з && !итог.includes(з)) итог.push(з);
    if (итог.length >= сколько) break;
  }
  return итог;
}

export function БлокЗикров() {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const { перейти } = useНавигация();
  const загрузка = useЗикры();
  const счёт = useСчётЗикров();
  const зикры = загрузка.состояние === 'есть' ? быстрыеЗикры(загрузка.данные.зикры, счёт.избранное) : [];

  return (
    <Карточка testID="главная-зикры">
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
        <Значок имя="тасбих" размер={22} цвет={цвет.акцент} />
        <Текст вид="подзаголовок" accessibilityRole="header" стиль={{ flex: 1 }}>
          {т('зикры')}
        </Текст>
        <Pressable
          accessibilityRole="link"
          onPress={() => перейти('зикры')}
          testID="главная-зикры-все"
          style={({ pressed }) => ({ minHeight: 44, flexDirection: 'row', alignItems: 'center', gap: 2, opacity: pressed ? 0.7 : 1 })}
        >
          <Текст вид="метка" цвет={цвет.акцент}>
            {т('все')}
          </Текст>
          <Значок имя="вперёд" размер={16} цвет={цвет.акцент} />
        </Pressable>
      </View>
      {зикры.length ? (
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
          {зикры.map((з) => {
            const запись = счёт.счёт[з.id];
            const цель = цельЗикра(запись, з.раз);
            const текущий = запись?.текущий ?? 0;
            const название = з.название[язык];
            return (
              <Pressable
                key={з.id}
                accessibilityRole="button"
                accessibilityLabel={т('диктор', { название, текущий, цель })}
                onPress={() => перейти('зикр', { номер: з.номер })}
                testID={'главная-зикр-' + з.id}
                style={({ pressed }) => ({
                  flexGrow: 1,
                  flexBasis: '45%',
                  minHeight: 56,
                  justifyContent: 'center',
                  gap: 2,
                  paddingHorizontal: отступ.m,
                  paddingVertical: отступ.s,
                  borderRadius: радиус.m,
                  borderWidth: 1,
                  borderColor: цвет.граница,
                  backgroundColor: pressed ? цвет.акцентМягкий : 'transparent',
                })}
              >
                <View aria-hidden>
                  <Текст вид="метка" numberOfLines={2}>
                    {название}
                  </Текст>
                  <Текст вид="мелкий" цвет={цвет.текстВторой} testID={'главная-зикр-' + з.id + '-счёт'}>
                    {т('счёт', { текущий, цель })}
                  </Текст>
                </View>
              </Pressable>
            );
          })}
        </View>
      ) : null}
    </Карточка>
  );
}

type Модуль = { id: 'зикры' | 'кибла'; значок: ИмяЗначка; надпись: 'мЗикры' | 'мКибла' };
// Кибла — первой, значком компаса с подписью (владелец 26.11.2026: «кибла — значок компаса и подпись „Кибла“»;
// в шапке на 360 px места рядом с городом нет).
const МОДУЛИ: readonly Модуль[] = [
  { id: 'кибла', значок: 'компас', надпись: 'мКибла' },
  { id: 'зикры', значок: 'тасбих', надпись: 'мЗикры' },
];

export function РядМодулей() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const { перейти } = useНавигация();
  const открыть = (id: Модуль['id']) => {
    if (id === 'зикры') перейти('зикры');
    else перейти('кибла');
  };
  return (
    <View testID="главная-модули" role="group" aria-label={т('модули')} style={{ flexDirection: 'row', gap: отступ.s }}>
      {МОДУЛИ.map((м) => (
        <Pressable
          key={м.id}
          accessibilityRole="button"
          onPress={() => открыть(м.id)}
          testID={'главная-модуль-' + м.id}
          style={({ pressed }) => ({
            flex: 1,
            minWidth: 0,
            minHeight: 56,
            flexDirection: 'row',
            alignItems: 'center',
            justifyContent: 'center',
            gap: отступ.s,
            paddingHorizontal: отступ.s,
            paddingVertical: отступ.xs,
            borderRadius: радиус.m,
            borderWidth: 1,
            borderColor: цвет.граница,
            backgroundColor: pressed ? цвет.акцентМягкий : цвет.поверхность,
          })}
        >
          <Значок имя={м.значок} размер={24} цвет={цвет.акцент} />
          <Текст вид="кнопка" цвет={цвет.акцент} стиль={{ flexShrink: 1 }} numberOfLines={2}>
            {т(м.надпись)}
          </Текст>
        </Pressable>
      ))}
    </View>
  );
}
