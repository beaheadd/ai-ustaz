const мб = (байт: number) => (байт / 1048576).toFixed(1);

/** Перерисовка при обновлении списка зеркала (издание опубликовали — появилась кнопка). */
function useЗеркало(): number {
  return useSyncExternalStore(подписатьсяНаЗеркало, версияЗеркала, () => 0);
}

/**
 * Маленькая кнопка «скачать» у суры в списке «Коран» (владелец 28.11.2026: «на каждую суру кнопку загрузки, чтобы отсюда
 * скачать, а не заходить внутрь и нажимать три точки — не каждый додумается»). ⬇ → проценты → ✓. Нет зеркала — не видна.
 */
export function КнопкаСкачатьСуру({ сура, подпись }: { сура: number; подпись: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет } = useТема();
  useЗеркало();
  useЧтец();
  const скачанное = useСкачанное();
  const [ход, установитьХод] = useState<{ готово: number; всего: number } | null>(null);
  const источник = доступныйИсточник();
  if (!источник || !можноСкачать(источник)) return null;
  const адреса = адресаСуры(источник, сура);
  const все = адреса.every((а) => скачанное.есть(а));
  const начать = () => {
    if (ход || все) return;
    установитьХод({ готово: 0, всего: адреса.length });
    void скачать(адреса, (готово, всего) => установитьХод({ готово, всего })).then(() => установитьХод(null));
  };
  const процент = ход && ход.всего ? Math.floor((ход.готово / ход.всего) * 100) : 0;
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={все ? `${подпись}: ${т('готово')}` : `${подпись}: ${т('скачатьСуру')}`}
      disabled={все}
      onPress={начать}
      testID={`скачать-суру-${сура}`}
      hitSlop={4}
      style={({ pressed }) => ({ width: 44, height: 44, borderRadius: 22, alignItems: 'center', justifyContent: 'center', backgroundColor: pressed ? цвет.акцентМягкий : 'transparent' })}
    >
      {ход ? (
        <Текст вид="мелкий" табличные цвет={цвет.акцент} testID={`скачать-суру-${сура}-ход`}>
          {процент + '%'}
        </Текст>
      ) : (
        <Значок имя={все ? 'галочка' : 'установить'} размер={22} цвет={все ? цвет.акцент : цвет.текстВторой} />
      )}
    </Pressable>
  );
}

export function СкачатьСуру({ сура }: { сура: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  useЗеркало();
  useЧтец();
  const скачанное = useСкачанное();
  const [ход, установитьХод] = useState<{ готово: number; всего: number } | null>(null);
  const [ошибок, установитьОшибок] = useState(0);
  const источник = доступныйИсточник();
  if (!источник || !можноСкачать(источник)) return null;
  const адреса = адресаСуры(источник, сура);
  const все = адреса.every((а) => скачанное.есть(а));
  const начать = () => {
    if (ход) return;
    установитьОшибок(0);
    установитьХод({ готово: 0, всего: адреса.length });
    void скачать(адреса, (готово, всего) => установитьХод({ готово, всего })).then((и) => {
      установитьОшибок(и.ошибок);
      установитьХод(null);
    });
  };
  return (
    <View testID="скачать-суру" style={{ gap: отступ.xs }}>
      {ход ? (
        <Текст вид="мелкий" табличные testID="скачать-суру-ход" {...({ accessibilityLiveRegion: 'polite', role: 'status' } as object)}>
          {т('ход', { готово: ход.готово, всего: ход.всего })}
        </Текст>
      ) : все ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }} testID="скачать-суру-готово">
          <Значок имя="галочка" размер={18} цвет={цвет.акцент} />
          <Текст вид="мелкий" стиль={{ flex: 1 }}>
            {т('готово')}
          </Текст>
        </View>
      ) : (
        <Кнопка
          вид="вторичная"
          значок="установить"
          надпись={ошибок ? т('ошибка') : т('скачатьСуру')}
          приНажатии={начать}
          testID={ошибок ? 'скачать-суру-ошибка' : 'скачать-суру-кнопка'}
        />
      )}
    </View>
  );
}

export function СкачанноеЧтение() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const язык = языкПлеера(useПеревод().язык);
  const { версия } = useСкачанное();
  useЗеркало();
  const [сводка, установитьСводку] = useState<СводкаИздания[] | null>(null);
  useEffect(() => {
    let живой = true;
    void сводкаСкачанного().then((с) => живой && установитьСводку(с));
    return () => {
      живой = false;
    };
  }, [версия]);
  if (!сводка || !чтецы().length) return null;
  // Скачивать здесь нельзя и скачанного нет (batr.kz, нет зеркала, нет service worker'а) — ничего не рисуем.
  if (сводка.length === 0 && !чтецы().some(можноСкачать)) return null;
  const всего = сводка.reduce((с, и) => с + и.байт, 0);
  const имя = (и: СводкаИздания) => чтецы().find((ч) => ч.cdn?.издание === и.издание && ч.cdn.битрейт === и.битрейт)?.кари[язык] ?? и.издание;
  return (
    <View testID="скачанное" style={{ gap: отступ.xs }}>
      <Текст вид="мелкий">{т('заголовок')}</Текст>
      {сводка.length === 0 ? (
        <Текст вид="мелкий" цвет={цвет.текстВторой}>
          {т('пусто')}
        </Текст>
      ) : (
        <>
          {сводка.map((и) => (
            <View key={и.битрейт + '/' + и.издание} testID={'скачанное-' + и.издание} style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s, minHeight: 48 }}>
              <Текст стиль={{ flex: 1 }} табличные>
                {т('строка', { кари: имя(и), файлов: и.файлов, мб: мб(и.байт) })}
              </Текст>
              <Кнопка вид="вторичная" надпись={т('удалить')} приНажатии={() => void удалитьСкачанное(и.битрейт + '/' + и.издание)} testID={'скачанное-' + и.издание + '-удалить'} />
            </View>
          ))}
          {сводка.length > 1 ? <Кнопка вид="вторичная" надпись={т('удалитьВсё', { мб: мб(всего) })} приНажатии={() => void удалитьСкачанное()} testID="скачанное-всё-удалить" /> : null}
        </>
      )}
    </View>
  );
}
