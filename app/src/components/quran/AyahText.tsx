/**
 * Текст аята из копии Tanzil ДЛЯ ПОКАЗА — один рисунок для экрана суры, бисмиллы и «Прочитать и записать».
 *
 * Правило 1 CLAUDE.md: строка не меняется — она режется только по пробелам (разборАята) и склеивается обратно теми же
 * пробелами, textContent элемента === строке Tanzil (e2e-quran сверяет побайтно).
 * Ревью 19.11.2026 (знаки остановки отрывались от слова): в Tanzil знак ۖ ۗ ۚ ۛ ۘ ۙ ۜ стоит отдельным токеном после
 * пробела; при переносе строки он уходил к краю колонки или в начало следующей строки, а при подсветке части — в
 * отдельный узел без своего пробела. Теперь «слово + пробел + знак(и)» (и «۞ + первое слово») — ОДНА группа
 * (группыТокенов, quran/text.ts): на вебе <span style="white-space:nowrap">, пробелы между группами — обычный текст.
 * Знак никогда не начинает строку и остаётся рядом со своим словом; пробел перед знаком — в том же текстовом узле.
 *
 * Контракт: <ТекстАята текст кегль? часть? замечания? подписьСлова? выравнивание? первоеСлово? testID? />
 *   кегль — по умолчанию выбор человека (useРазмерАрабского, quran/fontSize.ts); межстрочный — ×1,8.
 *   часть { токенС, токенПо } — группы внутри части: обычный цвет и мягкий фон (не только цветом — WCAG 1.4.1),
 *     вне части — приглушённый цвет. Группа относится к части по первому слову.
 *   замечания (номер uthmani-слова → уровень) — мягкий фон слова («Проверьте себя» — янтарь, «Подсказка» — акцент),
 *     data-testid «аят-слово-N»; без слова «ошибка» (правило 7). Для диктора слова замечаний перечисляет панель
 *     отдельным списком (RecitePanel, «Отмечены слова: 11 — проверьте себя»): подписи на <span> дикторы не читают.
 *   первоеСлово — текст является частью аята: номер его первого слова в аяте (для замечаний и «аят-слово-N»).
 *   Текст выделяется и копируется (selectable); lang="ar" dir="rtl". Пока шрифт не загружен — прозрачен.
 * Нативно (Android/iOS) группы — вложенные <Text> без nowrap (перенос по словам; проверить на устройстве — TODO).
 * Шрифт — выбор человека (components/quran/QuranFont.tsx, владелец 28.11.2026): «Мединский мусхаф» рисует строки через
 *   кусокКорана (подстройка показа, исходный текст — в data-o: копирование и сверки берут его); резка на группы и слова —
 *   по исходной строке, до подстройки.
 */
import { createElement, useMemo, type ReactNode } from 'react';
import { Platform, Text, type TextStyle } from 'react-native';
import { useРазмерАрабского } from '../../quran/fontSize';
import { группыТокенов, разборАята } from '../../quran/text';
import type { УровеньЗамечания } from '../../speech/answer';
import { useТема } from '../../theme';
import { кусокКорана, useШрифтКорана } from './QuranFont';

const ВЕБ = Platform.OS === 'web';
/** Атрибуты HTML для react-native-web (Text их поддерживает, в типах RN их нет). */
const ВЕБ_АР = (ВЕБ ? { lang: 'ar', dir: 'rtl' } : {}) as object;

export type СвойстваТекстаАята = {
  текст: string;
  кегль?: number;
  часть?: { токенС: number; токенПо: number } | null;
  замечания?: ReadonlyMap<number, УровеньЗамечания>;
  подписьСлова?: (номер: number) => string;
  выравнивание?: 'right' | 'center';
  /** Текст — часть аята: номер его первого слова в аяте (для замечаний и «аят-слово-N»); по умолчанию 1. */
  первоеСлово?: number;
  testID?: string;
};

export function ТекстАята({ текст, кегль: свой, часть = null, замечания, подписьСлова, выравнивание = 'right', первоеСлово = 1, testID }: СвойстваТекстаАята) {
  const { цвет, радиус } = useТема();
  const выбор = useРазмерАрабского();
  const шрифт = useШрифтКорана();
  const кегль = свой ?? выбор.кегль;
  const межстрочный = Math.round(кегль * 1.8);
  const токены = useMemo(() => разборАята(текст), [текст]);
  const группы = useMemo(() => группыТокенов(токены), [токены]);
  const естьЗамечания = !!замечания && замечания.size > 0;

  const дети: ReactNode[] = [];
  группы.forEach(([с, по], г) => {
    const первоеСловоГруппы = токены.slice(с, по + 1).findIndex((т) => т.вид === 'слово');
    const опорный = первоеСловоГруппы >= 0 ? с + первоеСловоГруппы : с;
    const вЧасти = часть === null || (опорный >= часть.токенС && опорный <= часть.токенПо);
    const внутри: ReactNode[] = [];
    for (let i = с; i <= по; i++) {
      const т = токены[i];
      const номер = т.вид === 'слово' ? т.номерСлова + первоеСлово - 1 : 0;
      const уровень = естьЗамечания && т.вид === 'слово' ? замечания?.get(номер) : undefined;
      if (уровень && т.вид === 'слово') {
        const стиль = {
          backgroundColor: уровень === 'подсказка' ? цвет.акцентМягкий : цвет.вниманиеФон,
          borderRadius: радиус.s,
          paddingLeft: 3,
          paddingRight: 3,
        };
        внутри.push(
          ВЕБ
            ? createElement('span', { key: i, 'data-testid': `аят-слово-${номер}`, title: подписьСлова?.(номер), style: стиль }, кусокКорана(шрифт, т.текст))
            : (
                <Text key={i} testID={`аят-слово-${номер}`} accessibilityLabel={подписьСлова?.(номер)} style={стиль as TextStyle}>
                  {кусокКорана(шрифт, т.текст)}
                </Text>
              ),
        );
      } else внутри.push(т.текст);
      if (i < по) внутри.push(' '); // пробел перед знаком — в том же узле, что и знак
    }
    // Склеить соседние строки в один текстовый узел (знак не отрывается от пробела перед ним).
    const склеено: ReactNode[] = [];
    for (const д of внутри) {
      const последний = склеено[склеено.length - 1];
      if (typeof д === 'string' && typeof последний === 'string') склеено[склеено.length - 1] = последний + д;
      else склеено.push(д);
    }
    // Подстройка для мединского шрифта — после склейки: пробел и знак остаются в одном узле.
    const показ = склеено.map((д, к) => (typeof д === 'string' ? кусокКорана(шрифт, д, 'к' + к) : д));
    const стильГруппы = {
      ...(ВЕБ ? { whiteSpace: 'nowrap' } : null),
      ...(часть === null ? null : вЧасти ? { backgroundColor: цвет.поверхностьАкцент, borderRadius: радиус.s } : { color: цвет.текстВторой }),
    };
    дети.push(
      ВЕБ
        ? createElement('span', { key: 'г' + г, 'data-group': '', style: стильГруппы }, ...показ)
        : (
            <Text key={'г' + г} style={стильГруппы as TextStyle}>
              {показ}
            </Text>
          ),
    );
    if (г < группы.length - 1) дети.push(' ');
  });

  return (
    <Text
      {...ВЕБ_АР}
      accessibilityLanguage="ar"
      selectable
      testID={testID}
      style={{
        flex: 1,
        minWidth: 0,
        fontFamily: шрифт.семейство,
        fontSize: кегль,
        lineHeight: межстрочный,
        color: цвет.арабский,
        textAlign: выравнивание,
        writingDirection: 'rtl',
        opacity: шрифт.готов ? 1 : 0,
      }}
    >
      {дети}
    </Text>
  );
}
