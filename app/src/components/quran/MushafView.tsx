function Листание({ индексСур, мусхаф, сура, аят, вид }: { индексСур: ИндексСур; мусхаф: ИндексМусхафа; сура: number; аят: number | null; вид: Exclude<ВидЧтения, 'обычный'> }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const уменьшить = useУменьшитьДвижение();
  const { перейти, обновитьПараметры } = useНавигация();
  const { ночьЦвета } = useВидЧтения();
  const ночь = вид === 'ночной';
  const сЦветами = вид === 'таджвид' || (ночь && ночьЦвета);
  const п = ночь ? НОЧЬ : БУМАГА;
  const всего = мусхаф.страницы.length;
  const аятов = useCallback((с: number) => индексСур.суры[с - 1]?.аятов ?? 1, [индексСур]);

  const [страница, установитьСтраницу] = useState(() => {
    const а = аят !== null && аят <= аятов(сура) ? аят : 1;
    return страницаАята(мусхаф.страницы, сура, а);
  });
  const [выбран, установитьВыбран] = useState<string | null>(null);
  const участки = useMemo(() => участкиСтраницы(мусхаф.страницы, страница, аятов), [мусхаф, страница, аятов]);

  // Суры страницы (1–4 файла; обычно уже в кэше) и разметка таджвида, если нужны цвета.
  const ключ = страница + ':' + (сЦветами ? 'ц' : '');
  const [данные, установитьДанные] = useState<{ ключ: string; д: ДанныеСтраницы | null; нет: { нетСвязи: boolean; причина: 'нет-связи' | 'сбой-сервера' | 'нет-файла' | 'не-прошло-сверку' } | null }>(() => ({ ключ: '', д: null, нет: null }));
  const [попытка, установитьПопытку] = useState(0);
  useEffect(() => {
    let живой = true;
    (async () => {
      const суры = new Map<number, СураКорана>();
      const цвета = new Map<number, ЦветаСуры | null>();
      for (const у of участки) {
        const р = await загрузитьСуру(у.сура);
        if (!р.ок) {
          if (живой) установитьДанные({ ключ, д: null, нет: { нетСвязи: р.причина === 'нет-связи' || р.причина === 'сбой-сервера', причина: р.причина } });
          return;
        }
        суры.set(у.сура, р.данные);
        if (сЦветами) {
          const м = await загрузитьРазметкуСуры(у.сура);
          цвета.set(у.сура, м.ок ? цветаСуры(р.данные, м.данные, индексСур.суры[у.сура - 1].sha256) : null);
        }
      }
      if (живой) установитьДанные({ ключ, д: { суры, цвета }, нет: null });
      // Следующая страница — заранее (свайп без ожидания).
      for (const у of участкиСтраницы(мусхаф.страницы, Math.min(всего, страница + 1), аятов)) if (!сураИзКэша(у.сура)) void загрузитьСуру(у.сура);
    })();
    return () => {
      живой = false;
    };
  }, [ключ, попытка]); // eslint-disable-line react-hooks/exhaustive-deps

  const свиток = useRef<ComponentRef<typeof ScrollView>>(null);
  const листать = useCallback(
    (н: number) => {
      const новая = Math.max(1, Math.min(всего, н));
      if (новая === страница) return;
      установитьСтраницу(новая);
      установитьВыбран(null);
      свиток.current?.scrollTo({ y: 0, animated: false });
      const [с, а] = мусхаф.страницы[новая - 1];
      обновитьПараметры('сура', { номер: с, аят: а });
      запомнитьЧтение(с, а);
    },
    [всего, страница, мусхаф, обновитьПараметры],
  );

  useEffect(() => {
    const [с, а] = мусхаф.страницы[страница - 1];
    запомнитьЧтение(с, а, true);
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  // Свайп по странице и ← / → (в арабской книге следующая страница — слева: палец слева направо — следующая).
  const лист = useRef<ComponentRef<typeof View>>(null);
  useEffect(() => {
    if (!ВЕБ || typeof document === 'undefined') return;
    const э = лист.current as unknown as HTMLElement | null;
    let старт: { x: number; y: number; t: number } | null = null;
    const вниз = (е: PointerEvent) => {
      старт = { x: е.clientX, y: е.clientY, t: Date.now() };
    };
    const вверх = (е: PointerEvent) => {
      const с = старт;
      старт = null;
      if (!с || Date.now() - с.t > 800 || String(globalThis.getSelection?.() ?? '').length > 0) return;
      const dx = е.clientX - с.x;
      const dy = е.clientY - с.y;
      if (Math.abs(dx) < 60 || Math.abs(dx) < 2 * Math.abs(dy)) return;
      листать(страница + (dx > 0 ? 1 : -1));
    };
    const клавиша = (е: KeyboardEvent) => {
      const цель = е.target as HTMLElement | null;
      if (!э || !э.isConnected || э.offsetParent === null || /^(INPUT|TEXTAREA|SELECT)$/.test(цель?.tagName ?? '')) return;
      if (е.key === 'ArrowLeft') листать(страница + 1);
      else if (е.key === 'ArrowRight') листать(страница - 1);
    };
    э?.addEventListener('pointerdown', вниз);
    э?.addEventListener('pointerup', вверх);
    document.addEventListener('keydown', клавиша);
    return () => {
      э?.removeEventListener('pointerdown', вниз);
      э?.removeEventListener('pointerup', вверх);
      document.removeEventListener('keydown', клавиша);
    };
  }, [листать, страница]);

  // Плеер: читаемый аят подсвечен; чтец ушёл со страницы, на которой был, — перелистнуть.
  const снимок = useПлеер();
  const тек = снимок.состояние !== 'стоп' && снимок.текущий && !снимок.текущий.бисмилла ? снимок.текущий : null;
  const играет = тек ? тек.сура + ':' + тек.аят : null;
  const былаСтраница = useRef<number | null>(null);
  useEffect(() => {
    if (!тек) {
      былаСтраница.current = null;
      return;
    }
    const н = страницаАята(мусхаф.страницы, тек.сура, тек.аят);
    if (былаСтраница.current === страница && н !== страница) листать(н);
    былаСтраница.current = н;
  }, [играет]); // eslint-disable-line react-hooks/exhaustive-deps

  const действия = useRef<ComponentRef<typeof View>>(null);
  useEffect(() => {
    if (!выбран || !ВЕБ) return;
    const т = setTimeout(() => (действия.current as unknown as HTMLElement | null)?.scrollIntoView?.({ block: 'nearest', behavior: уменьшить ? 'auto' : 'smooth' }), 30);
    return () => clearTimeout(т);
  }, [выбран, уменьшить]);

  const д = данные.ключ === ключ ? данные.д : null;
  const безЦветов = !!д && сЦветами && [...д.цвета.values()].some((ц) => ц === null);
  const хизб = хизбСтраницы(мусхаф, страница);
  const [вс, ва] = выбран ? выбран.split(':').map(Number) : [0, 0];

  return (
    <ScrollView
      ref={свиток}
      testID="мусхаф-прокрутка"
      style={{ flex: 1, width: '100%' }}
      contentContainerStyle={{ width: '100%', maxWidth: ШИРИНА_КОЛОНКИ, alignSelf: 'center', padding: отступ.l, paddingBottom: отступ.xxl, gap: отступ.m }}
      {...(ВЕБ ? ({ tabIndex: 0, 'aria-label': т('где', { н: страница, всего }) } as object) : null)}
    >
      <ВыборВидаЧтения вид="шапка" />
      {сЦветами ? <ПлашкаТаджвида /> : null}
      <View testID="мусхаф" ref={лист} style={{ gap: отступ.m, ...(ВЕБ ? ({ touchAction: 'pan-y' } as object) : null) }}>
        <Лист п={п} страница={страница}>
          <View testID="мусхаф-колонтитул" style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', gap: отступ.s, minHeight: 28 }}>
            <Текст вид="мелкий" цвет={п.второй} testID="мусхаф-джуз" табличные>
              {т('джуз', { д: джузСтраницы(мусхаф, страница), х: хизб.хизб })}
            </Текст>
            <Text {...((ВЕБ ? { lang: 'ar', dir: 'rtl' } : {}) as object)} style={{ fontFamily: ШРИФТ_АРАБСКИЙ, fontSize: 18, lineHeight: 28, color: п.второй, textAlign: 'right', flexShrink: 1 }}>
              {участки.map((у) => индексСур.суры[у.сура - 1].имя).join(' · ')}
            </Text>
          </View>
          {д ? (
            участки.map((у) => <УчастокСтраницы key={у.сура} у={у} сура={д.суры.get(у.сура)!} цвета={сЦветами ? (д.цвета.get(у.сура) ?? null) : null} ночь={ночь} п={п} центр={страница <= 2} выбран={выбран} играет={играет} выбрать={установитьВыбран} />)
          ) : данные.ключ === ключ && данные.нет ? (
            <ТекстКоранаНедоступен состояние={{ ...данные.нет, повторить: () => установитьПопытку((x) => x + 1) }} />
          ) : (
            <Текст вид="второй" цвет={п.второй}>
              {т('загрузка')}
            </Текст>
          )}
          <View style={{ alignItems: 'center' }} testID="мусхаф-номер" accessibilityLabel={т('где', { н: страница, всего })}>
            <View style={{ minWidth: 40, height: 30, paddingHorizontal: 10, borderRadius: 15, borderWidth: 1, borderColor: п.рамка, alignItems: 'center', justifyContent: 'center' }}>
              <Text {...((ВЕБ ? { lang: 'ar', 'aria-hidden': true } : {}) as object)} style={{ fontFamily: ШРИФТ_АРАБСКИЙ, fontSize: 18, lineHeight: 26, color: п.знак }}>
                {арабскиеЦифры(страница)}
              </Text>
            </View>
          </View>
        </Лист>
        {безЦветов ? (
          <Текст вид="мелкий" testID="мусхаф-без-цветов">
            {т('безЦветов')}
          </Текст>
        ) : null}
        {выбран ? (
          <View ref={действия} testID="мусхаф-действия" style={{ gap: отступ.s, padding: отступ.m, borderRadius: 12, backgroundColor: цвет.поверхностьАкцент }}>
            <Текст вид="метка">{т('аят', { с: вс, а: ва })}</Текст>
            <КнопкаСлушать сура={вс} сАята={ва} надпись={т('слушать')} testID="мусхаф-слушать" />
            <Кнопка
              вид="основная"
              значок="микрофон"
              надпись={т('записать')}
              приНажатии={() => {
                обновитьПараметры('сура', { номер: вс, аят: ва });
                запомнитьВозвратКАяту(вс, ва);
                перейти('проверкаАята', { номер: вс, аят: ва });
              }}
              testID="мусхаф-записать"
            />
          </View>
        ) : null}
        <View style={{ flexDirection: 'row', gap: отступ.s }}>
          <View style={{ flex: 1 }}>
            <Кнопка вид="вторичная" значок="назад" надпись={т('следующая')} отключена={страница >= всего} приНажатии={() => листать(страница + 1)} testID="мусхаф-следующая" />
          </View>
          <View style={{ flex: 1 }}>
            <Кнопка вид="вторичная" значок="вперёд" надпись={т('предыдущая')} отключена={страница <= 1} приНажатии={() => листать(страница - 1)} testID="мусхаф-предыдущая" />
          </View>
        </View>
        <Text testID="мусхаф-где" {...((ВЕБ ? { 'aria-live': 'polite' } : {}) as object)} style={{ textAlign: 'center', color: цвет.текстВторой, fontSize: 13, fontVariant: ['tabular-nums'] }}>
          {т('где', { н: страница, всего })}
        </Text>
        {страница < всего ? <Кнопка вид="тихая" значок="вниз" надпись={т('дальше')} приНажатии={() => листать(страница + 1)} testID="мусхаф-дальше" /> : null}
      </View>
      {сЦветами ? <ЛегендаТаджвида ночь={ночь} плашка={false} /> : null}
      <Текст вид="мелкий">{т('подсказка')}</Текст>
      <Текст вид="мелкий" testID="мусхаф-источник">
        {т('источник')}
      </Текст>
    </ScrollView>
  );
}

/** Лист «бумаги»: двойная рамка (рамка2 снаружи, золото внутри) и восьмиконечные звёзды в углах — своё SVG. */
function Лист({ п, страница, children }: { п: Палитра; страница: number; children: ReactNode }) {
  const { отступ } = useТема();
  const угол = (стиль: object, к: string) => (
    <View key={к} style={[{ position: 'absolute', width: 22, height: 22 }, стиль]} {...({ 'aria-hidden': true } as object)}>
      <Svg width={22} height={22} viewBox="0 0 22 22">
        <Path d="M4 4H18V18H4Z" fill={п.фон} stroke={п.рамка} strokeWidth={1.2} />
        <Path d="M11 1.1L20.9 11L11 20.9L1.1 11Z" fill={п.фон} stroke={п.рамка2} strokeWidth={1.2} />
        <Path d="M11 7L15 11L11 15L7 11Z" fill={п.рамка} />
      </Svg>
    </View>
  );
  return (
    <View testID="мусхаф-страница" {...({ dataSet: { page: страница } } as object)} style={{ backgroundColor: п.фон, borderWidth: 2, borderColor: п.рамка2, borderRadius: 4, padding: 4 }}>
      <View style={{ borderWidth: 1, borderColor: п.рамка, paddingHorizontal: отступ.m, paddingVertical: отступ.m + 2, gap: отступ.s, backgroundColor: п.фон }}>{children}</View>
      {угол({ top: -3, left: -3 }, 'а')}
      {угол({ top: -3, right: -3 }, 'б')}
      {угол({ bottom: -3, left: -3 }, 'в')}
      {угол({ bottom: -3, right: -3 }, 'г')}
    </View>
  );
}

