/**
 * «Шрифт Корана»: Мединский мусхаф · Классический (владелец 28.11.2026: «У меня уже два брата спросили, чтобы шрифт был
 * такой. Поставь выбор шрифта, по умолчанию — этот. Пусть наш тоже будет»). Выбор — quran/quranScript.ts (на устройстве;
 * с аккаунтом — в настройках аккаунта). Меню вида суры (⚙) и «Ещё» → «Настройки».
 *
 * Контракт: <ВыборШрифтаКорана testID? /> — подпись и две вкладки-выбора (radiogroup).
 * testID: шрифт-корана (группа), шрифт-мединский, шрифт-классический. kk, uz — черновик для редактора-носителя.
 */
import { View } from 'react-native';
import { создатьСловарь, useСловарь } from '../../i18n';
import { ШРИФТЫ_КОРАНА, установитьШрифтКорана, useВыборШрифтаКорана, type ШрифтКорана } from '../../quran/quranScript';
import { useТема } from '../../theme';
import { Вкладки } from '../Tabs';
import { Текст } from '../Text';

const СЛОВАРЬ = создатьСловарь({
  ru: { подпись: 'Шрифт Корана', мединский: 'Мединский мусхаф', классический: 'Классический' },
  kk: { подпись: 'Құран қаріпі', мединский: 'Мәдина мұсхафы', классический: 'Классикалық' },
  uz: { подпись: 'Qurʼon shrifti', мединский: 'Madina mushafi', классический: 'Klassik' },
  en: { подпись: 'Quran font', мединский: 'Madinah Mushaf', классический: 'Classic' },
}, 'components/quran/QuranFontPicker');

export function ВыборШрифтаКорана({ testID = 'шрифт-корана' }: { testID?: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const выбор = useВыборШрифтаКорана();
  return (
    <View style={{ gap: отступ.xs, alignSelf: 'stretch' }}>
      <Текст вид="мелкий">{т('подпись')}</Текст>
      <Вкладки
        подпись={т('подпись')}
        роль="выбор"
        testID={testID}
        вкладки={ШРИФТЫ_КОРАНА.map((ш) => ({ ключ: ш, надпись: т(ш), testID: 'шрифт-' + ш }))}
        выбрана={выбор}
        приВыборе={(к) => установитьШрифтКорана(к as ШрифтКорана)}
      />
    </View>
  );
}
