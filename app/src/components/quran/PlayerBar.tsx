/**
 * Мини-плеер чтения кари, кнопка «Слушать» и строка «почему не играет» (плеер — audio/player.ts).
 *
 * Решение владельца 19.11.2026: «добавить плеер нужно, чтобы можно было слушать, и когда экран выключен».
 * Правило 3: только записи кари по договору; пока разрешения нет — вместо ▶ строка «Аудио появится после
 * разрешения кари» (без сроков). Правило 9: в подписях — сура и аят номером/транслитом, без арабского текста.
 * kk-тексты — черновик (audio/texts.ts).
 *
 * Контракт:
 *   <МиниПлеер /> — без пропсов; рисует App.tsx НАД <НижнееМеню /> обычным элементом колонки (не position: fixed).
 *     Пока плеер стоит («стоп») — ничего не рисует. Ревью 19.11.2026 (панель в 125 px съедала 40% экрана 360×640):
 *     по умолчанию СВЁРНУТ — одна строка ≈ 60 px: название «Сура аль-Бакара · аят 255 (повтор 2 из 3)» и под ним
 *     кари/состояние (нажатие по ним — развернуть), ▶/❚❚ (при ошибке — «Повторить») и ✕ «остановить». Развёрнутый —
 *     ещё ряд: ×N (повтор аята 1/3/5, подпись «Аят ×3»), «предыдущий», «следующий», «по кругу» (свой значок петли,
 *     подпись «Отрезок»). При появлении — одно polite-объявление «Играет: Сура …, аят 1. Чтение: <кари>» (смену
 *     аятов не объявляем). Синхронизирует язык подписей Media Session.
 *   <КнопкаСлушать сура сАята? поАят? надпись? вид?='кнопка'|'значок' testID? /> — начать очередь из нажатия
 *     (вид «значок» — маленькая кнопка ▶ у аята «слушать с этого аята»). Нет источника: «кнопка» → <СтрокаБезЗвука>,
 *     «значок» → ничего (строку экран показывает один раз сверху).
 *   <СтрокаБезЗвука /> — причина (нет разрешения кари / не на этом сайте / не поддерживается) или null, если играет.
 * Без звуков интерфейса, вибрации, анимации, счётчиков и наград. Цели нажатия ≥ 48 px.
 * testID: мини-плеер, мини-плеер-развернуть, мини-плеер-название, мини-плеер-состояние, мини-плеер-объявление,
 *         плеер-повтор-аята, плеер-назад, плеер-играть, плеер-вперёд, плеер-по-кругу, плеер-стоп, слушать, строка-без-звука.
 */
import { useEffect, useRef, useState } from 'react';
import { Platform, Pressable, StyleSheet, View } from 'react-native';
import {
  ПОВТОРЫ_АЯТА,
  плеер,
  причинаБезЗвука,
  установитьЯзыкПлеера,
  useПлеер,
  type СнимокПлеера,
  type ИсточникЧтения,
} from '../../audio/player';
import { ТЕКСТЫ_ПЛЕЕРА, названиеДляСессии, языкПлеера, type КлючПлеера } from '../../audio/texts';
import type { ИмяЗначка } from '../../design/icons';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useИндексСур } from '../../quran/data';
import { useТема } from '../../theme';
import { Кнопка } from '../Button';
import { Значок } from '../Icon';
import { Текст } from '../Text';

const СЛОВАРЬ = создатьСловарь<КлючПлеера>(ТЕКСТЫ_ПЛЕЕРА);
const ВЕБ = Platform.OS === 'web';

/** Следующий вариант повтора аята по кругу: ×1 → ×3 → ×5 → ×1. */
function следующийПовтор(сейчас: number): number {
  const и = ПОВТОРЫ_АЯТА.indexOf(сейчас);
  return ПОВТОРЫ_АЯТА[(и + 1) % ПОВТОРЫ_АЯТА.length] ?? 1;
}

function useЯзыкПлеера() {
  const язык = языкПлеера(useПеревод().язык);
  useEffect(() => {
    установитьЯзыкПлеера(язык);
  }, [язык]);
  return язык;
}

export function МиниПлеер() {
  useЯзыкПлеера();
  const снимок = useПлеер();
  if (снимок.состояние === 'стоп') return null;
  return <Панель снимок={снимок} />;
}

/** Развёрнут ли плеер — помним на время страницы (между экранами), по умолчанию свёрнут. */
let развёрнутПоУмолчанию = false;

function Панель({ снимок }: { снимок: СнимокПлеера<ИсточникЧтения> }) {
  const т = useСловарь(СЛОВАРЬ);
  const язык = useЯзыкПлеера();
  const { цвет, отступ } = useТема();
  const индекс = useИндексСур();
  const [развёрнут, установитьРазвёрнут] = useState(развёрнутПоУмолчанию);
  const { состояние, текущий, ошибка, источник, очередь } = снимок;

  const транслит =
    текущий && индекс.состояние === 'есть' ? (индекс.данные.суры.find((с) => с.сура === текущий.сура)?.транслит[язык] ?? null) : null;
  const название = текущий
    ? названиеДляСессии({ язык, сура: текущий.сура, аят: текущий.аят, транслит, бисмилла: текущий.бисмилла, повтор: текущий.повтор, из: текущий.из })
    : т('плеер');
  const кари = источник ? т('кари', { кари: источник.кари[язык] }) : null;
  const строкаСостояния =
    состояние === 'ошибка'
      ? т(('ошибка.' + (ошибка ?? 'нет-файла')) as КлючПлеера)
      : [кари, состояние === 'загрузка' ? т('состояние.загрузка') : состояние === 'пауза' ? т('состояние.пауза') : null].filter(Boolean).join(' · ');
  const играет = состояние === 'играет' || состояние === 'загрузка';
  const можноПовторить = состояние === 'ошибка' && ошибка !== 'нет-источника' && !!очередь;
  const естьОчередь = !!очередь;

  // Одно объявление при появлении плеера (не на каждый аят): «Играет: Сура …, аят 1. Чтение: …».
  const [объявление, установитьОбъявление] = useState('');
  const объявлено = useRef(false);
  useEffect(() => {
    if (объявлено.current || !текущий || состояние === 'ошибка') return;
    объявлено.current = true;
    установитьОбъявление(т('объявление', { название, кари: кари ?? '' }).trim());
  }, [текущий, состояние, название, кари, т]);

  function переключитьРазвёрнут() {
    развёрнутПоУмолчанию = !развёрнут;
    установитьРазвёрнут(!развёрнут);
  }

  return (
    <View
      testID="мини-плеер"
      {...(ВЕБ ? { role: 'region' as const } : {})}
      accessibilityLabel={т('плеер')}
      style={[стили.панель, { backgroundColor: цвет.поверхность, borderTopColor: цвет.граница, paddingHorizontal: отступ.m, gap: отступ.xs }]}
    >
      <Текст
        testID="мини-плеер-объявление"
        accessibilityLiveRegion="polite"
        {...(ВЕБ ? ({ role: 'status' } as object) : null)}
        стиль={стили.скрыто}
      >
        {объявление}
      </Текст>
      <View style={стили.шапка}>
        <Pressable
          accessibilityRole="button"
          accessibilityLabel={(развёрнут ? т('свернуть') : т('развернуть')) + '. ' + название}
          aria-expanded={развёрнут}
          onPress={переключитьРазвёрнут}
          testID="мини-плеер-развернуть"
          style={({ pressed }) => [стили.название, { opacity: pressed ? 0.7 : 1 }]}
        >
          <Текст вид="метка" numberOfLines={1} testID="мини-плеер-название">
            {название}
          </Текст>
          <Текст
            вид="мелкий"
            numberOfLines={1}
            testID="мини-плеер-состояние"
            {...(состояние === 'ошибка' ? { accessibilityLiveRegion: 'polite' as const, role: 'status' as const } : {})}
          >
            {строкаСостояния}
          </Текст>
        </Pressable>
        {можноПовторить ? (
          <КнопкаЗначок значок="повтор" подпись={т('повторить')} приНажатии={() => плеер.продолжить()} главная testID="плеер-играть" />
        ) : (
          <КнопкаЗначок
            значок={играет ? 'пауза' : 'играть'}
            подпись={играет ? т('пауза') : т('продолжить')}
            приНажатии={() => плеер.переключить()}
            главная
            отключена={состояние === 'ошибка'}
            testID="плеер-играть"
          />
        )}
        <КнопкаЗначок значок="закрыть" подпись={т('стоп')} приНажатии={() => плеер.стоп()} testID="плеер-стоп" />
      </View>
      {развёрнут && естьОчередь ? (
        <View style={стили.ряд}>
          <View style={стили.сПодписью}>
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={т('повтор-аята', { n: снимок.повторАята })}
              accessibilityHint={т('повтор-аята-подсказка')}
              onPress={() => плеер.установитьПовтор(следующийПовтор(снимок.повторАята))}
              testID="плеер-повтор-аята"
              style={({ pressed }) => [
                стили.чип,
                {
                  borderColor: снимок.повторАята > 1 ? цвет.акцент : цвет.границаЭлемента,
                  backgroundColor: снимок.повторАята > 1 ? цвет.акцентМягкий : 'transparent',
                  opacity: pressed ? 0.7 : 1,
                },
              ]}
            >
              <Текст вид="метка" цвет={снимок.повторАята > 1 ? цвет.акцент : цвет.текст} табличные>
                {'×' + снимок.повторАята}
              </Текст>
            </Pressable>
            <Текст вид="мелкий" табличные стиль={стили.подпись} {...({ 'aria-hidden': true } as object)}>
              {т('подпись-повтор', { n: снимок.повторАята })}
            </Текст>
          </View>
          <КнопкаЗначок значок="назад" подпись={т('назад')} приНажатии={() => плеер.предыдущий()} testID="плеер-назад" />
          <КнопкаЗначок
            значок="вперёд"
            подпись={т('вперёд')}
            приНажатии={() => плеер.следующий()}
            отключена={!снимок.можноВперёд}
            testID="плеер-вперёд"
          />
          <View style={стили.сПодписью}>
            <Pressable
              accessibilityRole="switch"
              accessibilityState={{ checked: !!очередь?.повторОтрезка }}
              aria-checked={!!очередь?.повторОтрезка}
              accessibilityLabel={т('по-кругу')}
              accessibilityHint={т('по-кругу-подсказка')}
              onPress={() => плеер.установитьПовторОтрезка(!очередь?.повторОтрезка)}
              testID="плеер-по-кругу"
              style={({ pressed }) => [
                стили.чип,
                {
                  borderColor: очередь?.повторОтрезка ? цвет.акцент : цвет.границаЭлемента,
                  backgroundColor: очередь?.повторОтрезка ? цвет.акцентМягкий : 'transparent',
                  opacity: pressed ? 0.7 : 1,
                },
              ]}
            >
              <Значок имя="по-кругу" размер={20} цвет={очередь?.повторОтрезка ? цвет.акцент : цвет.текст} толщина={2} />
            </Pressable>
            <Текст вид="мелкий" стиль={стили.подпись} {...({ 'aria-hidden': true } as object)}>
              {т('подпись-отрезок')}
            </Текст>
          </View>
        </View>
      ) : null}
    </View>
  );
}

function КнопкаЗначок({
  значок,
  подпись,
  приНажатии,
  главная = false,
  отключена = false,
  testID,
}: {
  значок: ИмяЗначка;
  подпись: string;
  приНажатии: () => void;
  главная?: boolean;
  отключена?: boolean;
  testID?: string;
}) {
  const { цвет, радиус } = useТема();
  const размер = 48;
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={подпись}
      accessibilityState={{ disabled: отключена }}
      aria-disabled={отключена}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      style={({ pressed }) => [
        стили.круг,
        {
          width: размер,
          height: размер,
          borderRadius: радиус.круг,
          backgroundColor: главная ? (pressed ? цвет.акцентНажат : цвет.акцент) : 'transparent',
          opacity: отключена ? 0.4 : pressed && !главная ? 0.7 : 1,
        },
      ]}
    >
      <Значок имя={значок} размер={главная ? 24 : 22} цвет={главная ? цвет.акцентТекст : цвет.текст} толщина={2} />
    </Pressable>
  );
}

export type СвойстваКнопкиСлушать = {
  сура: number;
  сАята?: number;
  поАят?: number;
  /** Подпись кнопки; по умолчанию «Слушать суру» (с 1-го аята) или «Слушать с аята N». */
  надпись?: string;
  вид?: 'кнопка' | 'значок';
  testID?: string;
};

/** Начать чтение кари из нажатия. Источника нет — причина (вид «кнопка») или ничего (вид «значок»). */
export function КнопкаСлушать({ сура, сАята = 1, поАят, надпись, вид = 'кнопка', testID = 'слушать' }: СвойстваКнопкиСлушать) {
  const т = useСловарь(СЛОВАРЬ);
  const язык = useЯзыкПлеера();
  const снимок = useПлеер();
  if (!снимок.источник) return вид === 'кнопка' ? <СтрокаБезЗвука /> : null;
  const подпись = надпись ?? (сАята > 1 ? т('слушать-с-аята', { аят: сАята }) : т('слушать-суру'));
  const нажать = () => {
    установитьЯзыкПлеера(язык);
    // Синхронно из нажатия: первый play() браузеры разрешают только из жеста.
    плеер.играть({ сура, сАята, поАят });
  };
  if (вид === 'значок') return <КнопкаЗначок значок="играть" подпись={подпись} приНажатии={нажать} testID={testID} />;
  return <Кнопка надпись={подпись} значок="играть" вид="вторичная" приНажатии={нажать} testID={testID} />;
}

/** Почему чтение кари не играет — одной спокойной строкой (без сроков). null — играет. */
export function СтрокаБезЗвука() {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const причина = причинаБезЗвука();
  if (!причина) return null;
  return (
    <View style={[стили.строка, { gap: отступ.s }]} testID="строка-без-звука">
      <Значок имя="аудио" размер={20} цвет={цвет.текстВторой} />
      <Текст вид="второй" стиль={{ flex: 1 }}>
        {т(('причина.' + причина) as КлючПлеера)}
      </Текст>
    </View>
  );
}

const стили = StyleSheet.create({
  панель: { borderTopWidth: 1, paddingTop: 4, paddingBottom: 4 },
  шапка: { flexDirection: 'row', alignItems: 'center', gap: 4, minHeight: 52 },
  название: { flex: 1, minWidth: 0, minHeight: 48, justifyContent: 'center', paddingRight: 4 },
  ряд: { flexDirection: 'row', alignItems: 'flex-start', justifyContent: 'space-between', paddingBottom: 2 },
  сПодписью: { alignItems: 'center', gap: 2 },
  подпись: { fontSize: 12, lineHeight: 14 },
  скрыто: { position: 'absolute', width: 1, height: 1, overflow: 'hidden', opacity: 0 },
  круг: { alignItems: 'center', justifyContent: 'center' },
  чип: { minWidth: 48, height: 48, paddingHorizontal: 10, borderRadius: 999, borderWidth: 1.5, alignItems: 'center', justifyContent: 'center' },
  строка: { flexDirection: 'row', alignItems: 'center' },
});
