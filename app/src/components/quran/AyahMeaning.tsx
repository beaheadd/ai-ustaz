/** Стиль текста слоя: мельче арабского, шрифт интерфейса, направление и шрифт — по языку издания. */
function стильСлоя(язык: string, мелко: boolean, цвет: string) {
  const кегль = мелко ? 15 : 16;
  const строка = мелко ? 23 : 25;
  const урду = язык === 'ur';
  return {
    fontFamily: урду ? ШРИФТ_УРДУ : ШРИФТ_ИНТЕРФЕЙСА,
    fontSize: урду ? кегль + 1 : кегль,
    lineHeight: урду ? Math.round(строка * МЕЖСТРОЧНЫЙ_УРДУ) : строка,
    color: цвет,
    textAlign: (справаНалево(язык) ? 'right' : 'left') as 'right' | 'left',
    writingDirection: (справаНалево(язык) ? 'rtl' : 'ltr') as 'rtl' | 'ltr',
  };
}

export function ПодписьСлоя({ индекс, testID }: { индекс: ИндексПеревода; testID: string }) {
  const т = useСловарь(СЛОВАРЬ_СМЫСЛА);
  const { цвет, отступ } = useТема();
  const подпись = т('перевод', { автор: индекс.автор, источник: индекс.источник });
  const адрес = 'https://' + индекс.ссылка;
  const веб = ВЕБ ? ({ href: адрес, hrefAttrs: { target: '_blank', rel: 'noopener noreferrer' } } as object) : {};
  return (
    <View style={{ gap: отступ.xs }}>
      <Текст вид="мелкий" testID={testID}>
        {подпись}
        {индекс.версия ? ' · ' + т('версия', { версия: индекс.версия }) : ''}
        {' · '}
        <Текст
          вид="мелкий"
          {...веб}
          цвет={цвет.акцент}
          стиль={{ textDecorationLine: 'underline' }}
          accessibilityRole="link"
          onPress={ВЕБ ? undefined : () => void Linking.openURL(адрес)}
          testID={testID + '-ссылка'}
        >
          {т('открытьИсточник', { источник: индекс.источник })}
        </Текст>
      </Текст>
      {индекс.одобрено ? null : (
        <View style={{ alignSelf: 'flex-start' }}>
          <Плашка вид="черновик" малая надпись={т('черновикПеревода')} testID={testID.replace(/-подпись$/, '') + '-черновик'} />
        </View>
      )}
    </View>
  );
}

export function ТекстСлоя({ аят, язык, мелко = false, testID }: { аят: АятПеревода; язык: string; мелко?: boolean; testID: string }) {
  const т = useСловарь(СЛОВАРЬ_СМЫСЛА);
  const { цвет, отступ } = useТема();
  const [сноски, установитьСноски] = useState(false);
  const атрибуты = ВЕБ ? ({ lang: язык, dir: справаНалево(язык) ? 'rtl' : 'ltr' } as object) : {};
  return (
    <View style={{ gap: отступ.xs }}>
      <Text {...атрибуты} selectable testID={testID} style={стильСлоя(язык, мелко, цвет.текстВторой)}>
        {аят.текст}
      </Text>
      {аят.сноски ? (
        <>
          <Pressable
            accessibilityRole="button"
            {...((ВЕБ ? { 'aria-expanded': сноски } : { accessibilityState: { expanded: сноски } }) as object)}
            onPress={() => установитьСноски((с) => !с)}
            testID={testID + '-сноски'}
            hitSlop={6}
            style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: 4, alignSelf: 'flex-start', minHeight: 32, opacity: pressed ? 0.6 : 1 })}
          >
            <Значок имя={сноски ? 'вверх' : 'вниз'} размер={14} цвет={цвет.акцент} />
            <Текст вид="мелкий" цвет={цвет.акцент}>
              {сноски ? т('скрытьСноски') : т('сноски')}
            </Текст>
          </Pressable>
          {сноски ? (
            <Text {...атрибуты} selectable testID={testID + '-сноски-текст'} style={[стильСлоя(язык, true, цвет.текстВторой), { fontSize: язык === 'ur' ? 15 : 13, lineHeight: язык === 'ur' ? 28 : 19 }]}>
              {аят.сноски}
            </Text>
          ) : null}
        </>
      ) : null}
    </View>
  );
}

/** Состояние загрузки слоя: «Загружаем…», «Не загрузилось — Повторить», «не прошёл сверку». */
function СостояниеСлоя({ с, testID }: { с: { состояние: 'загрузка' } | { состояние: 'нет'; нетСвязи: boolean; причина: string }; testID: string }) {
  const т = useСловарь(СЛОВАРЬ_СМЫСЛА);
  const { цвет } = useТема();
  if (с.состояние === 'загрузка') {
    return (
      <Текст вид="мелкий" testID={testID + '-загрузка'}>
        {т('загрузка')}
      </Текст>
    );
  }
  return (
    <Текст вид="мелкий" цвет={цвет.текстВторой} testID={testID + '-нет'}>
      {с.нетСвязи ? т('нетСвязи') : с.причина === 'нет-файла' ? т('нетФайла') : т('неСверка')}
    </Текст>
  );
}

/** Есть ли перевод смыслов на языке интерфейса (ru, kk, ar — нет: кнопок «Перевод» там не показываем). */
export function useЕстьПеревод(): boolean {
  return useИзданиеЯзыка('перевод') !== null;
}

/**
 * Перевод аята на языке интерфейса. подпись — показать подпись издания над текстом (в листе и «Перевод»; под аятами
 * суры подпись одна — над окном аятов). Перевода на языке нет — ничего не рисует.
 */
export function СлойАята({ сура, аят, подпись = true, мелко = false, testID = 'слой-перевод' }: { сура: number; аят: number; подпись?: boolean; мелко?: boolean; testID?: string }) {
  const т = useСловарь(СЛОВАРЬ_СМЫСЛА);
  const { отступ } = useТема();
  const издание = useИзданиеЯзыка('перевод');
  const индекс = useИндексПеревода(издание);
  const данные = useСураПеревода(издание, сура);
  if (!издание) return null;
  const ид = testID;
  const состояние = индекс.состояние !== 'есть' ? индекс : данные.состояние !== 'есть' ? данные : null;
  return (
    <View testID={ид} style={{ gap: отступ.s }}>
      {подпись && индекс.состояние === 'есть' ? <ПодписьСлоя индекс={индекс.данные} testID={ид + '-подпись'} /> : null}
      {состояние ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s, flexWrap: 'wrap' }}>
          <СостояниеСлоя с={состояние as never} testID={ид} />
          {состояние.состояние === 'нет' && состояние.нетСвязи ? (
            <Pressable accessibilityRole="button" onPress={() => (индекс.состояние !== 'есть' ? индекс.повторить() : данные.повторить())} testID={ид + '-повторить'} hitSlop={6}>
              <Текст вид="метка">{т('повторить')}</Текст>
            </Pressable>
          ) : null}
        </View>
      ) : данные.состояние === 'есть' && данные.данные.аяты[аят - 1] ? (
        <ТекстСлоя аят={данные.данные.аяты[аят - 1]} язык={издание.язык} мелко={мелко} testID={ид + '-текст'} />
      ) : null}
    </View>
  );
}

/** «Перевод» аята из листа действий: арабский текст (Tanzil), пометка «не сам Коран», перевод смыслов с подписью. */
export function СмыслАята({ сура, аят }: { сура: СураКорана; аят: number }) {
  const т = useСловарь(СЛОВАРЬ_СМЫСЛА);
  const { цвет, отступ, радиус } = useТема();
  return (
    <View testID="смысл-аята" style={{ gap: отступ.m }}>
      <View testID="смысл-аята-арабский">
        <ТекстАята текст={сура.аяты[аят - 1].текст} />
      </View>
      <Текст вид="мелкий" testID="смысл-аята-не-коран">
        {т('неКоран')}
      </Текст>
      <View style={{ gap: отступ.s, padding: отступ.m, borderRadius: радиус.m, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность }}>
        <Текст вид="метка" accessibilityRole="header" уровень={2}>
          {т('заголовокПеревода')}
        </Текст>
        <СлойАята сура={сура.сура} аят={аят} testID="смысл-перевод" />
      </View>
    </View>
  );
}
