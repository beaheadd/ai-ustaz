/**
 * «Прочитать и записать» — запись и проверка ЛЮБОГО аята (экран #/quran/check, docs/дизайн/05 §2.4).
 *
 * Поток: аят (целиком; текущая часть выделена) → «Записать» (до 20 с) → «Послушать себя» → «Сравнить с кари»
 * (только если источник чтения разрешён и доступен здесь — плеер) → «Проверить» (только сборка своего домена: <ПроверкаГолосом>
 * сама молчит на batr.kz; там вместо неё честная строка «Проверка голосом появится на нашем отдельном сайте»).
 *
 * Контракт:
 *   <ПанельЧтенияАята сура аят текст бисмиллаПеред? часть? приСменеЧасти? кари? показатьАят? testID? />
 *   - текст — аят ДОСЛОВНО из копии для показа (useСура → данные.аяты[i].текст); панель его не меняет и не режет:
 *     рисует целиком токенами разборАята (склейка через пробел = строке), часть — подсветкой (правила 1 и 8).
 *   - бисмиллаПеред — у суры есть бисмилла и это аят 1: подсказка, что бисмилла в проверку не входит.
 *   - часть — номер с 1 (параметр p маршрута); вне диапазона — 1. приСменеЧасти(н) — экран пишет p в адрес; без него
 *     панель помнит часть сама. Части — quran-check (parts.ts, черновик политики, утверждает устаз).
 *   - кари — по умолчанию (не задано) панель сама берёт плеер (audio/player.ts): «Сравнить с кари» есть, только если
 *     доступныйИсточник() не null, и играет ВЕСЬ аят (у пофайлового набора частей нет); иначе — строка причины плеера
 *     (<СтрокаБезЗвука>: «Аудио появится после разрешения кари» / «…на отдельном сайте»). Свой { играет, играть(),
 *     стоп() } — для другого источника; null — без кари. Синтеза нет никогда (правило 3).
 *   - Запись и «Послушать себя» ставят плеер на паузу (микрофон не должен слышать кари), «Сравнить с кари»
 *     останавливает «Послушать себя».
 *   - показатьАят (по умолчанию true) — рисовать аят с подсветкой части и слов замечаний; false — экран рисует сам.
 *   Экспорт для экранов: АятСЧастью (тот же рисунок аята), УправлениеКари.
 * Приватность (CLAUDE.md «Данные и приватность»): запись только в памяти страницы; смена части, аята или уход —
 *   запись стирается (панель части перемонтируется по ключу). На сервер — только по «Проверить», только свой домен.
 * Правило 7: виды замечаний — по прогрессу (видыПоПрогрессу); подсказки — только «Проверьте себя»/«Подсказка».
 * testID: панель-чтения-аята, аят-с-частью, аят-слово-N (слово замечания), часть-аята, часть-назад, часть-вперёд,
 *   часть-вынужденная, бисмилла-не-входит, сравнить-с-кари, строка-без-звука (причина плеера) / кари-нет (кари={null});
 *   внутри — ПанельЗаписи (панель-записи, …, запись-инфо — строка приватности; на batr.kz — «…на отдельном сайте»).
 * Тексты интерфейса — ru и kk (kk — черновик для редактора-носителя). Новых религиозных текстов здесь нет.
 * Решение владельца 19.11.2026: «заходишь и читаешь любой аят, и записываешь голос и проверяешь, где ошибки».
 */
