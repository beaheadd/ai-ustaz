/**
 * Шрифт текста Корана на экране: «Мединский мусхаф» (KFGQPC Hafs 3.0, по умолчанию) или «Классический» (Amiri Quran).
 *
 * Владелец 28.11.2026: «Поставь выбор шрифта, по умолчанию — этот. Пусть наш тоже будет»; «Да, с подстройкой».
 *
 * Контракт:
 *   useШрифтКорана(коран = true) → { выбор, мединский, семейство, готов }:
 *     коран = false — текст не из Корана (буквы, слоги урока в <АрабскийТекст>): классический шрифт, мединский не грузится;
 *     выбор — что выбрал человек (quran/quranScript.ts);
 *     мединский — рисуем шрифтом KFGQPC (выбран И загружен): тогда строки идут через кусокКорана (подстройка показа);
 *     семейство — fontFamily для текста Корана; готов — шрифт загружен (пока нет — текст прозрачен и держит место).
 *   Мединский грузится лениво — при первом вызове хука, то есть при первом показе текста Корана (theme/quranFontLoader).
 *   Пока грузится — текст прозрачен не дольше ТЕРПЕНИЕ_МС; не загрузился (нет связи и нет в кэше) — классический
 *   шрифт и исходный текст без подстройки (Коран всегда читается), новая попытка — не раньше ПОВТОР_МС.
 *   кусокКорана(ш, строка, ключ?) — узел для отрисовки куска строки Корана: при мединском — подстроенная строка
 *     (quran/displayKfgqpc.ts), на вебе в <span data-o="исходная"> (если подстройка что-то поменяла), чтобы копирование,
 *     «Сообщить об ошибке» и проверки брали исходный текст (quran/originalText.ts); иначе — строка как есть.
 *     Резать строку (цвета таджвида, слова, группы) — ДО кусокКорана, по исходной строке.
 * Правило 1 CLAUDE.md: текст в хранилище и данные не меняются; подстройка — только при отрисовке этим шрифтом.
 */
import { createElement, useEffect, useSyncExternalStore, type Key, type ReactNode } from 'react';
import { Platform } from 'react-native';
import { подстроитьДляKfgqpc } from '../../quran/displayKfgqpc';
import { ШРИФТ_KFGQPC } from '../../quran/kfgqpcFont';
import { включитьКопированиеИсходного } from '../../quran/originalText';
import { useВыборШрифтаКорана, type ШрифтКорана } from '../../quran/quranScript';
import { ШРИФТ_АРАБСКИЙ, useАрабскийШрифтГотов } from '../../theme';
import { загрузитьШрифтKfgqpc, шрифтKfgqpcГотов } from '../../theme/quranFontLoader';

const ВЕБ = Platform.OS === 'web';
export const ТЕРПЕНИЕ_МС = 4000;
const ПОВТОР_МС = 30_000;

type Загрузка = 'нет' | 'грузится' | 'готов' | 'нет-шрифта';
let загрузка: Загрузка = шрифтKfgqpcГотов() ? 'готов' : 'нет';
let последняяНеудача = 0;
const слушатели = new Set<() => void>();
const сообщить = () => {
  for (const с of [...слушатели]) с();
};

function запросить(): void {
  if (загрузка === 'готов' || загрузка === 'грузится') return;
  if (загрузка === 'нет-шрифта' && Date.now() - последняяНеудача < ПОВТОР_МС) return;
  загрузка = 'грузится';
  // Не дольше ТЕРПЕНИЕ_МС держим текст прозрачным: дальше — классический шрифт, пока мединский не придёт.
  const таймер = setTimeout(() => {
    if (загрузка === 'грузится') {
      загрузка = 'нет-шрифта';
      последняяНеудача = Date.now();
      сообщить();
    }
  }, ТЕРПЕНИЕ_МС);
  void загрузитьШрифтKfgqpc().then((ок) => {
    clearTimeout(таймер);
    if (ок) {
      if (ВЕБ) включитьКопированиеИсходного();
      загрузка = 'готов';
    } else {
      загрузка = 'нет-шрифта';
      последняяНеудача = Date.now();
    }
    сообщить();
  });
  сообщить();
}

function подписаться(с: () => void): () => void {
  слушатели.add(с);
  return () => {
    слушатели.delete(с);
  };
}
const снимок = () => загрузка;

export type ШрифтКоранаСейчас = { выбор: ШрифтКорана; мединский: boolean; семейство: string; готов: boolean };

export function useШрифтКорана(коран = true): ШрифтКоранаСейчас {
  const выборЧеловека = useВыборШрифтаКорана();
  const выбор: ШрифтКорана = коран ? выборЧеловека : 'классический';
  const з = useSyncExternalStore(подписаться, снимок, снимок);
  const амириГотов = useАрабскийШрифтГотов();
  useEffect(() => {
    if (выбор === 'мединский') запросить();
  }, [выбор]);
  if (выбор === 'мединский' && з === 'готов') return { выбор, мединский: true, семейство: ШРИФТ_KFGQPC.семейство, готов: true };
  const ждём = выбор === 'мединский' && (з === 'нет' || з === 'грузится');
  return { выбор, мединский: false, семейство: ШРИФТ_АРАБСКИЙ, готов: амириГотов && !ждём };
}

export function кусокКорана(ш: ШрифтКоранаСейчас, строка: string, ключ?: Key): ReactNode {
  if (!ш.мединский) return строка;
  const показ = подстроитьДляKfgqpc(строка);
  if (показ === строка) return строка;
  return ВЕБ ? createElement('span', { key: ключ, 'data-o': строка }, показ) : показ;
}
