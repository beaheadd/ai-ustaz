export function ПереключательВидаЧтения() {
  const т = useСловарь(СЛОВАРЬ);
  const { вид, ночьЦвета } = useВидЧтения();
  const { отступ } = useТема();
  return (
    <View style={{ gap: отступ.s }} testID="вид-чтения-выбор">
      <Вкладки
        подпись={т('подпись')}
        роль="выбор"
        вкладки={ВИДЫ_ЧТЕНИЯ.map((в) => ({ ключ: в, надпись: т(в), testID: 'вид-' + в }))}
        выбрана={вид}
        приВыборе={(к) => установитьВидЧтения(к as ВидЧтения)}
      />
      {вид === 'ночной' ? (
        <СтрокаПереключателя заголовок={т('ночьЦвета')} подпись={т('ночьЦветаПодпись')} включено={ночьЦвета} приСмене={установитьНочьЦвета} testID="вид-ночь-цвета" />
      ) : null}
    </View>
  );
}

export function ВыборВидаЧтения({ вид = 'строка' }: { вид?: 'строка' | 'шапка' }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const выбор = useВидЧтения();
  const [открыт, установитьОткрыт] = useState(false);
  if (вид === 'строка') {
    return (
      <View style={{ gap: отступ.xs }} testID="ещё-вид-чтения">
        <Текст вид="мелкий">{т('подпись')}</Текст>
        <ПереключательВидаЧтения />
      </View>
    );
  }
  return (
    <View style={{ alignSelf: 'stretch', gap: отступ.s }}>
      <СтрокаСписка
        заголовок={т('кнопка', { вид: т((выбор.вид + 'Полно') as 'обычныйПолно') })}
        значок="коран"
        раскрыт={открыт}
        приНажатии={() => установитьОткрыт((о) => !о)}
        testID="вид-чтения"
      />
      {открыт ? (
        <View style={{ gap: отступ.s }}>
          <ПереключательВидаЧтения />
          <View style={{ alignItems: 'center' }}>
            <РазмерАрабского вид="кнопки" testID="вид-размер" />
          </View>
        </View>
      ) : null}
    </View>
  );
}
