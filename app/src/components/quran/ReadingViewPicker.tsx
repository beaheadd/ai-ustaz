/** Образец темы страницы: буква ب на фоне темы (не текст Корана — одна буква алфавита). «Авто» — половины день/ночь. */
function ОбразецТемы({ тема }: { тема: ТемаЧтения }) {
  const половины = тема === 'авто' ? [СТРАНИЦА.день, СТРАНИЦА.ночь] : [СТРАНИЦА[тема]];
  return (
    <View style={{ width: '100%', height: 34, borderRadius: 8, overflow: 'hidden', flexDirection: 'row', borderWidth: 1, borderColor: 'rgba(0,0,0,0.12)' }} {...({ 'aria-hidden': true } as object)}>
      {половины.map((с, i) => (
        <View key={i} style={{ flex: 1, backgroundColor: с.фон, alignItems: 'center', justifyContent: 'center' }}>
          <Text style={{ fontFamily: ШРИФТ_АРАБСКИЙ, fontSize: 18, lineHeight: 28, color: с.чернила }}>ب</Text>
        </View>
      ))}
    </View>
  );
}

/** «Страница»: 5 образцов в ряд (radiogroup); выбранный — рамка акцента 2 px и полужирная подпись (не только цветом). */
function ВыборТемыСтраницы() {
  const т = useСловарь(СЛОВАРЬ);
  const { тема } = useВидЧтения();
  const { цвет, отступ, радиус } = useТема();
  return (
    <View style={{ gap: отступ.xs }}>
      <Текст вид="мелкий">{т('тема')}</Текст>
      <View accessibilityRole="radiogroup" accessibilityLabel={т('тема')} style={{ flexDirection: 'row', gap: 6 }}>
        {ТЕМЫ_ЧТЕНИЯ.map((в) => {
          const выбрана = в === тема;
          const подпись = в === 'авто' ? т('автоПодпись') : в === 'безСинего' ? т('безСинегоПодпись') : undefined;
          return (
            <Pressable
              key={в}
              accessibilityRole="radio"
              accessibilityLabel={подпись ? т(в) + ' — ' + подпись : т(в)}
              {...({ 'aria-checked': выбрана } as object)}
              onPress={() => установитьТемуЧтения(в)}
              testID={'чтение-' + в}
              style={({ pressed }) => ({
                flex: 1,
                minWidth: 0,
                minHeight: 72,
                padding: 4,
                gap: 4,
                alignItems: 'center',
                borderRadius: радиус.m,
                borderWidth: выбрана ? 2 : 1,
                borderColor: выбрана ? цвет.акцент : цвет.граница,
                backgroundColor: цвет.поверхность,
                opacity: pressed ? 0.8 : 1,
              })}
            >
              <ОбразецТемы тема={в} />
              <Текст вид="метка" цвет={выбрана ? цвет.акцент : цвет.текстВторой} стиль={{ fontSize: 13, lineHeight: 16, textAlign: 'center', fontWeight: выбрана ? '600' : '400' }} numberOfLines={2}>
                {т(в)}
              </Текст>
            </Pressable>
          );
        })}
      </View>
    </View>
  );
}

export function ПереключательВидаЧтения() {
  const т = useСловарь(СЛОВАРЬ);
  const { вид, таджвид, режим } = useВидЧтения();
  const подсветкаСлов = useПодсветкаСловВкл();
  const { цвет, отступ, радиус } = useТема();
  // В «Аят за аятом» в обычном виде цветов нет — показываем «Без цвета»; выбор цвета включит «Мусхаф».
  const таджвидВиден: РежимТаджвида = режим === 'аяты' && вид === 'обычный' ? 'безЦвета' : таджвид;
  return (
    <View style={{ gap: отступ.m }} testID="вид-чтения-выбор">
      {/* Режим (владелец 27.11.2026): аят за аятом или страницами мусхафа, листание как в книге. */}
      <Вкладки
        подпись={т('режим')}
        роль="выбор"
        вкладки={РЕЖИМЫ_ЧТЕНИЯ.map((р) => ({ ключ: р, надпись: т(р), testID: 'режим-' + р }))}
        выбрана={режим}
        приВыборе={(к) => установитьРежимЧтения(к as РежимЧтения)}
      />
      {режим === 'аяты' ? (
        <Вкладки
          подпись={т('вид')}
          роль="выбор"
          вкладки={ВИДЫ_ЧТЕНИЯ.map((в) => ({ ключ: в, надпись: т(в), testID: 'вид-' + в }))}
          выбрана={вид}
          приВыборе={(к) => установитьВидЧтения(к as ВидЧтения)}
        />
      ) : null}
      <ВыборТемыСтраницы />
      <View style={{ gap: отступ.xs }}>
        <Текст вид="мелкий">{т('таджвид')}</Текст>
        {/* Пилюли с переносом (как в макете A): «Традиционные» целиком, без разрыва слова на 360 px. */}
        <View accessibilityRole="radiogroup" accessibilityLabel={т('таджвид')} style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
          {РЕЖИМЫ_ТАДЖВИДА.map((р) => {
            const выбран = р === таджвидВиден;
            return (
              <Pressable
                key={р}
                accessibilityRole="radio"
                {...({ 'aria-checked': выбран } as object)}
                onPress={() => установитьТаджвид(р)}
                testID={'таджвид-' + р}
                style={({ pressed }) => ({
                  minHeight: 44,
                  paddingHorizontal: отступ.l,
                  justifyContent: 'center',
                  borderRadius: радиус.круг,
                  backgroundColor: выбран ? цвет.акцент : цвет.поверхностьВторая,
                  opacity: pressed ? 0.8 : 1,
                })}
              >
                <Текст вид="метка" цвет={выбран ? цвет.акцентТекст : цвет.текст} стиль={{ fontSize: 15, lineHeight: 20 }}>
                  {т(р)}
                </Текст>
              </Pressable>
            );
          })}
        </View>
        {таджвидВиден === 'различимые' ? <Текст вид="мелкий">{т('различимыеПодпись')}</Текст> : null}
      </View>
      {/* Пословная подсветка чтения (владелец 28.11.2026; quran/wordHighlight.ts), по умолчанию вкл. */}
      <СтрокаПереключателя заголовок={т('слова')} подпись={т('словаПодпись')} включено={подсветкаСлов} приСмене={установитьПодсветкуСлов} testID="вид-слова" />
    </View>
  );
}

export function ВыборВидаЧтения({ вид = 'строка' }: { вид?: 'строка' | 'шапка' }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const выбор = useВидЧтения();
  const [открыт, установитьОткрыт] = useState(false);
  if (вид === 'строка') {
    return (
      <View style={{ gap: отступ.xs }} testID="ещё-вид-чтения">
        <Текст вид="мелкий">{т('подпись')}</Текст>
        <ПереключательВидаЧтения />
      </View>
    );
  }
  return (
    <View style={{ alignSelf: 'stretch', gap: отступ.s }}>
      <СтрокаСписка
        заголовок={т('кнопка', { вид: т((выбор.вид + 'Полно') as 'обычныйПолно') })}
        значок="коран"
        раскрыт={открыт}
        приНажатии={() => установитьОткрыт((о) => !о)}
        testID="вид-чтения"
      />
      {открыт ? (
        <View style={{ gap: отступ.s }}>
          <ПереключательВидаЧтения />
          <View style={{ alignItems: 'center' }}>
            <РазмерАрабского вид="кнопки" testID="вид-размер" />
          </View>
        </View>
      ) : null}
    </View>
  );
}
