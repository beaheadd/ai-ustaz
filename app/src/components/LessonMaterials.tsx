type Вкладка = 'объяснение' | 'видео' | 'аудио';
const ЗНАЧКИ_ВКЛАДОК = { объяснение: 'урок', видео: 'видео', аудио: 'аудио' } as const;

export function МатериалыУрока({ урок, материалы }: { урок: Урок; материалы: МатериалыМедиа }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const вкладки: Вкладка[] = ['объяснение', ...(материалы.видео.length ? (['видео'] as const) : []), ...(материалы.аудио.length ? (['аудио'] as const) : [])];
  const [выбрана, выбрать] = useState<Вкладка>('объяснение');
  const текущая = вкладки.includes(выбрана) ? выбрана : 'объяснение';
  return (
    <View style={{ gap: отступ.m }} testID="материалы-урока">
      <Текст вид="подзаголовок" accessibilityRole="header">
        {т('материалы')}
      </Текст>
      {вкладки.length > 1 ? (
        <Вкладки
          вкладки={вкладки.map((в) => ({ ключ: в, надпись: т(в), значок: ЗНАЧКИ_ВКЛАДОК[в], testID: 'материалы-вкладка-' + в }))}
          выбрана={текущая}
          приВыборе={(к) => выбрать(к as Вкладка)}
          подпись={т('материалы')}
        />
      ) : null}
      {текущая === 'объяснение' ? <Объяснение урок={урок} /> : null}
      {текущая === 'видео' ? <СписокВидео видео={материалы.видео} /> : null}
      {текущая === 'аудио' ? <СписокАудио аудио={материалы.аудио} /> : null}
    </View>
  );
}

function Объяснение({ урок }: { урок: Урок }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const буквы = урок.задания.filter((з): з is ЗаданиеЗнакомство => з.тип === 'знакомство');
  const цель = локально(урок.цель, язык);
  // Новое, которое уже показано буквой с названием, второй раз не рисуем.
  const новоеБезБукв = урок.новое.filter((н) => !буквы.some((б) => б.знак === н));
  return (
    <View style={{ gap: отступ.m }} testID="материалы-объяснение">
      {цель ? (
        <Карточка>
          <ЗаголовокРаздела надпись={т('цель')} />
          <СмешанныйТекст>{цель}</СмешанныйТекст>
        </Карточка>
      ) : null}
      {новоеБезБукв.length > 0 ? (
        <Карточка>
          <ЗаголовокРаздела надпись={т('новое')} />
          <View style={{ flexDirection: 'row-reverse', flexWrap: 'wrap', justifyContent: 'center', columnGap: отступ.xl }}>
            {новоеБезБукв.map((з, i) => (
              <АрабскийТекст key={i} размер="огромный" стиль={стильКрупного('огромный', { безЗнаков: true })}>
                {з}
              </АрабскийТекст>
            ))}
          </View>
        </Карточка>
      ) : null}
      {буквы.length > 0 ? (
        <Карточка testID="материалы-буквы">
          <ЗаголовокРаздела надпись={т('буквы')} />
          {буквы.map((б, i) => (
            <View
              key={i}
              style={{
                flexDirection: 'row',
                gap: отступ.m,
                alignItems: 'flex-start',
                paddingTop: i ? отступ.m : отступ.xs,
                borderTopWidth: i ? 1 : 0,
                borderColor: цвет.граница,
              }}
            >
              <View
                style={{
                  width: 72,
                  minHeight: 72,
                  borderRadius: радиус.l,
                  backgroundColor: цвет.поверхностьАкцент,
                  alignItems: 'center',
                  justifyContent: 'center',
                }}
              >
                <АрабскийТекст размер="огромный" выбираемый={false} стиль={стильКрупного(52, { безЗнаков: true })}>
                  {б.знак}
                </АрабскийТекст>
              </View>
              <View style={{ flex: 1, gap: отступ.xs }}>
                <Текст вид="подзаголовок">{локально(б.название, язык)}</Текст>
                {б.подсказка ? (
                  <>
                    <Текст вид="метка" цвет={цвет.текстВторой}>
                      {т('какПроизносить')}
                    </Текст>
                    <СмешанныйТекст>{локально(б.подсказка, язык)}</СмешанныйТекст>
                  </>
                ) : null}
              </View>
            </View>
          ))}
        </Карточка>
      ) : null}
      <Плашка надпись={т('черновик')} вид="черновик" значок="инфо" testID="материалы-черновик" />
    </View>
  );
}

