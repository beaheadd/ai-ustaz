/** На вебе — <a href target=_blank rel="noopener noreferrer"> (react-native-web: Text с href и hrefAttrs). */
const ТекстСсылка = Text as unknown as ComponentType<
  TextProps & { href?: string; hrefAttrs?: { target?: string; rel?: string }; role?: string }
>;

function СсылкаYoutube({ видео, номер }: { видео: ПоказВидео; номер: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, радиус, шрифт, отступ } = useТема();
  const надпись = '↗ ' + т('смотреть');
  if (Platform.OS !== 'web') {
    return <Кнопка надпись={т('смотреть')} значок="↗" вид="вторичная" приНажатии={() => Linking.openURL(видео.ссылка)} testID={'видео-youtube-' + номер} />;
  }
  return (
    <ТекстСсылка
      href={видео.ссылка}
      hrefAttrs={{ target: '_blank', rel: 'noopener noreferrer' }}
      role="link"
      testID={'видео-youtube-' + номер}
      style={{
        minHeight: 48,
        paddingVertical: 12,
        paddingHorizontal: отступ.l,
        borderRadius: радиус.m,
        borderWidth: 1,
        borderColor: цвет.граница,
        backgroundColor: цвет.акцентМягкий,
        color: цвет.акцент,
        fontSize: шрифт.обычный,
        fontWeight: '600',
        textAlign: 'center',
        textDecorationLine: 'none',
      }}
    >
      {надпись}
    </ТекстСсылка>
  );
}

function СписокВидео({ видео }: { видео: ПоказВидео[] }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { отступ } = useТема();
  const естьYoutube = видео.some((в) => !в.файлВидео);
  return (
    <View style={{ gap: отступ.m }} testID="материалы-видео">
      {видео.some((в) => в.безРазрешения) ? <ПлашкаПредпросмотра /> : null}
      {естьYoutube && Platform.OS === 'web' ? (
        <Текст вид="второй" testID="youtube-пояснение">
          {т('пояснениеYoutube')}
        </Текст>
      ) : null}
      {видео.map((в, i) => (
        <Карточка key={в.источник + в.youtubeId} акцент={в.роль === 'основное'} testID={'видео-' + i}>
          <Текст вид="мелкий">{т(в.роль)}</Текст>
          <СмешанныйТекст вид="подзаголовок">{в.название}</СмешанныйТекст>
          <Текст вид="мелкий">{т('язык', { язык: названиеЯзыка(в.автор.язык, т) })}</Текст>
          {в.файлВидео && Platform.OS === 'web' ? (
            createElement('video', {
              src: в.файлВидео, // относительный путь media/… — свой сервер (CSP media-src 'self')
              controls: true,
              preload: 'none',
              playsInline: true,
              'data-testid': 'видео-файл-' + i,
              style: { width: '100%', borderRadius: 12, background: '#000' },
            })
          ) : (
            <СсылкаYoutube видео={в} номер={i} />
          )}
          <Текст вид="мелкий" testID={'видео-атрибуция-' + i}>
            {локально(в.автор.атрибуция, язык)}
          </Текст>
          {в.безРазрешения ? <ПлашкаПредпросмотра мелкая /> : null}
        </Карточка>
      ))}
    </View>
  );
}

