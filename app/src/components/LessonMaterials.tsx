/** На вебе — <a href target=_blank rel="noopener noreferrer"> (react-native-web: Text с href и hrefAttrs). */
const ТекстСсылка = Text as unknown as ComponentType<
  TextProps & { href?: string; hrefAttrs?: { target?: string; rel?: string }; role?: string }
>;

/** «Смотреть урок учителя на YouTube» — ссылка в виде вторичной кнопки; значок «внешняя» поверх левого поля. */
function СсылкаYoutube({ видео, номер }: { видео: ПоказВидео; номер: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, радиус, отступ } = useТема();
  if (Platform.OS !== 'web') {
    return <Кнопка надпись={т('смотреть')} значок="внешняя" вид="вторичная" приНажатии={() => Linking.openURL(видео.ссылка)} testID={'видео-youtube-' + номер} />;
  }
  return (
    <View>
      <ТекстСсылка
        href={видео.ссылка}
        hrefAttrs={{ target: '_blank', rel: 'noopener noreferrer' }}
        role="link"
        testID={'видео-youtube-' + номер}
        style={[
          стильТекста('кнопка'),
          {
            minHeight: 48,
            paddingVertical: 13,
            paddingLeft: отступ.l + 28,
            paddingRight: отступ.l,
            borderRadius: радиус.m,
            backgroundColor: цвет.акцентМягкий,
            color: цвет.акцент,
            textAlign: 'center',
            textDecorationLine: 'none',
          },
        ]}
      >
        {т('смотреть')}
      </ТекстСсылка>
      <View style={{ position: 'absolute', left: отступ.l, top: 0, bottom: 0, justifyContent: 'center', pointerEvents: 'none' }}>
        <Значок имя="внешняя" размер={20} цвет={цвет.акцент} толщина={2} />
      </View>
    </View>
  );
}

