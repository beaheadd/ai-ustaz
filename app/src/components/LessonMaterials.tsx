/**
 * «Материалы урока» на вступлении урока: Объяснение · Видео · Аудио (вкладки; видны только непустые).
 * И «Послушать кари» в упражнениях — тот же клип кари по точному тексту буквы или слога.
 *
 * Решение владельца 19.11.2026: в каждом уроке — видео, аудио и объяснение. Видео и аудио — от учителей-
 * партнёров; ученик видит их, только если автор разрешил (content/media.json → источники.<id>.разрешено).
 *
 * Контракт:
 *   useМатериалыМедиа(номер) → МатериалыМедиа  — что можно показать (media/media.ts, материалыУрока);
 *       пока данные грузятся или не прошли проверку — пусто (ученик видит только «Объяснение»).
 *   <МатериалыУрока урок={Урок} материалы={МатериалыМедиа} />
 *     - Объяснение (всегда): цель, новое, у новых букв — название и подсказка артикуляции. Всё — из данных
 *       урока (задания «знакомство»), новых религиозных текстов здесь нет. Плашка «Черновик — проверяет устаз».
 *     - Видео (если есть что показать): основное, потом дополнительное; атрибуция автора на экране.
 *       Свой файл (media/…) — <video> со своего сервера. Только YouTube — НЕ iframe (реклама и метки Google),
 *       а ссылка «Смотреть урок учителя на YouTube» во внешнее приложение/вкладку (rel="noopener noreferrer")
 *       с пояснением «Откроется YouTube — там может быть реклама, она не от нас».
 *     - Аудио (если есть клипы): «буква/слог → <audio> кари» со своего сервера, «Голос: <кари>». Синтеза нет.
 *     - Предпросмотр (EXPO_PUBLIC_MEDIA_PREVIEW=1): неразрешённое видно с красной плашкой
 *       «Предпросмотр: нет разрешения автора — ученики этого не видят».
 *   <ПоставщикКлиповКари материалы>…</ПоставщикКлиповКари> — для упражнений урока.
 *   <ПослушатьКари тексты={[…]} /> — кнопка «Послушать кари» для первого текста, у которого есть клип; нет — ничего.
 *   есть ли клип: useЕстьКлипКари(тексты) (упражнения прячут строку «голос кари появится…»).
 * testID: материалы-урока, материалы-вкладка-<объяснение|видео|аудио>, материалы-объяснение,
 *   материалы-черновик, материалы-видео, видео-<i>, видео-файл-<i>, видео-youtube-<i>, видео-атрибуция-<i>,
 *   youtube-пояснение, материалы-аудио, аудио-плеер-<i>, предпросмотр-нет-разрешения, послушать-кари.
 */
