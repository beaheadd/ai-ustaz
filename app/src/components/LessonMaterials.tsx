type Вкладка = 'объяснение' | 'видео' | 'аудио';

export function МатериалыУрока({ урок, материалы }: { урок: Урок; материалы: МатериалыМедиа }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const вкладки: Вкладка[] = ['объяснение', ...(материалы.видео.length ? (['видео'] as const) : []), ...(материалы.аудио.length ? (['аудио'] as const) : [])];
  const [выбрана, выбрать] = useState<Вкладка>('объяснение');
  const текущая = вкладки.includes(выбрана) ? выбрана : 'объяснение';
  return (
    <View style={{ gap: отступ.m }} testID="материалы-урока">
      <Текст вид="подзаголовок" accessibilityRole="header">
        {т('материалы')}
      </Текст>
      {вкладки.length > 1 ? <Вкладки вкладки={вкладки} выбрана={текущая} выбрать={выбрать} /> : null}
      {текущая === 'объяснение' ? <Объяснение урок={урок} /> : null}
      {текущая === 'видео' ? <СписокВидео видео={материалы.видео} /> : null}
      {текущая === 'аудио' ? <СписокАудио аудио={материалы.аудио} /> : null}
    </View>
  );
}

function Вкладки({ вкладки, выбрана, выбрать }: { вкладки: Вкладка[]; выбрана: Вкладка; выбрать: (в: Вкладка) => void }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, радиус, шрифт } = useТема();
  return (
    <View accessibilityRole="tablist" style={{ flexDirection: 'row', borderRadius: радиус.m, borderWidth: 1, borderColor: цвет.граница, overflow: 'hidden' }}>
      {вкладки.map((в) => {
        const активна = в === выбрана;
        return (
          <Pressable
            key={в}
            accessibilityRole="tab"
            accessibilityState={{ selected: активна }}
            onPress={() => выбрать(в)}
            testID={'материалы-вкладка-' + в}
            style={{ flex: 1, minHeight: 48, alignItems: 'center', justifyContent: 'center', backgroundColor: активна ? цвет.акцент : цвет.поверхность }}
          >
            <Text style={{ color: активна ? цвет.акцентТекст : цвет.акцент, fontSize: шрифт.обычный, fontWeight: '600' }}>{т(в)}</Text>
          </Pressable>
        );
      })}
    </View>
  );
}

function Объяснение({ урок }: { урок: Урок }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const буквы = урок.задания.filter((з): з is ЗаданиеЗнакомство => з.тип === 'знакомство');
  const цель = локально(урок.цель, язык);
  return (
    <View style={{ gap: отступ.m }} testID="материалы-объяснение">
      {цель ? (
        <Карточка заголовок={т('цель')}>
          <СмешанныйТекст>{цель}</СмешанныйТекст>
        </Карточка>
      ) : null}
      {урок.новое.length > 0 ? (
        <Карточка заголовок={т('новое')}>
          <View style={{ flexDirection: 'row-reverse', flexWrap: 'wrap', justifyContent: 'center', columnGap: отступ.xl }}>
            {урок.новое.map((з, i) => (
              // Голые буквы без огласовок: место под огласовки не нужно, иначе буквы «проваливаются» вниз карточки.
              <АрабскийТекст key={i} размер="огромный" стиль={{ lineHeight: 100 }}>
                {з}
              </АрабскийТекст>
            ))}
          </View>
        </Карточка>
      ) : null}
      {буквы.length > 0 ? (
        <Карточка заголовок={т('буквы')} testID="материалы-буквы">
          {буквы.map((б, i) => (
            <View key={i} style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start', paddingTop: i ? отступ.s : 0, borderTopWidth: i ? 1 : 0, borderColor: цвет.граница }}>
              <View style={{ width: 56, alignItems: 'center', marginTop: -отступ.l }}>
                <АрабскийТекст размер="крупный" выбираемый={false}>
                  {б.знак}
                </АрабскийТекст>
              </View>
              <View style={{ flex: 1, gap: отступ.xs }}>
                <Текст вид="подзаголовок">{локально(б.название, язык)}</Текст>
                {б.подсказка ? (
                  <>
                    <Текст вид="мелкий">{т('какПроизносить')}</Текст>
                    <СмешанныйТекст>{локально(б.подсказка, язык)}</СмешанныйТекст>
                  </>
                ) : null}
              </View>
            </View>
          ))}
        </Карточка>
      ) : null}
      <View testID="материалы-черновик" style={{ padding: отступ.s, borderRadius: радиус.m, backgroundColor: цвет.плашкаФон }}>
        <Текст вид="мелкий" стиль={{ color: цвет.плашкаТекст, textAlign: 'center' }}>
          {т('черновик')}
        </Текст>
      </View>
    </View>
  );
}

