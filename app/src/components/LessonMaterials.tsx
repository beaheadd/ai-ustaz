const ПУСТО: МатериалыМедиа = { видео: [], аудио: [] };
const ЯЗЫКИ_ВИДЕО = ['uz', 'kk', 'ar', 'ru'] as const;

function названиеЯзыка(код: string, т: (ключ: `язык.${(typeof ЯЗЫКИ_ВИДЕО)[number]}`) => string): string {
  return (ЯЗЫКИ_ВИДЕО as readonly string[]).includes(код) ? т(`язык.${код as (typeof ЯЗЫКИ_ВИДЕО)[number]}`) : код;
}

/** Что из видео и аудио партнёров можно показать в уроке (с учётом разрешений и предпросмотра). */
export function useМатериалыМедиа(номер: number): МатериалыМедиа {
  const [м, установить] = useState<МатериалыМедиа>(ПУСТО);
  useEffect(() => {
    let живой = true;
    загрузитьДанные('media').then((медиа) => {
      if (живой) установить(материалыУрока(медиа, номер, предпросмотрМедиа()));
    });
    return () => {
      живой = false;
    };
  }, [номер]);
  return м;
}

// ───────────────────────── Клипы кари в упражнениях ─────────────────────────

const КонтекстКлипов = createContext<Map<string, ПоказАудио>>(new Map());

export function ПоставщикКлиповКари({ материалы, children }: { материалы: МатериалыМедиа; children: ReactNode }) {
  const карта = useMemo(() => клипыКари(материалы), [материалы]);
  return <КонтекстКлипов.Provider value={карта}>{children}</КонтекстКлипов.Provider>;
}

function useКлип(тексты: readonly (string | null | undefined)[]): ПоказАудио | null {
  const карта = useContext(КонтекстКлипов);
  if (Platform.OS !== 'web') return null; // нативный плеер — позже (expo-audio)
  for (const т of тексты) {
    const к = т ? карта.get(т) : undefined;
    if (к) return к;
  }
  return null;
}

export function useЕстьКлипКари(тексты: readonly (string | null | undefined)[]): boolean {
  return useКлип(тексты) != null;
}

/** Кнопка «Послушать кари» для первого текста с клипом. Клипа нет — ничего (синтеза нет). */
export function ПослушатьКари({ тексты }: { тексты: readonly (string | null | undefined)[] }) {
  const клип = useКлип(тексты);
  if (!клип) return null;
  return <КнопкаКари клип={клип} />;
}

function КнопкаКари({ клип }: { клип: ПоказАудио }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { отступ } = useТема();
  const плеер = useRef<HTMLAudioElement | null>(null);
  const [играет, установитьИграет] = useState(false);
  useEffect(
    () => () => {
      плеер.current?.pause();
      плеер.current = null;
    },
    [],
  );
  const нажать = () => {
    if (typeof Audio === 'undefined') return;
    if (играет && плеер.current) {
      плеер.current.pause();
      плеер.current.currentTime = 0;
      установитьИграет(false);
      return;
    }
    if (!плеер.current) {
      плеер.current = new Audio(клип.файл); // относительный путь media/… — свой сервер (CSP media-src 'self')
      плеер.current.addEventListener('ended', () => установитьИграет(false));
      плеер.current.addEventListener('error', () => установитьИграет(false));
    }
    установитьИграет(true);
    плеер.current.play().catch(() => установитьИграет(false));
  };
  return (
    <View style={{ gap: отступ.xs }} testID="послушать-кари-блок">
      <Кнопка надпись={играет ? т('стоп') : т('послушать')} значок={играет ? '■' : '▶'} вид="вторичная" приНажатии={нажать} testID="послушать-кари" />
      <Текст вид="мелкий">{т('голос', { кари: локально(клип.автор.имя, язык) })}</Текст>
      {клип.безРазрешения ? <ПлашкаПредпросмотра мелкая /> : null}
    </View>
  );
}

