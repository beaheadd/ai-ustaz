/**
 * Пояснение о приватности записи — показывается ПЕРЕД первым запросом микрофона.
 *
 * Контракт: <ПояснениеМикрофона приСогласии={() => …} приОтказе={() => …} />
 *   приСогласии — человек согласен: отметить флаг в прогрессе и сразу начать запись
 *                 (в том же обработчике нажатия — так браузер покажет свой запрос);
 *   приОтказе   — «Позже — без записи»: задания продолжаются без голоса.
 * Обычно используется внутри <ПанельЗаписи>, которая делает всё это сама.
 * Тексты — i18n 'микрофон.*' (прототип: запись только в памяти страницы, без ИИ-проверки; на своём
 * домене с проверкой голосом — «уходит на сервер только по «Проверить»», speech/flag.ts).
 * Вид (дизайн-система 19.11.2026): мягкая изумрудная карточка, значок микрофона в плитке, пункты с нуктами.
 */
import { View } from 'react-native';
import { useПеревод } from '../i18n';
import { проверкаГолосомВключена } from '../speech/flag';
import { useТема } from '../theme';
import { Кнопка } from './Button';
import { Карточка } from './Card';
import { Значок } from './Icon';
import { Текст } from './Text';

export function ПояснениеМикрофона({ приСогласии, приОтказе }: { приСогласии: () => void; приОтказе: () => void }) {
  const { t } = useПеревод();
  const { отступ, цвет, радиус } = useТема();
  // На своём домене с проверкой голосом — честно: запись может уйти на сервер, но только по «Проверить».
  const проверка = проверкаГолосомВключена();
  const пункты = [
    t('микрофон.нажатие'),
    t(проверка ? 'микрофон.памятьПроверка' : 'микрофон.память'),
    t('микрофон.удаление'),
    t(проверка ? 'микрофон.проверка' : 'микрофон.безОценки'),
    t(проверка ? 'микрофон.сайтСвой' : 'микрофон.сайт'),
  ];
  return (
    <Карточка вид="акцент" testID="пояснение-микрофона">
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
        <View style={{ width: 40, height: 40, borderRadius: радиус.m, backgroundColor: цвет.поверхность, alignItems: 'center', justifyContent: 'center' }}>
          <Значок имя="микрофон" размер={22} цвет={цвет.акцент} толщина={2} />
        </View>
        <Текст вид="подзаголовок" accessibilityRole="header" стиль={{ flex: 1 }}>
          {t('микрофон.заголовок')}
        </Текст>
      </View>
      <View style={{ gap: отступ.s, marginTop: отступ.xs }}>
        {пункты.map((пункт) => (
          <View key={пункт} style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'flex-start' }}>
            <Значок имя="нукта" размер={16} цвет={цвет.акцент} стиль={{ marginTop: 4 }} />
            <Текст стиль={{ flex: 1 }}>{пункт}</Текст>
          </View>
        ))}
      </View>
      <View style={{ gap: отступ.s, marginTop: отступ.s }}>
        <Кнопка надпись={t('микрофон.разрешить')} значок="микрофон" приНажатии={приСогласии} testID="микрофон-разрешить" />
        <Кнопка надпись={t('микрофон.позже')} приНажатии={приОтказе} вид="тихая" testID="микрофон-позже" />
      </View>
    </Карточка>
  );
}
