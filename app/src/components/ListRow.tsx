/**
 * СтрокаСписка — строка меню, настройки или списка (город, урок, пункт «О проекте»).
 *
 * Контракт:
 *   <СтрокаСписка заголовок подпись? значок? значение? справа? приНажатии? стрелка? раскрыт?
 *                 выбрана? вид?="карточка|плоская" отключена? testID? />
 * - значок — имя значка из набора (в мягкой изумрудной плитке 40×40) или короткий символ (☰, ✎, i);
 * - значение — короткий текст справа («Астана», «12:58»), табличные цифры;
 * - справа — свой элемент справа (вместо значения и стрелки);
 * - стрелка — «›» справа (по умолчанию — если есть приНажатии и нет раскрыт/справа);
 * - раскрыт — для раскрывашек: вместо стрелки «вниз/вверх», accessibilityState.expanded;
 * - выбрана — отмеченный вариант списка (галочка, accessibilityState.selected);
 * - вид: «карточка» — отдельная плитка с рамкой (по умолчанию), «плоская» — строка в общем списке
 *   (без фона, разделитель снизу).
 * Высота ≥ 56 px. Без лиц и картинок.
 */
import type { ReactNode } from 'react';
import { Pressable, View } from 'react-native';
import { useТема } from '../theme';
import { Значок, этоЗначок } from './Icon';
import { Текст } from './Text';

export type СвойстваСтроки = {
  заголовок: string;
  подпись?: string;
  значок?: string;
  значение?: string;
  справа?: ReactNode;
  приНажатии?: () => void;
  стрелка?: boolean;
  раскрыт?: boolean;
  выбрана?: boolean;
  вид?: 'карточка' | 'плоская';
  отключена?: boolean;
  testID?: string;
};

export function СтрокаСписка({
  заголовок,
  подпись,
  значок,
  значение,
  справа,
  приНажатии,
  стрелка,
  раскрыт,
  выбрана,
  вид = 'карточка',
  отключена = false,
  testID,
}: СвойстваСтроки) {
  const { цвет, отступ, радиус } = useТема();
  const раскрывашка = раскрыт !== undefined;
  const показатьСтрелку = стрелка ?? (!!приНажатии && !раскрывашка && !справа && выбрана === undefined);
  const карточка = вид === 'карточка';

  const тело = (
    <>
      {значок ? (
        <View
          style={{ width: 40, height: 40, borderRadius: радиус.m, backgroundColor: цвет.поверхностьАкцент, alignItems: 'center', justifyContent: 'center' }}
          accessibilityElementsHidden
          importantForAccessibility="no-hide-descendants"
        >
          {этоЗначок(значок) ? (
            <Значок имя={значок} размер={22} цвет={цвет.акцент} />
          ) : (
            <Текст вид="подзаголовок" цвет={цвет.акцент}>
              {значок}
            </Текст>
          )}
        </View>
      ) : null}
      <View style={{ flex: 1, gap: 2 }}>
        <Текст стиль={{ fontWeight: '600' }}>{заголовок}</Текст>
        {подпись ? <Текст вид="мелкий">{подпись}</Текст> : null}
      </View>
      {справа ?? null}
      {!справа && значение ? (
        <Текст вид="второй" табличные>
          {значение}
        </Текст>
      ) : null}
      {выбрана ? <Значок имя="галочка" размер={22} цвет={цвет.акцент} /> : null}
      {раскрывашка ? <Значок имя={раскрыт ? 'вверх' : 'вниз'} размер={20} цвет={цвет.текстВторой} /> : null}
      {показатьСтрелку ? <Значок имя="вперёд" размер={20} цвет={цвет.текстВторой} /> : null}
    </>
  );

  const стиль = {
    flexDirection: 'row' as const,
    alignItems: 'center' as const,
    gap: отступ.m,
    minHeight: 56,
    paddingVertical: отступ.s,
    paddingHorizontal: карточка ? отступ.m : 0,
    ...(карточка
      ? { borderRadius: радиус.m, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность }
      : { borderBottomWidth: 1, borderBottomColor: цвет.граница }),
    opacity: отключена ? 0.5 : 1,
  };

  if (!приНажатии) {
    return (
      <View testID={testID} style={стиль}>
        {тело}
      </View>
    );
  }
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityState={{ disabled: отключена, ...(раскрывашка ? { expanded: раскрыт } : null), ...(выбрана !== undefined ? { selected: выбрана } : null) }}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      style={({ pressed }) => [стиль, pressed ? { backgroundColor: цвет.акцентМягкий } : null]}
    >
      {тело}
    </Pressable>
  );
}
