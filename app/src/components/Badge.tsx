/**
 * Плашка — короткая метка-капсула рядом с заголовком или значением.
 *
 * Контракт: <Плашка надпись вид?="черновик|прототип|ии|внимание|успех|инфо|скоро|следующий" значок? testID? />
 * - черновик / прототип — «Черновик — проверяет устаз», «Прототип» (правило 11: пока устаз не посмотрел);
 *   ии — «ИИ» рядом с подсказкой ИИ (не путать с живым устазом);
 *   внимание — «Проверьте себя» (янтарь; красный для чтения не используем);
 *   успех — нейтральное «Записали», «Сохранено» (не «Верно» по голосу);
 *   инфо / скоро — серо-песочная («скоро» — модуль ещё не готов);
 *   следующий — мягкое золото («Следующий» намаз, текущий шаг).
 * - значок — имя значка из набора (14 px) или ничего. Цвет — не единственный носитель смысла: надпись обязательна.
 * Полоса прототипа под шапкой — <ПлашкаПрототипа> (её ставит <Экран плашка>).
 */
import { View } from 'react-native';
import { useТема } from '../theme';
import { Значок, type ИмяЗначка } from './Icon';
import { Текст } from './Text';

export type ВидПлашкиМетки = 'черновик' | 'прототип' | 'ии' | 'внимание' | 'успех' | 'инфо' | 'скоро' | 'следующий';

export type СвойстваПлашки = { надпись: string; вид?: ВидПлашкиМетки; значок?: ИмяЗначка; testID?: string };

export function Плашка({ надпись, вид = 'инфо', значок, testID }: СвойстваПлашки) {
  const { цвет, радиус, поверхность } = useТема();
  const [фон, текст] =
    вид === 'черновик' || вид === 'прототип'
      ? [цвет.плашкаФон, цвет.плашкаТекст]
      : вид === 'ии'
        ? [цвет.акцентМягкий, цвет.акцент]
        : вид === 'внимание'
          ? [цвет.вниманиеФон, цвет.внимание]
          : вид === 'успех'
            ? [цвет.успехФон, цвет.успех]
            : вид === 'следующий'
              ? [цвет.следующийФон, цвет.следующийТекст]
              : поверхность === 'герой'
                ? [цвет.геройЛиния, цвет.геройТекст]
                : [цвет.поверхностьВторая, цвет.текстВторой];
  return (
    <View
      testID={testID}
      style={{
        flexDirection: 'row',
        alignItems: 'center',
        alignSelf: 'flex-start',
        gap: 4,
        minHeight: 24,
        paddingHorizontal: 10,
        paddingVertical: 2,
        borderRadius: радиус.круг,
        backgroundColor: фон,
      }}
    >
      {значок ? <Значок имя={значок} размер={14} цвет={текст} толщина={2.25} /> : null}
      <Текст вид="метка" цвет={текст}>
        {надпись}
      </Текст>
    </View>
  );
}
