/**
 * Прогресс урока: «Задание 3 из 10» и полоса из отрезков — пройденные (акцент), текущий (мягкое золото
 * «следующий»), будущие (цвет границы). Больше 24 заданий — сплошная полоса.
 *
 * Контракт: <ПрогрессУрока текущий={3} всего={10} подпись? />
 *   текущий — номер текущего задания (1…всего); подпись (по умолчанию true) — текст над полосой.
 * Доступность: progressbar с подписью «Задание 3 из 10»; цвет — не единственный носитель смысла (подпись).
 * Только прогресс внутри урока: без очков, жизней и наград (CLAUDE.md, правило 9).
 * Дизайн-система 19.11.2026 (docs/дизайн/03-дизайн-система.md): золото — только текущий шаг (≤ 5 % площади).
 */
import { View } from 'react-native';
import { useПеревод } from '../i18n';
import { useТема } from '../theme';
import { Текст } from './Text';

/** До скольких заданий рисуем отрезки (дальше они слишком узкие на 360 px). */
const МАКС_ОТРЕЗКОВ = 24;

export function ПрогрессУрока({ текущий, всего, подпись = true }: { текущий: number; всего: number; подпись?: boolean }) {
  const { t } = useПеревод();
  const { цвет, радиус, отступ } = useТема();
  const n = Math.max(0, Math.min(текущий, всего));
  const доля = всего > 0 ? n / всего : 0;
  const надпись = t('прогресс.задание', { текущий: n, всего });
  const отрезки = всего > 0 && всего <= МАКС_ОТРЕЗКОВ;
  return (
    <View style={{ gap: отступ.s }}>
      {подпись ? (
        <Текст вид="метка" цвет={цвет.текстВторой}>
          {надпись}
        </Текст>
      ) : null}
      <View
        accessibilityRole="progressbar"
        accessibilityLabel={надпись}
        accessibilityValue={{ min: 0, max: всего, now: n }}
        style={{ flexDirection: 'row', gap: 3, height: 6 }}
      >
        {отрезки ? (
          Array.from({ length: всего }, (_, i) => (
            <View
              key={i}
              style={{
                flex: 1,
                borderRadius: радиус.круг,
                backgroundColor: i < n - 1 ? цвет.акцент : i === n - 1 ? цвет.следующийФон : цвет.граница,
              }}
            />
          ))
        ) : (
          <View style={{ flex: 1, borderRadius: радиус.круг, backgroundColor: цвет.граница, overflow: 'hidden' }}>
            <View style={{ width: `${Math.round(доля * 100)}%`, height: '100%', backgroundColor: цвет.акцент, borderRadius: радиус.круг }} />
          </View>
        )}
      </View>
    </View>
  );
}
