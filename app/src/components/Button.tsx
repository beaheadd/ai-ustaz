/**
 * Кнопка.
 *
 * Контракт:
 *   <Кнопка надпись="Начать" приНажатии={() => …}
 *           вид="основная|вторичная|тихая" отключена? крупная? значок? растянуть? подсказка? testID? />
 * - основная — одна на экран (главное действие): изумруд, светлый текст;
 *   вторичная — мягкий изумрудный фон; тихая — без фона (второстепенное, «Пропустить»).
 *   На поверхности «герой» (<Карточка вид="герой">) основная — мягкое золото, вторичная — контур.
 * - значок — имя значка из набора (<Значок>: 'микрофон', 'кибла', 'играть'…) или короткий символ (●, ▶, ■);
 *   эмодзи — только без лиц; растровых картинок нет.
 * - растянуть (по умолчанию true) — на всю ширину колонки.
 * - Высота ≥ 48 px (крупная — 56): удобно пальцем. Нажатие — затемнение, без звука и вибрации.
 */
import { Pressable, StyleSheet, Text, View } from 'react-native';
import { useТема } from '../theme';
import { Значок, этоЗначок } from './Icon';
import { стильТекста } from './Text';

export type ВидКнопки = 'основная' | 'вторичная' | 'тихая';

export type СвойстваКнопки = {
  надпись: string;
  приНажатии: () => void;
  вид?: ВидКнопки;
  отключена?: boolean;
  крупная?: boolean;
  /** Имя значка из набора (ИмяЗначка) или короткий текстовый символ. */
  значок?: string;
  растянуть?: boolean;
  /** accessibilityHint: что произойдёт после нажатия. */
  подсказка?: string;
  testID?: string;
};

export function Кнопка({
  надпись,
  приНажатии,
  вид = 'основная',
  отключена = false,
  крупная = false,
  значок,
  растянуть = true,
  подсказка,
  testID,
}: СвойстваКнопки) {
  const { цвет, радиус, отступ, поверхность } = useТема();
  const герой = поверхность === 'герой';
  const фон = (нажата: boolean) =>
    вид === 'основная'
      ? герой
        ? цвет.следующийФон
        : нажата
          ? цвет.акцентНажат
          : цвет.акцент
      : вид === 'вторичная'
        ? герой
          ? 'transparent'
          : цвет.акцентМягкий
        : нажата
          ? цвет.акцентМягкий
          : 'transparent';
  const цветТекста = вид === 'основная' ? (герой ? цвет.следующийТекст : цвет.акцентТекст) : цвет.акцент;
  const рамка = вид === 'вторичная' && герой ? цвет.границаЭлемента : 'transparent';
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityState={{ disabled: отключена }}
      accessibilityHint={подсказка}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      style={({ pressed }) => [
        стили.кнопка,
        {
          backgroundColor: фон(pressed),
          borderRadius: радиус.m,
          minHeight: крупная ? 56 : 48,
          paddingHorizontal: отступ.l,
          alignSelf: растянуть ? 'stretch' : 'flex-start',
          borderWidth: 1,
          borderColor: рамка,
          opacity: отключена ? 0.45 : pressed && (герой || вид !== 'основная') ? 0.85 : 1,
        },
      ]}
    >
      <View style={стили.ряд}>
        {значок ? (
          этоЗначок(значок) ? (
            <Значок имя={значок} размер={крупная ? 22 : 20} цвет={цветТекста} толщина={2} />
          ) : (
            <Text style={[стили.символ, { color: цветТекста, fontSize: крупная ? 22 : 18 }]}>{значок}</Text>
          )
        ) : null}
        <Text style={[стильТекста('кнопка'), { color: цветТекста, textAlign: 'center' }]}>
          {надпись}
        </Text>
      </View>
    </Pressable>
  );
}

const стили = StyleSheet.create({
  кнопка: { justifyContent: 'center', alignItems: 'center', paddingVertical: 10 },
  ряд: { flexDirection: 'row', alignItems: 'center', justifyContent: 'center', gap: 8 },
  символ: { lineHeight: 26 },
});
