/**
 * ОбразУстаза — образ AI Устаза для чата и центральной кнопки меню: взрослый мужчина в одежде сунны, БЕЗ ЛИЦА.
 *
 * Решение владельца 27.11.2026: «Нужно создать образ AI Устаза без лица. Мужчина без лица, в одежде сунна, который
 * объясняет… помогает мусульманину больше понять». Это меняет правило 9 CLAUDE.md («маскот — предмет без лица или без
 * маскота») на «образ Устаза — мужчина без лица в одежде сунны (не пророк и не сподвижник)» — обобщённый образ учителя.
 *
 * Как нарисован (свой рисунок, одна система с иллюстрациями ИллюстрацияРаздела, components/SectionArt.tsx):
 *   - голова — пустой овал телесного цвета: без глаз, носа, рта и бороды (бороду не рисуем — она была бы частью лица);
 *   - белая тюбетейка-куфи с тонким узором; светлая джубба (камис) с воротом; поверх — зелёный плащ (бишт) с золотой
 *     каймой; в руках — раскрытая книга (учитель объясняет по книге), ладони — простые овалы без пальцев;
 *   - фон — круг (поверхностьАкцент темы) или без фона.
 * Решение владельца 28.11.2026 (дизайн A): силуэт тот же (узнаваемость), геометрия — design/illustrations.ts «устаз»,
 * цвета — роли ПАЛИТРА_ИЛЛЮСТРАЦИЙ темы (в тёмной — приглушённые: аудит P2-18, светлое пятно в меню ночью).
 * Контракт: <ОбразУстаза размер={32|48|96|160} фон? testID? /> — inline SVG (primitives/svg), viewBox 64×64, декоративный
 *   (подпись даёт место, где он стоит: «AI Ustaz» в меню, имя в пузыре чата). Без анимации.
 */
import { View } from 'react-native';
import { ПАЛИТРА_ИЛЛЮСТРАЦИЙ, useТема } from '../theme';
import { Circle, Svg } from './primitives/svg';
import { ФигурыИллюстрации } from './SectionArt';

export function ОбразУстаза({ размер = 48, фон = true, testID }: { размер?: number; фон?: boolean; testID?: string }) {
  const { цвет, тёмная } = useТема();
  const п = тёмная ? ПАЛИТРА_ИЛЛЮСТРАЦИЙ.тёмная : ПАЛИТРА_ИЛЛЮСТРАЦИЙ.светлая;
  return (
    <View
      testID={testID}
      {...({ 'aria-hidden': true } as object)}
      importantForAccessibility="no-hide-descendants"
      style={{ width: размер, height: размер }}
    >
      <Svg width={размер} height={размер} viewBox="0 0 64 64">
        {фон ? <Circle cx={32} cy={32} r={32} fill={цвет.поверхностьАкцент} /> : null}
        <ФигурыИллюстрации имя="устаз" п={п} />
      </Svg>
    </View>
  );
}
