/**
 * Строка «Скачать хадисы для офлайн» — сохранить все хадисы в кэш service worker'а, чтобы они открывались без сети.
 *
 * Владелец 27.11.2026: «пусть все суры и другая информация сохраняются… чтобы можно было пользоваться офлайн».
 * Коран, зикры и махраджи докачиваются сами (offline/offline.ts); хадисы большие (≈7 МБ) — по кнопке, с ходом загрузки.
 * Показывается только там, где есть worker (aiustaz.pro); на batr.kz и без поддержки — ничего.
 * Контракт: <ЗагрузкаОфлайн группа="хадисы" />. testID: офлайн-<группа>, офлайн-<группа>-скачать, офлайн-<группа>-ход,
 * офлайн-<группа>-готово. kk, uz, en — черновики.
 */
import { View } from 'react-native';
import { создатьСловарь, useСловарь } from '../i18n';
import { useГруппаОфлайн, type ГруппаОфлайн } from '../offline/offline';
import { useТема } from '../theme';
import { Кнопка } from './Button';
import { Значок } from './Icon';
import { Текст } from './Text';

const СЛОВАРЬ = создатьСловарь({
  ru: { скачать: 'Скачать хадисы для офлайн ({мб} МБ)', ход: 'Скачиваем: {готово} из {всего}', готово: 'Хадисы сохранены — открываются без интернета' },
  kk: { скачать: 'Хадистерді офлайнға жүктеу ({мб} МБ)', ход: 'Жүктелуде: {всего} ішінен {готово}', готово: 'Хадистер сақталды — интернетсіз ашылады' },
  uz: { скачать: 'Hadislarni oflayn uchun yuklab olish ({мб} MB)', ход: 'Yuklanmoqda: {всего} dan {готово}', готово: 'Hadislar saqlandi — internetsiz ochiladi' },
  en: { скачать: 'Download hadith for offline ({мб} MB)', ход: 'Downloading: {готово} of {всего}', готово: 'Hadith saved — they open without internet' },
});

export function ЗагрузкаОфлайн({ группа }: { группа: ГруппаОфлайн }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const г = useГруппаОфлайн(группа);
  if (!г.можно) return null;
  const все = г.всего > 0 && г.есть >= г.всего;
  const мб = (г.байт / 1048576).toFixed(1);
  return (
    <View testID={'офлайн-' + группа} style={{ gap: отступ.xs }}>
      {все ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }} testID={'офлайн-' + группа + '-готово'}>
          <Значок имя="галочка" размер={18} цвет={цвет.акцент} />
          <Текст вид="мелкий" стиль={{ flex: 1 }}>
            {т('готово')}
          </Текст>
        </View>
      ) : г.идёт ? (
        <Текст вид="мелкий" табличные testID={'офлайн-' + группа + '-ход'} {...({ accessibilityLiveRegion: 'polite' } as object)}>
          {т('ход', { готово: г.есть, всего: г.всего })}
        </Текст>
      ) : (
        <Кнопка вид="вторичная" значок="установить" надпись={т('скачать', { мб })} приНажатии={г.скачать} testID={'офлайн-' + группа + '-скачать'} />
      )}
    </View>
  );
}
