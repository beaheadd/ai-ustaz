/**
 * Упражнение «Пара похожих» (задание «выбор» ровно с 2 вариантами): две похожие буквы
 * или слога рядом, крупно — различить на глаз (на слух — когда появятся записи кари).
 *
 * Контракт: <ПараПохожих задание={ЗаданиеВыбор} приГотово={…} />
 *   вопрос («Где ح?»), показ — необязательно; варианты — 2 буквы/слога; верный — индекс.
 * Две попытки, в итог идёт первая (useВыбор); мягкая обратная связь «Верно!» / «Посмотрите ещё раз»
 * репликой ИИ-наставника. Показ — в карточке-арке, две крупные плитки рядом.
 */
import { View } from 'react-native';
import type { ЗаданиеВыбор } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { useПеревод } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { арабскийВарианта, КнопкаВарианта, ОбратнаяСвязь, стильКрупного, type СвойстваУпражнения } from './common';
import { useВыбор } from './useChoice';
import { ПослушатьКари } from '../LessonMaterials';

export function ПараПохожих({ задание, приГотово }: СвойстваУпражнения<ЗаданиеВыбор>) {
  const { язык } = useПеревод();
  const { отступ } = useТема();
  const в = useВыбор(задание, приГотово);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-пара">
      <СмешанныйТекст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.вопрос, язык)}
      </СмешанныйТекст>
      {задание.показ ? (
        <Карточка вид="арка" стиль={{ alignItems: 'center', paddingBottom: отступ.l }}>
          <АрабскийТекст размер="огромный" testID="показ" стиль={стильКрупного(88)}>
            {задание.показ}
          </АрабскийТекст>
        </Карточка>
      ) : null}
      <View style={{ flexDirection: 'row', gap: отступ.m }}>
        {задание.варианты.map((вариант, i) => (
          <View key={i} style={{ flex: 1, minHeight: 140, flexDirection: 'row' }}>
            <КнопкаВарианта
              вариант={вариант}
              номер={i + 1}
              состояние={в.состояние(i)}
              отключена={в.закрыт(i)}
              приНажатии={() => в.ответить(i)}
              размерАрабского="огромный"
              testID={'вариант-' + i}
            />
          </View>
        ))}
      </View>
      {в.выбран != null && в.обратнаяСвязь ? (
        <ОбратнаяСвязь
          состояние={в.обратнаяСвязь}
          соВторой={в.соВторой}
          выбрано={задание.варианты[в.выбран]}
          нужно={задание.варианты[задание.верный]}
          пояснение={локально(задание.пояснение, язык) || undefined}
        />
      ) : null}
      {/* Клип кари — только после ответа, чтобы не подсказывать: показанный текст или верный вариант. */}
      {в.завершено ? <ПослушатьКари тексты={[задание.показ, арабскийВарианта(задание.варианты[задание.верный])]} /> : null}
    </View>
  );
}
