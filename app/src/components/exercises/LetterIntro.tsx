/**
 * Упражнение «Знакомство с буквой» (задание «знакомство»).
 *
 * Контракт: <ЗнакомствоСБуквой задание={ЗаданиеЗнакомство} приГотово={…} />
 *   знак — буква крупно (120 px) в нише (карточка-арка); название; формы — отдельная, начальная, срединная,
 *   конечная (сеткой 2×2 справа налево, как в «Муаллим сани», по 72 px; null — у хамзы);
 *   соединяетсяСлева=false — пометка; подсказка — артикуляция (дословно из каталога ошибок §8; null — нет);
 *   подмены — «Обратите внимание»; примеры — буква с огласовками.
 * Голос кари: «Послушать кари», если есть клип буквы (content/media.json, с разрешением автора);
 * нет — честная строка. Синтеза нет. Без оценки: «Далее» открыто сразу.
 * testID: упражнение-знакомство, буква-крупно, название-буквы, формы-буквы, подсказка-артикуляции.
 * Дизайн-система 19.11.2026: арка — главное на экране (буква «стоит в нише»); без орнамента под арабским.
 */
import { View } from 'react-native';
import type { ЗаданиеЗнакомство } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { создатьСловарь, useПеревод, useСловарь, РЯД_АРАБСКИЙ } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { ПослушатьКари, useЕстьКлипКари } from '../LessonMaterials';
import { ЗаголовокРаздела, НетГолосаКари, ПунктыСНуктой, СтрокаСоЗначком, стильКрупного, useГотовоСразу, type СвойстваУпражнения } from './common';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    буква: 'Новая буква',
    отдельная: 'Отдельно',
    начальная: 'В начале',
    срединная: 'В середине',
    конечная: 'В конце',
    формы: 'Формы буквы',
    неСоединяется: 'Эта буква не соединяется со следующей буквой (слева).',
    подсказка: 'Как произносить',
    вниманию: 'Обратите внимание',
    примеры: 'С огласовками',
  },
  kk: {
    буква: 'Жаңа әріп',
    отдельная: 'Жеке',
    начальная: 'Басында',
    срединная: 'Ортасында',
    конечная: 'Соңында',
    формы: 'Әріп пішіндері',
    неСоединяется: 'Бұл әріп келесі әріппен (сол жағынан) жалғанбайды.',
    подсказка: 'Қалай айтылады',
    вниманию: 'Назар аударыңыз',
    примеры: 'Қозғалыс белгілерімен',
  },
  uz: {
    буква: 'Yangi harf',
    отдельная: 'Alohida',
    начальная: 'Boshida',
    срединная: 'Oʻrtasida',
    конечная: 'Oxirida',
    формы: 'Harf shakllari',
    неСоединяется: 'Bu harf keyingi (chapdagi) harfga qoʻshilmaydi.',
    подсказка: 'Qanday talaffuz qilinadi',
    вниманию: 'Eʼtibor bering',
    примеры: 'Harakatlar bilan',
  },
  en: {
    буква: 'New letter',
    отдельная: 'Isolated',
    начальная: 'Initial',
    срединная: 'Medial',
    конечная: 'Final',
    формы: 'Letter forms',
    неСоединяется: 'This letter does not join to the next letter (on its left).',
    подсказка: 'How to pronounce',
    вниманию: 'Note',
    примеры: 'With vowel marks',
  },
}, 'components/exercises/LetterIntro');

/** Ряды сетки форм: справа налево (row-reverse) — «отдельно» справа сверху, как в книге. */
const РЯДЫ_ФОРМ = [
  ['отдельная', 'начальная'],
  ['срединная', 'конечная'],
] as const;

export function ЗнакомствоСБуквой({ задание, приГотово }: СвойстваУпражнения<ЗаданиеЗнакомство>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  useГотовоСразу(приГотово);
  const название = локально(задание.название, язык);
  const естьКлип = useЕстьКлипКари([задание.знак]);
  const формы = задание.формы;

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-знакомство">
      <Карточка вид="арка" подъём={28} стиль={{ alignItems: 'center', paddingBottom: отступ.xl }}>
        <Текст вид="метка" цвет={цвет.золотоТекст}>
          {т('буква')}
        </Текст>
        <АрабскийТекст размер="огромный" testID="буква-крупно" стиль={стильКрупного(120, { безЗнаков: true })}>
          {задание.знак}
        </АрабскийТекст>
        <Текст вид="заголовок" testID="название-буквы" стиль={{ textAlign: 'center' }}>
          {название}
        </Текст>
      </Карточка>
      <ПослушатьКари тексты={[задание.знак]} />

      {формы ? (
        <View style={{ gap: отступ.s }}>
          <ЗаголовокРаздела надпись={т('формы')} />
          <View style={{ gap: отступ.s }} testID="формы-буквы">
            {РЯДЫ_ФОРМ.map((ряд, r) => (
              <View key={r} {...РЯД_АРАБСКИЙ} style={{ flexDirection: 'row-reverse', gap: отступ.s }}>
                {ряд.map((ключ) => (
                  <View
                    key={ключ}
                    accessible
                    accessibilityLabel={т(ключ) + ': ' + формы[ключ]}
                    style={{
                      flex: 1,
                      alignItems: 'center',
                      paddingTop: отступ.s,
                      paddingBottom: отступ.s,
                      borderRadius: радиус.l,
                      borderWidth: 1,
                      borderColor: цвет.граница,
                      backgroundColor: цвет.поверхность,
                    }}
                  >
                    <АрабскийТекст размер="огромный" выбираемый={false} стиль={стильКрупного(72, { безЗнаков: true })}>
                      {формы[ключ]}
                    </АрабскийТекст>
                    <Текст вид="метка" цвет={цвет.текстВторой} стиль={{ textAlign: 'center' }}>
                      {т(ключ)}
                    </Текст>
                  </View>
                ))}
              </View>
            ))}
          </View>
          {!задание.соединяетсяСлева ? <СтрокаСоЗначком значок="инфо" текст={т('неСоединяется')} /> : null}
        </View>
      ) : null}

      {задание.примеры.length > 0 ? (
        <Карточка>
          <ЗаголовокРаздела надпись={т('примеры')} />
          <View {...РЯД_АРАБСКИЙ} style={{ flexDirection: 'row-reverse', flexWrap: 'wrap', justifyContent: 'center', columnGap: отступ.xl, marginTop: отступ.l }}>
            {задание.примеры.map((пример, i) => (
              <АрабскийТекст key={i} размер="огромный" стиль={стильКрупного(60)}>
                {пример}
              </АрабскийТекст>
            ))}
          </View>
        </Карточка>
      ) : null}

      {задание.подсказка ? (
        <Карточка вид="акцент" testID="подсказка-артикуляции">
          <ЗаголовокРаздела надпись={т('подсказка')} значок="микрофон" />
          <СмешанныйТекст>{локально(задание.подсказка, язык)}</СмешанныйТекст>
        </Карточка>
      ) : null}

      {задание.подмены.length > 0 ? (
        <Карточка>
          <ЗаголовокРаздела надпись={т('вниманию')} значок="инфо" />
          <ПунктыСНуктой пункты={задание.подмены.map((п) => локально(п, язык))} />
        </Карточка>
      ) : null}

      {естьКлип ? null : <НетГолосаКари />}
    </View>
  );
}
