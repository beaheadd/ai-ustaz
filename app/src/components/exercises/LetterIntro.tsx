/**
 * Упражнение «Знакомство с буквой» (задание «знакомство»).
 *
 * Контракт: <ЗнакомствоСБуквой задание={ЗаданиеЗнакомство} приГотово={…} />
 *   знак — буква крупно (96 px); название; формы — отдельная, начальная, срединная, конечная
 *   (справа налево, как в «Муаллим сани»; null — у хамзы); соединяетсяСлева=false — пометка;
 *   подсказка — артикуляция (дословно из каталога ошибок §8; null — нет); подмены — «Обратите внимание»;
 *   примеры — буква с огласовками.
 * Голос кари: «Послушать кари», если есть клип буквы (content/media.json, с разрешением автора);
 * нет — честная строка. Синтеза нет. Без оценки: «Далее» открыто сразу.
 */
import { View } from 'react-native';
import type { ЗаданиеЗнакомство } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { ПослушатьКари, useЕстьКлипКари } from '../LessonMaterials';
import { НетГолосаКари, useГотовоСразу, type СвойстваУпражнения } from './common';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    буква: 'Буква',
    отдельная: 'Отдельно',
    начальная: 'В начале',
    срединная: 'В середине',
    конечная: 'В конце',
    формы: 'Формы буквы',
    неСоединяется: 'Эта буква не соединяется со следующей буквой (слева).',
    подсказка: 'Как произносить',
    вниманию: 'Обратите внимание',
    примеры: 'С огласовками',
  },
  kk: {
    буква: 'Әріп',
    отдельная: 'Жеке',
    начальная: 'Басында',
    срединная: 'Ортасында',
    конечная: 'Соңында',
    формы: 'Әріп пішіндері',
    неСоединяется: 'Бұл әріп келесі әріппен (сол жағынан) жалғанбайды.',
    подсказка: 'Қалай айтылады',
    вниманию: 'Назар аударыңыз',
    примеры: 'Қозғалыс белгілерімен',
  },
});

const ФОРМЫ = ['отдельная', 'начальная', 'срединная', 'конечная'] as const;

export function ЗнакомствоСБуквой({ задание, приГотово }: СвойстваУпражнения<ЗаданиеЗнакомство>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  useГотовоСразу(приГотово);
  const название = локально(задание.название, язык);
  const естьКлип = useЕстьКлипКари([задание.знак]);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-знакомство">
      <Карточка стиль={{ alignItems: 'center', paddingVertical: отступ.l }}>
        <АрабскийТекст размер="огромный" testID="буква-крупно" стиль={{ fontSize: 96, lineHeight: 170 }}>
          {задание.знак}
        </АрабскийТекст>
        <Текст вид="заголовок" testID="название-буквы" стиль={{ textAlign: 'center' }}>
          {название}
        </Текст>
      </Карточка>
      <ПослушатьКари тексты={[задание.знак]} />

      {задание.формы ? (
        <View style={{ gap: отступ.s }}>
          <Текст вид="мелкий">{т('формы')}</Текст>
          <View style={{ flexDirection: 'row-reverse', gap: отступ.s }} testID="формы-буквы">
            {ФОРМЫ.map((ключ) => (
              <View
                key={ключ}
                accessible
                accessibilityLabel={т(ключ) + ': ' + задание.формы![ключ]}
                style={{
                  flex: 1,
                  alignItems: 'center',
                  paddingVertical: отступ.s,
                  borderRadius: радиус.m,
                  borderWidth: 1,
                  borderColor: цвет.граница,
                  backgroundColor: цвет.поверхность,
                }}
              >
                <АрабскийТекст размер="крупный" выбираемый={false}>
                  {задание.формы![ключ]}
                </АрабскийТекст>
                <Текст вид="мелкий" стиль={{ textAlign: 'center' }}>
                  {т(ключ)}
                </Текст>
              </View>
            ))}
          </View>
          {!задание.соединяетсяСлева ? <Текст вид="второй">{т('неСоединяется')}</Текст> : null}
        </View>
      ) : null}

      {задание.примеры.length > 0 ? (
        <Карточка заголовок={т('примеры')}>
          <View style={{ flexDirection: 'row-reverse', flexWrap: 'wrap', justifyContent: 'center', columnGap: отступ.xl }}>
            {задание.примеры.map((пример, i) => (
              <АрабскийТекст key={i} размер="крупный">
                {пример}
              </АрабскийТекст>
            ))}
          </View>
        </Карточка>
      ) : null}

      {задание.подсказка ? (
        <Карточка акцент заголовок={т('подсказка')} testID="подсказка-артикуляции">
          <СмешанныйТекст>{локально(задание.подсказка, язык)}</СмешанныйТекст>
        </Карточка>
      ) : null}

      {задание.подмены.length > 0 ? (
        <Карточка заголовок={т('вниманию')}>
          {задание.подмены.map((п, i) => (
            <View key={i} style={{ flexDirection: 'row', gap: отступ.s }}>
              <Текст accessibilityElementsHidden importantForAccessibility="no">
                •
              </Текст>
              <Текст стиль={{ flex: 1 }}>{локально(п, язык)}</Текст>
            </View>
          ))}
        </Карточка>
      ) : null}

      {естьКлип ? null : <НетГолосаКари />}
    </View>
  );
}
