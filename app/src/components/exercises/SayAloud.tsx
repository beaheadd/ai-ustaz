/**
 * Упражнение «Скажи вслух» (задание «запись»): текст крупно → записать себя → послушать.
 *
 * Контракт: <СкажиВслух задание={ЗаданиеЗапись} приГотово={…} />
 *   подсказка — что сделать; читать — учебный текст или фрагмент Корана (дословно, Tanzil,
 *   хеш сверен движком); слоги — разбивка под словом (по кнопке «Показать подсказку»).
 * Запись — <ПанельЗаписи>: кнопка с индикатором громкости, «Стоп», «Послушать себя»,
 * «Записать ещё раз», «Удалить». ВЕРДИКТА НЕТ: «Записали! Послушайте себя». На своём домене (speech/flag.ts) —
 * ещё «Проверить»: мягкие подсказки «Проверьте себя»/«Подсказка» (эталон — текст задания, виды — задание.виды).
 * Голоса кари нет — честную строку «появится после записи эталона» и «без оценки» показывает <ПанельЗаписи>.
 * Запись живёт только в памяти страницы и удаляется при уходе с задания (размонтирование).
 * Без оценки: «Далее» открыто сразу (можно пройти без микрофона).
 */
import { useMemo, useState } from 'react';
import { View } from 'react-native';
import type { ЗаданиеЗапись } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { эталонЗадания } from '../../speech/check';
import { useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { ПослушатьКари } from '../LessonMaterials';
import { ПанельЗаписи } from '../RecordPanel';
import { Текст } from '../Text';
import { СЛОВАРЬ_УПРАЖНЕНИЙ, ТекстДляЧтения, useГотовоСразу, type СвойстваУпражнения } from './common';

/** Запись одного задания — не длиннее 30 с (слог, слово, фраза или аят). */
export const МАКС_ЗАПИСИ_МС = 30_000;

export function СкажиВслух({ задание, приГотово }: СвойстваУпражнения<ЗаданиеЗапись>) {
  const { язык } = useПеревод();
  const тО = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const { отступ } = useТема();
  const [подсказка, установитьПодсказку] = useState(false);
  useГотовоСразу(приГотово);
  // Подсказка «по слогам» — только для учебного текста (для Корана разбивку не показываем).
  const слоги = 'учебный' in задание.читать && задание.слоги && задание.слоги.length > 1 ? задание.слоги : null;
  // Эталон для проверки голосом (кнопка «Проверить» — только на своём домене, speech/flag.ts).
  const проверка = useMemo(() => ({ ...эталонЗадания(задание.читать), виды: задание.виды }), [задание]);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-скажи">
      <Текст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.подсказка, язык)}
      </Текст>
      <Карточка стиль={{ alignItems: 'center', paddingVertical: отступ.l }}>
        <ТекстДляЧтения читать={задание.читать} testID="текст-для-чтения" />
      </Карточка>
      {'учебный' in задание.читать ? <ПослушатьКари тексты={[задание.читать.учебный]} /> : null}
      {слоги ? (
        <>
          <Кнопка
            надпись={подсказка ? тО('подсказкаСкрыть') : тО('подсказкаПоказать')}
            вид="тихая"
            приНажатии={() => установитьПодсказку((п) => !п)}
            testID="подсказка"
          />
          {подсказка ? (
            <Карточка акцент testID="текст-подсказки">
              <Текст вид="мелкий">{тО('слоги')}</Текст>
              <АрабскийТекст размер="крупный">{слоги.join(' · ')}</АрабскийТекст>
            </Карточка>
          ) : null}
        </>
      ) : null}
      <ПанельЗаписи максДлительностьМс={МАКС_ЗАПИСИ_МС} проверка={проверка} />
    </View>
  );
}
