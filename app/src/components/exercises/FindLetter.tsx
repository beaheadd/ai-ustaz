/**
 * Упражнение «Найди букву/слог» (задание «выбор», 3–6 вариантов).
 *
 * Контракт: <НайдиБукву задание={ЗаданиеВыбор} приГотово={…} />
 *   вопрос; показ — что крупно над вариантами (необязательно); варианты — буквы/слоги
 *   (или текст на языке интерфейса); верный — индекс.
 * Две попытки, в итог идёт первая (useВыбор): «Верно!»; после первой ошибки — «Посмотрите ещё раз»;
 * после второй — «Это …, а нужно …» (+ пояснение из данных). Без звуков, таймеров и жизней.
 */
import { View } from 'react-native';
import type { ЗаданиеВыбор } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { useПеревод } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { арабскийВарианта, КнопкаВарианта, ОбратнаяСвязь, type СвойстваУпражнения } from './common';
import { useВыбор } from './useChoice';
import { ПослушатьКари } from '../LessonMaterials';

/** Разбить варианты на ряды: до 3 — один ряд; 4 — 2×2; больше — по 3. */
export function рядыВариантов<Т>(варианты: readonly Т[]): Т[][] {
  const вРяду = варианты.length <= 3 ? варианты.length : варианты.length === 4 ? 2 : 3;
  const ряды: Т[][] = [];
  for (let i = 0; i < варианты.length; i += вРяду) ряды.push(варианты.slice(i, i + вРяду));
  return ряды;
}

export function НайдиБукву({ задание, приГотово }: СвойстваУпражнения<ЗаданиеВыбор>) {
  const { язык } = useПеревод();
  const { отступ } = useТема();
  const в = useВыбор(задание, приГотово);
  const всеАрабские = задание.варианты.every((вар) => 'арабский' in вар);
  const индексы = задание.варианты.map((_, i) => i);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-найди">
      <СмешанныйТекст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.вопрос, язык)}
      </СмешанныйТекст>
      {задание.показ ? (
        <Карточка стиль={{ alignItems: 'center' }}>
          <АрабскийТекст размер="огромный" testID="показ">
            {задание.показ}
          </АрабскийТекст>
        </Карточка>
      ) : null}
      <View style={{ gap: отступ.s }}>
        {(всеАрабские ? рядыВариантов(индексы) : индексы.map((i) => [i])).map((ряд, r) => (
          <View key={r} style={{ flexDirection: 'row', gap: отступ.s }}>
            {ряд.map((i) => (
              <КнопкаВарианта
                key={i}
                вариант={задание.варианты[i]}
                номер={i + 1}
                состояние={в.состояние(i)}
                отключена={в.закрыт(i)}
                приНажатии={() => в.ответить(i)}
                testID={'вариант-' + i}
              />
            ))}
          </View>
        ))}
      </View>
      {в.выбран != null && в.обратнаяСвязь ? (
        <ОбратнаяСвязь
          состояние={в.обратнаяСвязь}
          соВторой={в.соВторой}
          выбрано={задание.варианты[в.выбран]}
          нужно={задание.варианты[задание.верный]}
          пояснение={локально(задание.пояснение, язык) || undefined}
        />
      ) : null}
      {/* Клип кари — только после ответа, чтобы не подсказывать: показанный текст или верный вариант. */}
      {в.завершено ? <ПослушатьКари тексты={[задание.показ, арабскийВарианта(задание.варианты[задание.верный])]} /> : null}
    </View>
  );
}
