/**
 * Упражнение «Теория» — карточка объяснения без проверки (задание «теория» без форм буквы).
 *
 * Контракт: <Теория задание={ЗаданиеТеория} приГотово={…} />
 *   заголовок, текст; примеры — учебные буквы/слоги крупно, справа налево.
 * Без оценки: «Далее» открыто сразу.
 */
import { View } from 'react-native';
import type { ЗаданиеТеория } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { useПеревод } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Карточка } from '../Card';
import { useГотовоСразу, type СвойстваУпражнения } from './common';

export function Теория({ задание, приГотово }: СвойстваУпражнения<ЗаданиеТеория>) {
  const { язык } = useПеревод();
  const { отступ } = useТема();
  useГотовоСразу(приГотово);
  const примеры = задание.примеры ?? [];
  return (
    <View style={{ gap: отступ.l }} testID="упражнение-теория">
      <СмешанныйТекст вид="заголовок">{локально(задание.заголовок, язык)}</СмешанныйТекст>
      <СмешанныйТекст>{локально(задание.текст, язык)}</СмешанныйТекст>
      {примеры.length > 0 ? (
        <Карточка>
          <View style={{ flexDirection: 'row-reverse', flexWrap: 'wrap', justifyContent: 'center', columnGap: отступ.xl }}>
            {примеры.map((пример, i) => (
              <АрабскийТекст key={i} размер="огромный">
                {пример}
              </АрабскийТекст>
            ))}
          </View>
        </Карточка>
      ) : null}
    </View>
  );
}
