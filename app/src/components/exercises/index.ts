/**
 * Упражнения урока — реестр и единая точка входа.
 *
 * Контракт:
 *   <Упражнение задание={Задание} приГотово={(итог, опции?) => …} заменитьДалее?={(замена | null) => …} />
 *     выбирает компонент по видУпражнения(задание) (engine/lessonEngine.ts) и рисует его.
 *   УПРАЖНЕНИЯ — вид → компонент; СвойстваУпражнения<З> — общий интерфейс (см. common.tsx).
 *
 * Виды: знакомство (буква и 4 формы) · теория · найди (букву/слог) · пара (похожих) ·
 *       собери (слог) · прочитай (слог, без записи) · скажи (вслух, запись без вердикта) · лестница.
 * Новый вид: компонент в этой папке → ВидУпражнения и видУпражнения() в lessonEngine.ts → строка здесь.
 */
import { createElement, type ComponentType } from 'react';
import type { Задание, ЗаданиеВыбор, ЗаданиеЗапись, ЗаданиеЗнакомство, ЗаданиеЛестница, ЗаданиеПрочитай, ЗаданиеТеория } from '../../content/types';
import { видУпражнения, type ВидУпражнения } from '../../engine/lessonEngine';
import { СобериСлог } from './BuildSyllable';
import type { СвойстваУпражнения } from './common';
import { НайдиБукву } from './FindLetter';
import { Лестница } from './Ladder';
import { ЗнакомствоСБуквой } from './LetterIntro';
import { ПрочитайСлог } from './ReadSyllable';
import { СкажиВслух } from './SayAloud';
import { ПараПохожих } from './SimilarPair';
import { Теория } from './Theory';

export type { ИтогЗадания } from '../../engine/lessonEngine';
export type { ЗаменаДалее, ОпцииГотово, СвойстваУпражнения } from './common';
export { НайдиБукву, ПараПохожих, СобериСлог, ПрочитайСлог, СкажиВслух, Лестница, ЗнакомствоСБуквой, Теория };

type ЗаданиеВида = {
  знакомство: ЗаданиеЗнакомство;
  теория: ЗаданиеТеория;
  найди: ЗаданиеВыбор;
  пара: ЗаданиеВыбор;
  собери: ЗаданиеВыбор;
  прочитай: ЗаданиеПрочитай;
  скажи: ЗаданиеЗапись;
  лестница: ЗаданиеЛестница;
};

export const УПРАЖНЕНИЯ: { [В in ВидУпражнения]: ComponentType<СвойстваУпражнения<ЗаданиеВида[В]>> } = {
  знакомство: ЗнакомствоСБуквой,
  теория: Теория,
  найди: НайдиБукву,
  пара: ПараПохожих,
  собери: СобериСлог,
  прочитай: ПрочитайСлог,
  скажи: СкажиВслух,
  лестница: Лестница,
};

export function Упражнение({ задание, приГотово, заменитьДалее }: СвойстваУпражнения<Задание>) {
  const вид = видУпражнения(задание);
  const Компонент = УПРАЖНЕНИЯ[вид] as ComponentType<СвойстваУпражнения<Задание>>;
  return createElement(Компонент, { задание, приГотово, заменитьДалее });
}
