/** Кегли учебного арабского (как РАЗМЕРЫ в ArabicText.tsx). */
const КЕГЛИ: Record<РазмерАрабского, number> = { малый: 24, средний: 32, крупный: 46, огромный: 68 };

/**
 * Крупный учебный арабский по центру ниши. У Amiri Quran базовая линия на 0,59 em ниже середины строки:
 * сверху строки пусто (место под знаки), а кясра и хвост «م» уходят ниже её края — без поправки буква сидит
 * у нижнего края карточки. Поправка: блок подтянут вверх (marginTop) и добавлено место снизу (paddingBottom).
 *   по умолчанию — со знаками (слоги с огласовками): строка 1,9 em, вверх 0,5 em, снизу 0,24 em;
 *   безЗнаков — голая буква или форма с татвилем: строка 1,5 em, вверх 0,55 em, снизу 0,36 em (компактнее).
 * Только для учебных букв и слогов (Коран — без поправок, как есть).
 */
export function стильКрупного(кегль: number | РазмерАрабского, { безЗнаков = false }: { безЗнаков?: boolean } = {}): TextStyle {
  const к = typeof кегль === 'number' ? кегль : КЕГЛИ[кегль];
  const [строка, вверх, снизу] = безЗнаков ? [1.5, 0.55, 0.36] : [1.9, 0.5, 0.24];
  return { fontSize: к, lineHeight: Math.round(к * строка), marginTop: -Math.round(к * вверх), paddingBottom: Math.round(к * снизу) };
}

/** Арабский текст варианта ответа (буква, слог, учебное слово) или null — для клипа кари. */
export function арабскийВарианта(вариант: ВариантОтвета | undefined): string | null {
  return вариант && 'арабский' in вариант ? вариант.арабский : null;
}

/** Сообщить «готово» один раз при появлении (теория, голос — без оценки). */
export function useГотовоСразу(приГотово: СвойстваУпражнения['приГотово']) {
  const ссылка = useRef(приГотово);
  ссылка.current = приГотово;
  useEffect(() => {
    ссылка.current({ оценивается: false });
  }, []);
}

