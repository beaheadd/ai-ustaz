/**
 * Общее для упражнений урока: интерфейс упражнения, кнопка-вариант, мягкая обратная связь,
 * показ учебного арабского или фрагмента Корана, текст со вставками, оформление разделов.
 *
 * Контракт упражнения (все компоненты в components/exercises/ его соблюдают):
 *   type СвойстваУпражнения<З extends Задание> = {
 *     задание: З;                                   // проверенное движком (engine/lessonEngine.ts)
 *     приГотово: (итог: ИтогЗадания, опции?: { сразуДалее?: boolean }) => void;
 *     заменитьДалее?: (замена: ЗаменаДалее | null) => void;
 *   };
 *   - приГотово вызывается, когда задание можно завершить: экран урока откроет «Далее»
 *     (сразуДалее — перейти без нажатия «Далее»).
 *   - Засчитывается первый вызов (повторные движок игнорирует).
 *   - Оценивается только выбор: { оценивается: true, верно } — по ПЕРВОЙ попытке (useВыбор).
 *     Голос и теория — { оценивается: false }.
 *   - заменитьДалее — упражнение может поменять нижнюю кнопку экрана урока: надпись и, если задано
 *     приНажатии, действие (например, «Следующая ступень» в «Лестнице»); null — обычная «Далее».
 *     Без приНажатии меняется только надпись, а кнопка ведёт дальше (если задание готово).
 *     Экран урока сбрасывает замену при переходе к следующему заданию. Lesson0Screen её не передаёт.
 *   - Упражнение пересоздаётся на каждое задание (key) — своё состояние держит внутри.
 *
 * Обратная связь — мягкая, репликой ИИ-наставника (<РепликаУстаза>, эмблема-фонарь): «Верно!» спокойно,
 * без конфетти и звука; после первой ошибки — «Посмотрите ещё раз» (верный не раскрываем), после второй —
 * «Сравните» с подсветкой верного (без «неправильно», «плохо»). Арабские варианты в обратной связи —
 * карточками крупным шрифтом (огласовки должны быть видны). Блок обратной связи сам прокручивает экран
 * к себе (useПрокрутка), чтобы не прятаться под нижней панелью. Без звуков-эффектов, без жизней и таймеров.
 *
 * Оформление (дизайн-система 19.11.2026, docs/дизайн/03-дизайн-система.md): только компоненты и токены темы.
 *   стильКрупного(кегль) — крупный учебный арабский (Amiri Quran) по центру ниши: у шрифта базовая линия
 *     низко (подъём 1,815 em, спуск 0,634 em), без поправки буква «проваливается» вниз карточки.
 *   <ЗаголовокРаздела надпись значок?> — метка раздела внутри карточки («Формы буквы», «Как произносить»).
 *   <ПунктыСНуктой пункты> — список с ромбами-нуктами (вместо «•»).
 *   ПодписьКорана, ТекстДляЧтения — Коран всегда в своей рамке (обычная карточка, не арка) и с источником.
 */
