/** Арабский текст варианта ответа (буква, слог, учебное слово) или null — для клипа кари. */
export function арабскийВарианта(вариант: ВариантОтвета | undefined): string | null {
  return вариант && 'арабский' in вариант ? вариант.арабский : null;
}

/** Сообщить «готово» один раз при появлении (теория, голос — без оценки). */
export function useГотовоСразу(приГотово: СвойстваУпражнения['приГотово']) {
  const ссылка = useRef(приГотово);
  ссылка.current = приГотово;
  useEffect(() => {
    ссылка.current({ оценивается: false });
  }, []);
}

/** Строка с вставками: шаблон «Это {выбрано}, а нужно {нужно}.» + узлы для {имён}. */
export function ТекстСВставками({ шаблон, вставки, вид = 'обычный', стиль }: {
  шаблон: string;
  вставки: Record<string, ReactNode>;
  вид?: 'обычный' | 'подзаголовок';
  стиль?: StyleProp<TextStyle>;
}) {
  const части = шаблон.split(/(\{[^{}]+\})/g);
  return (
    <Текст вид={вид} стиль={стиль}>
      {части.map((ч, i) => {
        const имя = /^\{([^{}]+)\}$/.exec(ч)?.[1];
        return <Fragment key={i}>{имя && имя in вставки ? вставки[имя] : ч}</Fragment>;
      })}
    </Текст>
  );
}

/** Вариант ответа как узел в строке (арабский — RTL, Amiri, не мельче 36 px; текст — без внешних кавычек). */
export function ВариантВСтроке({ вариант }: { вариант: ВариантОтвета }) {
  const { язык } = useПеревод();
  if ('арабский' in вариант) {
    return (
      <АрабскийТекст встроенный размер="малый" стиль={{ fontSize: 36 }}>
        {вариант.арабский}
      </АрабскийТекст>
    );
  }
  return <>{локально(вариант.текст, язык)}</>;
}

/** Мини-карточка варианта в обратной связи: подпись сверху, арабский крупно (огласовки видны). */
function КарточкаВарианта({ подпись, вариант, акцент, testID }: { подпись: string; вариант: ВариантОтвета; акцент: boolean; testID?: string }) {
  const { цвет, радиус, отступ } = useТема();
  return (
    <View
      testID={testID}
      style={{
        flex: 1,
        alignItems: 'center',
        gap: 2,
        paddingVertical: отступ.xs,
        borderRadius: радиус.m,
        borderWidth: 2,
        borderColor: акцент ? цвет.успех : цвет.внимание,
        backgroundColor: цвет.поверхность,
      }}
    >
      <Текст вид="мелкий">{подпись}</Текст>
      {'арабский' in вариант ? (
        <АрабскийТекст размер="крупный" стиль={{ lineHeight: 84 }}>
          {вариант.арабский}
        </АрабскийТекст>
      ) : null}
    </View>
  );
}

export function подписьВарианта(вариант: ВариантОтвета, язык: 'ru' | 'kk'): string {
  return 'арабский' in вариант ? вариант.арабский : локально(вариант.текст, язык);
}

export type СостояниеВарианта = 'обычный' | 'верный' | 'выбранНеверный' | 'приглушён';

/** Кнопка-вариант: ≥ 48 px (крупная — ≥ 88 px), видимый фокус с клавиатуры, aria-label. */
export function КнопкаВарианта({
  вариант,
  номер,
  состояние,
  приНажатии,
  отключена,
  размерАрабского = 'крупный',
  выбрана = false,
  подписьДоступности,
  testID,
}: {
  вариант: ВариантОтвета;
  номер: number;
  состояние: СостояниеВарианта;
  приНажатии: () => void;
  отключена?: boolean;
  размерАрабского?: РазмерАрабского;
  /** Для «собери»: вариант выбран, но ещё не проверен. */
  выбрана?: boolean;
  /** Подпись для экранного диктора вместо содержимого (например, слог целиком для знака огласовки). */
  подписьДоступности?: string;
  testID?: string;
}) {
  const { цвет, радиус, отступ, шрифт } = useТема();
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const рамка =
    состояние === 'верный' ? цвет.успех : состояние === 'выбранНеверный' ? цвет.внимание : выбрана ? цвет.акцент : цвет.граница;
  const фон = состояние === 'верный' ? цвет.поверхностьАкцент : выбрана ? цвет.акцентМягкий : цвет.поверхность;
  const пометка =
    состояние === 'верный' ? ', ' + т('вариантВерный') : состояние === 'выбранНеверный' ? ', ' + т('вариантВыбран') : '';
  const арабский = 'арабский' in вариант;
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={т('вариант', { номер, что: подписьДоступности ?? подписьВарианта(вариант, язык) }) + пометка}
      accessibilityState={{ disabled: отключена, selected: выбрана || состояние === 'выбранНеверный' }}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      style={(с) => {
        const { pressed, focused } = с as { pressed: boolean; focused?: boolean };
        return {
          flex: 1,
          minWidth: 64,
          minHeight: арабский ? 88 : 56,
          alignItems: 'center',
          justifyContent: 'center',
          paddingHorizontal: отступ.m,
          paddingVertical: отступ.xs,
          borderRadius: радиус.m,
          borderWidth: состояние === 'обычный' && !выбрана ? 1 : 3,
          borderColor: рамка,
          backgroundColor: фон,
          opacity: состояние === 'приглушён' ? 0.55 : pressed ? 0.8 : 1,
          ...(Platform.OS === 'web' && focused ? { outlineColor: цвет.акцент, outlineWidth: 3, outlineStyle: 'solid', outlineOffset: 2 } : {}),
        } as object;
      }}
    >
      {арабский ? (
        <АрабскийТекст размер={размерАрабского} выбираемый={false}>
          {вариант.арабский}
        </АрабскийТекст>
      ) : (
        <Текст стиль={{ fontSize: шрифт.крупный, textAlign: 'center' }}>{локально(вариант.текст, язык)}</Текст>
      )}
      {состояние === 'верный' ? (
        <Текст вид="мелкий" стиль={{ color: цвет.успех }} accessibilityElementsHidden importantForAccessibility="no">
          ✓
        </Текст>
      ) : null}
    </Pressable>
  );
}

/**
 * Мягкая обратная связь после ответа на выбор. Только тап — голос не оценивается.
 * состояние: 'верно' — «Верно!» (или «Теперь верно…», если со второй попытки);
 *            'ещёРаз' — после первой ошибки: что выбрано, верный НЕ раскрывается;
 *            'нужно' — после второй ошибки: выбрано и нужно рядом.
 * testID: ответ-верно | ответ-ещё-раз | ответ-подсказка.
 */
export function ОбратнаяСвязь({
  состояние,
  выбрано,
  нужно,
  пояснение,
  соВторой = false,
}: {
  состояние: 'верно' | 'ещёРаз' | 'нужно';
  выбрано: ВариантОтвета;
  нужно: ВариантОтвета;
  пояснение?: string;
  /** Верный ответ дан со второй попытки. */
  соВторой?: boolean;
}) {
  const { цвет, радиус, отступ } = useТема();
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const { вКонец } = useПрокрутка();
  const верно = состояние === 'верно';
  const арабские = 'арабский' in выбрано && 'арабский' in нужно;

  // Новый ответ — прокрутить к блоку, чтобы он не прятался под нижней панелью «Далее».
  useEffect(() => {
    вКонец();
  }, [состояние, выбрано, вКонец]);

  return (
    <View
      accessibilityLiveRegion="polite"
      testID={верно ? 'ответ-верно' : состояние === 'ещёРаз' ? 'ответ-ещё-раз' : 'ответ-подсказка'}
      style={{
        borderRadius: радиус.m,
        padding: отступ.m,
        gap: отступ.s,
        backgroundColor: верно ? цвет.поверхностьАкцент : цвет.поверхность,
        borderWidth: 1,
        borderColor: верно ? цвет.успех : цвет.внимание,
      }}
    >
      {верно ? (
        <Текст вид="подзаголовок" стиль={{ color: цвет.успех }}>
          {соВторой ? т('вернаяВторая') : т('верно')}
        </Текст>
      ) : состояние === 'ещёРаз' ? (
        арабские ? (
          <>
            <Текст вид="подзаголовок">{т('неТоЕщёРаз')}</Текст>
            <View style={{ flexDirection: 'row', justifyContent: 'center' }}>
              <View style={{ width: '50%' }}>
                <КарточкаВарианта подпись={т('вашВыбор')} вариант={выбрано} акцент={false} testID="ответ-выбрано" />
              </View>
            </View>
          </>
        ) : (
          <ТекстСВставками вид="подзаголовок" шаблон={т('этоЕщёРаз')} вставки={{ выбрано: <ВариантВСтроке вариант={выбрано} /> }} />
        )
      ) : арабские ? (
        <>
          <Текст вид="подзаголовок">{т('сравните')}</Текст>
          <View style={{ flexDirection: 'row', gap: отступ.s }}>
            <КарточкаВарианта подпись={т('вашВыбор')} вариант={выбрано} акцент={false} testID="ответ-выбрано" />
            <КарточкаВарианта подпись={т('нужноПодпись')} вариант={нужно} акцент testID="ответ-нужно" />
          </View>
        </>
      ) : (
        <ТекстСВставками
          шаблон={т('этоНоНужно')}
          вставки={{ выбрано: <ВариантВСтроке вариант={выбрано} />, нужно: <ВариантВСтроке вариант={нужно} /> }}
        />
      )}
      {пояснение && состояние !== 'ещёРаз' ? <СмешанныйТекст вид="второй">{пояснение}</СмешанныйТекст> : null}
    </View>
  );
}

/** Подпись фрагмента Корана: «Сура 112, аят 1» (+ слова). */
export function ПодписьКорана({ фрагмент }: { фрагмент: ФрагментКорана }) {
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const ссылка = фрагмент.слова
    ? т('сураАятСлова', { сура: фрагмент.сура, аят: фрагмент.аят, с: фрагмент.слова.с, по: фрагмент.слова.по })
    : т('сураАят', { сура: фрагмент.сура, аят: фрагмент.аят });
  return (
    <View style={{ gap: 2 }}>
      <Текст вид="мелкий" стиль={{ textAlign: 'center' }}>
        {ссылка}
      </Текст>
      <Текст вид="мелкий" стиль={{ textAlign: 'center' }}>
        {т('источникКорана')}
      </Текст>
    </View>
  );
}

/**
 * Что читать: учебный арабский (буква, слог, учебное слово) или фрагмент Корана.
 * Коран выводится строкой из данных как есть (движок уже сверил sha256 с Tanzil).
 */
export function ТекстДляЧтения({
  читать,
  размер = 'огромный',
  testID,
}: {
  читать: { учебный: string } | { коран: ФрагментКорана };
  размер?: РазмерАрабского;
  testID?: string;
}) {
  if ('коран' in читать) {
    return (
      <View style={{ gap: 4 }} testID={testID}>
        <АрабскийТекст размер="крупный" testID="текст-корана">
          {читать.коран.текст}
        </АрабскийТекст>
        <ПодписьКорана фрагмент={читать.коран} />
      </View>
    );
  }
  return (
    <АрабскийТекст размер={размер} testID={testID}>
      {читать.учебный}
    </АрабскийТекст>
  );
}

