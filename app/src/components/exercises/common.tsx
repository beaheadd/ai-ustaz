/**
 * Общее для упражнений урока: интерфейс упражнения, кнопка-вариант, мягкая обратная связь,
 * показ учебного арабского или фрагмента Корана, текст со вставками.
 *
 * Контракт упражнения (все компоненты в components/exercises/ его соблюдают):
 *   type СвойстваУпражнения<З extends Задание> = {
 *     задание: З;                                   // проверенное движком (engine/lessonEngine.ts)
 *     приГотово: (итог: ИтогЗадания, опции?: { сразуДалее?: boolean }) => void;
 *     заменитьДалее?: (замена: ЗаменаДалее | null) => void;
 *   };
 *   - приГотово вызывается, когда задание можно завершить: экран урока откроет «Далее»
 *     (сразуДалее — перейти без нажатия «Далее»).
 *   - Засчитывается первый вызов (повторные движок игнорирует).
 *   - Оценивается только выбор: { оценивается: true, верно } — по ПЕРВОЙ попытке (useВыбор).
 *     Голос и теория — { оценивается: false }.
 *   - заменитьДалее — упражнение может поменять нижнюю кнопку экрана урока: надпись и, если задано
 *     приНажатии, действие (например, «Следующая ступень» в «Лестнице»); null — обычная «Далее».
 *     Без приНажатии меняется только надпись, а кнопка ведёт дальше (если задание готово).
 *     Экран урока сбрасывает замену при переходе к следующему заданию. Lesson0Screen её не передаёт.
 *   - Упражнение пересоздаётся на каждое задание (key) — своё состояние держит внутри.
 *
 * Обратная связь — мягкая: «Верно!», после первой ошибки — «Посмотрите ещё раз» (верный не раскрываем),
 * после второй — «Это …, а нужно …» с подсветкой верного (без «неправильно», «плохо»).
 * Арабские варианты в обратной связи — карточками крупным шрифтом (огласовки должны быть видны).
 * Блок обратной связи сам прокручивает экран к себе (useПрокрутка), чтобы не прятаться под нижней панелью.
 * Без звуков-эффектов, без жизней и таймеров.
 */
