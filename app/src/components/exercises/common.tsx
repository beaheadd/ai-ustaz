export type СостояниеВарианта = 'обычный' | 'верный' | 'выбранНеверный' | 'приглушён';

/**
 * Кнопка-вариант: плитка на поверхности; ≥ 56 px (арабская — ≥ 96 px), видимый фокус с клавиатуры, aria-label.
 * Верный (после завершения) — рамка и фон «успех» и отметка-галочка в углу; выбранный неверный — янтарь
 * (красный для чтения не используем); остальные после завершения приглушены.
 */
export function КнопкаВарианта({
  вариант,
  номер,
  состояние,
  приНажатии,
  отключена,
  размерАрабского = 'огромный',
  выбрана = false,
  подписьДоступности,
  testID,
}: {
  вариант: ВариантОтвета;
  номер: number;
  состояние: СостояниеВарианта;
  приНажатии: () => void;
  отключена?: boolean;
  размерАрабского?: РазмерАрабского;
  /** Для «собери»: вариант выбран, но ещё не проверен. */
  выбрана?: boolean;
  /** Подпись для экранного диктора вместо содержимого (например, слог целиком для знака огласовки). */
  подписьДоступности?: string;
  testID?: string;
}) {
  const { цвет, радиус, отступ, тень } = useТема();
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const рамка =
    состояние === 'верный' ? цвет.успех : состояние === 'выбранНеверный' ? цвет.внимание : выбрана ? цвет.акцент : цвет.граница;
  const фон =
    состояние === 'верный' ? цвет.успехФон : состояние === 'выбранНеверный' ? цвет.вниманиеФон : выбрана ? цвет.акцентМягкий : цвет.поверхность;
  const толщина = состояние === 'обычный' && !выбрана ? 1 : 2;
  const пометка =
    состояние === 'верный' ? ', ' + т('вариантВерный') : состояние === 'выбранНеверный' ? ', ' + т('вариантВыбран') : '';
  const арабский = 'арабский' in вариант;
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={т('вариант', { номер, что: подписьДоступности ?? подписьВарианта(вариант, язык) }) + пометка}
      accessibilityState={{ disabled: отключена, selected: выбрана || состояние === 'выбранНеверный' }}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      style={(с) => {
        const { pressed, focused } = с as { pressed: boolean; focused?: boolean };
        return {
          flex: 1,
          minWidth: 64,
          minHeight: арабский ? 96 : 56,
          alignItems: 'center',
          justifyContent: 'center',
          // Рамка 1 или 2 px — содержимое не прыгает: разницу добираем отступом.
          paddingHorizontal: отступ.m + 2 - толщина,
          paddingVertical: отступ.xs + 2 - толщина,
          borderRadius: радиус.l,
          borderWidth: толщина,
          borderColor: рамка,
          backgroundColor: pressed && состояние === 'обычный' ? цвет.акцентМягкий : фон,
          opacity: состояние === 'приглушён' ? 0.5 : 1,
          ...(состояние === 'обычный' && !выбрана ? тень(1) : null),
          // Кольцо фокуса — только у доступного варианта (после ответа нажатый закрыт и кольцо не висит).
          ...(Platform.OS === 'web' && focused && !отключена ? { outlineColor: цвет.фокус, outlineWidth: 3, outlineStyle: 'solid', outlineOffset: 2 } : {}),
        } as object;
      }}
    >
      {арабский ? (
        <АрабскийТекст размер={размерАрабского} выбираемый={false} стиль={стильКрупного(размерАрабского)}>
          {вариант.арабский}
        </АрабскийТекст>
      ) : (
        <Текст вид="кнопка" стиль={{ textAlign: 'center' }}>
          {локально(вариант.текст, язык)}
        </Текст>
      )}
      {состояние === 'верный' ? (
        <View
          accessibilityElementsHidden
          importantForAccessibility="no-hide-descendants"
          style={{
            position: 'absolute',
            top: 6,
            right: 6,
            width: 24,
            height: 24,
            borderRadius: радиус.круг,
            backgroundColor: цвет.успех,
            alignItems: 'center',
            justifyContent: 'center',
          }}
        >
          <Значок имя="галочка" размер={16} цвет={цвет.поверхность} толщина={2.75} />
        </View>
      ) : null}
    </Pressable>
  );
}

/**
 * Мягкая обратная связь после ответа на выбор — репликой ИИ-наставника. Только тап — голос не оценивается.
 * состояние: 'верно' — «Верно!» (или «Теперь верно…», если со второй попытки); эмблема в покое;
 *            'ещёРаз' — после первой ошибки: что выбрано, верный НЕ раскрывается; эмблема «объясняю»;
 *            'нужно' — после второй ошибки: выбрано и нужно рядом; эмблема «объясняю».
 * testID: ответ-верно | ответ-ещё-раз | ответ-подсказка (+ ответ-выбрано, ответ-нужно).
 */
export function ОбратнаяСвязь({
  состояние,
  выбрано,
  нужно,
  пояснение,
  соВторой = false,
}: {
  состояние: 'верно' | 'ещёРаз' | 'нужно';
  выбрано: ВариантОтвета;
  нужно: ВариантОтвета;
  пояснение?: string;
  /** Верный ответ дан со второй попытки. */
  соВторой?: boolean;
}) {
  const { цвет, отступ } = useТема();
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const { вКонец } = useПрокрутка();
  const верно = состояние === 'верно';
  const арабские = 'арабский' in выбрано && 'арабский' in нужно;

  // Новый ответ — прокрутить к блоку, чтобы он не прятался под нижней панелью «Далее».
  useEffect(() => {
    вКонец();
  }, [состояние, выбрано, вКонец]);

  return (
    <View accessibilityLiveRegion="polite" testID={верно ? 'ответ-верно' : состояние === 'ещёРаз' ? 'ответ-ещё-раз' : 'ответ-подсказка'}>
      <РепликаУстаза состояние={верно ? 'покой' : 'объясняю'}>
        <View style={{ gap: отступ.s }}>
          {верно ? (
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
              <Значок имя="галочка" размер={20} цвет={цвет.успех} толщина={2.5} />
              <Текст вид="подзаголовок" цвет={цвет.успех} стиль={{ flex: 1 }}>
                {соВторой ? т('вернаяВторая') : т('верно')}
              </Текст>
            </View>
          ) : состояние === 'ещёРаз' ? (
            арабские ? (
              <>
                <Текст вид="подзаголовок">{т('неТоЕщёРаз')}</Текст>
                <View style={{ flexDirection: 'row' }}>
                  <View style={{ width: '55%', flexDirection: 'row' }}>
                    <КарточкаВарианта подпись={т('вашВыбор')} вариант={выбрано} верный={false} testID="ответ-выбрано" />
                  </View>
                </View>
              </>
            ) : (
              <ТекстСВставками вид="подзаголовок" шаблон={т('этоЕщёРаз')} вставки={{ выбрано: <ВариантВСтроке вариант={выбрано} /> }} />
            )
          ) : арабские ? (
            <>
              <Текст вид="подзаголовок">{т('сравните')}</Текст>
              <View style={{ flexDirection: 'row', gap: отступ.s }}>
                <КарточкаВарианта подпись={т('вашВыбор')} вариант={выбрано} верный={false} testID="ответ-выбрано" />
                <КарточкаВарианта подпись={т('нужноПодпись')} вариант={нужно} верный testID="ответ-нужно" />
              </View>
            </>
          ) : (
            <ТекстСВставками
              шаблон={т('этоНоНужно')}
              вставки={{ выбрано: <ВариантВСтроке вариант={выбрано} />, нужно: <ВариантВСтроке вариант={нужно} /> }}
            />
          )}
          {пояснение && состояние !== 'ещёРаз' ? <СмешанныйТекст вид="второй">{пояснение}</СмешанныйТекст> : null}
        </View>
      </РепликаУстаза>
    </View>
  );
}

/** Подпись фрагмента Корана: «Сура 112, аят 1» (+ слова) и источник. */
export function ПодписьКорана({ фрагмент }: { фрагмент: ФрагментКорана }) {
  const т = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const ссылка = фрагмент.слова
    ? т('сураАятСлова', { сура: фрагмент.сура, аят: фрагмент.аят, с: фрагмент.слова.с, по: фрагмент.слова.по })
    : т('сураАят', { сура: фрагмент.сура, аят: фрагмент.аят });
  return (
    <View style={{ gap: 2 }}>
      <Текст вид="метка" стиль={{ textAlign: 'center' }}>
        {ссылка}
      </Текст>
      <Текст вид="мелкий" стиль={{ textAlign: 'center' }}>
        {т('источникКорана')}
      </Текст>
    </View>
  );
}

/**
 * Что читать: учебный арабский (буква, слог, учебное слово) или фрагмент Корана.
 * Коран выводится строкой из данных как есть (движок уже сверил sha256 с Tanzil), своим шрифтом,
 * без поправок положения и без украшений.
 */
export function ТекстДляЧтения({
  читать,
  размер = 'огромный',
  testID,
}: {
  читать: { учебный: string } | { коран: ФрагментКорана };
  размер?: РазмерАрабского;
  testID?: string;
}) {
  if ('коран' in читать) {
    return (
      <View style={{ gap: 4 }} testID={testID}>
        <АрабскийТекст размер="крупный" testID="текст-корана">
          {читать.коран.текст}
        </АрабскийТекст>
        <ПодписьКорана фрагмент={читать.коран} />
      </View>
    );
  }
  return (
    <АрабскийТекст размер={размер} testID={testID} стиль={стильКрупного(размер)}>
      {читать.учебный}
    </АрабскийТекст>
  );
}

/**
 * Рамка для текста чтения: учебный текст «стоит в нише» (карточка-арка), Коран — в обычной карточке
 * (своя рамка, без арки и орнамента рядом с аятом).
 */
export function РамкаЧтения({ читать, children, testID }: { читать: { учебный: string } | { коран: ФрагментКорана }; children: ReactNode; testID?: string }) {
  const { отступ } = useТема();
  return (
    <Карточка вид={'коран' in читать ? 'обычная' : 'арка'} testID={testID} стиль={{ alignItems: 'center', paddingBottom: отступ.l }}>
      {children}
    </Карточка>
  );
}

