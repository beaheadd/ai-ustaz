const АРАБСКАЯ_БУКВА = /[\u0600-\u06FF]/;

/** Список с ромбами-нуктами; пункты могут содержать арабские вставки. */
export function ПунктыСНуктой({ пункты, вид = 'обычный' }: { пункты: string[]; вид?: 'обычный' | 'второй' }) {
  const { цвет, отступ } = useТема();
  return (
    <View style={{ gap: отступ.s }}>
      {пункты.map((пункт, i) => (
        <View key={i} style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'flex-start' }}>
          {/* Арабская вставка делает строку выше (36 вместо 24) — нукта по середине первой строки. */}
          <Значок имя="нукта" размер={16} цвет={цвет.золотоЗначок} стиль={{ marginTop: АРАБСКАЯ_БУКВА.test(пункт) ? 10 : 4 }} />
          <СмешанныйТекст вид={вид} стиль={{ flex: 1 }}>
            {пункт}
          </СмешанныйТекст>
        </View>
      ))}
    </View>
  );
}

/** Строка с вставками: шаблон «Это {выбрано}, а нужно {нужно}.» + узлы для {имён}. */
export function ТекстСВставками({ шаблон, вставки, вид = 'обычный', стиль }: {
  шаблон: string;
  вставки: Record<string, ReactNode>;
  вид?: 'обычный' | 'подзаголовок';
  стиль?: StyleProp<TextStyle>;
}) {
  const части = шаблон.split(/(\{[^{}]+\})/g);
  return (
    <Текст вид={вид} стиль={стиль}>
      {части.map((ч, i) => {
        const имя = /^\{([^{}]+)\}$/.exec(ч)?.[1];
        return <Fragment key={i}>{имя && имя in вставки ? вставки[имя] : ч}</Fragment>;
      })}
    </Текст>
  );
}

/** Вариант ответа как узел в строке (арабский — RTL, Amiri, не мельче 36 px; текст — без внешних кавычек). */
