/**
 * Логика задания «выбор» для упражнений «найди», «пара», «собери»: две попытки, в итог урока идёт первая.
 *
 * Контракт:
 *   const в = useВыбор(задание, приГотово);
 *   в.ответить(индекс)            — ответ (повторный выбор того же неверного варианта игнорируется);
 *   в.состояние(индекс) → СостояниеВарианта;  в.закрыт(индекс) → boolean (вариант нельзя нажать);
 *   в.выбран: number | null       — последний ответ;
 *   в.обратнаяСвязь: 'верно' | 'ещёРаз' | 'нужно' | null — что показать под вариантами;
 *   в.завершено: boolean          — задание закончено (верный ответ или вторая ошибка);
 *   в.соВторой: boolean           — верный ответ дан со второй попытки.
 * Порядок (решение рецензии UX, 18.11.2026): первая ошибка — «Посмотрите ещё раз», верный НЕ раскрывается,
 * можно выбрать снова; верный ответ или вторая ошибка — задание завершено, верный подсвечен, движку
 * сообщается приГотово({ оценивается: true, верно: первая попытка верна }) — тогда открывается «Далее».
 * Без таймеров и «жизней»: отвечать можно сколько угодно долго.
 */
import { useCallback, useState } from 'react';
import type { ЗаданиеВыбор } from '../../content/types';
import type { СвойстваУпражнения, СостояниеВарианта } from './common';

export function useВыбор(задание: ЗаданиеВыбор, приГотово: СвойстваУпражнения['приГотово']) {
  const [попытки, установитьПопытки] = useState<number[]>([]);
  const верный = задание.верный;
  const выбран = попытки.length ? попытки[попытки.length - 1] : null;
  const завершено = выбран === верный || попытки.length >= 2;

  const ответить = useCallback(
    (индекс: number) => {
      if (завершено || попытки.includes(индекс)) return;
      const новые = [...попытки, индекс];
      установитьПопытки(новые);
      if (индекс === верный || новые.length >= 2) {
        приГотово({ оценивается: true, верно: новые[0] === верный });
      }
    },
    [завершено, попытки, верный, приГотово],
  );

  const состояние = (индекс: number): СостояниеВарианта => {
    if (!завершено) return попытки.includes(индекс) ? 'выбранНеверный' : 'обычный';
    if (индекс === верный) return 'верный';
    if (попытки.includes(индекс)) return 'выбранНеверный';
    return 'приглушён';
  };

  const закрыт = (индекс: number) => завершено || попытки.includes(индекс);

  const обратнаяСвязь: 'верно' | 'ещёРаз' | 'нужно' | null =
    выбран == null ? null : выбран === верный ? 'верно' : завершено ? 'нужно' : 'ещёРаз';

  return { выбран, ответить, состояние, закрыт, обратнаяСвязь, завершено, соВторой: завершено && выбран === верный && попытки.length > 1 };
}
