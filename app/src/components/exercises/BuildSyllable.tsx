/**
 * Упражнение «Собери слог» (задание «выбор»: показ — буква, варианты — эта буква с разными
 * огласовками; движок узнаёт такое задание сам, см. этоСобериСлог в engine/lessonEngine.ts).
 *
 * Контракт: <СобериСлог задание={ЗаданиеВыбор} приГотово={…} />
 *   Ученик выбирает знак (фатха, кясра, дамма, сукун, танвин — что есть в вариантах),
 *   видит собранный слог крупно и нажимает «Проверить». Две проверки, в итог идёт первая (useВыбор).
 * Неверные варианты — только слоги (буква + знак), как требует правило контента.
 * Знак показан на татвиле «ـ» (шрифт Amiri Quran рисует его надёжно).
 * Вид (дизайн-система): собранный слог — в нише (карточка-арка) с пунктирным местом под знак, пока знак
 * не выбран; варианты — плитки; обратная связь — реплика ИИ-наставника.
 */
import { useState } from 'react';
import { View } from 'react-native';
import type { ЗаданиеВыбор } from '../../content/types';
import { локально, разобратьСлог } from '../../engine/lessonEngine';
import { СмешанныйТекст } from '../info/MixedText';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { КнопкаВарианта, ОбратнаяСвязь, стильКрупного, type СвойстваУпражнения } from './common';
import { рядыВариантов } from './FindLetter';
import { useВыбор } from './useChoice';

const СЛОВАРЬ = создатьСловарь({
  ru: { знак: 'Выберите знак для буквы', проверить: 'Проверить', собрано: 'Собранный слог' },
  kk: { знак: 'Әріпке белгіні таңдаңыз', проверить: 'Тексеру', собрано: 'Құралған буын' },
});

export function СобериСлог({ задание, приГотово }: СвойстваУпражнения<ЗаданиеВыбор>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет, радиус } = useТема();
  const в = useВыбор(задание, приГотово);
  const [отмечен, установитьОтмечен] = useState<number | null>(null);
  const слоги = задание.варианты.map((вар) => ('арабский' in вар ? вар.арабский : ''));
  const знаки = слоги.map((с) => разобратьСлог(с)?.знаки ?? '');
  const основа = задание.показ ?? '';
  const выбранныйИндекс = в.завершено ? в.выбран : (отмечен ?? в.выбран);
  const собрано = выбранныйИндекс != null ? слоги[выбранныйИндекс] : основа;
  const индексы = слоги.map((_, i) => i);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-собери">
      <СмешанныйТекст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.вопрос, язык)}
      </СмешанныйТекст>
      <Карточка вид="арка" стиль={{ alignItems: 'center', paddingBottom: отступ.l }}>
        <Текст вид="метка" цвет={цвет.текстВторой}>
          {т('собрано')}
        </Текст>
        <View
          accessible
          accessibilityLabel={т('собрано') + ': ' + собрано}
          style={{
            minWidth: 148,
            alignItems: 'center',
            borderRadius: радиус.l,
            borderWidth: 2,
            borderStyle: выбранныйИндекс == null ? 'dashed' : 'solid',
            borderColor: выбранныйИндекс == null ? цвет.границаЭлемента : в.завершено ? цвет.успех : цвет.акцент,
            backgroundColor: выбранныйИндекс == null ? 'transparent' : в.завершено ? цвет.успехФон : цвет.поверхностьАкцент,
            paddingHorizontal: отступ.xl,
            paddingTop: отступ.s,
          }}
        >
          <АрабскийТекст размер="огромный" testID="собранный-слог" стиль={стильКрупного(96)}>
            {собрано}
          </АрабскийТекст>
        </View>
      </Карточка>
      <Текст вид="метка" цвет={цвет.текстВторой}>
        {т('знак')}
      </Текст>
      <View style={{ gap: отступ.s }}>
        {рядыВариантов(индексы).map((ряд, r) => (
          <View key={r} style={{ flexDirection: 'row', gap: отступ.s }}>
            {ряд.map((i) => (
              <КнопкаВарианта
                key={i}
                вариант={{ арабский: 'ـ' + знаки[i] }}
                подписьДоступности={слоги[i]}
                номер={i + 1}
                состояние={в.состояние(i)}
                выбрана={!в.завершено && отмечен === i}
                отключена={в.закрыт(i)}
                приНажатии={() => установитьОтмечен(i)}
                testID={'знак-' + i}
              />
            ))}
          </View>
        ))}
      </View>
      {в.выбран != null && в.обратнаяСвязь ? (
        <ОбратнаяСвязь
          состояние={в.обратнаяСвязь}
          соВторой={в.соВторой}
          выбрано={задание.варианты[в.выбран]}
          нужно={задание.варианты[задание.верный]}
          пояснение={локально(задание.пояснение, язык) || undefined}
        />
      ) : null}
      {!в.завершено ? (
        <Кнопка
          надпись={т('проверить')}
          отключена={отмечен == null || в.закрыт(отмечен)}
          приНажатии={() => {
            if (отмечен == null) return;
            в.ответить(отмечен);
            установитьОтмечен(null);
          }}
          testID="собери-проверить"
        />
      ) : null}
    </View>
  );
}
