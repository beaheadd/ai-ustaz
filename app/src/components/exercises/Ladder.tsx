/**
 * Упражнение «Лестница» «Муаллим сани»: слог → слово → фраза (→ аят), каждую ступень —
 * прочитать и (по желанию) записать себя. Без вердикта.
 *
 * Контракт: <Лестница задание={ЗаданиеЛестница} приГотово={…} заменитьДалее?={…} />
 *   ступени — учебный текст или ФрагментКорана (дословно, хеш сверен движком).
 * Пройденные ступени видны выше мельче; на каждой ступени — своя ПанельЗаписи (новая
 * ступень размонтирует прежнюю панель — запись удаляется). На своём домене — «Проверить» по тексту ступени.
 * Нижняя кнопка экрана урока, пока ступень не последняя, — «Следующая ступень» (заменитьДалее,
 * testID лестница-следующая); на последней — обычная «Далее»/«Завершить урок» (задание готово).
 * Без заменитьДалее (урок 0) — своя кнопка «Следующая ступень» под ступенью.
 */
import { useCallback, useEffect, useMemo, useState } from 'react';
import { View } from 'react-native';
import type { ЗаданиеЛестница } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { эталонЗадания } from '../../speech/check';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { ПанельЗаписи } from '../RecordPanel';
import { Текст } from '../Text';
import { ТекстДляЧтения, type СвойстваУпражнения } from './common';
import { МАКС_ЗАПИСИ_МС } from './SayAloud';

const СЛОВАРЬ = создатьСловарь({
  ru: { ступень: 'Ступень {номер} из {всего}', следующая: 'Следующая ступень' },
  kk: { ступень: '{всего} ішінен {номер}-саты', следующая: 'Келесі саты' },
});

export function Лестница({ задание, приГотово, заменитьДалее }: СвойстваУпражнения<ЗаданиеЛестница>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const [ступень, установитьСтупень] = useState(0);
  const всего = задание.ступени.length;
  const последняя = ступень >= всего - 1;
  const проверка = useMemo(() => ({ ...эталонЗадания(задание.ступени[ступень]), виды: задание.виды }), [задание, ступень]);

  useEffect(() => {
    if (последняя) приГотово({ оценивается: false });
    // приГотово засчитывается один раз (движок игнорирует повторы)
  }, [последняя]);

  const следующая = useCallback(() => установитьСтупень((с) => Math.min(с + 1, всего - 1)), [всего]);
  const надпись = т('следующая');
  useEffect(() => {
    заменитьДалее?.(последняя ? null : { надпись, приНажатии: следующая, testID: 'лестница-следующая' });
  }, [заменитьДалее, последняя, надпись, следующая]);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-лестница">
      <Текст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.подсказка, язык)}
      </Текст>
      {ступень > 0 ? (
        <View style={{ gap: отступ.xs, opacity: 0.7 }}>
          {задание.ступени.slice(0, ступень).map((с, i) => (
            <ТекстДляЧтения key={i} читать={с} размер="средний" />
          ))}
        </View>
      ) : null}
      <Текст вид="мелкий" accessibilityLiveRegion="polite" testID="ступень">
        {т('ступень', { номер: ступень + 1, всего })}
      </Текст>
      <Карточка стиль={{ alignItems: 'center', paddingVertical: отступ.l }}>
        <ТекстДляЧтения читать={задание.ступени[ступень]} testID="текст-ступени" />
      </Карточка>
      <ПанельЗаписи key={ступень} максДлительностьМс={МАКС_ЗАПИСИ_МС} проверка={проверка} />
      {!последняя && !заменитьДалее ? (
        <Кнопка
          надпись={т('следующая')}
          вид="вторичная"
          значок="↑"
          приНажатии={следующая}
          testID="лестница-следующая"
        />
      ) : null}
    </View>
  );
}
