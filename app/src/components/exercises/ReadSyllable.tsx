/**
 * Упражнение «Прочитай слог» (задание «прочитай»): слоги/учебные слова крупно, строкой справа налево,
 * как в книге → «Показать подсказку» (кириллическая транскрипция из данных, по схеме каталога §10.1)
 * под каждым слогом.
 *
 * Контракт: <ПрочитайСлог задание={ЗаданиеПрочитай} приГотово={…} заменитьДалее?={…} />
 *   подсказка — что сделать; строки — [{ арабский, транскрипция }] (только учебный текст, не Коран).
 * Транскрипция скрыта, пока ученик сам не попросит. Без микрофона и без оценки: задание готово сразу
 * (useГотовоСразу), нижняя кнопка экрана урока подписана «Прочитал(а) — дальше» (заменитьДалее, только
 * надпись). Голос кари: «Послушать кари», если есть клип строки (первой по порядку); нет — честная строка.
 * Вид (дизайн-система): строка — в нише (карточка-арка), транскрипция — акцентом под слогом.
 */
import { useEffect, useState } from 'react';
import { View } from 'react-native';
import type { ЗаданиеПрочитай } from '../../content/types';
import { локально } from '../../engine/lessonEngine';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import { useТема } from '../../theme';
import { АрабскийТекст } from '../ArabicText';
import { Кнопка } from '../Button';
import { Карточка } from '../Card';
import { Текст } from '../Text';
import { ПослушатьКари, useЕстьКлипКари } from '../LessonMaterials';
import { НетГолосаКари, СЛОВАРЬ_УПРАЖНЕНИЙ, стильКрупного, useГотовоСразу, type СвойстваУпражнения } from './common';

const СЛОВАРЬ = создатьСловарь({
  ru: { прочитал: 'Прочитал(а) — дальше', звучит: 'Звучит как' },
  kk: { прочитал: 'Оқыдым — әрі қарай', звучит: 'Былай оқылады' },
});

export function ПрочитайСлог({ задание, приГотово, заменитьДалее }: СвойстваУпражнения<ЗаданиеПрочитай>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тО = useСловарь(СЛОВАРЬ_УПРАЖНЕНИЙ);
  const { отступ, цвет } = useТема();
  const [подсказка, установитьПодсказку] = useState(false);
  const одна = задание.строки.length === 1;
  const тексты = задание.строки.map((с) => с.арабский);
  const естьКлип = useЕстьКлипКари(тексты);
  useГотовоСразу(приГотово);
  const надпись = т('прочитал');
  useEffect(() => {
    заменитьДалее?.({ надпись });
  }, [заменитьДалее, надпись]);

  return (
    <View style={{ gap: отступ.l }} testID="упражнение-прочитай">
      <Текст вид="подзаголовок" accessibilityRole="header">
        {локально(задание.подсказка, язык)}
      </Текст>
      <Карточка вид="арка" стиль={{ paddingBottom: отступ.l }}>
        {/* Справа налево, с переносом: первый слог — справа, как в книге. */}
        <View
          style={{
            flexDirection: 'row-reverse',
            flexWrap: 'wrap',
            justifyContent: 'center',
            columnGap: одна ? 0 : отступ.l,
            rowGap: отступ.xs,
          }}
        >
          {задание.строки.map((строка, i) => (
            <View key={i} style={{ alignItems: 'center', minWidth: одна ? undefined : 72, paddingVertical: одна ? отступ.s : 0 }}>
              {/* Amiri Quran: кясра под низкими буквами (ر ز و) уходит глубоко вниз — интерлиньяж с запасом,
                  чтобы огласовка не налезала на транскрипцию (сверху строки пусто — подтягиваем только верх). */}
              <АрабскийТекст
                размер={одна ? 'огромный' : 'крупный'}
                testID={'строка-' + i}
                стиль={одна ? стильКрупного(88) : { lineHeight: 100, marginTop: -16 }}
              >
                {строка.арабский}
              </АрабскийТекст>
              {подсказка && строка.транскрипция ? (
                <Текст
                  вид="подзаголовок"
                  testID={'транскрипция-' + i}
                  accessibilityLabel={т('звучит') + ': ' + строка.транскрипция}
                  стиль={{ textAlign: 'center', color: цвет.акцент }}
                >
                  {строка.транскрипция}
                </Текст>
              ) : null}
            </View>
          ))}
        </View>
      </Карточка>
      <Кнопка
        надпись={подсказка ? тО('подсказкаСкрыть') : тО('подсказкаПоказать')}
        вид="вторичная"
        значок={подсказка ? 'вверх' : 'инфо'}
        приНажатии={() => установитьПодсказку((п) => !п)}
        testID="подсказка"
      />
      <ПослушатьКари тексты={тексты} />
      {естьКлип ? null : <НетГолосаКари />}
    </View>
  );
}
