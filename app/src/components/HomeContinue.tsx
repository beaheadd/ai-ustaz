/** Верх карточки: что продолжить в курсе (готовит главная — те же числа, что на карте курса). */
export type ДанныеУрока = {
  /** Метка урока ('2', 'К1') или null — уроки прототипа пройдены. */
  метка: string | null;
  /** Название урока на языке интерфейса (может содержать учебные арабские буквы) или «Уроки прототипа пройдены». */
  название: string;
  пройдено: number;
  всего: number;
  /** Для диктора: «Этап 1: пройдено 1 из 17 уроков». */
  подписьПрогресса: string;
  /** Для диктора ссылки: «Продолжить: урок 2». */
  диктор: string;
  открыть: () => void;
};

/** Короткое имя суры на языке интерфейса: транслитерация индекса (с заглавной), ar/ur — арабское имя Tanzil. */
export function короткоеИмяСуры(запись: Pick<ЗаписьСуры, 'имя' | 'транслит'> | null, номер: number, язык: Язык): string {
  if ((язык === 'ar' || язык === 'ur') && запись?.имя) return запись.имя;
  const т = !запись ? null : язык === 'ru' ? запись.транслит.ru : язык === 'kk' ? запись.транслит.kk : язык === 'uz' ? запись.транслит.uz : запись.транслит.en;
  if (т) return т.charAt(0).toLocaleUpperCase(язык === 'tr' ? 'tr' : 'ru') + т.slice(1);
  return названиеСуры(null, номер, язык);
}

export function КарточкаПродолжить({ урок }: { урок: ДанныеУрока | null }) {
  const { цвет, отступ, радиус, тень } = useТема();
  const [чтение, установитьЧтение] = useState<МестоЧтения | null | undefined>(undefined);
  useEffect(() => {
    let живой = true;
    void прочитатьЧтение().then((м) => {
      if (живой) установитьЧтение(м);
    });
    return () => {
      живой = false;
    };
  }, []);

  // Пока место не прочитано — не рисуем (без мигания «Начать» → «Продолжить»).
  if (чтение === undefined) return null;
  if (!урок && !чтение) return null;

  return (
    <View
      testID="главная-продолжить-карточка"
      style={{ borderRadius: радиус.l, backgroundColor: цвет.поверхность, borderWidth: 1, borderColor: цвет.граница, overflow: 'hidden', ...тень(1) }}
    >
      {урок ? <ВерхУрока урок={урок} /> : null}
      {урок ? <View aria-hidden style={{ height: 1, marginHorizontal: отступ.m, backgroundColor: цвет.граница }} /> : null}
      <СтрокаЧтения место={чтение} />
    </View>
  );
}

function ВерхУрока({ урок }: { урок: ДанныеУрока }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const доля = урок.всего > 0 ? Math.min(1, урок.пройдено / урок.всего) : 0;
  // 320 px (kk): иллюстрация чуть меньше — подписи не рвутся на три строки.
  const узко = useWindowDimensions().width < 360;
  return (
    <View style={{ paddingHorizontal: отступ.m, paddingTop: отступ.m, paddingBottom: отступ.s, gap: отступ.s }}>
      <Pressable
        accessibilityRole="link"
        accessibilityLabel={`${урок.диктор}. ${урок.название}`}
        onPress={урок.открыть}
        testID="главная-продолжить"
        style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: отступ.m, opacity: pressed ? 0.75 : 1, minHeight: 56 })}
      >
        <ИллюстрацияРаздела имя="таджвид" размер={узко ? 40 : 48} />
        <View style={{ flex: 1, minWidth: 0, gap: 2 }}>
          <Текст вид="мелкий" цвет={цвет.текстВторой} testID="главная-продолжить-метка">
            {неРватьТочку(урок.метка ? т('тренерУрок', { метка: урок.метка }) : т('тренер'))}
          </Текст>
          <СмешанныйТекст вид="подзаголовок" арабскийКегль={24} арабскаяСтрока={28} стиль={{ lineHeight: 30 }} testID="главная-продолжить-название">
            {урок.название}
          </СмешанныйТекст>
        </View>
        <View aria-hidden style={{ width: 48, height: 48, borderRadius: 24, backgroundColor: цвет.акцент, alignItems: 'center', justifyContent: 'center' }}>
          <Значок имя="вперёд" размер={24} цвет={цвет.акцентТекст} толщина={2} />
        </View>
      </Pressable>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
        <View
          testID="главная-прогресс"
          {...({ role: 'progressbar', 'aria-valuemin': 0, 'aria-valuemax': урок.всего, 'aria-valuenow': урок.пройдено, 'aria-label': урок.подписьПрогресса } as object)}
          style={{ flex: 1, height: 6, borderRadius: 3, backgroundColor: цвет.поверхностьВторая, overflow: 'hidden' }}
        >
          <View style={{ width: `${Math.round(доля * 1000) / 10}%`, height: 6, borderRadius: 3, backgroundColor: цвет.акцент }} />
        </View>
        <Текст вид="мелкий" цвет={цвет.текстВторой} табличные testID="главная-прогресс-подпись" aria-hidden>
          {т('прогресс', { пройдено: урок.пройдено, всего: урок.всего })}
        </Текст>
      </View>
    </View>
  );
}

/** Нижняя строка: «Продолжить чтение · Аль-Бакара · 2:5 · стр. 2  البقرة ›» (или «Начать читать Коран» → аль-Фатиха). */
function СтрокаЧтения({ место }: { место: МестоЧтения | null }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ } = useТема();
  const { перейти } = useНавигация();
  const индекс = useИндексСур();
  const { режим } = useВидЧтения();
  const суры = индекс.состояние === 'есть' ? индекс.данные.суры : null;
  // Место вне суры (данные с другого устройства, старый индекс) — как «не читал».
  const где = место && (!суры || (суры[место.сура - 1] && место.аят <= суры[место.сура - 1].аятов)) ? место : null;
  const цель = где ?? { сура: 1, аят: 1 };
  const запись = суры?.[цель.сура - 1] ?? null;
  const страница = useСтраница(режим === 'страницы' ? цель : null);
  const имя = короткоеИмяСуры(запись, цель.сура, язык);
  const ссылка = `${цель.сура}:${цель.аят}`;
  const части = [имя, где ? ссылка : null, страница ? т('страница', { н: страница }) : null].filter((ч): ч is string => !!ч);
  const подпись = части.join(' · ');
  const арабскоеОтдельно = язык !== 'ar' && язык !== 'ur' && !!запись?.имя;
  return (
    <Pressable
      accessibilityRole="link"
      accessibilityLabel={`${т(где ? 'чтение' : 'начать')}: ${подпись}`}
      onPress={() => перейти('сура', { номер: цель.сура, аят: цель.аят })}
      testID="главная-чтение"
      {...({ dataSet: { sura: String(цель.сура), ayah: String(цель.аят), page: страница ? String(страница) : '' } } as object)}
      style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: отступ.s, minHeight: 56, paddingHorizontal: отступ.m, paddingVertical: отступ.s, backgroundColor: pressed ? цвет.акцентМягкий : 'transparent' })}
    >
      <Значок имя="коранМеню" размер={24} цвет={цвет.акцент} />
      <View style={{ flex: 1, minWidth: 0 }}>
        <Текст вид="метка" стиль={{ fontSize: 15, lineHeight: 20 }}>{т(где ? 'чтение' : 'начать')}</Текст>
        <Текст вид="мелкий" цвет={цвет.текстВторой} testID="главная-чтение-где">
          {частиБезРазрыва(части)}
        </Текст>
      </View>
      {арабскоеОтдельно ? (
        <АрабскийТекст размер="малый" выравнивание="right" testID="главная-чтение-имя" стиль={{ fontSize: 22, lineHeight: 34, flexShrink: 0 }}>
          {запись?.имя ?? ''}
        </АрабскийТекст>
      ) : null}
      <Значок имя="вперёд" размер={18} цвет={цвет.текстВторой} />
    </Pressable>
  );
}

/** Страница мусхафа для места (только в режиме «Страницами»: индекс мусхафа ≈ 35 КБ грузится лишь тогда). */
function useСтраница(место: МестоЧтения | null): number | null {
  const и = useИндексМусхафа(место !== null);
  return место && и.состояние === 'есть' ? страницаАята(и.данные.страницы, место.сура, место.аят) : null;
}

/** «Тәжуид жаттықтырушысы · 2-сабақ»: точка-разделитель не начинает строку (неразрывный пробел перед ней). */
function неРватьТочку(с: string): string {
  return с.replace(/ · /g, '\u00A0· ');
}

/** «2-сүре · 2:255 · 42-бет»: каждая часть не рвётся внутри (на вебе — nowrap), перенос — только между частями. */
function частиБезРазрыва(части: string[]): ReactNode {
  if (Platform.OS !== 'web') return неРватьТочку(части.join(' · '));
  return части.map((ч, i) => (
    <Fragment key={i}>
      {i > 0 ? '\u00A0· ' : null}
      {createElement('span', { style: { whiteSpace: 'nowrap' } }, ч)}
    </Fragment>
  ));
}
