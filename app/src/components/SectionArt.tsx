function Тасбих() {
  // Кольцо бусин: центр (32, 27), радиус 16; внизу разрыв под имам-бусину.
  const бусины = [];
  const всего = 22;
  for (let i = 0; i < всего; i++) {
    // Ось y вниз: 90° — низ кольца. Бусины от 90°+30° до 90°+330° — внизу разрыв под имам-бусину.
    const угол = ((120 + (i * 300) / (всего - 1)) * Math.PI) / 180;
    const x = 32 + 16 * Math.cos(угол);
    const y = 27 + 16 * Math.sin(угол);
    const разделитель = i === 7 || i === 14;
    бусины.push(
      <G key={i}>
        <Circle cx={x} cy={y} r={разделитель ? 3.6 : 3.1} fill={разделитель ? П.золото : П.зелёныйСредний} />
        <Circle cx={x - 0.9} cy={y - 1} r={0.9} fill="#FFFFFF" opacity={0.55} />
      </G>,
    );
  }
  return (
    <>
      <Circle cx={32} cy={27} r={16} fill="none" stroke={П.коричневый} strokeWidth={0.9} opacity={0.6} />
      {бусины}
      {/* Имам-бусина, втулка и кисточка */}
      <Circle cx={32} cy={45} r={4.4} fill={П.золото} />
      <Circle cx={30.8} cy={43.8} r={1.2} fill="#FFFFFF" opacity={0.55} />
      <Rect x={30} y={49} width={4} height={4} rx={1} fill={П.зелёный} />
      <Path d="M29 53 L35 53 L37 61 L27 61 Z" fill={П.золотоСветлое} />
      <Path d="M30 54 L29 61 M32 54 L32 61 M34 54 L35 61" stroke={П.золото} strokeWidth={0.8} strokeLinecap="round" fill="none" />
    </>
  );
}

// Ладонь, обращённая к смотрящему (локальные координаты: запястье внизу около y=58, большой палец справа снаружи).
// Четыре пальца сомкнуты и почти одной высоты — верх ладони из четырёх невысоких скруглений с неглубокими стыками;
