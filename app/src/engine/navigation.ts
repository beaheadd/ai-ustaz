/**
 * Навигация: стек экранов в состоянии + синхронизация с историей браузера (hash).
 *
 * Контракт:
 *   <ПоставщикНавигации> — оборачивает приложение (App.tsx).
 *   useНавигация() → {
 *     текущий: ЗаписьСтека;             // верх стека: { экран, параметры, ключ }
 *     стек: readonly ЗаписьСтека[];      // всегда начинается с главной
 *     можноНазад: boolean;
 *     перейти(экран, параметры?)         // перейти('урок', { номер: 3 }); перейти('оПроекте')
 *     заменить(экран, параметры?)        // заменить верх стека (без новой записи в истории);
 *                                        // с главной — как перейти(); заменить('главная') — как наГлавную()
 *     назад()                            // как кнопка «назад» браузера
 *     наГлавную()                        // вернуться к главной (стек из одного экрана)
 *     задатьЗащиту(защита | null)        // защита ухода с текущего экрана (см. ниже)
 *   }
 *
 * Защита ухода (урок посреди заданий): защита() вызывается, когда «назад/вперёд» браузера, свайп
 * «назад» в iOS Safari или системная «назад» Android уводят с текущего экрана. Вернула true — уход
 * перехвачен: стек остаётся, в историю снова кладётся запись текущего экрана (pushState), экран сам
 * показывает «Выйти из урока?». Вернула false — уход как обычно. Экран снимает защиту при уходе.
 * Кнопки самого приложения (перейти, назад…) защиту не проверяют — экран вызывает их сам после подтверждения.
 * Экраны и их параметры — engine/routes.ts; компоненты экранов — screens/index.ts.
 *
 * Веб: каждый шаг — запись в history с адресом /aiustaz#/… (history.web.ts); «назад» и
 * «вперёд» браузера, перезагрузка и глубокая ссылка (#/lesson/3) работают. Нативно:
 * стек только в состоянии, системная кнопка «назад» Android вызывает назад().
 * Рисуется только верхний экран: уходя с экрана, он размонтируется (запись голоса удаляется).
 */
import { createContext, createElement, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import { ГЛАВНАЯ, вХэш, изХэша, type ИмяЭкрана, type ПараметрыЭкрана, type Цель } from './routes';
import {
  записатьСтек,
  подписатьсяНаИсторию,
  подписатьсяНаКнопкуНазад,
  прочитатьНачальныйАдрес,
  шагНазад,
} from './history';

export type ЗаписьСтека = Цель & { ключ: string };

export type Навигация = {
  текущий: ЗаписьСтека;
  стек: readonly ЗаписьСтека[];
  можноНазад: boolean;
  перейти: <K extends ИмяЭкрана>(экран: K, ...параметры: ПараметрыЭкрана<K>) => void;
  заменить: <K extends ИмяЭкрана>(экран: K, ...параметры: ПараметрыЭкрана<K>) => void;
  назад: () => void;
  наГлавную: () => void;
  задатьЗащиту: (защита: (() => boolean) | null) => void;
};

type ЗаписьИстории = { стек: string[]; способ: 'push' | 'replace' };

let счётчикКлючей = 0;
function новаяЗапись(цель: Цель): ЗаписьСтека {
  счётчикКлючей += 1;
  return { ...цель, ключ: 'экран-' + счётчикКлючей } as ЗаписьСтека;
}

function хэши(стек: readonly ЗаписьСтека[]): string[] {
  return стек.map(вХэш);
}

/** Стек из hash-адресов; совпадающее начало переиспользует прежние записи (их ключи). */
function стекИзХэшей(адреса: readonly string[], прежний: readonly ЗаписьСтека[]): ЗаписьСтека[] {
  const результат: ЗаписьСтека[] = [];
  for (const адрес of адреса) {
    const цель = изХэша(адрес);
    if (!цель) continue;
    const был = прежний[результат.length];
    результат.push(был && вХэш(был) === вХэш(цель) ? был : новаяЗапись(цель));
  }
  if (результат.length === 0 || результат[0].экран !== 'главная') {
    результат.unshift(прежний[0]?.экран === 'главная' ? прежний[0] : новаяЗапись(ГЛАВНАЯ));
  }
  return результат;
}

/** Начальный стек (чисто, без побочных эффектов) и записи в историю, которые нужно сделать. */
function начало(): { стек: ЗаписьСтека[]; записи: ЗаписьИстории[] } {
  const адрес = прочитатьНачальныйАдрес();
  if (!адрес) return { стек: [новаяЗапись(ГЛАВНАЯ)], записи: [] };
  // Перезагрузка или «вперёд» на нашу запись: стек сохранён в истории.
  if (адрес.стек && адрес.стек[адрес.стек.length - 1] === адрес.хэш) {
    const стек = стекИзХэшей(адрес.стек, []);
    if (хэши(стек).join() === адрес.стек.join()) {
      return { стек, записи: [{ стек: хэши(стек), способ: 'replace' }] };
    }
  }
  // Первый вход или глубокая ссылка: главная внизу, чтобы «назад» вёл на неё.
  const цель = изХэша(адрес.хэш);
  const главная = новаяЗапись(ГЛАВНАЯ);
  if (!цель || цель.экран === 'главная') {
    return { стек: [главная], записи: [{ стек: [вХэш(ГЛАВНАЯ)], способ: 'replace' }] };
  }
  const стек = [главная, новаяЗапись(цель)];
  return {
    стек,
    записи: [
      { стек: [вХэш(ГЛАВНАЯ)], способ: 'replace' },
      { стек: хэши(стек), способ: 'push' },
    ],
  };
}

const КонтекстНавигации = createContext<Навигация | null>(null);

export function ПоставщикНавигации({ children }: { children: ReactNode }) {
  const [старт] = useState(начало);
  const [стек, установитьСтек] = useState<ЗаписьСтека[]>(старт.стек);
  const стекСсылка = useRef<ЗаписьСтека[]>(старт.стек);
  const записиСделаны = useRef(false);
  const защитаСсылка = useRef<(() => boolean) | null>(null);
  const задатьЗащиту = useCallback((защита: (() => boolean) | null) => {
    защитаСсылка.current = защита;
  }, []);

  const применить = useCallback((новый: ЗаписьСтека[]) => {
    стекСсылка.current = новый;
    установитьСтек(новый);
  }, []);

  useEffect(() => {
    if (записиСделаны.current) return;
    записиСделаны.current = true;
    for (const з of старт.записи) записатьСтек(з.стек, з.способ);
  }, [старт]);

  const назад = useCallback(() => {
    const с = стекСсылка.current;
    if (с.length <= 1) return;
    if (!шагНазад(1)) применить(с.slice(0, -1));
  }, [применить]);

  useEffect(
    () =>
      подписатьсяНаИсторию((адреса, хэш) => {
        const с0 = стекСсылка.current;
        const тотЖе = адреса != null && адреса.join() === хэши(с0).join();
        if (!тотЖе && защитаСсылка.current?.()) {
          // Уход перехвачен: вернуть запись текущего экрана в историю, стек не менять.
          записатьСтек(хэши(с0), 'push');
          return;
        }
        if (адреса && адреса[адреса.length - 1] === хэш) {
          применить(стекИзХэшей(адреса, стекСсылка.current));
          return;
        }
        // Адрес поправили вручную (или запись не наша): кладём экран поверх стека.
        const цель = изХэша(хэш) ?? ГЛАВНАЯ;
        const с = стекСсылка.current;
        const новый = цель.экран === 'главная' ? [с[0]] : [...с, новаяЗапись(цель)];
        применить(новый);
        записатьСтек(хэши(новый), 'replace');
      }),
    [применить],
  );

  useEffect(
    () =>
      подписатьсяНаКнопкуНазад(() => {
        if (стекСсылка.current.length <= 1) return false;
        if (защитаСсылка.current?.()) return true;
        назад();
        return true;
      }),
    [назад],
  );

  const перейти = useCallback(
    <K extends ИмяЭкрана>(экран: K, ...параметры: ПараметрыЭкрана<K>) => {
      const цель = { экран, параметры: параметры[0] } as Цель;
      const новый = [...стекСсылка.current, новаяЗапись(цель)];
      применить(новый);
      записатьСтек(хэши(новый), 'push');
    },
    [применить],
  );



  const наГлавную = useCallback(() => {
    const с = стекСсылка.current;
    if (с.length <= 1) return;
    if (!шагНазад(с.length - 1)) применить(с.slice(0, 1));
  }, [применить]);

  const заменить = useCallback(
    <K extends ИмяЭкрана>(экран: K, ...параметры: ПараметрыЭкрана<K>) => {
      const с = стекСсылка.current;
      // Главную внизу стека не заменяем: на ней стоит «назад». С главной — обычный переход.
      if (с.length <= 1 || экран === 'главная') {
        if (экран === 'главная') наГлавную();
        else перейти(экран, ...параметры);
        return;
      }
      const цель = { экран, параметры: параметры[0] } as Цель;
      const новый = [...с.slice(0, -1), новаяЗапись(цель)];
      применить(новый);
      записатьСтек(хэши(новый), 'replace');
    },
    [применить, перейти, наГлавную],
  );

  const значение = useMemo<Навигация>(
    () => ({
      текущий: стек[стек.length - 1],
      стек,
      можноНазад: стек.length > 1,
      перейти,
      заменить,
      назад,
      наГлавную,
      задатьЗащиту,
    }),
    [стек, перейти, заменить, назад, наГлавную, задатьЗащиту],
  );

  return createElement(КонтекстНавигации.Provider, { value: значение }, children);
}

export function useНавигация(): Навигация {
  const н = useContext(КонтекстНавигации);
  if (!н) throw new Error('useНавигация: нет <ПоставщикНавигации> выше по дереву');
  return н;
}
