function вUtf8(строка: string): number[] {
  const байты: number[] = [];
  for (const символ of строка) {
    const к = символ.codePointAt(0)!;
    if (к < 0x80) байты.push(к);
    else if (к < 0x800) байты.push(0xc0 | (к >> 6), 0x80 | (к & 63));
    else if (к < 0x10000) байты.push(0xe0 | (к >> 12), 0x80 | ((к >> 6) & 63), 0x80 | (к & 63));
    else байты.push(0xf0 | (к >> 18), 0x80 | ((к >> 12) & 63), 0x80 | ((к >> 6) & 63), 0x80 | (к & 63));
  }
  return байты;
}

/** sha256 строки в UTF-8, hex в нижнем регистре. */
export function sha256Hex(строка: string): string {
  const б = вUtf8(строка);
  const длинаБит = б.length * 8;
  б.push(0x80);
  while (б.length % 64 !== 56) б.push(0);
  for (let i = 7; i >= 0; i--) б.push(i >= 4 ? 0 : (длинаБит >>> (i * 8)) & 0xff);
  // Строки длиннее 512 МБ не бывают — старшие 32 бита длины всегда 0.
  const h = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
  const w = new Array<number>(64);
  const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));
  for (let блок = 0; блок < б.length; блок += 64) {
    for (let t = 0; t < 16; t++) {
      const i = блок + t * 4;
      w[t] = ((б[i] << 24) | (б[i + 1] << 16) | (б[i + 2] << 8) | б[i + 3]) | 0;
    }
    for (let t = 16; t < 64; t++) {
      const s0 = rotr(w[t - 15], 7) ^ rotr(w[t - 15], 18) ^ (w[t - 15] >>> 3);
      const s1 = rotr(w[t - 2], 17) ^ rotr(w[t - 2], 19) ^ (w[t - 2] >>> 10);
      w[t] = (w[t - 16] + s0 + w[t - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let t = 0; t < 64; t++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K256[t] + w[t]) | 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) | 0;
      hh = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    h[0] = (h[0] + a) | 0;
    h[1] = (h[1] + b) | 0;
    h[2] = (h[2] + c) | 0;
    h[3] = (h[3] + d) | 0;
    h[4] = (h[4] + e) | 0;
    h[5] = (h[5] + f) | 0;
    h[6] = (h[6] + g) | 0;
    h[7] = (h[7] + hh) | 0;
  }
  return h.map((x) => (x >>> 0).toString(16).padStart(8, '0')).join('');
}
