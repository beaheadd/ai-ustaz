/**
 * Движок урока: загрузка урока из /content, проверка данных, выбор вида упражнения,
 * прохождение (чистый редьюсер) и итог. Экран — screens/LessonScreen.tsx,
 * упражнения — components/exercises/*.
 *
 * Контракт:
 *   загрузитьУрок(номер) → Promise<Урок | null>  — урок из /content/lessons/*.json (лениво, отдельный чанк);
 *                                                   null — нет такого урока или данные не прошли проверку;
 *                                                   промис отклоняется, если чанк не загрузился (нет сети) —
 *                                                   экран урока пишет «Нет связи», а не «Урок не найден».
 *   естьУрок(номер) → boolean; следующийУрок(номер) → number | null — для кнопки «Следующий урок».
 *   проверитьУрок(сырые) → Урок | null            — чистая проверка формы; плохие задания отбрасываются;
 *                                                   фрагмент Корана с неверным хешем НЕ показывается.
 *   видУпражнения(задание) → ВидУпражнения        — какой компонент рисует задание.
 *   начальноеСостояние(всего) / шагУрока(с, д, всего) — прохождение: вступление → задания → итог;
 *                                                   «восстановить» — продолжить с задания K (итоги 0…K-1 из
 *                                                   сохранённого прохождения, engine/lessonSession.ts).
 *   подсчитатьИтог(урок, итоги) → ИтогУрокаПодсчёт — «пройден» при доле верных ≥ критерия урока
 *                                                   (по умолчанию 0,8) в заданиях с выбором; голос не оценивается.
 *   локально(текст, язык) → string; sha256Hex(строка) → hex.
 *
 * Где лежат уроки: /content/lessons/<папка>/L01.json … L16.json, K1.json (раскладка из src/content/types.ts),
 * один урок в файле по типу Урок. Номер — из имени файла (L07 → 7, K1 → 101) и сверяется с полем
 * «номер». Папку подхватывает require.context (Metro, режим lazy): новый файл подключается без
 * правки кода, каждый урок — отдельный чанк с хэшем в имени.
 *
 * Вид упражнения (по типу задания; у «выбор» — по полю вид):
 *   теория → 'теория'; знакомство → 'знакомство'; прочитай → 'прочитай'; запись → 'скажи';
 *   лестница → 'лестница'; выбор → 'собери' | 'пара' | 'найди' (см. видУпражнения).
 *
 * Правила (CLAUDE.md): Коран — только ФрагментКорана с источником tanzil-uthmani-1.1 и
 * совпадающим sha256; проверки голоса ИИ нет — задания с записью не оцениваются;
 * без жизней, очков, таймеров-наказаний.
 * Решение владельца 18.11.2026: первая версия — честный прототип v0 на batr.kz/aiustaz.
 */
