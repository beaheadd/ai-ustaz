export function локально(текст: ЛокализованныйТекст | undefined, язык: Язык): string {
  if (!текст) return '';
  return (язык === 'kk' ? текст.kk : текст.ru) || текст.ru || текст.kk || '';
}

// ───────────────────────── Проверка данных ─────────────────────────

function этоСтрока(з: unknown): з is string {
  return typeof з === 'string' && з.length > 0;
}

function этоЛокализованный(з: unknown): з is ЛокализованныйТекст {
  if (!з || typeof з !== 'object') return false;
  const т = з as Record<string, unknown>;
  return typeof т.ru === 'string' && typeof т.kk === 'string' && (т.ru.length > 0 || т.kk.length > 0);
}

function этоЦелое(з: unknown, мин: number, макс: number): з is number {
  return typeof з === 'number' && Number.isInteger(з) && з >= мин && з <= макс;
}

/** Фрагмент Корана: источник Tanzil Uthmani v1.1 и sha256 текста совпадает. Иначе — не показываем. */
export function проверитьФрагментКорана(з: unknown): ФрагментКорана | null {
  if (!з || typeof з !== 'object') return null;
  const ф = з as Record<string, unknown>;
  if (ф.источник !== 'tanzil-uthmani-1.1') return null;
  if (!этоЦелое(ф.сура, 1, 114) || !этоЦелое(ф.аят, 1, 286)) return null;
  if (!этоСтрока(ф.текст) || !этоСтрока(ф.хеш)) return null;
  if (sha256Hex(ф.текст) !== ф.хеш.toLowerCase()) return null;
  if (ф.слова !== undefined) {
    const с = ф.слова as Record<string, unknown> | null;
    if (!с || !этоЦелое(с.с, 1, 1000) || !этоЦелое(с.по, 1, 1000) || с.по < с.с) return null;
  }
  return з as ФрагментКорана;
}

function проверитьЧтение(з: unknown): { учебный: string } | { коран: ФрагментКорана } | null {
  if (!з || typeof з !== 'object') return null;
  const ч = з as Record<string, unknown>;
  if ('учебный' in ч) return этоСтрока(ч.учебный) ? { учебный: ч.учебный } : null;
  if ('коран' in ч) {
    const ф = проверитьФрагментКорана(ч.коран);
    return ф ? { коран: ф } : null;
  }
  return null;
}

function проверитьВариант(з: unknown): ВариантОтвета | null {
  if (!з || typeof з !== 'object') return null;
  const в = з as Record<string, unknown>;
  if ('арабский' in в) return этоСтрока(в.арабский) ? { арабский: в.арабский } : null;
  if ('текст' in в) return этоЛокализованный(в.текст) ? { текст: в.текст } : null;
  return null;
}

/** Проверка одного задания; null — задание отбрасывается (не показываем то, что не прошло проверку). */
export function проверитьЗадание(з: unknown): Задание | null {
  if (!з || typeof з !== 'object') return null;
  const с = з as Record<string, unknown>;
  switch (с.тип) {
    case 'теория': {
      if (!этоЛокализованный(с.заголовок) || !этоЛокализованный(с.текст)) return null;
      if (с.примеры !== undefined && !(Array.isArray(с.примеры) && с.примеры.every(этоСтрока))) return null;
      return з as Задание;
    }
    case 'знакомство': {
      if (!этоСтрока(с.знак) || !этоЛокализованный(с.название)) return null;
      if (с.формы !== null) {
        const ф = с.формы as Record<string, unknown> | undefined;
        if (!ф || !этоСтрока(ф.отдельная) || !этоСтрока(ф.начальная) || !этоСтрока(ф.срединная) || !этоСтрока(ф.конечная)) return null;
      }
      if (с.подсказка !== null && !этоЛокализованный(с.подсказка)) return null;
      const подмены = Array.isArray(с.подмены) ? с.подмены.filter(этоЛокализованный) : [];
      const примеры = Array.isArray(с.примеры) ? с.примеры.filter(этоСтрока) : [];
      return { ...(з as ЗаданиеЗнакомство), подмены, примеры, соединяетсяСлева: с.соединяетсяСлева !== false, голосКари: null };
    }
    case 'прочитай': {
      if (!этоЛокализованный(с.подсказка) || !Array.isArray(с.строки)) return null;
      const строки = с.строки.filter(
        (стр): стр is { арабский: string; транскрипция: string } =>
          !!стр && typeof стр === 'object' && этоСтрока((стр as Record<string, unknown>).арабский) &&
          typeof (стр as Record<string, unknown>).транскрипция === 'string',
      );
      if (строки.length === 0) return null;
      return { ...(з as ЗаданиеПрочитай), строки, голосКари: null };
    }
    case 'выбор': {
      if (!этоЛокализованный(с.вопрос) || !Array.isArray(с.варианты)) return null;
      if (с.показ !== undefined && !этоСтрока(с.показ)) return null;
      if (с.пояснение !== undefined && !этоЛокализованный(с.пояснение)) return null;
      const варианты = с.варианты.map(проверитьВариант);
      if (варианты.length < 2 || варианты.length > 6 || варианты.some((в) => !в)) return null;
      if (!этоЦелое(с.верный, 0, варианты.length - 1)) return null;
      return { ...(з as ЗаданиеВыбор), варианты: варианты as ВариантОтвета[] };
    }
    case 'запись': {
      if (!этоЛокализованный(с.подсказка)) return null;
      const читать = проверитьЧтение(с.читать);
      if (!читать) return null;
      if (с.слоги !== undefined && !(Array.isArray(с.слоги) && с.слоги.every(этоСтрока))) return null;
      // Голоса кари в прототипе нет (этап 0б); любое значение кроме null игнорируем.
      return { ...(з as Задание & { тип: 'запись' }), читать, голосКари: null };
    }
    case 'лестница': {
      if (!этоЛокализованный(с.подсказка) || !Array.isArray(с.ступени)) return null;
      const ступени = с.ступени.map(проверитьЧтение).filter((ч): ч is NonNullable<typeof ч> => ч != null);
      if (ступени.length === 0) return null;
      return { ...(з as Задание & { тип: 'лестница' }), ступени, голосКари: null };
    }
    default:
      return null;
  }
}

const СТАТУСЫ: readonly СтатусКонтента[] = ['черновик', 'проверен-устазом', 'подписан-советом'];

export function проверитьУрок(сырые: unknown): Урок | null {
  if (!сырые || typeof сырые !== 'object') return null;
  const у = сырые as Record<string, unknown>;
  if (!этоЦелое(у.номер, 0, 999) || !этоЛокализованный(у.название) || !Array.isArray(у.задания)) return null;
  const задания = у.задания.map(проверитьЗадание).filter((з): з is Задание => з != null);
  if (задания.length === 0) return null;
  const критерий = у.критерий && typeof у.критерий === 'object' ? (у.критерий as Урок['критерий']) : { доляВерных: ПОРОГ_ПО_УМОЛЧАНИЮ };
  return {
    ...(сырые as Урок),
    цель: этоЛокализованный(у.цель) ? у.цель : { ru: '', kk: '' },
    новое: Array.isArray(у.новое) ? у.новое.filter(этоСтрока) : [],
    задания,
    критерий,
    статус: (СТАТУСЫ as readonly unknown[]).includes(у.статус) ? (у.статус as СтатусКонтента) : 'черновик',
  };
}

