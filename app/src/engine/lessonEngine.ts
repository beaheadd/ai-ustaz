// ───────────────────────── Итог задания и урока ─────────────────────────

/** Что сообщает упражнение, когда его можно завершить. Голос и теория — без оценки. */
export type ИтогЗадания = { оценивается: false } | { оценивается: true; верно: boolean };

export type ИтогУрокаПодсчёт = {
  /** Заданий с выбором (оцениваемых). */
  оцениваемых: number;
  верных: number;
  /** Доля верных 0..1; если оцениваемых нет — 1. */
  доля: number;
  /** Порог прохождения 0..1 (критерий урока, по умолчанию 0,8). */
  порог: number;
  пройден: boolean;
};

export const ПОРОГ_ПО_УМОЛЧАНИЮ = 0.8;

export function порогУрока(урок: Pick<Урок, 'критерий'>): number {
  const д = урок.критерий?.доляВерных;
  return typeof д === 'number' && Number.isFinite(д) && д > 0 && д <= 1 ? д : ПОРОГ_ПО_УМОЛЧАНИЮ;
}

export function подсчитатьИтог(урок: Pick<Урок, 'критерий'>, итоги: ReadonlyArray<ИтогЗадания | null>): ИтогУрокаПодсчёт {
  let оцениваемых = 0;
  let верных = 0;
  for (const и of итоги) {
    if (и && и.оценивается) {
      оцениваемых += 1;
      if (и.верно) верных += 1;
    }
  }
  const доля = оцениваемых > 0 ? верных / оцениваемых : 1;
  const порог = порогУрока(урок);
  // Небольшой допуск на дробную арифметику (4/5 = 0.8000000001 и т. п.).
  return { оцениваемых, верных, доля, порог, пройден: доля + 1e-9 >= порог };
}

// ───────────────────────── Прохождение (редьюсер) ─────────────────────────

export type ФазаУрока = 'вступление' | 'задания' | 'итог';

export type СостояниеУрока = {
  фаза: ФазаУрока;
  /** Индекс текущего задания (0…всего-1). */
  индекс: number;
  /** Итог каждого задания; засчитывается ПЕРВЫЙ ответ (повторный тап не меняет итог). */
  итоги: Array<ИтогЗадания | null>;
  /** Номер прохождения (растёт при «Пройти ещё раз»): ключ для пересоздания упражнений. */
  попытка: number;
};

export type ДействиеУрока =
  | { тип: 'начать' }
  | { тип: 'итогЗадания'; индекс: number; итог: ИтогЗадания }
  | { тип: 'далее' }
  | { тип: 'заново' }
  | { тип: 'восстановить'; индекс: number; итоги: ReadonlyArray<ИтогЗадания | null> };

export function начальноеСостояние(всего: number, попытка = 1): СостояниеУрока {
  return { фаза: 'вступление', индекс: 0, итоги: Array.from({ length: всего }, () => null), попытка };
}

export function шагУрока(с: СостояниеУрока, д: ДействиеУрока, всего: number): СостояниеУрока {
  switch (д.тип) {
    case 'начать':
      if (с.фаза !== 'вступление') return с;
      return всего > 0 ? { ...с, фаза: 'задания', индекс: 0 } : { ...с, фаза: 'итог' };
    case 'итогЗадания': {
      if (с.фаза !== 'задания' || д.индекс !== с.индекс || с.итоги[д.индекс] != null) return с;
      const итоги = с.итоги.slice();
      итоги[д.индекс] = д.итог;
      return { ...с, итоги };
    }
    case 'далее':
      if (с.фаза !== 'задания' || с.итоги[с.индекс] == null) return с;
      return с.индекс + 1 < всего ? { ...с, индекс: с.индекс + 1 } : { ...с, фаза: 'итог' };
    case 'восстановить': {
      if (с.фаза !== 'вступление' || !Number.isInteger(д.индекс) || д.индекс < 0 || д.индекс >= всего) return с;
      if (д.итоги.length !== всего) return с;
      // Задания до K — как были; текущее и дальше — заново.
      const итоги = д.итоги.map((и, i) => (i < д.индекс ? и : null));
      if (итоги.slice(0, д.индекс).some((и) => и == null)) return с;
      return { ...с, фаза: 'задания', индекс: д.индекс, итоги };
    }
    case 'заново': {
      const н = начальноеСостояние(всего, с.попытка + 1);
      return всего > 0 ? { ...н, фаза: 'задания' } : н;
    }
  }
}

// ───────────────────────── Вид упражнения ─────────────────────────

export type ВидУпражнения = 'знакомство' | 'теория' | 'найди' | 'пара' | 'собери' | 'прочитай' | 'скажи' | 'лестница';

/** Огласовки, танвины, шадда, сукун, малый алиф. */
const ЗНАК_ОГЛАСОВКИ = /^[\u064B-\u0652\u0670]+$/u;

/** Слог «буква + огласовка»: основа (первый символ) и знаки. null — если это не так. */
export function разобратьСлог(слог: string): { основа: string; знаки: string } | null {
  const символы = Array.from(слог);
  if (символы.length < 2) return null;
  const [основа, ...остальное] = символы;
  const знаки = остальное.join('');
  if (ЗНАК_ОГЛАСОВКИ.test(основа) || !ЗНАК_ОГЛАСОВКИ.test(знаки)) return null;
  return { основа, знаки };
}

/** «Собери слог» можно нарисовать: показ — буква, все варианты — эта буква с разными знаками. */
export function этоСобериСлог(з: ЗаданиеВыбор): boolean {
  if (!з.показ || з.варианты.length < 2) return false;
  const разборы = з.варианты.map((в) => ('арабский' in в ? разобратьСлог(в.арабский) : null));
  if (разборы.some((р) => !р || р.основа !== з.показ)) return false;
  return new Set(разборы.map((р) => р!.знаки)).size === разборы.length;
}

/**
 * Компонент для задания. Для «выбор» — по полю вид (ВидВыбора):
 *   собери → 'собери' (если данные подходят, иначе 'найди'); пара → 'пара' (2 варианта);
 *   буква, слог, огласовка, форма, вСлове, соединение → 'найди';
 *   без вида — 'собери', если подходит, 2 варианта — 'пара', иначе 'найди'.
 */
export function видУпражнения(задание: Задание): ВидУпражнения {
  switch (задание.тип) {
    case 'теория':
      return 'теория';
    case 'знакомство':
      return 'знакомство';
    case 'прочитай':
      return 'прочитай';
    case 'запись':
      return 'скажи';
    case 'лестница':
      return 'лестница';
    case 'выбор': {
      const вид = задание.вид;
      if (вид === 'собери') return этоСобериСлог(задание) ? 'собери' : 'найди';
      if (вид === 'пара') return задание.варианты.length === 2 ? 'пара' : 'найди';
      if (вид) return 'найди';
      if (этоСобериСлог(задание)) return 'собери';
      return задание.варианты.length === 2 ? 'пара' : 'найди';
    }
  }
}

