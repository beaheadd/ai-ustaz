type ИсточникУроков = { ключи: () => string[]; загрузить: (ключ: string) => Promise<unknown> };

function источникИзКонтекста(контекст: __MetroModuleApi.RequireContext): ИсточникУроков {
  return {
    ключи: () => контекст.keys(),
    загрузить: async (ключ) => {
      const м = await (контекст(ключ) as Promise<unknown> | unknown);
      return м && typeof м === 'object' && 'default' in м ? (м as { default: unknown }).default : м;
    },
  };
}

/**
 * Откуда берутся уроки. Каждый файл — отдельный чанк (lazy), грузится только при открытии урока.
 */
const ИСТОЧНИКИ: ИсточникУроков[] = [
  // /content/lessons/level1/L01.json … L16.json, K1.json (раскладка агента контента, src/content/types.ts)
  источникИзКонтекста(require.context('../../../content/lessons', true, /(^|\/)[LK]\d+\.json$/, 'lazy')),
];

/** Номер урока по имени файла: L07.json → 7, K1.json → 101 (контрольные точки: К1 = 101, К2 = 102…). */
export function номерИзИмениФайла(ключ: string): number | null {
  const н = /(?:^|\/)([LK])(\d+)\.json$/.exec(ключ);
  if (!н) return null;
  const число = Number(н[2]);
  return н[1] === 'K' ? 100 + число : число;
}

function найтиКлюч(номер: number): { источник: ИсточникУроков; ключ: string } | null {
  for (const источник of ИСТОЧНИКИ) {
    const ключ = источник.ключи().find((к) => номерИзИмениФайла(к) === номер);
    if (ключ) return { источник, ключ };
  }
  return null;
}

export function естьУрок(номер: number): boolean {
  return найтиКлюч(номер) != null;
}

/** Номера всех уроков, у которых есть файл (по возрастанию). */
export function номераУроков(): number[] {
  const все = new Set<number>();
  for (const источник of ИСТОЧНИКИ) {
    for (const к of источник.ключи()) {
      const н = номерИзИмениФайла(к);
      if (н != null) все.add(н);
    }
  }
  return [...все].sort((а, б) => а - б);
}

/**
 * Следующий урок для кнопки «Следующий урок»: ближайший больший номер того же ряда
 * (уроки 1–99 отдельно от контрольных 101+). Порядок курса с контрольными точками —
 * на карте курса (/content/course.json).
 */
export function следующийУрок(номер: number): number | null {
  const ряд = (н: number) => (н >= 100 ? Math.floor(н / 100) : 0);
  return номераУроков().find((н) => н > номер && ряд(н) === ряд(номер)) ?? null;
}

export async function загрузитьУрок(номер: number): Promise<Урок | null> {
  const найдено = найтиКлюч(номер);
  if (!найдено) return null;
  // Ошибка загрузки чанка (нет сети) — пробрасываем: это не «урока нет».
  const сырые = await найдено.источник.загрузить(найдено.ключ);
  try {
    const урок = проверитьУрок(сырые);
    return урок && урок.номер === номер ? урок : null;
  } catch {
    return null;
  }
}

