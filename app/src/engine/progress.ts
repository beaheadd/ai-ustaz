/**
 * Прогресс ученика — на устройстве (engine/storage.ts); на сервер — только если человек сам вошёл в аккаунт (account/,
 * владелец 28.11.2026: «кто хочет, мог заходить входом, и у него прогресс сохраняется»).
 *
 * Что храним (и ничего больше): пройденные уроки и лучший результат, дни занятий
 * (даты по Алматы, UTC+5), язык интерфейса, флаги «онбординг пройден» (место и аср; 28.11.2026), «ИИ-предупреждение показано»,
 * «пояснение о микрофоне показано» и «согласие на проверку голосом» (запись уходит на сервер
 * AI Ustaz в РК только по нажатию «Проверить»; только свой домен). Никаких персональных данных и записей голоса.
 *
 * Контракт (чистые функции — для экранов и тестов):
 *   датаАлматы(момент?) → 'ГГГГ-ММ-ДД' по Алматы (UTC+5, без перехода на летнее время);
 *   отметитьДеньЗанятий(п, момент?) → Прогресс;
 *   отметитьУрок(п, номер, { доля, пройден }, момент?) → Прогресс (лучший = максимум доли);
 *   днейЗанятийЗа(п, дней = 30, момент?) → число дней занятий в последних N днях (включая сегодня);
 *   нормализоватьПрогресс(сырые) → Прогресс (защита от испорченных данных).
 * React:
 *   <ПоставщикПрогресса> — оборачивает приложение (App.tsx);
 *   useПрогресс() → { прогресс, загружен, изменить(функция), сбросить() }.
 *   изменить(п => отметитьУрок(п, 3, { доля: 0.9, пройден: true })) — сохраняет сам.
 *   сбросить() — удаляет прогресс на устройстве, язык интерфейса и отметка онбординга сохраняются.
 *
 * Мотивация (программа курса §3.5): «N из последних 30 дней» вместо сгорающей серии;
 * никаких публичных рейтингов, очков, «хасанат-счётчиков».
 */
import { createContext, createElement, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import { прочитатьJSON, записатьJSON, приВнешнемИзменении } from './storage';

/** Язык интерфейса — i18n/languages.ts (ru, kk, uz, en; с 28.11.2026 ещё ar, tr, id, ur). Кроме ru — черновики (CLAUDE.md). */
import { ВСЕ_ЯЗЫКИ, type Язык } from '../i18n/languages';
export type { Язык } from '../i18n/languages';
export { ВСЕ_ЯЗЫКИ } from '../i18n/languages';

export type ИтогУрока = {
  /** Урок пройден хотя бы раз (по критерию урока). */
  пройден: boolean;
  /** Лучший результат — доля верных ответов 0..1 (только задания «тап»; голос без оценки). */
  лучший: number;
  /** Сколько раз урок завершали. */
  попыток: number;
  /** Дата последнего завершения, 'ГГГГ-ММ-ДД' по Алматы. */
  последний: string;
};

export type Прогресс = {
  версия: 1;
  язык: Язык | null;
  /** Онбординг «Где вы? · Время асра» пройден или отложен «Позже» — главная его больше не открывает (28.11.2026). */
  онбордингПройден: boolean;
  /** ИИ-предупреждение QML (урок 0) показано и принято. */
  предупреждениеПоказано: boolean;
  /** Пояснение о приватности записи показано (перед первым запросом микрофона). */
  пояснениеМикрофонаПоказано: boolean;
  /** Пояснение «запись уйдёт на сервер AI Ustaz в Казахстане, удалится сразу после проверки» показано и принято. */
  согласиеПроверкиГолосом: boolean;
  /** Ключ — номер урока строкой: '0', '1', … */
  уроки: Record<string, ИтогУрока>;
  /** Дни занятий 'ГГГГ-ММ-ДД' по Алматы, по возрастанию, без повторов. */
  дниЗанятий: string[];
};

const КЛЮЧ = 'progress.v1';
const МАКС_ДНЕЙ = 400;
const СМЕЩЕНИЕ_АЛМАТЫ_МС = 5 * 60 * 60 * 1000;
const ДЕНЬ_МС = 24 * 60 * 60 * 1000;
const ДАТА = /^\d{4}-\d{2}-\d{2}$/;

export const начальныйПрогресс: Прогресс = {
  версия: 1,
  язык: null,
  онбордингПройден: false,
  предупреждениеПоказано: false,
  пояснениеМикрофонаПоказано: false,
  согласиеПроверкиГолосом: false,
  уроки: {},
  дниЗанятий: [],
};

export function датаАлматы(момент: Date = new Date()): string {
  return new Date(момент.getTime() + СМЕЩЕНИЕ_АЛМАТЫ_МС).toISOString().slice(0, 10);
}

export function отметитьДеньЗанятий(п: Прогресс, момент: Date = new Date()): Прогресс {
  const сегодня = датаАлматы(момент);
  if (п.дниЗанятий.includes(сегодня)) return п;
  const дни = [...п.дниЗанятий, сегодня].sort().slice(-МАКС_ДНЕЙ);
  return { ...п, дниЗанятий: дни };
}

export function отметитьУрок(
  п: Прогресс,
  номер: number,
  итог: { доля: number; пройден: boolean },
  момент: Date = new Date(),
): Прогресс {
  const ключ = String(номер);
  const был = п.уроки[ключ];
  const доля = Math.min(1, Math.max(0, Number.isFinite(итог.доля) ? итог.доля : 0));
  const новый: ИтогУрока = {
    пройден: Boolean(был?.пройден) || итог.пройден,
    лучший: Math.max(был?.лучший ?? 0, доля),
    попыток: (был?.попыток ?? 0) + 1,
    последний: датаАлматы(момент),
  };
  return отметитьДеньЗанятий({ ...п, уроки: { ...п.уроки, [ключ]: новый } }, момент);
}

export function днейЗанятийЗа(п: Прогресс, дней = 30, момент: Date = new Date()): number {
  const граница = датаАлматы(new Date(момент.getTime() - (дней - 1) * ДЕНЬ_МС));
  const сегодня = датаАлматы(момент);
  return п.дниЗанятий.filter((д) => д >= граница && д <= сегодня).length;
}

export function нормализоватьПрогресс(сырые: unknown): Прогресс {
  if (!сырые || typeof сырые !== 'object') return начальныйПрогресс;
  const с = сырые as Partial<Record<keyof Прогресс, unknown>>;
  const уроки: Record<string, ИтогУрока> = {};
  if (с.уроки && typeof с.уроки === 'object') {
    for (const [ключ, з] of Object.entries(с.уроки as Record<string, unknown>)) {
      if (!/^\d{1,3}$/.test(ключ) || !з || typeof з !== 'object') continue;
      const у = з as Partial<ИтогУрока>;
      уроки[ключ] = {
        пройден: у.пройден === true,
        лучший: typeof у.лучший === 'number' && Number.isFinite(у.лучший) ? Math.min(1, Math.max(0, у.лучший)) : 0,
        попыток: typeof у.попыток === 'number' && у.попыток >= 0 ? Math.floor(у.попыток) : 0,
        последний: typeof у.последний === 'string' && ДАТА.test(у.последний) ? у.последний : '',
      };
    }
  }
  const дни = Array.isArray(с.дниЗанятий)
    ? [...new Set(с.дниЗанятий.filter((д): д is string => typeof д === 'string' && ДАТА.test(д)))].sort().slice(-МАКС_ДНЕЙ)
    : [];
  return {
    версия: 1,
    язык: (ВСЕ_ЯЗЫКИ as readonly unknown[]).includes(с.язык) ? (с.язык as Язык) : null,
    онбордингПройден: с.онбордингПройден === true,
    предупреждениеПоказано: с.предупреждениеПоказано === true,
    пояснениеМикрофонаПоказано: с.пояснениеМикрофонаПоказано === true,
    согласиеПроверкиГолосом: с.согласиеПроверкиГолосом === true,
    уроки,
    дниЗанятий: дни,
  };
}

type ЗначениеПрогресса = {
  прогресс: Прогресс;
  /** false, пока прогресс читается из хранилища (первые миллисекунды). */
  загружен: boolean;
  изменить: (функция: (п: Прогресс) => Прогресс) => void;
  сбросить: () => void;
};

const КонтекстПрогресса = createContext<ЗначениеПрогресса | null>(null);

export function ПоставщикПрогресса({ children }: { children: ReactNode }) {
  const [прогресс, установить] = useState<Прогресс>(начальныйПрогресс);
  const [загружен, установитьЗагружен] = useState(false);
  const загруженСсылка = useRef(false);
  // Изменения, пришедшие до чтения хранилища, применяем поверх прочитанного — не теряем ни то, ни другое.
  const очередь = useRef<Array<(п: Прогресс) => Прогресс>>([]);

  useEffect(() => {
    let живой = true;
    прочитатьJSON<unknown>(КЛЮЧ, null).then((сырые) => {
      if (!живой) return;
      let п = нормализоватьПрогресс(сырые);
      for (const функция of очередь.current) п = функция(п);
      очередь.current = [];
      загруженСсылка.current = true;
      установить(п);
      установитьЗагружен(true);
    });
    return () => {
      живой = false;
    };
  }, []);

  useEffect(
    () =>
      // Аккаунт (владелец 28.11.2026): синхронизация записала прогресс другого устройства — перечитать.
      приВнешнемИзменении(КЛЮЧ, () => {
        void прочитатьJSON<unknown>(КЛЮЧ, null).then((сырые) => {
          if (загруженСсылка.current) установить(нормализоватьПрогресс(сырые));
        });
      }),
    [],
  );

  useEffect(() => {
    if (загружен) void записатьJSON(КЛЮЧ, прогресс);
  }, [прогресс, загружен]);

  const изменить = useCallback((функция: (п: Прогресс) => Прогресс) => {
    if (!загруженСсылка.current) {
      очередь.current.push(функция);
      return;
    }
    установить((п) => функция(п));
  }, []);

  const сбросить = useCallback(() => {
    изменить((п) => ({ ...начальныйПрогресс, язык: п.язык, онбордингПройден: п.онбордингПройден }));
  }, [изменить]);

  const значение = useMemo(() => ({ прогресс, загружен, изменить, сбросить }), [прогресс, загружен, изменить, сбросить]);
  return createElement(КонтекстПрогресса.Provider, { value: значение }, children);
}

export function useПрогресс(): ЗначениеПрогресса {
  const з = useContext(КонтекстПрогресса);
  if (!з) throw new Error('useПрогресс: нет <ПоставщикПрогресса> выше по дереву');
  return з;
}
