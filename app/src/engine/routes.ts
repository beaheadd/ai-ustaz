/** Разделы нижнего меню по порядку (список владельца 19.11.2026). */
export const ВКЛАДКИ = ['главная', 'таджвид', 'коран', 'хадисы', 'ещё'] as const;
export type Вкладка = (typeof ВКЛАДКИ)[number];

/** Экран-корень раздела (адрес таджвида — прежний #/course: на него ведут ссылки и тесты). */
