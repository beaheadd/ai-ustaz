/**
 * Маршруты приложения: список экранов, их параметры и запись в hash-адрес.
 *
 * Контракт:
 *   Маршруты — карта «экран → параметры» (undefined — без параметров);
 *   вХэш({ экран, параметры }) → '#/lesson/3';  изХэша('#/lesson/3') → { экран: 'урок', параметры: { номер: 3 } } | null.
 * Адреса в hash латиницей (#/course), чтобы ссылки не превращались в %D0%…
 *
 * Новый экран: 1) добавить в Маршруты; 2) путь в ПУТИ (и разбор параметров в ПАРАМЕТРЫ,
 * если они есть); 3) компонент в src/screens/index.ts (ЭКРАНЫ); 4) его вкладку в ВКЛАДКА_ЭКРАНА
 * (а если у экрана свой закреплённый низ — в ФОКУСНЫЕ).
 *
 * Нижнее меню (docs/дизайн/04-нижнее-меню-и-главная.md, решение владельца 19.11.2026 «нижний блок меню
 * обязательно»): ВКЛАДКИ — пять разделов по порядку (главная · таджвид · коран · хадисы · ещё);
 * КОРЕНЬ_ВКЛАДКИ — экран-корень раздела; ВКЛАДКА_ЭКРАНА — к какому разделу относится экран;
 * активнаяВкладка(стек) — подсвеченный раздел: при одном экране — главная, иначе раздел второго экрана стека
 * (подстраница остаётся в разделе, откуда её открыли: «Город» из «Ещё» — «Ещё», с главной — «Главная»);
 * ФОКУСНЫЕ — экраны без меню (урок, урок 0, онбординг: свой закреплённый низ); этоКореньВкладки(экран).
 * Путевую маршрутизацию не использовать: на batr.kz перезагрузка /aiustaz/что-то
 * отдаст index.html сайта BATR (nginx без $uri/), а hash переживает редирект.
 */
export type Маршруты = {
  главная: undefined;
  онбординг: undefined;
  урок0: undefined;
  картаКурса: undefined;
  урок: { номер: number };
  какОбъясняем: undefined;
  оПроекте: undefined;
  лицензии: undefined;
  кибла: undefined;
  намаз: undefined;
  городНамаза: undefined;
  коран: undefined;
  хадисы: undefined;
  ещё: undefined;
};

export type ИмяЭкрана = keyof Маршруты;

/** Экран с параметрами — то, что лежит в стеке навигации (без служебного ключа). */
export type Цель = { [K in ИмяЭкрана]: { экран: K; параметры: Маршруты[K] } }[ИмяЭкрана];

/** Пропсы компонента экрана: { параметры } его маршрута. */
export type ПропсыЭкрана<K extends ИмяЭкрана> = { параметры: Маршруты[K] };

/** Кортеж параметров для перейти(экран, ...параметры): у экранов без параметров — пусто. */
export type ПараметрыЭкрана<K extends ИмяЭкрана> = Маршруты[K] extends undefined ? [] : [Маршруты[K]];

const ПУТИ: { [K in ИмяЭкрана]: string } = {
  главная: '',
  онбординг: 'onboarding',
  урок0: 'lesson0',
  картаКурса: 'course',
  урок: 'lesson',
  какОбъясняем: 'how',
  оПроекте: 'about',
  лицензии: 'licenses',
  кибла: 'qibla',
  намаз: 'prayer',
  городНамаза: 'prayer-city',
  коран: 'quran',
  хадисы: 'hadith',
  ещё: 'more',
};

type Разбор<P> = { вСтроку: (п: P) => string; изСтроки: (с: string) => P | null };

const ПАРАМЕТРЫ: { [K in ИмяЭкрана]?: Разбор<NonNullable<Маршруты[K]>> } = {
  урок: {
    вСтроку: (п) => String(п.номер),
    изСтроки: (с) => (/^\d{1,3}$/.test(с) ? { номер: Number(с) } : null),
  },
};

export const ГЛАВНАЯ: Цель = { экран: 'главная', параметры: undefined };

// ───────────────────────── Нижнее меню: разделы верхнего уровня ─────────────────────────

/** Разделы нижнего меню по порядку (список владельца 19.11.2026). */
export const ВКЛАДКИ = ['главная', 'таджвид', 'коран', 'хадисы', 'ещё'] as const;
export type Вкладка = (typeof ВКЛАДКИ)[number];

/** Экран-корень раздела (адрес таджвида — прежний #/course: на него ведут ссылки и тесты). */
export const КОРЕНЬ_ВКЛАДКИ = {
  главная: 'главная',
  таджвид: 'картаКурса',
  коран: 'коран',
  хадисы: 'хадисы',
  ещё: 'ещё',
} as const satisfies Record<Вкладка, ИмяЭкрана>;

/** Раздел каждого экрана (для подсветки, когда экран — второй в стеке, например после глубокой ссылки). */
export const ВКЛАДКА_ЭКРАНА: { [K in ИмяЭкрана]: Вкладка } = {
  главная: 'главная',
  онбординг: 'главная',
  намаз: 'главная',
  кибла: 'главная',
  городНамаза: 'главная',
  картаКурса: 'таджвид',
  урок: 'таджвид',
  урок0: 'таджвид',
  коран: 'коран',
  хадисы: 'хадисы',
  ещё: 'ещё',
  оПроекте: 'ещё',
  лицензии: 'ещё',
  какОбъясняем: 'ещё',
};

/** Экраны без нижнего меню: самодостаточная задача со своим закреплённым низом («Далее»). */
export const ФОКУСНЫЕ: ReadonlySet<ИмяЭкрана> = new Set<ИмяЭкрана>(['урок', 'урок0', 'онбординг']);

/** Подсвеченный раздел: при одном экране — главная, иначе раздел второго экрана стека. Чистая функция. */
export function активнаяВкладка(стек: readonly { экран: ИмяЭкрана }[]): Вкладка {
  return стек.length <= 1 ? 'главная' : ВКЛАДКА_ЭКРАНА[стек[1].экран];
}

/** Экран — корень одного из разделов (на корне в шапке эмблема, а не «Назад»). */
export function этоКореньВкладки(экран: ИмяЭкрана): boolean {
  return ВКЛАДКИ.some((в) => КОРЕНЬ_ВКЛАДКИ[в] === экран);
}

export function вХэш(цель: Цель): string {
  const путь = ПУТИ[цель.экран];
  const разбор = ПАРАМЕТРЫ[цель.экран] as Разбор<unknown> | undefined;
  const хвост = разбор && цель.параметры !== undefined ? '/' + encodeURIComponent(разбор.вСтроку(цель.параметры)) : '';
  return '#/' + путь + хвост;
}

export function изХэша(хэш: string): Цель | null {
  const чистый = хэш.replace(/^#/, '').replace(/^\/+/, '').replace(/\/+$/, '');
  if (чистый === '') return ГЛАВНАЯ;
  const [путь, ...остаток] = чистый.split('/');
  const экран = (Object.keys(ПУТИ) as ИмяЭкрана[]).find((к) => ПУТИ[к] === путь && путь !== '');
  if (!экран) return null;
  const разбор = ПАРАМЕТРЫ[экран] as Разбор<unknown> | undefined;
  if (!разбор) return остаток.length === 0 ? ({ экран, параметры: undefined } as Цель) : null;
  if (остаток.length !== 1) return null;
  let строка: string;
  try {
    строка = decodeURIComponent(остаток[0]);
  } catch {
    return null;
  }
  const параметры = разбор.изСтроки(строка);
  return параметры == null ? null : ({ экран, параметры } as Цель);
}
