/** Подсвеченный раздел: при одном экране — главная, иначе раздел второго экрана стека. Чистая функция. */
export function активнаяВкладка(стек: readonly { экран: ИмяЭкрана }[]): Вкладка {
  return стек.length <= 1 ? 'главная' : ВКЛАДКА_ЭКРАНА[стек[1].экран];
}

/** Экран — корень одного из разделов (на корне в шапке эмблема, а не «Назад»). */
export function этоКореньВкладки(экран: ИмяЭкрана): boolean {
  return ВКЛАДКИ.some((в) => КОРЕНЬ_ВКЛАДКИ[в] === экран);
}

/**
 * Предки экрана для глубокой ссылки (первый вход, перезагрузка без своей записи в истории): стек будет
 * [главная, ...предки, экран], и «назад» ведёт по ним. #/quran/sura?n=2&a=255 → [главная, коран, сура];
 * #/quran/check?n=2&a=255 → [главная, коран, сура 2 (к аяту 255), проверкаАята]; #/hadith/item?n=1751 и
 * #/hadith/list?n=4 → [главная, хадисы, экран]. Остальные экраны — без предков.
 */
export function предкиГлубокойСсылки(цель: Цель): Цель[] {
  const коран: Цель = { экран: 'коран', параметры: undefined };
  if (цель.экран === 'сура') return [коран];
  if (цель.экран === 'проверкаАята') return [коран, { экран: 'сура', параметры: { номер: цель.параметры.номер, аят: цель.параметры.аят } }];
  // Хадисы (владелец 21.11.2026): #/hadith/item?n=1751 и #/hadith/list?n=4 → [главная, хадисы, …].
  if (цель.экран === 'хадис' || цель.экран === 'разделХадисов') return [{ экран: 'хадисы', параметры: undefined }];
  // Зикры (владелец 26.11.2026): #/dhikr → [главная, ещё, зикры]; #/dhikr/item?n=3 → [главная, ещё, зикры, зикр].
  if (цель.экран === 'зикры') return [{ экран: 'ещё', параметры: undefined }];
  if (цель.экран === 'зикр') return [{ экран: 'ещё', параметры: undefined }, { экран: 'зикры', параметры: undefined }];
  // Махраджи (владелец 26.11.2026): #/makharij → [главная, таджвид, махраджи]; #/makharij/letter?n=3 → […, махраджи, буква].
  if (цель.экран === 'махраджи') return [{ экран: 'картаКурса', параметры: undefined }];
  if (цель.экран === 'букваМахраджа') return [{ экран: 'картаКурса', параметры: undefined }, { экран: 'махраджи', параметры: undefined }];
  return [];
}

export function вХэш(цель: Цель): string {
  const путь = ПУТИ[цель.экран];
  const разбор = ПАРАМЕТРЫ[цель.экран] as Разбор<unknown> | undefined;
  if (!разбор || цель.параметры === undefined) return '#/' + путь;
  if (разбор.вид === 'сегмент') return '#/' + путь + '/' + encodeURIComponent(разбор.вСтроку(цель.параметры));
  const з = разбор.вЗапрос(цель.параметры);
  const пары = КЛЮЧИ_ЗАПРОСА.flatMap((к) => (з[к] === undefined ? [] : [к + '=' + з[к]]));
  return '#/' + путь + (пары.length ? '?' + пары.join('&') : '');
}

export function изХэша(хэш: string): Цель | null {
  const безРешётки = хэш.replace(/^#/, '');
  const знак = безРешётки.indexOf('?');
  const строкаЗапроса = знак < 0 ? null : безРешётки.slice(знак + 1);
  const чистый = (знак < 0 ? безРешётки : безРешётки.slice(0, знак)).replace(/^\/+/, '').replace(/\/+$/, '');
  if (чистый === '') return строкаЗапроса === null ? ГЛАВНАЯ : null;
  const экран = ПУТИ_ПО_ДЛИНЕ.find((к) => чистый === ПУТИ[к] || чистый.startsWith(ПУТИ[к] + '/'));
  if (!экран) return null;
  const остаток = чистый === ПУТИ[экран] ? [] : чистый.slice(ПУТИ[экран].length + 1).split('/');
  const разбор = ПАРАМЕТРЫ[экран] as Разбор<unknown> | undefined;
  if (!разбор) return остаток.length === 0 && строкаЗапроса === null ? ({ экран, параметры: undefined } as Цель) : null;
  if (разбор.вид === 'запрос') {
    if (остаток.length !== 0 || строкаЗапроса === null) return null;
    const запрос = разобратьЗапрос(строкаЗапроса);
    const параметры = запрос ? разбор.изЗапроса(запрос) : null;
    return параметры == null ? null : ({ экран, параметры } as Цель);
  }
  if (остаток.length !== 1 || строкаЗапроса !== null) return null;
  let строка: string;
  try {
    строка = decodeURIComponent(остаток[0]);
  } catch {
    return null;
  }
  const параметры = разбор.изСтроки(строка);
  return параметры == null ? null : ({ экран, параметры } as Цель);
}
