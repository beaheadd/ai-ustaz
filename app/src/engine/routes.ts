/**
 * Маршруты приложения: список экранов, их параметры и запись в hash-адрес.
 *
 * Контракт:
 *   Маршруты — карта «экран → параметры» (undefined — без параметров);
 *   вХэш({ экран, параметры }) → '#/lesson/3';  изХэша('#/lesson/3') → { экран: 'урок', параметры: { номер: 3 } } | null.
 * Адреса в hash латиницей (#/course), чтобы ссылки не превращались в %D0%…
 *
 * Новый экран: 1) добавить в Маршруты; 2) путь в ПУТИ (и разбор параметров в ПАРАМЕТРЫ,
 * если они есть: «сегмент» #/lesson/3 или «запрос» #/quran/sura?n=2&a=255); 3) компонент в src/screens/index.ts (ЭКРАНЫ); 4) его вкладку в ВКЛАДКА_ЭКРАНА
 * (а если у экрана свой закреплённый низ — в ФОКУСНЫЕ).
 *
 * Нижнее меню (docs/дизайн/04-нижнее-меню-и-главная.md, решение владельца 19.11.2026 «нижний блок меню
 * обязательно»): ВКЛАДКИ — пять разделов по порядку (главная · таджвид · коран · хадисы · ещё);
 * КОРЕНЬ_ВКЛАДКИ — экран-корень раздела; ВКЛАДКА_ЭКРАНА — к какому разделу относится экран;
 * активнаяВкладка(стек) — подсвеченный раздел: при одном экране — главная, иначе раздел второго экрана стека
 * (подстраница остаётся в разделе, откуда её открыли: «Город» из «Ещё» — «Ещё», с главной — «Главная»);
 * ФОКУСНЫЕ — экраны без меню (урок, урок 0, онбординг: свой закреплённый низ); этоКореньВкладки(экран).
 * Коран (решение владельца 19.11.2026: «Коран полностью, все аяты…», docs/дизайн/05 §2.1): путь может быть из двух
 * сегментов (quran/sura, quran/check — сопоставляется самый длинный), параметры — query-строкой n/a/p (только цифры);
 * предкиГлубокойСсылки(цель) — промежуточные экраны стека при глубокой ссылке ([главная, коран, сура]).
 * Путевую маршрутизацию не использовать: на batr.kz перезагрузка /aiustaz/что-то
 * отдаст index.html сайта BATR (nginx без $uri/), а hash переживает редирект.
 */
export type Маршруты = {
  главная: undefined;
  онбординг: undefined;
  урок0: undefined;
  картаКурса: undefined;
  урок: { номер: number };
  какОбъясняем: undefined;
  оПроекте: undefined;
  лицензии: undefined;
  кибла: undefined;
  намаз: undefined;
  городНамаза: undefined;
  коран: undefined;
  /** Сура полного Корана: номер 1…114, аят — к какому прокрутить (1…286; больше аятов суры — проверяет экран). */
  сура: { номер: number; аят?: number };
  /** «Прочитать и записать» аят: часть — номер части аята с 1 (quran-check), по умолчанию 1. */
  проверкаАята: { номер: number; аят: number; часть?: number };
  хадисы: undefined;
  ещё: undefined;
  установка: undefined;
  /** Уведомления о времени намаза (владелец 20.11.2026). */
  уведомления: undefined;
};

export type ИмяЭкрана = keyof Маршруты;

/** Экран с параметрами — то, что лежит в стеке навигации (без служебного ключа). */
export type Цель = { [K in ИмяЭкрана]: { экран: K; параметры: Маршруты[K] } }[ИмяЭкрана];

/** Пропсы компонента экрана: { параметры } его маршрута. */
export type ПропсыЭкрана<K extends ИмяЭкрана> = { параметры: Маршруты[K] };

/** Кортеж параметров для перейти(экран, ...параметры): у экранов без параметров — пусто. */
export type ПараметрыЭкрана<K extends ИмяЭкрана> = Маршруты[K] extends undefined ? [] : [Маршруты[K]];

const ПУТИ: { [K in ИмяЭкрана]: string } = {
  главная: '',
  онбординг: 'onboarding',
  урок0: 'lesson0',
  картаКурса: 'course',
  урок: 'lesson',
  какОбъясняем: 'how',
  оПроекте: 'about',
  лицензии: 'licenses',
  кибла: 'qibla',
  намаз: 'prayer',
  городНамаза: 'prayer-city',
  коран: 'quran',
  сура: 'quran/sura',
  проверкаАята: 'quran/check',
  хадисы: 'hadith',
  ещё: 'more',
  установка: 'install',
  уведомления: 'notifications',
};

/**
 * Разбор параметров: «сегмент» — один сегмент пути после экрана (#/lesson/3); «запрос» — query-строка после «?»
 * (#/quran/sura?n=2&a=255): только ключи n, a, p, значения — только цифры; лишний, повторный или пустой ключ — null.
 * вЗапрос пишет ключи в порядке n, a, p и пропускает незаданные (undefined).
 */
type Разбор<P> =
  | { вид: 'сегмент'; вСтроку: (п: P) => string; изСтроки: (с: string) => P | null }
  | { вид: 'запрос'; вЗапрос: (п: P) => Partial<Record<КлючЗапроса, number>>; изЗапроса: (з: Partial<Record<КлючЗапроса, number>>) => P | null };

type КлючЗапроса = 'n' | 'a' | 'p';
const КЛЮЧИ_ЗАПРОСА: readonly КлючЗапроса[] = ['n', 'a', 'p'];

/** Целое в диапазоне или null (undefined — нет ключа). */
function вДиапазоне(з: number | undefined, мин: number, макс: number): number | null | undefined {
  if (з === undefined) return undefined;
  return Number.isInteger(з) && з >= мин && з <= макс ? з : null;
}

/** Сур в мусхафе; аятов в самой длинной суре (аль-Бакара); частей аята — с запасом (самый длинный аят — 2:282). */
const СУР = 114;
const МАКС_АЯТ = 286;
const МАКС_ЧАСТЬ = 99;

const ПАРАМЕТРЫ: { [K in ИмяЭкрана]?: Разбор<NonNullable<Маршруты[K]>> } = {
  урок: {
    вид: 'сегмент',
    вСтроку: (п) => String(п.номер),
    изСтроки: (с) => (/^\d{1,3}$/.test(с) ? { номер: Number(с) } : null),
  },
  сура: {
    вид: 'запрос',
    вЗапрос: (п) => ({ n: п.номер, a: п.аят }),
    изЗапроса: (з) => {
      const номер = вДиапазоне(з.n, 1, СУР);
      const аят = вДиапазоне(з.a, 1, МАКС_АЯТ);
      if (!номер || аят === null || з.p !== undefined) return null;
      return аят === undefined ? { номер } : { номер, аят };
    },
  },
  проверкаАята: {
    вид: 'запрос',
    вЗапрос: (п) => ({ n: п.номер, a: п.аят, p: п.часть }),
    изЗапроса: (з) => {
      const номер = вДиапазоне(з.n, 1, СУР);
      const аят = вДиапазоне(з.a, 1, МАКС_АЯТ);
      const часть = вДиапазоне(з.p, 1, МАКС_ЧАСТЬ);
      if (!номер || !аят || часть === null) return null;
      return часть === undefined ? { номер, аят } : { номер, аят, часть };
    },
  },
};

/** Разбор query-строки: только n, a, p, только цифры (1–3), без повторов. null — строка неверная. */
function разобратьЗапрос(строка: string): Partial<Record<КлючЗапроса, number>> | null {
  const итог: Partial<Record<КлючЗапроса, number>> = {};
  if (строка === '') return итог;
  for (const пара of строка.split('&')) {
    const м = /^([nap])=(\d{1,3})$/.exec(пара);
    if (!м) return null;
    const ключ = м[1] as КлючЗапроса;
    if (итог[ключ] !== undefined) return null;
    итог[ключ] = Number(м[2]);
  }
  return итог;
}

/** Пути по убыванию числа сегментов: «quran/sura» сопоставляется раньше «quran» (самое длинное совпадение). */
const ПУТИ_ПО_ДЛИНЕ = (Object.keys(ПУТИ) as ИмяЭкрана[])
  .filter((к) => ПУТИ[к] !== '')
  .sort((а, б) => ПУТИ[б].split('/').length - ПУТИ[а].split('/').length);

export const ГЛАВНАЯ: Цель = { экран: 'главная', параметры: undefined };

