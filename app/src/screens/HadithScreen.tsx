export function Хадисы(_: ПропсыЭкрана<'хадисы'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тх = useСловарь(СЛОВАРЬ_ХАДИСОВ);
  const { перейти, перейтиВкладку } = useНавигация();
  const { цвет, отступ } = useТема();
  const индекс = useИндексХадисов();
  const заголовки = useЗаголовкиЯзыка(язык);
  const [запрос, установитьЗапрос] = useState('');
  const [показано, установитьПоказано] = useState(ПО);

  const и = индекс.состояние === 'есть' ? индекс.данные : null;
  const найдено = useMemo(() => (и && заголовки.состояние.состояние === 'есть' ? найти(и, заголовки.заголовки, запрос) : null), [и, заголовки.состояние.состояние, заголовки.заголовки, запрос]); // eslint-disable-line react-hooks/exhaustive-deps
  const корни = и ? подкатегории(и, 0) : [];
  const ищем = запрос.trim().length > 0;

  return (
    <Экран заголовок={t('экран.хадисы')} testID="экран-хадисы">
      <Карточка вид="арка" testID="хадисы-вступление">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <Значок имя="хадис" размер={24} цвет={цвет.акцент} />
          <Текст вид="подзаголовок" accessibilityRole="header" уровень={2} стиль={{ flex: 1 }}>
            {т('заголовок')}
          </Текст>
        </View>
        <Текст>{т('вступление')}</Текст>
        <Плашка вид="черновик" надпись={тх('черновик')} testID="хадисы-черновик" />
      </Карточка>

      <Карточка вид="акцент" testID="хадисы-ии">
        <View style={{ flexDirection: 'row', alignItems: 'flex-start', gap: отступ.s }}>
          <Значок имя="инфо" размер={22} цвет={цвет.акцент} />
          <View style={{ flex: 1, gap: отступ.xs }}>
            <Текст стиль={{ fontWeight: '600' }}>{т('ии')}</Текст>
            <Текст>{т('имам')}</Текст>
          </View>
        </View>
      </Карточка>

      {/* Без сети (владелец 27.11.2026): все хадисы — в память телефона одной кнопкой (≈7 МБ). */}
      <ЗагрузкаОфлайн группа="хадисы" />

      {язык === 'kk' ? (
        <Текст вид="второй" testID="хадисы-нет-перевода">
          {тх('запасной')}
        </Текст>
      ) : null}

      {индекс.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="хадисы-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : индекс.состояние === 'нет' ? (
        <ХадисыНедоступны состояние={индекс} />
      ) : (
        <View style={{ gap: отступ.m }}>
          <ПолеПоиска
            значение={запрос}
            изменить={(с) => {
              установитьЗапрос(с);
              установитьПоказано(ПО);
            }}
            подсказка={т('поиск')}
            подпись={т('поискПодпись')}
            testID="хадисы-поиск"
          />
          <Текст testID="хадисы-найдено" accessibilityLiveRegion="polite" {...(ВЕБ ? ({ role: 'status' } as object) : null)} стиль={стильСкрытого}>
            {ищем && найдено ? т('найдено', { н: найдено.length }) : ''}
          </Текст>
          {ищем ? (
            заголовки.состояние.состояние === 'нет' ? (
              <ХадисыНедоступны состояние={{ ...заголовки.состояние, повторить: заголовки.повторить }} />
            ) : !найдено ? (
              <Текст вид="второй">{t('общее.загрузка')}</Текст>
            ) : найдено.length === 0 ? (
              <Текст вид="второй" testID="хадисы-ничего" accessibilityLiveRegion="polite">
                {т('ничего')}
              </Текст>
            ) : (
              <View style={{ gap: отступ.s }}>
                <СписокХадисов записи={найдено.slice(0, показано)} заголовки={заголовки.заголовки} testID="хадисы-результаты" />
                {найдено.length > показано ? (
                  <Кнопка вид="вторичная" надпись={т('ещё')} приНажатии={() => установитьПоказано((п) => п + ПО)} testID="хадисы-ещё" />
                ) : null}
              </View>
            )
          ) : (
            <View style={{ gap: отступ.s }} testID="хадисы-разделы">
              <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
                {т('разделы')}
              </Текст>
              {корни.map((к) => (
                <СтрокаСписка
                  key={к.id}
                  заголовок={названиеКатегории(к, язык)}
                  подпись={тх('хадисов', { н: к.хадисов })}
                  значок="хадис"
                  приНажатии={() => перейти('разделХадисов', { номер: к.id })}
                  testID={'хадисы-раздел-' + к.id}
                />
              ))}
            </View>
          )}
        </View>
      )}

      <Текст вид="мелкий" testID="хадисы-ждут">
        {т('ждут')}
      </Текст>
      <Текст вид="мелкий" testID="хадисы-источник">
        {т('источник')}
      </Текст>
      <СтрокаСписка заголовок={т('лицензии')} подпись={т('лицензииПояснение')} значок="меню" приНажатии={() => перейти('лицензии')} testID="хадисы-лицензии" />
      <Кнопка вид="вторичная" значок="таджвид" надпись={т('кУрокам')} приНажатии={() => перейтиВкладку('таджвид')} testID="хадисы-к-урокам" />
    </Экран>
  );
}
