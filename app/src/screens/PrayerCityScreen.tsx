/**
 * Экран «Город» (#/prayer-city): выбор места для времени намаза и киблы.
 *
 * Контракт: ПропсыЭкрана<'городНамаза'>. Внутри — ВыборГорода (components/prayer/CityPicker.tsx):
 * единый поиск по местам КЗ и УЗ и по всему миру (без выбора страны — владелец 20.11.2026), крупные города КЗ и УЗ
 * сразу, все их места по странам и областям, «Определить по геолокации» с пояснением (координаты остаются на телефоне). После выбора — назад() (на главную или к времени намаза).
 * testID: экран-город (+ testID ВыбораГорода).
 */
import { Экран } from '../components';
import { ВыборГорода } from '../components/prayer';
import { useНавигация } from '../engine/navigation';
import type { ПропсыЭкрана } from '../engine/routes';
import { создатьСловарь, useСловарь } from '../i18n';

const СЛОВАРЬ = создатьСловарь({
  ru: { заголовок: 'Город' },
  kk: { заголовок: 'Қала' },
  uz: { заголовок: 'Shahar' },
  en: { заголовок: 'City' },
});

export function ГородНамаза(_: ПропсыЭкрана<'городНамаза'>) {
  const т = useСловарь(СЛОВАРЬ);
  const { назад } = useНавигация();
  return (
    <Экран заголовок={т('заголовок')} testID="экран-город">
      <ВыборГорода приВыборе={() => назад()} />
    </Экран>
  );
}
