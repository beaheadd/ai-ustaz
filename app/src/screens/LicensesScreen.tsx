/** Домен в начале строки ссылки источника: 'tanzil.net', 'github.com/aliftype/amiri — …'. */
const ДОМЕН = /^(?:https?:\/\/)?([a-z0-9-]+(?:\.[a-z0-9-]+)*\.[a-z]{2,}(?:\/[^\s]*)?)/i;

/**
 * Ссылка источника: адрес в начале строки — ссылка (на вебе <a target="_blank" rel="noopener noreferrer">),
 * остальное — текст. Переход только по нажатию человека; https:// добавляется здесь, а не в данных.
 */
function Ссылка({ строка, testID }: { строка: string; testID?: string }) {
  const { цвет } = useТема();
  const н = ДОМЕН.exec(строка);
  if (!н) return <Текст вид="мелкий" testID={testID}>{строка}</Текст>;
  const адрес = 'https://' + н[1];
  const веб = Platform.OS === 'web' ? ({ href: адрес, hrefAttrs: { target: '_blank', rel: 'noopener noreferrer' } } as object) : {};
  return (
    <Текст вид="мелкий" testID={testID}>
      <Text {...веб} selectable style={{ color: цвет.акцент, textDecorationLine: 'underline' }}>
        {н[1]}
      </Text>
      {строка.slice(н[0].length)}
    </Текст>
  );
}

function КарточкаИсточника({ и }: { и: ИсточникКонтента }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const [условия, установитьУсловия] = useState(false);
  return (
    <Карточка testID={'источник-' + и.id}>
      <Текст вид="подзаголовок">{и.название}</Текст>
      {и.что ? (
        <Текст вид="второй">
          {т('что')}: {и.что}
        </Текст>
      ) : null}
      {и.лицензия ? (
        <Текст>
          {т('лицензия')}: {и.лицензия}
        </Текст>
      ) : null}
      {и.лицензияСсылка ? <Ссылка строка={и.лицензияСсылка} testID={'источник-' + и.id + '-лицензия'} /> : null}
      {и.атрибуция ? (
        <Текст вид="мелкий" selectable>
          {т('атрибуция')}: {и.атрибуция}
        </Текст>
      ) : null}
      {и.ссылка ? <Ссылка строка={и.ссылка} /> : null}
      {и.прочитано ? <Текст вид="мелкий">{т('прочитано', { дата: и.прочитано })}</Текст> : null}
      {и.примечание ? (
        <Текст вид="мелкий">
          {т('примечание')}: {и.примечание}
        </Текст>
      ) : null}
      {и.условия ? (
        <View style={{ gap: отступ.xs }}>
          <Text
            accessibilityRole="button"
            accessibilityState={{ expanded: условия }}
            onPress={() => установитьУсловия((у) => !у)}
            testID={'источник-' + и.id + '-условия'}
            style={{ color: цвет.акцент, fontWeight: '600', paddingVertical: 6 }}
          >
            {(условия ? т('скрытьУсловия') : т('показатьУсловия')) + (условия ? ' ▾' : ' ▸')}
          </Text>
          {условия ? (
            <View style={{ backgroundColor: цвет.фон, borderRadius: радиус.s, padding: отступ.s }}>
              <Текст вид="мелкий">{т('условия')}</Текст>
              <Text selectable style={{ fontFamily: Platform.OS === 'web' ? 'monospace' : undefined, fontSize: 11, lineHeight: 15, color: цвет.текст }}>
                {и.условия}
              </Text>
            </View>
          ) : null}
        </View>
      ) : null}
    </Карточка>
  );
}

export function Лицензии(_: ПропсыЭкрана<'лицензии'>) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const источники = useДанные('sources');
  const [прямые, установитьПрямые] = useState<ПрямаяЗависимость[] | null>(null);
  const [список, установитьСписок] = useState<ЛицензияПакета[] | null>(null);
  const [открыт, установитьОткрыт] = useState<string | null>(null);

  useEffect(() => {
    let живой = true;
    import('../content/licenses.generated.json').then((модуль) => {
      if (живой) установитьПрямые((модуль.default ?? модуль) as unknown as ПрямаяЗависимость[]);
    });
    import('../legal/licenses.json').then((модуль) => {
      if (живой) установитьСписок((модуль.default ?? модуль) as unknown as ЛицензияПакета[]);
    });
    return () => {
      живой = false;
    };
  }, []);

  return (
    <Экран заголовок={t('экран.лицензии')} testID="экран-лицензии">
      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('источники')}
        </Текст>
        <Текст вид="второй">{т('источникиПояснение')}</Текст>
      </View>
      {источники.состояние === 'загрузка' ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {источники.состояние === 'нет' ? <Текст вид="второй">{т('нетИсточников')}</Текст> : null}
      {источники.состояние === 'есть' ? источники.данные.источники.map((и) => <КарточкаИсточника key={и.id} и={и} />) : null}

      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('зависимости')}
        </Текст>
        <Текст вид="второй">{т('зависимостиПояснение')}</Текст>
      </View>
      {прямые == null ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {прямые != null ? (
        <Карточка>
          {прямые.map((з) => (
            <View key={з.пакет} testID={'зависимость-' + з.пакет} style={{ paddingVertical: 4 }}>
              <Текст стиль={{ fontWeight: '600' }}>{з.пакет}</Текст>
              <Текст вид="мелкий">
                {з.версия} · {з.лицензия} · {т(`вид.${з.вид}`)}
              </Текст>
            </View>
          ))}
        </Карточка>
      ) : null}

      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('бандл')}
        </Текст>
        <Текст вид="второй">{т('бандлПояснение')}</Текст>
      </View>
      {список == null ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {(список ?? []).map((п) => {
        const ключ = п.пакет + '@' + п.версия;
        return (
          <Карточка key={ключ} приНажатии={() => установитьОткрыт(открыт === ключ ? null : ключ)} testID={'лицензия-' + п.пакет}>
            <Текст стиль={{ fontWeight: '600' }}>{п.пакет}</Текст>
            <Текст вид="мелкий">
              {п.версия} · {п.лицензия}
            </Текст>
            {открыт === ключ ? (
              п.тексты.length > 0 ? (
                п.тексты.map((тк) => (
                  <Текст key={тк.файл} вид="мелкий" selectable>
                    {тк.текст}
                  </Текст>
                ))
              ) : (
                <Текст вид="мелкий">{т('нетТекста')}</Текст>
              )
            ) : null}
          </Карточка>
        );
      })}
    </Экран>
  );
}
