/**
 * Лицензии: сторонние пакеты, которые реально попали в веб-бандл, и шрифт Amiri Quran (OFL-1.1).
 * Список — src/legal/licenses.json, его пишет scripts/gen-licenses.mjs (по source map экспорта).
 * Тексты грузятся отдельным файлом только при открытии экрана (import() → свой чанк с хэшем).
 * ЗАГЛУШКА каркаса (рабочая) — можно заменить. Контракт: ПропсыЭкрана<'лицензии'>.
 */
import { useEffect, useState } from 'react';
import { Карточка, Текст, Экран } from '../components';
import type { ПропсыЭкрана } from '../engine/routes';
import { useПеревод } from '../i18n';

export type ЛицензияПакета = {
  пакет: string;
  версия: string;
  лицензия: string;
  тексты: { файл: string; текст: string }[];
};

export function Лицензии(_: ПропсыЭкрана<'лицензии'>) {
  const { t } = useПеревод();
  const [список, установитьСписок] = useState<ЛицензияПакета[] | null>(null);
  const [открыт, установитьОткрыт] = useState<string | null>(null);

  useEffect(() => {
    let живой = true;
    import('../legal/licenses.json').then((модуль) => {
      if (живой) установитьСписок((модуль.default ?? модуль) as unknown as ЛицензияПакета[]);
    });
    return () => {
      живой = false;
    };
  }, []);

  return (
    <Экран заголовок={t('экран.лицензии')} testID="экран-лицензии">
      {список == null ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {(список ?? []).map((п) => {
        const ключ = п.пакет + '@' + п.версия;
        return (
          <Карточка key={ключ} приНажатии={() => установитьОткрыт(открыт === ключ ? null : ключ)} testID={'лицензия-' + п.пакет}>
            <Текст вид="подзаголовок">{п.пакет}</Текст>
            <Текст вид="мелкий">
              {п.версия} · {п.лицензия}
            </Текст>
            {открыт === ключ
              ? п.тексты.map((т) => (
                  <Текст key={т.файл} вид="мелкий" selectable>
                    {т.текст}
                  </Текст>
                ))
              : null}
          </Карточка>
        );
      })}
    </Экран>
  );
}
