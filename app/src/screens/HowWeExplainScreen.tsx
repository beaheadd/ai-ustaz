export function КакОбъясняем(_: ПропсыЭкрана<'какОбъясняем'>) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const демо = useДанные('fatiha-demo');
  return (
    <Экран заголовок={т('заголовок')} плашка="урок" testID="экран-как">
      {демо.состояние === 'есть' ? (
        <Разбор демо={демо.данные} />
      ) : (
        <Текст вид="второй">{демо.состояние === 'загрузка' ? t('общее.загрузка') : т('нетДанных')}</Текст>
      )}
    </Экран>
  );
}

/** Прокрутить к узлу на вебе: карточка объяснения после выбора слова или примера. */
function прокрутитьК(узел: unknown) {
  if (Platform.OS !== 'web') return;
  const э = узел as HTMLElement | null;
  if (э && typeof э.scrollIntoView === 'function') э.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function Разбор({ демо }: { демо: ДемоФатихи }) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет, радиус } = useТема();
  const [выбран, установитьВыбран] = useState<string | null>(null);
  const карточка = useRef<ComponentRef<typeof View>>(null);

  /** Ключ «сура:аят» → (номер слова → id примера). */
  const подсветка = useMemo(() => {
    const к = new Map<string, Map<number, string>>();
    for (const п of демо.примеры) {
      const ключ = `${п.сура}:${п.аят}`;
      if (!к.has(ключ)) к.set(ключ, new Map());
      const слова = к.get(ключ)!;
      if (!слова.has(п.слово)) слова.set(п.слово, п.id);
    }
    return к;
  }, [демо]);

  const пример = демо.примеры.find((п) => п.id === выбран) ?? null;
  const выбрать = (id: string) => {
    установитьВыбран(id);
    setTimeout(() => прокрутитьК(карточка.current), 0);
  };

  return (
    <>
      <Карточка вид="арка" testID="как-вступление">
        <View style={{ alignItems: 'center', gap: отступ.s }}>
          <ЭмблемаУстаза размер={88} состояние="объясняю" />
          <Текст вид="подзаголовок" стиль={{ textAlign: 'center' }} accessibilityRole="header">
            {т('одно')}
          </Текст>
        </View>
        <Текст>{т('вступление')}</Текст>
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.xs }} accessibilityLabel={т('шаги')}>
          {т('шаги')
            .split(' · ')
            .map((шаг, i) => (
              <Плашка key={шаг} вид="инфо" надпись={`${i + 1} · ${шаг}`} />
            ))}
        </View>
      </Карточка>

      <View
        style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'flex-start', backgroundColor: цвет.плашкаФон, borderRadius: радиус.m, padding: отступ.m }}
        testID="как-пометка"
      >
        <Значок имя="инфо" размер={20} цвет={цвет.плашкаТекст} />
        <View style={{ flex: 1, gap: отступ.xs }}>
          <Текст цвет={цвет.плашкаТекст} стиль={{ fontWeight: '600' }}>
            {локально(демо.пометка, язык)}
          </Текст>
          {локально(демо.пометкаИИ, язык) ? (
            <Текст вид="мелкий" цвет={цвет.плашкаТекст}>
              {локально(демо.пометкаИИ, язык)}
            </Текст>
          ) : null}
        </View>
      </View>

      <Карточка testID="как-фатиха">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <Значок имя="коран" размер={22} цвет={цвет.акцент} />
          <Текст вид="подзаголовок" стиль={{ flex: 1 }}>
            {т('сура')}
          </Текст>
        </View>
        <Текст вид="мелкий">{т('подсказка')}</Текст>
        <View style={{ gap: отступ.xs }}>
          {демо.аяты.map((аят) => (
            <АятСоСловами
              key={`${аят.сура}:${аят.аят}`}
              фрагмент={аят}
              подсвеченные={подсветка.get(`${аят.сура}:${аят.аят}`) ?? new Map()}
              выбран={выбран}
              приВыборе={выбрать}
              подпись={(слово) => т('словоПодпись', { аят: аят.аят, слово })}
              testID={'как-аят-' + аят.аят}
            />
          ))}
        </View>
      </Карточка>

      <View ref={карточка}>
        {пример ? <КарточкаОбъяснения key={пример.id} пример={пример} пометка={демо.пометка} /> : null}
      </View>

      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('примеры')}
        </Текст>
        {демо.примеры.map((п) => (
          <Карточка
            key={п.id}
            приНажатии={() => выбрать(п.id)}
            testID={'как-пример-' + п.id}
            стиль={п.id === выбран ? { borderColor: цвет.акцент, borderWidth: 2 } : undefined}
          >
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
              <View style={{ flex: 1, gap: отступ.xs }}>
                <ЧипУровня пример={п} />
                <Текст вид="мелкий">{т('гдеСлово', { сура: п.сура, аят: п.аят, слово: п.слово })}</Текст>
                <СмешанныйТекст>{локально(п.правило, язык)}</СмешанныйТекст>
              </View>
              <View style={{ minWidth: 64, alignItems: 'center', paddingHorizontal: отступ.s, borderRadius: радиус.m, backgroundColor: цвет.фон }}>
                <АрабскийТекст размер="средний">{п.текстСлова}</АрабскийТекст>
              </View>
            </View>
          </Карточка>
        ))}
      </View>

      <Карточка вид="песок" testID="как-правила">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <Значок имя="инфо" размер={22} цвет={цвет.песокТекст} />
          <Текст вид="подзаголовок" цвет={цвет.песокТекст} стиль={{ flex: 1 }}>
            {т('правилаЗаголовок')}
          </Текст>
        </View>
        <Пункты пункты={[т('правила'), ...(локально(демо.пометкаУровней, язык) ? [локально(демо.пометкаУровней, язык)] : [])]} />
      </Карточка>
      <View style={{ gap: отступ.s }}>
        <Плашка вид="черновик" надпись={т('черновик')} />
        <Текст вид="мелкий">
          {т('источник', { версия: демо.версия, статус: т(`статус.${демо.статус as СтатусКонтента}`) })}
        </Текст>
      </View>
    </>
  );
}
