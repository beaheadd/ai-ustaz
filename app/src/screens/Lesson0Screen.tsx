/** Вариант ответа без оценки (маршрут, намерение): переключатель-радио, а не тест. */
function Выбор({ надпись, выбран, приНажатии, testID }: { надпись: string; выбран: boolean; приНажатии: () => void; testID: string }) {
  const { цвет, отступ, радиус, тень } = useТема();
  return (
    <Pressable
      accessibilityRole="radio"
      aria-checked={выбран}
      accessibilityLabel={надпись}
      onPress={приНажатии}
      testID={testID}
      style={({ pressed }) => [
        {
          flexDirection: 'row',
          alignItems: 'center',
          gap: отступ.m,
          minHeight: 56,
          paddingVertical: отступ.m,
          paddingHorizontal: отступ.l - (выбран ? 1 : 0),
          borderRadius: радиус.l,
          borderWidth: выбран ? 2 : 1,
          borderColor: выбран ? цвет.акцент : цвет.граница,
          backgroundColor: выбран ? цвет.поверхностьАкцент : pressed ? цвет.акцентМягкий : цвет.поверхность,
        },
        выбран ? null : тень(1),
      ]}
    >
      <View
        style={{
          width: 22,
          height: 22,
          borderRadius: радиус.круг,
          borderWidth: 2,
          borderColor: выбран ? цвет.акцент : цвет.границаЭлемента,
          alignItems: 'center',
          justifyContent: 'center',
        }}
      >
        {выбран ? <View style={{ width: 10, height: 10, borderRadius: радиус.круг, backgroundColor: цвет.акцент }} /> : null}
      </View>
      <Текст стиль={{ flex: 1, fontWeight: выбран ? '600' : '400' }}>{надпись}</Текст>
    </Pressable>
  );
}

