function ПрохождениеУрока0({ данные }: { данные: Урок0Данные }) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const { заменить } = useНавигация();
  const { изменить } = useПрогресс();
  const шаги = шагиУрока0(данные);
  const [номер, установитьНомер] = useState(0);
  const [маршрут, установитьМаршрут] = useState<string | null>(null);
  const [намерение, установитьНамерение] = useState<string | null>(null);
  const [готово, установитьГотово] = useState<Record<number, boolean>>({});
  const шаг = шаги[номер];
  const последний = номер === шаги.length - 1;

  const приГотово = useCallback(() => установитьГотово((г) => ({ ...г, [номер]: true })), [номер]);

  function завершить() {
    изменить((п) => отметитьУрок({ ...п, предупреждениеПоказано: true }, 0, { доля: 1, пройден: true }));
    const выбран = данные.маршрут.варианты.find((в) => в.id === маршрут);
    const куда: КудаВести = выбран?.куда ?? { экран: 'урок', номер: 1 };
    if (куда.экран === 'урок' && естьУрок(куда.номер)) заменить('урок', { номер: куда.номер });
    else if (куда.экран === 'какОбъясняем') заменить('какОбъясняем');
    else заменить('картаКурса');
  }

  function далее() {
    if (шаг.вид === 'предупреждение') изменить((п) => (п.предупреждениеПоказано ? п : { ...п, предупреждениеПоказано: true }));
    if (последний) завершить();
    else установитьНомер((н) => н + 1);
  }

  // «Далее» закрыт только на задании с выбором, пока на него не ответили.
  const можноДальше = шаг.вид !== 'задание' || шаг.задание.тип !== 'выбор' || готово[номер] === true;
  const надпись = шаг.вид === 'предупреждение' ? т('понятно') : последний ? т('завершить') : т('далее');

  return (
    <Экран
      key={номер}
      заголовок={t('экран.урок0')}
      плашка="урок"
      testID="экран-урок0"
      низ={<Кнопка надпись={надпись} крупная отключена={!можноДальше} приНажатии={далее} testID="урок0-далее" />}
    >
      <ПрогрессУрока текущий={номер + 1} всего={шаги.length} />

      {шаг.вид === 'предупреждение' ? (
        <View style={{ gap: отступ.l }} testID="урок0-шаг-предупреждение">
          <Текст вид="заголовок">{локально(данные.название, язык)}</Текст>
          <Текст>{т('предупреждениеВступление')}</Текст>
          <КарточкаПредупрежденияИИ предупреждение={данные.предупреждениеИИ} />
          <Текст вид="мелкий">
            {т('версия', { версия: данные.версия, статус: т(`статус.${данные.статус as СтатусКонтента}`) })}
          </Текст>
        </View>
      ) : null}

      {шаг.вид === 'маршрут' ? (
        <View style={{ gap: отступ.m }} testID="урок0-шаг-маршрут">
          <Текст вид="подзаголовок" accessibilityRole="header">
            {локально(данные.маршрут.вопрос, язык)}
          </Текст>
          <Текст вид="второй">{т('маршрутПояснение')}</Текст>
          <View accessibilityRole="radiogroup" style={{ gap: отступ.s }}>
            {данные.маршрут.варианты.map((в) => (
              <Выбор
                key={в.id}
                надпись={локально(в.текст, язык)}
                выбран={маршрут === в.id}
                приНажатии={() => установитьМаршрут(в.id)}
                testID={'урок0-маршрут-' + в.id}
              />
            ))}
          </View>
          {(() => {
            const выбран = данные.маршрут.варианты.find((в) => в.id === маршрут);
            return выбран?.примечание ? (
              <Карточка акцент testID="урок0-маршрут-примечание">
                <Текст>{локально(выбран.примечание, язык)}</Текст>
              </Карточка>
            ) : null;
          })()}
        </View>
      ) : null}

      {шаг.вид === 'намерение' ? (
        <View style={{ gap: отступ.m }} testID="урок0-шаг-намерение">
          <Текст вид="подзаголовок" accessibilityRole="header">
            {локально(данные.намерение.вопрос, язык)}
          </Текст>
          <Текст вид="второй">{т('намерениеПояснение')}</Текст>
          <View accessibilityRole="radiogroup" style={{ gap: отступ.s }}>
            {данные.намерение.варианты.map((в) => (
              <Выбор
                key={в.id}
                надпись={локально(в.текст, язык)}
                выбран={намерение === в.id}
                приНажатии={() => установитьНамерение(в.id)}
                testID={'урок0-намерение-' + в.id}
              />
            ))}
          </View>
        </View>
      ) : null}

      {шаг.вид === 'задание' ? (
        <View testID={'урок0-шаг-задание-' + (шаг.индекс + 1)}>
          <ЗаданиеУрока0 задание={шаг.задание} приГотово={приГотово} />
        </View>
      ) : null}

      {номер > 0 ? (
        <Кнопка надпись={т('назадШаг')} вид="тихая" растянуть={false} приНажатии={() => установитьНомер((н) => н - 1)} testID="урок0-шаг-назад" />
      ) : null}
    </Экран>
  );
}

/** Вариант ответа без оценки (маршрут, намерение): переключатель, а не тест. */
function Выбор({ надпись, выбран, приНажатии, testID }: { надпись: string; выбран: boolean; приНажатии: () => void; testID: string }) {
  const { цвет } = useТема();
  return (
    <Карточка приНажатии={приНажатии} testID={testID} стиль={выбран ? { borderColor: цвет.акцент, borderWidth: 2, backgroundColor: цвет.поверхностьАкцент } : null}>
      <View accessibilityRole="radio" accessibilityState={{ checked: выбран }} style={{ flexDirection: 'row', alignItems: 'center', gap: 10 }}>
        <Текст стиль={{ color: выбран ? цвет.акцент : цвет.текстВторой }}>{выбран ? '◉' : '○'}</Текст>
        <Текст стиль={{ flex: 1, fontWeight: выбран ? '600' : '400' }}>{надпись}</Текст>
      </View>
    </Карточка>
  );
}

function ЗаданиеУрока0({ задание, приГотово }: { задание: Задание; приГотово: () => void }) {
  if (задание.тип === 'теория') return <ТеорияУрока0 задание={задание} />;
  if (задание.тип === 'запись' && 'учебный' in задание.читать) return <ПерваяЗапись задание={задание} учебный={задание.читать.учебный} />;
  return <Упражнение задание={задание} приГотово={приГотово} />;
}

