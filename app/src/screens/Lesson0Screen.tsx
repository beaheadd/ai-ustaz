type Шаг = { вид: 'предупреждение' } | { вид: 'маршрут' } | { вид: 'намерение' } | { вид: 'задание'; задание: Задание; индекс: number };

export function шагиУрока0(данные: Урок0Данные): Шаг[] {
  const шаги: Шаг[] = [{ вид: 'предупреждение' }];
  if (данные.маршрут.варианты.length > 0) шаги.push({ вид: 'маршрут' });
  if (данные.намерение.варианты.length > 0) шаги.push({ вид: 'намерение' });
  данные.задания.forEach((задание, индекс) => шаги.push({ вид: 'задание', задание, индекс }));
  return шаги;
}

