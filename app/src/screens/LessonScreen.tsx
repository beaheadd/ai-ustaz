type Загрузка = { состояние: 'загрузка' } | { состояние: 'нет' } | { состояние: 'есть'; урок: ДанныеУрока };

export function Урок({ параметры }: ПропсыЭкрана<'урок'>) {
  const { номер } = параметры;
  const [загрузка, установитьЗагрузку] = useState<Загрузка>({ состояние: 'загрузка' });

  useEffect(() => {
    let живой = true;
    загрузитьУрок(номер).then((урок) => {
      if (живой) установитьЗагрузку(урок ? { состояние: 'есть', урок } : { состояние: 'нет' });
    });
    return () => {
      живой = false;
    };
  }, [номер]);

  if (загрузка.состояние === 'есть') return <ПрохождениеУрока урок={загрузка.урок} />;
  return <УрокНеГотов номер={номер} загрузка={загрузка.состояние === 'загрузка'} />;
}

