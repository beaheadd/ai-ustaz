/** 4288 → '4 288' (неразрывный пробел). */
const тысячи = (ч: number) => String(Math.round(ч)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
/** 10.1 → '+10,1' (ru и kk — десятичная запятая). */
const соЗнаком = (ч: number) => (ч >= 0 ? '+' : '−') + Math.abs(ч).toFixed(1).replace('.', ',');

/** Текущее время с обновлением на границе минуты (не каждую секунду). */
function useСейчас(): Date {
  const [сейчас, установить] = useState(() => new Date());
  useEffect(() => {
    let таймер: ReturnType<typeof setTimeout>;
    const ждать = () => {
      таймер = setTimeout(() => {
        установить(new Date());
        ждать();
      }, 60_000 - (Date.now() % 60_000) + 50);
    };
    ждать();
    return () => clearTimeout(таймер);
  }, []);
  return сейчас;
}

