/** Раскрывающийся блок: строка-кнопка (aria-expanded) и под ней весь текст. */
function Раскрывашка({ заголовок, testID, children }: { заголовок: string; testID: string; children: ReactNode }) {
  const [открыт, установить] = useState(false);
  const { отступ } = useТема();
  return (
    <View style={{ gap: отступ.s }}>
      <СтрокаСписка заголовок={заголовок} раскрыт={открыт} приНажатии={() => установить((о) => !о)} testID={testID} />
      {открыт ? (
        <View style={{ gap: отступ.s }} testID={testID + '-текст'}>
          {children}
        </View>
      ) : null}
    </View>
  );
}

/** Текст как есть, одним абзацем: переводы строк сохраняются (react-native-web: white-space pre-wrap). */
function Абзацы({ текст }: { текст: string }) {
  return (
    <Текст selectable testID="хадис-разъяснение-абзац">
      {текст}
    </Текст>
  );
}

export function Хадис({ параметры }: ПропсыЭкрана<'хадис'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тх = useСловарь(СЛОВАРЬ_ХАДИСОВ);
  const { перейти, перейтиВкладку } = useНавигация();
  const { цвет, отступ } = useТема();
  const х = useХадис(параметры.номер, язык);
  const д = х.состояние === 'есть' ? х.данные : null;

  return (
    <Экран заголовок={д ? т('номер', { n: д.запись.n }) : т('хадис')} testID="экран-хадис">
      {х.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="хадис-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : х.состояние === 'нет' ? (
        <ХадисыНедоступны состояние={х} />
      ) : !д ? (
        <View style={{ gap: отступ.s }}>
          <Текст вид="второй" testID="хадис-нет">
            {т('нет')}
          </Текст>
          <Кнопка вид="вторичная" надпись={т('кРазделам')} приНажатии={() => перейтиВкладку('хадисы')} testID="хадис-к-разделам" />
        </View>
      ) : (
        <View style={{ gap: отступ.m }}>
          <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', gap: отступ.s }}>
            <Текст вид="мелкий" табличные testID="хадис-номер">
              {т('hadeethenc', { id: д.запись.id })}
            </Текст>
            {д.одобрено ? (
              <Плашка вид="успех" надпись={т('одобрено', { кто: д.одобрено.кто, когда: д.одобрено.когда })} testID="хадис-одобрено" />
            ) : (
              <Плашка вид="черновик" надпись={тх('черновик')} testID="хадис-черновик" />
            )}
          </View>
          {д.запасной ? (
            <Текст вид="второй" testID="хадис-нет-перевода">
              {тх('запасной')}
            </Текст>
          ) : null}

          <Карточка>
            <Текст вид="подзаголовок" accessibilityRole="header" уровень={2} selectable testID="хадис-заголовок">
              {д.перевод.title}
            </Текст>
            <АрабскийАбзац текст={арабскийТекст(д.ar, д.перевод)} testID="хадис-арабский" />
            <View style={{ height: 1, backgroundColor: цвет.граница }} />
            <Текст selectable testID="хадис-перевод">
              {д.перевод.hadeeth}
            </Текст>
            {д.языкПеревода === 'uz' ? (
              <Текст вид="мелкий" testID="хадис-кириллица">
                {т('кириллица')}
              </Текст>
            ) : null}
          </Карточка>

          <View style={{ gap: отступ.xs }}>
            <Текст стиль={{ fontWeight: '600' }} selectable testID="хадис-степень">
              {т('степень', { степень: д.перевод.grade })}
            </Текст>
            <Текст selectable testID="хадис-такхридж">
              {д.перевод.attribution}
            </Текст>
          </View>

          <Раскрывашка заголовок={т('разъяснение')} testID="хадис-разъяснение">
            <Абзацы текст={д.перевод.explanation} />
          </Раскрывашка>
          {д.перевод.hints.length ? (
            <Раскрывашка заголовок={т('польза')} testID="хадис-польза">
              {д.перевод.hints.map((п, i) => (
                <View key={i} style={{ flexDirection: 'row', gap: отступ.s }}>
                  <Текст цвет={цвет.акцент}>•</Текст>
                  <Текст selectable стиль={{ flex: 1 }}>
                    {п}
                  </Текст>
                </View>
              ))}
            </Раскрывашка>
          ) : null}
          {д.ar.words_meanings && д.ar.words_meanings.length ? (
            <Раскрывашка заголовок={т('слова')} testID="хадис-слова">
              {д.ar.words_meanings.map((с, i) => (
                <View key={i} style={{ gap: 2 }}>
                  <АрабскийАбзац текст={с.word} мелкий />
                  <АрабскийАбзац текст={с.meaning} мелкий />
                </View>
              ))}
            </Раскрывашка>
          ) : null}
          {д.ar.reference ? (
            <Раскрывашка заголовок={т('ссылки')} testID="хадис-ссылки">
              <АрабскийАбзац текст={д.ar.reference} мелкий />
            </Раскрывашка>
          ) : null}

          <Текст вид="мелкий" testID="хадис-фикх">
            {т('фикх')}
          </Текст>
          <СсылкаHadeethEnc адрес={д.перевод.link} надпись={т('источник')} testID="хадис-источник" />
          <Текст вид="мелкий" testID="хадис-как-есть">
            {т('какЕсть')}
          </Текст>
          {д.запись.категории.length ? (
            <View style={{ gap: отступ.s }}>
              <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
                {т('разделы')}
              </Текст>
              {д.запись.категории.map((id) => {
                const к = категория(д.индекс, id);
                return к ? (
                  <СтрокаСписка
                    key={id}
                    заголовок={названиеКатегории(к, язык)}
                    значок="хадис"
                    приНажатии={() => перейти('разделХадисов', { номер: id })}
                    testID={'хадис-раздел-' + id}
                  />
                ) : null;
              })}
            </View>
          ) : null}
        </View>
      )}
    </Экран>
  );
}
