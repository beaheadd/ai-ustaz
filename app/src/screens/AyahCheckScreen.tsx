export function ПроверкаАята({ параметры }: ПропсыЭкрана<'проверкаАята'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const { заменить, обновитьПараметры, перейти, стек, назад } = useНавигация();
  const { номер: н, аят: а, часть } = параметры;
  const сура = useСура(н);
  const индекс = useИндексСур();
  const запись = индекс.состояние === 'есть' ? (индекс.данные.суры[н - 1] ?? null) : null;
  const название = названиеСуры(запись, н, язык);
  const естьТранслит = !!запись?.транслит[язык];
  const [проверкаВключена] = useState(проверкаГолосомВключена);

  /** «Вся сура»: если под нами эта сура — назад к ней, иначе — открыть её у этого аята. */
  function кСуре() {
    const под = стек[стек.length - 2];
    if (под?.экран === 'сура' && под.параметры.номер === н) назад();
    else перейти('сура', { номер: н, аят: а });
  }

  return (
    <Экран заголовок={т('заголовок', { сура: н, аят: а })} плашка="общая" testID="экран-проверка-аята">
      {сура.состояние === 'загрузка' ? (
        <Текст вид="второй">{t('общее.загрузка')}</Текст>
      ) : сура.состояние === 'нет' ? (
        <ТекстКоранаНедоступен состояние={сура} />
      ) : а > сура.данные.аятов ? (
        <View style={{ gap: отступ.m }}>
          <Текст вид="второй" testID="проверка-нет-аята">
            {т('нетАята', { аятов: словоАятов(сура.данные.аятов, язык), аят: а })}
          </Текст>
          <СтрокаСписка заголовок={т('кСуре')} подпись={название} значок="коран" приНажатии={кСуре} testID="проверка-к-суре" />
        </View>
      ) : (
        <>
          <View style={{ gap: отступ.xs }}>
            <Текст вид="подзаголовок" accessibilityRole="header" уровень={2} testID="проверка-сура">
              {т('где', { сура: название, аят: а, аятов: сура.данные.аятов })}
            </Текст>
            <Текст вид="второй">{т(проверкаВключена ? 'пояснениеПроверка' : 'пояснение')}</Текст>
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s, flexWrap: 'wrap', justifyContent: 'space-between' }}>
              {естьТранслит ? <Плашка вид="черновик" надпись={т('черновикНазвания')} малая testID="проверка-черновик-названия" /> : <View />}
              <РазмерАрабского вид="кнопки" />
            </View>
          </View>
          <ПанельЧтенияАята
            key={`${н}:${а}`}
            сура={н}
            аят={а}
            текст={сура.данные.аяты[а - 1].текст}
            бисмиллаПеред={сура.данные.бисмилла != null}
            часть={часть ?? 1}
            приСменеЧасти={(п) => обновитьПараметры('проверкаАята', { номер: н, аят: а, часть: п })}
          />
          <View style={{ flexDirection: 'row', gap: отступ.s, flexWrap: 'wrap' }}>
            <Кнопка
              вид="вторичная"
              значок="назад"
              растянуть={false}
              надпись={т('пред')}
              отключена={а <= 1}
              приНажатии={() => заменить('проверкаАята', { номер: н, аят: а - 1 })}
              testID="проверка-пред"
            />
            <Кнопка
              вид="вторичная"
              значок="вперёд"
              растянуть={false}
              надпись={т('след')}
              отключена={а >= сура.данные.аятов}
              приНажатии={() => заменить('проверкаАята', { номер: н, аят: а + 1 })}
              testID="проверка-след"
            />
          </View>
          <СтрокаСписка заголовок={т('кСуре')} подпись={название} значок="коран" приНажатии={кСуре} testID="проверка-к-суре" />
          <Плашка вид="черновик" надпись={т('черновик')} testID="проверка-черновик" />
        </>
      )}
    </Экран>
  );
}
