/**
 * «Прочитать и записать» любой аят (#/quran/check?n=2&a=255&p=1): аят целиком, часть для записи, запись голоса,
 * «Послушать себя», «Сравнить с кари» (если источник разрешён), «Проверить» (только сборка своего домена).
 *
 * Решение владельца 19.11.2026: «Чтобы Коран мог читать и проверить, как он читает … заходишь и читаешь любой аят,
 * и записываешь голос и проверяешь, где ошибки». Поток и правила — docs/дизайн/05 §2.4; панель — <ПанельЧтенияАята>
 * (components/quran/RecitePanel.tsx): текст аята она получает ДОСЛОВНО из копии для показа и не режет (правила 1, 8),
 * подсказки — только «Проверьте себя»/«Подсказка» (правило 7), проверка — только свой домен (QML; на batr.kz её нет).
 *
 * Контракт: ПропсыЭкрана<'проверкаАята'> = { номер; аят; часть? }. Вкладка «Коран», меню видно (запись — встроенная
 * панель, без закреплённого низа). Смена части — обновитьПараметры (p в адресе, экран не перемонтируется; запись части
 * стирается панелью). «Предыдущий/Следующий аят» — заменить (новая запись стирается вместе с экраном).
 * Аят больше числа аятов суры — «такого аята нет» и ссылка на суру. Без сети — «Нет связи» и «Повторить».
 * Приватность: запись только в памяти страницы, уход с экрана её стирает (navigation: рисуется только верхний экран).
 * Заголовок — «Аят 2:255» (без арабского текста). Пояснения и деление на части — черновик (плашка, правило 11);
 * название суры по-русски — транслитерация, черновик (плашка «проверка-черновик-названия»). Пояснение о записи —
 * по флагу проверки: на своём домене «…остаётся на устройстве, пока вы не нажмёте „Проверить“» (ревью 19.11.2026),
 * иначе «Запись слышите только вы». Размер арабского текста — А− / А+ (quran/fontSize.ts).
 * testID: экран-проверка-аята, проверка-сура, проверка-пред, проверка-след, проверка-к-суре, проверка-нет-аята,
 *   проверка-черновик; панель — testID <ПанельЧтенияАята> (панель-чтения-аята, аят-с-частью, часть-*, панель-записи…).
 * kk — черновик для редактора-носителя.
 */
