const ДНЕЙ = 8;

export function ВремяНамаза(_: ПропсыЭкрана<'намаз'>) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { отступ } = useТема();
  const { место } = useМестоНамаза();
  const сейчас = useСейчас();

  const продолжитьУрок = () => {
    const шаг = следующийШаг(прогресс, номераУроков());
    if (шаг.вид === 'урок0') перейти('урок0');
    else if (шаг.вид === 'урок') перейти('урок', { номер: шаг.номер });
    else перейти('картаКурса');
  };

  const число = (х: number) => х.toFixed(2).replace('.', ',');

  return (
    <Экран заголовок={т('заголовок')} плашка="общая" testID="экран-намаз">
      <КарточкаНамаза перейтиККибле={() => перейти('кибла')} />

      <ПриглашениеПослеНамаза продолжить={продолжитьУрок} видКнопки="основная" />

      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('неделя')}
        </Текст>
        <ТаблицаНедели место={место} сегодня={деньРК(сейчас)} подписьСегодня={т('сегодня')} />
        <Текст вид="мелкий">{т('пояс')}</Текст>
      </View>

      <Карточка вид="акцент" заголовок={т('метод')} testID="намаз-метод">
        <Плашка вид="черновик" надпись={т('черновик')} testID="намаз-метод-черновик" />
        <Текст>{т('метод1')}</Текст>
        <Текст>{т('метод2')}</Текст>
        <Текст>{т('метод3')}</Текст>
        {оговоркаТочности(место) ? <Текст>{т('оговорка')}</Текст> : null}
        <Текст вид="второй" testID="намаз-место">
          {т('место', { место: место[язык], широта: число(место.широта), долгота: число(место.долгота) })}
        </Текст>
        <Текст вид="второй">{т('источники')}</Текст>
      </Карточка>

      <СтрокаСписка заголовок={т('лицензии')} значок="инфо" приНажатии={() => перейти('лицензии')} testID="намаз-лицензии" />
    </Экран>
  );
}

/**
 * Сегодня и ещё 7 дней: строка — день, столбцы — шесть времён по порядку дня. Влезает в 328 px без прокрутки:
 * день — две строки (день недели и число), в шапке — значок и название, время — 13 px с табличными цифрами.
 */
function ТаблицаНедели({ место, сегодня, подписьСегодня }: { место: Место; сегодня: string; подписьСегодня: string }) {
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const { широта, долгота } = место;
  const дни = useMemo(() => {
    const итог: ВременаДня[] = [];
    for (let i = 0; i < ДНЕЙ; i++) {
      try {
        итог.push(временаДня({ широта, долгота }, сдвигДня(сегодня, i)));
      } catch {
        // вне РК не бывает: место проверено при выборе
      }
    }
    return итог;
  }, [широта, долгота, сегодня]);

  const заголовокСтолбца = (к: КлючВремени) => (язык === 'kk' && к === 'sunrise' ? 'Күн' : НАЗВАНИЯ[к][язык]);
  // Ширина столбца — по длине названия (≥ 4,5 знака под «12:05»): «Магриб», «Құптан» не обрезаются на 360 px.
  const вес = (к: КлючВремени) => Math.max(4.5, заголовокСтолбца(к).length);
  const ячейка = (к: КлючВремени) => ({ flex: вес(к), minWidth: 0, alignItems: 'center' as const, justifyContent: 'center' as const, paddingVertical: отступ.s });
  const деньСтолбец = { width: 36, paddingLeft: отступ.s, justifyContent: 'center' as const, paddingVertical: отступ.s };

  return (
    <View
      testID="намаз-неделя"
      style={{ borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность, overflow: 'hidden' }}
    >
      <View style={{ flexDirection: 'row', backgroundColor: цвет.поверхностьВторая, paddingRight: 2 }}>
        <View style={деньСтолбец} />
        {КЛЮЧИ_ВРЕМЁН.map((к) => (
          <View key={к} style={[ячейка(к), { gap: 2 }]}>
            <Значок имя={ЗНАЧКИ_НАМАЗА[к]} размер={16} цвет={к === 'sunrise' ? цвет.текстВторой : цвет.акцент} />
            <Текст вид="мелкий" цвет={к === 'sunrise' ? цвет.текстВторой : цвет.текст} numberOfLines={1}>
              {заголовокСтолбца(к)}
            </Текст>
          </View>
        ))}
      </View>
      {дни.map((в) => {
        const этоСегодня = в.день === сегодня;
        const к = короткийДень(в.день, язык);
        return (
          <View
            key={в.день}
            testID={'неделя-' + в.день}
            accessible
            accessibilityLabel={[`${этоСегодня ? подписьСегодня + ', ' : ''}${к.деньНедели} ${к.дата}`, ...КЛЮЧИ_ВРЕМЁН.map((кл) => `${НАЗВАНИЯ[кл][язык]} ${чч_мм(в[кл])}`)].join(', ')}
            style={{
              flexDirection: 'row',
              paddingRight: 2,
              borderTopWidth: 1,
              borderTopColor: цвет.граница,
              backgroundColor: этоСегодня ? цвет.акцентМягкий : 'transparent',
            }}
          >
            <View style={деньСтолбец}>
              <Текст вид="метка" цвет={этоСегодня ? цвет.акцент : цвет.текст}>
                {к.деньНедели}
              </Текст>
              <Текст вид="мелкий" табличные>
                {к.число}
              </Текст>
            </View>
            {КЛЮЧИ_ВРЕМЁН.map((кл) => (
              <View key={кл} style={ячейка(кл)}>
                <Текст вид="мелкий" табличные цвет={кл === 'sunrise' ? цвет.текстВторой : цвет.текст} testID={`неделя-${в.день}-${кл}`}>
                  {чч_мм(в[кл])}
                </Текст>
              </View>
            ))}
          </View>
        );
      })}
    </View>
  );
}
