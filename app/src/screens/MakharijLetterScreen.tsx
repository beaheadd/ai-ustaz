/** Кнопка-значок 48×48 (‹ ›): подпись — для диктора (как в счётчике зикра). */
function КнопкаЗначок({ значок, подпись, приНажатии, отключена, testID }: { значок: 'назад' | 'вперёд'; подпись: string; приНажатии: () => void; отключена: boolean; testID: string }) {
  const { цвет } = useТема();
  return (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={подпись}
      accessibilityState={{ disabled: отключена }}
      disabled={отключена}
      onPress={приНажатии}
      testID={testID}
      hitSlop={4}
      style={({ pressed }) => ({ width: 48, height: 48, borderRadius: 24, alignItems: 'center', justifyContent: 'center', opacity: отключена ? 0.35 : 1, backgroundColor: pressed ? цвет.акцентМягкий : 'transparent' })}
    >
      <Значок имя={значок} размер={24} цвет={цвет.акцент} />
    </Pressable>
  );
}

function Раздел({ запись, индекс, язык, testID, заголовок }: { запись: ЗаписьБуквы; индекс: ИндексМахраджей; язык: Язык; testID: string; заголовок?: string }) {
  const т = useСловарь(СЛОВАРЬ);
  const тм = useСловарь(СЛОВАРЬ_МАХРАДЖЕЙ);
  const { цвет, отступ } = useТема();
  const м = индекс.махраджи.find((х) => х.id === запись.махрадж);
  if (!м) return null;
  const выделено = описаниеПодсветки(м, язык, тм);
  return (
    <View testID={testID} style={{ gap: отступ.s }}>
      {заголовок ? <Текст вид="подзаголовок">{заголовок}</Текст> : null}
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', gap: отступ.s }}>
        <Текст вид="второй">{т('проба')}</Текст>
        <АрабскийМахраджа текст={запись.проба} размер={30} testID={testID === 'буква-основа' ? 'буква-проба' : undefined} />
      </View>
      <Текст стиль={{ fontWeight: '700' }} testID={testID === 'буква-основа' ? 'буква-махрадж' : undefined}>
        {т('махрадж', { n: м.номер, название: текстМахраджа(м.название, язык) })}
      </Текст>
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', justifyContent: 'center', gap: отступ.m }}>
        <АрабскийМахраджа текст={м.арабский.название} размер={20} цвет={цвет.текстВторой} />
        {м.лакаб ? <АрабскийМахраджа текст={м.лакаб} размер={20} цвет={цвет.текстВторой} /> : null}
      </View>
      <СхемаМахраджа файл={запись.схема} подпись={текстМахраджа(м.подпись, язык)} выделено={выделено} testID={testID === 'буква-основа' ? 'буква-схема' : testID + '-схема'} />
      {запись.схемаСверху && м.подписьСверху ? (
        <View style={{ gap: отступ.xs }}>
          <Текст вид="мелкий">{т('сверху')}</Текст>
          <СхемаМахраджа
            файл={запись.схемаСверху}
            подпись={текстМахраджа(м.подписьСверху, язык)}
            выделено={выделено}
            testID={testID === 'буква-основа' ? 'буква-схема-сверху' : testID + '-схема-сверху'}
          />
        </View>
      ) : null}
      <Текст testID={testID === 'буква-основа' ? 'буква-описание' : undefined}>{текстМахраджа(м.описание, язык)}</Текст>
      {м.условие ? (
        <Текст вид="второй" testID={testID === 'буква-основа' ? 'буква-условие' : undefined}>
          {текстМахраджа(м.условие, язык)}
        </Текст>
      ) : null}
      {м.гунна ? <Текст вид="второй">{текстМахраджа(м.гунна, язык)}</Текст> : null}
      {запись.примечание ? (
        <Текст вид="второй" testID={testID === 'буква-основа' ? 'буква-примечание' : undefined}>
          {текстМахраджа(запись.примечание, язык)}
        </Текст>
      ) : null}
      {м.арабский.стих ? (
        <View testID={testID === 'буква-основа' ? 'буква-бейт' : undefined} style={{ gap: отступ.xs }}>
          <Текст вид="мелкий">{т('бейт')}</Текст>
          <АрабскийМахраджа текст={м.арабский.стих} размер={20} />
        </View>
      ) : null}
    </View>
  );
}

function Карта({ буква, индекс, язык }: { буква: БукваМахраджа; индекс: ИндексМахраджей; язык: Язык }) {
  const т = useСловарь(СЛОВАРЬ);
  const тм = useСловарь(СЛОВАРЬ_МАХРАДЖЕЙ);
  const { отступ } = useТема();
  const { перейти } = useНавигация();
  const состав = (буква.состав ?? []).map((id) => индекс.буквы.find((б) => б.id === id)).filter((б): б is БукваМахраджа => !!б);
  return (
    <Карточка testID="буква-карточка">
      <Плашка вид="черновик" надпись={тм('черновик')} testID="буква-черновик" />
      {поРусски(язык) ? (
        <Текст вид="мелкий" testID="буква-по-русски">
          {тм('поРусски')}
        </Текст>
      ) : null}
      <View style={{ alignItems: 'center', gap: отступ.xs }}>
        <АрабскийМахраджа текст={буква.знак} размер={96} testID="буква-знак" />
        <Текст вид="заголовок" testID="буква-название">
          {буква.название[язык]}
        </Текст>
      </View>
      {состав.length ? (
        <View testID="буква-состав" style={{ gap: отступ.s }}>
          <Текст вид="второй">{т('состав')}</Текст>
          <View style={{ flexDirection: 'row', gap: отступ.s, flexWrap: 'wrap' }}>
            {состав.map((б) => (
              <Кнопка key={б.id} вид="вторичная" растянуть={false} надпись={`${б.знак} — ${б.название[язык]}`} приНажатии={() => перейти('букваМахраджа', { номер: б.номер })} />
            ))}
          </View>
        </View>
      ) : null}
      <Раздел запись={буква} индекс={индекс} язык={язык} testID="буква-основа" />
      {буква.мадд ? <Раздел запись={буква.мадд} индекс={индекс} язык={язык} testID="буква-вариант-мадд" заголовок={т('мадд')} /> : null}
      {буква.лин ? <Раздел запись={буква.лин} индекс={индекс} язык={язык} testID="буква-вариант-лин" заголовок={т('лин')} /> : null}
      {буква.гунна ? <Раздел запись={буква.гунна} индекс={индекс} язык={язык} testID="буква-вариант-гунна" заголовок={т('гунна')} /> : null}
    </Карточка>
  );
}

export function БукваМахраджаЭкран({ параметры }: ПропсыЭкрана<'букваМахраджа'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  const { обновитьПараметры, перейти } = useНавигация();
  const индекс = useМахраджи();
  const номер = параметры.номер;

  if (индекс.состояние === 'загрузка') {
    return (
      <Экран заголовок={t('экран.букваМахраджа')} testID="экран-буква-махраджа">
        <Текст вид="второй" testID="буква-загрузка">
          {t('общее.загрузка')}
        </Текст>
      </Экран>
    );
  }
  if (индекс.состояние === 'нет') {
    return (
      <Экран заголовок={t('экран.букваМахраджа')} testID="экран-буква-махраджа">
        <МахраджиНедоступны состояние={индекс} />
      </Экран>
    );
  }
  const всего = индекс.данные.буквы.length;
  const буква = индекс.данные.буквы[номер - 1];
  if (!буква) {
    return (
      <Экран заголовок={t('экран.букваМахраджа')} testID="экран-буква-махраджа">
        <Текст testID="буква-нет">{т('нет')}</Текст>
        <Кнопка надпись={т('кСписку')} приНажатии={() => перейти('махраджи')} testID="буква-к-списку" />
      </Экран>
    );
  }
  return (
    <Экран заголовок={t('экран.букваМахраджа')} testID="экран-буква-махраджа">
      <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'center', gap: отступ.s }}>
        <КнопкаЗначок значок="назад" подпись={т('пред')} отключена={номер <= 1} приНажатии={() => обновитьПараметры('букваМахраджа', { номер: номер - 1 })} testID="буква-пред" />
        <Текст вид="метка" табличные testID="буква-позиция" accessibilityLabel={т('позиция', { n: номер, всего })} стиль={{ minWidth: 72, textAlign: 'center' }}>
          {`${номер} / ${всего}`}
        </Текст>
        <КнопкаЗначок значок="вперёд" подпись={т('след')} отключена={номер >= всего} приНажатии={() => обновитьПараметры('букваМахраджа', { номер: номер + 1 })} testID="буква-след" />
      </View>
      <Карта key={буква.id} буква={буква} индекс={индекс.данные} язык={язык} />
    </Экран>
  );
}
