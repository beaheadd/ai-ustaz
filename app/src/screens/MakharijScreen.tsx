/**
 * «Как произносить буквы» (#/makharij) — 17 махраджей Ибн аль-Джазари по областям (полость, горло, язык, губы, нос)
 * и буквы каждого; нажатие на букву — карточка буквы со схемой (#/makharij/letter?n=). Вход — «Таджвид» и «Ещё».
 *
 * Решения владельца: 19.11.2026 — «добавить картинку произношения каждой буквы»; 26.11.2026 — «Тот раз ты же рисовал
 * картинки произношения букв. Почему их нету в нашем приложении? Не выкатывал?». Данные — src/makharij/data.ts.
 *
 * Контракт: ПропсыЭкрана<'махраджи'>.
 * - Вступление: что это; плашка «Черновик: описания и схемы проверяет устаз» (правило 11); для uz и en — пометка,
 *   что описание пока на русском.
 * - Области (заголовок + арабское название из данных) → карточки махраджей: номер, название, арабское название;
 *   буквы — кнопки-ссылки (крупная буква + название на языке интерфейса). У хайшума — гунна ن и م (ссылки на буквы).
 * - Состояния: загрузка; нет связи — «Повторить»; не прошло сверку — ничего не показываем.
 * Без аудио и синтеза (правила 3, 7); без текста Корана.
 * testID: экран-махраджи, махраджи-вступление, махраджи-черновик, махраджи-по-русски, махраджи-загрузка,
 *   махраджи-область-<id>, махрадж-<id> (-название), махрадж-буква-<id буквы> (+ состояния из screens/makharij/common.tsx).
 */
import { Pressable, View } from 'react-native';
import { Карточка, Плашка, Значок, Текст, Экран } from '../components';
import { useНавигация } from '../engine/navigation';
import { вХэш, type ПропсыЭкрана } from '../engine/routes';
import { создатьСловарь, useПеревод, useСловарь, type Язык } from '../i18n';
import { поРусски, текстМахраджа, useМахраджи, type БукваМахраджа, type Махрадж } from '../makharij/data';
import { useТема } from '../theme';
import { АрабскийМахраджа, ВЕБ, СЛОВАРЬ_МАХРАДЖЕЙ, МахраджиНедоступны } from './makharij/common';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    вступление: 'Махрадж — место, откуда выходит звук буквы. Нажмите на букву: схема покажет, что работает и куда касается.',
    гунна: 'Гунна',
    букваПодпись: '{буква} — {название}',
  },
  kk: {
    вступление: 'Махраж — әріп дыбысы шығатын жер. Әріпті басыңыз: сызба не жұмыс істейтінін және қайда тиетінін көрсетеді.',
    гунна: 'Ғұнна',
    букваПодпись: '{буква} — {название}',
  },
  uz: {
    вступление: 'Maxraj — harf tovushi chiqadigan joy. Harfni bosing: chizma nima ishlashini va qayerga tegishini koʻrsatadi.',
    гунна: 'Gʻunna',
    букваПодпись: '{буква} — {название}',
  },
  en: {
    вступление: "A makhraj is the place a letter's sound comes from. Tap a letter: the diagram shows what moves and where it touches.",
    гунна: 'Ghunnah',
    букваПодпись: '{буква} — {название}',
  },
});

function КнопкаБуквы({ буква, язык }: { буква: БукваМахраджа; язык: Язык }) {
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { цвет, отступ, радиус } = useТема();
  const ссылка = вХэш({ экран: 'букваМахраджа', параметры: { номер: буква.номер } });
  return (
    <Pressable
      accessibilityRole="link"
      accessibilityLabel={т('букваПодпись', { буква: буква.знак, название: буква.название[язык] })}
      {...(ВЕБ ? ({ href: ссылка } as object) : null)}
      onPress={(е) => {
        const с = е as unknown as { metaKey?: boolean; ctrlKey?: boolean; shiftKey?: boolean; altKey?: boolean; preventDefault?: () => void };
        if (с.metaKey || с.ctrlKey || с.shiftKey || с.altKey) return;
        с.preventDefault?.();
        перейти('букваМахраджа', { номер: буква.номер });
      }}
      testID={'махрадж-буква-' + буква.id}
      style={({ pressed, hovered }: { pressed: boolean; hovered?: boolean }) => ({
        minWidth: 64,
        minHeight: 64,
        paddingHorizontal: отступ.s,
        paddingVertical: отступ.xs,
        borderRadius: радиус.m,
        borderWidth: 1,
        borderColor: цвет.граница,
        alignItems: 'center',
        justifyContent: 'center',
        backgroundColor: pressed ? цвет.акцентМягкий : hovered ? цвет.поверхностьВторая : цвет.поверхность,
        ...(ВЕБ ? ({ textDecorationLine: 'none' } as object) : null),
      })}
    >
      <АрабскийМахраджа текст={буква.знак} размер={28} />
      <Текст вид="мелкий" numberOfLines={1}>
        {буква.название[язык]}
      </Текст>
    </Pressable>
  );
}

function КарточкаМахраджа({ м, буквы, гунна, язык }: { м: Махрадж; буквы: БукваМахраджа[]; гунна: БукваМахраджа[]; язык: Язык }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  return (
    <View testID={'махрадж-' + м.id} style={{ gap: отступ.s, padding: отступ.m, borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность }}>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
        <View style={{ minWidth: 36, height: 36, borderRadius: радиус.m, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.акцент }}>
          <Текст вид="метка" цвет={цвет.акцентТекст} табличные>
            {String(м.номер)}
          </Текст>
        </View>
        <View style={{ flex: 1, minWidth: 0 }}>
          <Текст стиль={{ fontWeight: '700' }} testID={`махрадж-${м.id}-название`}>
            {текстМахраджа(м.название, язык)}
          </Текст>
        </View>
        <View style={{ flexShrink: 1, maxWidth: '45%' }}>
          <АрабскийМахраджа текст={м.арабский.название} размер={17} цвет={цвет.текстВторой} />
        </View>
      </View>
      {буквы.length ? (
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
          {буквы.map((б) => (
            <КнопкаБуквы key={б.id} буква={б} язык={язык} />
          ))}
        </View>
      ) : null}
      {гунна.length ? (
        <View style={{ gap: отступ.xs }}>
          <Текст вид="мелкий">{т('гунна')}</Текст>
          <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
            {гунна.map((б) => (
              <КнопкаБуквы key={б.id} буква={б} язык={язык} />
            ))}
          </View>
        </View>
      ) : null}
    </View>
  );
}

export function Махраджи(_: ПропсыЭкрана<'махраджи'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тм = useСловарь(СЛОВАРЬ_МАХРАДЖЕЙ);
  const { цвет, отступ } = useТема();
  const индекс = useМахраджи();

  return (
    <Экран заголовок={t('экран.махраджи')} testID="экран-махраджи">
      <Карточка вид="арка" testID="махраджи-вступление">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <Значок имя="таджвид" размер={24} цвет={цвет.акцент} />
          <Текст стиль={{ flex: 1 }}>{т('вступление')}</Текст>
        </View>
        <Плашка вид="черновик" надпись={тм('черновик')} testID="махраджи-черновик" />
        {поРусски(язык) ? (
          <Текст вид="мелкий" testID="махраджи-по-русски">
            {тм('поРусски')}
          </Текст>
        ) : null}
      </Карточка>

      {индекс.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="махраджи-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : индекс.состояние === 'нет' ? (
        <МахраджиНедоступны состояние={индекс} />
      ) : (
        индекс.данные.области.map((о) => {
          const махраджи = о.махраджи.map((id) => индекс.данные.махраджи.find((м) => м.id === id)).filter((м): м is Махрадж => !!м);
          return (
            <View key={о.id} testID={'махраджи-область-' + о.id} style={{ gap: отступ.s }}>
              <View style={{ flexDirection: 'row', alignItems: 'baseline', justifyContent: 'space-between', gap: отступ.s }}>
                <Текст вид="подзаголовок" {...(ВЕБ ? ({ role: 'heading', 'aria-level': 2 } as object) : null)}>
                  {текстМахраджа(о.название, язык)}
                </Текст>
                <АрабскийМахраджа текст={о.арабский} размер={18} цвет={цвет.текстВторой} />
              </View>
              {махраджи.map((м) => (
                <КарточкаМахраджа
                  key={м.id}
                  м={м}
                  язык={язык}
                  буквы={м.буквы.map((id) => индекс.данные.буквы.find((б) => б.id === id)).filter((б): б is БукваМахраджа => !!б)}
                  гунна={индекс.данные.буквы.filter((б) => б.гунна?.махрадж === м.id)}
                />
              ))}
            </View>
          );
        })
      )}
    </Экран>
  );
}
