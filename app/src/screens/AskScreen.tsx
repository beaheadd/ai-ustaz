type Ключ = Parameters<ReturnType<typeof useСловарь<keyof (typeof СЛОВАРЬ)['ru']>>>[0];

type Запись = { кто: 'вы'; текст: string } | { кто: 'устаз'; ответ: ОтветУстаза };

/** Переписка — только в памяти страницы (между разделами сохраняется, после перезагрузки — нет). */
let переписка: Запись[] = [];

const ПРИМЕРЫ = ['пример1', 'пример2', 'пример3', 'пример4'] as const;

export function СпроситьУстаза(_: ПропсыЭкрана<'устаз'>) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const уменьшить = useУменьшитьДвижение();
  const [записи, установитьЗаписи] = useState<Запись[]>(переписка);
  const [вопрос, установитьВопрос] = useState('');
  const [ждём, установитьЖдём] = useState(false);
  const [ошибка, установитьОшибку] = useState<ПричинаОтказа | null>(null);
  const включено = спроситьВключено();
  const свиток = useRef<ComponentRef<typeof ScrollView>>(null);
  const отмена = useRef<AbortController | null>(null);

  useEffect(() => {
    переписка = записи;
  }, [записи]);
  useEffect(() => () => отмена.current?.abort(), []);
  useEffect(() => {
    const т_ = setTimeout(() => свиток.current?.scrollToEnd({ animated: !уменьшить }), 60);
    return () => clearTimeout(т_);
  }, [записи.length, ждём, уменьшить]);

  async function отправить(текст: string) {
    const q = текст.trim();
    if (!включено || ждём) return;
    if (q.length < МИН_ВОПРОС || q.length > МАКС_ВОПРОС) {
      установитьОшибку('вопрос');
      return;
    }
    установитьОшибку(null);
    установитьВопрос('');
    установитьЗаписи((з) => [...з, { кто: 'вы', текст: q }]);
    установитьЖдём(true);
    отмена.current = typeof AbortController === 'function' ? new AbortController() : null;
    const итог = await спросить(q, язык as 'ru' | 'kk', { signal: отмена.current?.signal });
    установитьЖдём(false);
    if (итог.ок) установитьЗаписи((з) => [...з, { кто: 'устаз', ответ: итог.ответ }]);
    else установитьОшибку(итог.причина);
  }

  const колонка = { width: '100%' as const, maxWidth: ШИРИНА_КОЛОНКИ, alignSelf: 'center' as const };
  const можно = включено && !ждём && вопрос.trim().length >= МИН_ВОПРОС;

  return (
    <Экран заголовок="AI Ustaz" прокрутка={false} testID="экран-устаз">
      <ScrollView ref={свиток} style={{ flex: 1, width: '100%' }} contentContainerStyle={[колонка, { padding: отступ.l, gap: отступ.m }]} keyboardShouldPersistTaps="handled">
        {записи.length === 0 ? (
          <View testID="устаз-пусто" style={{ alignItems: 'center', gap: отступ.m, paddingTop: отступ.l }}>
            <ЭмблемаУстаза размер={96} />
            <Текст вид="заголовок" стиль={{ textAlign: 'center' }}>
              {т('заголовок')}
            </Текст>
            <Текст вид="второй" стиль={{ textAlign: 'center' }} testID="устаз-границы">
              {т('границы')}
            </Текст>
            <View style={{ alignSelf: 'stretch', gap: отступ.s, marginTop: отступ.s }}>
              <Текст вид="мелкий">{т('примеры')}</Текст>
              {ПРИМЕРЫ.map((к, i) => (
                <Pressable
                  key={к}
                  accessibilityRole="button"
                  disabled={!включено}
                  onPress={() => void отправить(т(к))}
                  testID={'устаз-пример-' + (i + 1)}
                  style={({ pressed }) => ({ minHeight: 48, justifyContent: 'center', paddingHorizontal: отступ.m, borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность, opacity: !включено ? 0.5 : pressed ? 0.7 : 1 })}
                >
                  <Текст>{т(к)}</Текст>
                </Pressable>
              ))}
            </View>
          </View>
        ) : (
          записи.map((з, i) =>
            з.кто === 'вы' ? (
              <View key={i} testID={'устаз-вопрос-' + i} style={{ alignSelf: 'flex-end', maxWidth: '85%', backgroundColor: цвет.акцент, borderRadius: 18, borderBottomRightRadius: 6, paddingHorizontal: отступ.m, paddingVertical: отступ.s }}>
                <Текст цвет={цвет.акцентТекст}>{з.текст}</Текст>
              </View>
            ) : (
              <КарточкаОтвета key={i} ответ={з.ответ} номер={i} />
            ),
          )
        )}
        {ждём ? (
          <View testID="устаз-ждём" style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }} {...((ВЕБ ? { role: 'status' } : {}) as object)}>
            <ЭмблемаУстаза размер={32} состояние="объясняю" />
            <Текст вид="второй">{т('ждём')}</Текст>
          </View>
        ) : null}
      </ScrollView>

      <View style={{ borderTopWidth: 1, borderTopColor: цвет.граница, backgroundColor: цвет.фон }}>
        <View style={[колонка, { paddingHorizontal: отступ.l, paddingTop: отступ.s, paddingBottom: отступ.s + 18, gap: 4 }]}>
          {ошибка ? (
            <Текст вид="мелкий" цвет={цвет.текстВторой} testID="устаз-ошибка" {...((ВЕБ ? { role: 'alert' } : {}) as object)}>
              {т(('ошибка.' + ошибка) as Ключ)}
            </Текст>
          ) : null}
          {!включено ? (
            <Текст вид="мелкий" testID="устаз-выключено">
              {т('выключено')}
            </Текст>
          ) : null}
          <View style={{ flexDirection: 'row', alignItems: 'flex-end', gap: отступ.s }}>
            <TextInput
              value={вопрос}
              onChangeText={(т_) => установитьВопрос(т_.slice(0, МАКС_ВОПРОС))}
              onSubmitEditing={() => void отправить(вопрос)}
              placeholder={т('полеПодсказка')}
              placeholderTextColor={цвет.текстВторой}
              accessibilityLabel={т('поле')}
              editable={включено}
              multiline
              maxLength={МАКС_ВОПРОС}
              blurOnSubmit
              enterKeyHint="send"
              testID="устаз-поле"
              style={{
                flex: 1,
                minWidth: 0,
                minHeight: 48,
                maxHeight: 120,
                paddingHorizontal: отступ.m,
                paddingVertical: 12,
                borderRadius: 24,
                borderWidth: 1,
                borderColor: цвет.граница,
                backgroundColor: цвет.поверхность,
                fontFamily: ШРИФТ_ИНТЕРФЕЙСА,
                fontSize: 16,
                color: цвет.текст,
                ...(ВЕБ ? ({ outlineStyle: 'none' } as object) : null),
              }}
            />
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={т('отправить')}
              disabled={!можно}
              onPress={() => void отправить(вопрос)}
              testID="устаз-отправить"
              style={({ pressed }) => ({ width: 48, height: 48, borderRadius: 24, alignItems: 'center', justifyContent: 'center', backgroundColor: можно ? цвет.акцент : цвет.граница, opacity: pressed ? 0.7 : 1 })}
            >
              <Значок имя="вперёд" размер={22} цвет={можно ? цвет.акцентТекст : цвет.текстВторой} толщина={2.25} />
            </Pressable>
          </View>
          <Текст вид="мелкий" стиль={{ textAlign: 'center' }}>
            {т('личное')}
          </Текст>
        </View>
      </View>
    </Экран>
  );
}

function КарточкаОтвета({ ответ, номер }: { ответ: ОтветУстаза; номер: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const шаблон: Record<ОтветУстаза['вид'], Ключ> = { ответ: 'шаблонОтвет', 'нет-в-базе': 'шаблонНет', 'к-имаму': 'шаблонИмам', 'вне-темы': 'шаблонВне' };
  // «к-имаму» и «вне-темы» — всегда наш шаблон (правило 5), «нет-в-базе» — тоже; «ответ» — текст сервера, если прошёл проверку.
  const текст = ответ.вид === 'ответ' && ответ.текст ? ответ.текст : т(шаблон[ответ.вид]);
  return (
    <View testID={'устаз-ответ-' + номер} style={{ alignSelf: 'stretch', gap: отступ.s }}>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
        <ЭмблемаУстаза размер={28} />
        <Текст вид="метка">{т('устаз')}</Текст>
        {ответ.черновик ? <Плашка вид="черновик" надпись={т('черновик')} малая /> : null}
      </View>
      <View
        testID={ответ.вид === 'к-имаму' ? 'устаз-к-имаму' : undefined}
        style={{ backgroundColor: цвет.поверхность, borderRadius: радиус.l, borderTopLeftRadius: 6, borderWidth: 1, borderColor: ответ.вид === 'к-имаму' ? цвет.акцент : цвет.граница, padding: отступ.m, gap: отступ.s }}
      >
        <Текст testID={'устаз-ответ-' + номер + '-текст'}>{текст}</Текст>
        {ответ.вид === 'ответ' ? (
          <Текст вид="мелкий" цвет={цвет.текстВторой}>
            {ответ.режим === 'ии' ? т('режимИИ') : т('режимПоиск')}
          </Текст>
        ) : null}
        {ответ.вид === 'к-имаму' && ответ.источники.length ? <Текст вид="мелкий">{т('общие')}</Текст> : null}
      </View>
      {ответ.источники.length ? (
        <View style={{ gap: отступ.s }} {...((ВЕБ ? { role: 'list', 'aria-label': т('источники') } : {}) as object)}>
          {ответ.источники.map((и) => (
            <КарточкаИсточника key={и.id} и={и} />
          ))}
        </View>
      ) : null}
    </View>
  );
}

function КарточкаИсточника({ и }: { и: ИсточникОтвета }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ, радиус } = useТема();
  const аят = и.вид === 'коран' ? ссылкаАята(и.ссылка) : null;
  const метка = и.вид === 'коран' && аят ? т('коран', { с: аят.сура + ':' + аят.аят }) : и.вид === 'хадис' ? т('хадис') + (и.ссылка ? ' · ' + и.ссылка : '') : т(и.вид);
  return (
    <View
      testID={'устаз-источник-' + и.id}
      {...((ВЕБ ? { role: 'listitem' } : {}) as object)}
      style={{ borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, borderLeftWidth: 4, borderLeftColor: цвет.золотоДекор, padding: отступ.m, gap: отступ.s, backgroundColor: цвет.фон }}
    >
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s, flexWrap: 'wrap' }}>
        <Текст вид="метка" цвет={цвет.акцент}>
          {метка}
        </Текст>
        {и.черновик ? <Плашка вид="черновик" надпись={т('черновик')} малая /> : null}
      </View>
      <Текст вид="подзаголовок">{и.заголовок}</Текст>
      {аят ? <АятИзКопии сура={аят.сура} аят={аят.аят} /> : null}
      {и.вид === 'хадис' && и.арабский ? (
        <АрабскийТекст размер="малый" выравнивание="right">
          {и.арабский}
        </АрабскийТекст>
      ) : null}
      {и.текст ? <Текст>{и.текст}</Текст> : null}
      {и.вид === 'хадис' && и.степень && и.кто_оценил ? (
        <Текст вид="мелкий">{т('степень', { с: и.степень, к: и.кто_оценил })}</Текст>
      ) : null}
      <Текст вид="мелкий" цвет={цвет.текстВторой}>
        {т('источник', { и: и.источник })}
      </Текст>
    </View>
  );
}

/** Аят — только из своей проверенной копии Tanzil по ссылке (правило 1), и переход к нему в Коране. */
function АятИзКопии({ сура, аят }: { сура: number; аят: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { цвет } = useТема();
  const { перейти } = useНавигация();
  const с = useСура(сура);
  const текст = с.состояние === 'есть' ? (с.данные.аяты[аят - 1]?.текст ?? null) : null;
  return (
    <View style={{ gap: 4 }}>
      {текст ? <ТекстАята текст={текст} кегль={24} testID={`устаз-аят-${сура}-${аят}`} /> : <Текст вид="мелкий">{т('аятЗагрузка')}</Текст>}
      <Pressable accessibilityRole="link" onPress={() => перейти('сура', { номер: сура, аят })} style={({ pressed }) => ({ minHeight: 44, justifyContent: 'center', opacity: pressed ? 0.6 : 1 })} testID={`устаз-открыть-${сура}-${аят}`}>
        <Текст вид="метка" цвет={цвет.акцент} стиль={{ textDecorationLine: 'underline' }}>
          {т('открыть', { с: сура + ':' + аят })}
        </Текст>
      </Pressable>
    </View>
  );
}
