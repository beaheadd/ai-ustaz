const ВСЕГО = 4;
type Т = (ключ: keyof (typeof СЛОВАРЬ)['ru'], параметры?: ПараметрыСтроки) => string;

export function Онбординг(_: ПропсыЭкрана<'онбординг'>) {
  const { t, язык, установитьЯзык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { заменить, назад } = useНавигация();
  const { отступ } = useТема();
  const [шаг, установитьШаг] = useState(0);

  useEffect(() => {
    отметитьОнбордингПредложен();
  }, []);

  /** Сохранить язык (даже если оставили русский по умолчанию) — онбординг пройден. */
  const запомнитьЯзык = () => установитьЯзык(язык);
  const последний = шаг === ВСЕГО - 1;

  const низ = последний ? (
    <>
      <Кнопка
        надпись={т('начать')}
        крупная
        значок="урок"
        приНажатии={() => {
          запомнитьЯзык();
          заменить('урок0');
        }}
        testID="онбординг-начать"
      />
      <Кнопка
        надпись={т('наГлавную')}
        вид="тихая"
        приНажатии={() => {
          запомнитьЯзык();
          назад();
        }}
        testID="онбординг-на-главную"
      />
    </>
  ) : (
    <>
      <Кнопка
        надпись={т('далее')}
        крупная
        приНажатии={() => {
          запомнитьЯзык();
          установитьШаг((ш) => ш + 1);
        }}
        testID="онбординг-далее"
      />
      <Кнопка
        надпись={т('пропустить')}
        вид="тихая"
        приНажатии={() => {
          запомнитьЯзык();
          назад();
        }}
        testID="онбординг-пропустить"
      />
    </>
  );

  return (
    <Экран key={шаг} заголовок={t('экран.онбординг')} плашка="общая" testID="экран-онбординг" низ={низ}>
      <Ход шаг={шаг} т={т} />

      {шаг === 0 ? <ШагЗнакомство т={т} /> : null}
      {шаг === 1 ? <ШагБесплатно т={т} /> : null}
      {шаг === 2 ? <ШагНамаз т={т} /> : null}
      {шаг === 3 ? <ШагПрототип т={т} /> : null}

      {шаг > 0 ? (
        <View style={{ paddingTop: отступ.xs }}>
          <Кнопка надпись={т('назадШаг')} вид="тихая" значок="назад" растянуть={false} приНажатии={() => установитьШаг((ш) => ш - 1)} testID="онбординг-шаг-назад" />
        </View>
      ) : null}
    </Экран>
  );
}

/** Ход по шагам: узлы пути (пройден — изумруд с галочкой, текущий — золото, впереди — тише) и подпись. */
function Ход({ шаг, т }: { шаг: number; т: Т }) {
  const { цвет, отступ } = useТема();
  const подпись = т('шаг', { номер: шаг + 1, всего: ВСЕГО }) + ' · ' + т(`шаг.${шаг + 1}` as keyof (typeof СЛОВАРЬ)['ru']);
  return (
    <View style={{ gap: отступ.s }} accessibilityRole="progressbar" accessibilityLabel={подпись} testID="онбординг-ход">
      <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between' }}>
        {/* Линия пути — только декор (золотоДекор), под узлами. */}
        <View style={{ position: 'absolute', left: 18, right: 18, height: 2, borderRadius: 1, backgroundColor: цвет.золотоДекор, opacity: 0.55 }} />
        {Array.from({ length: ВСЕГО }, (_, i) => (
          <УзелПути
            key={i}
            размер={28}
            вид={i < шаг ? 'пройден' : i === шаг ? 'текущий' : 'скоро'}
            значок={i < шаг ? 'галочка' : undefined}
            метка={i < шаг ? undefined : String(i + 1)}
          />
        ))}
      </View>
      <Текст вид="мелкий" accessibilityElementsHidden importantForAccessibility="no">
        {подпись}
      </Текст>
    </View>
  );
}

