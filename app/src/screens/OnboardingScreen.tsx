/** Шаг 4: уведомления — 5 намазов (все включены) и «Включить уведомления» (системное окно — только из нажатия). */
function ШагУведомления({ т }: { т: Т }) {
  const { язык } = useПеревод();
  const { отступ } = useТема();
  const поддержка = useПоддержкаУведомлений();
  const { настройки, изменить } = useНастройкиУведомлений();
  const { место } = useМестоНамаза();
  const [итог, установитьИтог] = useState<'ждём' | 'включено' | 'отказ' | 'закрыто' | 'ошибка' | null>(настройки.включено ? 'включено' : null);

  async function включитьСейчас() {
    установитьИтог('ждём');
    const момент = Date.now();
    const данные = данныеРасписания(место, язык, настройки, момент);
    const р = await включить(данные);
    if (р === 'включено') {
      await изменить({ включено: true, отправлено: момент, до: концаРасписания(данные.пункты) });
      отметитьОтправку(ключСинхронизации(место, язык, настройки, текущийМазхаб(), версияОфициальных()));
      установитьИтог('включено');
    } else установитьИтог(р === 'отказ' ? 'отказ' : р === 'закрыто' ? 'закрыто' : 'ошибка');
  }

  if (поддержка !== 'можно') {
    const ключ = поддержка === 'batr' ? 'ш4.batr' : поддержка === 'ios-домой' ? 'ш4.ios' : 'ш4.нет';
    return (
      <>
        <Шапка заголовок={т('ш4.заголовок')} текст={т('ш4.текст')} />
        <Текст testID="онбординг-уведомления-подсказка" стиль={{ textAlign: 'center' }}>
          {т(ключ)}
        </Текст>
      </>
    );
  }

  return (
    <>
      <Шапка заголовок={т('ш4.заголовок')} текст={т('ш4.текст')} />
      {итог === 'включено' ? null : (
        <Кнопка
          надпись={итог === 'ждём' ? т('ш4.ждём') : т('ш4.включить')}
          вид="вторичная"
          значок="колокол"
          отключена={итог === 'ждём' || !ПЯТЬ.some((к) => настройки.намазы[к])}
          приНажатии={() => void включитьСейчас()}
          testID="онбординг-уведомления-включить"
        />
      )}
      {итог && итог !== 'ждём' ? (
        <View style={{ paddingHorizontal: отступ.xs }}>
          <Текст testID="онбординг-уведомления-итог" accessibilityLiveRegion="polite">
            {т(итог === 'включено' ? 'ш4.включено' : итог === 'отказ' ? 'ш4.отказ' : итог === 'закрыто' ? 'ш4.закрыто' : 'ш4.ошибка')}
          </Текст>
        </View>
      ) : null}
      <View>
        {ПЯТЬ.map((к) => (
          <СтрокаПереключателя
            key={к}
            заголовок={НАЗВАНИЯ[к][язык]}
            включено={настройки.намазы[к]}
            приСмене={(н) => void изменить({ намазы: { ...настройки.намазы, [к]: н } })}
            testID={'онбординг-намаз-' + к}
          />
        ))}
      </View>
    </>
  );
}
