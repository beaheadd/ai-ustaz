const ВСЕГО = 3;

export function Онбординг(_: ПропсыЭкрана<'онбординг'>) {
  const { t, язык, установитьЯзык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { заменить, назад } = useНавигация();
  const { отступ, цвет, радиус } = useТема();
  const [шаг, установитьШаг] = useState(0);

  useEffect(() => {
    отметитьОнбордингПредложен();
  }, []);

  /** Сохранить язык (даже если оставили русский по умолчанию) — онбординг пройден. */
  const запомнитьЯзык = () => установитьЯзык(язык);
  const последний = шаг === ВСЕГО - 1;

  const низ = последний ? (
    <>
      <Кнопка
        надпись={т('начать')}
        крупная
        приНажатии={() => {
          запомнитьЯзык();
          заменить('урок0');
        }}
        testID="онбординг-начать"
      />
      <Кнопка
        надпись={т('наГлавную')}
        вид="тихая"
        приНажатии={() => {
          запомнитьЯзык();
          назад();
        }}
        testID="онбординг-на-главную"
      />
    </>
  ) : (
    <>
      <Кнопка
        надпись={т('далее')}
        крупная
        приНажатии={() => {
          запомнитьЯзык();
          установитьШаг((ш) => ш + 1);
        }}
        testID="онбординг-далее"
      />
      <Кнопка
        надпись={т('пропустить')}
        вид="тихая"
        приНажатии={() => {
          запомнитьЯзык();
          назад();
        }}
        testID="онбординг-пропустить"
      />
    </>
  );

  return (
    <Экран key={шаг} заголовок={t('экран.онбординг')} плашка="общая" testID="экран-онбординг" низ={низ}>
      <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }} accessibilityLabel={т('шаг', { номер: шаг + 1, всего: ВСЕГО })}>
        {Array.from({ length: ВСЕГО }, (_, i) => (
          <View
            key={i}
            style={{ flex: 1, height: 6, borderRadius: радиус.круг, backgroundColor: i <= шаг ? цвет.акцент : цвет.акцентМягкий }}
          />
        ))}
      </View>
      <Текст вид="мелкий">{т('шаг', { номер: шаг + 1, всего: ВСЕГО })}</Текст>

      {шаг === 0 ? (
        <View style={{ gap: отступ.l }} testID="онбординг-шаг-1">
          <Текст вид="заголовок">{т('ш1.заголовок')}</Текст>
          <Текст вид="подзаголовок">{т('ш1.текст')}</Текст>
          <Пункты пункты={[т('ш1.п1'), т('ш1.п2'), т('ш1.п3')]} />
          <Карточка заголовок={т('ш1.язык')}>
            <ПереключательЯзыка />
            <Текст вид="мелкий">{т('ш1.языкПояснение')}</Текст>
          </Карточка>
        </View>
      ) : null}

      {шаг === 1 ? (
        <View style={{ gap: отступ.l }} testID="онбординг-шаг-2">
          <Текст вид="заголовок">{т('ш2.заголовок')}</Текст>
          <Пункты пункты={[т('ш2.п1'), т('ш2.п2'), т('ш2.п3'), т('ш2.п4')]} />
        </View>
      ) : null}

      {шаг === 2 ? (
        <View style={{ gap: отступ.l }} testID="онбординг-шаг-3">
          <Текст вид="заголовок">{т('ш3.заголовок')}</Текст>
          <Текст>{т('ш3.текст')}</Текст>
          <Карточка акцент заголовок={т('ш3.нет')}>
            <Пункты пункты={[т('ш3.нет1'), т('ш3.нет2'), т('ш3.нет3')]} />
          </Карточка>
          <Текст>{т('ш3.будет')}</Текст>
          <Текст вид="второй">{т('ш3.черновик')}</Текст>
        </View>
      ) : null}

      {шаг > 0 ? (
        <Кнопка надпись={т('назадШаг')} вид="тихая" растянуть={false} приНажатии={() => установитьШаг((ш) => ш - 1)} testID="онбординг-шаг-назад" />
      ) : null}
    </Экран>
  );
}
