const ВСЕГО = 4;
const ЗНАЧКИ_ШАГОВ: readonly ИмяЗначка[] = ['язык', 'город', 'время', 'колокол'];
/** Пять намазов шага «Уведомления» — восход не показываем (владелец 28.11.2026). */
const ПЯТЬ: readonly КлючВремени[] = ['fajr', 'dhuhr', 'asr', 'maghrib', 'isha'];
type Т = (ключ: keyof (typeof СЛОВАРЬ)['ru'], параметры?: Record<string, string | number>) => string;

export function Онбординг(_: ПропсыЭкрана<'онбординг'>) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { назад } = useНавигация();
  const { изменить } = useПрогресс();
  const { цвет, отступ } = useТема();
  const [шаг, установитьШаг] = useState(0);

  useEffect(() => {
    отметитьОнбордингПредложен();
  }, []);

  /** Конец онбординга — больше не открывается сам (то, что пропущено, остаётся по умолчанию). */
  const завершить = () => {
    изменить((п) => ({ ...п, онбордингПройден: true }));
    назад();
  };
  const дальше = () => (шаг < ВСЕГО - 1 ? установитьШаг(шаг + 1) : завершить());
  const последний = шаг === ВСЕГО - 1;

  const низ = (
    <View style={{ gap: отступ.s }}>
      <View
        testID="онбординг-точки"
        accessibilityRole="progressbar"
        accessibilityLabel={т('шаг', { номер: шаг + 1, всего: ВСЕГО })}
        style={{ flexDirection: 'row', justifyContent: 'center', gap: 8, paddingVertical: 4 }}
      >
        {Array.from({ length: ВСЕГО }, (_, i) => (
          <View
            key={i}
            testID={'онбординг-точка-' + (i + 1)}
            style={{ width: i === шаг ? 22 : 8, height: 8, borderRadius: 4, backgroundColor: i === шаг ? цвет.акцент : цвет.граница }}
          />
        ))}
      </View>
      <Кнопка надпись={последний ? т('готово') : т('далее')} крупная приНажатии={дальше} testID={последний ? 'онбординг-готово' : 'онбординг-далее'} />
      <Кнопка надпись={т('пропустить')} вид="тихая" приНажатии={дальше} testID="онбординг-пропустить" />
    </View>
  );

  return (
    <Экран key={шаг} заголовок={t('экран.онбординг')} testID="экран-онбординг" низ={низ} назад={false}>
      <View style={{ gap: отступ.l }} testID={'онбординг-шаг-' + (шаг + 1)}>
        <Значок_ имя={ЗНАЧКИ_ШАГОВ[шаг]} />
        {шаг === 0 ? <ШагЯзык т={т} /> : null}
        {шаг === 1 ? <ШагМесто т={т} /> : null}
        {шаг === 2 ? <ШагРасчёт т={т} /> : null}
        {шаг === 3 ? <ШагУведомления т={т} /> : null}
      </View>
    </Экран>
  );
}

