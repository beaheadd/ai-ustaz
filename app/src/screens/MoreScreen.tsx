/** Раздел страницы: заголовок и содержимое. */
function Раздел({ заголовок, children, testID }: { заголовок: string; children: ReactNode; testID?: string }) {
  const { отступ } = useТема();
  return (
    <View style={{ gap: отступ.s }} testID={testID}>
      <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
        {заголовок}
      </Текст>
      {children}
    </View>
  );
}

export function Ещё(_: ПропсыЭкрана<'ещё'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { место } = useМестоНамаза();
  const { отступ } = useТема();
  const [предупреждениеОткрыто, установитьПредупреждение] = useState(false);
  const { сценарий } = useУстановка();
  const поддержка = useПоддержкаУведомлений();
  const { настройки: уведомления } = useНастройкиУведомлений();
  const подписьУведомлений =
    поддержка === 'можно' ? (уведомления.включено ? т('уведомленияВкл') : т('уведомленияВыкл')) : поддержка === 'ios-домой' ? т('уведомленияIOS') : т('уведомленияНет');
  const подписьУстановки = сценарий === 'установлено' ? т('установкаЕсть') : сценарий === 'batr' ? т('установкаBatr') : т('установкаПояснение');

  return (
    <Экран заголовок={t('экран.ещё')} testID="экран-ещё">
      {Platform.OS === 'web' ? (
        <СтрокаСписка заголовок={т('установка')} подпись={подписьУстановки} значок="телефон" приНажатии={() => перейти('установка')} testID="ещё-установка" />
      ) : null}
      {/* «Хадисы» — раздел из нижнего меню переехал сюда: в центре меню теперь AI Ustaz (владелец 20.11.2026). */}
      {УСТАЗ_В_МЕНЮ ? (
        <СтрокаСписка заголовок={т('хадисы')} подпись={т('хадисыПодпись')} значок="хадис" приНажатии={() => перейти('хадисы')} testID="ещё-хадисы" />
      ) : null}
      <Раздел заголовок={т('настройки')}>
        <View style={{ gap: отступ.xs }} testID="ещё-язык">
          <Текст вид="мелкий">{т('язык')}</Текст>
          <ПереключательЯзыка />
        </View>
        <View style={{ gap: отступ.xs }} testID="ещё-тема">
          <Текст вид="мелкий">{т('тема')}</Текст>
          <ПереключательТемы />
        </View>
        {/* Размер арабского текста Корана (ревью 19.11.2026; тот же выбор — А− / А+ в шапке суры). */}
        <РазмерАрабского testID="ещё-размер-арабского" />
        {/* Вид чтения Корана (владелец 20.11.2026: «3–4 варианта … чтобы человек выбрал»); тот же выбор — в шапке суры. */}
        <ВыборВидаЧтения />
        <СтрокаСписка заголовок={т('город')} подпись={названиеМеста(место, язык)} значок="город" приНажатии={() => перейти('городНамаза')} testID="ещё-город" />
        {/* Уведомления о времени намаза (владелец 20.11.2026): только aiustaz.pro; на batr.kz — пояснение без нажатия. */}
        {поддержка === 'batr' ? (
          <Текст вид="мелкий" testID="ещё-уведомления-batr">
            {т('уведомленияBatr')}
          </Текст>
        ) : (
          <СтрокаСписка
            заголовок={т('уведомления')}
            подпись={подписьУведомлений}
            значок={поддержка === 'можно' && уведомления.включено ? 'колокол' : 'колоколВыкл'}
            приНажатии={() => перейти('уведомления')}
            testID="ещё-уведомления"
          />
        )}
      </Раздел>

      <Раздел заголовок="AI Ustaz">
        <СтрокаСписка
          заголовок={т('предупреждение')}
          подпись={т('предупреждениеПояснение')}
          значок="инфо"
          раскрыт={предупреждениеОткрыто}
          приНажатии={() => установитьПредупреждение((о) => !о)}
          testID="ещё-предупреждение"
        />
        {предупреждениеОткрыто ? <ПредупреждениеИИИзКонтента testID="ещё-текст-предупреждения" /> : null}
        <СтрокаСписка заголовок={т('как')} подпись={т('какПояснение')} значок="нукта" приНажатии={() => перейти('какОбъясняем')} testID="ещё-как" />
      </Раздел>

      <Раздел заголовок={т('оПроектеРаздел')}>
        <СтрокаСписка заголовок={т('оПроекте')} подпись={т('оПроектеПояснение')} значок="хатам" приНажатии={() => перейти('оПроекте')} testID="ещё-о-проекте" />
        <СтрокаСписка заголовок={т('лицензии')} подпись={т('лицензииПояснение')} значок="меню" приНажатии={() => перейти('лицензии')} testID="ещё-лицензии" />
      </Раздел>

      <Раздел заголовок={т('готовим')} testID="ещё-готовим">
        <Текст вид="мелкий">{т('готовимПояснение')}</Текст>
        {(['намаз', 'дуа'] as const).map((ключ) => (
          <СтрокаСписка
            key={ключ}
            вид="плоская"
            заголовок={т(`модуль.${ключ}`)}
            подпись={т(`модуль.${ключ}Пояснение`)}
            значок={ключ === 'намаз' ? 'кааба' : 'луна'}
            справа={<Плашка вид="скоро" надпись={т('готовим')} />}
            testID={'ещё-готовим-' + ключ}
          />
        ))}
      </Раздел>

      <Текст вид="мелкий">{т('безВхода')}</Текст>
    </Экран>
  );
}
