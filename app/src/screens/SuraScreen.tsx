/** Плавающие кнопки: «Слушать» (▶/⏸) и «Прочитать и проверить»; чип выбранного аята. Уезжают вниз при чтении. */
function ПлавающиеКнопки({ сура, видны, выбран, снятьВыбор, цель, записать, фон, закладка, начальное }: { сура: number; видны: boolean; выбран: number | null; снятьВыбор: () => void; цель: () => number; записать: (аят: number) => void; фон: string; закладка: number | null; начальное: string | null }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ } = useТема();
  const снимок = useПлеер();
  const появление = useПоявление(видны, 120, true);
  const [безЗвука, установитьБезЗвука] = useState(false);
  const [сообщение, установитьСообщение] = useState<string | null>(начальное);
  useEffect(() => {
    if (!сообщение) return;
    const т_ = setTimeout(() => установитьСообщение(null), 3500);
    return () => clearTimeout(т_);
  }, [сообщение]);
  useEffect(() => {
    if (!безЗвука) return;
    const т_ = setTimeout(() => установитьБезЗвука(false), 4000);
    return () => clearTimeout(т_);
  }, [безЗвука]);

  const здесь = !!снимок.текущий && снимок.текущий.сура === сура && снимок.состояние !== 'стоп';
  const играет = здесь && (снимок.состояние === 'играет' || снимок.состояние === 'загрузка');
  const наПаузе = здесь && снимок.состояние === 'пауза';
  const аят = выбран ?? null;
  // Выбран другой аят, чем читает кари, — «Слушать» начинает с него; иначе — пауза / продолжить.
  const сВыбранного = аят !== null && (!здесь || снимок.текущий?.аят !== аят);

  function слушать() {
    if (!сВыбранного && играет) return плеер.пауза();
    if (!сВыбранного && наПаузе) return плеер.продолжить();
    if (!снимок.источник || !доступныйИсточник()) {
      установитьБезЗвука(true);
      return;
    }
    установитьЯзыкПлеера(язык);
    // Синхронно из нажатия: первый play() браузеры разрешают только из жеста.
    плеер.играть({ сура, сАята: аят ?? цель() });
  }

  const подписьСлушать = сВыбранного ? т('слушать', { аят: аят ?? 1 }) : играет ? т('пауза') : наПаузе ? т('продолжить') : т('слушать', { аят: цель() });
  return (
    <View
      testID="сура-кнопки"
      pointerEvents="box-none"
      {...((ВЕБ ? { 'aria-hidden': видны ? undefined : true } : {}) as object)}
      style={{
        position: 'absolute',
        left: 0,
        right: 0,
        bottom: 0,
        alignItems: 'center',
        paddingBottom: ВЕБ ? ('calc(16px + env(safe-area-inset-bottom))' as unknown as number) : 16,
        ...появление,
      }}
    >
      <View pointerEvents="box-none" style={{ width: '100%', maxWidth: ШИРИНА_КОЛОНКИ, paddingHorizontal: отступ.l, alignItems: 'flex-end', gap: отступ.s }}>
        {безЗвука ? (
          <View testID="сура-без-звука" style={{ alignSelf: 'stretch', backgroundColor: цвет.поверхность, borderRadius: 14, borderWidth: 1, borderColor: цвет.граница, paddingHorizontal: отступ.m, paddingVertical: отступ.s }}>
            <СтрокаБезЗвука />
          </View>
        ) : null}
        {сообщение ? (
          <View testID="сура-сообщение" {...((ВЕБ ? { role: 'status' } : {}) as object)} style={{ alignSelf: 'stretch', backgroundColor: цвет.поверхность, borderRadius: 14, borderWidth: 1, borderColor: цвет.граница, paddingHorizontal: отступ.m, paddingVertical: отступ.s }}>
            <Текст>{сообщение}</Текст>
          </View>
        ) : null}
        {выбран !== null ? (
          // Выбранный аят: «Сохранить место» и «Аят N ×» — отдельным рядом над кнопками (на 360 px в один ряд не влезают).
          <View pointerEvents="box-none" style={{ flexDirection: 'row', flexWrap: 'wrap', justifyContent: 'flex-end', alignItems: 'center', gap: отступ.s }}>
            {выбран !== null ? (
              // Закладка (владелец 21.11.2026): нажали на номер аята — «Сохранить место»; продолжить — в «Коран».
              <Pressable
                accessibilityRole="button"
                accessibilityLabel={закладка === выбран ? т('закладкаЕсть') : т('закладка', { аят: выбран })}
                focusable={видны}
                onPress={() => {
                  const убрать = закладка === выбран;
                  поставитьЗакладку(убрать ? null : { сура, аят: выбран });
                  установитьСообщение(убрать ? т('закладкаУбрана') : т('закладкаСохранена', { сура, аят: выбран }));
                }}
                testID="сура-закладка"
                style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: 6, height: 40, paddingHorizontal: 12, borderRadius: 20, backgroundColor: фон, borderWidth: 1, borderColor: цвет.золотоДекор, opacity: pressed ? 0.7 : 1 })}
              >
                <Значок имя={закладка === выбран ? 'закладкаЕсть' : 'закладка'} размер={18} цвет={цвет.золотоДекор} толщина={2} />
                <Текст вид="метка">{закладка === выбран ? т('закладкаЕсть') : т('закладка', { аят: выбран })}</Текст>
              </Pressable>
            ) : null}
            {выбран !== null ? (
              <Pressable
                accessibilityRole="button"
                accessibilityLabel={т('снятьВыбор', { аят: выбран })}
                focusable={видны}
                onPress={снятьВыбор}
                testID="сура-выбран"
                style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: 4, height: 40, paddingHorizontal: 14, borderRadius: 20, backgroundColor: фон, borderWidth: 1, borderColor: цвет.акцент, opacity: pressed ? 0.7 : 1 })}
              >
                <Текст вид="метка" цвет={цвет.акцент} табличные>
                  {т('аят', { аят: выбран })}
                </Текст>
                <Значок имя="закрыть" размер={16} цвет={цвет.акцент} толщина={2} />
              </Pressable>
            ) : null}
          </View>
        ) : null}
        <View pointerEvents="box-none" style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <КругКнопка значок="микрофон" подпись={т('записать', { аят: аят ?? цель() })} приНажатии={() => записать(цель())} доступна={видны} testID="сура-записать" вторая />
          <КругКнопка значок={играет && !сВыбранного ? 'пауза' : 'играть'} подпись={подписьСлушать} приНажатии={слушать} доступна={видны} testID="сура-слушать" />
        </View>
      </View>
    </View>
  );
}

