const ВЕБ = Platform.OS === 'web';
/** Высота шапки без системной строки. */
const ВЫСОТА_ШАПКИ = 56;
/** Не прокручивать за чтецом, если пользователь сам прокручивал недавно (мс). */
const СЛЕДИТЬ_ПОСЛЕ_РУЧНОЙ_МС = 4000;
/** Аятов в порции: строки — 20, поток мусхафа — 40 (аят там короче по высоте). */
const порцияВида = (вид: ВидЧтения) => (вид === 'обычный' ? 20 : 40);
const ВЕРХ_СИСТЕМЫ = Platform.OS === 'android' ? (StatusBar.currentHeight ?? 0) : 0;

export function Сура({ параметры }: ПропсыЭкрана<'сура'>) {
  const { t, язык } = useПеревод();
  const { цвет, отступ } = useТема();
  const н = параметры.номер;
  const { вид, ночьЦвета } = useВидЧтения();
  const сура = useСура(н);
  const индекс = useИндексСур();
  const суры = индекс.состояние === 'есть' ? индекс.данные.суры : null;
  const заголовок = названиеСуры(суры?.[н - 1] ?? null, н, язык);
  const ночь = вид === 'ночной';
  const бумага = вид !== 'обычный';
  const п = ночь ? ПАЛИТРЫ_МУСХАФА.ночь : ПАЛИТРЫ_МУСХАФА.бумага;
  const фон = бумага ? п.фон : цвет.фон;
  const чернила = бумага ? п.чернила : цвет.текст;
  const акцент = !бумага ? цвет.акцент : ночь ? п.знак : п.рамка2;

  useEffect(() => {
    if (ВЕБ && typeof document !== 'undefined') document.title = `${заголовок} — AI Ustaz`;
  }, [заголовок]);

  const [меню, установитьМеню] = useState(false);
  const [панели, установитьПанели] = useState(true);
  // Владелец 27.11.2026: «сохранить аят, где остановился». Открыли суру без аята (из списка) — вернуть к месту, где
  // человек остановился в этой суре (если не в начале); с аятом в адресе (переход, «Продолжить», закладка) — туда.
  const [возврат, установитьВозврат] = useState<{ сура: number; аят: number | null } | null>(null);
  const безАята = параметры.аят === undefined || параметры.аят === null;
  useEffect(() => {
    if (!безАята) return;
    let живой = true;
    void прочитатьЧтение().then((м) => {
      if (живой) установитьВозврат({ сура: н, аят: м && м.сура === н && м.аят > 1 ? м.аят : null });
    });
    return () => {
      живой = false;
    };
    // при открытии суры без аята: прокрутка сама добавляет аят в адрес — это не новое открытие
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [н, безАята]);
  const местоГотово = !безАята || (возврат !== null && возврат.сура === н);
  const цель = безАята ? (возврат?.аят ?? null) : (параметры.аят ?? null);
  const [вернулись] = useState(() => ({ н, было: безАята }));

  return (
    <View testID="экран-сура" style={{ flex: 1, backgroundColor: фон }}>
      <View role={ВЕБ ? 'main' : undefined} style={{ flex: 1 }}>
        {сура.состояние === 'есть' && местоГотово ? (
          <ТелоСуры
            key={н + ':' + (бумага ? 'м' : 'о')}
            сура={сура.данные}
            суры={суры}
            цель={цель}
            вернулись={вернулись.н === н && вернулись.было && !!возврат?.аят && возврат.сура === н}
            вид={вид}
            сЦветами={вид === 'таджвид' || (ночь && ночьЦвета)}
            панели={панели || меню}
            установитьПанели={установитьПанели}
          />
        ) : (
          <View style={{ padding: отступ.l, paddingTop: ВЫСОТА_ШАПКИ + ВЕРХ_СИСТЕМЫ + отступ.l, gap: отступ.s, width: '100%', maxWidth: ШИРИНА_КОЛОНКИ, alignSelf: 'center' }}>
            {сура.состояние === 'загрузка' || сура.состояние === 'есть' ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : <ТекстКоранаНедоступен состояние={сура} />}
          </View>
        )}
      </View>
      <Шапка заголовок={заголовок} видна={панели || меню} фон={фон} чернила={чернила} акцент={акцент} меню={меню} переключитьМеню={() => установитьМеню((м) => !м)} />
      {меню ? (
        <МенюВида
          закрыть={() => установитьМеню(false)}
          сура={сура.состояние === 'есть' ? сура.данные : null}
          естьТранслит={!!суры?.[н - 1]?.транслит[язык]}
        />
      ) : null}
    </View>
  );
}

/** Шапка поверх текста: «назад», название, кнопка вида. Уезжает вверх при чтении. */
function Шапка({ заголовок, видна, фон, чернила, акцент, меню, переключитьМеню }: { заголовок: string; видна: boolean; фон: string; чернила: string; акцент: string; меню: boolean; переключитьМеню: () => void }) {
  const т = useСловарь(СЛОВАРЬ);
  const { отступ, цвет } = useТема();
  const { назад } = useНавигация();
  const высота = ВЫСОТА_ШАПКИ + ВЕРХ_СИСТЕМЫ;
  const появление = useПоявление(видна, -высота - 2);
  return (
    <View
      testID="сура-шапка"
      {...((ВЕБ ? { role: 'banner', 'aria-hidden': видна ? undefined : true } : {}) as object)}
      style={{
        position: 'absolute',
        top: 0,
        left: 0,
        right: 0,
        paddingTop: ВЕРХ_СИСТЕМЫ,
        height: высота,
        backgroundColor: фон,
        borderBottomWidth: 1,
        borderBottomColor: цвет.граница,
        ...появление,
      }}
    >
      <View style={{ flex: 1, flexDirection: 'row', alignItems: 'center', width: '100%', maxWidth: ШИРИНА_КОЛОНКИ, alignSelf: 'center', paddingHorizontal: отступ.xs, gap: отступ.xs }}>
        <КруглаяКнопка значок="назад" подпись={т('назад')} цвет={акцент} приНажатии={назад} доступна={видна} testID="сура-назад" />
        <Текст вид="подзаголовок" numberOfLines={1} accessibilityRole="header" уровень={1} цвет={чернила} стиль={{ flex: 1 }} testID="сура-заголовок">
          {заголовок}
        </Текст>
        <КруглаяКнопка значок="настройки" подпись={т('вид')} цвет={акцент} приНажатии={переключитьМеню} раскрыт={меню} доступна={видна} testID="сура-вид" />
      </View>
    </View>
  );
}

