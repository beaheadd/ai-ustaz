/** Атрибуты HTML для react-native-web (Text их поддерживает, в типах RN их нет). */
const АРАБСКИЙ_ВЕБ = (ВЕБ ? { lang: 'ar', dir: 'rtl' } : {}) as object;
/** Обычный арабский шрифт системы для хадисов (не Amiri Quran — это не Коран). */
const ШРИФТ_АРАБСКИЙ_ТЕКСТ = ВЕБ ? "'Noto Naskh Arabic', 'Geeza Pro', 'Segoe UI', Tahoma, 'Arial', sans-serif" : undefined;

/** Арабский текст зикра: каждый абзац ar[] отдельно, по центру. */
export function АрабскийЗикра({ зикр, крупный = true, testID }: { зикр: Зикр; крупный?: boolean; testID?: string }) {
  const { цвет, отступ } = useТема();
  // Длинный текст (аят аль-Курси, сайид аль-истигфар) — мельче, чтобы не уходил на несколько экранов.
  const длинный = зикр.ar.join(' ').length > 160;
  return (
    <View testID={testID} style={{ gap: отступ.s }}>
      {зикр.ar.map((абзац, i) =>
        зикр.вид === 'коран' ? (
          <АрабскийТекст key={i} размер={крупный && !длинный ? 'крупный' : 'средний'} выравнивание="center" выбираемый>
            {абзац}
          </АрабскийТекст>
        ) : (
          <Text
            key={i}
            {...АРАБСКИЙ_ВЕБ}
            selectable
            style={{
              fontFamily: ШРИФТ_АРАБСКИЙ_ТЕКСТ,
              fontSize: крупный && !длинный ? 32 : 24,
              lineHeight: Math.round((крупный && !длинный ? 32 : 24) * 1.8),
              color: цвет.текст,
              textAlign: 'center',
              writingDirection: 'rtl',
            }}
          >
            {абзац}
          </Text>
        ),
      )}
    </View>
  );
}

/** «Коран, 2:255» или «HadeethEnc № 5475 · صحيح (сахих) · رواه مسلم (Муслим)». */
export function подписьИсточника(зикр: Зикр, язык: Язык, т: (к: 'коран' | 'hadeethenc', п?: Record<string, string | number>) => string): string {
  const и = зикр.источник;
  if (зикр.вид === 'коран') return т('коран', { ссылка: и.коран ?? '' });
  const части = [т('hadeethenc', { n: и.hadeethenc ?? '' })];
  if (и.степень_ar) части.push(`${и.степень_ar} (${и.степень?.[язык] ?? ''})`);
  if (и.передали_ar) части.push(`${и.передали_ar} (${и.передали?.[язык] ?? ''})`);
  return части.join(' · ');
}

/** «Нет связи» + «Повторить» | «Файл не найден» | «не прошло сверку» (непроверенное не показываем). */
export function ЗикрыНедоступны({ состояние }: { состояние: { нетСвязи: boolean; причина: ПричинаОтказа; повторить: () => void } }) {
  const т = useСловарь(СЛОВАРЬ_ЗИКРОВ);
  const { отступ } = useТема();
  if (состояние.нетСвязи) {
    return (
      <View style={{ gap: отступ.s }}>
        <Текст вид="второй" testID="зикры-нет-связи" accessibilityLiveRegion="polite">
          {т('нетСвязи')}
        </Текст>
        <Кнопка вид="вторичная" значок="повтор" надпись={т('повторить')} растянуть={false} приНажатии={состояние.повторить} testID="зикры-повторить" />
      </View>
    );
  }
  if (состояние.причина === 'нет-файла') {
    return (
      <View style={{ gap: отступ.s }}>
        <Текст вид="второй" testID="зикры-нет-файла" accessibilityLiveRegion="polite">
          {т('нетФайла')}
        </Текст>
        {ВЕБ ? <Кнопка вид="вторичная" значок="повтор" надпись={т('обновить')} растянуть={false} приНажатии={() => globalThis.location?.reload()} /> : null}
      </View>
    );
  }
  return (
    <Текст вид="второй" testID="зикры-нет-сверки">
      {т('нетСверки')}
    </Текст>
  );
}
