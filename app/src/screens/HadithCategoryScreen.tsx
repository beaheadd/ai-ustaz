/**
 * Раздел хадисов (#/hadith/list?n=<id категории HadeethEnc>): путь раздела, подразделы и хадисы раздела.
 *
 * Решение владельца 21.11.2026: «Добавь хадисы Аль-Бухари ещё перевод!». Разделы — категории HadeethEnc как есть
 * (названия из выгрузки языка интерфейса; kk — русские, uz — как у HadeethEnc, кириллицей); в списке — только
 * опубликованные хадисы (без ждущих устаза).
 *
 * Контракт: ПропсыЭкрана<'разделХадисов'> ({ номер }).
 * - Заголовок экрана — название раздела; над списком — путь от корня («Фикх › Фикх поклонения › …»).
 * - Подразделы — строки с числом хадисов → #/hadith/list?n=<id>.
 * - Хадисы раздела — строки (номер по порядку, заголовок перевода, «аль-Бухари · степень») → #/hadith/item?n=<id>.
 * - Неизвестный номер — «Такого раздела нет» и «К разделам».
 * - Плашка «Черновик — проверяет устаз» (правило 11); kk — строка о русском переводе.
 * testID: экран-раздел-хадисов, раздел-путь, раздел-подразделы, раздел-подраздел-<id>, раздел-хадисы, раздел-нет,
 *   раздел-к-разделам, раздел-черновик, раздел-нет-перевода, раздел-загрузка.
 */
import { View } from 'react-native';
import { Кнопка, Плашка, СтрокаСписка, Текст, Экран } from '../components';
import { useНавигация } from '../engine/navigation';
import type { ПропсыЭкрана } from '../engine/routes';
import { категория, названиеКатегории, подкатегории, путьКатегории, хадисыКатегории, useИндексХадисов } from '../hadith/data';
import { создатьСловарь, useПеревод, useСловарь } from '../i18n';
import { useТема } from '../theme';
import { СЛОВАРЬ_ХАДИСОВ, СписокХадисов, ХадисыНедоступны, useЗаголовкиЯзыка } from './hadith/common';

const СЛОВАРЬ = создатьСловарь({
  ru: { раздел: 'Раздел хадисов', подразделы: 'Подразделы', хадисы: 'Хадисы раздела', нет: 'Такого раздела нет.', кРазделам: 'К разделам хадисов' },
  kk: { раздел: 'Хадистер бөлімі', подразделы: 'Ішкі бөлімдер', хадисы: 'Бөлімдегі хадистер', нет: 'Мұндай бөлім жоқ.', кРазделам: 'Хадис бөлімдеріне' },
  uz: { раздел: 'Hadislar boʻlimi', подразделы: 'Ichki boʻlimlar', хадисы: 'Boʻlimdagi hadislar', нет: 'Bunday boʻlim yoʻq.', кРазделам: 'Hadis boʻlimlariga' },
  en: { раздел: 'Hadith section', подразделы: 'Subsections', хадисы: 'Hadiths in this section', нет: 'There is no such section.', кРазделам: 'To hadith sections' },
}, 'screens/HadithCategoryScreen');

export function РазделХадисов({ параметры }: ПропсыЭкрана<'разделХадисов'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тх = useСловарь(СЛОВАРЬ_ХАДИСОВ);
  const { перейти, перейтиВкладку } = useНавигация();
  const { отступ } = useТема();
  const индекс = useИндексХадисов();
  const заголовки = useЗаголовкиЯзыка(язык);
  const и = индекс.состояние === 'есть' ? индекс.данные : null;
  const к = и ? категория(и, параметры.номер) : null;
  const название = к ? названиеКатегории(к, язык) : т('раздел');
  const путь = и && к ? путьКатегории(и, к.id) : [];
  const дети = и && к ? подкатегории(и, к.id) : [];
  const хадисы = и && к ? хадисыКатегории(и, к.id) : [];

  return (
    <Экран заголовок={название} testID="экран-раздел-хадисов">
      {язык === 'kk' ? (
        <Текст вид="второй" testID="раздел-нет-перевода">
          {тх('запасной')}
        </Текст>
      ) : null}
      {индекс.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="раздел-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : индекс.состояние === 'нет' ? (
        <ХадисыНедоступны состояние={индекс} />
      ) : !к ? (
        <View style={{ gap: отступ.s }}>
          <Текст вид="второй" testID="раздел-нет">
            {т('нет')}
          </Текст>
          <Кнопка вид="вторичная" надпись={т('кРазделам')} приНажатии={() => перейтиВкладку('хадисы')} testID="раздел-к-разделам" />
        </View>
      ) : (
        <View style={{ gap: отступ.m }}>
          {путь.length > 1 ? (
            <Текст вид="мелкий" testID="раздел-путь">
              {путь.map((п) => названиеКатегории(п, язык)).join(' › ')}
            </Текст>
          ) : null}
          {дети.length ? (
            <View style={{ gap: отступ.s }} testID="раздел-подразделы">
              <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
                {т('подразделы')}
              </Текст>
              {дети.map((д) => (
                <СтрокаСписка
                  key={д.id}
                  заголовок={названиеКатегории(д, язык)}
                  подпись={тх('хадисов', { н: д.хадисов })}
                  значок="хадис"
                  приНажатии={() => перейти('разделХадисов', { номер: д.id })}
                  testID={'раздел-подраздел-' + д.id}
                />
              ))}
            </View>
          ) : null}
          {хадисы.length ? (
            <View style={{ gap: отступ.s }}>
              <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
                {т('хадисы')}
              </Текст>
              {заголовки.состояние.состояние === 'нет' ? (
                <ХадисыНедоступны состояние={{ ...заголовки.состояние, повторить: заголовки.повторить }} />
              ) : заголовки.состояние.состояние === 'загрузка' ? (
                <Текст вид="второй">{t('общее.загрузка')}</Текст>
              ) : (
                <СписокХадисов записи={хадисы} заголовки={заголовки.заголовки} testID="раздел-хадисы" />
              )}
            </View>
          ) : null}
        </View>
      )}
      <Плашка вид="черновик" надпись={тх('черновик')} testID="раздел-черновик" />
    </Экран>
  );
}
