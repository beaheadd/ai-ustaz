export function Главная(_: ПропсыЭкрана<'главная'>) {
  const { t, язык, языкВыбран, установитьЯзык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { цвет, отступ, радиус } = useТема();
  const курс = useДанные('course');
  const { место } = useМестоНамаза();
  const { широта, долгота } = место;
  // Время суток — строка; корень перерисуется, только когда она сменится (несколько раз в сутки).
  const времяСуток = useЧасы((мс) => {
    const сегодня = временаДняКэш({ широта, долгота }, деньРК(мс));
    return сегодня ? репликаПоВремени(фазаДня(мс, сегодня), часРК(мс)) : null;
  });
  const { приглашение, скрыть: скрытьПриглашение } = useПриглашениеПослеНамаза();
  const [предупреждениеОткрыто, установитьПредупреждение] = useState(false);

  // Первый вход: один раз за заход показать онбординг (язык, бесплатно, время намаза, прототип).
  const первыйВход = !языкВыбран && Object.keys(прогресс.уроки).length === 0 && !прогресс.предупреждениеПоказано;
  // Переход — после текущего кадра эффектов: ПоставщикНавигации пишет стартовую запись истории
  // в своём эффекте, который идёт ПОСЛЕ эффектов экрана; иначе он затёр бы #/onboarding.
  useEffect(() => {
    if (!первыйВход || онбордингПредлагался()) return;
    const таймер = setTimeout(() => {
      if (онбордингПредлагался()) return;
      отметитьОнбордингПредложен();
      перейти('онбординг');
    }, 0);
    return () => clearTimeout(таймер);
  }, [первыйВход, перейти]);

  const данныеКурса = курс.состояние === 'есть' ? курс.данные : null;
  const шаг = useMemo(() => следующийШаг(прогресс, номераУроков()), [прогресс]);

  // Пункт и этап курса для следующего урока (если карта курса загрузилась).
  const пунктШага = useMemo(() => {
    if (шаг.вид !== 'урок' || !данныеКурса) return null;
    for (const у of данныеКурса.уровни) {
      const п = у.пункты.find((п) => п.номер === шаг.номер);
      if (п) return { пункт: п, уровень: у };
    }
    return null;
  }, [шаг, данныеКурса]);

  const уровни: УровеньКурса[] = useMemo(() => данныеКурса?.уровни ?? [], [данныеКурса]);
  const этапы = useMemo(() => статусыЭтапов(уровни, прогресс), [уровни, прогресс]);
  const сводка = useMemo(() => сводкаПути(уровни, прогресс), [уровни, прогресс]);

  // В простое после показа — заранее подгрузить список мест и следующий урок (работают и без сети).
  const номерШага = шаг.вид === 'урок' ? шаг.номер : null;
  useEffect(() => {
    const таймер = setTimeout(() => {
      void загрузитьМеста().catch(() => undefined);
      if (номерШага !== null) void загрузитьУрок(номерШага).catch(() => undefined);
    }, 2000);
    return () => clearTimeout(таймер);
  }, [номерШага]);
  const названиеЭтапа = (уровень: number) => (уровень === 0 ? т('вход') : т('этапКоротко', { номер: уровень }));
  const iТекущего = этапы.indexOf('текущий');
  const текущийЭтап = iТекущего >= 0 ? уровни[iТекущего] : null;

  let надпись: string;
  let действие: () => void;
  let метка: string;
  let название: string | null = null;
  let шагРеплики: string;
  if (шаг.вид === 'урок0') {
    надпись = т('начатьУрок0');
    действие = () => перейти('урок0');
    метка = т('урок0');
    название = т('урок0Название');
    шагРеплики = т('шаг.урок0');
  } else if (шаг.вид === 'урок') {
    const м = меткаУрока(данныеКурса, шаг.номер);
    надпись = т(шаг.начат ? 'продолжитьУрок' : 'следующийУрок', { метка: м });
    const номер = шаг.номер;
    действие = () => перейти('урок', { номер });
    метка = т('урокМетка', { метка: м });
    название = пунктШага ? локально(пунктШага.пункт.название, язык) : null;
    шагРеплики = т(шаг.начат ? 'шаг.начат' : 'шаг.новый', { метка: м });
  } else {
    надпись = т('всёПройдено');
    действие = () => перейти('картаКурса');
    метка = т('всёМетка');
    шагРеплики = т('шаг.карта');
  }
  // Через 10–40 мин после начала намаза реплика — приглашение («После зухра — 5 минут урока?»), иначе — время суток.
  const начало = приглашение ? т('приглашение', { намаз: приглашение.названиеПосле }) : времяСуток ? т(`время.${времяСуток}`) : '';
  const реплика = (начало ? начало + ' ' : '') + шагРеплики;

  // Этап следующего урока — та же сводка, что на карте курса: «Этап 1: пройдено 1 из 17 уроков».
  const этапШага = пунктШага && сводка && сводка.этап.уровень === пунктШага.уровень.уровень ? сводка : null;

  return (
    <Экран
      заголовок={t('экран.главная')}
      плашка="общая"
      testID="экран-главная"
      справа={
        <Кнопка
          вид="тихая"
          растянуть={false}
          значок="язык"
          надпись={т('языкКратко')}
          подсказка={т('языкПодсказка')}
          приНажатии={() => установитьЯзык(язык === 'ru' ? 'kk' : 'ru')}
          testID="главная-язык"
        />
      }
    >
      {/* 1. Время намаза — вверху (решение владельца 19.11.2026). */}
      <КарточкаНамаза перейтиКНамазу={() => перейти('намаз')} перейтиККибле={() => перейти('кибла')} арабские={false} />

      {/* 2. Урок: AI Ustaz и одна основная кнопка; после намаза реплика — приглашение и «Не сейчас». */}
      <Карточка вид="арка" testID="главная-урок">
        <РепликаУстаза состояние="покой" testID="главная-реплика">
          {реплика}
        </РепликаУстаза>
        <View style={{ gap: отступ.xs }}>
          <Текст вид="метка" цвет={цвет.золотоТекст} testID="главная-этап">
            {этапШага ? т('этап', { номер: этапШага.этап.уровень, пройдено: этапШага.пройдено, всего: этапШага.всего }) : метка}
          </Текст>
          {этапШага ? <Текст вид="подзаголовок">{метка}</Текст> : null}
          {название ? (
            <СмешанныйТекст вид="второй" testID="главная-название-урока">
              {название}
            </СмешанныйТекст>
          ) : null}
        </View>
        <Кнопка надпись={надпись} крупная приНажатии={действие} testID="главная-начать" />
        {приглашение ? (
          <View style={{ flexDirection: 'row', justifyContent: 'center' }}>
            <Кнопка вид="тихая" надпись={т('неСейчас')} растянуть={false} приНажатии={скрытьПриглашение} testID="главная-не-сейчас" />
          </View>
        ) : null}
      </Карточка>

      {/* 3. Путь обучения → карта курса. */}
      <Карточка приНажатии={() => перейти('картаКурса')} testID="главная-карта">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          <Значок имя="карта" размер={22} цвет={цвет.акцент} />
          <View style={{ flex: 1 }}>
            <Текст вид="подзаголовок" accessibilityRole="header">
              {т('путь')}
            </Текст>
            <Текст вид="мелкий">{т('путьДевиз')}</Текст>
          </View>
          <Значок имя="вперёд" размер={20} цвет={цвет.акцент} подпись={т('путьКарта')} />
        </View>
        {уровни.length > 1 ? <ОбзорЭтапов уровни={уровни} этапы={этапы} названия={уровни.map((у) => названиеЭтапа(у.уровень))} testID="главная-обзор" /> : null}
        {текущийЭтап ? (
          <СмешанныйТекст вид="мелкий">{т('сейчасНаПути', { этап: локально(текущийЭтап.название, язык) })}</СмешанныйТекст>
        ) : null}
      </Карточка>

      <СтрокаСписка заголовок={т('как')} подпись={т('какПояснение')} значок="нукта" приНажатии={() => перейти('какОбъясняем')} testID="главная-как" />

      <ДниЗанятий />

      {/* 4. «Скоро»: модули без контента — только название и что в них будет (≤ 25 % внимания). */}
      <View style={{ gap: отступ.s }} testID="главная-скоро">
        <View style={{ gap: 2 }}>
          <Текст вид="подзаголовок" accessibilityRole="header">
            {т('скоро')}
          </Текст>
          <Текст вид="мелкий">{т('скороПояснение')}</Текст>
        </View>
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: отступ.s }}>
          {МОДУЛИ.map(({ ключ, значок }) => (
            <View
              key={ключ}
              testID={'главная-скоро-' + ключ}
              accessible
              accessibilityLabel={`${т(`модуль.${ключ}`)}, ${т('скороМетка')}. ${т(`модуль.${ключ}Пояснение`)}`}
              style={{
                flexBasis: '47%',
                flexGrow: 1,
                minHeight: 96,
                padding: отступ.m,
                gap: отступ.xs,
                borderRadius: радиус.l,
                borderWidth: 1,
                borderStyle: 'dashed',
                borderColor: цвет.граница,
                backgroundColor: цвет.поверхностьВторая,
              }}
            >
              <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between', gap: отступ.xs }}>
                <Значок имя={значок} размер={22} цвет={цвет.текстВторой} />
                <Плашка вид="скоро" надпись={т('скороМетка')} />
              </View>
              <Текст вид="метка">{т(`модуль.${ключ}`)}</Текст>
              <Текст вид="мелкий">{т(`модуль.${ключ}Пояснение`)}</Текст>
            </View>
          ))}
        </View>
      </View>

      {/* 5. О проекте, ИИ-предупреждение (QML — всегда доступно), лицензии, «Это прототип» → «О проекте». */}
      <View style={{ gap: отступ.s }}>
        <СтрокаСписка
          заголовок={т('оПроекте')}
          подпись={т('оПроектеПояснение')}
          значок="хатам"
          приНажатии={() => перейти('оПроекте')}
          testID="главная-о-проекте"
        />
        <СтрокаСписка
          заголовок={т('предупреждение')}
          подпись={т('предупреждениеПояснение')}
          значок="инфо"
          раскрыт={предупреждениеОткрыто}
          приНажатии={() => установитьПредупреждение((о) => !о)}
          testID="главная-предупреждение"
        />
        {предупреждениеОткрыто ? <ПредупреждениеИИИзКонтента testID="главная-текст-предупреждения" /> : null}
        <СтрокаСписка
          заголовок={т('лицензии')}
          подпись={т('лицензииПояснение')}
          значок="меню"
          приНажатии={() => перейти('лицензии')}
          testID="главная-лицензии"
        />
        <СтрокаСписка
          заголовок={т('прототип')}
          подпись={т('прототипПояснение')}
          значок="инфо"
          приНажатии={() => перейти('оПроекте')}
          testID="главная-прототип"
        />
      </View>

      {/* 6. Язык и оформление. */}
      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('настройки')}
        </Текст>
        <Текст вид="мелкий">{т('язык')}</Текст>
        <ПереключательЯзыка />
        <Текст вид="мелкий">{т('тема')}</Текст>
        <ПереключательТемы />
      </View>
    </Экран>
  );
}
