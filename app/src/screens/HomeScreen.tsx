  const узко = useWindowDimensions().width < 390;

  // Выбрали язык в панели — панель закрывается сама.
  useEffect(() => установитьЯзыкОткрыт(false), [язык]);

  // Первый вход: онбординг «Язык · Место · Расчёт · Уведомления» (владелец 28.11.2026), пока его не прошли. Кто уже
