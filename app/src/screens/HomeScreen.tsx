/**
 * Главная. Объясняет, что это прототип и чего в нём пока нет; ведёт в онбординг или курс.
 * Заглушка каркаса: экран может быть заменён (контракт — ПропсыЭкрана<'главная'>).
 */
import { View } from 'react-native';
import { Карточка, Кнопка, ПереключательЯзыка, Текст, Экран } from '../components';
import { useНавигация } from '../engine/navigation';
import { днейЗанятийЗа, useПрогресс } from '../engine/progress';
import type { ПропсыЭкрана } from '../engine/routes';
import { useПеревод } from '../i18n';
import { useТема } from '../theme';

export function Главная(_: ПропсыЭкрана<'главная'>) {
  const { t } = useПеревод();
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { отступ } = useТема();
  const дней = днейЗанятийЗа(прогресс, 30);
  const начато = Object.keys(прогресс.уроки).length > 0;
  const пункты = [
    t('главная.прототип.голос'),
    t('главная.прототип.кари'),
    t('главная.прототип.черновик'),
    t('главная.прототип.данные'),
    t('главная.прототип.бесплатно'),
  ];

  return (
    <Экран заголовок={t('экран.главная')} плашка="общая" testID="экран-главная">
      <Текст вид="второй">{t('главная.подзаголовок')}</Текст>

      <Карточка акцент заголовок={t('главная.прототип.заголовок')} testID="главная-прототип">
        <Текст>{t('главная.прототип.вступление')}</Текст>
        <View style={{ gap: отступ.s }}>
          {пункты.map((пункт) => (
            <View key={пункт} style={{ flexDirection: 'row', gap: отступ.s }}>
              <Текст accessibilityElementsHidden importantForAccessibility="no">•</Текст>
              <Текст стиль={{ flex: 1 }}>{пункт}</Текст>
            </View>
          ))}
        </View>
      </Карточка>

      <Кнопка
        надпись={начато ? t('главная.продолжить') : t('главная.начать')}
        крупная
        приНажатии={() => перейти(начато ? 'картаКурса' : 'онбординг')}
        testID="главная-начать"
      />
      <Кнопка надпись={t('главная.картаКурса')} вид="вторичная" приНажатии={() => перейти('картаКурса')} testID="главная-карта" />
      <Кнопка надпись={t('главная.какОбъясняем')} вид="тихая" приНажатии={() => перейти('какОбъясняем')} testID="главная-как" />
      <Кнопка надпись={t('главная.оПроекте')} вид="тихая" приНажатии={() => перейти('оПроекте')} testID="главная-о-проекте" />

      {дней > 0 ? <Текст вид="мелкий">{t('главная.дниЗанятий', { дней })}</Текст> : null}
      <ПереключательЯзыка />
    </Экран>
  );
}
