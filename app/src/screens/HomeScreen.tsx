export type СледующийШаг = { вид: 'урок0' } | { вид: 'урок'; номер: number; начат: boolean } | { вид: 'карта' };

/** Куда ведёт «Продолжить» (чистая функция). номера — уроки, у которых есть файл. */
export function следующийШаг(п: Прогресс, номера: number[]): СледующийШаг {
  if (!п.уроки['0']?.пройден && !п.предупреждениеПоказано) return { вид: 'урок0' };
  // Ряды курса: уроки 1–99, затем контрольные (101+); прочие номера не предлагаем.
  const порядок = номера.filter((н) => н >= 1 && н < 200).sort((а, б) => а - б);
  for (const номер of порядок) {
    const итог = п.уроки[String(номер)];
    if (!итог?.пройден) return { вид: 'урок', номер, начат: (итог?.попыток ?? 0) > 0 };
  }
  return { вид: 'карта' };
}

export type ВремяСуток = 'утро' | 'день' | 'вечер' | 'ночь' | 'доФаджра';

/**
 * Время суток для реплики AI Ustaz — по часам места и фазе дня (последнее наступившее время намаза). Чистая функция.
 * Фаджр и восход — утро (летом на севере фаджр бывает около 02:30); 22:00–03:59 — ночь; 04:00 до фаджра —
 * «до фаджра»; зухр и аср — день; магриб и иша до 22:00 — вечер (зимой иша начинается около 18:00).
 */
export function репликаПоВремени(фаза: КлючВремени, час: number): ВремяСуток {
  if (фаза === 'fajr' || фаза === 'sunrise') return 'утро';
  if (час >= 22 || час < 4) return 'ночь';
  if (фаза === 'isha' && час < 12) return 'доФаджра';
  if (фаза === 'dhuhr' || фаза === 'asr') return 'день';
  return 'вечер';
}

/** Подпись урока на кнопке: метка с карты курса ('3', 'К1'); без карты — по номеру. */
function меткаУрока(курс: КартаКурсаДанные | null, номер: number): string {
  for (const у of курс?.уровни ?? []) {
    const п = у.пункты.find((п) => п.номер === номер);
    if (п) return п.метка;
  }
  return номер > 100 ? 'К' + (номер - 100) : String(номер);
}

