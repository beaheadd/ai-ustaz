export type СледующийШаг = { вид: 'урок0' } | { вид: 'урок'; номер: number; начат: boolean } | { вид: 'карта' };

/** Куда ведёт «Продолжить» (чистая функция). номера — уроки, у которых есть файл. */
export function следующийШаг(п: Прогресс, номера: number[]): СледующийШаг {
  if (!п.уроки['0']?.пройден && !п.предупреждениеПоказано) return { вид: 'урок0' };
  // Ряды курса: уроки 1–99, затем контрольные (101+); прочие номера не предлагаем.
  const порядок = номера.filter((н) => н >= 1 && н < 200).sort((а, б) => а - б);
  for (const номер of порядок) {
    const итог = п.уроки[String(номер)];
    if (!итог?.пройден) return { вид: 'урок', номер, начат: (итог?.попыток ?? 0) > 0 };
  }
  return { вид: 'карта' };
}

/** Подпись урока на кнопке: метка с карты курса ('3', 'К1'); без карты — по номеру. */
function меткаУрока(курс: КартаКурсаДанные | null, номер: number): string {
  for (const у of курс?.уровни ?? []) {
    const п = у.пункты.find((п) => п.номер === номер);
    if (п) return п.метка;
  }
  return номер > 100 ? 'К' + (номер - 100) : String(номер);
}

export function Главная(_: ПропсыЭкрана<'главная'>) {
  const { t, язык, языкВыбран } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { отступ } = useТема();
  const курс = useДанные('course');
  const [предупреждениеОткрыто, установитьПредупреждение] = useState(false);

  // Первый вход: один раз за заход показать онбординг (язык, бесплатно, прототип).
  const первыйВход = !языкВыбран && Object.keys(прогресс.уроки).length === 0 && !прогресс.предупреждениеПоказано;
  // Переход — после текущего кадра эффектов: ПоставщикНавигации пишет стартовую запись истории
  // в своём эффекте, который идёт ПОСЛЕ эффектов экрана; иначе он затёр бы #/onboarding.
  useEffect(() => {
    if (!первыйВход || онбордингПредлагался()) return;
    const таймер = setTimeout(() => {
      if (онбордингПредлагался()) return;
      отметитьОнбордингПредложен();
      перейти('онбординг');
    }, 0);
    return () => clearTimeout(таймер);
  }, [первыйВход, перейти]);

  const данныеКурса = курс.состояние === 'есть' ? курс.данные : null;
  const шаг = useMemo(() => следующийШаг(прогресс, номераУроков()), [прогресс]);
  const названиеШага = useMemo(() => {
    if (шаг.вид !== 'урок' || !данныеКурса) return null;
    for (const у of данныеКурса.уровни) {
      const п = у.пункты.find((п) => п.номер === шаг.номер);
      if (п) return локально(п.название, язык);
    }
    return null;
  }, [шаг, данныеКурса, язык]);

  const пункты = [
    t('главная.прототип.голос'),
    t('главная.прототип.кари'),
    t('главная.прототип.черновик'),
    t('главная.прототип.данные'),
    t('главная.прототип.бесплатно'),
  ];

  let надпись: string;
  let действие: () => void;
  if (шаг.вид === 'урок0') {
    надпись = т('начатьУрок0');
    действие = () => перейти('урок0');
  } else if (шаг.вид === 'урок') {
    const метка = меткаУрока(данныеКурса, шаг.номер);
    надпись = т(шаг.начат ? 'продолжитьУрок' : 'следующийУрок', { метка });
    const номер = шаг.номер;
    действие = () => перейти('урок', { номер });
  } else {
    надпись = т('всёПройдено');
    действие = () => перейти('картаКурса');
  }

  return (
    <Экран заголовок={t('экран.главная')} плашка="общая" testID="экран-главная">
      <Текст вид="второй">{t('главная.подзаголовок')}</Текст>

      <View style={{ gap: отступ.xs }}>
        <Кнопка надпись={надпись} крупная приНажатии={действие} testID="главная-начать" />
        {названиеШага ? (
          <СмешанныйТекст вид="мелкий" стиль={{ textAlign: 'center' }} testID="главная-название-урока">
            {названиеШага}
          </СмешанныйТекст>
        ) : null}
      </View>

      <Карточка акцент заголовок={t('главная.прототип.заголовок')} testID="главная-прототип">
        <Текст>{t('главная.прототип.вступление')}</Текст>
        <Пункты пункты={пункты} />
      </Карточка>

      <View style={{ gap: отступ.s }}>
        <Текст вид="подзаголовок" accessibilityRole="header">
          {т('курс')}
        </Текст>
        <ПунктМеню
          надпись={t('главная.картаКурса')}
          пояснение={т('картаПояснение')}
          значок="☰"
          приНажатии={() => перейти('картаКурса')}
          testID="главная-карта"
        />
        <ПунктМеню надпись={т('как')} пояснение={т('какПояснение')} значок="✎" приНажатии={() => перейти('какОбъясняем')} testID="главная-как" />
        <ПунктМеню
          надпись={т('предупреждение')}
          пояснение={т('предупреждениеПояснение')}
          значок="!"
          раскрыт={предупреждениеОткрыто}
          приНажатии={() => установитьПредупреждение((о) => !о)}
          testID="главная-предупреждение"
        />
        {предупреждениеОткрыто ? <ПредупреждениеИИИзКонтента testID="главная-текст-предупреждения" /> : null}
        <ПунктМеню надпись={т('оПроекте')} пояснение={т('оПроектеПояснение')} значок="i" приНажатии={() => перейти('оПроекте')} testID="главная-о-проекте" />
        <ПунктМеню
          надпись={т('лицензии')}
          пояснение={т('лицензииПояснение')}
          значок="©"
          приНажатии={() => перейти('лицензии')}
          testID="главная-лицензии"
        />
      </View>

      <ДниЗанятий />

      <ЧтоЕстьЧтоБудет />

      <View style={{ gap: отступ.s }}>
        <Текст вид="мелкий">{т('язык')}</Текст>
        <ПереключательЯзыка />
      </View>

      <View style={{ gap: отступ.s }}>
        <Текст вид="мелкий">{т('тема')}</Текст>
        <ПереключательТемы />
      </View>
    </Экран>
  );
}
