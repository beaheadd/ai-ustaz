export function Коран(_: ПропсыЭкрана<'коран'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти, перейтиВкладку } = useНавигация();
  const { цвет, отступ, радиус } = useТема();
  const индекс = useИндексСур();
  const [запрос, установитьЗапрос] = useState('');
  const [вФокусе, установитьФокус] = useState(false);
  const [чтение, установитьЧтение] = useState<МестоЧтения | null>(null);
  const закладка = useЗакладка();
  // Суры или джузы (владелец 27.11.2026: «добавить джузы, чтобы можно было выбрать между сурами и джузами»).
  const [видСписка, установитьВидСписка] = useState<'суры' | 'джузы'>('суры');

  useEffect(() => {
    let живой = true;
    void прочитатьЧтение().then((м) => {
      if (живой) установитьЧтение(м);
    });
    return () => {
      живой = false;
    };
  }, []);

  const суры = индекс.состояние === 'есть' ? индекс.данные.суры : null;
  const найдено = useMemo(() => (суры ? подходящиеСуры(суры, запрос) : null), [суры, запрос]);
  const переход = useMemo(() => разобратьПереход(запрос), [запрос]);
  const записьПерехода = переход && суры ? суры[переход.сура - 1] : null;
  const переходВозможен = !!(переход && записьПерехода && переход.аят <= записьПерехода.аятов);

  function открытьПереход() {
    if (переход && переходВозможен) перейти('сура', { номер: переход.сура, аят: переход.аят });
  }

  const записьЧтения = чтение && суры ? суры[чтение.сура - 1] : null;
  const джузы = индекс.состояние === 'есть' ? индекс.данные.джузы : [];
  const безПоиска = !запрос.trim();
  /** «стр. 562 · 30 аятов · мекканская» — деление мусхафа из Tanzil Quran Metadata. */
  const мета = (з: ЗаписьСуры) =>
    [з.страница ? т('страница', { н: з.страница }) : null, словоАятов(з.аятов, язык), з.тип ? т(з.тип) : null].filter(Boolean).join(' · ');
  const поле = useRef<ComponentRef<typeof TextInput>>(null);

  // «Назад» из суры: список прокручен к ней, фокус — на её строке (а не на заголовке и не в начале списка).
  const [возврат] = useState(взятьВозвратКСуре);
  useEffect(() => {
    if (возврат === null || !суры || !ВЕБ || typeof document === 'undefined') return;
    const таймер = setTimeout(() => {
      const э = document.querySelector<HTMLElement>(`[data-testid="коран-сура-${возврат}"]`);
      э?.scrollIntoView({ block: 'center' });
      э?.focus({ preventScroll: true });
    }, 120);
    return () => clearTimeout(таймер);
  }, [возврат, суры]);

  function открытьСуру(номер: number) {
    запомнитьВозвратКСуре(номер);
    перейти('сура', { номер });
  }

  return (
    <Экран заголовок={t('экран.коран')} testID="экран-коран">
      {/* «Суры | Джузы» — сразу под шапкой, компактно (владелец 28.11.2026: «меньше сделай блок и на самом верху
          поставь ниже шапки»). */}
      {безПоиска && джузы.length === 30 ? (
        <View
          testID="коран-вид"
          {...(ВЕБ ? ({ role: 'tablist', 'aria-label': т('вид') } as object) : null)}
          style={{ flexDirection: 'row', padding: 3, borderRadius: радиус.m, backgroundColor: цвет.поверхностьВторая, gap: 3 }}
        >
          {(['суры', 'джузы'] as const).map((в) => (
            <Pressable
              key={в}
              accessibilityRole="tab"
              {...(ВЕБ ? ({ 'aria-selected': видСписка === в } as object) : { accessibilityState: { selected: видСписка === в } })}
              onPress={() => установитьВидСписка(в)}
              testID={'коран-вид-' + в}
              style={{ flex: 1, minHeight: 38, borderRadius: радиус.s, alignItems: 'center', justifyContent: 'center', backgroundColor: видСписка === в ? цвет.поверхность : 'transparent' }}
            >
              <Текст вид="метка" цвет={видСписка === в ? цвет.акцент : цвет.текстВторой}>
                {т(в)}
              </Текст>
            </Pressable>
          ))}
        </View>
      ) : null}
      {/* Где остановился (запоминается само при чтении; владелец 27.11.2026) — первым, затем закладка. */}
      {чтение && суры && записьЧтения && чтение.аят <= записьЧтения.аятов ? (
        <СтрокаСписка
          заголовок={т('продолжить')}
          подпись={т('продолжитьГде', { сура: названиеСуры(записьЧтения, чтение.сура, язык), аят: чтение.аят })}
          значок="коран"
          приНажатии={() => перейти('сура', { номер: чтение.сура, аят: чтение.аят })}
          testID="коран-продолжить"
        />
      ) : null}

      {/* Закладка (владелец 21.11.2026: «сохранить, чтобы, когда хотел продолжить, мог начать с этого места») — её
          человек поставил сам кнопкой «Сохранить закладку» у аята. */}
      {закладка && суры && суры[закладка.сура - 1] && закладка.аят <= суры[закладка.сура - 1].аятов ? (
        <СтрокаСписка
          заголовок={т('закладка')}
          подпись={т('продолжитьГде', { сура: названиеСуры(суры[закладка.сура - 1], закладка.сура, язык), аят: закладка.аят })}
          значок="закладкаЕсть"
          приНажатии={() => перейти('сура', { номер: закладка.сура, аят: закладка.аят })}
          testID="коран-закладка"
        />
      ) : null}
      {индекс.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="коран-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : индекс.состояние === 'нет' ? (
        <ТекстКоранаНедоступен состояние={индекс} />
      ) : (
        <View style={{ gap: отступ.m }}>
          <Pressable
            // Нажатие по всему полю (и по значку) ставит курсор в поиск.
            onPress={() => поле.current?.focus()}
            accessible={false}
            {...(ВЕБ ? ({ tabIndex: -1 } as object) : null)}
            style={{
              flexDirection: 'row',
              alignItems: 'center',
              gap: отступ.s,
              minHeight: 52,
              paddingHorizontal: вФокусе ? отступ.m - 1 : отступ.m,
              borderRadius: радиус.m,
              borderWidth: вФокусе ? 2 : 1,
              borderColor: вФокусе ? цвет.фокус : цвет.границаЭлемента,
              backgroundColor: цвет.поверхность,
            }}
          >
            <Значок имя="поиск" размер={20} цвет={цвет.текстВторой} />
            <TextInput
              ref={поле}
              value={запрос}
              onChangeText={установитьЗапрос}
              onFocus={() => установитьФокус(true)}
              onBlur={() => установитьФокус(false)}
              onSubmitEditing={открытьПереход}
              placeholder={т('поиск')}
              placeholderTextColor={цвет.текстВторой}
              accessibilityLabel={т('поискПодпись')}
              autoCorrect={false}
              autoCapitalize="none"
              inputMode="search"
              enterKeyHint="go"
              testID="коран-поиск"
              style={{
                flex: 1,
                minWidth: 0,
                minHeight: 48,
                fontFamily: ШРИФТ_ИНТЕРФЕЙСА,
                fontSize: 16,
                color: цвет.текст,
                ...(ВЕБ ? ({ outlineStyle: 'none' } as object) : null),
              }}
            />
          </Pressable>

          {/* Диктору — сколько нашлось (polite, только при запросе); глазами это видно по списку. */}
          <Текст
            testID="коран-найдено"
            accessibilityLiveRegion="polite"
            {...(ВЕБ ? ({ role: 'status' } as object) : null)}
            стиль={стильСкрытого}
          >
            {запрос.trim() && найдено && !переход ? т('найдено', { н: найдено.length }) : ''}
          </Текст>


          {безПоиска && видСписка === 'джузы' && суры && джузы.length === 30 ? (
            <View
              testID="коран-джузы"
              {...(ВЕБ ? { role: 'list' as const } : {})}
              style={{ borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность, overflow: 'hidden' }}
            >
              {джузы.map(([сура, аят], i) => (
                <View key={i} {...(ВЕБ ? { role: 'listitem' as const } : {})} style={{ borderBottomWidth: i === 29 ? 0 : 1, borderBottomColor: цвет.граница }}>
                  <Pressable
                    accessibilityRole="link"
                    onPress={() => перейти('сура', { номер: сура, аят })}
                    testID={'коран-джуз-' + (i + 1)}
                    style={({ pressed }) => ({ flexDirection: 'row', alignItems: 'center', gap: отступ.m, minHeight: 64, paddingHorizontal: отступ.m, paddingVertical: отступ.xs, backgroundColor: pressed ? цвет.акцентМягкий : 'transparent' })}
                  >
                    <View style={{ width: 40, height: 40, borderRadius: радиус.круг, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.акцент }}>
                      <Текст вид="метка" цвет={цвет.акцентТекст} табличные>
                        {String(i + 1)}
                      </Текст>
                    </View>
                    <View style={{ flex: 1, minWidth: 0 }}>
                      <Текст стиль={{ fontWeight: '600' }}>{т('джуз', { н: i + 1 })}</Текст>
                      <Текст вид="мелкий" numberOfLines={2} testID={`коран-джуз-${i + 1}-начало`}>
                        {т('джузНачало', { сура: названиеСуры(суры[сура - 1], сура, язык), аят })}
                      </Текст>
                    </View>
                    <АрабскийТекст размер="малый" выравнивание="right" стиль={{ lineHeight: 40, flexShrink: 0 }}>
                      {суры[сура - 1].имя}
                    </АрабскийТекст>
                  </Pressable>
                </View>
              ))}
            </View>
          ) : null}

          {переход && записьПерехода ? (
            переходВозможен ? (
              <СтрокаСписка
                заголовок={т('перейти', { сура: переход.сура, аят: переход.аят })}
                подпись={т('перейтиПодпись', { название: названиеСуры(записьПерехода, переход.сура, язык), аят: переход.аят })}
                значок="вперёд"
                приНажатии={открытьПереход}
                testID="коран-перейти"
              />
            ) : (
              <Текст вид="второй" testID="коран-нет-аята-поиск" accessibilityLiveRegion="polite">
                {т('нетАята', { сура: переход.сура, аятов: словоАятов(записьПерехода.аятов, язык) })}
              </Текст>
            )
          ) : null}

          {найдено && найдено.length === 0 && !переход ? (
            <Текст вид="второй" testID="коран-ничего" accessibilityLiveRegion="polite">
              {т('ничего')}
            </Текст>
          ) : null}

          {найдено && найдено.length > 0 && !переход && !(безПоиска && видСписка === 'джузы' && джузы.length === 30) ? (
            <View style={{ flexDirection: 'row', gap: 6, alignItems: 'flex-start' }}>
              {/* Столбик джузов 1…30 убран (владелец 28.11.2026: «с левой стороны цифры джузов убери»); джузы — вкладка «Джузы». */}
              <View
                testID="коран-список"
                {...(ВЕБ ? { role: 'list' as const } : {})}
                style={{ flex: 1, minWidth: 0, borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность, overflow: 'hidden' }}
              >
                {найдено.map((запись, i) => {
                  // Заголовок «Джуз N» — перед сурой, первый аят которой в новом джузе (как в мусхафе-оглавлении).
                  const новыйДжуз = безПоиска && запись.джуз && (i === 0 || найдено[i - 1].джуз !== запись.джуз) ? запись.джуз : null;
                  return (
                    <View key={запись.сура}>
                      {новыйДжуз ? (
                        <View
                          testID={'коран-джуз-заголовок-' + новыйДжуз}
                          {...(ВЕБ ? ({ role: 'heading', 'aria-level': 3 } as object) : null)}
                          style={{ paddingHorizontal: отступ.m, paddingTop: отступ.s, paddingBottom: 4, backgroundColor: цвет.поверхностьВторая }}
                        >
                          <Текст вид="метка" цвет={цвет.текстВторой}>
                            {т('джуз', { н: новыйДжуз })}
                          </Текст>
                        </View>
                      ) : null}
                      <СтрокаСуры запись={запись} язык={язык} мета={мета(запись)} последняя={i === найдено.length - 1} приНажатии={открытьСуру} />
                    </View>
                  );
                })}
              </View>
            </View>
          ) : null}
        </View>
      )}

      <СтрокаСоЗначком значок="инфо" вид="мелкий" текст={т('перевод')} testID="коран-перевод" />
      <Текст вид="мелкий" testID="коран-источник">
        {т('источник')}
      </Текст>
      <СтрокаСписка заголовок={т('лицензии')} подпись={т('лицензииПояснение')} значок="меню" приНажатии={() => перейти('лицензии')} testID="коран-лицензии" />
      <СтрокаСписка заголовок={т('как')} подпись={т('какПояснение')} значок="нукта" приНажатии={() => перейти('какОбъясняем')} testID="коран-как" />
      <Кнопка вид="вторичная" значок="таджвид" надпись={т('кУрокам')} приНажатии={() => перейтиВкладку('таджвид')} testID="коран-к-урокам" />
      <Плашка вид="черновик" надпись={т('черновик')} testID="коран-черновик" />
      {/* Выбор чтеца при первом заходе (владелец 27.11.2026: «пусть слушают аль-Фатиху и выбирают чтеца»); один раз. */}
      <ПервыйВыборЧтеца />
    </Экран>
  );
}

/** Скрыт глазами, читается диктором (live-регион). */
const стильСкрытого = {
  position: 'absolute' as const,
  width: 1,
  height: 1,
  overflow: 'hidden' as const,
  opacity: 0,
};

/** Строка суры: элемент списка → ссылка «#/quran/sura?n=N». Номер · транслитерация и число аятов · арабское имя. */
const СтрокаСуры = memo(function СтрокаСуры({
  запись,
  язык,
  мета,
  последняя,
  приНажатии,
}: {
  запись: ЗаписьСуры;
  язык: string;
  /** «стр. 562 · 30 аятов · мекканская» — вместо одного числа аятов. */
  мета: string;
  последняя: boolean;
  приНажатии: (номер: number) => void;
}) {
  const { цвет, отступ, радиус } = useТема();
  const н = запись.сура;
  const естьИмя = !!(запись.транслит as Record<string, string | null>)[язык];
  const название = естьИмя ? названиеСуры(запись, н, язык) : null;
  const аятов = словоАятов(запись.аятов, язык);
  const подпись = название ? `${название}, ${аятов}` : `${названиеСуры(запись, н, язык)}, ${аятов}`;
  const ссылка = вХэш({ экран: 'сура', параметры: { номер: н } });
  return (
    <View {...(ВЕБ ? { role: 'listitem' as const } : {})} style={{ flexDirection: 'row', alignItems: 'center', borderBottomWidth: последняя ? 0 : 1, borderBottomColor: цвет.граница }}>
      <Pressable
        accessibilityRole="link"
        accessibilityLabel={подпись}
        {...(ВЕБ
          ? ({
              href: ссылка,
              // Пробел ссылку не открывает (так у браузера) — открываем сами, как Enter.
              onKeyDown: (е: { key: string; preventDefault: () => void }) => {
                if (е.key === ' ' || е.key === 'Spacebar') {
                  е.preventDefault();
                  приНажатии(н);
                }
              },
            } as object)
          : null)}
        onPress={(е) => {
          const с = е as unknown as { metaKey?: boolean; ctrlKey?: boolean; shiftKey?: boolean; altKey?: boolean; preventDefault?: () => void };
          if (с.metaKey || с.ctrlKey || с.shiftKey || с.altKey) return; // новая вкладка/окно — пусть делает браузер
          с.preventDefault?.();
          приНажатии(н);
        }}
        testID={'коран-сура-' + н}
        style={({ pressed, hovered }: { pressed: boolean; hovered?: boolean }) => ({
          flex: 1,
          minWidth: 0,
          flexDirection: 'row',
          alignItems: 'center',
          gap: отступ.m,
          minHeight: 64,
          paddingHorizontal: отступ.m,
          paddingVertical: отступ.xs,
          backgroundColor: pressed ? цвет.акцентМягкий : hovered ? цвет.поверхностьВторая : 'transparent',
          ...(ВЕБ ? ({ textDecorationLine: 'none' } as object) : null),
        })}
      >
        <View
          style={{ width: 40, height: 40, borderRadius: радиус.круг, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.поверхностьАкцент }}
        >
          <Текст вид="метка" цвет={цвет.акцент} табличные>
            {String(н)}
          </Текст>
        </View>
        <View style={{ flex: 1, minWidth: 0 }}>
          {название ? (
            <>
              <Текст numberOfLines={1} стиль={{ fontWeight: '600' }} testID={`коран-сура-${н}-транслит`}>
                {название}
              </Текст>
              <Текст вид="мелкий" табличные testID={`коран-сура-${н}-мета`}>
                {мета}
              </Текст>
            </>
          ) : (
            // kk: транслитерации нет — без дубля «N-сүре» рядом с кружком N.
            <Текст табличные testID={`коран-сура-${н}-транслит`}>
              {мета}
            </Текст>
          )}
        </View>
        <АрабскийТекст размер="малый" выравнивание="right" testID={`коран-сура-${н}-имя`} стиль={{ lineHeight: 40, flexShrink: 0 }}>
          {запись.имя}
        </АрабскийТекст>
      </Pressable>
      <View style={{ paddingEnd: 4 }}>
        <КнопкаСкачатьСуру сура={н} подпись={подпись} />
      </View>
    </View>
  );
});
