/** Ключ хранения (storage.ts сам добавит «aiustaz:»): aiustaz:zakat.v1. */
const КЛЮЧ = 'zakat.v1';

type ИмяПоля = 'наличные' | 'счета' | 'золотоГ' | 'ценаЗолота' | 'сереброГ' | 'ценаСеребра' | 'товары' | 'долгиВам' | 'вашиДолги';
const ПОЛЯ: readonly ИмяПоля[] = ['наличные', 'счета', 'золотоГ', 'ценаЗолота', 'сереброГ', 'ценаСеребра', 'товары', 'долгиВам', 'вашиДолги'];
/** Знаков после запятой: граммы — до 3, тенге — до 2. */
const ЗНАКОВ: Record<ИмяПоля, number> = { наличные: 2, счета: 2, золотоГ: 3, ценаЗолота: 2, сереброГ: 3, ценаСеребра: 2, товары: 2, долгиВам: 2, вашиДолги: 2 };

/** вручную — человек открыл «Изменить цену вручную»: считаем по его полям цены, а не по ценам с сервера. */
type Сохранённое = { версия: 1; поля: Record<ИмяПоля, string>; нисабПо: МеталлНисаба; хауль: boolean; вручную: boolean };

const ПУСТЫЕ_ПОЛЯ = Object.fromEntries(ПОЛЯ.map((п) => [п, ''])) as Record<ИмяПоля, string>;
const ПУСТО: Сохранённое = { версия: 1, поля: ПУСТЫЕ_ПОЛЯ, нисабПо: 'серебро', хауль: false, вручную: false };

/** Сохранённое из хранилища → проверенное (кривое — пусто; лишнее отбрасываем; строки — снова через очиститьВвод). */
function разобратьСохранённое(сырое: unknown): Сохранённое {
  if (!сырое || typeof сырое !== 'object') return ПУСТО;
  const с = сырое as Partial<Сохранённое>;
  if (с.версия !== 1) return ПУСТО;
  const поля = { ...ПУСТЫЕ_ПОЛЯ };
  for (const п of ПОЛЯ) {
    const з = с.поля?.[п];
    if (typeof з === 'string') поля[п] = очиститьВвод(з, ЗНАКОВ[п]);
  }
  return { версия: 1, поля, нисабПо: с.нисабПо === 'золото' ? 'золото' : 'серебро', хауль: с.хауль === true, вручную: с.вручную === true };
}

/** Веб — читаем сразу (без мигания пустой формы); натив — после AsyncStorage. */
function прочитатьСразу(): Сохранённое | null {
  if (!ВЕБ) return null;
  try {
    const строка = globalThis.localStorage?.getItem('aiustaz:' + КЛЮЧ);
    return разобратьСохранённое(строка ? JSON.parse(строка) : null);
  } catch {
    return ПУСТО;
  }
}

function useСохранённое() {
  const [данные, установить] = useState<Сохранённое>(() => прочитатьСразу() ?? ПУСТО);
  const изменено = useRef(false);
  useEffect(() => {
    if (ВЕБ) return;
    void прочитатьJSON<unknown>(КЛЮЧ, null).then((з) => {
      if (!изменено.current) установить(разобратьСохранённое(з));
    });
  }, []);
  const изменить = (часть: Partial<Omit<Сохранённое, 'версия'>>) => {
    изменено.current = true;
    установить((прежнее) => {
      const новое = { ...прежнее, ...часть };
      void записатьJSON(КЛЮЧ, новое);
      return новое;
    });
  };
  const сбросить = () => {
    изменено.current = true;
    установить(ПУСТО);
    void удалитьКлюч(КЛЮЧ);
  };
  return { данные, изменить, сбросить };
}

/** Цены с сервера: сразу — сохранённые (без мигания формы), потом — свежие с aiustaz.pro (или null: ручной ввод). */
function useЦены(): ЗагруженныеЦены | null {
  const [цены, установить] = useState<ЗагруженныеЦены | null>(() => {
    if (!ВЕБ) return null;
    const ц = сохранённыеЦены();
    return ц ? { цены: ц, откуда: 'память' } : null;
  });
  useEffect(() => {
    if (!ВЕБ) return;
    let живо = true;
    void загрузитьЦены().then((з) => {
      if (живо) установить(з);
    });
    return () => {
      живо = false;
    };
  }, []);
  return цены;
}

