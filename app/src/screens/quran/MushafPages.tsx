/** Угол листа (0 — лежит, 90 — ребром у корешка) по доле пути края листа p ∈ [0, 1] (1 — переворот закончен). */
function уголИз(к: 1 | -1, p: number): number {
  const д = Math.min(1, Math.max(0, p));
  return (Math.acos(к === 1 ? 1 - д : д) * 180) / Math.PI;
}

