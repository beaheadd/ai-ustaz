/** Межстрочный листа (px) по кеглю и шрифту. */
const межстрочныйЛиста = (кегль: number, мединский: boolean) => Math.round(кегль * (мединский ? МЕЖСТРОЧНЫЙ_МЕДИНСКИЙ : МЕЖСТРОЧНЫЙ_КЛАССИЧЕСКИЙ));

type Подбор = { кегль: number; межстрочный: number };

/**
 * Подбор кегля по замеру (веб): абзацам листа на время замера ставятся кегль и межстрочный, высота содержимого
 * сравнивается с местом, поиск делением пополам с шагом 0,5 px; потом стили возвращаются (React рисует итог).
 * Книжная — наибольший кегль, при котором страница помещается целиком, и добор межстрочного до низа листа
 * (≤ ДОБОР_ДОЛЯ кегля); альбомная — наибольший, при котором строк не больше СТРОК_МУСХАФА (дальше — прокрутка).
 * Нет текста или места — null.
 */
function подобратьКегль(э: HTMLElement, альбом: boolean, мединский: boolean): Подбор | null {
  const содержимое = э.firstElementChild as HTMLElement | null;
  const абзацы = Array.from(э.querySelectorAll<HTMLElement>('p'));
  const место = э.clientHeight;
  const ш = э.clientWidth;
  if (!содержимое || !абзацы.length || !э.querySelector('[data-ayah]') || место < 40 || ш < 40) return null;
  const прежние = абзацы.map((а) => [а.style.fontSize, а.style.lineHeight] as const);
  const поставить = (кегль: number, мс: number) => {
    for (const а of абзацы) {
      а.style.fontSize = кегль + 'px';
      а.style.lineHeight = мс + 'px';
    }
  };
  const высотаПри = (кегль: number, мс: number) => {
    поставить(кегль, мс);
    return содержимое.getBoundingClientRect().height;
  };
  const запас = (кегль: number) => (мединский ? 0 : Math.ceil(кегль * ЗАПАС_СНИЗУ_КЛАССИЧЕСКИЙ));
  const влезает = (кегль: number) => {
    const мс = межстрочныйЛиста(кегль, мединский);
    return высотаПри(кегль, мс) <= (альбом ? СТРОК_МУСХАФА * мс + 16 : место - запас(кегль)) + 0.5;
  };
  // Полупиксели: ниж — влезает, верх — нет (или потолок).
  let ниж = МИН_КЕГЛЬ * 2;
  let верх = Math.round((альбом ? ш / 9 : ш / 6) * 2);
  if (влезает(ниж / 2)) {
    while (верх - ниж > 1) {
      const с = (ниж + верх) >> 1;
      if (влезает(с / 2)) ниж = с;
      else верх = с;
    }
  }
  const кегль = ниж / 2;
  let мс = межстрочныйЛиста(кегль, мединский);
  if (!альбом) {
    const свободно = место - запас(кегль) - высотаПри(кегль, мс);
    let строк = 0;
    for (const а of абзацы) строк += Math.round(а.getBoundingClientRect().height / мс);
    if (строк > 0 && свободно > 0) мс += Math.min(Math.floor(свободно / строк), Math.round(кегль * ДОБОР_ДОЛЯ));
  }
  абзацы.forEach((а, i) => {
    а.style.fontSize = прежние[i][0];
    а.style.lineHeight = прежние[i][1];
  });
  return { кегль, межстрочный: мс };
}

/**
 * Лист: рамка мусхафа и текст страницы со своим подбором кегля (подобратьКегль). Пересчёт — синхронно при смене
 * размеров окна, ориентации, шрифта и «во весь экран» (до отрисовки, без мигания) и после кадра — при смене размера
 * листа или содержимого (текст сур приходит позже, шрифт догрузился) и по document.fonts «loadingdone».
 */
function ЛистСтраницы({ номер, страницы, аятов, открыта, ночь, п, сЦветами, таджвид, кегльЧеловека, альбом, ширина, высота, весьЭкран, приТапеПоля, выбран, играет, открыть, снять, приПрокрутке, приКегле, узел, область }: СвойстваЛиста) {
  const участки = useMemo(() => участкиСтраницы(страницы, номер, аятов), [страницы, номер, аятов]);
  const прокрутка = useRef<HTMLElement | null>(null);
  // Шрифт Корана (владелец 28.11.2026): у мединского другие метрики — при смене или загрузке шрифта подбор заново.
  const { семейство, мединский, готов } = useШрифтКорана();
  const [подбор, установитьПодбор] = useState<Подбор>(() => {
    // Нативно замера нет — кегль от ширины (как прежде); на вебе — до первого замера.
    const к = Math.max(МИН_КЕГЛЬ, Math.round(альбом ? ширина / 16 : Math.max(кегльЧеловека, ширина / 13)));
    return { кегль: к, межстрочный: межстрочныйЛиста(к, мединский) };
  });
  const пересчитать = useCallback(() => {
    const э = прокрутка.current;
    if (!ВЕБ || !э) return;
    const р = подобратьКегль(э, альбом, мединский);
    if (р) установитьПодбор((б) => (б.кегль === р.кегль && б.межстрочный === р.межстрочный ? б : р));
  }, [альбом, мединский]);
  const пересчитатьРеф = useRef(пересчитать);
  пересчитатьРеф.current = пересчитать;
  useLayoutEffect(() => {
    пересчитать();
  }, [пересчитать, ширина, высота, весьЭкран, семейство, готов]);
  // Размер листа и содержимого (текст пришёл, шрифт сменился) — пересчёт со следующего кадра (не внутри наблюдателя:
  // иначе «ResizeObserver loop»).
  useEffect(() => {
    const э = прокрутка.current;
    if (!ВЕБ || !э) return;
    let кадр = 0;
    const позже = () => {
      if (кадр) return;
      кадр = requestAnimationFrame(() => {
        кадр = 0;
        пересчитатьРеф.current();
      });
    };
    const н = typeof ResizeObserver !== 'undefined' ? new ResizeObserver(позже) : null;
    н?.observe(э);
    if (э.firstElementChild) н?.observe(э.firstElementChild);
    const шрифты = typeof document !== 'undefined' ? document.fonts : undefined;
    шрифты?.addEventListener?.('loadingdone', позже);
    return () => {
      н?.disconnect();
      шрифты?.removeEventListener?.('loadingdone', позже);
      if (кадр) cancelAnimationFrame(кадр);
    };
  }, []);
  const кегль = подбор.кегль;
  useEffect(() => {
    приКегле?.(кегль);
  }, [кегль, приКегле]);
  // Тап по полю страницы (не по аяту, не по кнопке, без выделения текста) — «во весь экран» и обратно.
  const тапРеф = useRef(приТапеПоля);
  тапРеф.current = приТапеПоля;
  useEffect(() => {
    const э = прокрутка.current;
    if (!ВЕБ || !э) return;
    const ф = (е: MouseEvent) => {
      const ц = е.target as HTMLElement | null;
      if (!тапРеф.current || !ц || ц.closest?.('[data-ayah], a, button, [role="button"]')) return;
      if (String(globalThis.getSelection?.() ?? '').length > 0) return;
      тапРеф.current();
    };
    э.addEventListener('click', ф);
    return () => э.removeEventListener('click', ф);
  }, []);

  return (
    <View
      ref={(р) => узел((р as unknown as HTMLElement | null) ?? null)}
      testID="мусхаф-лист"
      {...((ВЕБ ? { dataSet: { sheet: String(номер) }, 'aria-hidden': открыта ? undefined : true } : {}) as object)}
      style={{
        position: 'absolute',
        top: 0,
        bottom: 0,
        left: 0,
        right: 0,
        backgroundColor: п.фон,
        borderWidth: 1,
        borderColor: п.рамка,
        borderRadius: 4,
        padding: 1,
        // Порядок листов при перевороте — zIndex в стиле узла (поставитьУгол), не здесь: перерисовка его не собьёт.
        ...(ВЕБ ? ({ backfaceVisibility: 'hidden' } as object) : null),
      }}
    >
      <View style={{ flex: 1, borderWidth: 0.5, borderColor: п.рамка2, borderRadius: 3 }}>
        <ScrollView
          ref={(р) => {
            const узелП = (р as unknown as { getScrollableNode?: () => HTMLElement } | null)?.getScrollableNode?.() ?? null;
            прокрутка.current = узелП;
            if (узелП && ВЕБ) узелП.style.touchAction = 'pan-y';
            область(узелП);
          }}
          style={{ flex: 1 }}
          contentContainerStyle={{ paddingHorizontal: 3, paddingVertical: 2 }}
          onScroll={открыта ? приПрокрутке : undefined}
          scrollEventThrottle={100}
          testID={открыта ? 'мусхаф-страница-текст' : undefined}
          {...((ВЕБ && открыта ? { dataSet: { orientation: альбом ? 'landscape' : 'portrait' } } : {}) as object)}
        >
          <View style={{ gap: 2 }}>
            {участки.map((уч) => (
              <УчастокСтраницы key={уч.сура + ':' + уч.с} участок={уч} тема={п.тема} таджвид={таджвид} кегль={кегль} межстрочный={подбор.межстрочный} открыть={открыть} снять={снять} выбран={выбран} играет={играет} />
            ))}
          </View>
        </ScrollView>
      </View>
      {/* Тень сгиба: тёмная полоса у корешка (справа); прозрачность меняет переворот. */}
      <View
        pointerEvents="none"
        {...((ВЕБ ? { dataSet: { shade: '1' } } : {}) as object)}
        style={{
          position: 'absolute',
          top: 0,
          bottom: 0,
          left: 0,
          right: 0,
          opacity: 0,
          ...(ВЕБ ? ({ backgroundImage: 'linear-gradient(to left, rgba(0,0,0,0.42), rgba(0,0,0,0.12) 35%, rgba(0,0,0,0) 70%)' } as object) : null),
        }}
      />
    </View>
  );
}

type СвойстваУчастка = { участок: Участок; тема: ТемаСтраницы; таджвид: РежимТаджвида; кегль: number; межстрочный: number; открыть: (сура: СураКорана, аят: number) => void; снять: () => void; выбран: string | null; играет: string | null };

function УчастокСтраницы(с: СвойстваУчастка) {
  const сура = useСура(с.участок.сура);
  if (сура.состояние !== 'есть') return null;
  return <УчастокСуры {...с} сура={сура.данные} />;
}

function УчастокСуры({ сура, участок, тема, таджвид, кегль, межстрочный, открыть, снять, выбран, играет }: СвойстваУчастка & { сура: СураКорана }): ReactNode {
  const { цвета } = useЦветаСуры(сура, таджвид !== 'безЦвета');
  const закладка = useЗакладка();
  return (
    <ПотокМусхафа
      сура={сура}
      с={участок.с}
      по={участок.по}
      цвета={цвета}
      тема={тема}
      таджвид={таджвид}
      выбран={выбран}
      играет={играет}
      закладка={закладка ? закладка.сура + ':' + закладка.аят : null}
      строкой
      кегль={кегль}
      межстрочный={межстрочный}
      выбрать={(ключ) => {
        if (!ключ) return снять();
        const а = Number(ключ.split(':')[1]);
        if (а >= 1) открыть(сура, а);
      }}
    />
  );
}
