function КнопкаДействия({ значок, надпись, приНажатии, testID, раскрыта }: { значок: string; надпись: string; приНажатии: () => void; testID: string; раскрыта?: boolean }) {
  const { цвет, отступ, радиус } = useТема();
  return (
    <Pressable
      accessibilityRole="button"
      {...(раскрыта !== undefined ? ((ВЕБ ? { 'aria-expanded': раскрыта } : { accessibilityState: { expanded: раскрыта } }) as object) : null)}
      onPress={приНажатии}
      testID={testID}
      style={({ pressed }) => ({
        flexDirection: 'row',
        alignItems: 'center',
        gap: отступ.m,
        minHeight: 52,
        paddingHorizontal: отступ.m,
        borderRadius: радиус.m,
        borderWidth: 1,
        borderColor: цвет.граница,
        backgroundColor: pressed || раскрыта ? цвет.акцентМягкий : цвет.поверхность,
      })}
    >
      <Значок имя={значок as never} размер={22} цвет={цвет.акцент} толщина={2} />
      <Текст стиль={{ flex: 1, fontWeight: '600' }}>{надпись}</Текст>
    </Pressable>
  );
}

/** Таджвид аята: раскрашенный текст и список правил, которые в нём встречаются (из разметки build_tajweed.py). */
function ТаджвидАята({ сура, аят }: { сура: СураКорана; аят: number }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, тёмная } = useТема();
  const разметка = useРазметкаСуры(сура.сура);
  const текст = сура.аяты[аят - 1].текст;
  const палитра = тёмная ? ЦВЕТА_ТАДЖВИДА.ночь : ЦВЕТА_ТАДЖВИДА.страница;

  const данные = useMemo(() => {
    if (разметка.состояние !== 'есть') return null;
    const отрезки = разобратьРазметку(разметка.данные.аяты[аят - 1]);
    if (!отрезки || !отрезкиВерны(текст, отрезки)) return { отрезки: null, правила: [] as { код: КодТаджвида; слова: string[] }[] };
    // Слова аята (по пробелам) и какие из них задевает каждое правило — без изменения текста.
    const границы: [number, number][] = [];
    let п = 0;
    for (const слово of текст.split(' ')) {
      границы.push([п, п + слово.length]);
      п += слово.length + 1;
    }
    const поКоду = new Map<КодТаджвида, Set<number>>();
    for (const [с, , код] of отрезки) {
      const i = границы.findIndex(([а, б]) => с >= а && с < б);
      if (i < 0) continue;
      if (!поКоду.has(код)) поКоду.set(код, new Set());
      поКоду.get(код)!.add(i);
    }
    const слова = текст.split(' ');
    const правила = КОДЫ_ТАДЖВИДА.filter((к) => поКоду.has(к)).map((код) => ({ код, слова: [...поКоду.get(код)!].sort((а, б) => а - б).map((i) => слова[i]) }));
    return { отрезки, правила };
  }, [разметка, аят, текст]);

  if (разметка.состояние === 'загрузка') {
    return (
      <Текст вид="второй" testID="таджвид-аята-загрузка">
        {т('загрузка')}
      </Текст>
    );
  }
  if (разметка.состояние === 'нет' || !данные || !данные.отрезки) {
    return (
      <Текст вид="второй" testID="таджвид-аята-нет">
        {т('нетРазметки')}
      </Текст>
    );
  }
  const куски = кускиТекста(текст, данные.отрезки);
  const стильАр = { fontFamily: ШРИФТ_АРАБСКИЙ, fontSize: 28, lineHeight: 52, color: цвет.текст, textAlign: 'right' as const, writingDirection: 'rtl' as const };
  // Вложенные <Text> — на вебе это строчные span внутри одного абзаца (как в мусхафе): буквы не разрываются.
  const раскрашенный: ReactNode = (
    <Text testID="таджвид-аята-текст" {...((ВЕБ ? { lang: 'ar', dir: 'rtl' } : {}) as object)} style={стильАр}>
      {куски.map((к, i) => (
        <Text key={i} style={к.код ? { color: палитра[к.код] } : undefined}>
          {к.текст}
        </Text>
      ))}
    </Text>
  );
  return (
    <View testID="таджвид-аята" style={{ gap: отступ.s }}>
      <Плашка вид="черновик" надпись={т('черновик')} testID="таджвид-аята-черновик" />
      {раскрашенный}
      {данные.правила.length === 0 ? (
        <Текст вид="второй">{т('нетПравил')}</Текст>
      ) : (
        данные.правила.map(({ код, слова }) => {
          const правило = ПРАВИЛА_ТАДЖВИДА[код];
          return (
            <View key={код} testID={'таджвид-аята-правило-' + код} style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'flex-start' }}>
              <View style={{ width: 14, height: 14, borderRadius: 7, marginTop: 4, backgroundColor: палитра[код] }} />
              <View style={{ flex: 1, gap: 2 }}>
                <Текст стиль={{ fontWeight: '600' }}>{правило[язык as 'ru' | 'kk' | 'uz' | 'en'] ?? правило.ru}</Текст>
                <Текст вид="мелкий" цвет={цвет.текстВторой}>
                  {т('урок', { н: правило.урок })}
                </Текст>
                <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', gap: 6 }} testID={'таджвид-аята-слова-' + код}>
                  <Текст вид="мелкий" цвет={цвет.текстВторой}>
                    {т('гдеВстречается')}
                  </Текст>
                  {слова.map((с, i) => (
                    <Text key={i} {...((ВЕБ ? { lang: 'ar', dir: 'rtl' } : {}) as object)} style={{ fontFamily: ШРИФТ_АРАБСКИЙ, fontSize: 20, lineHeight: 34, color: палитра[код] }}>
                      {с}
                    </Text>
                  ))}
                </View>
              </View>
            </View>
          );
        })
      )}
    </View>
  );
}

export function ЛистДействийАята({ сура, аят, закрыть, проверить }: { сура: СураКорана; аят: number; закрыть: () => void; проверить: (аят: number) => void }) {
  const т = useСловарь(СЛОВАРЬ);
  const { язык } = useПеревод();
  const { цвет, отступ, радиус } = useТема();
  const закладка = useЗакладка();
  const есть = !!закладка && закладка.сура === сура.сура && закладка.аят === аят;
  const [нетЗаписи, установитьНетЗаписи] = useState(false);
  const [таджвид, установитьТаджвид] = useState(false);
  const [сохранено, установитьСохранено] = useState(false);
  // Esc закрывает лист (как остальные листы экрана суры).
  useEffect(() => {
    if (!ВЕБ || typeof document === 'undefined') return;
    const ф = (е: KeyboardEvent) => {
      if (е.key === 'Escape') закрыть();
    };
    document.addEventListener('keydown', ф);
    return () => document.removeEventListener('keydown', ф);
  }, [закрыть]);

  function слушать() {
    if (!доступныйИсточник()) {
      установитьНетЗаписи(true);
      return;
    }
    установитьЯзыкПлеера(язык);
    // Синхронно из нажатия: первый play() браузеры разрешают только из жеста. Только этот аят.
    плеер.играть({ сура: сура.сура, сАята: аят });
    закрыть();
  }

  return (
    <>
      <Pressable accessibilityLabel={т('закрыть')} onPress={закрыть} style={{ position: 'absolute', top: 0, left: 0, right: 0, bottom: 0, backgroundColor: 'rgba(0,0,0,0.3)' }} {...((ВЕБ ? { tabIndex: -1 } : {}) as object)} />
      <View
        testID="сура-действия"
        {...((ВЕБ ? { role: 'dialog', 'aria-modal': true, 'aria-label': т('заголовок', { сура: сура.сура, аят }) } : {}) as object)}
        pointerEvents="box-none"
        style={{ position: 'absolute', left: 0, right: 0, bottom: 0, top: '8%', justifyContent: 'flex-end', alignItems: 'center' }}
      >
        <View style={{ width: '100%', maxWidth: ШИРИНА_КОЛОНКИ, maxHeight: '100%', backgroundColor: цвет.фон, borderTopLeftRadius: радиус.l, borderTopRightRadius: радиус.l, borderWidth: 1, borderBottomWidth: 0, borderColor: цвет.граница }}>
          <View style={{ flexDirection: 'row', alignItems: 'center', paddingLeft: отступ.l, paddingRight: отступ.s, paddingTop: отступ.xs, borderBottomWidth: 1, borderBottomColor: цвет.граница }}>
            <Текст вид="подзаголовок" табличные стиль={{ flex: 1 }} testID="действия-заголовок">
              {т('заголовок', { сура: сура.сура, аят })}
            </Текст>
            <Pressable accessibilityRole="button" accessibilityLabel={т('закрыть')} onPress={закрыть} testID="действия-закрыть" style={{ width: 48, height: 48, alignItems: 'center', justifyContent: 'center' }}>
              <Значок имя="закрыть" размер={22} цвет={цвет.акцент} толщина={2} />
            </Pressable>
          </View>
          <ScrollView style={{ flexShrink: 1 }} contentContainerStyle={{ padding: отступ.l, gap: отступ.s, paddingBottom: ВЕБ ? ('calc(24px + env(safe-area-inset-bottom))' as unknown as number) : 24 }}>
            <КнопкаДействия значок="играть" надпись={т('слушать')} приНажатии={слушать} testID="действия-слушать" />
            {нетЗаписи ? (
              <View testID="действия-нет-записи" style={{ paddingHorizontal: отступ.s }}>
                <СтрокаБезЗвука />
              </View>
            ) : null}
            <КнопкаДействия значок="таджвид" надпись={т('таджвид')} приНажатии={() => установитьТаджвид((в) => !в)} раскрыта={таджвид} testID="действия-таджвид" />
            {таджвид ? <ТаджвидАята сура={сура} аят={аят} /> : null}
            <КнопкаДействия значок="микрофон" надпись={т('проверить')} приНажатии={() => проверить(аят)} testID="действия-проверить" />
            <КнопкаДействия
              значок={есть ? 'закладкаЕсть' : 'закладка'}
              надпись={есть ? т('закладкаЕсть') : т('закладка')}
              приНажатии={() => {
                поставитьЗакладку(есть ? null : { сура: сура.сура, аят });
                установитьСохранено(!есть);
              }}
              testID="действия-закладка"
            />
            {сохранено && есть ? (
              <Текст вид="второй" testID="действия-закладка-готово" {...((ВЕБ ? { role: 'status' } : {}) as object)}>
                {т('закладкаГотово', { сура: сура.сура, аят })}
              </Текст>
            ) : null}
          </ScrollView>
        </View>
      </View>
    </>
  );
}
