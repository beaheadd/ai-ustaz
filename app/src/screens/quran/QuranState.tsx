/**
 * Состояние «текста нет» на экранах Корана (#/quran, #/quran/sura, #/quran/check) — одно для всех трёх.
 *
 * Контракт: <ТекстКоранаНедоступен состояние={useСура(...) | useИндексСур()} /> — только для состояния 'нет':
 *   нетСвязи (нет сети, таймаут, 5xx)      → «Нет связи» и «Повторить» (live polite; без перезагрузки страницы);
 *   причина 'нет-файла' (404, HTML вместо JSON — старая вкладка после выпуска) → «Файл не найден. Обновите страницу»
 *     и «Обновить» (ревью 19.11.2026: это не «текст испорчен»);
 *   иначе ('не-прошло-сверку')             → «Текст не прошёл сверку с проверенной базой — не показываем» (правило 1).
 * testID: коран-нет-связи, коран-повторить, коран-нет-файла, коран-обновить, коран-нет-сверки.
 * kk — черновик для редактора-носителя.
 */
import { Platform, View } from 'react-native';
import { Кнопка, Текст } from '../../components';
import { создатьСловарь, useПеревод, useСловарь } from '../../i18n';
import type { ПричинаОтказа } from '../../quran/data';
import { useТема } from '../../theme';

const СЛОВАРЬ = создатьСловарь({
  ru: {
    нетФайла: 'Файл с текстом не найден — возможно, вышла новая версия. Обновите страницу.',
    обновить: 'Обновить страницу',
    нет: 'Текст не прошёл сверку с проверенной базой — не показываем.',
  },
  kk: {
    нетФайла: 'Мәтін файлы табылмады — жаңа нұсқа шыққан болуы мүмкін. Бетті жаңартыңыз.',
    обновить: 'Бетті жаңарту',
    нет: 'Мәтін тексерілген базамен салыстырудан өтпеді — көрсетпейміз.',
  },
  uz: {
    нетФайла: 'Matnli fayl topilmadi — ehtimol, yangi versiya chiqqan. Sahifani yangilang.',
    обновить: 'Sahifani yangilash',
    нет: 'Matn tekshirilgan baza bilan solishtiruvdan oʻtmadi — koʻrsatmaymiz.',
  },
  en: {
    нетФайла: 'The text file was not found — perhaps a new version has been released. Refresh the page.',
    обновить: 'Refresh the page',
    нет: 'The text did not pass verification against the verified database — not shown.',
  },
});

export function ТекстКоранаНедоступен({ состояние }: { состояние: { нетСвязи: boolean; причина: ПричинаОтказа; повторить: () => void } }) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { отступ } = useТема();
  if (состояние.нетСвязи) {
    return (
      <View style={{ gap: отступ.s }}>
        <Текст вид="второй" testID="коран-нет-связи" accessibilityLiveRegion="polite">
          {t('общее.нетСвязи')}
        </Текст>
        <Кнопка вид="вторичная" значок="повтор" надпись={t('общее.повторить')} растянуть={false} приНажатии={состояние.повторить} testID="коран-повторить" />
      </View>
    );
  }
  if (состояние.причина === 'нет-файла') {
    return (
      <View style={{ gap: отступ.s }}>
        <Текст вид="второй" testID="коран-нет-файла" accessibilityLiveRegion="polite">
          {т('нетФайла')}
        </Текст>
        {Platform.OS === 'web' ? (
          <Кнопка
            вид="вторичная"
            значок="повтор"
            надпись={т('обновить')}
            растянуть={false}
            приНажатии={() => globalThis.location?.reload()}
            testID="коран-обновить"
          />
        ) : null}
      </View>
    );
  }
  return (
    <Текст вид="второй" testID="коран-нет-сверки">
      {т('нет')}
    </Текст>
  );
}
