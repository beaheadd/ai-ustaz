/**
 * Общее для экранов Корана (#/quran, #/quran/sura, #/quran/check): название суры, поиск и переход «2:255»,
 * «Продолжить чтение» (последний открытый аят — только на этом устройстве), тексты ru/kk.
 *
 * Решение владельца 19.11.2026: «Коран полностью, все аяты … заходишь и читаешь любой аят, и записываешь голос
 * и проверяешь, где ошибки» (docs/дизайн/05-коран-чтение-и-плеер.md, §2.1).
 *
 * Контракт (чистые функции, кроме хранилища):
 *   названиеСуры(запись | null, номер, язык) → «Сура аль-Бакара (2)» (ru) / «2-сүре» (kk — транслитерации пока нет).
 *     Без арабского текста: годится для заголовка экрана и document.title (правило 9 и §2.1 — без текста Корана).
 *   словоАятов(n, язык) → «7 аятов» / «7 аят».
 *   разобратьПереход(строка) → { сура, аят } | null — «2:255», «2 255», «2.255», «2-255» (сура 1…114, аят ≥ 1;
 *     больше аятов суры — проверяет вызывающий по индексу).
 *   подходящиеСуры(суры, запрос) → ЗаписьСуры[] — цифры: номер начинается с запроса; иначе — транслитерация ru/kk
 *     или синонимы индекса (латиница, «Ясин», «Табарак») после упростить() (бакара → аль-Бакара, ясин → Йа Син,
 *     baqara → Al-Baqarah) или арабское имя как есть (подстрока).
 *   прочитатьЧтение() / запомнитьЧтение(сура, аят) — localStorage «aiustaz:quran-reading.v1» = { версия: 1, сура, аят }.
 *     Только номера, ничего не отправляется (engine/storage.ts). Пишется не чаще раза в ЗАПИСЬ_ЧТЕНИЯ_МС.
 *   запомнитьВозвратКАяту/взятьВозвратКАяту, запомнитьВозвратКСуре/взятьВозвратКСуре — куда вернуть фокус по «Назад»
 *     (кружок аята после записи; строка суры в списке — прокрутка к ней). Только в памяти страницы.
 * kk — черновик для редактора-носителя.
 */
import type { ЗаписьСуры } from '../../quran/data';
import { прочитатьJSON, записатьJSON } from '../../engine/storage';

export type МестоЧтения = { сура: number; аят: number };

const КЛЮЧ_ЧТЕНИЯ = 'quran-reading.v1';
export const ЗАПИСЬ_ЧТЕНИЯ_МС = 800;

export function названиеСуры(запись: Pick<ЗаписьСуры, 'транслит'> | null, номер: number, язык: string): string {
  if (язык === 'kk') {
    const т = запись?.транслит.kk;
    return т ? `${т} сүресі (${номер})` : `${номер}-сүре`;
  }
  if (язык === 'uz') {
    const т = запись?.транслит.uz;
    return т ? `${т} surasi (${номер})` : `${номер}-sura`;
  }
  if (язык === 'en') {
    const т = запись?.транслит.en;
    return т ? `Surah ${т} (${номер})` : `Surah ${номер}`;
  }
  const т = запись?.транслит.ru;
  return т ? `Сура ${т} (${номер})` : `Сура ${номер}`;
}

export function словоАятов(н: number, язык: string): string {
  if (язык === 'kk') return `${н} аят`;
  if (язык === 'uz') return `${н} oyat`;
  if (язык === 'en') return `${н} ${н === 1 ? 'ayah' : 'ayahs'}`;
  const д = н % 100;
  const е = н % 10;
  const слово = д >= 11 && д <= 14 ? 'аятов' : е === 1 ? 'аят' : е >= 2 && е <= 4 ? 'аята' : 'аятов';
  return `${н} ${слово}`;
}

export function разобратьПереход(строка: string): МестоЧтения | null {
  const м = /^\s*(\d{1,3})\s*[:.\-\s]\s*(\d{1,3})\s*$/.exec(строка);
  if (!м) return null;
  const сура = Number(м[1]);
  const аят = Number(м[2]);
  return сура >= 1 && сура <= 114 && аят >= 1 ? { сура, аят } : null;
}

/**
 * Упрощение для поиска (ревью 19.11.2026: «Ясин» не находил «Йа Син»): нижний регистр, без пробелов, дефисов и
 * апострофов; й→и, я→а, ю→у, ё/э→е, без ь/ъ; удвоенные буквы — одна (Муззаммиль = Музаммиль, Baqarah = Baqara по
 * подстроке). Латиница — та же схема.
 */
export function упростить(с: string): string {
  return с
    .toLocaleLowerCase('ru')
    .replace(/[\s\-‐‑–—'’‘ʼʻ`.]/g, '')
    .replace(/й/g, 'и')
    .replace(/я/g, 'а')
    .replace(/ю/g, 'у')
    .replace(/[ёэ]/g, 'е')
    .replace(/[ьъ]/g, '')
    .replace(/(.)\1+/g, '$1');
}

export function подходящиеСуры(суры: readonly ЗаписьСуры[], запрос: string): readonly ЗаписьСуры[] {
  const з = запрос.trim();
  if (!з) return суры;
  if (/^\d{1,3}$/.test(з)) return суры.filter((с) => String(с.сура).startsWith(з));
  const у = упростить(з);
  if (!у) return суры;
  const подходит = (т: string | null | undefined) => !!т && упростить(т).includes(у);
  return суры.filter((с) => с.имя.includes(з) || подходит(с.транслит.ru) || подходит(с.транслит.kk) || подходит(с.транслит.uz) || подходит(с.транслит.en) || (с.синонимы ?? []).some(подходит));
}

function место(з: unknown): МестоЧтения | null {
  if (!з || typeof з !== 'object') return null;
  const о = з as Record<string, unknown>;
  const { сура, аят } = о;
  if (о.версия !== 1 || typeof сура !== 'number' || typeof аят !== 'number') return null;
  if (!Number.isInteger(сура) || !Number.isInteger(аят) || сура < 1 || сура > 114 || аят < 1 || аят > 286) return null;
  return { сура, аят };
}

export async function прочитатьЧтение(): Promise<МестоЧтения | null> {
  return место(await прочитатьJSON<unknown>(КЛЮЧ_ЧТЕНИЯ, null));
}

let последнее = '';
let таймер: ReturnType<typeof setTimeout> | null = null;

/** Запомнить последний открытый аят (с задержкой: прокрутка зовёт часто). */
export function запомнитьЧтение(сура: number, аят: number, сразу = false): void {
  const ключ = сура + ':' + аят;
  if (ключ === последнее) return;
  последнее = ключ;
  if (таймер) clearTimeout(таймер);
  const записать = () => {
    таймер = null;
    void записатьJSON(КЛЮЧ_ЧТЕНИЯ, { версия: 1, сура, аят });
  };
  if (сразу) записать();
  else таймер = setTimeout(записать, ЗАПИСЬ_ЧТЕНИЯ_МС);
}

// ── Закладка (владелец 21.11.2026: «при нажатии на номер аята … сохранить, чтобы, когда хотел продолжить, мог начать
// с этого сохранённого места») — одна, как в бумажном мусхафе; только на устройстве: «aiustaz:quran-bookmark.v1» =
// { версия: 1, сура, аят }. Отличается от «Продолжить чтение» (тот запоминает сам, где остановилась прокрутка).

const КЛЮЧ_ЗАКЛАДКИ = 'quran-bookmark.v1';
const слушателиЗакладки = new Set<(з: МестоЧтения | null) => void>();
let закладкаСейчас: МестоЧтения | null | undefined;

export async function прочитатьЗакладку(): Promise<МестоЧтения | null> {
  if (закладкаСейчас === undefined) закладкаСейчас = место(await прочитатьJSON<unknown>(КЛЮЧ_ЗАКЛАДКИ, null));
  return закладкаСейчас;
}

/** Поставить закладку (null — убрать). Подписчики (экран суры, список) узнают сразу. */
export function поставитьЗакладку(з: МестоЧтения | null): void {
  закладкаСейчас = з;
  void записатьJSON(КЛЮЧ_ЗАКЛАДКИ, з ? { версия: 1, сура: з.сура, аят: з.аят } : null);
  for (const ф of [...слушателиЗакладки]) ф(з);
}

export function подписатьсяНаЗакладку(ф: (з: МестоЧтения | null) => void): () => void {
  слушателиЗакладки.add(ф);
  return () => слушателиЗакладки.delete(ф);
}

// ── Возврат фокуса (ревью 19.11.2026): только в памяти страницы, ничего не хранится ──

let возвратКАяту: МестоЧтения | null = null;
let возвратКСуре: number | null = null;

/** Уходим с суры на «Прочитать и записать»: «Назад» вернёт фокус на кружок этого аята, а не на заголовок. */
export function запомнитьВозвратКАяту(сура: number, аят: number): void {
  возвратКАяту = { сура, аят };
}
/** Один раз: аят, на кружок которого вернуть фокус при открытии суры, или null. */
export function взятьВозвратКАяту(сура: number): number | null {
  const в = возвратКАяту;
  возвратКАяту = null;
  return в && в.сура === сура ? в.аят : null;
}
/** Уходим со списка сур в суру: «Назад» прокрутит список к ней и поставит на неё фокус. */
export function запомнитьВозвратКСуре(сура: number): void {
  возвратКСуре = сура;
}
export function взятьВозвратКСуре(): number | null {
  const в = возвратКСуре;
  возвратКСуре = null;
  return в;
}
