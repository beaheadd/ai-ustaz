/**
 * О проекте: что такое AI Ustaz, бесплатно ради Аллаха, без рекламы и трекинга, приватность,
 * версия уроков, удаление локального прогресса, ссылка на лицензии.
 * ЗАГЛУШКА каркаса — заменит агент этого экрана. Контракт: ПропсыЭкрана<'оПроекте'>.
 * Обязательная строка: казахские тексты — черновик для редактора-носителя ('оПроекте.казахский').
 */
import { useState } from 'react';
import версияКонтента from '@content/version.json';
import { Карточка, Кнопка, Текст, Экран } from '../components';
import type { ВерсияКонтента } from '../content/types';
import { useНавигация } from '../engine/navigation';
import { useПрогресс } from '../engine/progress';
import type { ПропсыЭкрана } from '../engine/routes';
import { useПеревод } from '../i18n';

const ВЕРСИЯ = версияКонтента as ВерсияКонтента;

export function ОПроекте(_: ПропсыЭкрана<'оПроекте'>) {
  const { t } = useПеревод();
  const { перейти } = useНавигация();
  const { сбросить } = useПрогресс();
  const [удалено, установитьУдалено] = useState(false);
  return (
    <Экран заголовок={t('экран.оПроекте')} плашка="общая" testID="экран-о-проекте">
      <Карточка>
        <Текст testID="версия-контента">{t('оПроекте.версияКонтента', { версия: ВЕРСИЯ.версия, статус: ВЕРСИЯ.статус })}</Текст>
        <Текст вид="второй">{t('оПроекте.казахский')}</Текст>
      </Карточка>
      <Кнопка
        надпись={t('оПроекте.удалитьДанные')}
        вид="вторичная"
        приНажатии={() => {
          сбросить();
          установитьУдалено(true);
        }}
        testID="удалить-прогресс"
      />
      {удалено ? <Текст вид="второй">{t('оПроекте.данныеУдалены')}</Текст> : null}
      <Кнопка надпись={t('экран.лицензии')} вид="тихая" приНажатии={() => перейти('лицензии')} testID="о-проекте-лицензии" />
      <Текст вид="второй">{t('общее.вРазработке')}</Текст>
    </Экран>
  );
}
