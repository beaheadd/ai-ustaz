const КЛЮЧ_ФИЛЬТРА = 'dhikr-filter.v1';
type ФильтрЗикров = 'утро' | 'вечер' | 'после-намаза' | 'все' | 'избранное';
type ФильтрДуа = ТемаДуа | 'все' | 'избранное';

/** Ряд чипов-переключателей (прокрутка вбок на узких экранах); выбранный — aria-pressed. */
function Чипы<К extends string>({ чипы, выбран, приВыборе, подпись, testID }: { чипы: { ключ: К; надпись: string }[]; выбран: К; приВыборе: (к: К) => void; подпись: string; testID: string }) {
  const { цвет, отступ, радиус } = useТема();
  return (
    <ScrollView horizontal showsHorizontalScrollIndicator={false} accessibilityLabel={подпись} testID={testID} contentContainerStyle={{ gap: отступ.s, paddingVertical: 2 }}>
      {чипы.map((ч) => {
        const да = ч.ключ === выбран;
        return (
          <Pressable
            key={ч.ключ}
            accessibilityRole="button"
            accessibilityState={{ selected: да }}
            {...(ВЕБ ? ({ 'aria-pressed': да } as object) : null)}
            onPress={() => приВыборе(ч.ключ)}
            testID={testID + '-' + ч.ключ}
            style={({ pressed }) => ({
              minHeight: 44,
              paddingHorizontal: отступ.m,
              borderRadius: радиус.круг,
              justifyContent: 'center',
              borderWidth: 1,
              borderColor: да ? цвет.акцент : цвет.границаЭлемента,
              backgroundColor: да ? цвет.акцент : pressed ? цвет.акцентМягкий : цвет.поверхность,
            })}
          >
            <Текст вид="метка" цвет={да ? цвет.акцентТекст : цвет.текст} numberOfLines={1}>
              {ч.надпись}
            </Текст>
          </Pressable>
        );
      })}
    </ScrollView>
  );
}

function СписокЗикров({ дуа }: { дуа: boolean }) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тз = useСловарь(СЛОВАРЬ_ЗИКРОВ);
  const { цвет, отступ } = useТема();
  const набор = useЗикры();
  const счёт = useСчётЗикров();
  // Владелец 27.11.2026: «разделить зикры: утренние, вечерние…» — чипы времени (выбор запоминается на устройстве);
  // «дуа для входа в мечеть, путника, повседневные» — темы на экране «Дуа».
  const [фильтр, установитьФильтр] = useState<ФильтрЗикров>('все');
  const [тема, установитьТему] = useState<ФильтрДуа>('все');
  useEffect(() => {
    if (дуа) return;
    let жив = true;
    void прочитатьJSON<{ фильтр?: string } | null>(КЛЮЧ_ФИЛЬТРА, null).then((з) => {
      const ф = з?.фильтр;
      if (жив && (ф === 'утро' || ф === 'вечер' || ф === 'после-намаза' || ф === 'все' || ф === 'избранное')) установитьФильтр(ф);
    });
    return () => {
      жив = false;
    };
  }, [дуа]);
  const выбратьФильтр = (ф: ФильтрЗикров) => {
    установитьФильтр(ф);
    void записатьJSON(КЛЮЧ_ФИЛЬТРА, { фильтр: ф });
  };
  const всеЗикры = набор.состояние === 'есть' ? набор.данные.зикры : [];
  const зикры = дуа ? всеЗикры.filter((з) => з.дуа) : всеЗикры.filter((з) => !з.повседневная);
  const избранные = (с: Зикр[]) => с.filter((з) => счёт.избранное.includes(з.id));

  let показать: Зикр[];
  let группы: { тема: ТемаДуа; зикры: Зикр[] }[] | null = null;
  const чипыЗикров: { ключ: ФильтрЗикров; надпись: string }[] = [];
  const чипыДуа: { ключ: ФильтрДуа; надпись: string }[] = [];
  if (дуа) {
    const темы = ТЕМЫ_ДУА.filter((тм) => зикры.some((з) => з.тема === тм));
    чипыДуа.push({ ключ: 'все', надпись: т('все') }, ...темы.map((тм) => ({ ключ: тм as ФильтрДуа, надпись: т(('т.' + тм) as 'т.дом') })), { ключ: 'избранное', надпись: т('избранное') });
    if (тема === 'все') {
      группы = темы.map((тм) => ({ тема: тм, зикры: зикры.filter((з) => з.тема === тм) }));
      показать = зикры;
    } else показать = тема === 'избранное' ? избранные(зикры) : зикры.filter((з) => з.тема === тема);
  } else {
    for (const в of ['утро', 'вечер', 'после-намаза'] as const) if (зикры.some((з) => з.время.includes(в))) чипыЗикров.push({ ключ: в, надпись: т(в) });
    чипыЗикров.push({ ключ: 'все', надпись: т('все') }, { ключ: 'избранное', надпись: т('избранное') });
    показать = фильтр === 'все' ? зикры : фильтр === 'избранное' ? избранные(зикры) : зикры.filter((з) => з.время.includes(фильтр));
  }
  const карточка = (з: Зикр) => <КарточкаЗикра key={з.id} зикр={з} запись={счёт.счёт[з.id]} избран={счёт.избранное.includes(з.id)} язык={язык} />;

  return (
    <Экран заголовок={t(дуа ? 'экран.дуа' : 'экран.зикры')} testID={дуа ? 'экран-дуа' : 'экран-зикры'}>
      <Карточка вид="арка" testID="зикры-вступление">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          {дуа ? <ИллюстрацияРаздела имя="дуа" размер={36} /> : <Значок имя="тасбих" размер={24} цвет={цвет.акцент} />}
          <Текст стиль={{ flex: 1 }}>{т(дуа ? 'вступлениеДуа' : 'вступление')}</Текст>
        </View>
        <Плашка вид="черновик" надпись={тз('черновик')} testID="зикры-черновик" />
        <Текст вид="мелкий" testID="зикры-устройство">
          {т('устройство')}
        </Текст>
      </Карточка>

      {набор.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="зикры-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : набор.состояние === 'нет' ? (
        <ЗикрыНедоступны состояние={набор} />
      ) : (
        <View style={{ gap: отступ.m }}>
          {дуа ? (
            <Чипы чипы={чипыДуа} выбран={тема} приВыборе={установитьТему} подпись={т('темы')} testID="дуа-тема" />
          ) : (
            <Чипы чипы={чипыЗикров} выбран={фильтр} приВыборе={выбратьФильтр} подпись={т('фильтры')} testID="зикры-фильтр" />
          )}
          {показать.length === 0 ? (
            <Текст вид="второй" testID="зикры-избранное-пусто">
              {т('пусто')}
            </Текст>
          ) : группы ? (
            <View testID="зикры-список" style={{ gap: отступ.l }}>
              {группы.map((г) => (
                <View key={г.тема} style={{ gap: отступ.s }} testID={'дуа-группа-' + г.тема}>
                  <Текст вид="подзаголовок" accessibilityRole="header">
                    {т(('т.' + г.тема) as 'т.дом')}
                  </Текст>
                  <View {...(ВЕБ ? { role: 'list' as const } : {})} style={{ gap: отступ.s }}>
                    {г.зикры.map(карточка)}
                  </View>
                </View>
              ))}
            </View>
          ) : (
            <View testID="зикры-список" {...(ВЕБ ? { role: 'list' as const } : {})} style={{ gap: отступ.s }}>
              {показать.map(карточка)}
            </View>
          )}
        </View>
      )}
    </Экран>
  );
}
