const КарточкаЗикра = memo(function КарточкаЗикра({ зикр, запись, избран, язык }: { зикр: Зикр; запись: ЗаписьСчёта | undefined; избран: boolean; язык: Язык }) {
  const т = useСловарь(СЛОВАРЬ);
  const тз = useСловарь(СЛОВАРЬ_ЗИКРОВ);
  const { перейти } = useНавигация();
  const { цвет, отступ, радиус } = useТема();
  const название = зикр.название[язык];
  const счёт = { текущий: сегодняЗикра(запись), цель: цельЗикра(запись, зикр.раз), всего: запись?.всего ?? 0 };
  const ссылка = вХэш({ экран: 'зикр', параметры: { номер: зикр.номер } });
  return (
    <View
      {...(ВЕБ ? { role: 'listitem' as const } : {})}
      style={{ flexDirection: 'row', alignItems: 'stretch', borderRadius: радиус.l, borderWidth: 1, borderColor: цвет.граница, backgroundColor: цвет.поверхность, overflow: 'hidden' }}
    >
      <Pressable
        accessibilityRole="link"
        accessibilityLabel={`${зикр.номер}. ${название}. ${тз('счётПодпись', счёт)}`}
        {...(ВЕБ
          ? ({
              href: ссылка,
              onKeyDown: (е: { key: string; preventDefault: () => void }) => {
                if (е.key === ' ' || е.key === 'Spacebar') {
                  е.preventDefault();
                  перейти('зикр', { номер: зикр.номер });
                }
              },
            } as object)
          : null)}
        onPress={(е) => {
          const с = е as unknown as { metaKey?: boolean; ctrlKey?: boolean; shiftKey?: boolean; altKey?: boolean; preventDefault?: () => void };
          if (с.metaKey || с.ctrlKey || с.shiftKey || с.altKey) return;
          с.preventDefault?.();
          перейти('зикр', { номер: зикр.номер });
        }}
        testID={'зикры-строка-' + зикр.id}
        style={({ pressed, hovered }: { pressed: boolean; hovered?: boolean }) => ({
          flex: 1,
          minWidth: 0,
          flexDirection: 'row',
          alignItems: 'flex-start',
          gap: отступ.m,
          padding: отступ.m,
          backgroundColor: pressed ? цвет.акцентМягкий : hovered ? цвет.поверхностьВторая : 'transparent',
          ...(ВЕБ ? ({ textDecorationLine: 'none' } as object) : null),
        })}
      >
        <View style={{ minWidth: 40, height: 40, paddingHorizontal: 6, borderRadius: радиус.m, alignItems: 'center', justifyContent: 'center', backgroundColor: цвет.акцент }}>
          <Текст вид="метка" цвет={цвет.акцентТекст} табличные>
            {String(зикр.номер)}
          </Текст>
        </View>
        <View style={{ flex: 1, minWidth: 0, gap: 2 }}>
          <Текст numberOfLines={2} стиль={{ fontWeight: '700', fontSize: 17 }} testID={`зикры-строка-${зикр.id}-название`}>
            {название}
          </Текст>
          <Текст вид="второй" numberOfLines={2} testID={`зикры-строка-${зикр.id}-произношение`}>
            {зикр.произношение[язык]}
          </Текст>
          <Текст вид="мелкий" табличные testID={`зикры-строка-${зикр.id}-счёт`} стиль={{ marginTop: отступ.xs }}>
            {тз('счёт', счёт)}
          </Текст>
        </View>
      </Pressable>
      <Pressable
        accessibilityRole="button"
        accessibilityLabel={т(избран ? 'изИзбранного' : 'вИзбранное', { название })}
        accessibilityState={{ selected: избран }}
        {...(ВЕБ ? ({ 'aria-pressed': избран } as object) : null)}
        onPress={() => переключитьИзбранное(зикр.id)}
        testID={'зикры-избранное-' + зикр.id}
        style={({ pressed }) => ({ width: 56, alignItems: 'center', justifyContent: 'center', backgroundColor: pressed ? цвет.акцентМягкий : 'transparent' })}
      >
        <Значок имя={избран ? 'избранноеЕсть' : 'избранное'} размер={26} цвет={избран ? цвет.золотоЗначок : цвет.текстВторой} />
      </Pressable>
    </View>
  );
});

/** Раздел «Дуа» (владелец 27.11.2026: «добавить дуа, дұғалар»): тот же список, только записи с пометкой «дуа». */
export function Дуа(_: ПропсыЭкрана<'дуа'>) {
  return <СписокЗикров дуа />;
}

export function Зикры(_: ПропсыЭкрана<'зикры'>) {
  return <СписокЗикров дуа={false} />;
}

function СписокЗикров({ дуа }: { дуа: boolean }) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const тз = useСловарь(СЛОВАРЬ_ЗИКРОВ);
  const { цвет, отступ } = useТема();
  const набор = useЗикры();
  const счёт = useСчётЗикров();
  const [фильтр, установитьФильтр] = useState<'все' | 'избранное'>('все');
  const всеЗикры = набор.состояние === 'есть' ? набор.данные.зикры : [];
  const зикры = дуа ? всеЗикры.filter((з) => з.дуа) : всеЗикры;
  const показать = фильтр === 'все' ? зикры : зикры.filter((з) => счёт.избранное.includes(з.id));

  return (
    <Экран заголовок={t(дуа ? 'экран.дуа' : 'экран.зикры')} testID={дуа ? 'экран-дуа' : 'экран-зикры'}>
      <Карточка вид="арка" testID="зикры-вступление">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s }}>
          {дуа ? <ИллюстрацияРаздела имя="дуа" размер={36} /> : <Значок имя="тасбих" размер={24} цвет={цвет.акцент} />}
          <Текст стиль={{ flex: 1 }}>{т(дуа ? 'вступлениеДуа' : 'вступление')}</Текст>
        </View>
        <Плашка вид="черновик" надпись={тз('черновик')} testID="зикры-черновик" />
        <Текст вид="мелкий" testID="зикры-устройство">
          {т('устройство')}
        </Текст>
      </Карточка>

      {набор.состояние === 'загрузка' ? (
        <Текст вид="второй" testID="зикры-загрузка">
          {t('общее.загрузка')}
        </Текст>
      ) : набор.состояние === 'нет' ? (
        <ЗикрыНедоступны состояние={набор} />
      ) : (
        <View style={{ gap: отступ.m }}>
          <Вкладки
            вкладки={[
              { ключ: 'все', надпись: т('все'), testID: 'зикры-фильтр-все' },
              { ключ: 'избранное', надпись: т('избранное'), testID: 'зикры-фильтр-избранное' },
            ]}
            выбрана={фильтр}
            приВыборе={(к) => установитьФильтр(к as 'все' | 'избранное')}
            роль="выбор"
          />
          {показать.length === 0 ? (
            <Текст вид="второй" testID="зикры-избранное-пусто">
              {т('пусто')}
            </Текст>
          ) : (
            <View testID="зикры-список" {...(ВЕБ ? { role: 'list' as const } : {})} style={{ gap: отступ.s }}>
              {показать.map((з) => (
                <КарточкаЗикра key={з.id} зикр={з} запись={счёт.счёт[з.id]} избран={счёт.избранное.includes(з.id)} язык={язык} />
              ))}
            </View>
          )}
        </View>
      )}
    </Экран>
  );
}
