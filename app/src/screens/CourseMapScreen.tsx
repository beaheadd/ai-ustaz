type Т = (ключ: keyof (typeof СЛОВАРЬ)['ru'], параметры?: ПараметрыСтроки) => string;

/** Запасная карта: урок 0 и уроки, у которых есть файл (если course.json не загрузился). */
function запаснойУровень(): УровеньКурса {
  const пункты: ПунктКурса[] = [0, ...номераУроков().filter((н) => н >= 1 && н < 200)].map((номер) => ({
    номер,
    id: String(номер),
    уровень: номер === 0 ? 0 : 1,
    метка: номер > 100 ? 'К' + (номер - 100) : String(номер),
    вид: номер === 0 ? 'вход' : номер > 100 ? 'контрольная' : 'урок',
    название: { ru: '', kk: '' },
    цель: { ru: '', kk: '' },
    очередь: 'сейчас',
    статус: 'черновик',
    доступен: true,
    файл: номер === 0 ? 'lesson0.json' : 'lesson',
  }));
  return { уровень: 1, название: { ru: '', kk: '' }, пункты };
}

function названиеЭтапа(уровень: number, т: Т): string {
  return уровень === 0 ? т('вход') : т('этап', { номер: уровень });
}

export function КартаКурса(_: ПропсыЭкрана<'картаКурса'>) {
  const { t, язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { прогресс } = useПрогресс();
  const { отступ, цвет } = useТема();
  const { перейти } = useНавигация();
  const курс = useДанные('course');
  const [раскрыты, установитьРаскрыты] = useState<Record<number, boolean>>({});

  const уровни = курс.состояние === 'есть' ? курс.данные.уровни : курс.состояние === 'нет' ? [запаснойУровень()] : [];
  const этапы = статусыЭтапов(уровни, прогресс);
  // «Следующий шаг» — первый непройденный доступный пункт текущего этапа (один на карту).
  const iТекущего = этапы.indexOf('текущий');
  const следующий = iТекущего >= 0 ? (уровни[iТекущего].пункты.find((п) => п.доступен && статусПункта(п, прогресс) !== 'пройден') ?? null) : null;
  // Сводка — та же, что на главной (components/info/CourseOverview.tsx): текущий этап, вход — отдельно.
  const сводка = сводкаПути(уровни, прогресс);

  // Следующий шаг — тот же, что у «Продолжить» на главной (урок 0 → первый непройденный урок → всё пройдено).
  const шаг = следующийШаг(прогресс, номераУроков());
  const пунктШага = шаг.вид === 'урок' ? (уровни.flatMap((у) => у.пункты).find((п) => п.номер === шаг.номер) ?? null) : null;
  const меткаШага = шаг.вид === 'урок' ? (пунктШага?.метка ?? (шаг.номер > 100 ? 'К' + (шаг.номер - 100) : String(шаг.номер))) : '';
  const названиеШага =
    шаг.вид === 'урок0'
      ? т('урок0Название')
      : шаг.вид === 'урок'
        ? [т('урокНомер', { метка: меткаШага }), пунктШага ? локально(пунктШага.название, язык) : ''].filter(Boolean).join(' · ')
        : null;
  const открытьШаг =
    шаг.вид === 'урок0' ? () => перейти('урок0') : шаг.вид === 'урок' ? () => перейти('урок', { номер: шаг.номер }) : null;
  const надписьШага =
    шаг.вид === 'урок0' ? т('начатьУрок0') : шаг.вид === 'урок' ? т(шаг.начат ? 'продолжитьУрок' : 'начатьУрок', { метка: меткаШага }) : '';

  return (
    <Экран заголовок={t('экран.картаКурса')} testID="экран-карта">
      {/* Первым — действие: следующий урок и одна основная кнопка (как на главной). */}
      <Карточка вид="арка" подъём={16} testID="карта-шаг">
        <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', columnGap: отступ.s, rowGap: отступ.xs }}>
          <Плашка вид="следующий" надпись={т('следующий')} />
          {курс.состояние !== 'загрузка' && сводка ? (
            <Текст вид="метка" цвет={цвет.текстВторой} testID="карта-итого">
              {т('итого', { номер: сводка.этап.уровень, пройдено: сводка.пройдено, всего: сводка.всего })}
            </Текст>
          ) : null}
        </View>
        {названиеШага ? (
          <СмешанныйТекст вид="подзаголовок" testID="карта-шаг-название">
            {названиеШага}
          </СмешанныйТекст>
        ) : (
          <Текст testID="карта-шаг-название">{т('всёПройдено')}</Текст>
        )}
        {открытьШаг ? <Кнопка надпись={надписьШага} крупная приНажатии={открытьШаг} testID="карта-продолжить" /> : null}
      </Карточка>

      <Карточка testID="карта-вступление">
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.m }}>
          <ЭмблемаУстаза размер={40} />
          <View style={{ flex: 1, gap: 2 }}>
            <Текст вид="подзаголовок" accessibilityRole="header" уровень={2}>
              {т('путь')}
            </Текст>
            <Текст вид="мелкий">{т('девиз')}</Текст>
          </View>
        </View>
        <Текст вид="второй">{т('вступление')}</Текст>
        {уровни.length > 1 ? <ОбзорЭтапов уровни={уровни} этапы={этапы} названия={уровни.map((у) => названиеЭтапа(у.уровень, т))} /> : null}
        {курс.состояние !== 'загрузка' && сводка?.входПройден ? (
          <Текст вид="мелкий" testID="карта-вход-пройден">
            {т('входПройден')}
          </Текст>
        ) : null}
      </Карточка>

      {/* Дни занятий — сразу под путём (ревью 19.11.2026: внизу карты их было не найти). */}
      <ДниЗанятий testID="карта-дни-занятий" />

      {курс.состояние === 'загрузка' ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {курс.состояние === 'нет' ? <Текст вид="мелкий">{т('запасной')}</Текст> : null}

      <ОрнаментПолоса />

      <View>
        {уровни.map((у, i) => {
          // Этап 1 и текущий раскрыты; «Вход» — пока не пройден (пройденный свёрнут, ревью 19.11.2026).
          const раскрыт = раскрыты[у.уровень] ?? (у.уровень === 1 || этапы[i] === 'текущий' || (у.уровень === 0 && этапы[i] !== 'пройден'));
          return (
            <БлокЭтапа
              key={у.уровень}
              уровень={у}
              вид={этапы[i]}
              первый={i === 0}
              последний={i === уровни.length - 1}
              раскрыт={раскрыт}
              следующий={следующий}
              переключить={() => установитьРаскрыты((р) => ({ ...р, [у.уровень]: !раскрыт }))}
              т={т}
            />
          );
        })}
      </View>

      <СтрокаСписка заголовок={т('как')} подпись={т('какПояснение')} значок="нукта" приНажатии={() => перейти('какОбъясняем')} testID="карта-как" />

      {курс.состояние === 'есть' ? (
        <View style={{ gap: отступ.s }}>
          <ОрнаментПолоса />
          <Плашка вид="черновик" надпись={т('черновик')} />
          <Текст вид="мелкий">{т('версия', { версия: курс.данные.версия })}</Текст>
        </View>
      ) : null}
    </Экран>
  );
}

function БлокЭтапа({
  уровень,
  вид,
  первый,
  последний,
  раскрыт,
  следующий,
  переключить,
  т,
}: {
  уровень: УровеньКурса;
  вид: ВидУзла;
  первый: boolean;
  последний: boolean;
  раскрыт: boolean;
  следующий: ПунктКурса | null;
  переключить: () => void;
  т: Т;
}) {
  const { язык } = useПеревод();
  const { прогресс } = useПрогресс();
  const { цвет, отступ } = useТема();
  const доступно = уровень.пункты.filter((п) => п.доступен).length;
  const пройдено = уровень.пункты.filter((п) => статусПункта(п, прогресс) === 'пройден').length;
  const название = локально(уровень.название, язык);
  const сворачиваемый = уровень.уровень > 1 || (уровень.уровень === 0 && вид === 'пройден');
  const пункты = раскрыт ? уровень.пункты : [];
  const очередь = уровень.пункты.find((п) => !п.доступен)?.очередь as ОчередьВыпуска | undefined;

  const плашка =
    вид === 'пройден' ? (
      <Плашка вид="успех" значок="галочка" надпись={т('этапПройден')} />
    ) : вид === 'текущий' ? (
      <Плашка вид="следующий" надпись={т('этапТекущий')} />
    ) : вид === 'доступен' ? (
      <Плашка вид="инфо" надпись={т('этапДоступен')} />
    ) : (
      <Плашка вид="скоро" надпись={т(`очередь.${очередь ?? 'позже'}`)} />
    );

  const шапка = (
    <View style={{ gap: отступ.xs, paddingTop: 2 }}>
      <Текст вид="метка" цвет={вид === 'текущий' ? цвет.золотоТекст : цвет.текстВторой}>
        {названиеЭтапа(уровень.уровень, т)}
      </Текст>
      {название && уровень.уровень > 0 ? <СмешанныйТекст вид="подзаголовок">{название}</СмешанныйТекст> : null}
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', gap: отступ.s }}>
        {плашка}
        <Текст вид="мелкий">
          {вид === 'скоро' ? т('доступно', { доступно, всего: уровень.пункты.length }) : т('пройденоИз', { пройдено, всего: уровень.пункты.length })}
        </Текст>
      </View>
      {сворачиваемый ? (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: 4, minHeight: 32 }} aria-hidden>
          <Текст вид="метка" цвет={цвет.акцент}>
            {раскрыт ? т('скрыть') : т('показать')}
          </Текст>
          <Значок имя={раскрыт ? 'вверх' : 'вниз'} размер={18} цвет={цвет.акцент} />
        </View>
      ) : null}
    </View>
  );

  return (
    <View testID={'карта-уровень-' + уровень.уровень}>
      <ШагПути
        первый={первый}
        последний={последний && пункты.length === 0}
        линия={вид === 'скоро' ? 'тихая' : 'сплошная'}
        верхУзла={2}
        узел={<УзелПути вид={вид} размер={40} значок={вид === 'пройден' ? 'галочка' : undefined} метка={вид === 'пройден' ? undefined : String(уровень.уровень)} />}
      >
        {сворачиваемый ? (
          <Pressable
            accessibilityRole="button"
            aria-expanded={раскрыт}
            accessibilityHint={раскрыт ? т('скрыть') : т('показать')}
            onPress={переключить}
            testID={'карта-уровень-' + уровень.уровень + '-заголовок'}
            style={({ pressed }) => ({ opacity: pressed ? 0.7 : 1, paddingBottom: отступ.s })}
          >
            {шапка}
          </Pressable>
        ) : (
          <View accessibilityRole="header" testID={'карта-уровень-' + уровень.уровень + '-заголовок'} style={{ paddingBottom: отступ.s }}>
            {шапка}
          </View>
        )}
      </ШагПути>
      {пункты.map((п, j) => (
        <СтрокаПункта
          key={п.номер + '-' + п.id}
          пункт={п}
          следующий={следующий === п}
          последний={последний && j === пункты.length - 1}
          т={т}
        />
      ))}
    </View>
  );
}

function СтрокаПункта({ пункт, следующий, последний, т }: { пункт: ПунктКурса; следующий: boolean; последний: boolean; т: Т }) {
  const { язык } = useПеревод();
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { цвет, отступ, радиус } = useТема();
  const статус = статусПункта(пункт, прогресс);
  const открыть = пункт.доступен
    ? () => (пункт.номер === 0 || пункт.вид === 'вход' ? перейти('урок0') : перейти('урок', { номер: пункт.номер }))
    : undefined;
  const название = локально(пункт.название, язык) || т('урокНомер', { метка: пункт.метка });
  const цель = локально(пункт.цель, язык);
  const вид =
    пункт.вид === 'контрольная' ? т('контрольная') : пункт.вид === 'намаз' ? т('намаз') : пункт.вид === 'итог' ? т('итог') : null;
  const особый = пункт.вид !== 'урок' && пункт.вид !== 'вход';
  const видУзла: ВидУзла = статус === 'пройден' ? 'пройден' : следующий ? 'текущий' : статус === 'скоро' ? 'скоро' : 'доступен';

  const статусЭлемент =
    статус === 'пройден' ? (
      <Плашка вид="успех" значок="галочка" надпись={т('пройден')} testID={'карта-статус-' + пункт.номер} />
    ) : статус === 'скоро' ? (
      <Текст вид="мелкий" testID={'карта-статус-' + пункт.номер}>
        {т(`очередь.${пункт.очередь as ОчередьВыпуска}`)}
      </Текст>
    ) : (
      <View style={{ flexDirection: 'row', flexWrap: 'wrap', alignItems: 'center', gap: отступ.s }}>
        {следующий ? <Плашка вид="следующий" надпись={т('следующий')} testID="карта-следующий" /> : null}
        <Текст вид="метка" цвет={цвет.акцент} testID={'карта-статус-' + пункт.номер}>
          {статус === 'начат' ? т('начат') : т('доступен')}
        </Текст>
      </View>
    );

  const тело = (
    <View style={{ flexDirection: 'row', gap: отступ.s, alignItems: 'center' }}>
      <View style={{ flex: 1, gap: 2 }}>
        {вид ? (
          <Текст вид="метка" цвет={цвет.золотоТекст}>
            {вид}
          </Текст>
        ) : null}
        {/* Названия и цели содержат арабские буквы: СмешанныйТекст изолирует их направление. */}
        <СмешанныйТекст стиль={{ fontWeight: '600' }}>{название}</СмешанныйТекст>
        {цель ? <СмешанныйТекст вид="мелкий">{цель}</СмешанныйТекст> : null}
        {пункт.примечание ? <СмешанныйТекст вид="мелкий">{локально(пункт.примечание, язык)}</СмешанныйТекст> : null}
        <View style={{ paddingTop: отступ.xs }}>{статусЭлемент}</View>
      </View>
      {открыть ? <Значок имя="вперёд" размер={20} цвет={цвет.текстВторой} /> : null}
    </View>
  );

  return (
    <ШагПути
      последний={последний}
      линия={статус === 'скоро' ? 'тихая' : 'сплошная'}
      верхУзла={14}
      узел={
        <УзелПути вид={видУзла} размер={34} форма={особый ? 'квадрат' : 'круг'} метка={пункт.метка} />
      }
    >
      {открыть ? (
        <Карточка приНажатии={открыть} testID={'карта-урок-' + пункт.номер} стиль={следующий ? { borderColor: цвет.следующийФон, borderWidth: 2 } : undefined}>
          {тело}
        </Карточка>
      ) : (
        // Ещё не вышло: пунктирная рамка, без тени и нажатия.
        <View
          testID={'карта-урок-' + пункт.номер}
          style={{ borderWidth: 1, borderStyle: 'dashed', borderColor: цвет.границаЭлемента, borderRadius: радиус.l, padding: отступ.l, gap: отступ.s }}
        >
          {тело}
        </View>
      )}
    </ШагПути>
  );
}
