type Статус = 'пройден' | 'начат' | 'доступен' | 'скоро';

export function статусПункта(п: Pick<ПунктКурса, 'номер' | 'доступен'>, прогресс: Прогресс): Статус {
  const итог = прогресс.уроки[String(п.номер)];
  if (итог?.пройден) return 'пройден';
  if (!п.доступен) return 'скоро';
  return (итог?.попыток ?? 0) > 0 ? 'начат' : 'доступен';
}

/** Запасная карта: урок 0 и уроки, у которых есть файл (если course.json не загрузился). */
function запаснойУровень(): УровеньКурса {
  const пункты: ПунктКурса[] = [0, ...номераУроков().filter((н) => н >= 1 && н < 200)].map((номер) => ({
    номер,
    id: String(номер),
    уровень: номер === 0 ? 0 : 1,
    метка: номер > 100 ? 'К' + (номер - 100) : String(номер),
    вид: номер === 0 ? 'вход' : номер > 100 ? 'контрольная' : 'урок',
    название: { ru: '', kk: '' },
    цель: { ru: '', kk: '' },
    очередь: 'сейчас',
    статус: 'черновик',
    доступен: true,
    файл: номер === 0 ? 'lesson0.json' : 'lesson',
  }));
  return { уровень: 1, название: { ru: '', kk: '' }, пункты };
}

export function КартаКурса(_: ПропсыЭкрана<'картаКурса'>) {
  const { t } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const курс = useДанные('course');
  const [раскрыты, установитьРаскрыты] = useState<Record<number, boolean>>({});

  const уровни = курс.состояние === 'есть' ? курс.данные.уровни : курс.состояние === 'нет' ? [запаснойУровень()] : [];

  return (
    <Экран заголовок={t('экран.картаКурса')} плашка="общая" testID="экран-карта">
      <Текст вид="второй">{т('вступление')}</Текст>
      {курс.состояние === 'загрузка' ? <Текст вид="второй">{t('общее.загрузка')}</Текст> : null}
      {курс.состояние === 'нет' ? <Текст вид="мелкий">{т('запасной')}</Текст> : null}
      {уровни.map((у) => {
        const раскрыт = раскрыты[у.уровень] ?? у.уровень <= 1;
        return (
          <БлокУровня
            key={у.уровень}
            уровень={у}
            раскрыт={раскрыт}
            переключить={() => установитьРаскрыты((р) => ({ ...р, [у.уровень]: !раскрыт }))}
          />
        );
      })}
      {курс.состояние === 'есть' ? <Текст вид="мелкий">{т('версия', { версия: курс.данные.версия })}</Текст> : null}
    </Экран>
  );
}

function БлокУровня({ уровень, раскрыт, переключить }: { уровень: УровеньКурса; раскрыт: boolean; переключить: () => void }) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { цвет, отступ } = useТема();
  const доступно = уровень.пункты.filter((п) => п.доступен).length;
  const заголовок = уровень.уровень === 0 ? т('вход') : т('уровень', { номер: уровень.уровень });
  const название = локально(уровень.название, язык);
  const сворачиваемый = уровень.уровень > 1;
  return (
    <View style={{ gap: отступ.s }} testID={'карта-уровень-' + уровень.уровень}>
      <Pressable
        accessibilityRole={сворачиваемый ? 'button' : 'header'}
        accessibilityState={сворачиваемый ? { expanded: раскрыт } : undefined}
        disabled={!сворачиваемый}
        onPress={переключить}
        testID={'карта-уровень-' + уровень.уровень + '-заголовок'}
        style={{ flexDirection: 'row', alignItems: 'center', gap: отступ.s, paddingVertical: отступ.xs, minHeight: 44 }}
      >
        <View style={{ flex: 1, gap: 2 }}>
          <Текст вид="подзаголовок">{название && уровень.уровень > 0 ? `${заголовок}. ${название}` : заголовок}</Текст>
          <Текст вид="мелкий">{т('доступно', { доступно, всего: уровень.пункты.length })}</Текст>
        </View>
        {сворачиваемый ? (
          <Текст стиль={{ color: цвет.акцент }} accessibilityElementsHidden importantForAccessibility="no">
            {(раскрыт ? т('скрыть') : т('показать')) + (раскрыт ? ' ▾' : ' ▸')}
          </Текст>
        ) : null}
      </Pressable>
      {раскрыт ? уровень.пункты.map((п) => <СтрокаПункта key={п.номер + '-' + п.id} пункт={п} />) : null}
    </View>
  );
}

function СтрокаПункта({ пункт }: { пункт: ПунктКурса }) {
  const { язык } = useПеревод();
  const т = useСловарь(СЛОВАРЬ);
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  const { цвет, отступ, радиус } = useТема();
  const статус = статусПункта(пункт, прогресс);
  const открыть = пункт.доступен
    ? () => (пункт.номер === 0 || пункт.вид === 'вход' ? перейти('урок0') : перейти('урок', { номер: пункт.номер }))
    : undefined;
  const название = локально(пункт.название, язык) || т('урокНомер', { метка: пункт.метка });
  const цель = локально(пункт.цель, язык);
  const вид =
    пункт.вид === 'контрольная' ? т('контрольная') : пункт.вид === 'намаз' ? т('намаз') : пункт.вид === 'итог' ? т('итог') : null;
  const особый = пункт.вид !== 'урок' && пункт.вид !== 'вход';
  const подписьСтатуса =
    статус === 'пройден'
      ? т('пройден')
      : статус === 'начат'
        ? т('начат')
        : статус === 'доступен'
          ? т('доступен')
          : т(`очередь.${пункт.очередь as ОчередьВыпуска}`);
  const цветСтатуса = статус === 'пройден' ? цвет.успех : статус === 'скоро' ? цвет.текстВторой : цвет.акцент;

  return (
    <Карточка приНажатии={открыть} testID={'карта-урок-' + пункт.номер} стиль={пункт.доступен ? undefined : { opacity: 0.85 }}>
      <View style={{ flexDirection: 'row', gap: отступ.m, alignItems: 'flex-start' }}>
        <View
          accessibilityElementsHidden
          importantForAccessibility="no"
          style={{
            minWidth: 40,
            height: 40,
            paddingHorizontal: 4,
            borderRadius: особый ? радиус.s : радиус.круг,
            alignItems: 'center',
            justifyContent: 'center',
            backgroundColor: статус === 'пройден' ? цвет.успех : пункт.доступен ? цвет.акцент : цвет.акцентМягкий,
          }}
        >
          <Текст стиль={{ fontWeight: '700', color: пункт.доступен || статус === 'пройден' ? цвет.акцентТекст : цвет.акцент }}>
            {пункт.метка}
          </Текст>
        </View>
        <View style={{ flex: 1, gap: 2 }}>
          {вид ? (
            <Текст вид="мелкий" стиль={{ fontWeight: '600', color: цвет.внимание }}>
              {вид}
            </Текст>
          ) : null}
          {/* Названия и цели содержат арабские буквы: СмешанныйТекст изолирует их направление. */}
          <СмешанныйТекст стиль={{ fontWeight: '600' }}>{название}</СмешанныйТекст>
          {цель ? <СмешанныйТекст вид="мелкий">{цель}</СмешанныйТекст> : null}
          {пункт.примечание ? <СмешанныйТекст вид="мелкий">{локально(пункт.примечание, язык)}</СмешанныйТекст> : null}
          <Текст вид="мелкий" стиль={{ color: цветСтатуса, fontWeight: '600' }} testID={'карта-статус-' + пункт.номер}>
            {подписьСтатуса}
          </Текст>
        </View>
        {открыть ? (
          <Текст стиль={{ color: цвет.текстВторой, fontSize: 22 }} accessibilityElementsHidden importantForAccessibility="no">
            ›
          </Текст>
        ) : null}
      </View>
    </Карточка>
  );
}
