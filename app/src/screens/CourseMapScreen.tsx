/**
 * Карта курса: уровни и уроки (программа курса §5–8), отметки пройденного — из прогресса.
 * ЗАГЛУШКА каркаса — заменит агент карты курса (данные — реестр уроков из /content).
 * Контракт: ПропсыЭкрана<'картаКурса'>.
 */
import { Карточка, Текст, Экран } from '../components';
import { useНавигация } from '../engine/navigation';
import { useПрогресс } from '../engine/progress';
import type { ПропсыЭкрана } from '../engine/routes';
import { useПеревод } from '../i18n';

const УРОКИ_ЗАГЛУШКИ = [1, 2, 3];

export function КартаКурса(_: ПропсыЭкрана<'картаКурса'>) {
  const { t } = useПеревод();
  const { перейти } = useНавигация();
  const { прогресс } = useПрогресс();
  return (
    <Экран заголовок={t('экран.картаКурса')} плашка="общая" testID="экран-карта">
      <Карточка заголовок={t('экран.урок0')} приНажатии={() => перейти('урок0')} testID="карта-урок-0" />
      {УРОКИ_ЗАГЛУШКИ.map((номер) => (
        <Карточка
          key={номер}
          заголовок={t('экран.урок', { номер }) + (прогресс.уроки[String(номер)]?.пройден ? ' ✓' : '')}
          приНажатии={() => перейти('урок', { номер })}
          testID={'карта-урок-' + номер}
        />
      ))}
      <Текст вид="второй">{t('общее.вРазработке')}</Текст>
    </Экран>
  );
}
