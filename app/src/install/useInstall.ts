/**
 * Хуки установки AI Ustaz на телефон (экран #/install и строка на главной).
 *
 * Контракт:
 *   useУстановка() → { среда, сценарий, естьПредложение, предложить } — среда и сценарий (install/platform.ts)
 *     пересчитываются, когда приходит beforeinstallprompt или appinstalled; предложить() — системное окно Chrome.
 *   useПодсказкаУстановки() → { показать, скрыть } — одноразовая строка на главной: только на своём домене
 *     (aiustaz.pro), только на телефоне, только пока приложение не установлено и человек её не скрыл и не открыл
 *     экран установки (ключ aiustaz:install-hint.v1 — только отметка «скрыта», без личных данных).
 * Решение владельца 19.11.2026 (установка на экран «Домой»); главная — компактная, поэтому одна узкая строка.
 */
import { useCallback, useEffect, useMemo, useState, useSyncExternalStore } from 'react';
import { прочитатьJSON, записатьJSON } from '../engine/storage';
import { естьПредложение, подписаться, предложитьУстановку, прочитатьСреду, версия } from './browser';
import { сценарий, этоТелефон, type Сценарий, type Среда } from './platform';

export const КЛЮЧ_ПОДСКАЗКИ = 'install-hint.v1';

export function useУстановка(): {
  среда: Среда;
  сценарий: Сценарий;
  естьПредложение: boolean;
  предложить: () => Promise<'принято' | 'отклонено' | 'недоступно'>;
} {
  const в = useSyncExternalStore(подписаться, версия, версия);
  return useMemo(() => {
    const среда = прочитатьСреду();
    const есть = естьПредложение();
    return { среда, сценарий: сценарий(среда, есть), естьПредложение: есть, предложить: предложитьУстановку };
    // в — номер изменения: пересчитать после beforeinstallprompt / appinstalled
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [в]);
}

export function отметитьПодсказкуУстановки(): void {
  void записатьJSON(КЛЮЧ_ПОДСКАЗКИ, { скрыта: true });
}

export function useПодсказкаУстановки(): { показать: boolean; скрыть: () => void } {
  const { среда } = useУстановка();
  const [скрыта, установитьСкрыта] = useState(true);
  useEffect(() => {
    let жив = true;
    void прочитатьJSON<{ скрыта?: boolean } | null>(КЛЮЧ_ПОДСКАЗКИ, null).then((з) => {
      if (жив) установитьСкрыта(з?.скрыта === true);
    });
    return () => {
      жив = false;
    };
  }, []);
  const скрыть = useCallback(() => {
    установитьСкрыта(true);
    отметитьПодсказкуУстановки();
  }, []);
  const показать = !скрыта && среда.хост === 'свой' && этоТелефон(среда) && !среда.установлено;
  return { показать, скрыть };
}
