/** Код MediaError → наша ошибка (1 ABORTED — не ошибка). */
export function ошибкаПоКоду(код: number, вСети: boolean): ОшибкаПлеера | null {
  if (код === 1) return null;
  if (!вСети || код === 2) return 'нет-связи';
  if (код === 3) return 'не-поддерживается';
  return 'нет-файла'; // 4: нет файла (404) или формат не тот
}

const ДЕЙСТВИЯ: readonly ДействиеСессии[] = ['play', 'pause', 'stop', 'previoustrack', 'nexttrack', 'seekto'];

export function создатьПлеер<И extends ИсточникЗвука>(з: ЗависимостиПлеера<И>): Плеер<И> {
  let элемент: ЭлементЗвука | null = null;
  let нетЭлемента = false;
  let очередь: Очередь | null = null;
  let шаг: Шаг | null = null;
  let источникИгры: И | null = null;
  /** Чего хочет человек: от этого зависит, как понимать события элемента. */
  let намерение: 'играть' | 'пауза' | 'стоп' = 'стоп';
  let состояние: СостояниеПлеера = 'стоп';
  let ошибка: ОшибкаПлеера | undefined;
  /** Растёт при каждой смене файла: поздние отказы play() и события старого файла не трогают новый. */
  let поколение = 0;
  let предзагруженоДля = -1;
  let сессияГотова = false;
  let повторАята: number;
  const слушатели = new Set<() => void>();
  /** адрес файла → предзагрузка (blob: URL, когда готово). */
  const кэш = new Map<string, { готово: string | null; нужен: boolean }>();

  // Сохранённое на этом устройстве: повтор аята и последний аят (последнийАят()).
  const сохранённое = прочитатьСохранённое();
  повторАята = сохранённое.повторАята;
  let последний: ПоследнийАят | null = сохранённое.последний;

  let снимокСейчас: СнимокПлеера<И> = собратьСнимок();

  function прочитатьСохранённое(): { последний: ПоследнийАят | null; повторАята: number } {
    const пусто = { последний: null, повторАята: 1 };
    try {
      const строка = з.хранилище?.прочитать(КЛЮЧ_ХРАНИЛИЩА);
      if (!строка) return пусто;
      const д = JSON.parse(строка) as Record<string, unknown> | null;
      if (!д || typeof д !== 'object' || д.версия !== 1) return пусто;
      const сура = целое(д.сура) ?? 0;
      const аят = целое(д.аят) ?? 0;
      const п = целое(д.повторАята) ?? 1;
      return {
        последний: аятовВСуре(сура) && аят >= 1 && аят <= аятовВСуре(сура) ? { сура, аят } : null,
        повторАята: Math.min(МАКС_ПОВТОР, Math.max(1, п)),
      };
    } catch {
      return пусто; // хранилище недоступно или испорчено — просто не помним
    }
  }

  function сохранить() {
    if (очередь && шаг && шаг.вид === 'аят') последний = { сура: очередь.сура, аят: шаг.аят };
    try {
      з.хранилище?.записать(КЛЮЧ_ХРАНИЛИЩА, JSON.stringify({ версия: 1, ...(последний ?? {}), повторАята }));
    } catch {
      // приватный режим, переполнено — без памяти о последнем аяте
    }
  }

  function собратьСнимок(): СнимокПлеера<И> {
    const текущий: ТекущийАят | null =
      очередь && шаг && состояние !== 'стоп'
        ? {
            сура: очередь.сура,
            аят: шаг.вид === 'аят' ? шаг.аят : очередь.сАята,
            повтор: шаг.вид === 'аят' ? шаг.повтор : 1,
            из: шаг.вид === 'аят' ? очередь.повторАята : 1,
            бисмилла: шаг.вид === 'бисмилла',
          }
        : null;
    let источник: И | null = null;
    try {
      источник = з.источник();
    } catch {
      источник = null;
    }
    return {
      состояние,
      текущий,
      очередь: очередь && состояние !== 'стоп' ? { ...очередь } : null,
      ...(ошибка ? { ошибка } : {}),
      источник,
      можноНазад: !!(очередь && шаг && шаг.вид === 'аят' && шаг.аят > очередь.сАята),
      можноВперёд: !!(очередь && шаг && состояние !== 'стоп' && шагВперёд(очередь, шаг)),
      повторАята,
    };
  }

  function обновить() {
    снимокСейчас = собратьСнимок();
    for (const с of [...слушатели]) {
      try {
        с();
      } catch {
        // ошибка подписчика не ломает плеер
      }
    }
  }

  function установить(новое: СостояниеПлеера, новаяОшибка?: ОшибкаПлеера) {
    состояние = новое;
    ошибка = новое === 'ошибка' ? новаяОшибка : undefined;
    обновитьСостояниеСессии();
    обновить();
  }

  // ── Media Session ──

  function сессия(): СессияМедиа | null {
    try {
      return з.сессия?.() ?? null;
    } catch {
      return null;
    }
  }

  function подготовитьСессию() {
    const с = сессия();
    if (!с || сессияГотова) return;
    сессияГотова = true;
    const обработчики: Record<ДействиеСессии, (д: ДеталиДействия) => void> = {
      play: () => продолжить(),
      pause: () => пауза(),
      stop: () => стоп(),
      previoustrack: () => void предыдущий(),
      nexttrack: () => void следующий(),
      seekto: (д) => перемотать(д),
    };
    for (const д of ДЕЙСТВИЯ) {
      try {
        с.setActionHandler(д, обработчики[д]);
      } catch {
        // старый браузер не знает действие (например, stop или seekto) — пропускаем
      }
    }
  }

  function обновитьМетаданные() {
    const с = сессия();
    if (!с) return;
    try {
      if (!очередь || !шаг) {
        с.metadata = null;
        return;
      }
      const п = з.подписи(очередь.сура, шаг, очередь.повторАята);
      с.metadata = з.метаданные ? з.метаданные({ title: п.название, artist: п.исполнитель, album: п.альбом }) : null;
    } catch {
      // MediaMetadata недоступен — без подписи на экране блокировки
    }
  }

  function обновитьСостояниеСессии() {
    const с = сессия();
    if (!с) return;
    try {
      с.playbackState = состояние === 'играет' || состояние === 'загрузка' ? 'playing' : состояние === 'пауза' ? 'paused' : 'none';
    } catch {
      // нет playbackState
    }
  }

  function обновитьПозицию() {
    const с = сессия();
    if (!с || !элемент || typeof с.setPositionState !== 'function') return;
    try {
      const длительность = элемент.duration;
      if (!Number.isFinite(длительность) || длительность <= 0) return;
      const позиция = Math.min(Math.max(0, элемент.currentTime || 0), длительность);
      с.setPositionState({ duration: длительность, playbackRate: элемент.playbackRate > 0 ? элемент.playbackRate : 1, position: позиция });
    } catch {
      // браузер отверг значения — без полосы позиции
    }
  }

  function перемотать(д: ДеталиДействия) {
    if (!элемент || typeof д.seekTime !== 'number' || !Number.isFinite(д.seekTime)) return;
    const длительность = Number.isFinite(элемент.duration) ? элемент.duration : Infinity;
    элемент.currentTime = Math.min(Math.max(0, д.seekTime), длительность);
    обновитьПозицию();
  }

  // ── Элемент ──

  function получитьЭлемент(): ЭлементЗвука | null {
    if (элемент || нетЭлемента) return элемент;
    try {
      элемент = з.создатьЭлемент();
    } catch {
      элемент = null;
    }
    if (!элемент) {
      нетЭлемента = true;
      return null;
    }
    const э = элемент;
    try {
      э.preload = 'auto';
    } catch {
      // только чтение — не важно
    }
    э.addEventListener('playing', () => {
      if (намерение !== 'играть') return;
      установить('играет');
      обновитьПозицию();
      предзагрузитьСледующий();
    });
    э.addEventListener('waiting', () => {
      if (намерение === 'играть' && состояние === 'играет') установить('загрузка');
    });
    э.addEventListener('pause', () => {
      // Перед `ended` браузер шлёт pause — это не пауза человека. Пауза ОС (звонок, наушники) — пауза.
      if (э.ended || намерение !== 'играть') return;
      намерение = 'пауза';
      установить('пауза');
    });
    э.addEventListener('play', () => {
      // Продолжили не через нас (встроенные кнопки ОС без Media Session): идём за ними.
      if (намерение === 'пауза' && шаг) {
        намерение = 'играть';
        установить('загрузка');
      }
    });
    э.addEventListener('ended', () => обработатьКонец());
    э.addEventListener('error', () => {
      if (намерение === 'стоп' || !шаг) return;
      const о = ошибкаПоКоду(э.error?.code ?? 4, вСети());
      if (!о) return;
      намерение = 'пауза';
      установить('ошибка', о);
    });
    for (const тип of ['loadedmetadata', 'durationchange', 'ratechange', 'seeked']) э.addEventListener(тип, обновитьПозицию);
    return э;
  }

  function вСети(): boolean {
    try {
      return з.вСети ? з.вСети() !== false : true;
    } catch {
      return true;
    }
  }

  function запуститьИгру() {
    if (!элемент) return;
    const п = поколение;
    let обещание: Promise<void> | void;
    try {
      обещание = элемент.play();
    } catch (е) {
      отказИгры(е, п);
      return;
    }
    if (обещание && typeof (обещание as Promise<void>).then === 'function') (обещание as Promise<void>).then(undefined, (е: unknown) => отказИгры(е, п));
  }

  function отказИгры(е: unknown, п: number) {
    if (п !== поколение || намерение !== 'играть') return; // файл уже сменили или человек нажал паузу/стоп
    const имя = (е as { name?: string } | null)?.name;
    if (имя === 'AbortError') return;
    if (имя === 'NotAllowedError') {
      // Браузер не дал играть без нажатия (например, после долгой паузы в фоне на iOS) — ждём «Продолжить».
      намерение = 'пауза';
      установить('пауза');
      return;
    }
    if (состояние === 'ошибка') return; // событие error уже объяснило
    const код = элемент?.error?.code;
    намерение = 'пауза';
    установить('ошибка', (код != null ? ошибкаПоКоду(код, вСети()) : null) ?? (вСети() ? 'не-поддерживается' : 'нет-связи'));
  }

  /** Поставить файл шага в элемент. играть — сразу play() (из нажатия или из `ended`), иначе ждать «Продолжить». */
  function загрузитьШаг(новый: Шаг, играть: boolean) {
    if (!элемент || !очередь || !источникИгры) return;
    поколение += 1;
    шаг = новый;
    const адрес = адресШага(источникИгры, очередь, новый);
    const готовый = кэш.get(адрес)?.готово ?? null;
    элемент.src = готовый ?? адрес;
    освободитьЛишнее(адрес, null);
    намерение = играть ? 'играть' : 'пауза';
    сохранить();
    установить(играть ? 'загрузка' : 'пауза');
    обновитьМетаданные();
    if (играть) запуститьИгру();
  }

  function обработатьКонец() {
    if (!очередь || !шаг || намерение !== 'играть') return;
    const след = шагПослеКонца(очередь, шаг);
    if (!след) {
      завершить();
      return;
    }
    if (одинФайл(шаг, след)) {
      // Повтор того же аята: тот же файл сначала, без смены src.
      шаг = след;
      поколение += 1;
      if (элемент) элемент.currentTime = 0;
      установить('загрузка');
      обновитьМетаданные();
      запуститьИгру();
      return;
    }
    загрузитьШаг(след, true);
  }

  function предзагрузитьСледующий() {
    if (!з.предзагрузить || !очередь || !шаг || !источникИгры || предзагруженоДля === поколение) return;
    предзагруженоДля = поколение;
    const след = следующийФайл(очередь, шаг);
    if (!след) return;
    const адрес = адресШага(источникИгры, очередь, след);
    освободитьЛишнее(адресШага(источникИгры, очередь, шаг), адрес);
    if (кэш.has(адрес)) return;
    const запись = { готово: null as string | null, нужен: true };
    кэш.set(адрес, запись);
    let обещание: Promise<string | null>;
    try {
      обещание = з.предзагрузить(адрес);
    } catch {
      кэш.delete(адрес);
      return;
    }
    обещание.then(
      (url) => {
        if (!url) {
          if (кэш.get(адрес) === запись) кэш.delete(адрес);
          return;
        }
        if (кэш.get(адрес) === запись && запись.нужен) запись.готово = url;
        else освободитьОбъект(url);
      },
      () => {
        if (кэш.get(адрес) === запись) кэш.delete(адрес); // не скачалось — сыграем прямой адрес
      },
    );
  }

  function освободитьОбъект(url: string) {
    try {
      з.освободить?.(url);
    } catch {
      // уже освобождён
    }
  }

  /** Оставить в кэше только текущий и следующий файлы; остальные blob освободить. */
  function освободитьЛишнее(текущий: string | null, следующий: string | null) {
    for (const [адрес, запись] of [...кэш]) {
      if (адрес === текущий || адрес === следующий) continue;
      запись.нужен = false;
      кэш.delete(адрес);
      if (запись.готово) освободитьОбъект(запись.готово);
    }
  }

  function завершить() {
    намерение = 'стоп';
    поколение += 1;
    if (элемент) {
      try {
        элемент.pause();
        элемент.removeAttribute('src');
        элемент.load();
      } catch {
        // элемент уже пуст
      }
    }
    очередь = null;
    шаг = null;
    источникИгры = null;
    освободитьЛишнее(null, null);
    установить('стоп');
    обновитьМетаданные();
  }

  // ── Команды ──

  function играть(запрос: ЗапросОчереди): boolean {
    const о = нормализоватьОчередь(запрос, повторАята);
    if (!о) return false;
    let и: И | null = null;
    try {
      и = з.источник();
    } catch {
      и = null;
    }
    if (!и) {
      установить('ошибка', 'нет-источника');
      return false;
    }
    const э = получитьЭлемент();
    if (!э) {
      установить('ошибка', 'не-поддерживается');
      return false;
    }
    if (запрос.повторАята != null) повторАята = о.повторАята;
    else о.повторАята = повторАята;
    подготовитьСессию();
    if (источникИгры && источникИгры.id !== и.id) освободитьЛишнее(null, null);
    источникИгры = и;
    очередь = о;
    загрузитьШаг(первыйШаг(о, !!и.бисмилла), true);
    return true;
  }

  function пауза() {
    if (!элемент || (состояние !== 'играет' && состояние !== 'загрузка')) return;
    намерение = 'пауза';
    элемент.pause();
    установить('пауза');
  }

  function продолжить() {
    if (!элемент || !шаг || !очередь) return;
    if (состояние === 'пауза') {
      намерение = 'играть';
      установить('загрузка');
      запуститьИгру();
    } else if (состояние === 'ошибка' && ошибка !== 'нет-источника') {
      загрузитьШаг(шаг, true); // «Повторить»: тот же аят заново (связь могла вернуться)
    }
  }

  function переключить() {
    if (состояние === 'играет' || состояние === 'загрузка') пауза();
    else продолжить();
  }

  function стоп() {
    if (состояние === 'стоп' && !очередь) return;
    завершить();
  }

  function перейти(новый: Шаг | null): boolean {
    if (!новый || !очередь || !элемент) return false;
    const играть = намерение === 'играть' || состояние === 'ошибка';
    загрузитьШаг(новый, играть);
    return true;
  }

  function следующий(): boolean {
    if (!очередь || !шаг || состояние === 'стоп') return false;
    return перейти(шагВперёд(очередь, шаг));
  }

  function предыдущий(): boolean {
    if (!очередь || !шаг || состояние === 'стоп') return false;
    return перейти(шагНазад(очередь, шаг));
  }

  function кАяту(аят: number): boolean {
    if (!очередь || состояние === 'стоп' || !Number.isInteger(аят) || аят < 1 || аят > аятовВСуре(очередь.сура)) return false;
    if (аят < очередь.сАята) очередь = { ...очередь, сАята: аят };
    if (аят > очередь.поАят) очередь = { ...очередь, поАят: аят };
    return перейти({ вид: 'аят', аят, повтор: 1 });
  }

  function установитьПовтор(раз: number) {
    if (!Number.isInteger(раз)) return;
    повторАята = Math.min(МАКС_ПОВТОР, Math.max(1, раз));
    if (очередь) очередь = { ...очередь, повторАята };
    сохранить();
    обновитьМетаданные();
    обновить();
  }

  function установитьПовторОтрезка(поКругу: boolean) {
    if (!очередь) return;
    очередь = { ...очередь, повторОтрезка: поКругу === true };
    обновить();
  }

  function обновитьПодписи() {
    обновитьМетаданные();
    обновить();
  }

  return {
    играть,
    пауза,
    продолжить,
    переключить,
    стоп,
    следующий,
    предыдущий,
    кАяту,
    установитьПовтор,
    установитьПовторОтрезка,
    обновитьПодписи,
    снимок: () => снимокСейчас,
    подписаться(слушатель) {
      слушатели.add(слушатель);
      return () => {
        слушатели.delete(слушатель);
      };
    },
    последнийАят: () => (последний ? { ...последний } : null),
  };
}
