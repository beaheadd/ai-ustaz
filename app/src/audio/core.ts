/** Минимум, что ядру нужно от источника (полная запись — audio/sources.ts ИсточникЧтения). */
export type ИсточникЗвука = { id: string; база: string; шаблон: string; бисмилла: string | null };

const три = (н: number) => String(н).padStart(3, '0');

export function адресАята(и: ИсточникЗвука, сура: number, аят: number): string {
  return и.база + '/' + и.шаблон.replace('{sura3}', три(сура)).replace('{aya3}', три(аят));
}

export function адресШага(и: ИсточникЗвука, о: Очередь, ш: Шаг): string {
  return ш.вид === 'бисмилла' && и.бисмилла ? и.база + '/' + и.бисмилла : адресАята(и, о.сура, ш.вид === 'аят' ? ш.аят : 1);
}

