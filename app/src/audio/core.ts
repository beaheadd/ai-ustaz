/** Варианты повтора аята для кнопки панели; допустимо 1…МАКС_ПОВТОР. */
export const ПОВТОРЫ_АЯТА: readonly number[] = [1, 3, 5];
export const МАКС_ПОВТОР = 9;
/** localStorage (с префиксом aiustaz:): { версия: 1, сура, аят, повторАята } — только на этом устройстве. */
export const КЛЮЧ_ХРАНИЛИЩА = 'aiustaz:quran-player.v1';

export function аятовВСуре(сура: number): number {
  return Number.isInteger(сура) && сура >= 1 && сура <= 114 ? АЯТОВ_В_СУРЕ[сура - 1] : 0;
}

// ───────────────────────── Очередь ─────────────────────────

export type Очередь = {
  сура: number;
  сАята: number;
  поАят: number;
  /** Сколько раз читать каждый аят (1…9). */
  повторАята: number;
  /** После последнего аята отрезка — снова с первого (до «Стоп»). */
  повторОтрезка: boolean;
  /** Бисмилла перед аятом 1 (если у источника она отдельным файлом; не у сур 1 и 9). */
  бисмиллаПеред: boolean;
};

/** То, что передают экраны: обязательна только сура. */
export type ЗапросОчереди = { сура: number } & Partial<Omit<Очередь, 'сура'>>;

export type Шаг = { вид: 'бисмилла' } | { вид: 'аят'; аят: number; повтор: number };

function целое(з: unknown): number | null {
  return typeof з === 'number' && Number.isInteger(з) ? з : null;
}

export function нормализоватьОчередь(з: ЗапросОчереди, повторПоУмолчанию = 1): Очередь | null {
  const аятов = аятовВСуре(з.сура);
  if (!аятов) return null;
  const с = з.сАята == null ? 1 : целое(з.сАята);
  if (с == null || с < 1 || с > аятов) return null;
  const по = з.поАят == null ? аятов : целое(з.поАят);
  if (по == null || по < с || по > аятов) return null;
  const п = целое(з.повторАята ?? повторПоУмолчанию) ?? 1;
  return {
    сура: з.сура,
    сАята: с,
    поАят: по,
    повторАята: Math.min(МАКС_ПОВТОР, Math.max(1, п)),
    повторОтрезка: з.повторОтрезка === true,
    бисмиллаПеред: з.бисмиллаПеред ?? с === 1,
  };
}

/** Бисмилла отдельным файлом — только перед аятом 1 сур 2–8 и 10–114 (у суры 1 она — аят 1:1, у суры 9 её нет). */
export function бисмиллаНужна(о: Очередь, естьБисмилла: boolean): boolean {
  return естьБисмилла && о.бисмиллаПеред && о.сАята === 1 && о.сура !== 1 && о.сура !== 9;
}

export function первыйШаг(о: Очередь, естьБисмилла: boolean): Шаг {
  return бисмиллаНужна(о, естьБисмилла) ? { вид: 'бисмилла' } : { вид: 'аят', аят: о.сАята, повтор: 1 };
}

/** «Следующий аят» (кнопка): с бисмиллы — на первый аят; в конце отрезка — на начало, если по кругу; иначе null. */
export function шагВперёд(о: Очередь, ш: Шаг): Шаг | null {
  if (ш.вид === 'бисмилла') return { вид: 'аят', аят: о.сАята, повтор: 1 };
  if (ш.аят < о.поАят) return { вид: 'аят', аят: ш.аят + 1, повтор: 1 };
  if (о.повторОтрезка) return { вид: 'аят', аят: о.сАята, повтор: 1 };
  return null;
}

/** «Предыдущий аят» (кнопка): на аят назад; на первом аяте отрезка — этот же аят сначала. */
export function шагНазад(о: Очередь, ш: Шаг): Шаг {
  if (ш.вид === 'бисмилла') return ш;
  if (ш.аят > о.сАята) return { вид: 'аят', аят: ш.аят - 1, повтор: 1 };
  return { вид: 'аят', аят: ш.аят, повтор: 1 };
}

/** Что играть после `ended`: повтор того же аята, следующий аят, начало отрезка (по кругу) или null — конец. */
export function шагПослеКонца(о: Очередь, ш: Шаг): Шаг | null {
  if (ш.вид === 'аят' && ш.повтор < о.повторАята) return { вид: 'аят', аят: ш.аят, повтор: ш.повтор + 1 };
  return шагВперёд(о, ш);
}

/** Ближайший следующий шаг с ДРУГИМ файлом (для предзагрузки): повторы того же аята пропускаются. */
export function следующийФайл(о: Очередь, ш: Шаг): Шаг | null {
  const след = шагВперёд(о, ш);
  if (!след) return null;
  if (ш.вид === 'аят' && след.вид === 'аят' && след.аят === ш.аят) return null; // отрезок из одного аята по кругу
  return след;
}

function одинФайл(а: Шаг, б: Шаг): boolean {
  return а.вид === б.вид && (а.вид === 'бисмилла' || (б.вид === 'аят' && а.аят === б.аят));
}

