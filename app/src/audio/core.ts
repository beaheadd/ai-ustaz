/**
 * Ядро плеера чтения кари: очередь аятов суры, повтор аята и отрезка, один звуковой элемент, Media Session.
 *
 * Решение владельца 19.11.2026: «Коран нужно Мишари Ар-Рашид добавить аудио, добавить плеер нужно, чтобы можно было
 * слушать, и когда экран выключен». Правило 3 CLAUDE.md: только живые записи кари по договору, без синтеза.
 * Правило 9: без текста Корана в уведомлениях — подписи Media Session собирает зависимость «подписи» (audio/texts.ts),
 * здесь арабского текста нет вовсе. Без автозапуска, без звуков интерфейса.
 *
 * Как работает при выключенном экране (веб; подробно — docs/дизайн/05, §2.3):
 *   - ОДИН элемент <audio> на всё приложение (синглтон модуля, вне экранов). Следующий аят — сменой src в обработчике
 *     `ended` того же элемента и play() сразу, синхронно: так Android Chrome и iOS Safari продолжают очередь
 *     в фоне. Web Audio не используется (на iOS при блокировке он останавливается).
 *   - Таймеров нет (в фоне их душат): всё — по событиям элемента (ended, playing, waiting, pause, error, …).
 *   - Предзагрузка следующего файла — без второго проигрывающего элемента: зависимость «предзагрузить» скачивает
 *     следующий аят (fetch → Blob → object URL), пока играет текущий; по `ended` src = готовый blob: — без паузы на сеть.
 *     Не успело — src = прямой адрес (как без предзагрузки). Держим не больше двух blob: текущий и следующий.
 *   - Первый play() — только из нажатия (играть() вызывается синхронно из onPress), дальше тот же элемент.
 *   - Media Session: metadata (сура, аят, кари; без арабского), playbackState, setPositionState, действия
 *     play, pause, previoustrack, nexttrack, stop, seekto. seekbackward/seekforward не задаём — тогда iOS показывает
 *     на экране блокировки «предыдущий/следующий», а не ±10 с.
 *
 * Контракт (чистые функции и фабрика, без импортов кода — проверяются в node и в Chromium: scripts/test-audio.mjs,
 * scripts/e2e-audio.mjs):
 *   АЯТОВ_В_СУРЕ[сура − 1]; аятовВСуре(сура) → 0 для неверного номера
 *   нормализоватьОчередь(запрос, повторПоУмолчанию) → Очередь | null  (сАята=1, поАят=конец суры, бисмилла при сАята=1)
 *   шагПослеКонца / шагВперёд / шагНазад / следующийФайл(очередь, шаг, естьБисмилла) — переходы очереди
 *   адресАята(источник, сура, аят) → '/aiustaz-audio/alafasy/002255.mp3'
 *   создатьПлеер(зависимости) → Плеер: играть, пауза, продолжить, переключить, стоп, следующий, предыдущий, кАяту,
 *     установитьПовтор, установитьПовторОтрезка, обновитьПодписи, снимок, подписаться, последнийАят
 * Повтор аята ×N — для заучивания (1…9; кнопка панели — ×1/×3/×5), не награда и не счётчик.
 */

