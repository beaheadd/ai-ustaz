/**
 * Плеер чтения кари для приложения: синглтон модуля (живёт вне экранов — экран размонтируется при уходе,
 * а чтение продолжается), один HTMLAudioElement на всё приложение, Media Session, хук useПлеер().
 *
 * Решение владельца 19.11.2026: «Коран нужно Мишари Ар-Рашид добавить аудио, добавить плеер нужно, чтобы можно было
 * слушать, и когда экран выключен». Права на записи выясняет владелец: пока в content/audio-sources.json
 * «разрешено: false» — доступныйИсточник() = null, плеер не играет, экраны показывают причину (texts.ts).
 * Синтеза нет никогда (правило 3). Аудиофайлов Корана в репозитории и сборке нет: база — путь на своём домене.
 *
 * Контракт для экранов (docs/дизайн/05, §2.3):
 *   плеер.играть({ сура, сАята?, поАят?, повторАята?, повторОтрезка?, бисмиллаПеред? }) → boolean
 *       звать СИНХРОННО из нажатия (первый play() — только из жеста); по умолчанию с 1-го аята до конца суры,
 *       повтор — выбранный ×N, бисмилла — если сАята = 1 и у источника она отдельным файлом
 *   плеер.пауза() · продолжить() · переключить() · стоп() · следующий() · предыдущий() · кАяту(н)
 *   плеер.установитьПовтор(1…9) · установитьПовторОтрезка(bool) · последнийАят() → { сура, аят } | null
 *   useПлеер() → СнимокПлеера: { состояние: 'стоп'|'загрузка'|'играет'|'пауза'|'ошибка'; текущий: { сура, аят, повтор,
 *       из, бисмилла } | null; очередь; ошибка?: 'нет-источника'|'нет-связи'|'нет-файла'|'не-поддерживается';
 *       источник: ИсточникЧтения | null; можноНазад; можноВперёд; повторАята }
 *   доступныйИсточник() → ИсточникЧтения | null; причинаБезЗвука() → ПричинаБезЗвука | null
 *   адресАята(источник, сура, аят) → '/aiustaz-audio/alafasy/002255.mp3'
 *   установитьЯзыкПлеера(языкИнтерфейса) — язык подписей Media Session: ru, kk или uz (делают <МиниПлеер> и <КнопкаСлушать>)
 * Перед записью голоса экран записи зовёт плеер.пауза() — микрофон не должен слышать кари.
 *
 * Хранение: localStorage «aiustaz:quran-player.v1» = { версия: 1, сура, аят, повторАята } — только на этом
 * устройстве, никуда не отправляется (try/catch: приватный режим — просто не помним).
 * Нативно (Android/iOS) HTMLAudioElement нет → «не поддерживается»; план — expo-audio с фоновым режимом (docs/дизайн/05).
 */
import { useSyncExternalStore } from 'react';
import { Platform } from 'react-native';
import данныеИсточников from '@content/audio-sources.json';
import { загрузитьИндексСур, индексИзКэша } from '../quran/data';
import { создатьПлеер, type СнимокПлеера, type Шаг } from './core';
import { выбратьИсточник, проверитьИсточникиЧтения, type ИсточникЧтения, type ПричинаБезЗвука } from './sources';
import { ТЕКСТЫ_ПЛЕЕРА, названиеДляСессии, языкПлеера, type ЯзыкПлеера } from './texts';
import { естьЗвукВеба, зависимостиВеба } from './web';

export { адресАята, ПОВТОРЫ_АЯТА, АЯТОВ_В_СУРЕ, аятовВСуре } from './core';
export type { Очередь, ЗапросОчереди, СнимокПлеера, СостояниеПлеера, ОшибкаПлеера, ТекущийАят, ПоследнийАят } from './core';
export type { ИсточникЧтения, ПричинаБезЗвука } from './sources';

const ИСТОЧНИКИ: readonly ИсточникЧтения[] = проверитьИсточникиЧтения(данныеИсточников);
const ВЕБ = Platform.OS === 'web';

function среда() {
  const хост = ВЕБ && typeof window !== 'undefined' ? String(window.location?.hostname ?? '') : '';
  const естьЗвук = ВЕБ && естьЗвукВеба();
  return { хост, естьЗвук };
}

/** Источник, который можно играть здесь и сейчас, или null. */
export function доступныйИсточник(): ИсточникЧтения | null {
  return выбратьИсточник(ИСТОЧНИКИ, среда()).источник;
}

/** Почему чтение кари не играет (null — играет). */
export function причинаБезЗвука(): ПричинаБезЗвука | null {
  return выбратьИсточник(ИСТОЧНИКИ, среда()).причина;
}

let язык: ЯзыкПлеера = 'ru';

/** Язык подписей Media Session; при смене подписи на экране блокировки пересобираются. */
export function установитьЯзыкПлеера(языкИнтерфейса: string) {
  const новый = языкПлеера(языкИнтерфейса);
  if (новый === язык) return;
  язык = новый;
  плеер.обновитьПодписи();
}

function транслитСуры(сура: number): string | null {
  const индекс = индексИзКэша();
  if (!индекс) {
    // Индекс ещё не загружен: подпись пока с номером; после загрузки — с названием.
    void загрузитьИндексСур().then((р) => {
      if (р.ок) плеер.обновитьПодписи();
    });
    return null;
  }
  const запись = индекс.суры.find((с) => с.сура === сура);
  return запись?.транслит[язык] ?? null;
}

function подписи(сура: number, ш: Шаг, из: number) {
  const источник = доступныйИсточник();
  return {
    название: названиеДляСессии({
      язык,
      сура,
      аят: ш.вид === 'аят' ? ш.аят : 1,
      транслит: транслитСуры(сура),
      бисмилла: ш.вид === 'бисмилла',
      повтор: ш.вид === 'аят' ? ш.повтор : 1,
      из,
    }),
    исполнитель: источник ? источник.кари[язык] : ТЕКСТЫ_ПЛЕЕРА[язык]['плеер'],
    альбом: 'AI Ustaz',
  };
}

export const плеер = создатьПлеер<ИсточникЧтения>({
  источник: доступныйИсточник,
  подписи,
  // Веб: <audio>, Media Session, localStorage, предзагрузка (audio/web.ts). Нативно — пока без звука (expo-audio — план).
  ...(ВЕБ ? зависимостиВеба() : { создатьЭлемент: () => null }),
});

/** Снимок плеера для экранов: перерисовка при каждой смене состояния или аята (не по времени). */
export function useПлеер(): СнимокПлеера<ИсточникЧтения> {
  return useSyncExternalStore(плеер.подписаться, плеер.снимок, плеер.снимок);
}
