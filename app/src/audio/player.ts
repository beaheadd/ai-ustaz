/**
 * Плеер чтения кари для приложения: синглтон модуля (живёт вне экранов — экран размонтируется при уходе,
 * а чтение продолжается), один HTMLAudioElement на всё приложение, Media Session, хук useПлеер().
 *
 * Решение владельца 19.11.2026: «Коран нужно Мишари Ар-Рашид добавить аудио, добавить плеер нужно, чтобы можно было
 * слушать, и когда экран выключен». Права на записи выясняет владелец: пока в content/audio-sources.json
 * «разрешено: false» — доступныйИсточник() = null, плеер не играет, экраны показывают причину (texts.ts).
 * Синтеза нет никогда (правило 3). Аудиофайлов Корана в репозитории и сборке нет: база — путь на своём домене.
 *
 * Контракт для экранов (docs/дизайн/05, §2.3):
 *   плеер.играть({ сура, сАята?, поАят?, повторАята?, повторОтрезка?, бисмиллаПеред? }) → boolean
 *       звать СИНХРОННО из нажатия (первый play() — только из жеста); по умолчанию с 1-го аята до конца суры,
 *       повтор — выбранный ×N, бисмилла — если сАята = 1 и у источника она отдельным файлом
 *   плеер.пауза() · продолжить() · переключить() · стоп() · следующий() · предыдущий() · кАяту(н)
 *   плеер.установитьПовтор(1…9) · установитьПовторОтрезка(bool) · последнийАят() → { сура, аят } | null
 *   useПлеер() → СнимокПлеера: { состояние: 'стоп'|'загрузка'|'играет'|'пауза'|'ошибка'; текущий: { сура, аят, повтор,
 *       из, бисмилла } | null; очередь; ошибка?: 'нет-источника'|'нет-связи'|'нет-файла'|'не-поддерживается';
 *       источник: ИсточникЧтения | null; можноНазад; можноВперёд; повторАята }
 *   доступныйИсточник() → ИсточникЧтения | null; причинаБезЗвука() → ПричинаБезЗвука | null
 *   чтецы() → ИсточникЧтения[] (можно слушать здесь); выбратьЧтеца(id); useЧтец() → id текущего чтеца
 *     (владелец 27.11.2026: аудио AlQuran Cloud — аль-Хусари по умолчанию; выбор — localStorage aiustaz:quran-reciter.v1)
 *   адресАята(источник, сура, аят) → '/aiustaz-audio/alafasy/002255.mp3'
 *   Своё зеркало (владелец 27.11.2026): издание опубликовано на aiustaz.pro → адреса '/aiustaz-audio/128/ar.husary/262.mp3'
 *     (audio/mirror.ts), скачанные аяты играют без сети (audio/download.ts, service worker).
 *   установитьЯзыкПлеера(языкИнтерфейса) — язык подписей Media Session: ru, kk, uz или en (делают <МиниПлеер> и <КнопкаСлушать>)
 * Перед записью голоса экран записи зовёт плеер.пауза() — микрофон не должен слышать кари.
 *
 * Хранение: localStorage «aiustaz:quran-player.v1» = { версия: 1, сура, аят, повторАята } — только на этом
 * устройстве, никуда не отправляется (try/catch: приватный режим — просто не помним).
 * Нативно (Android/iOS) HTMLAudioElement нет → «не поддерживается»; план — expo-audio с фоновым режимом (docs/дизайн/05).
 */
