export const ТЕКСТЫ_ПЛЕЕРА: Record<ЯзыкПлеера, Record<КлючПлеера, string>> = { ru, kk, uz, en };

/** Язык интерфейса → язык текстов плеера (неизвестный язык — русский, пока не добавят тексты). */
export function языкПлеера(язык: string): ЯзыкПлеера {
  return язык === 'kk' || язык === 'uz' || язык === 'en' ? язык : 'ru';
}

/** Арабские буквы и знаки (основной блок, дополнения, формы представления). */
export const ЕСТЬ_АРАБСКИЙ = /[؀-ۿݐ-ݿࢠ-ࣿﭐ-﷿ﹰ-﻿]/;

export function подставитьВ(строка: string, параметры: Record<string, string | number>): string {
  return строка.replace(/\{([^{}]+)\}/g, (весь, имя: string) =>
    Object.prototype.hasOwnProperty.call(параметры, имя) ? String(параметры[имя]) : весь,
  );
}

export type ДанныеНазвания = {
  язык: ЯзыкПлеера;
  сура: number;
  аят: number;
  /** Транслитерация названия суры на языке интерфейса (индекс сур, черновик) или null — тогда номер. */
  транслит: string | null;
  бисмилла: boolean;
  повтор: number;
  из: number;
};

/**
 * Подпись текущего аята — для Media Session (title) и мини-панели. Без арабских букв: если транслитерация вдруг
 * содержит арабское — берётся номер суры (правило 9: без текста Корана в уведомлениях).
 */
export function названиеДляСессии(д: ДанныеНазвания): string {
  const т = ТЕКСТЫ_ПЛЕЕРА[д.язык] ?? ТЕКСТЫ_ПЛЕЕРА.ru;
  const имя = д.транслит && !ЕСТЬ_АРАБСКИЙ.test(д.транслит) ? д.транслит : null;
  const ключ: КлючПлеера = д.бисмилла ? (имя ? 'бисмилла' : 'бисмилла-номер') : имя ? 'название' : 'название-номер';
  let строка = подставитьВ(т[ключ], { имя: имя ?? '', сура: д.сура, аят: д.аят });
  if (!д.бисмилла && д.из > 1) строка += ' (' + подставитьВ(т['повтор'], { n: д.повтор, из: д.из }) + ')';
  return строка;
}
