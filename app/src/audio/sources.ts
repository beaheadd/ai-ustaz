/**
 * Источники чтения Корана для плеера: проверка формы content/audio-sources.json и правило, можно ли играть.
 *
 * Решение владельца 19.11.2026: «Коран нужно Мишари Ар-Рашид добавить аудио, добавить плеер нужно, чтобы можно было
 * слушать, и когда экран выключен». Правило 3 CLAUDE.md: Коран звучит ТОЛЬКО в живых записях кари по договору —
 * без синтеза и клонирования голоса. Права на записи аль-Афаси выясняет владелец (отдельный процесс), поэтому
 * в данных «разрешено: false» и база пустая: плеер не играет и показывает причину.
 *
 * Играть можно, только если ОДНОВРЕМЕННО:
 *   (а) «разрешено» строго true, есть дата разрешения (ГГГГ-ММ-ДД) и условия — как у видео партнёров (media.json);
 *   (б) база — путь на ТОМ ЖЕ домене (/aiustaz-audio/…; CSP media-src 'self'), без схемы, «..» и «//»;
 *       шаблон с {sura3} и {aya3}; файлы лежат на сервере своего домена, вне dist;
 *   (в) страница НЕ на batr.kz (там файлов нет: весь Коран — сотни МБ, в git batr-world им не место). Свой домен
 *       aiustaz.pro (владелец 19.11.2026) отдаёт ту же сборку — там файлы по базе /aiustaz-audio/… (nginx своего домена);
 *   (г) есть HTMLAudioElement (веб). Нативная сборка — план в docs/дизайн/05 (expo-audio), пока «не поддерживается».
 *
 * Контракт (чистые функции, без импортов кода — проверяются в node: scripts/test-audio.mjs):
 *   проверитьИсточникиЧтения(сырые) → ИсточникЧтения[]   — кривые записи отбрасываются (не играют)
 *   можноИграть(источник) → boolean                       — (а) и (б)
 *   выбратьИсточник(источники, среда) → { источник } | { источник: null; причина: ПричинаБезЗвука }
 *   ЭТО_БАЗА, ЭТО_ШАБЛОН, ЭТО_ФАЙЛ_БИСМИЛЛЫ — образцы допустимых значений (те же — в tools/audio/check_audio.py)
 */

export type ИсточникЧтения = {
  id: string;
  /** Имя кари: ru, kk (черновик), ar — сверить у владельца. */
  кари: { ru: string; kk: string; ar: string | null };
  /** Путь на своём домене без завершающего «/», например /aiustaz-audio/alafasy. Пусто — файлов нет. */
  база: string;
  /** Имя файла аята: {sura3}{aya3}.mp3 → 002255.mp3. */
  шаблон: string;
  /** Отдельный файл бисмиллы перед сурой (если у набора она отдельно), иначе null. */
  бисмилла: string | null;
  разрешено: boolean;
  датаРазрешения: string | null;
  условия: string | null;
  атрибуция: { ru: string; kk: string };
};

/** Почему чтение кари не играет. Тексты — audio/texts.ts (ru, kk — черновик). */
export type ПричинаБезЗвука = 'нет-разрешения' | 'не-на-этом-сайте' | 'не-поддерживается';

export type СредаПлеера = {
  /** location.hostname ('' — нет window). */
  хост: string;
  /** Есть ли HTMLAudioElement (веб). */
  естьЗвук: boolean;
};

export type ВыборИсточника =
  | { источник: ИсточникЧтения; причина: null }
  | { источник: null; причина: ПричинаБезЗвука };

export const ЭТО_БАЗА = /^(?:\/[A-Za-z0-9_-]+)+$/;
export const ЭТО_ШАБЛОН = /^(?=.*\{sura3\})(?=.*\{aya3\})[A-Za-z0-9_{}-]+\.(mp3|m4a|ogg|opus)$/;
export const ЭТО_ФАЙЛ_БИСМИЛЛЫ = /^[A-Za-z0-9_-]+\.(mp3|m4a|ogg|opus)$/;
const ДАТА = /^\d{4}-\d{2}-\d{2}$/;

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
function строка(з: unknown): з is string {
  return typeof з === 'string' && з.trim().length > 0;
}

function проверитьОдин(з: unknown): ИсточникЧтения | null {
  const и = объект(з);
  if (!и || !строка(и.id) || !/^[a-z0-9-]+$/.test(и.id)) return null;
  const кари = объект(и.кари);
  const атрибуция = объект(и.атрибуция);
  if (!кари || !строка(кари.ru) || !строка(кари.kk)) return null;
  if (!атрибуция || !строка(атрибуция.ru) || !строка(атрибуция.kk)) return null;
  if (typeof и.шаблон !== 'string' || !ЭТО_ШАБЛОН.test(и.шаблон)) return null;
  const база = typeof и.база === 'string' ? и.база : '';
  if (база !== '' && (!ЭТО_БАЗА.test(база) || база.startsWith('/aiustaz/'))) return null;
  if (и.бисмилла != null && (typeof и.бисмилла !== 'string' || !ЭТО_ФАЙЛ_БИСМИЛЛЫ.test(и.бисмилла))) return null;
  return {
    id: и.id,
    кари: { ru: кари.ru, kk: кари.kk, ar: строка(кари.ar) ? кари.ar : null },
    база,
    шаблон: и.шаблон,
    бисмилла: typeof и.бисмилла === 'string' ? и.бисмилла : null,
    // Строго true: всё остальное (нет поля, строка «true», 1) — нет разрешения.
    разрешено: и.разрешено === true,
    датаРазрешения: typeof и.дата_разрешения === 'string' && ДАТА.test(и.дата_разрешения) ? и.дата_разрешения : null,
    условия: строка(и.условия) ? и.условия : null,
    атрибуция: { ru: атрибуция.ru, kk: атрибуция.kk },
  };
}

export function проверитьИсточникиЧтения(сырые: unknown): ИсточникЧтения[] {
  const д = объект(сырые);
  if (!д || !Array.isArray(д.источники)) return [];
  const итог: ИсточникЧтения[] = [];
  for (const з of д.источники as unknown[]) {
    const и = проверитьОдин(з);
    if (и && !итог.some((у) => у.id === и.id)) итог.push(и);
  }
  return итог;
}

/** (а) разрешение с датой и условиями и (б) файлы на своём домене. */
export function можноИграть(и: ИсточникЧтения): boolean {
  return и.разрешено === true && и.датаРазрешения != null && и.условия != null && ЭТО_БАЗА.test(и.база);
}

function этоBatr(хост: string): boolean {
  const х = String(хост ?? '').trim().toLowerCase().replace(/\.+$/, '');
  return х === 'batr.kz' || х.endsWith('.batr.kz');
}

/**
 * Первый источник, который можно играть в этой среде, или причина, почему нет.
 * Порядок причин: нет разрешения (главное — права кари) → не на этом сайте (batr.kz) → не поддерживается (натив).
 */
export function выбратьИсточник(источники: readonly ИсточникЧтения[], среда: СредаПлеера): ВыборИсточника {
  const разрешённый = источники.find(можноИграть);
  if (!разрешённый) return { источник: null, причина: 'нет-разрешения' };
  if (этоBatr(среда.хост)) return { источник: null, причина: 'не-на-этом-сайте' };
  if (!среда.естьЗвук) return { источник: null, причина: 'не-поддерживается' };
  return { источник: разрешённый, причина: null };
}
