/**
 * Источники чтения Корана для плеера: проверка формы content/audio-sources.json и правило, можно ли играть.
 *
 * Решение владельца 19.11.2026: «Коран нужно Мишари Ар-Рашид добавить аудио, добавить плеер нужно, чтобы можно было
 * слушать, и когда экран выключен». Правило 3 CLAUDE.md: Коран звучит ТОЛЬКО в живых записях кари по договору —
 * без синтеза и клонирования голоса. Права на записи аль-Афаси выясняет владелец (отдельный процесс), поэтому
 * в данных «разрешено: false» и база пустая: плеер не играет и показывает причину.
 *
 * Решение владельца 27.11.2026: «Найди аудио Корана и поставь на сайт. Мы используем для некоммерческого использования».
 * Источник с письменным разрешением — AlQuran Cloud (Islamic Network), условия alquran.cloud/terms-and-conditions (ред.
 * 13.11.2026): «You may stream, embed and download the recitations for personal and educational use». AI Ustaz —
 * бесплатное учебное приложение: СТРИМИМ с их CDN (cdn.islamic.network), не зеркалим. Записи не используем для
 * обучения моделей и не синтезируем (правило 3). Такой источник — поле cdn (хост из РАЗРЕШЁННЫЕ_CDN, издание, битрейт).
 *
 * Играть можно, только если ОДНОВРЕМЕННО:
 *   (а) «разрешено» строго true, есть дата разрешения (ГГГГ-ММ-ДД) и условия — как у видео партнёров (media.json);
 *   (б) либо cdn — хост из РАЗРЕШЁННЫЕ_CDN (CSP media-src разрешает только его), издание вида «ar.husary», битрейт;
 *       либо база — путь на ТОМ ЖЕ домене (/aiustaz-audio/…; CSP media-src 'self'), без схемы, «..» и «//»;
 *       шаблон с {sura3} и {aya3}; файлы лежат на сервере своего домена, вне dist;
 *   (в) страница НЕ на batr.kz (там файлов нет: весь Коран — сотни МБ, в git batr-world им не место; CDN AlQuran Cloud
 *       там тоже не играет — только бесплатный AI Ustaz на своём домене). Свой домен
 *       aiustaz.pro (владелец 19.11.2026) отдаёт ту же сборку — там файлы по базе /aiustaz-audio/… (nginx своего домена);
 *   (г) есть HTMLAudioElement (веб). Нативная сборка — план в docs/дизайн/05 (expo-audio), пока «не поддерживается».
 *
 * Контракт (чистые функции, без импортов кода — проверяются в node: scripts/test-audio.mjs):
 *   проверитьИсточникиЧтения(сырые) → ИсточникЧтения[]   — кривые записи отбрасываются (не играют)
 *   можноИграть(источник) → boolean                       — (а) и (б)
 *   выбратьИсточник(источники, среда, предпочтение?) → { источник } | { источник: null; причина: ПричинаБезЗвука }
 *     — предпочтение: id чтеца, выбранного человеком; нет или не играет — первый играющий по порядку данных
 *   играющиеИсточники(источники, среда) → ИсточникЧтения[] — список для выбора чтеца
 *   ЭТО_БАЗА, ЭТО_ШАБЛОН, ЭТО_ФАЙЛ_БИСМИЛЛЫ — образцы допустимых значений (те же — в tools/audio/check_audio.py)
 */

export type ИсточникЧтения = {
  id: string;
  /** Имя кари: ru, kk, uz и en (черновики), ar — сверить у владельца. uz/en нет в данных — ru. */
  кари: { ru: string; kk: string; uz: string; en: string; ar: string | null };
  /** Внешний CDN с разрешением (AlQuran Cloud): адрес аята — https://<хост>/quran/audio/<битрейт>/<издание>/<номер 1…6236>.mp3. */
  cdn: { хост: string; издание: string; битрейт: number } | null;
  /** Путь на своём домене без завершающего «/», например /aiustaz-audio/alafasy. Пусто — файлов нет. */
  база: string;
  /** Имя файла аята: {sura3}{aya3}.mp3 → 002255.mp3. */
  шаблон: string;
  /** Отдельный файл бисмиллы перед сурой (если у набора она отдельно), иначе null. */
  бисмилла: string | null;
  разрешено: boolean;
  датаРазрешения: string | null;
  условия: string | null;
  атрибуция: { ru: string; kk: string; uz: string; en: string };
};

/** Почему чтение кари не играет. Тексты — audio/texts.ts (ru; kk, uz и en — черновик). */
export type ПричинаБезЗвука = 'нет-разрешения' | 'не-на-этом-сайте' | 'не-поддерживается';

export type СредаПлеера = {
  /** location.hostname ('' — нет window). */
  хост: string;
  /** Есть ли HTMLAudioElement (веб). */
  естьЗвук: boolean;
};

export type ВыборИсточника =
  | { источник: ИсточникЧтения; причина: null }
  | { источник: null; причина: ПричинаБезЗвука };

export const ЭТО_БАЗА = /^(?:\/[A-Za-z0-9_-]+)+$/;
/** Единственный разрешённый внешний хост аудио (CSP media-src; scripts/after-export.mjs, check-dist). */
export const РАЗРЕШЁННЫЕ_CDN: readonly string[] = ['cdn.islamic.network'];
export const ЭТО_ИЗДАНИЕ = /^[a-z]{2}\.[a-z0-9-]+$/;
export const БИТРЕЙТЫ_CDN: readonly number[] = [32, 40, 48, 64, 128, 192];
export const ЭТО_ШАБЛОН = /^(?=.*\{sura3\})(?=.*\{aya3\})[A-Za-z0-9_{}-]+\.(mp3|m4a|ogg|opus)$/;
export const ЭТО_ФАЙЛ_БИСМИЛЛЫ = /^[A-Za-z0-9_-]+\.(mp3|m4a|ogg|opus)$/;
const ДАТА = /^\d{4}-\d{2}-\d{2}$/;

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
function строка(з: unknown): з is string {
  return typeof з === 'string' && з.trim().length > 0;
}

function проверитьОдин(з: unknown): ИсточникЧтения | null {
  const и = объект(з);
  if (!и || !строка(и.id) || !/^[a-z0-9-]+$/.test(и.id)) return null;
  const кари = объект(и.кари);
  const атрибуция = объект(и.атрибуция);
  if (!кари || !строка(кари.ru) || !строка(кари.kk)) return null;
  if (!атрибуция || !строка(атрибуция.ru) || !строка(атрибуция.kk)) return null;
  const cdnСырой = объект(и.cdn);
  let cdn: ИсточникЧтения['cdn'] = null;
  if (и.cdn != null) {
    if (!cdnСырой || typeof cdnСырой.хост !== 'string' || !РАЗРЕШЁННЫЕ_CDN.includes(cdnСырой.хост)) return null;
    if (typeof cdnСырой.издание !== 'string' || !ЭТО_ИЗДАНИЕ.test(cdnСырой.издание)) return null;
    if (typeof cdnСырой.битрейт !== 'number' || !БИТРЕЙТЫ_CDN.includes(cdnСырой.битрейт)) return null;
    cdn = { хост: cdnСырой.хост, издание: cdnСырой.издание, битрейт: cdnСырой.битрейт };
  }
  if (!cdn && (typeof и.шаблон !== 'string' || !ЭТО_ШАБЛОН.test(и.шаблон))) return null;
  const база = typeof и.база === 'string' ? и.база : '';
  if (база !== '' && (!ЭТО_БАЗА.test(база) || база.startsWith('/aiustaz/'))) return null;
  if (и.бисмилла != null && (typeof и.бисмилла !== 'string' || !ЭТО_ФАЙЛ_БИСМИЛЛЫ.test(и.бисмилла))) return null;
  return {
    id: и.id,
    кари: { ru: кари.ru, kk: кари.kk, uz: строка(кари.uz) ? кари.uz : кари.ru, en: строка(кари.en) ? кари.en : кари.ru, ar: строка(кари.ar) ? кари.ar : null },
    cdn,
    база: cdn ? '' : база,
    шаблон: cdn ? '' : (и.шаблон as string),
    бисмилла: typeof и.бисмилла === 'string' ? и.бисмилла : null,
    // Строго true: всё остальное (нет поля, строка «true», 1) — нет разрешения.
    разрешено: и.разрешено === true,
    датаРазрешения: typeof и.дата_разрешения === 'string' && ДАТА.test(и.дата_разрешения) ? и.дата_разрешения : null,
    условия: строка(и.условия) ? и.условия : null,
    атрибуция: { ru: атрибуция.ru, kk: атрибуция.kk, uz: строка(атрибуция.uz) ? атрибуция.uz : атрибуция.ru, en: строка(атрибуция.en) ? атрибуция.en : атрибуция.ru },
  };
}

export function проверитьИсточникиЧтения(сырые: unknown): ИсточникЧтения[] {
  const д = объект(сырые);
  if (!д || !Array.isArray(д.источники)) return [];
  const итог: ИсточникЧтения[] = [];
  for (const з of д.источники as unknown[]) {
    const и = проверитьОдин(з);
    if (и && !итог.some((у) => у.id === и.id)) итог.push(и);
  }
  return итог;
}

/** (а) разрешение с датой и условиями и (б) разрешённый CDN или файлы на своём домене. */
export function можноИграть(и: ИсточникЧтения): boolean {
  return и.разрешено === true && и.датаРазрешения != null && и.условия != null && (и.cdn != null || ЭТО_БАЗА.test(и.база));
}

function этоBatr(хост: string): boolean {
  const х = String(хост ?? '').trim().toLowerCase().replace(/\.+$/, '');
  return х === 'batr.kz' || х.endsWith('.batr.kz');
}

/**
 * Источники, которые можно играть в этой среде (для выбора чтеца). На batr.kz — никаких: там нет своих файлов, а записи
 * AlQuran Cloud — только для бесплатного учебного AI Ustaz на своём домене (их условие о коммерческих продуктах; CLAUDE.md:
 * «из batr.kz к AI Ustaz — только ссылка»). На batr.kz — строка «Чтение кари — на сайте AI Ustaz: aiustaz.pro».
 */
export function играющиеИсточники(источники: readonly ИсточникЧтения[], среда: СредаПлеера): ИсточникЧтения[] {
  if (!среда.естьЗвук || этоBatr(среда.хост)) return [];
  return источники.filter(можноИграть);
}

/**
 * Источник для игры (выбранный человеком, иначе первый по порядку данных) или причина, почему нет.
 * Порядок причин: нет разрешения (главное — права кари) → не на этом сайте (batr.kz) → не поддерживается (натив).
 */
export function выбратьИсточник(источники: readonly ИсточникЧтения[], среда: СредаПлеера, предпочтение?: string | null): ВыборИсточника {
  const разрешённые = источники.filter(можноИграть);
  if (!разрешённые.length) return { источник: null, причина: 'нет-разрешения' };
  if (этоBatr(среда.хост)) return { источник: null, причина: 'не-на-этом-сайте' };
  if (!среда.естьЗвук) return { источник: null, причина: 'не-поддерживается' };
  return { источник: разрешённые.find((и) => и.id === предпочтение) ?? разрешённые[0], причина: null };
}
