/**
 * Прослушивание чтеца при выборе: аль-Фатиха (1:1–1:7) выбранного кари, аят за аятом.
 *
 * Владелец 27.11.2026: «Когда человек только заходит на Коран, нужно поставить выбор чтеца. Рядом должно быть
 * воспроизведение. Аль-Фатиху можешь поставить, пусть они слушают голос и выбирают того чтеца, который ему понравился».
 *
 * Отдельный <audio> (не очередь основного плеера: прослушивание не должно сбивать место чтения, мини-плеер и экран
 * блокировки). Адреса — те же, что у плеера (audio/core.ts адресАята, своё зеркало — audio/mirror.ts, иначе CDN).
 * Перед прослушиванием основной плеер ставится на паузу. Одновременно звучит один чтец; повторное нажатие — пауза.
 * Правило 3: только живые записи кари, без синтеза.
 *
 * Контракт: прослушать(источник) — звать синхронно из нажатия; остановитьПрослушивание();
 *   useПрослушивание() → { id, состояние: 'загрузка' | 'играет' | 'пауза', аят } | null
 */
import { useSyncExternalStore } from 'react';
import { адресАята } from './core';
import { сЗеркалом } from './mirror';
import { плеер } from './player';
import type { ИсточникЧтения } from './sources';

export type Прослушивание = { id: string; состояние: 'загрузка' | 'играет' | 'пауза'; аят: number } | null;

const АЯТОВ_ФАТИХИ = 7;
let элемент: HTMLAudioElement | null = null;
let источник: ИсточникЧтения | null = null;
let снимок: Прослушивание = null;
const слушатели = new Set<() => void>();

function установить(новый: Прослушивание) {
  снимок = новый;
  for (const ф of [...слушатели]) ф();
}

function звук(): HTMLAudioElement | null {
  if (элемент) return элемент;
  if (typeof Audio !== 'function') return null;
  const э = new Audio();
  э.preload = 'auto';
  э.addEventListener('playing', () => снимок && установить({ ...снимок, состояние: 'играет' }));
  э.addEventListener('waiting', () => снимок && установить({ ...снимок, состояние: 'загрузка' }));
  э.addEventListener('ended', () => {
    if (!снимок || !источник) return;
    if (снимок.аят >= АЯТОВ_ФАТИХИ) {
      установить(null);
      return;
    }
    const аят = снимок.аят + 1;
    э.src = адресАята(сЗеркалом(источник), 1, аят);
    установить({ ...снимок, аят, состояние: 'загрузка' });
    void э.play().catch(() => установить(null));
  });
  э.addEventListener('error', () => установить(null));
  // Основной плеер заиграл (человек нажал «Слушать») — прослушивание замолкает: звучит один чтец.
  плеер.подписаться(() => {
    if (снимок && плеер.снимок().состояние === 'играет') остановитьПрослушивание();
  });
  элемент = э;
  return э;
}

/** Слушать Фатиху этого чтеца; тот же чтец играет — пауза, на паузе — продолжить. */
export function прослушать(и: ИсточникЧтения) {
  const э = звук();
  if (!э) return;
  if (снимок && снимок.id === и.id) {
    if (снимок.состояние === 'пауза') {
      установить({ ...снимок, состояние: 'загрузка' });
      void э.play().catch(() => установить(null));
    } else {
      э.pause();
      установить({ ...снимок, состояние: 'пауза' });
    }
    return;
  }
  const основной = плеер.снимок();
  if (основной.состояние === 'играет' || основной.состояние === 'загрузка') плеер.пауза();
  источник = и;
  э.pause();
  э.src = адресАята(сЗеркалом(и), 1, 1);
  установить({ id: и.id, состояние: 'загрузка', аят: 1 });
  void э.play().catch(() => установить(null));
}

export function остановитьПрослушивание() {
  if (элемент) {
    элемент.pause();
    элемент.removeAttribute('src');
  }
  источник = null;
  if (снимок) установить(null);
}

function подписаться(ф: () => void) {
  слушатели.add(ф);
  return () => {
    слушатели.delete(ф);
  };
}

export function useПрослушивание(): Прослушивание {
  return useSyncExternalStore(подписаться, () => снимок, () => null);
}
