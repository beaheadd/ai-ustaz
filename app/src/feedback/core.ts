/**
 * «Сообщить об ошибке» — общее ядро (основной чанк, без словарей и формы: форма — ленивым чанком FeedbackSheet).
 *
 * Владелец 28.11.2026: «Нужно разработать функцию, чтобы клиент мог выделить и нажать на кнопку „Ошибка“. И написать,
 * какая там ошибка… Любой человек увидел ошибку, нажал, он попадает к нам и обрабатывает. Если это реальная ошибка, то
 * мы улучшаем.» Сервер — server/feedback.py (POST /api/feedback, только aiustaz.pro), админка — раздел «Ошибки».
 *
 * Контракт:
 *   сообщитьОбОшибке({ цитата?, место? }) — открыть лист «Сообщить об ошибке» (строка «Ещё», меню суры и хадиса, лист
 *     аята; выделение текста — сам слой FeedbackLayer). место — '2:255', 'hadith:1751'; не задано — из текущего экрана.
 *   слушатьСообщения(ф) → отписка — слой FeedbackLayer (один на приложение).
 *   категорияЭкрана(экран) → КатегорияОшибки — какую категорию выбрать заранее.
 *   местоЦели(цель) → string | null — место из экрана и его параметров (без личных данных).
 *   КАТЕГОРИИ_ОШИБОК — коды, как на сервере.
 */
import type { ИмяЭкрана, Цель } from '../engine/routes';

export const КАТЕГОРИИ_ОШИБОК = ['quran', 'hadith', 'translation', 'dhikr', 'prayer', 'ui', 'other'] as const;
export type КатегорияОшибки = (typeof КАТЕГОРИИ_ОШИБОК)[number];
export type ЗапросСообщения = { цитата?: string; место?: string | null };

let слушатель: ((з: ЗапросСообщения) => void) | null = null;

export function сообщитьОбОшибке(з: ЗапросСообщения = {}): void {
  слушатель?.(з);
}

export function слушатьСообщения(ф: (з: ЗапросСообщения) => void): () => void {
  слушатель = ф;
  return () => {
    if (слушатель === ф) слушатель = null;
  };
}

const ПО_ЭКРАНУ: Partial<Record<ИмяЭкрана, КатегорияОшибки>> = {
  коран: 'quran', сура: 'quran', проверкаАята: 'quran', урок: 'quran', урок0: 'quran', картаКурса: 'quran',
  какОбъясняем: 'quran', махраджи: 'quran', букваМахраджа: 'quran',
  хадисы: 'hadith', разделХадисов: 'hadith', хадис: 'hadith',
  зикры: 'dhikr', дуа: 'dhikr', зикр: 'dhikr',
  намаз: 'prayer', городНамаза: 'prayer', кибла: 'prayer', уведомления: 'prayer',
  главная: 'ui', ещё: 'ui', установка: 'ui', онбординг: 'ui', лицензии: 'ui', оПроекте: 'ui',
};

export function категорияЭкрана(экран: ИмяЭкрана): КатегорияОшибки {
  return ПО_ЭКРАНУ[экран] ?? 'other';
}

/** Место ошибки: сура:аят, хадис HadeethEnc, зикр, урок, раздел намаза, буква махраджа. Только номера. */
export function местоЦели(ц: Цель): string | null {
  switch (ц.экран) {
    case 'сура':
      return ц.параметры.аят ? `${ц.параметры.номер}:${ц.параметры.аят}` : String(ц.параметры.номер);
    case 'проверкаАята':
      return `${ц.параметры.номер}:${ц.параметры.аят}`;
    case 'хадис':
      return 'hadith:' + ц.параметры.номер;
    case 'разделХадисов':
      return 'hadith-cat:' + ц.параметры.номер;
    case 'зикр':
      return 'dhikr:' + ц.параметры.номер;
    case 'урок':
      return 'lesson:' + ц.параметры.номер;
    case 'разделНамаза':
      return 'namaz:' + ц.параметры.номер;
    case 'букваМахраджа':
      return 'letter:' + ц.параметры.номер;
    default:
      return null;
  }
}
