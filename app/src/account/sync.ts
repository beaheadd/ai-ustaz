// ───────────── localStorage ─────────────
function взять(ключ: string): unknown {
  try {
    const с = globalThis.localStorage?.getItem(П + ключ);
    return с == null ? undefined : JSON.parse(с);
  } catch {
    return undefined;
  }
}
function положить(ключ: string, з: unknown): void {
  try {
    globalThis.localStorage?.setItem(П + ключ, JSON.stringify(з));
  } catch {
    // переполнено или приватный режим — останется как было
  }
}
function строкаЧтеца(): string | undefined {
  try {
    const з = globalThis.localStorage?.getItem(П + 'quran-reciter.v1');
    return з && /^[a-z0-9-]{1,40}$/.test(з) ? з : undefined;
  } catch {
    return undefined;
  }
}

const объект = (з: unknown): Record<string, unknown> => (з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : {});
const место = (з: unknown) => {
  const о = объект(з);
  return Number.isInteger(о.сура) && Number.isInteger(о.аят) && (о.сура as number) >= 1 && (о.сура as number) <= 114 && (о.аят as number) >= 1 && (о.аят as number) <= 286
    ? { сура: о.сура as number, аят: о.аят as number }
    : null;
};

/** Значения ключа синхронизации на устройстве (undefined у поля — «на устройстве не выбирали»). */
export function прочитатьЛокальное(ключ: КлючСинхронизации): unknown {
  switch (ключ) {
    case 'progress': {
      const п = нормализоватьПрогресс(взять('progress.v1') ?? null);
      return { уроки: п.уроки, дниЗанятий: п.дниЗанятий, онбордингПройден: п.онбордингПройден, предупреждениеПоказано: п.предупреждениеПоказано } satisfies ЛокальныйПрогресс;
    }
    case 'dhikr': {
      const з = объект(взять('dhikr.v1'));
      const счёт: ЛокальныеЗикры['счёт'] = {};
      for (const [id, з2] of Object.entries(объект(з.счёт))) {
        const о = объект(з2);
        if (Number.isInteger(о.текущий) && Number.isInteger(о.всего))
          счёт[id] = { текущий: о.текущий as number, всего: о.всего as number, день: typeof о.день === 'string' ? о.день : датаАлматы() /* записи до 27.11.2026 без дня — сегодняшние, как в dhikr/data.ts */, ...(Number.isInteger(о.цель) ? { цель: о.цель as number } : null) };
      }
      const избранное = Array.isArray(з.избранное) ? (з.избранное as unknown[]).filter((и): и is string => typeof и === 'string') : [];
      return { счёт, избранное } satisfies ЛокальныеЗикры;
    }
    case 'quran': {
      const закладка = взять('quran-bookmark.v1');
      return { чтение: место(взять('quran-reading.v1')) ?? undefined, закладка: закладка === undefined ? undefined : место(закладка) };
    }
    case 'settings': {
      const п = объект(взять('progress.v1'));
      const пр = объект(объект(взять('prayer-place.v1')).место);
      const у = взять('notify.v1');
      const ву = объект(взять('quran-view.v1'));
      return {
        язык: typeof п.язык === 'string' ? п.язык : undefined,
        тема: (объект(взять('theme.v1')).режим as string | undefined) ?? undefined,
        место: пр.вид === 'место' && typeof пр.id === 'string' ? пр : undefined,
        аср: (объект(взять('prayer-asr.v1')).мазхаб as string | undefined) ?? undefined,
        подсветка: typeof объект(взять('quran-words.v1')).вкл === 'boolean' ? объект(взять('quran-words.v1')).вкл : undefined,
        вид: ву.версия === 1 ? { вид: ву.вид, ночьЦвета: ву.ночьЦвета === true, режим: ву.режим ?? 'аяты' } : undefined,
        кегль: typeof объект(взять('quran-font.v1')).кегль === 'number' ? объект(взять('quran-font.v1')).кегль : undefined,
        // Шрифт Корана (владелец 28.11.2026): «мединский» | «классический» (quran/quranScript.ts).
        шрифт: (объект(взять('quran-script.v1')).шрифт as string | undefined) ?? undefined,
        чтец: строкаЧтеца(),
        уведомления: у === undefined ? undefined : { намазы: объект(у).намазы ?? null, заранее: объект(у).заранее ?? 0 },
      };
    }
    case 'zakat': {
      const з = взять('zakat.v1');
      return { ввод: з === undefined ? undefined : з };
    }
  }
}

/** Записать на устройство то, что пришло с сервера (только разрешённые формы); → изменённые ключи хранилища. */
export function записатьЛокальное(ключ: КлючСинхронизации, значение: unknown): string[] {
  const изменены: string[] = [];
  const если = (имя: string, новое: unknown, писать: () => void) => {
    if (!одинаково(взять(имя), новое)) {
      писать();
      изменены.push(имя);
    }
  };
  const з = объект(значение);
  switch (ключ) {
    case 'progress': {
      const л = значение as ЛокальныйПрогресс;
      const п = нормализоватьПрогресс(взять('progress.v1') ?? null);
      const новый = нормализоватьПрогресс({ ...п, уроки: л.уроки, дниЗанятий: л.дниЗанятий, онбордингПройден: л.онбордингПройден, предупреждениеПоказано: л.предупреждениеПоказано });
      если('progress.v1', новый, () => положить('progress.v1', новый));
      break;
    }
    case 'dhikr': {
      const л = значение as ЛокальныеЗикры;
      const было = прочитатьЛокальное('dhikr') as ЛокальныеЗикры;
      if (!зикрыОдинаковы(было, л, датаАлматы())) {
        положить('dhikr.v1', { версия: 1, счёт: л.счёт, избранное: л.избранное });
        изменены.push('dhikr.v1');
      }
      break;
    }
    case 'quran': {
      const ч = место(з.чтение);
      if (ч) если('quran-reading.v1', { версия: 1, ...ч }, () => положить('quran-reading.v1', { версия: 1, ...ч }));
      if ('закладка' in з && з.закладка !== undefined) {
        const к = з.закладка === null ? null : место(з.закладка);
        const новое = к ? { версия: 1, ...к } : null;
        если('quran-bookmark.v1', новое, () => положить('quran-bookmark.v1', новое));
      }
      break;
    }
    case 'settings': {
      if (typeof з.язык === 'string' && ['ru', 'kk', 'uz', 'en', 'ar', 'tr', 'id', 'ur'].includes(з.язык)) {
        const п = нормализоватьПрогресс(взять('progress.v1') ?? null);
        if (п.язык !== з.язык) {
          положить('progress.v1', { ...п, язык: з.язык });
          изменены.push('progress.v1');
        }
      }
      if (typeof з.тема === 'string' && ['система', 'светлая', 'тёмная'].includes(з.тема)) {
        const н = { версия: 1, режим: з.тема };
        если('theme.v1', н, () => положить('theme.v1', н));
      }
      const м = объект(з.место);
      const сейчасМесто = объект(объект(взять('prayer-place.v1')).место);
      // Свою точку по геолокации не заменяем городом из аккаунта (точка — только на этом устройстве).
      if (м.вид === 'место' && typeof м.id === 'string' && typeof м.широта === 'number' && typeof м.долгота === 'number' && сейчасМесто.вид !== 'точка') {
        const н = { версия: 1, место: м };
        если('prayer-place.v1', н, () => положить('prayer-place.v1', н));
      }
      if (з.аср === 'hanafi' || з.аср === 'shafi') {
        const н = { версия: 1, мазхаб: з.аср };
        если('prayer-asr.v1', н, () => положить('prayer-asr.v1', н));
      }
      if (typeof з.подсветка === 'boolean') {
        const н = { версия: 1, вкл: з.подсветка };
        если('quran-words.v1', н, () => положить('quran-words.v1', н));
      }
      const в = объект(з.вид);
      if (typeof в.вид === 'string') {
        const н = { версия: 1, вид: в.вид, ночьЦвета: в.ночьЦвета === true, режим: в.режим === 'страницы' ? 'страницы' : 'аяты' };
        если('quran-view.v1', н, () => положить('quran-view.v1', н));
      }
      if (typeof з.кегль === 'number' && Number.isFinite(з.кегль)) {
        const н = { версия: 1, кегль: з.кегль };
        если('quran-font.v1', н, () => положить('quran-font.v1', н));
      }
      if (з.шрифт === 'мединский' || з.шрифт === 'классический') {
        const н = { версия: 1, шрифт: з.шрифт };
        если('quran-script.v1', н, () => положить('quran-script.v1', н));
      }
      if (typeof з.чтец === 'string' && /^[a-z0-9-]{1,40}$/.test(з.чтец) && з.чтец !== строкаЧтеца()) {
        try {
          globalThis.localStorage?.setItem(П + 'quran-reciter.v1', з.чтец);
          изменены.push('quran-reciter.v1');
        } catch {
          // не вышло — останется прежний
        }
      }
      const у = объект(з.уведомления);
      if (у.намазы && typeof у.намазы === 'object' && typeof у.заранее === 'number') {
        // Включены ли уведомления, когда отправлено расписание и до какого момента — свои у устройства.
        const было = объект(взять('notify.v1'));
        const н = было.версия === 1 ? { ...было, намазы: у.намазы, заранее: у.заранее } : { версия: 1, включено: false, намазы: у.намазы, заранее: у.заранее, отправлено: null, до: null };
        если('notify.v1', н, () => положить('notify.v1', н));
      }
      break;
    }
    case 'zakat': {
      if (з.ввод && typeof з.ввод === 'object') если('zakat.v1', з.ввод, () => положить('zakat.v1', з.ввод));
      break;
    }
  }
  return изменены;
}

// ───────────── состояние синхронизации ─────────────
function новыйId(): string {
  const б = new Uint8Array(12);
  globalThis.crypto.getRandomValues(б);
  return Array.from(б, (х) => х.toString(16).padStart(2, '0')).join('');
}

function состояние(аккаунт: string): Состояние {
  try {
    const с = JSON.parse(globalThis.localStorage?.getItem(КЛЮЧ_СОСТОЯНИЯ) ?? 'null') as Состояние | null;
    // Тот же аккаунт на этом устройстве — продолжаем с общих версий (иначе зикры посчитались бы дважды).
    if (с && с.аккаунт === аккаунт && typeof с.устройство === 'string' && /^[0-9a-f]{24}$/.test(с.устройство) && с.базы && typeof с.базы === 'object') return с;
  } catch {
    // испорчено — начинаем заново
  }
  return { аккаунт, устройство: новыйId(), базы: {} };
}

function сохранитьСостояние(с: Состояние): void {
  try {
    globalThis.localStorage?.setItem(КЛЮЧ_СОСТОЯНИЯ, JSON.stringify(с));
  } catch {
    // переполнено — в следующий раз сольём заново (union и метки времени это переносят)
  }
}

export function забытьСинхронизацию(): void {
  try {
    globalThis.localStorage?.removeItem(КЛЮЧ_СОСТОЯНИЯ);
  } catch {
    // нечего удалять
  }
}

function вДокумент(ключ: КлючСинхронизации, л: unknown, база: Документ | null, к: Контекст): Документ {
  if (ключ === 'progress') return вДокументПрогресса(л as ЛокальныйПрогресс, база as ДокПрогресса | null, к.сейчас);
  if (ключ === 'dhikr') return вДокументЗикров(л as ЛокальныеЗикры, база as ДокЗикров | null, к);
  return вДокументПолей(л as Record<string, unknown>, база as ДокПолей | null, к.сейчас);
}

function изДокумента(ключ: КлючСинхронизации, д: Документ, л: unknown, к: Контекст): unknown {
  if (ключ === 'progress') return изДокументаПрогресса(д as ДокПрогресса);
  if (ключ === 'dhikr') return изДокументаЗикров(д as ДокЗикров, л as ЛокальныеЗикры, к.день);
  return изДокументаПолей(д as ДокПолей);
}

// ───────────── сама синхронизация ─────────────
let идёт: Promise<string> | null = null;
let ещёРаз = false;
let тишинаДо = 0;

export function синхронизировать(): Promise<string> {
  if (идёт) {
    ещёРаз = true;
    return идёт;
  }
  идёт = (async () => {
    let итог = 'ок';
    do {
      ещёРаз = false;
      итог = await одинПроход();
    } while (ещёРаз && итог === 'ок');
    return итог;
  })().finally(() => {
    идёт = null;
  });
  return идёт;
}

async function одинПроход(): Promise<string> {
  const а = текущийАккаунт();
  if (!а) return 'вышли';
  обновитьАккаунт({ статус: 'идёт' });
  const о = await документы();
  if (!о.ок) {
    if (о.код === 'login') {
      остановитьСинхронизацию();
      задатьАккаунт(null);
      return 'вышли';
    }
    обновитьАккаунт({ статус: о.код === 'нет-сети' ? 'нет-сети' : 'ошибка' });
    return о.код === 'нет-сети' ? 'нет-сети' : 'ошибка';
  }
  const с = состояние(а.email);
  let сервер: Record<string, ДокСервера | undefined> = о.данные.docs;
  const закят = о.данные.закят;
  const ключи = СИНХРОННЫЕ_КЛЮЧИ.filter((к) => к !== 'zakat' || закят);
  const изменены = new Set<string>();
  let ожидают = new Set<КлючСинхронизации>(ключи);
  for (let попытка = 0; попытка < 3 && ожидают.size; попытка += 1) {
    const к: Контекст = { сейчас: Date.now(), день: датаАлматы(), устройство: с.устройство };
    const запись: Record<string, { base: number; data: unknown }> = {};
    const итоги: Partial<Record<КлючСинхронизации, Документ>> = {};
    for (const ключ of ожидают) {
      const там = сервер[ключ];
      const документТам = там ? разобратьДокумент(ключ, там.data) : null;
      const база = с.базы[ключ] ? разобратьДокумент(ключ, с.базы[ключ]!.data) : null;
      const л = прочитатьЛокальное(ключ);
      const итог = слить(ключ, вДокумент(ключ, л, база, к), документТам);
      for (const имя of записатьЛокальное(ключ, изДокумента(ключ, итог, л, к))) изменены.add(имя);
      итоги[ключ] = итог;
      if (!документТам || !одинаково(итог, документТам)) запись[ключ] = { base: там?.v ?? 0, data: итог };
      else с.базы[ключ] = { v: там!.v, data: итог };
    }
    if (!Object.keys(запись).length) break;
    const р = await записатьДокументы(запись);
    if (!р.ок) {
      сохранитьСостояние(с);
      if (изменены.size) объявить([...изменены]);
      обновитьАккаунт({ статус: р.код === 'нет-сети' ? 'нет-сети' : 'ошибка' });
      return р.код === 'нет-сети' ? 'нет-сети' : 'ошибка';
    }
    for (const [ключ, в] of Object.entries(р.данные.docs)) с.базы[ключ as КлючСинхронизации] = { v: в.v, data: итоги[ключ as КлючСинхронизации] };
    ожидают = new Set();
    const новыйСервер: Record<string, ДокСервера | undefined> = { ...сервер };
    for (const [ключ, д] of Object.entries(р.данные.conflicts)) {
      if (!д) continue; // суммы закята сервер не принял (выключатель выключен) — не повторяем
      новыйСервер[ключ] = д;
      ожидают.add(ключ as КлючСинхронизации);
    }
    сервер = новыйСервер;
  }
  сохранитьСостояние(с);
  if (изменены.size) объявить([...изменены]);
  обновитьАккаунт({ статус: 'ок', синхронизировано: Date.now(), закят });
  return 'ок';
}

function объявить(ключи: string[]): void {
  тишинаДо = Date.now() + 1500; // модули перечитают и запишут то же самое — это не новое изменение
  сообщитьВнешнееИзменение(ключи);
}

