/**
 * Синхронизация аккаунта (ленивый чанк): локальные ключи ↔ документы сервера. Правила слияния — account/merge.ts.
 *
 * Владелец 28.11.2026: «у него прогресс сохраняется. И с другого устройства он также может зайти с сохраненным
 * прогрессом». Сначала всегда устройство: без сети и без входа всё работает как раньше; синхронизация догоняет потом.
 *
 * Когда: при входе, при запуске приложения (если вошли), когда приложение снова на экране, когда вернулась сеть, и через
 * 4 с после изменения синхронного ключа (engine/storage.ts наблюдатьЗаписи; ключи, которые модули пишут напрямую в
 * localStorage, — чтец, вид чтения, подсветка, размер, шрифт Корана, — догоняют при следующем поводе).
 * Как: GET документов → по каждому ключу слить с локальным → записать на устройство, что изменилось (модули перечитывают
 * свой ключ: сообщитьВнешнееИзменение) → PUT поверх версий сервера; конфликт (другое устройство успело раньше) — ещё раз
 * со свежей версией, до 3 раз.
 * Локально: aiustaz:account-sync.v1 = { аккаунт, устройство, базы: { ключ: { v, data } } } — общая версия по ключу и
 *   случайный id устройства для счёта зикров (не id статистики, наружу — только внутри документа зикров).
 *
 * Контракт: запуститьСинхронизацию(); синхронизировать() → Promise<'ок' | 'нет-сети' | 'вышли' | 'ошибка'>;
 *   остановитьСинхронизацию(); забытьСинхронизацию() — после удаления аккаунта;
 *   прочитатьЛокальное(ключ), записатьЛокальное(ключ, значение) — для тестов.
 */
