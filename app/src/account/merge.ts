/** Доля устройства по зикру: [день, сегодня, всего]. */
export type Доля = [string, number, number];
export type ДокЗикров = {
  уст: Record<string, { at: number; с: Record<string, Доля> }>;
  цели: Record<string, Метка<number | null>>;
  избр: Record<string, Метка<boolean>>;
};
/** Счёт зикров устройства (dhikr/data.ts СчётЗикров). */
export type ЛокальныеЗикры = {
  счёт: Record<string, { текущий: number; день?: string; всего: number; цель?: number }>;
  избранное: string[];
};

const ПУСТЫЕ_ЗИКРЫ: ДокЗикров = { уст: {}, цели: {}, избр: {} };

export function документЗикров(з: unknown): ДокЗикров | null {
  const о = объект(з);
  if (!о.уст && !о.цели && !о.избр) return null;
  const уст: ДокЗикров['уст'] = {};
  for (const [у, з2] of Object.entries(объект(о.уст))) {
    const в = объект(з2);
    if (!/^[A-Za-z0-9_-]{8,40}$/.test(у) || typeof в.at !== 'number') continue;
    const с: Record<string, Доля> = {};
    for (const [id, д] of Object.entries(объект(в.с)))
      if (Array.isArray(д) && typeof д[0] === 'string' && ДАТА.test(д[0]) && ЦЕЛОЕ(д[1]) && ЦЕЛОЕ(д[2])) с[id] = [д[0], д[1], д[2]];
    уст[у] = { at: в.at, с };
  }
  const цели: ДокЗикров['цели'] = {};
  for (const [id, м] of Object.entries(объект(о.цели))) {
    const мм = метка(м);
    if (мм && (мм[0] === null || (ЦЕЛОЕ(мм[0]) && мм[0] >= 1 && мм[0] <= 1000))) цели[id] = мм as Метка<number | null>;
  }
  const избр: ДокЗикров['избр'] = {};
  for (const [id, м] of Object.entries(объект(о.избр))) {
    const мм = метка(м);
    if (мм && typeof мм[0] === 'boolean') избр[id] = мм as Метка<boolean>;
  }
  return { уст, цели, избр };
}

function суммыДругих(д: ДокЗикров, кромеУстройства: string, день: string): Map<string, [number, number]> {
  const итог = new Map<string, [number, number]>();
  for (const [у, в] of Object.entries(д.уст)) {
    if (у === кромеУстройства) continue;
    for (const [id, [дн, сег, всего]] of Object.entries(в.с)) {
      const с = итог.get(id) ?? [0, 0];
      итог.set(id, [с[0] + (дн === день ? сег : 0), с[1] + всего]);
    }
  }
  return итог;
}

export function вДокументЗикров(л: ЛокальныеЗикры, база: ДокЗикров | null, к: Контекст): ДокЗикров {
  const б = база ?? ПУСТЫЕ_ЗИКРЫ;
  const другие = суммыДругих(б, к.устройство, к.день);
  // Своя доля = то, что на экране, минус доли других устройств из общей версии (которые уже вошли в экранный счёт).
  const с: Record<string, Доля> = {};
  for (const id of new Set([...Object.keys(л.счёт), ...другие.keys()])) {
    const з = л.счёт[id];
    const [сегДругих, всегоДругих] = другие.get(id) ?? [0, 0];
    const сегодня = (з && з.день === к.день ? з.текущий : 0) - сегДругих;
    const всего = (з?.всего ?? 0) - всегоДругих;
    if (сегодня !== 0 || всего !== 0) с[id] = [к.день, сегодня, всего];
  }
  const прежняя = б.уст[к.устройство];
  const уст = { ...б.уст };
  const изменилась = !прежняя || !одинаково(Object.fromEntries(Object.entries(прежняя.с).map(([id, д]) => [id, д[0] === к.день ? д : [к.день, 0, д[2]]])), с);
  if (Object.keys(с).length || прежняя) уст[к.устройство] = изменилась ? { at: к.сейчас, с } : прежняя;
  // Цели: своя цель зикра или null (по умолчанию из набора).
  const цели: Record<string, Метка<number | null>> = { ...б.цели };
  const первая = база === null;
  for (const id of new Set([...Object.keys(л.счёт), ...Object.keys(б.цели)])) {
    const цель = л.счёт[id]?.цель ?? null;
    if (цель === null && !б.цели[id]) continue;
    цели[id] = меткаЗначения(цель, б.цели[id], к.сейчас, первая);
  }
  // Избранное — множество с «надгробиями».
  const избр: Record<string, Метка<boolean>> = { ...б.избр };
  const есть = new Set(л.избранное);
  for (const id of new Set([...есть, ...Object.keys(б.избр)])) {
    const сейчасЕсть = есть.has(id);
    const было = б.избр[id];
    if (!было && !сейчасЕсть) continue;
    избр[id] = меткаЗначения(сейчасЕсть, было, к.сейчас, первая);
  }
  return { уст, цели, избр };
}

export function слитьЗикры(а: ДокЗикров, б: ДокЗикров): ДокЗикров {
  const уст: ДокЗикров['уст'] = { ...б.уст };
  for (const [у, в] of Object.entries(а.уст)) {
    const там = уст[у];
    if (!там || в.at > там.at) уст[у] = в;
  }
  return {
    уст,
    цели: слитьМетки(а.цели, б.цели) as ДокЗикров['цели'],
    избр: слитьМетки(а.избр, б.избр) as ДокЗикров['избр'],
  };
}

export function изДокументаЗикров(д: ДокЗикров, л: ЛокальныеЗикры, день: string): ЛокальныеЗикры {
  const суммы = суммыДругих(д, '', день);
  const счёт: ЛокальныеЗикры['счёт'] = {};
  for (const id of new Set([...суммы.keys(), ...Object.keys(д.цели)])) {
    const [сег, всего] = суммы.get(id) ?? [0, 0];
    const цель = д.цели[id]?.[0];
    счёт[id] = { текущий: Math.max(0, сег), день, всего: Math.max(0, всего), ...(typeof цель === 'number' ? { цель } : null) };
  }
  // Порядок избранного: как было на устройстве, новые — в конце.
  const в = Object.entries(д.избр).filter(([, м]) => м[0]).map(([id]) => id);
  const избранное = [...л.избранное.filter((id) => в.includes(id)), ...в.filter((id) => !л.избранное.includes(id)).sort()];
  return { счёт, избранное };
}

/** Экранный счёт: записи без счёта и цели не важны (равны отсутствию), день записи без счёта сегодня — не важен. */
export function зикрыОдинаковы(а: ЛокальныеЗикры, б: ЛокальныеЗикры, день: string): boolean {
  const н = (л: ЛокальныеЗикры) => {
    const с: Record<string, unknown> = {};
    for (const [id, з] of Object.entries(л.счёт)) {
      const сег = з.день === день ? з.текущий : 0;
      if (сег || з.всего || з.цель !== undefined) с[id] = [сег, з.всего, з.цель ?? null];
    }
    return { с, и: л.избранное };
  };
  return одинаково(н(а), н(б));
}

// ───────────────────────── поля с метками: quran, settings, zakat ─────────────────────────
export type ДокПолей = Record<string, Метка<unknown>>;

export function документПолей(з: unknown): ДокПолей | null {
  const о = объект(з);
  const итог: ДокПолей = {};
  for (const [к, м] of Object.entries(о)) {
    const мм = метка(м);
    if (мм) итог[к] = мм;
  }
  return Object.keys(о).length && !Object.keys(итог).length ? null : итог;
}

export function вДокументПолей(поля: Record<string, unknown>, база: ДокПолей | null, сейчас: number): ДокПолей {
  return меткиПолей(поля, база, сейчас);
}

export function слитьПоля(а: ДокПолей, б: ДокПолей): ДокПолей {
  return слитьМетки(а, б);
}

export function изДокументаПолей(д: ДокПолей): Record<string, unknown> {
  return Object.fromEntries(Object.entries(д).map(([к, м]) => [к, м[0]]));
}

// ───────────────────────── общий вход ─────────────────────────
export type Документ = ДокПрогресса | ДокЗикров | ДокПолей;

export function разобратьДокумент(ключ: КлючСинхронизации, з: unknown): Документ | null {
  if (з === null || з === undefined) return null;
  if (ключ === 'progress') return документПрогресса(з);
  if (ключ === 'dhikr') return документЗикров(з);
  return документПолей(з);
}

export function слить(ключ: КлючСинхронизации, здесь: Документ, там: Документ | null): Документ {
  if (!там) return здесь;
  if (ключ === 'progress') return слитьПрогресс(здесь as ДокПрогресса, там as ДокПрогресса);
  if (ключ === 'dhikr') return слитьЗикры(здесь as ДокЗикров, там as ДокЗикров);
  return слитьПоля(здесь as ДокПолей, там as ДокПолей);
}
