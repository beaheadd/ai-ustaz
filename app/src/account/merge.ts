/**
 * Синхронизация аккаунта — документы и правила слияния (чистые функции; тесты — scripts/test-account.mjs).
 *
 * Владелец 28.11.2026: «создай вход, чтобы кто хочет, мог заходить входом, и у него прогресс сохраняется. И с другого
 * устройства он также может зайти с сохраненным прогрессом». Дизайн — docs/дизайн/13-аккаунт-и-синхронизация.md.
 *
 * Сервер хранит документы по ключу с версией и НЕ сливает (server/account.py): слияние — здесь. Для каждого ключа:
 *   документ = вДокумент(ключ, локальное, база, контекст)   — что на этом устройстве, с учётом последней общей версии;
 *   итог     = слить(ключ, документ, сервер)                — с документом сервера (другие устройства);
 *   локальное = изДокумента(ключ, итог, локальное, контекст) — записать на устройство (если изменилось);
 *   итог ≠ сервер → записать на сервер поверх его версии (конфликт — повторить со свежей версией).
 * «База» — документ, с которым это устройство последний раз сошлось с сервером: по ней видно, что изменилось здесь.
 *
 * Что синхронизируется (и ничего больше; список ключей — СИНХРОННЫЕ_КЛЮЧИ ниже):
 *   progress — уроки (пройден: «или», лучший: максимум, попыток: максимум, последний: позже), дни занятий (объединение,
 *              ≤ 400), отметки «первый вход пройден» и «ИИ-предупреждение показано» («или»). Сброс прогресса на
 *              устройстве — новая «эпоха»: документ с более поздней эпохой заменяет старый целиком. Не синхронизируются:
 *              согласие на проверку голосом и пояснение о микрофоне (свои у каждого устройства), язык (он — в settings);
 *   dhikr    — счёт по устройствам: у каждого устройства своя доля «сегодня» (день по Алматы) и «всего», на экране —
 *              сумма долей (≥ 0). Нажатие +1 здесь — +1 к своей доле; сброс — своя доля становится отрицательной, сумма —
 *              0; одинаковые нажатия на двух телефонах складываются, а не теряются. Цель — последняя по времени;
 *              избранное — множество с «надгробиями» (убрали — [false, когда]), каждое последнее по времени;
 *   quran    — место чтения и закладка (одна, как в бумажном мусхафе): последняя по времени;
 *   settings — язык, тема, город из списка (своя точка по геолокации НЕ уходит), аср, подсветка слов, вид чтения, размер
 *              арабского, чтец, выбор намазов и «напомнить заранее» для уведомлений (включены ли уведомления и подписка —
 *              у каждого устройства свои): по полю, последнее по времени;
 *   zakat    — суммы калькулятора закята — только с выключателем «Сохранять суммы закята в аккаунте» (выкл.): целиком,
 *              последнее по времени.
 * Никогда: история чата, голос, фото, id статистики, подписка на уведомления, кэши, скачанное.
 *
 * «Последнее по времени» — пара [значение, мс]. Значение, которого на устройстве ещё не было в общей версии (первая
 * синхронизация), получает время 0: аккаунт важнее того, что устройство успело выбрать до входа; при равном времени —
 * то, что уже на сервере.
 */

export const СИНХРОННЫЕ_КЛЮЧИ = ['progress', 'dhikr', 'quran', 'settings', 'zakat'] as const;
export type КлючСинхронизации = (typeof СИНХРОННЫЕ_КЛЮЧИ)[number];

/** Значение и момент изменения (мс). */
export type Метка<T> = [T, number];

export type Контекст = { сейчас: number; день: string; устройство: string };

const МАКС_ДНЕЙ = 400;
const ДАТА = /^\d{4}-\d{2}-\d{2}$/;
const ЦЕЛОЕ = (x: unknown): x is number => typeof x === 'number' && Number.isInteger(x) && Math.abs(x) <= 1e9;

/** Устойчивое сравнение (порядок ключей не важен). */
export function одинаково(а: unknown, б: unknown): boolean {
  return устойчиво(а) === устойчиво(б);
}

export function устойчиво(з: unknown): string {
  if (з === undefined) return 'undefined';
  if (з === null || typeof з !== 'object') return JSON.stringify(з);
  if (Array.isArray(з)) return '[' + з.map(устойчиво).join(',') + ']';
  const о = з as Record<string, unknown>;
  return '{' + Object.keys(о).filter((к) => о[к] !== undefined).sort().map((к) => JSON.stringify(к) + ':' + устойчиво(о[к])).join(',') + '}';
}

function метка(з: unknown): Метка<unknown> | null {
  return Array.isArray(з) && з.length === 2 && typeof з[1] === 'number' && Number.isFinite(з[1]) ? (з as Метка<unknown>) : null;
}

/** Последнее по времени; при равенстве — серверное (второй аргумент). */
export function позднее<T>(здесь: Метка<T> | null | undefined, там: Метка<T> | null | undefined): Метка<T> | null {
  if (!здесь) return там ?? null;
  if (!там) return здесь;
  return здесь[1] > там[1] ? здесь : там;
}

/** Метка для значения с устройства: не менялось с общей версии — прежняя метка; первая встреча — время 0; иначе — сейчас. */
export function меткаЗначения<T>(значение: T, база: Метка<T> | null | undefined, сейчас: number, первая: boolean): Метка<T> {
  if (база && одинаково(база[0], значение)) return база;
  return [значение, первая && !база ? 0 : сейчас];
}

function объект(з: unknown): Record<string, unknown> {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : {};
}

/** Поля с метками: по каждому — позднее (ключи из обоих). */
function слитьМетки(здесь: Record<string, unknown>, там: Record<string, unknown>): Record<string, Метка<unknown>> {
  const итог: Record<string, Метка<unknown>> = {};
  for (const к of new Set([...Object.keys(здесь), ...Object.keys(там)])) {
    const м = позднее(метка(здесь[к]), метка(там[к]));
    if (м) итог[к] = м;
  }
  return итог;
}

/** Поля с устройства (undefined — «нет мнения») → метки относительно базы. */
function меткиПолей(поля: Record<string, unknown>, база: Record<string, unknown> | null, сейчас: number): Record<string, Метка<unknown>> {
  const б = база ?? {};
  const итог: Record<string, Метка<unknown>> = {};
  for (const [к, м] of Object.entries(б)) {
    const мм = метка(м);
    if (мм) итог[к] = мм;
  }
  for (const [к, з] of Object.entries(поля)) {
    if (з === undefined) continue;
    итог[к] = меткаЗначения(з, метка(б[к]), сейчас, база === null);
  }
  return итог;
}

// ───────────────────────── progress ─────────────────────────
export type УрокДок = { п: boolean; л: number; р: number; д: string };
export type ДокПрогресса = { эпоха: number; уроки: Record<string, УрокДок>; дни: string[]; флаги: { онбординг: boolean; предупреждение: boolean } };
/** Часть прогресса устройства, которая синхронизируется (engine/progress.ts Прогресс без языка и согласий). */
export type ЛокальныйПрогресс = {
  уроки: Record<string, { пройден: boolean; лучший: number; попыток: number; последний: string }>;
  дниЗанятий: string[];
  онбордингПройден: boolean;
  предупреждениеПоказано: boolean;
};

function урокИз(з: unknown): УрокДок | null {
  const у = объект(з);
  if (typeof у.п !== 'boolean' || typeof у.л !== 'number' || !Number.isFinite(у.л) || !ЦЕЛОЕ(у.р) || typeof у.д !== 'string') return null;
  return { п: у.п, л: Math.min(1, Math.max(0, у.л)), р: Math.max(0, у.р), д: ДАТА.test(у.д) ? у.д : '' };
}

export function документПрогресса(з: unknown): ДокПрогресса | null {
  const о = объект(з);
  if (!ЦЕЛОЕ(о.эпоха) && typeof о.эпоха !== 'number') return null;
  const уроки: Record<string, УрокДок> = {};
  for (const [к, у] of Object.entries(объект(о.уроки))) {
    const р = урокИз(у);
    if (р && /^\d{1,3}$/.test(к)) уроки[к] = р;
  }
  const дни = Array.isArray(о.дни) ? [...new Set(о.дни.filter((д): д is string => typeof д === 'string' && ДАТА.test(д)))].sort().slice(-МАКС_ДНЕЙ) : [];
  const ф = объект(о.флаги);
  return { эпоха: Number(о.эпоха) || 0, уроки, дни, флаги: { онбординг: ф.онбординг === true, предупреждение: ф.предупреждение === true } };
}

export function вДокументПрогресса(л: ЛокальныйПрогресс, база: ДокПрогресса | null, сейчас: number): ДокПрогресса {
  const уроки: Record<string, УрокДок> = {};
  for (const [к, у] of Object.entries(л.уроки)) уроки[к] = { п: у.пройден, л: у.лучший, р: у.попыток, д: у.последний };
  // Сброс прогресса на устройстве: урок из общей версии пропал или дни занятий стали пустыми — новая эпоха.
  const сброс = !!база && (Object.keys(база.уроки).some((к) => !(к in уроки)) || (база.дни.length > 0 && л.дниЗанятий.length === 0));
  return {
    эпоха: сброс ? сейчас : база?.эпоха ?? 0,
    уроки,
    дни: [...new Set(л.дниЗанятий)].sort().slice(-МАКС_ДНЕЙ),
    флаги: { онбординг: л.онбордингПройден, предупреждение: л.предупреждениеПоказано },
  };
}

export function слитьПрогресс(а: ДокПрогресса, б: ДокПрогресса): ДокПрогресса {
  if (а.эпоха !== б.эпоха) return а.эпоха > б.эпоха ? а : б;
  const уроки: Record<string, УрокДок> = { ...б.уроки };
  for (const [к, у] of Object.entries(а.уроки)) {
    const в = уроки[к];
    уроки[к] = в ? { п: у.п || в.п, л: Math.max(у.л, в.л), р: Math.max(у.р, в.р), д: у.д > в.д ? у.д : в.д } : у;
  }
  return {
    эпоха: а.эпоха,
    уроки,
    дни: [...new Set([...а.дни, ...б.дни])].sort().slice(-МАКС_ДНЕЙ),
    флаги: { онбординг: а.флаги.онбординг || б.флаги.онбординг, предупреждение: а.флаги.предупреждение || б.флаги.предупреждение },
  };
}

export function изДокументаПрогресса(д: ДокПрогресса): ЛокальныйПрогресс {
  const уроки: ЛокальныйПрогресс['уроки'] = {};
  for (const [к, у] of Object.entries(д.уроки)) уроки[к] = { пройден: у.п, лучший: у.л, попыток: у.р, последний: у.д };
  return { уроки, дниЗанятий: д.дни, онбордингПройден: д.флаги.онбординг, предупреждениеПоказано: д.флаги.предупреждение };
}

