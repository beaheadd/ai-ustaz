export type ВидСлоя = 'перевод' | 'тафсир';
export type ЗаписьИздания = { readonly ключ: string; readonly индекс: string; readonly sha256Индекса: string };
export type МанифестПереводов = {
  readonly формат: 1;
  readonly переводы: Readonly<Record<string, ЗаписьИздания>>;
  readonly тафсиры: Readonly<Record<string, ЗаписьИздания>>;
};

export type Одобрение = { кто: string; когда: string } | null;

export type ИндексПеревода = {
  ключ: string;
  вид: ВидСлоя;
  /** Язык текста издания (ru, kk, …, ar). */
  язык: string;
  /** Название издания как у источника (QuranEnc, title). */
  название: string;
  /** Переводчик или автор — по-русски и на языке издания (для подписи «Перевод смыслов (…, QuranEnc.com)»). */
  автор: string;
  версия: string;
  /** Дата последнего обновления у источника (ГГГГ-ММ-ДД) или ''. */
  дата: string;
  источник: string;
  /** Страница издания у источника без схемы (условие QuranEnc — ясная ссылка на источник). */
  ссылка: string;
  одобрено: Одобрение;
  аятов: readonly number[];
  суры: readonly { файл: string; sha256: string }[];
};

/** Аят слоя: текст и сноски переводчика (null — нет). */
export type АятПеревода = { текст: string; сноски: string | null };
export type СураПеревода = { ключ: string; сура: number; аяты: АятПеревода[] };

/** Тафсира на языке нет — запасной язык с пометкой (владелец 28.11.2026: «если разрешено, арабский или английский вариант
 * с пометкой»). Сейчас запаса нет: «аль-Мухтасар» у QuranEnc на ru, kk, en, ur нет, а арабский оригинал этим людям
 * почти ничего не даст и в аятах об атрибутах расходится с линией ДУМК (решение — за владельцем и устазом; включить —
 * вписать ['ar'] для языка). Экран пишет «Тафсир на вашем языке пока недоступен». */
export const ЗАПАС_ТАФСИРА: Readonly<Record<string, readonly string[]>> = {};

const SHA = /^[0-9a-f]{64}$/;
const ТЕГ = /<\/?[a-z][^>]*>/i;

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
function строка(з: unknown): з is string {
  return typeof з === 'string' && з.length > 0;
}

export function изданиеДляЯзыка(м: МанифестПереводов, вид: ВидСлоя, язык: string): (ЗаписьИздания & { язык: string; свой: boolean }) | null {
  const таблица = вид === 'перевод' ? м.переводы : м.тафсиры;
  const есть = (я: string) => Object.prototype.hasOwnProperty.call(таблица, я);
  if (есть(язык)) return { ...таблица[язык], язык, свой: true };
  if (вид === 'перевод') return null;
  for (const я of ЗАПАС_ТАФСИРА[язык] ?? []) if (есть(я)) return { ...таблица[я], язык: я, свой: false };
  return null;
}

/** Индекс издания: ключ = манифесту, 114 сур, имя файла суры с началом sha256, аятов 6236. */
export function проверитьИндексПеревода(сырые: unknown, запись: ЗаписьИздания): ИндексПеревода | null {
  const и = объект(сырые);
  if (!и || и.формат !== 1 || и.ключ !== запись.ключ || (и.вид !== 'перевод' && и.вид !== 'тафсир')) return null;
  if (!строка(и.язык) || !строка(и.название) || !строка(и.автор) || !строка(и.источник) || !строка(и.ссылка)) return null;
  if (typeof и.версия !== 'string' || typeof и.дата !== 'string') return null;
  const о = и.одобрено === null ? null : объект(и.одобрено);
  if (и.одобрено !== null && !(о && строка(о.кто) && строка(о.когда))) return null;
  if (!Array.isArray(и.суры) || и.суры.length !== 114 || !Array.isArray(и.аятов) || и.аятов.length !== 114) return null;
  let всего = 0;
  const суры: { файл: string; sha256: string }[] = [];
  for (let i = 0; i < 114; i++) {
    const з = объект(и.суры[i]);
    const н = и.аятов[i];
    if (typeof н !== 'number' || !Number.isInteger(н) || н < 3 || н > 286) return null;
    всего += н;
    if (!з || !строка(з.файл) || !строка(з.sha256) || !SHA.test(з.sha256)) return null;
    const ожидаемое = `quran-trans/${запись.ключ}/${String(i + 1).padStart(3, '0')}.${з.sha256.slice(0, 20)}.json`;
    if (з.файл !== ожидаемое) return null;
    суры.push({ файл: з.файл, sha256: з.sha256 });
  }
  if (всего !== 6236) return null;
  return {
    ключ: запись.ключ,
    вид: и.вид,
    язык: и.язык,
    название: и.название,
    автор: и.автор,
    версия: и.версия,
    дата: и.дата,
    источник: и.источник,
    ссылка: и.ссылка,
    одобрено: о ? { кто: о.кто as string, когда: о.когда as string } : null,
    аятов: и.аятов as number[],
    суры,
  };
}

export function проверитьСуруПеревода(сырые: unknown, индекс: ИндексПеревода, сура: number): СураПеревода | null {
  const с = объект(сырые);
  if (!с || с.формат !== 1 || с.ключ !== индекс.ключ || с.сура !== сура || !Array.isArray(с.аяты)) return null;
  if (с.аяты.length !== индекс.аятов[сура - 1]) return null;
  const аяты: АятПеревода[] = [];
  for (const а of с.аяты) {
    if (!Array.isArray(а) || а.length !== 2 || !строка(а[0]) || ТЕГ.test(а[0])) return null;
    if (а[1] !== null && (!строка(а[1]) || ТЕГ.test(а[1]))) return null;
    аяты.push({ текст: а[0], сноски: а[1] });
  }
  return { ключ: индекс.ключ, сура, аяты };
}
