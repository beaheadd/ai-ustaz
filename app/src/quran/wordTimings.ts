/**
 * Пословные тайминги чтения — данные для подсветки слова, которое сейчас читает кари (владелец 27.11.2026: «когда
 * выйдет вот этот жёлтый, который вместе двигается с чтецом, выделение именно слов, которые читают»). Только данные и
 * чистые функции — подключение к экранам делается отдельно.
 *
 * Откуда: dist/quran-words/<издание>/… (app/public/quran-words; tools/quran_words/build_words.py), источник —
 * quran-align (Collin Fair), CC BY 4.0, приняты только записи, сверенные с нашими файлами (content/quran-words/report.json).
 * Есть не у всех изданий: МАНИФЕСТ_СЛОВ.издания — список. Нет издания или аята — подсветки слова нет (только аят).
 *
 * Контракт (без React; проверяется в node — scripts/test-word-timings.mjs):
 *   развернуть(плоский) → Array<[началоМс, конецМс]> — из формата файла (сантисекунды, [начало, длит, пауза, длит, …]);
 *   словоПоВремени(слова, мс) → номер слова с 0 или -1 (до первого слова); между словами — предыдущее (подсветка не
 *     мигает в паузах); после последнего — последнее;
 *   естьТайминги(манифест, издание) → boolean (манифест — МАНИФЕСТ_СЛОВ из wordsManifest.generated.ts; модуль без
 *     импортов, чтобы node проверял его как есть);
 *   создатьЗагрузчикСлов({ манифест, база, получить, sha256 }) → { таймингиСуры(издание, сура) → Promise<ТаймингиСуры | null> }:
 *     индекс издания и суры — по одному запросу, кэш в памяти, сверка sha256 (не сошлось — null, без кэша);
 *     ТаймингиСуры.аят(номер с 1) → Array<[началоМс, конецМс]> | null.
 */
export type МанифестСлов = { формат: 1; издания: Readonly<Record<string, { индекс: string; sha256Индекса: string }>> };

export type ОтрезокСлова = readonly [number, number];
export type ТаймингиСуры = { издание: string; сура: number; аят(номер: number): ОтрезокСлова[] | null };

type ФайлСуры = { формат: 1; издание: string; сура: number; аяты: Array<number[] | null> };
type ИндексИздания = { формат: 1; издание: string; суры: Record<string, { файл: string; sha256: string }> };

export function развернуть(плоский: readonly number[]): ОтрезокСлова[] {
  const итог: ОтрезокСлова[] = [];
  let конец = 0;
  for (let i = 0; i + 1 < плоский.length; i += 2) {
    const начало = i === 0 ? плоский[0] : конец + плоский[i];
    конец = начало + плоский[i + 1];
    итог.push([начало * 10, конец * 10]);
  }
  return итог;
}

export function словоПоВремени(слова: readonly ОтрезокСлова[], мс: number): number {
  if (!слова.length || !(мс >= слова[0][0])) return -1;
  let низ = 0;
  let верх = слова.length - 1;
  while (низ < верх) {
    const сер = (низ + верх + 1) >> 1;
    if (слова[сер][0] <= мс) низ = сер;
    else верх = сер - 1;
  }
  return низ;
}

export function естьТайминги(манифест: МанифестСлов, издание: string): boolean {
  return Object.prototype.hasOwnProperty.call(манифест.издания, издание);
}

export type ЗависимостиЗагрузчика = {
  манифест: МанифестСлов;
  /** База адресов сборки ('/aiustaz'). */
  база: string;
  /** Текст файла или null (нет файла, нет связи). */
  получить: (адрес: string) => Promise<string | null>;
  sha256: (текст: string) => Promise<string>;
};

export function создатьЗагрузчикСлов(з: ЗависимостиЗагрузчика) {
  const индексы = new Map<string, ИндексИздания>();
  const суры = new Map<string, ТаймингиСуры>();

  async function файл<T>(путь: string, sha: string): Promise<T | null> {
    const текст = await з.получить(`${з.база}/${путь}`);
    if (текст == null || (await з.sha256(текст)) !== sha) return null;
    try {
      return JSON.parse(текст) as T;
    } catch {
      return null;
    }
  }

  async function индекс(издание: string): Promise<ИндексИздания | null> {
    const есть = индексы.get(издание);
    if (есть) return есть;
    const м = естьТайминги(з.манифест, издание) ? з.манифест.издания[издание] : undefined;
    if (!м) return null;
    const и = await файл<ИндексИздания>(м.индекс, м.sha256Индекса);
    if (и && и.издание === издание) индексы.set(издание, и);
    return и && и.издание === издание ? и : null;
  }

  async function таймингиСуры(издание: string, сура: number): Promise<ТаймингиСуры | null> {
    const ключ = `${издание}/${сура}`;
    const есть = суры.get(ключ);
    if (есть) return есть;
    const и = await индекс(издание);
    const запись = и?.суры[String(сура)];
    if (!запись) return null;
    const ф = await файл<ФайлСуры>(запись.файл, запись.sha256);
    if (!ф || ф.издание !== издание || ф.сура !== сура || !Array.isArray(ф.аяты)) return null;
    const кэш = new Map<number, ОтрезокСлова[]>();
    const итог: ТаймингиСуры = {
      издание,
      сура,
      аят(номер) {
        const п = ф.аяты[номер - 1];
        if (!п) return null;
        let р = кэш.get(номер);
        if (!р) {
          р = развернуть(п);
          кэш.set(номер, р);
        }
        return р;
      },
    };
    суры.set(ключ, итог);
    return итог;
  }

  return { таймингиСуры };
}
