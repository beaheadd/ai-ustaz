export const ТАЙМАУТ_МС = 20000;

/** baseUrl сборки ('/aiustaz' из app.json experiments.baseUrl): Expo подставляет process.env.EXPO_BASE_URL при сборке. */
export function базаСборки(): string {
  try {
    const б = process.env.EXPO_BASE_URL;
    if (typeof б === 'string') return б;
  } catch {
    // нет process в среде — ниже значение по умолчанию
  }
  return '/aiustaz';
}

async function получить(адрес: string): Promise<ОтветФайла> {
  const стоп = typeof AbortController === 'function' ? new AbortController() : null;
  const таймер = стоп ? setTimeout(() => стоп.abort(), ТАЙМАУТ_МС) : null;
  try {
    const ответ = await fetch(адрес, { credentials: 'omit', referrerPolicy: 'no-referrer', signal: стоп?.signal });
    // Тело читаем здесь же, пока таймер жив: обрыв на середине — тоже «нет связи».
    const текст = ответ.ok ? await ответ.text() : '';
    return { ok: ответ.ok, status: ответ.status, text: async () => текст, тип: ответ.headers?.get?.('content-type') ?? null };
  } finally {
    if (таймер) clearTimeout(таймер);
  }
}

const загрузчик = создатьЗагрузчик({ база: базаСборки(), манифест: МАНИФЕСТ_КОРАНА, получить, sha256: sha256Hex });

export const загрузитьИндексСур = загрузчик.загрузитьИндексСур;
export const загрузитьСуру = загрузчик.загрузитьСуру;
export const сураИзКэша = загрузчик.сураИзКэша;
