export type СостояниеКорана<Т> =
  | { состояние: 'загрузка' }
  | { состояние: 'нет'; нетСвязи: boolean; причина: ПричинаОтказа }
  | { состояние: 'есть'; данные: Т };

function изРезультата<Т>(р: Результат<Т>): СостояниеКорана<Т> {
  return р.ок ? { состояние: 'есть', данные: р.данные } : { состояние: 'нет', нетСвязи: причинаНетСвязи(р.причина), причина: р.причина };
}

export function useЗагрузка<Т>(ключ: string | null, сразу: Т | null, загрузить: () => Promise<Результат<Т>>) {
  // Состояние помнит, к какому ключу оно относится: при смене суры старая не мелькает, кэш показывается сразу.
  const [запись, установить] = useState<{ ключ: string | null; с: СостояниеКорана<Т> }>({ ключ: null, с: { состояние: 'загрузка' } });
  const [попытка, установитьПопытку] = useState(0);
  const с: СостояниеКорана<Т> =
    запись.ключ === ключ ? запись.с : сразу ? { состояние: 'есть', данные: сразу } : { состояние: 'загрузка' };
  useEffect(() => {
    if (ключ === null) return;
    let живой = true;
    загрузить().then((р) => {
      if (живой) установить({ ключ, с: изРезультата(р) });
    });
    return () => {
      живой = false;
    };
    // загрузить зависит только от ключа
  }, [ключ, попытка]); // eslint-disable-line react-hooks/exhaustive-deps
  const повторить = useCallback(() => {
    установить({ ключ, с: { состояние: 'загрузка' } });
    установитьПопытку((п) => п + 1);
  }, [ключ]);
  return useMemo(() => ({ ...с, повторить }), [с, повторить]);
}

/** Индекс сур (список для экрана #/quran). */
export function useИндексСур(): СостояниеКорана<ИндексСур> & { повторить: () => void } {
  return useЗагрузка('индекс', индексИзКэша(), загрузитьИндексСур);
}

/** Сура н (1…114); null — ничего не грузить. */
export function useСура(номер: number | null): СостояниеКорана<СураКорана> & { повторить: () => void } {
  return useЗагрузка(номер === null ? null : 'сура-' + номер, номер === null ? null : сураИзКэша(номер), () =>
    загрузитьСуру(номер ?? 0),
  );
}
