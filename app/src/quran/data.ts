/**
 * Полный Коран для показа — загрузка в приложении (веб): индекс сур и суры по одной, с кэшем и сверкой.
 * Чистая логика и типы — src/quran/loader.ts; разбор аята на слова и знаки — src/quran/text.ts.
 *
 * Откуда: статические файлы сборки /aiustaz/quran/… (app/public/quran → dist/quran; tools/quran/build_quran.py).
 * Текста Корана в JS-чанках нет — только манифест (manifest.generated.ts: имя и sha256 индекса). Запросы — только
 * на свой адрес (CSP connect-src 'self'), без cookie; по одной суре, когда экран её попросил.
 *
 * Контракт:
 *   загрузитьИндексСур(): Promise<Результат<ИндексСур>>; загрузитьСуру(н): Promise<Результат<СураКорана>>
 *   сураИзКэша(н), индексИзКэша() — уже загруженное, без ожидания (плеер, переход к следующей суре)
 *   useИндексСур(), useСура(н | null) → ({ состояние: 'загрузка' } | { состояние: 'нет'; нетСвязи; причина }
 *     | { состояние: 'есть'; данные }) & { повторить() } — как useДанные (components/info/data.ts):
 *     нетСвязи: true — «Нет связи» и «Повторить» (без перезагрузки страницы); причина 'нет-файла' — «Файл не найден,
 *     обновите страницу»; иначе — «Текст не прошёл сверку — не показываем». Экраны рисуют это <СостояниеКорана>
 *     (screens/quran/QuranState.tsx). Неудачи не кэшируются.
 *   ТАЙМАУТ_МС — запрос дольше считается «нет связи».
 * Нативно (Android/iOS) относительного адреса нет: пока база — EXPO_BASE_URL, запросы не дойдут → «нет связи».
 * TODO: на телефоне — адрес своего домена или файлы в пакете приложения (docs/дизайн/05, «Контракт»).
 * Решение владельца 19.11.2026: «Коран полностью, все аяты…».
 */
