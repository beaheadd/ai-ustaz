/**
 * Размер арабского текста Корана (экран суры, «Прочитать и записать», бисмилла) — выбор человека, только на устройстве.
 *
 * Зачем (ревью 19.11.2026): кегль был зашит в px, а системный «крупный текст» iOS Safari на px не влияет; у читалок
 * Корана регулятор размера есть всегда, а среди учеников — люди старшего возраста.
 *
 * Контракт:
 *   РАЗМЕРЫ_АРАБСКОГО = [24, 28, 32, 36, 40] (кегль, px); ПО_УМОЛЧАНИЮ = 28.
 *   межстрочныйАрабского(кегль) → round(кегль × МЕЖСТРОЧНЫЙ): 1,8 (было 2,0 — знаки остановки уходили к строке выше;
 *     по снимкам 1,8 держит огласовки и знаки над и под строкой Amiri Quran без наложения; утверждать вместе с кари).
 *   useРазмерАрабского() → { кегль, межстрочный, меньше(), больше(), можноМеньше, можноБольше } — подписка на выбор.
 *   установитьРазмерАрабского(кегль) — ближайшая ступень; хранение: localStorage «aiustaz:quran-font.v1» = { версия: 1,
 *     кегль } (веб, синхронно — без мигания; в try/catch: приватный режим — просто не помним). Нативно — пока в памяти.
 * Без импортов кода, кроме React (тест в node: scripts/test-quran.mjs — ступени и межстрочный).
 */
import { useSyncExternalStore } from 'react';

export const РАЗМЕРЫ_АРАБСКОГО: readonly number[] = [24, 28, 32, 36, 40];
export const ПО_УМОЛЧАНИЮ = 28;
export const МЕЖСТРОЧНЫЙ = 1.8;
const КЛЮЧ = 'aiustaz:quran-font.v1';

export function межстрочныйАрабского(кегль: number): number {
  return Math.round(кегль * МЕЖСТРОЧНЫЙ);
}

/** Ближайшая ступень (неверное — по умолчанию). */
export function ступеньАрабского(кегль: unknown): number {
  if (typeof кегль !== 'number' || !Number.isFinite(кегль)) return ПО_УМОЛЧАНИЮ;
  let лучшая = РАЗМЕРЫ_АРАБСКОГО[0];
  for (const р of РАЗМЕРЫ_АРАБСКОГО) if (Math.abs(р - кегль) < Math.abs(лучшая - кегль)) лучшая = р;
  return лучшая;
}

function прочитать(): number {
  try {
    const строка = globalThis.localStorage?.getItem(КЛЮЧ);
    if (!строка) return ПО_УМОЛЧАНИЮ;
    const д = JSON.parse(строка) as { версия?: unknown; кегль?: unknown } | null;
    return д && д.версия === 1 ? ступеньАрабского(д.кегль) : ПО_УМОЛЧАНИЮ;
  } catch {
    return ПО_УМОЛЧАНИЮ;
  }
}

let кегльСейчас: number | null = null;
const слушатели = new Set<() => void>();

function текущий(): number {
  if (кегльСейчас === null) кегльСейчас = прочитать();
  return кегльСейчас;
}

export function установитьРазмерАрабского(кегль: number): void {
  const новый = ступеньАрабского(кегль);
  if (новый === текущий()) return;
  кегльСейчас = новый;
  try {
    globalThis.localStorage?.setItem(КЛЮЧ, JSON.stringify({ версия: 1, кегль: новый }));
  } catch {
    // приватный режим или переполнено — выбор живёт до перезагрузки
  }
  for (const с of [...слушатели]) с();
}

function подписаться(с: () => void): () => void {
  слушатели.add(с);
  return () => {
    слушатели.delete(с);
  };
}

export function useРазмерАрабского() {
  const кегль = useSyncExternalStore(подписаться, текущий, текущий);
  const и = РАЗМЕРЫ_АРАБСКОГО.indexOf(кегль);
  return {
    кегль,
    межстрочный: межстрочныйАрабского(кегль),
    можноМеньше: и > 0,
    можноБольше: и >= 0 && и < РАЗМЕРЫ_АРАБСКОГО.length - 1,
    меньше: () => установитьРазмерАрабского(РАЗМЕРЫ_АРАБСКОГО[Math.max(0, и - 1)] ?? ПО_УМОЛЧАНИЮ),
    больше: () => установитьРазмерАрабского(РАЗМЕРЫ_АРАБСКОГО[Math.min(РАЗМЕРЫ_АРАБСКОГО.length - 1, и + 1)] ?? ПО_УМОЛЧАНИЮ),
  };
}
