/**
 * Шрифт Корана — выбор человека: «Мединский мусхаф» (KFGQPC HAFS Uthmanic Script, Комплекс короля Фахда) или
 * «Классический» (Amiri Quran, прежний шрифт приложения).
 *
 * Владелец 28.11.2026: «У меня уже два брата спросили, чтобы шрифт был такой. Поставь выбор шрифта, по умолчанию — этот.
 * Пусть наш тоже будет»; «Да, с подстройкой» — мединский по умолчанию, подстройка показа (quran/displayKfgqpc.ts)
 * утверждена, ждёт проверки устаза.
 *
 * Контракт:
 *   ШРИФТЫ_КОРАНА = ['мединский', 'классический']; ШРИФТ_КОРАНА_ПО_УМОЛЧАНИЮ = 'мединский'.
 *   useВыборШрифтаКорана() → ШрифтКорана — подписка на выбор; выборШрифтаКорана() — без подписки.
 *   установитьШрифтКорана(шрифт) — хранение: localStorage «aiustaz:quran-script.v1» = { версия: 1, шрифт } (веб,
 *     синхронно — без мигания; в try/catch: приватный режим — просто не помним). Аккаунт синхронизирует его в
 *     документе settings (account/sync.ts, поле «шрифт»); пришло с другого устройства — событие «aiustaz:внешнее».
 * Без импортов кода, кроме React (тест в node: scripts/test-quran.mjs).
 */
import { useSyncExternalStore } from 'react';

export type ШрифтКорана = 'мединский' | 'классический';
export const ШРИФТЫ_КОРАНА: readonly ШрифтКорана[] = ['мединский', 'классический'];
export const ШРИФТ_КОРАНА_ПО_УМОЛЧАНИЮ: ШрифтКорана = 'мединский';
export const КЛЮЧ_ШРИФТА_КОРАНА = 'quran-script.v1';
const КЛЮЧ = 'aiustaz:' + КЛЮЧ_ШРИФТА_КОРАНА;

export function этоШрифтКорана(з: unknown): з is ШрифтКорана {
  return typeof з === 'string' && (ШРИФТЫ_КОРАНА as readonly string[]).includes(з);
}

function прочитать(): ШрифтКорана {
  try {
    const строка = globalThis.localStorage?.getItem(КЛЮЧ);
    if (!строка) return ШРИФТ_КОРАНА_ПО_УМОЛЧАНИЮ;
    const д = JSON.parse(строка) as { версия?: unknown; шрифт?: unknown } | null;
    return д && д.версия === 1 && этоШрифтКорана(д.шрифт) ? д.шрифт : ШРИФТ_КОРАНА_ПО_УМОЛЧАНИЮ;
  } catch {
    return ШРИФТ_КОРАНА_ПО_УМОЛЧАНИЮ;
  }
}

let сейчас: ШрифтКорана | null = null;
const слушатели = new Set<() => void>();
// Аккаунт: синхронизация записала выбор другого устройства — перечитать (событие окна, как в quran/fontSize.ts).
globalThis.addEventListener?.('aiustaz:внешнее', (е) => {
  if (!(е as CustomEvent<string[]>).detail?.includes(КЛЮЧ_ШРИФТА_КОРАНА)) return;
  сейчас = null;
  for (const ф of [...слушатели]) ф();
});

export function выборШрифтаКорана(): ШрифтКорана {
  if (сейчас === null) сейчас = прочитать();
  return сейчас;
}

export function установитьШрифтКорана(шрифт: ШрифтКорана): void {
  if (!этоШрифтКорана(шрифт) || шрифт === выборШрифтаКорана()) return;
  сейчас = шрифт;
  try {
    globalThis.localStorage?.setItem(КЛЮЧ, JSON.stringify({ версия: 1, шрифт }));
  } catch {
    // приватный режим или переполнено — выбор живёт до перезагрузки
  }
  for (const с of [...слушатели]) с();
}

function подписаться(с: () => void): () => void {
  слушатели.add(с);
  return () => {
    слушатели.delete(с);
  };
}

export function useВыборШрифтаКорана(): ШрифтКорана {
  return useSyncExternalStore(подписаться, выборШрифтаКорана, выборШрифтаКорана);
}
