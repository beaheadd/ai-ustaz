/**
 * Перевод смыслов и тафсир — загрузка в приложении: индекс издания и суры по одной, лениво (только когда экран попросил),
 * тем же загрузчиком, что текст Корана (quran/data.ts: sha256, проверка формы, кэш; неудачи не кэшируются).
 * Чистая часть и формат — quran/translation.ts; данные — tools/quran_trans/build_translations.py.
 *
 * Контракт:
 *   useИзданиеЯзыка(вид) → запись издания для языка интерфейса (или запаса тафсира) | null — без сети;
 *   useИндексПеревода(запись | null), useСураПеревода(запись | null, сура | null) → СостояниеКорана<…> & { повторить };
 *   загрузитьСуруПеревода(запись, сура); докачатьСмыслСуры(язык, сура) — кнопки «Скачать суру»: перевод и тафсир суры
 *     на языке интерфейса (запрос идёт через service worker — файл с хэшем в имени остаётся в кэше без сети; тафсир в
 *     кэш попадает только так — его группа сама не докачивается, объём большой).
 * Владелец 28.11.2026: «Нам нужно теперь добавить перевод каждого аята!».
 */
import { useMemo } from 'react';
import { useПеревод } from '../i18n';
import { загрузитьФайл, изКэша, useЗагрузка, type Результат } from './data';
import { МАНИФЕСТ_ПЕРЕВОДОВ } from './transManifest.generated';
import {
  изданиеДляЯзыка,
  проверитьИндексПеревода,
  проверитьСуруПеревода,
  type ВидСлоя,
  type ЗаписьИздания,
  type ИндексПеревода,
  type СураПеревода,
} from './translation';

export type { АятПеревода, ВидСлоя, ИндексПеревода, СураПеревода } from './translation';
export type ИзданиеЯзыка = ЗаписьИздания & { язык: string; свой: boolean };

export function изданиеЯзыка(вид: ВидСлоя, язык: string): ИзданиеЯзыка | null {
  return изданиеДляЯзыка(МАНИФЕСТ_ПЕРЕВОДОВ, вид, язык);
}

export function useИзданиеЯзыка(вид: ВидСлоя): ИзданиеЯзыка | null {
  const { язык } = useПеревод();
  return useMemo(() => изданиеЯзыка(вид, язык), [вид, язык]);
}

export function загрузитьИндексПеревода(з: ЗаписьИздания): Promise<Результат<ИндексПеревода>> {
  return загрузитьФайл('перевод-' + з.ключ, з.индекс, з.sha256Индекса, (с) => проверитьИндексПеревода(с, з));
}

export async function загрузитьСуруПеревода(з: ЗаписьИздания, сура: number): Promise<Результат<СураПеревода>> {
  const и = await загрузитьИндексПеревода(з);
  if (!и.ок) return и;
  const запись = и.данные.суры[сура - 1];
  if (!запись) return { ок: false, причина: 'нет-файла' };
  return загрузитьФайл(`перевод-${з.ключ}-${сура}`, запись.файл, запись.sha256, (с) => проверитьСуруПеревода(с, и.данные, сура));
}

export function useИндексПеревода(з: ЗаписьИздания | null) {
  const ключ = з ? 'перевод-' + з.ключ : null;
  return useЗагрузка(ключ, ключ ? изКэша<ИндексПеревода>(ключ) : null, () => (з ? загрузитьИндексПеревода(з) : Promise.resolve({ ок: false, причина: 'нет-файла' } as const)));
}

export function useСураПеревода(з: ЗаписьИздания | null, сура: number | null) {
  const ключ = з && сура ? `перевод-${з.ключ}-${сура}` : null;
  return useЗагрузка(ключ, ключ ? изКэша<СураПеревода>(ключ) : null, () =>
    з && сура ? загрузитьСуруПеревода(з, сура) : Promise.resolve({ ок: false, причина: 'нет-файла' } as const),
  );
}

export function докачатьСмыслСуры(язык: string, сура: number): void {
  for (const вид of ['перевод', 'тафсир'] as const) {
    const з = изданиеЯзыка(вид, язык);
    if (з) void загрузитьСуруПеревода(з, сура);
  }
}
