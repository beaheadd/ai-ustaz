const ВЕРНЫЕ = new Set<string>(КОДЫ_ТАДЖВИДА);
const ФОРМАТ = /^(?:\d+[A-Z][1-9a-z])*$/;
const ЗНАК = /\p{Mn}/u;

/** Разметка аята из файла tajweed/NNN → отрезки [с, по, код] (индексы UTF-16 в строке аята). null — неверный формат. */
export function разобратьРазметку(строка: unknown): Отрезок[] | null {
  if (typeof строка !== 'string' || !ФОРМАТ.test(строка)) return null;
  const р: Отрезок[] = [];
  let конец = 0;
  for (const м of строка.matchAll(/(\d+)([A-Z])([1-9a-z])/g)) {
    const код = м[2].toLowerCase();
    if (!ВЕРНЫЕ.has(код)) return null;
    const с = конец + Number(м[1]);
    конец = с + parseInt(м[3], 36);
    р.push([с, конец, код as КодТаджвида]);
  }
  return р;
}

/** Отрезки годятся к этому тексту: по порядку, внутри, без пробелов, не режут букву и её знаки. */
export function отрезкиВерны(текст: string, отрезки: readonly Отрезок[]): boolean {
  let конец = 0;
  for (const [с, по] of отрезки) {
    if (с < конец || по <= с || по > текст.length) return false;
    if (текст.slice(с, по).includes(' ') || ЗНАК.test(текст[с]) || (по < текст.length && ЗНАК.test(текст[по]))) return false;
    конец = по;
  }
  return true;
}

/** Куски строки [с, по) по отрезкам: склейка === текст.slice(с, по). Отрезок, задевающий границу, обрезается по ней. */
export function кускиТекста(текст: string, отрезки: readonly Отрезок[], с = 0, по = текст.length): Кусок[] {
  const р: Кусок[] = [];
  let поз = с;
  for (const [а, б, код] of отрезки) {
    if (б <= поз || а >= по) continue;
    const н = Math.max(а, поз);
    const к = Math.min(б, по);
    if (н > поз) р.push({ текст: текст.slice(поз, н), код: null });
    р.push({ текст: текст.slice(н, к), код });
    поз = к;
  }
  if (поз < по) р.push({ текст: текст.slice(поз, по), код: null });
  return р;
}
