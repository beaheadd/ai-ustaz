/**
 * Страницы мусхафа и проверка файлов видов чтения — чистая часть (без импортов: проверяется в node, scripts/test-quran.mjs).
 *
 * Данные: app/public/quran/tajweed/index.<хэш>.json и NNN.<хэш>.json (tools/quran/build_tajweed.py). Страницы, джузы и
 * четверти хизба — Tanzil Quran Metadata 1.0 (CC BY 3.0): только номера «сура:аят» начала; 604 страницы мединского
 * мусхафа. Переносов строк мусхафа в данных нет — строки на экране переносятся по ширине (честно: docs/дизайн/05).
 * Разметка таджвида привязана к тексту: sha256Текста = sha256 файла суры в индексе Корана, длины аятов = длинам строк.
 * Не совпало — цвета не показываем (текст — показываем: он сверен своей цепочкой sha256, src/quran/loader.ts).
 *
 * Контракт:
 *   проверитьИндексМусхафа(сырые, манифест) → ИндексМусхафа | null
 *   проверитьРазметкуСуры(сырые, запись) → РазметкаСуры | null   (запись — из ИндексМусхафа.суры)
 *   страницаАята(страницы, сура, аят) → 1…604;  куски страницы: участкиСтраницы(страницы, номер, аятов(сура)) →
 *     [{ сура, с, по }] — аяты страницы по сурам (с, по включительно);
 *   джузСтраницы(и, номер) → 1…30;  хизбСтраницы(и, номер) → { хизб 1…60, четверть 1…4 } — по первому аяту страницы.
 * Решение владельца 20.11.2026: виды чтения Корана («как на реальной странице»).
 */

export type МанифестТаджвида = { readonly формат: number; readonly индекс: string; readonly sha256Индекса: string; readonly коды: string; readonly страниц: number };
export type НачалоАята = readonly [number, number];
export type ЗаписьРазметки = { сура: number; файл: string; sha256: string; sha256Текста: string };
export type ИндексМусхафа = {
  страницы: НачалоАята[];
  джузы: НачалоАята[];
  четверти: НачалоАята[];
  суры: ЗаписьРазметки[];
  атрибуция: string;
};
export type РазметкаСуры = { сура: number; sha256Текста: string; длины: number[]; аяты: string[]; бисмилла: string | null; длинаБисмиллы: number | null };
export type Участок = { сура: number; с: number; по: number };

const ФАЙЛ = /^quran\/tajweed\/(\d{3})\.([0-9a-f]{20})\.json$/;
const SHA = /^[0-9a-f]{64}$/;

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}

function пары(з: unknown, сколько: number): НачалоАята[] | null {
  if (!Array.isArray(з) || з.length !== сколько) return null;
  const р: НачалоАята[] = [];
  for (const п of з) {
    if (!Array.isArray(п) || п.length !== 2 || !Number.isInteger(п[0]) || !Number.isInteger(п[1]) || п[0] < 1 || п[0] > 114 || п[1] < 1) return null;
    const пред = р[р.length - 1];
    if (пред && (п[0] < пред[0] || (п[0] === пред[0] && п[1] <= пред[1]))) return null;
    р.push([п[0], п[1]]);
  }
  return р;
}

export function проверитьИндексМусхафа(сырые: unknown, м: МанифестТаджвида): ИндексМусхафа | null {
  const и = объект(сырые);
  if (!и || и.формат !== м.формат || и.коды !== м.коды) return null;
  const страницы = пары(и.страницы, м.страниц);
  const джузы = пары(и.джузы, 30);
  const четверти = пары(и.четверти, 240);
  if (!страницы || !джузы || !четверти || страницы[0][0] !== 1 || страницы[0][1] !== 1) return null;
  if (!Array.isArray(и.суры) || и.суры.length !== 114) return null;
  const суры: ЗаписьРазметки[] = [];
  for (let i = 0; i < 114; i++) {
    const з = объект(и.суры[i]);
    const ф = з && typeof з.файл === 'string' ? ФАЙЛ.exec(з.файл) : null;
    if (!з || з.сура !== i + 1 || !ф || Number(ф[1]) !== i + 1 || typeof з.sha256 !== 'string' || !SHA.test(з.sha256) || ф[2] !== з.sha256.slice(0, 20)) return null;
    if (typeof з.sha256Текста !== 'string' || !SHA.test(з.sha256Текста)) return null;
    суры.push({ сура: i + 1, файл: з.файл as string, sha256: з.sha256, sha256Текста: з.sha256Текста });
  }
  const мета = объект(и.метаданные);
  return { страницы, джузы, четверти, суры, атрибуция: typeof мета?.атрибуция === 'string' ? мета.атрибуция : 'Tanzil Quran Metadata' };
}

export function проверитьРазметкуСуры(сырые: unknown, запись: ЗаписьРазметки): РазметкаСуры | null {
  const д = объект(сырые);
  if (!д || д.сура !== запись.сура || д.sha256Текста !== запись.sha256Текста) return null;
  if (!Array.isArray(д.длины) || !Array.isArray(д.аяты) || д.длины.length !== д.аяты.length) return null;
  if (!д.длины.every((н) => Number.isInteger(н) && н > 0) || !д.аяты.every((с) => typeof с === 'string')) return null;
  const бисмилла = typeof д.бисмилла === 'string' ? д.бисмилла : null;
  return {
    сура: запись.сура,
    sha256Текста: запись.sha256Текста,
    длины: д.длины as number[],
    аяты: д.аяты as string[],
    бисмилла,
    длинаБисмиллы: бисмилла !== null && typeof д.длиныБисмиллы === 'number' ? д.длиныБисмиллы : null,
  };
}

function раньше(а: НачалоАята, сура: number, аят: number): boolean {
  return а[0] < сура || (а[0] === сура && а[1] <= аят);
}

/** Номер (с 1) последнего начала, которое не позже сура:аят. */
function поиск(начала: readonly НачалоАята[], сура: number, аят: number): number {
  let л = 0;
  let п = начала.length - 1;
  while (л < п) {
    const с = (л + п + 1) >> 1;
    if (раньше(начала[с], сура, аят)) л = с;
    else п = с - 1;
  }
  return л + 1;
}

export function страницаАята(страницы: readonly НачалоАята[], сура: number, аят: number): number {
  return поиск(страницы, сура, аят);
}

/** Аяты страницы по сурам. аятов(сура) — число аятов суры (из индекса Корана). */
export function участкиСтраницы(страницы: readonly НачалоАята[], номер: number, аятов: (сура: number) => number): Участок[] {
  const начало = страницы[номер - 1];
  if (!начало) return [];
  const след = страницы[номер] ?? ([115, 1] as const);
  const р: Участок[] = [];
  for (let с = начало[0]; с <= Math.min(114, след[0]); с++) {
    const от = с === начало[0] ? начало[1] : 1;
    const до = с === след[0] ? след[1] - 1 : аятов(с);
    if (до >= от) р.push({ сура: с, с: от, по: до });
  }
  return р;
}

export function джузСтраницы(и: Pick<ИндексМусхафа, 'страницы' | 'джузы'>, номер: number): number {
  const н = и.страницы[номер - 1];
  return н ? поиск(и.джузы, н[0], н[1]) : 1;
}

export function хизбСтраницы(и: Pick<ИндексМусхафа, 'страницы' | 'четверти'>, номер: number): { хизб: number; четверть: number } {
  const н = и.страницы[номер - 1];
  const ч = н ? поиск(и.четверти, н[0], н[1]) : 1;
  return { хизб: Math.ceil(ч / 4), четверть: ((ч - 1) % 4) + 1 };
}
