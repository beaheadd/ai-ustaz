/**
 * Разбор текста аята копии Tanzil ДЛЯ ПОКАЗА (со знаками остановки, саджды и руб‘ аль-хизба) на слова и знаки.
 * Только чтение строки: текст не меняется, не нормализуется и не собирается заново (правило 1 CLAUDE.md) —
 * токены — это куски исходной строки по пробелам, токены.map(т => т.текст).join(' ') === текст.
 *
 * В копии для показа знаки остановки, ۞ и ۩ стоят ОТДЕЛЬНЫМИ токенами между словами (проверено на всех 6236 аятах:
 * ۞ — только в начале аята (199), ۩ — только в конце (15), ۜ (сакта) — 5 раз токеном и 2 раза внутри слова).
 * Слова (без знаков-токенов) совпадают по числу и порядку со словами фонетической копии quran-transcript —
 * поэтому номерСлова здесь = номер uthmani-слова речевого сервиса (с 1). Внимание: поле word_from сервиса сейчас —
 * imlaey-слова с 0 (docs/дизайн/05-коран-чтение-и-плеер.md, «Контракт», «Проверка»).
 *
 * Контракт (без импортов: проверяется в node, scripts/test-quran.mjs):
 *   ЗНАКИ: Record<символ, ВидЗнака>; разборАята(текст) → Токен[]; словаАята(текст) → string[] (только слова);
 *   числоСлов(текст); остановкиАята(текст) → { послеСлова, знак, токен }[] — места, где МОЖНО остановиться
 *   (ОСТАНОВКИ_ДЛЯ_ЧАСТЕЙ); частиПоОстановкам(текст) → ЧастьАята[] — куски между этими местами
 *   (словоС с 1, слов, токенС/токенПо — индексы токенов для подсветки в целом аяте, знак в конце части).
 * Какие знаки делят аят на части для записи — ЧЕРНОВИК политики (утверждает устаз): ۘ (лязим), ۗ (кыля), ۖ (сыля),
 *   ۚ (джаиз). Не делим: ۙ (ля — не останавливаться), ۛ (муанака — останавливаются на одном из пары), ۜ (сакта —
 *   пауза без вдоха), ۞ и ۩ (не знаки остановки).
 * Решение владельца 19.11.2026: «заходишь и читаешь любой аят, и записываешь голос и проверяешь».
 */

export type ВидЗнака = 'лязим' | 'кыля' | 'сыля' | 'джаиз' | 'муанака' | 'ля' | 'сакта' | 'хизб' | 'саджда';

/** Знаки-токены копии для показа (Unicode → вид). */
export const ЗНАКИ: Readonly<Record<string, ВидЗнака>> = {
  'ۘ': 'лязим', // ۘ  малый мим — остановка обязательна
  'ۗ': 'кыля', // ۗ  «قلى» — остановка лучше
  'ۖ': 'сыля', // ۖ  «صلى» — лучше продолжить, остановиться можно
  'ۚ': 'джаиз', // ۚ  малый джим — можно и так, и так
  'ۛ': 'муанака', // ۛ  три точки — остановиться на одном из пары
  'ۙ': 'ля', // ۙ  «لا» — не останавливаться
  'ۜ': 'сакта', // ۜ  малый син — краткая пауза без вдоха
  '۞': 'хизб', // ۞  начало руб‘ аль-хизба
  '۩': 'саджда', // ۩  место земного поклона
};

/** Где аят можно разделить на части для записи (черновик политики, утверждает устаз). */
export const ОСТАНОВКИ_ДЛЯ_ЧАСТЕЙ: ReadonlySet<ВидЗнака> = new Set<ВидЗнака>(['лязим', 'кыля', 'сыля', 'джаиз']);

export type Токен =
  | { вид: 'слово'; текст: string; номерСлова: number }
  | { вид: 'знак'; текст: string; знак: ВидЗнака; /** номер слова перед знаком; 0 — знак в начале аята (۞) */ послеСлова: number };

export type ЧастьАята = {
  номер: number; // с 1
  словоС: number; // первое слово части, с 1 (uthmani-слова)
  слов: number;
  токенС: number; // индексы токенов разборАята (включительно) — для подсветки части в целом аяте
  токенПо: number;
  знакВКонце: ВидЗнака | null; // знак остановки после части (null — конец аята)
};

export function разборАята(текст: string): Токен[] {
  const токены: Токен[] = [];
  let слово = 0;
  for (const кусок of текст.split(' ')) {
    const знак = кусок.length === 1 ? ЗНАКИ[кусок] : undefined;
    if (знак) токены.push({ вид: 'знак', текст: кусок, знак, послеСлова: слово });
    else токены.push({ вид: 'слово', текст: кусок, номерСлова: ++слово });
  }
  return токены;
}

export function словаАята(текст: string): string[] {
  return разборАята(текст).flatMap((т) => (т.вид === 'слово' ? [т.текст] : []));
}

export function числоСлов(текст: string): number {
  return словаАята(текст).length;
}

export function остановкиАята(текст: string): { послеСлова: number; знак: ВидЗнака; токен: number }[] {
  const токены = разборАята(текст);
  const всего = токены.reduce((н, т) => (т.вид === 'слово' ? н + 1 : н), 0);
  return токены.flatMap((т, i) =>
    т.вид === 'знак' && ОСТАНОВКИ_ДЛЯ_ЧАСТЕЙ.has(т.знак) && т.послеСлова > 0 && т.послеСлова < всего
      ? [{ послеСлова: т.послеСлова, знак: т.знак, токен: i }]
      : [],
  );
}

/** Части аята между разрешёнными остановками. Аят без таких знаков — одна часть. */
export function частиПоОстановкам(текст: string): ЧастьАята[] {
  const токены = разборАята(текст);
  const всего = токены.reduce((н, т) => (т.вид === 'слово' ? н + 1 : н), 0);
  const части: ЧастьАята[] = [];
  let начало = 1;
  let токенС = 0;
  for (const о of остановкиАята(текст)) {
    if (о.послеСлова < начало) continue; // два знака подряд — пустой части нет
    части.push({ номер: части.length + 1, словоС: начало, слов: о.послеСлова - начало + 1, токенС, токенПо: о.токен, знакВКонце: о.знак });
    начало = о.послеСлова + 1;
    токенС = о.токен + 1;
  }
  if (всего >= начало) {
    части.push({ номер: части.length + 1, словоС: начало, слов: всего - начало + 1, токенС, токенПо: токены.length - 1, знакВКонце: null });
  }
  return части;
}
