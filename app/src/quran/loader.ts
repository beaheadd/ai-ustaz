/**
 * Загрузчик полного Корана для показа — чистая часть (без импортов: проверяется в node, scripts/test-quran.mjs).
 * Сеть, sha256 и адрес сборки подставляет src/quran/data.ts; экраны берут всё оттуда.
 *
 * Данные: статические файлы сборки (app/public/quran → dist/quran, собирает tools/quran/build_quran.py из
 * content/quran/quran-uthmani-marks.xml — Tanzil Uthmani v1.1, копия ДЛЯ ПОКАЗА со знаками остановки, саджды и
 * руб‘ аль-хизба). Цепочка доверия: манифест в бандле (имя и sha256 индекса) → индекс (имя файла и sha256 каждой
 * суры) → файл суры. Что не прошло сверку — НЕ показывается (правило 1 CLAUDE.md). Текст не меняется.
 *
 * Контракт:
 *   создатьЗагрузчик({ база, манифест, получить, sha256 }) → {
 *     загрузитьИндексСур(): Promise<Результат<ИндексСур>>;
 *     загрузитьСуру(н): Promise<Результат<СураКорана>>;        н — 1…114; индекс грузится сам (кэш общий)
 *     сураИзКэша(н): СураКорана | null;  индексИзКэша(): ИндексСур | null   — без ожидания (уже загруженное)
 *     адрес(файл): string                                       — база + '/' + 'quran/…json'
 *     загрузитьФайл(ключ, путь, sha256, проверка), изКэша(ключ) — то же для файлов видов чтения (20.11.2026)
 *   }
 *   Результат<Т> = { ок: true; данные: Т } | { ок: false; причина: ПричинаОтказа }. Промисы не отклоняются.
 *   ПричинаОтказа: 'нет-связи' (fetch не дошёл, таймаут) | 'сбой-сервера' (5xx, 408, 429) — показывать «Нет связи»
 *     и «Повторить»; 'нет-файла' (404 и прочие 4xx; ответ text/html вместо JSON — старая вкладка после выпуска) —
 *     «Файл не найден. Обновите страницу»; 'не-прошло-сверку' (sha256, номер суры, число и номера аятов,
 *     источник) — «Текст не прошёл сверку — не показываем». нетСвязи(причина) — для экрана.
 *   Неудачи не кэшируются: повторный вызов (кнопка «Повторить») снова идёт в сеть, без перезагрузки страницы.
 *   проверитьИндекс(сырые, манифест), проверитьСуру(сырые, запись, манифест) — чистые проверки формы.
 * Решение владельца 19.11.2026: «Коран полностью, все аяты…» (полный Коран, плеер, запись).
 */

export type МанифестКорана = {
  readonly формат: number;
  readonly индекс: string;
  readonly sha256Индекса: string;
  readonly сур: number;
  readonly аятов: number;
  readonly источник: string;
  readonly файлИсточника: string;
  readonly sha256Источника: string;
};

/** Транслитерация арабского имени суры (не перевод смыслов); черновик. kk пока null — показывать номер и арабское имя. */
/** Транслитерация названия суры (черновик). uz в индексе пока нет — null: подпись номером «2-sura». */
export type Транслит = { ru: string | null; kk: string | null; uz: string | null };

export type ЗаписьСуры = {
  сура: number;
  /** Арабское имя суры дословно из XML Tanzil (атрибут name). */
  имя: string;
  аятов: number;
  /** Путь относительно baseUrl сборки: 'quran/002.<хэш>.json'. */
  файл: string;
  sha256: string;
  транслит: Транслит;
  /** Другие написания только для поиска (латиница, привычные имена: «Ясин», «Табарак»); на экран не выводятся. */
  синонимы: readonly string[];
};

export type ИндексСур = {
  источник: string;
  файлИсточника: string;
  sha256Источника: string;
  сур: number;
  аятов: number;
  статусТранслита: string;
  суры: ЗаписьСуры[];
  /** Блок копирайта Tanzil дословно (условие Tanzil — в каждом производном файле). */
  копирайт: string;
};

export type АятКорана = { сура: number; аят: number; текст: string };

export type СураКорана = {
  сура: number;
  имя: string;
  аятов: number;
  /** Бисмилла перед первым аятом (атрибут XML) — у всех сур, кроме 1 (там она — аят 1:1) и 9: там null. */
  бисмилла: string | null;
  аяты: АятКорана[];
  источник: string;
  файлИсточника: string;
  sha256Источника: string;
  копирайт: string;
};

export type ПричинаОтказа = 'нет-связи' | 'сбой-сервера' | 'нет-файла' | 'не-прошло-сверку';
export type Результат<Т> = { ок: true; данные: Т } | { ок: false; причина: ПричинаОтказа };

/** Ответ получателя: подмножество Response (fetch) — подменяется в тестах. */
export type ОтветФайла = { ok: boolean; status: number; text(): Promise<string>; /** Content-Type, если известен. */ тип?: string | null };

export type НастройкиЗагрузчика = {
  /** Префикс адреса сборки без «/» в конце: '/aiustaz' (experiments.baseUrl). */
  база: string;
  манифест: МанифестКорана;
  /** Запрос файла; отклонение промиса = нет связи. */
  получить: (адрес: string) => Promise<ОтветФайла>;
  /** sha256 строки в UTF-8, hex в нижнем регистре. */
  sha256: (строка: string) => string;
};

export const ИСТОЧНИК_КОРАНА = 'tanzil-uthmani-1.1';
export const КОПИЯ_ДЛЯ_ПОКАЗА = 'показ';
const ФАЙЛ = /^quran\/(index|\d{3})\.([0-9a-f]{20})\.json$/;
const SHA = /^[0-9a-f]{64}$/;
const БЕЗ_БИСМИЛЛЫ = new Set([1, 9]);

export function нетСвязи(причина: ПричинаОтказа): boolean {
  return причина === 'нет-связи' || причина === 'сбой-сервера';
}

function объект(з: unknown): Record<string, unknown> | null {
  return з && typeof з === 'object' && !Array.isArray(з) ? (з as Record<string, unknown>) : null;
}
function целое(з: unknown, мин: number, макс: number): з is number {
  return typeof з === 'number' && Number.isInteger(з) && з >= мин && з <= макс;
}
function строка(з: unknown): з is string {
  return typeof з === 'string' && з.length > 0;
}
function строкаИлиNull(з: unknown): з is string | null {
  return з === null || строка(з);
}

/** Индекс сур: форма, 114 записей 1…114, сумма аятов, имя файла = номер суры и начало sha256. null — не прошёл. */
export function проверитьИндекс(сырые: unknown, м: МанифестКорана): ИндексСур | null {
  const и = объект(сырые);
  if (!и || и.формат !== м.формат || и.источник !== м.источник || и.копия !== КОПИЯ_ДЛЯ_ПОКАЗА) return null;
  if (и.sha256Источника !== м.sha256Источника || и.файлИсточника !== м.файлИсточника) return null;
  if (и.сур !== м.сур || и.аятов !== м.аятов || !Array.isArray(и.суры) || и.суры.length !== м.сур) return null;
  if (!строка(и.копирайт)) return null;
  const суры: ЗаписьСуры[] = [];
  let аятов = 0;
  for (let i = 0; i < и.суры.length; i++) {
    const з = объект(и.суры[i]);
    if (!з || з.сура !== i + 1 || !строка(з.имя) || !целое(з.аятов, 1, 286)) return null;
    if (!строка(з.файл) || !строка(з.sha256) || !SHA.test(з.sha256)) return null;
    const ф = ФАЙЛ.exec(з.файл);
    if (!ф || Number(ф[1]) !== i + 1 || ф[2] !== з.sha256.slice(0, 20)) return null;
    const т = объект(з.транслит);
    if (!т || !строкаИлиNull(т.ru) || !строкаИлиNull(т.kk)) return null;
    const син = з.синонимы === undefined ? [] : з.синонимы;
    if (!Array.isArray(син) || !син.every(строка)) return null;
    аятов += з.аятов;
    суры.push({ сура: i + 1, имя: з.имя, аятов: з.аятов, файл: з.файл, sha256: з.sha256, транслит: { ru: т.ru, kk: т.kk, uz: строка(т.uz) ? т.uz : null }, синонимы: син });
  }
  if (аятов !== м.аятов) return null;
  return {
    источник: м.источник,
    файлИсточника: м.файлИсточника,
    sha256Источника: м.sha256Источника,
    сур: м.сур,
    аятов: м.аятов,
    статусТранслита: строка(и.статусТранслита) ? и.статусТранслита : 'черновик',
    суры,
    копирайт: и.копирайт,
  };
}

/** Сура: номер, имя и число аятов = индексу, аяты 1…n подряд, бисмилла по правилу, источник = манифесту. */
export function проверитьСуру(сырые: unknown, запись: ЗаписьСуры, м: МанифестКорана): СураКорана | null {
  const с = объект(сырые);
  if (!с || с.формат !== м.формат || с.источник !== м.источник || с.копия !== КОПИЯ_ДЛЯ_ПОКАЗА) return null;
  if (с.sha256Источника !== м.sha256Источника || с.файлИсточника !== м.файлИсточника) return null;
  if (с.сура !== запись.сура || с.имя !== запись.имя || с.аятов !== запись.аятов) return null;
  if (!Array.isArray(с.аяты) || с.аяты.length !== запись.аятов || !строка(с.копирайт)) return null;
  const бисмилла = с.бисмилла;
  if (БЕЗ_БИСМИЛЛЫ.has(запись.сура) ? бисмилла !== null : !строка(бисмилла)) return null;
  const аяты: АятКорана[] = [];
  for (let i = 0; i < с.аяты.length; i++) {
    const а = объект(с.аяты[i]);
    if (!а || а.аят !== i + 1 || !строка(а.текст) || а.текст.includes('\n')) return null;
    аяты.push({ сура: запись.сура, аят: i + 1, текст: а.текст });
  }
  return {
    сура: запись.сура,
    имя: запись.имя,
    аятов: запись.аятов,
    бисмилла: бисмилла as string | null,
    аяты,
    источник: м.источник,
    файлИсточника: м.файлИсточника,
    sha256Источника: м.sha256Источника,
    копирайт: с.копирайт,
  };
}

function причинаПоСтатусу(статус: number): ПричинаОтказа {
  return статус >= 500 || статус === 408 || статус === 429 || статус === 0 ? 'сбой-сервера' : 'нет-файла';
}

export function создатьЗагрузчик(н: НастройкиЗагрузчика) {
  const база = н.база.replace(/\/+$/, '');
  const адрес = (файл: string) => база + '/' + файл;
  const ждут = new Map<string, Promise<Результат<unknown>>>();
  const готово = new Map<string, unknown>();

  /** Файл с проверкой sha256 текста и формы; удачное — в кэш навсегда (имена с хэшем неизменны), неудачное — нет. */
  function файл<Т>(ключ: string, путь: string, sha: string, проверка: (сырые: unknown) => Т | null): Promise<Результат<Т>> {
    const есть = ждут.get(ключ) as Promise<Результат<Т>> | undefined;
    if (есть) return есть;
    const обещание = (async (): Promise<Результат<Т>> => {
      let ответ: ОтветФайла;
      try {
        ответ = await н.получить(адрес(путь));
      } catch {
        return { ок: false, причина: 'нет-связи' };
      }
      if (!ответ.ok) return { ок: false, причина: причинаПоСтатусу(ответ.status) };
      // Сервер отдал страницу вместо файла (nginx batr.kz: try_files … index.html с кодом 200 для пропавшего
      // файла старой сборки) — это «файла нет», а не «текст не прошёл сверку» (ревью 19.11.2026).
      if (typeof ответ.тип === 'string' && /^\s*text\/html/i.test(ответ.тип)) return { ок: false, причина: 'нет-файла' };
      let текст: string;
      try {
        текст = await ответ.text();
      } catch {
        return { ок: false, причина: 'нет-связи' };
      }
      if (н.sha256(текст) !== sha) return { ок: false, причина: 'не-прошло-сверку' };
      let данные: Т | null = null;
      try {
        данные = проверка(JSON.parse(текст));
      } catch {
        данные = null;
      }
      return данные ? { ок: true, данные } : { ок: false, причина: 'не-прошло-сверку' };
    })().then((р) => {
      if (р.ок) готово.set(ключ, р.данные);
      else ждут.delete(ключ);
      return р;
    });
    ждут.set(ключ, обещание as Promise<Результат<unknown>>);
    return обещание;
  }

  function загрузитьИндексСур(): Promise<Результат<ИндексСур>> {
    return файл('индекс', н.манифест.индекс, н.манифест.sha256Индекса, (с) => проверитьИндекс(с, н.манифест));
  }

  async function загрузитьСуру(номер: number): Promise<Результат<СураКорана>> {
    if (!целое(номер, 1, н.манифест.сур)) return { ок: false, причина: 'нет-файла' };
    const индекс = await загрузитьИндексСур();
    if (!индекс.ок) return индекс;
    const запись = индекс.данные.суры[номер - 1];
    return файл('сура-' + номер, запись.файл, запись.sha256, (с) => проверитьСуру(с, запись, н.манифест));
  }

  return {
    загрузитьИндексСур,
    загрузитьСуру,
    сураИзКэша: (номер: number) => (готово.get('сура-' + номер) as СураКорана | undefined) ?? null,
    индексИзКэша: () => (готово.get('индекс') as ИндексСур | undefined) ?? null,
    адрес,
    /** Любой статический файл с той же проверкой (sha256 + форма) и кэшем — виды чтения (quran/mushafData.ts). */
    загрузитьФайл: файл,
    изКэша: <Т>(ключ: string) => (готово.get(ключ) as Т | undefined) ?? null,
  };
}

export type ЗагрузчикКорана = ReturnType<typeof создатьЗагрузчик>;
