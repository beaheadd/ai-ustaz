/**
 * Вид чтения Корана — выбор человека, только на устройстве (как размер арабского, quran/fontSize.ts).
 *
 * Владелец 20.11.2026: «Коран нужно нам сделать разные дизайны … варианты, чтобы человек выбрал … 3–4 варианта».
 * Решение владельца 28.11.2026 (дизайн A + B/C): вид, тема страницы и цвета таджвида — три независимых выбора.
 *   вид (в режиме «Аят за аятом»):
 *     'обычный' — аяты строками, номер — кружком отдельно, перевод под аятом;
 *     'мусхаф'  — сплошной текст «как в мусхафе»: картуш, бисмилла, ۝ с номером, цвета таджвида.
 *   тема страницы: 'авто' (по умолчанию: светлая тема телефона/приложения — «День», тёмная — «Ночь»; аудит P0-1: в
 *     тёмной теме мусхаф сам становится ночным) | 'день' | 'сепия' | 'ночь' | 'безСинего' (янтарь перед сном, из B).
 *   таджвид: 'традиционные' (по умолчанию) | 'различимые' | 'безЦвета' — цвета показываются в мусхафе и «Страницами».
 * Режим (владелец 27.11.2026: «переключение как книга, страницы листать, как в Коране»):
 *   'аяты'    — аят за аятом сплошной прокруткой (по умолчанию; владелец 21.11.2026 — без разбивки на страницы);
 *   'страницы' — страница мединского мусхафа целиком, листание как в книге (screens/quran/MushafPages.tsx).
 *
 * Контракт:
 *   ВИДЫ_ЧТЕНИЯ, ТЕМЫ_ЧТЕНИЯ, РЕЖИМЫ_ЧТЕНИЯ (и РЕЖИМЫ_ТАДЖВИДА из tajweed.ts);
 *   useВидЧтения() → { вид, тема, таджвид, режим }; установитьВидЧтения(вид); установитьТемуЧтения(тема);
 *   установитьТаджвид(режим); установитьРежимЧтения(режим); темаСтраницы(тема, тёмнаяТемаПриложения) → ТемаСтраницы;
 *   видЧтенияИз(сырые) — разбор хранимого (для теста в node). Версия 1 (до 28.11.2026: вид обычный | мусхаф | таджвид |
 *   ночной, ночьЦвета) переводится без потерь: таджвид → мусхаф + «Традиционные», ночной → мусхаф + «Ночь» (+ цвета по
 *   ночьЦвета), обычный и мусхаф → «Без цвета» (что человек видел, то и видит).
 *   Хранение: localStorage «aiustaz:quran-view.v1» = { версия: 2, вид, тема, таджвид, режим } (в try/catch: приватный
 *   режим — выбор живёт до перезагрузки). Нативно — пока в памяти.
 * Без импортов кода, кроме React и типов.
 */
import { useSyncExternalStore } from 'react';
import type { РежимТаджвида, ТемаСтраницы } from './tajweed';

export const ВИДЫ_ЧТЕНИЯ = ['обычный', 'мусхаф'] as const;
export type ВидЧтения = (typeof ВИДЫ_ЧТЕНИЯ)[number];
export const ТЕМЫ_ЧТЕНИЯ = ['авто', 'день', 'сепия', 'ночь', 'безСинего'] as const;
export type ТемаЧтения = (typeof ТЕМЫ_ЧТЕНИЯ)[number];
const ТАДЖВИД: readonly РежимТаджвида[] = ['традиционные', 'различимые', 'безЦвета'];
export const РЕЖИМЫ_ЧТЕНИЯ = ['аяты', 'страницы'] as const;
export type РежимЧтения = (typeof РЕЖИМЫ_ЧТЕНИЯ)[number];
export type ВыборВида = { readonly вид: ВидЧтения; readonly тема: ТемаЧтения; readonly таджвид: РежимТаджвида; readonly режим: РежимЧтения };

const КЛЮЧ = 'aiustaz:quran-view.v1';
const ПО_УМОЛЧАНИЮ: ВыборВида = { вид: 'обычный', тема: 'авто', таджвид: 'традиционные', режим: 'аяты' };

/** Тема страницы для показа: «авто» — по теме приложения (тёмная → «Ночь», светлая → «День»). */
export function темаСтраницы(тема: ТемаЧтения, тёмнаяТема: boolean): ТемаСтраницы {
  return тема === 'авто' ? (тёмнаяТема ? 'ночь' : 'день') : тема;
}

export function видЧтенияИз(сырые: unknown): ВыборВида {
  const д = сырые && typeof сырые === 'object' ? (сырые as { версия?: unknown; вид?: unknown; ночьЦвета?: unknown; режим?: unknown; тема?: unknown; таджвид?: unknown }) : null;
  if (!д) return ПО_УМОЛЧАНИЮ;
  const режим = РЕЖИМЫ_ЧТЕНИЯ.includes(д.режим as РежимЧтения) ? (д.режим as РежимЧтения) : 'аяты';
  if (д.версия === 2) {
    return {
      вид: ВИДЫ_ЧТЕНИЯ.includes(д.вид as ВидЧтения) ? (д.вид as ВидЧтения) : 'обычный',
      тема: ТЕМЫ_ЧТЕНИЯ.includes(д.тема as ТемаЧтения) ? (д.тема as ТемаЧтения) : 'авто',
      таджвид: ТАДЖВИД.includes(д.таджвид as РежимТаджвида) ? (д.таджвид as РежимТаджвида) : 'традиционные',
      режим,
    };
  }
  if (д.версия !== 1) return ПО_УМОЛЧАНИЮ;
  // Версия 1 (до 28.11.2026) — без потерь.
  switch (д.вид) {
    case 'таджвид':
      return { вид: 'мусхаф', тема: 'авто', таджвид: 'традиционные', режим };
    case 'ночной':
      return { вид: 'мусхаф', тема: 'ночь', таджвид: д.ночьЦвета === true ? 'традиционные' : 'безЦвета', режим };
    case 'мусхаф':
      return { вид: 'мусхаф', тема: 'авто', таджвид: 'безЦвета', режим };
    default:
      return { вид: 'обычный', тема: 'авто', таджвид: 'безЦвета', режим };
  }
}

let сейчас: ВыборВида | null = null;
const слушатели = new Set<() => void>();
// Аккаунт (владелец 28.11.2026): синхронизация записала данные другого устройства — перечитать.
// (событие окна, а не engine/storage: этот модуль без зависимостей импортируют тесты под node).
globalThis.addEventListener?.('aiustaz:внешнее', (е) => {
  if (!(е as CustomEvent<string[]>).detail?.includes('quran-view.v1')) return;
  сейчас = null;
  for (const ф of [...слушатели]) ф();
});

function текущий(): ВыборВида {
  if (сейчас === null) {
    try {
      const с = globalThis.localStorage?.getItem(КЛЮЧ);
      сейчас = с ? видЧтенияИз(JSON.parse(с)) : ПО_УМОЛЧАНИЮ;
    } catch {
      сейчас = ПО_УМОЛЧАНИЮ;
    }
  }
  return сейчас;
}

function сохранить(новый: ВыборВида): void {
  const с = текущий();
  if (с.вид === новый.вид && с.тема === новый.тема && с.таджвид === новый.таджвид && с.режим === новый.режим) return;
  сейчас = новый;
  try {
    globalThis.localStorage?.setItem(КЛЮЧ, JSON.stringify({ версия: 2, ...новый }));
  } catch {
    // приватный режим или переполнено — выбор живёт до перезагрузки
  }
  for (const ф of [...слушатели]) ф();
}

export function установитьВидЧтения(вид: ВидЧтения): void {
  сохранить({ ...текущий(), вид });
}

export function установитьТемуЧтения(тема: ТемаЧтения): void {
  сохранить({ ...текущий(), тема });
}

/** Цвета таджвида. В «Аят за аятом» цвета видны только в мусхафе — выбор цвета там сам включает вид «Мусхаф». */
export function установитьТаджвид(таджвид: РежимТаджвида): void {
  const с = текущий();
  сохранить({ ...с, таджвид, вид: таджвид !== 'безЦвета' && с.режим === 'аяты' ? 'мусхаф' : с.вид });
}

export function установитьРежимЧтения(режим: РежимЧтения): void {
  сохранить({ ...текущий(), режим });
}

function подписаться(ф: () => void): () => void {
  слушатели.add(ф);
  return () => {
    слушатели.delete(ф);
  };
}

export function useВидЧтения(): ВыборВида {
  return useSyncExternalStore(подписаться, текущий, текущий);
}
