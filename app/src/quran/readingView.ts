/**
 * Вид чтения Корана — выбор человека, только на устройстве (как размер арабского, quran/fontSize.ts).
 *
 * Владелец 20.11.2026: «Коран нужно нам сделать разные дизайны … варианты, чтобы человек выбрал … 3–4 варианта».
 *   'обычный' — как было: аяты на фоне приложения, номер — кружком отдельно;
 *   'мусхаф'  — страница мединского мусхафа (604 страницы): «бумага», рамка, сплошной текст, ۝ с номером;
 *   'таджвид' — та же страница с цветами правил таджвида (черновик — проверяет устаз);
 *   'ночной'  — тёмная страница, мягкий тёплый текст; цвета таджвида — переключателем (по умолчанию выкл.).
 *
 * Контракт:
 *   ВИДЫ_ЧТЕНИЯ; useВидЧтения() → { вид, ночьЦвета }; установитьВидЧтения(вид); установитьНочьЦвета(вкл);
 *   видЧтенияИз(сырые) — разбор хранимого (неверное — «обычный»; для теста в node).
 *   Хранение: localStorage «aiustaz:quran-view.v1» = { версия: 1, вид, ночьЦвета } (в try/catch: приватный режим —
 *   выбор живёт до перезагрузки). Нативно — пока в памяти.
 * Без импортов кода, кроме React.
 */
import { useSyncExternalStore } from 'react';

export const ВИДЫ_ЧТЕНИЯ = ['обычный', 'мусхаф', 'таджвид', 'ночной'] as const;
export type ВидЧтения = (typeof ВИДЫ_ЧТЕНИЯ)[number];
export type ВыборВида = { readonly вид: ВидЧтения; readonly ночьЦвета: boolean };

const КЛЮЧ = 'aiustaz:quran-view.v1';
const ПО_УМОЛЧАНИЮ: ВыборВида = { вид: 'обычный', ночьЦвета: false };

export function видЧтенияИз(сырые: unknown): ВыборВида {
  const д = сырые && typeof сырые === 'object' ? (сырые as { версия?: unknown; вид?: unknown; ночьЦвета?: unknown }) : null;
  if (!д || д.версия !== 1) return ПО_УМОЛЧАНИЮ;
  const вид = ВИДЫ_ЧТЕНИЯ.includes(д.вид as ВидЧтения) ? (д.вид as ВидЧтения) : 'обычный';
  return { вид, ночьЦвета: д.ночьЦвета === true };
}

let сейчас: ВыборВида | null = null;
const слушатели = new Set<() => void>();

function текущий(): ВыборВида {
  if (сейчас === null) {
    try {
      const с = globalThis.localStorage?.getItem(КЛЮЧ);
      сейчас = с ? видЧтенияИз(JSON.parse(с)) : ПО_УМОЛЧАНИЮ;
    } catch {
      сейчас = ПО_УМОЛЧАНИЮ;
    }
  }
  return сейчас;
}

function сохранить(новый: ВыборВида): void {
  const с = текущий();
  if (с.вид === новый.вид && с.ночьЦвета === новый.ночьЦвета) return;
  сейчас = новый;
  try {
    globalThis.localStorage?.setItem(КЛЮЧ, JSON.stringify({ версия: 1, ...новый }));
  } catch {
    // приватный режим или переполнено — выбор живёт до перезагрузки
  }
  for (const ф of [...слушатели]) ф();
}

export function установитьВидЧтения(вид: ВидЧтения): void {
  сохранить({ ...текущий(), вид });
}

export function установитьНочьЦвета(вкл: boolean): void {
  сохранить({ ...текущий(), ночьЦвета: вкл });
}

function подписаться(ф: () => void): () => void {
  слушатели.add(ф);
  return () => {
    слушатели.delete(ф);
  };
}

export function useВидЧтения(): ВыборВида {
  return useSyncExternalStore(подписаться, текущий, текущий);
}
