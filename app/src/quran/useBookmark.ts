/**
 * Закладка Корана для экранов (владелец 21.11.2026: «при нажатии на номер аята … сохранить, чтобы, когда хотел
 * продолжить, мог начать с этого сохранённого места»). Хранение — screens/quran/common.ts (только на устройстве).
 *
 * Контракт: useЗакладка() → МестоЧтения | null — текущая закладка; меняется сразу после поставитьЗакладку().
 */
import { useEffect, useState } from 'react';
import { подписатьсяНаЗакладку, прочитатьЗакладку, type МестоЧтения } from '../screens/quran/common';

export function useЗакладка(): МестоЧтения | null {
  const [закладка, установить] = useState<МестоЧтения | null>(null);
  useEffect(() => {
    let живой = true;
    void прочитатьЗакладку().then((з) => {
      if (живой) установить(з);
    });
    const отписаться = подписатьсяНаЗакладку(установить);
    return () => {
      живой = false;
      отписаться();
    };
  }, []);
  return закладка;
}
