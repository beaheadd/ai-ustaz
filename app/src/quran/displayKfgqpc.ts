/**
 * Подстройка показа текста Корана для шрифта «Мединский мусхаф» (KFGQPC HAFS Uthmanic Script 3.0) — чистая часть
 * (без импортов: проверяется в node, scripts/test-quran.mjs и scripts/test-quran-font.mjs).
 *
 * Решение владельца 28.11.2026 («Да, с подстройкой»): мединский шрифт KFGQPC Hafs 3.0 — по умолчанию, подстройка показа
 * утверждена. ТЕКСТ В ХРАНИЛИЩЕ НЕ МЕНЯЕТСЯ; подстройка — только для этого шрифта при отрисовке. ЖДЁТ ПРОВЕРКИ УСТАЗА
 * (правило 11 CLAUDE.md; docs/HANDOFF.md, docs/дизайн/05-коран-чтение-и-плеер.md).
 *
 * Зачем: шрифт Комплекса короля Фахда построен под кодировку текста самого Комплекса, а наш текст — Tanzil Uthmani 1.1
 * (правило 1). Сверка всех 6236 аятов с текстом из архива шрифта (hafs-3.0.zip, .docx Комплекса) и формирование
 * HarfBuzz показали, что без подстройки шрифт рисует Tanzil неверно:
 *   U+0652 сукун (≈ 37 тыс.)            → круглый «нолик» — в мусхафе Медины это знак НЕпроизносимой буквы (смысл меняется);
 *                                         сукун мединского письма в шрифте — U+06E1;
 *   U+06DF малый круглый нолик (≈ 4 тыс.) → в шрифте это не знак, а заглушка (чёрная точка в пунктирном кружке);
 *                                         круглый нолик шрифта — U+0652;
 *   U+06EA имала (11:41)                → заглушка; точка ималы в шрифте — U+065C;
 *   U+06EB ишмам (12:11)                → заглушка; ромб ишмама в шрифте — U+06EC (тем же знаком у Комплекса и ташиль 41:44);
 *   U+0640 татвиль перед U+0670 (≈ 5,9 тыс., ٱلْكِتَـٰبُ, ٱلرَّحْمَـٰنِ) → надстрочный алиф падает на строку после
 *                                         слова; у Комплекса татвиля перед ٰ нет.
 * Подстройка — ровно эти пять правил, ничего больше: 4 замены знака на знак и удаление татвиля, за которым сразу идёт
 * U+0670. Остальное (знаки остановки, ۞ ۩, малые ۥ ۦ ۧ ۨ, мадда, хамза на татвиле, танвин с малым мимом по Tanzil)
 * шрифт рисует верно — не трогаем. Расхождения изданий (знаки остановки Tanzil и Комплекса в ≈ 300 местах) не правим:
 * показываем Tanzil.
 *
 * Где применяется: только когда выбран «Мединский мусхаф» и шрифт загружен (components/quran/QuranFont.tsx), только к
 * строкам, которые уходят в отрисовку. Копирование, «Сообщить об ошибке», поиск, чат, речевой сервис и все сверки
 * «побайтно = Tanzil» берут ИСХОДНЫЙ текст: на вебе подстроенный кусок лежит в <span data-o="исходный">
 * (quran/originalText.ts восстанавливает выделение). Цвета таджвида режут ИСХОДНУЮ строку по своим отрезкам, а
 * подстройка применяется к каждому куску после разреза: отрезок таджвида не режет букву и её знаки (quran/tajweed.ts),
 * поэтому татвиль и его ٰ всегда в одном куске — индексы не съезжают.
 *
 * Контракт:
 *   ЗАМЕНЫ_KFGQPC — исходный знак → знак шрифта (4 пары);
 *   подстроитьДляKfgqpc(строка) → строка для отрисовки этим шрифтом;
 *   подстроитьСКартой(строка) → { текст, исходные } — исходные[i] = индекс в исходной строке для i-го знака текста,
 *     исходные[текст.length] = длина исходной строки (для частичного выделения);
 *   исходныйОтрезок(исходная, с, по) → отрезок исходной строки, который на экране был подстроенными знаками [с, по);
 *   кускиДляKfgqpc(куски) — куски цвета таджвида для этого шрифта: если цветной кусок начинается с «ـٰ» (мадд на
 *     надстрочном алифе после татвиля, ≈ 5,8 тыс. мест), а кусок перед ним без цвета, последняя буква (основа и её знаки)
 *     переходит в цветной кусок. Иначе после подстройки цветной кусок начинался бы со знака ٰ, а браузер красит знак цветом
 *     его основы — мадд потерял бы цвет. Так раскрашено и без татвиля (ذَٰ — буква с ٰ целиком). Склейка не меняется;
 *     только для показа этим шрифтом, разметка таджвида не меняется.
 */

export const ЗАМЕНЫ_KFGQPC: Readonly<Record<string, string>> = {
  'ْ': 'ۡ', // сукун → сукун мединского письма
  '۟': 'ْ', // малый круглый нолик (непроизносимая буква) → круглый нолик шрифта
  '۪': 'ٜ', // имала (11:41) → точка снизу
  '۫': '۬', // ишмам (12:11) → ромб
};
const ТАТВИЛЬ = 'ـ';
const НАДСТРОЧНЫЙ_АЛИФ = 'ٰ';

export function подстроитьСКартой(строка: string): { текст: string; исходные: number[] } {
  let текст = '';
  const исходные: number[] = [];
  for (let i = 0; i < строка.length; i++) {
    const з = строка[i];
    if (з === ТАТВИЛЬ && строка[i + 1] === НАДСТРОЧНЫЙ_АЛИФ) continue;
    текст += ЗАМЕНЫ_KFGQPC[з] ?? з;
    исходные.push(i);
  }
  исходные.push(строка.length);
  return { текст, исходные };
}

export function подстроитьДляKfgqpc(строка: string): string {
  let есть = false;
  for (let i = 0; i < строка.length && !есть; i++) есть = строка[i] in ЗАМЕНЫ_KFGQPC || строка[i] === ТАТВИЛЬ;
  return есть ? подстроитьСКартой(строка).текст : строка;
}

/** Отрезок исходной строки под подстроенными знаками [с, по): удалённый татвиль перед ٰ возвращается вместе с ٰ. */
export function исходныйОтрезок(исходная: string, с: number, по: number): string {
  const { исходные } = подстроитьСКартой(исходная);
  const н = Math.max(0, Math.min(с, исходные.length - 1));
  const к = Math.max(н, Math.min(по, исходные.length - 1));
  let начало = исходные[н];
  // ٰ — первый выделенный знак, а татвиль перед ним удалён: татвиль принадлежит той же букве.
  if (начало > 0 && исходная[начало - 1] === ТАТВИЛЬ && исходная[начало] === НАДСТРОЧНЫЙ_АЛИФ) начало -= 1;
  return исходная.slice(начало, исходные[к]);
}

const ЗНАК = /\p{M}/u;

export function кускиДляKfgqpc<К extends { текст: string; код: unknown }>(куски: readonly К[]): К[] {
  const итог: К[] = [];
  for (const к of куски) {
    const пред = итог[итог.length - 1];
    if (к.код && к.текст.startsWith(ТАТВИЛЬ + НАДСТРОЧНЫЙ_АЛИФ) && пред && !пред.код) {
      let i = пред.текст.length;
      while (i > 0 && ЗНАК.test(пред.текст[i - 1])) i -= 1;
      if (i > 0 && пред.текст[i - 1] !== ' ') i -= 1;
      const буква = пред.текст.slice(i);
      if (i === 0) итог.pop();
      else итог[итог.length - 1] = { ...пред, текст: пред.текст.slice(0, i) };
      итог.push({ ...к, текст: буква + к.текст });
    } else итог.push(к);
  }
  return итог;
}
