/**
 * Виды чтения «Страница мусхафа», «Мусхаф + цвета таджвида», «Ночной» — загрузка индекса страниц и разметки таджвида.
 * Чистая часть — quran/mushaf.ts (страницы, проверки), quran/tajweed.ts (разбор разметки, куски текста).
 *
 * Откуда: статические файлы /aiustaz/quran/tajweed/… (tools/quran/build_tajweed.py), цепочка sha256: манифест в бандле
 * (tajweedManifest.generated.ts) → индекс → файл разметки суры (его sha256Текста = sha256 файла суры Корана).
 * Тот же загрузчик и кэш, что у текста (quran/data.ts): неудачи не кэшируются, «Повторить» снова идёт в сеть.
 *
 * Контракт:
 *   useИндексМусхафа() → СостояниеКорана<ИндексМусхафа> & { повторить }
 *   useРазметкаСуры(н | null) → СостояниеКорана<РазметкаСуры> & { повторить }   (null — не грузить: вид без цветов)
 * Решение владельца 20.11.2026: виды чтения Корана.
 */
import { загрузитьФайл, изКэша, useЗагрузка, type Результат } from './data';
import { проверитьИндексМусхафа, проверитьРазметкуСуры, type ИндексМусхафа, type РазметкаСуры } from './mushaf';
import { МАНИФЕСТ_ТАДЖВИДА as М } from './tajweedManifest.generated';

export function загрузитьИндексМусхафа(): Promise<Результат<ИндексМусхафа>> {
  return загрузитьФайл('мусхаф', М.индекс, М.sha256Индекса, (с) => проверитьИндексМусхафа(с, М));
}

export async function загрузитьРазметкуСуры(н: number): Promise<Результат<РазметкаСуры>> {
  const и = await загрузитьИндексМусхафа();
  if (!и.ок) return и;
  const запись = и.данные.суры[н - 1];
  if (!запись) return { ок: false, причина: 'нет-файла' };
  return загрузитьФайл('таджвид-' + н, запись.файл, запись.sha256, (с) => проверитьРазметкуСуры(с, запись));
}

export function useИндексМусхафа() {
  return useЗагрузка('мусхаф', изКэша<ИндексМусхафа>('мусхаф'), загрузитьИндексМусхафа);
}

export function useРазметкаСуры(н: number | null) {
  return useЗагрузка(н === null ? null : 'таджвид-' + н, н === null ? null : изКэша<РазметкаСуры>('таджвид-' + н), () => загрузитьРазметкуСуры(н ?? 0));
}
