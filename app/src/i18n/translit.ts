/**
 * Учебная транскрипция (кириллица по схеме каталога ошибок §10.1, content: «транскрипция») → узбекская латиница
 * для интерфейса uz. Чистая функция, без импортов (тест — scripts/test-i18n.mjs).
 *
 * Решение владельца 20.11.2026: узбекский — латиницей. Транскрипция в данных остаётся кириллической (её сверяет
 * tools/check_content.py); для uz показываем её латиницей по той же схеме: дж → j, х → x, һ → h, қ → q, ғ → gʻ,
 * х̣ → ḥ, ш → sh, й → y, «ау» (و с сукуном после фатхи) → «av», «ль» → «l»; точки и черты под буквой (с̣, т̱ …) сохраняются;
 * ’ (хамза) → ʼ (U+02BC), ‘ (‘айн) — как есть. ЧЕРНОВИК для редактора-носителя.
 *
 * Контракт: транскрипцияЛатиницей(строка) → строка (uz); транскрипцияАнглийская(строка) → строка (en);
 *   транскрипцияЯзыка(строка, язык); неизвестные знаки остаются как есть.
 */
const БУКВЫ: Readonly<Record<string, string>> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'j', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n',
  о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'x', ш: 'sh', ь: '', ғ: 'gʻ', қ: 'q', һ: 'h',
  ӣ: 'ī', ӯ: 'ū', '’': 'ʼ',
};

/** Учебная транскрипция → английская латиница (интерфейс en, владелец 20.11.2026; ЧЕРНОВИК для редактора-носителя):
 * дж → j, х → kh, х̣ → ḥ, ш → sh, ғ → gh, қ → q, һ → h, в (و) → w, й → y, «ау» → «aw», с̱ → th, з̱ → dh;
 * точка снизу сохраняется (ṣ ṭ ḍ ẓ); ‘ (‘айн) → ʿ (U+02BF), ’ (хамза) → ʾ (U+02BE). */
const БУКВЫ_EN: Readonly<Record<string, string>> = {
  а: 'a', б: 'b', в: 'w', г: 'g', д: 'd', е: 'e', ж: 'j', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n',
  о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ш: 'sh', ь: '', ғ: 'gh', қ: 'q', һ: 'h',
  ӣ: 'ī', ӯ: 'ū', '’': 'ʾ', '‘': 'ʿ',
};

export function транскрипцияАнглийская(строка: string): string {
  return строка
    .replace(/дж/g, 'j')
    .replace(/х\u0323/g, 'ḥ')
    .replace(/с\u0331/g, 'th')
    .replace(/з\u0331/g, 'dh')
    .replace(/ау(?![\u0300-\u036f])/g, 'aw')
    .replace(/[^\s]/g, (б) => БУКВЫ_EN[б] ?? б)
    .normalize('NFC');
}

/** Транскрипция для языка интерфейса: uz — узбекская латиница, en — английская, ru/kk — кириллица из данных;
 * ar, tr, id, ur (28.11.2026) — английская: тексты уроков для них — английские (своего перевода пока нет). */
export function транскрипцияЯзыка(строка: string, язык: string): string {
  if (язык === 'uz') return транскрипцияЛатиницей(строка);
  if (язык === 'en' || язык === 'ar' || язык === 'tr' || язык === 'id' || язык === 'ur') return транскрипцияАнглийская(строка);
  return строка;
}

export function транскрипцияЛатиницей(строка: string): string {
  return строка
    .replace(/дж/g, 'j')
    .replace(/х\u0323/g, 'ḥ') // х̣ (ح) — как в названии буквы «ḥo»
    .replace(/ау(?![\u0300-\u036f])/g, 'av')
    .replace(/[^\s]/g, (б) => БУКВЫ[б] ?? б)
    .normalize('NFC'); // s + точка снизу → ṣ (как в НАЗВАНИЯ_БУКВ.трUz)
}
