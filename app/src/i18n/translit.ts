/**
 * Учебная транскрипция (кириллица по схеме каталога ошибок §10.1, content: «транскрипция») → узбекская латиница
 * для интерфейса uz. Чистая функция, без импортов (тест — scripts/test-i18n.mjs).
 *
 * Решение владельца 20.11.2026: узбекский — латиницей. Транскрипция в данных остаётся кириллической (её сверяет
 * tools/check_content.py); для uz показываем её латиницей по той же схеме: дж → j, х → x, һ → h, қ → q, ғ → gʻ,
 * х̣ → ḥ, ш → sh, й → y, «ау» (و с сукуном после фатхи) → «av», «ль» → «l»; точки и черты под буквой (с̣, т̱ …) сохраняются;
 * ’ (хамза) → ʼ (U+02BC), ‘ (‘айн) — как есть. ЧЕРНОВИК для редактора-носителя.
 *
 * Контракт: транскрипцияЛатиницей(строка) → строка; неизвестные знаки остаются как есть.
 */
const БУКВЫ: Readonly<Record<string, string>> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'j', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n',
  о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'x', ш: 'sh', ь: '', ғ: 'gʻ', қ: 'q', һ: 'h',
  ӣ: 'ī', ӯ: 'ū', '’': 'ʼ',
};

export function транскрипцияЛатиницей(строка: string): string {
  return строка
    .replace(/дж/g, 'j')
    .replace(/х\u0323/g, 'ḥ') // х̣ (ح) — как в названии буквы «ḥo»
    .replace(/ау(?![\u0300-\u036f])/g, 'av')
    .replace(/[^\s]/g, (б) => БУКВЫ[б] ?? б)
    .normalize('NFC'); // s + точка снизу → ṣ (как в НАЗВАНИЯ_БУКВ.трUz)
}
