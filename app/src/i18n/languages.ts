/**
 * Языки интерфейса — чистый модуль без React (его берут и engine/progress.ts, и prayer/*, и тесты в node).
 *
 * Владелец 20.11.2026: ru, kk, uz (латиница), en. Владелец 28.11.2026: «Нужно добавить языки наиболее мусульманских
 * стран сначала. Арабский…» → выбрано «Арабский + Турецкий + Индонезийский + Урду» (ar, tr, id, ur).
 * kk, uz, en, ar, tr, id и ur — ЧЕРНОВИКИ перевода для редактора-носителя (CLAUDE.md).
 *
 * Контракт:
 *   Язык — 'ru' | 'kk' | 'uz' | 'en' | 'ar' | 'tr' | 'id' | 'ur'; ВСЕ_ЯЗЫКИ — в этом порядке.
 *   ЯзыкОсновной — 'ru' | 'kk' | 'uz' | 'en': языки, на которых есть содержимое (уроки, правила, зикры, content/*.json).
 *   ЯзыкНовый — 'ar' | 'tr' | 'id' | 'ur': интерфейс есть (ленивый чанк словарей, i18n/locales/lang-*.json),
 *     содержимого своего пока нет — запасной язык английский (en).
 *   этоНовый(я) — я ∈ ЯзыкНовый; основной(я) → ЯзыкОсновной (новый → 'en'): для данных, где есть только 4 языка.
 *   справаНалево(я) — ar и ur (письмо справа налево: раскладка зеркально, <html dir="rtl">).
 *   ЛОКАЛЬ_INTL[я] — тег для Intl (числа и даты): цифры — западные (latn) во всех языках, см. i18n/format.ts.
 */
export type Язык = 'ru' | 'kk' | 'uz' | 'en' | 'ar' | 'tr' | 'id' | 'ur';
export type ЯзыкОсновной = 'ru' | 'kk' | 'uz' | 'en';
export type ЯзыкНовый = 'ar' | 'tr' | 'id' | 'ur';

export const ВСЕ_ЯЗЫКИ: readonly Язык[] = ['ru', 'kk', 'uz', 'en', 'ar', 'tr', 'id', 'ur'];
export const НОВЫЕ_ЯЗЫКИ: readonly ЯзыкНовый[] = ['ar', 'tr', 'id', 'ur'];

export function этоНовый(я: string | null | undefined): я is ЯзыкНовый {
  return я === 'ar' || я === 'tr' || я === 'id' || я === 'ur';
}

/** Язык данных, где есть только ru/kk/uz/en: новый язык → английский (en). */
export function основной(я: Язык): ЯзыкОсновной {
  return этоНовый(я) ? 'en' : я;
}

/** Письмо справа налево: арабский и урду. */
export function справаНалево(я: string | null | undefined): boolean {
  return я === 'ar' || я === 'ur';
}

/** Тег для Intl: западные цифры (latn) — и в ar, и в ur (решение: время намаза и счёт — 0–9, как на часах телефона). */
export const ЛОКАЛЬ_INTL: Record<Язык, string> = {
  ru: 'ru-RU',
  kk: 'kk-KZ',
  uz: 'uz-Latn-UZ',
  en: 'en-GB',
  ar: 'ar-u-nu-latn',
  tr: 'tr-TR',
  id: 'id-ID',
  ur: 'ur-PK-u-nu-latn',
};
