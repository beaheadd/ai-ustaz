import { прочитатьJSON, записатьJSON } from '../engine/storage';
import { этоНовый, type Язык, type ЯзыкНовый, type ЯзыкОсновной } from '../i18n/languages';
import { загрузитьФайл, изКэша, useЗагрузка, type Результат } from '../quran/data';
import { деньРК } from '../prayer/day';
import { МАНИФЕСТ_ЗИКРОВ } from './manifest.generated';

/** Тексты записи: ru, kk, uz, en — всегда; ar, tr, id, ur — если есть (черновики, владелец 28.11.2026). */
export type Тексты = Record<ЯзыкОсновной, string> & Partial<Record<ЯзыкНовый, string>>;

/** Текст на языке интерфейса: своего нет — для ar/tr/id/ur английский (экран пишет «Перевод на ваш язык готовится»). */
export function текстЗикра(т: Тексты | undefined, язык: Язык): string {
  if (!т) return '';
  return т[язык] || (этоНовый(язык) ? т.en : '') || т.ru;
}

/** Есть ли своё поле для языка (ar/tr/id/ur — не у всех записей). */
export function естьЯзыкЗикра(т: Тексты | undefined, язык: Язык): boolean {
  return !!т?.[язык]?.trim();
}

/**
 * Арабский интерфейс (владелец 28.11.2026): только арабский текст зикра — без произношения и перевода
 * (арабский читатель читает сам текст источника).
 */
export const толькоАрабский = (язык: Язык) => язык === 'ar';

export type Зикр = {
  id: string;
  номер: number;
  раз: number;
  вид: 'хадис' | 'коран';
  ar: string[];
  название: Тексты;
  произношение: Тексты;
  перевод: Тексты;
  примечание?: Тексты;
  /** Мольба — показывается и в разделе «Дуа» (#/dua; владелец 27.11.2026). */
  дуа?: boolean;
  /** Когда читать — по хадису (владелец 27.11.2026: «разделить зикры: утренние, вечерние…»). */
  время: ВремяЗикра[];
  /** Тема дуа (раздел «Дуа»: дом, мечеть, в пути…). */
  тема?: ТемаДуа;
  /** Повседневная дуа — только в разделе «Дуа», не в списке зикров. */
  повседневная?: boolean;
  источник: {
    коран?: string;
    hadeethenc?: number;
    степень_ar?: string;
    степень?: Тексты;
    передали_ar?: string;
    передали?: Тексты;
  };
};

export type НаборЗикров = { версия: string; зикры: Зикр[] };

export const ВРЕМЕНА_ЗИКРОВ = ['утро', 'вечер', 'после-намаза', 'любое'] as const;
export type ВремяЗикра = (typeof ВРЕМЕНА_ЗИКРОВ)[number];
/** Порядок тем на экране «Дуа». */
export const ТЕМЫ_ДУА = ['утро-вечер', 'дом', 'мечеть', 'путь', 'еда', 'сон', 'одежда', 'туалет', 'болезнь', 'беда', 'погода', 'покаяние', 'разное'] as const;
export type ТемаДуа = (typeof ТЕМЫ_ДУА)[number];

const ЯЗЫКИ_ЗИКРОВ: readonly ЯзыкОсновной[] = ['kk', 'ru', 'uz', 'en'];
const ЯЗЫКИ_НОВЫЕ: readonly ЯзыкНовый[] = ['ar', 'tr', 'id', 'ur'];
const КЛЮЧ_КЭША = 'зикры';

function строка(з: unknown): з is string {
  return typeof з === 'string' && з.trim().length > 0;
}

function тексты(з: unknown): Тексты | null {
  if (!з || typeof з !== 'object') return null;
  const о = з as Record<string, unknown>;
  for (const я of ЯЗЫКИ_ЗИКРОВ) if (!строка(о[я])) return null;
  const итог: Тексты = { kk: о.kk as string, ru: о.ru as string, uz: о.uz as string, en: о.en as string };
  for (const я of ЯЗЫКИ_НОВЫЕ) {
    if (о[я] === undefined) continue;
    if (!строка(о[я])) return null;
    итог[я] = о[я] as string;
  }
  return итог;
}

function целое(з: unknown, мин: number, макс: number): з is number {
  return typeof з === 'number' && Number.isInteger(з) && з >= мин && з <= макс;
}

/** Строгая проверка формы набора; null — не показываем ничего (правило: непроверенное не показываем). */
export function проверитьЗикры(сырые: unknown): НаборЗикров | null {
  if (!сырые || typeof сырые !== 'object') return null;
  const н = сырые as Record<string, unknown>;
  if (!строка(н.версия) || !Array.isArray(н.зикры) || н.зикры.length === 0) return null;
  const ids = new Set<string>();
  const зикры: Зикр[] = [];
  for (let i = 0; i < н.зикры.length; i++) {
    const з = н.зикры[i] as Record<string, unknown> | null;
    if (!з || typeof з !== 'object') return null;
    if (!строка(з.id) || !/^[a-z0-9-]{1,40}$/.test(з.id) || ids.has(з.id)) return null;
    ids.add(з.id);
    if (з.номер !== i + 1 || !целое(з.раз, 1, 1000) || (з.вид !== 'хадис' && з.вид !== 'коран')) return null;
    if (!Array.isArray(з.ar) || з.ar.length === 0 || !з.ar.every(строка)) return null;
    const название = тексты(з.название);
    const произношение = тексты(з.произношение);
    const перевод = тексты(з.перевод);
    if (!название || !произношение || !перевод) return null;
    let примечание: Тексты | undefined;
    if (з.примечание !== undefined) {
      const п = тексты(з.примечание);
      if (!п) return null;
      примечание = п;
    }
    if (з.дуа !== undefined && з.дуа !== true) return null;
    const время = з.время;
    if (!Array.isArray(время) || время.length === 0 || !время.every((в) => (ВРЕМЕНА_ЗИКРОВ as readonly unknown[]).includes(в))) return null;
    if (з.тема !== undefined && (з.дуа !== true || !(ТЕМЫ_ДУА as readonly unknown[]).includes(з.тема))) return null;
    if (з.повседневная !== undefined && (з.повседневная !== true || з.дуа !== true)) return null;
    const и = з.источник as Record<string, unknown> | null;
    if (!и || typeof и !== 'object') return null;
    const источник: Зикр['источник'] = {};
    if (з.вид === 'коран') {
      if (!строка(и.коран) || !/^\d{1,3}:\d{1,3}(-\d{1,3})?$/.test(и.коран)) return null;
      источник.коран = и.коран;
    } else {
      if (!целое(и.hadeethenc, 1, 999999) || !строка(и.степень_ar) || !строка(и.передали_ar)) return null;
      const степень = тексты(и.степень);
      const передали = тексты(и.передали);
      if (!степень || !передали) return null;
      Object.assign(источник, { hadeethenc: и.hadeethenc, степень_ar: и.степень_ar, степень, передали_ar: и.передали_ar, передали });
    }
    зикры.push({
      id: з.id,
      номер: з.номер as number,
      раз: з.раз,
      вид: з.вид,
      ar: з.ar as string[],
      название,
      произношение,
      перевод,
      ...(примечание ? { примечание } : null),
      ...(з.дуа === true ? { дуа: true } : null),
      время: время as ВремяЗикра[],
      ...(з.тема !== undefined ? { тема: з.тема as ТемаДуа } : null),
      ...(з.повседневная === true ? { повседневная: true } : null),
      источник,
    });
  }
  return { версия: н.версия, зикры };
}

export function загрузитьЗикры(): Promise<Результат<НаборЗикров>> {
  return загрузитьФайл(КЛЮЧ_КЭША, МАНИФЕСТ_ЗИКРОВ.файл, МАНИФЕСТ_ЗИКРОВ.sha256, проверитьЗикры);
}

export function useЗикры() {
  return useЗагрузка(КЛЮЧ_КЭША, изКэша<НаборЗикров>(КЛЮЧ_КЭША), загрузитьЗикры);
}

// ───────────────────────── Счёт (только на устройстве) ─────────────────────────

export type ЗаписьСчёта = { текущий: number; день?: string; всего: number; цель?: number };
export type СчётЗикров = { версия: 1; счёт: Record<string, ЗаписьСчёта>; избранное: string[] };

/** Варианты цели в меню счётчика. */
export const ЦЕЛИ: readonly number[] = [1, 3, 7, 10, 33, 99, 100];

const КЛЮЧ_СЧЁТА = 'dhikr.v1';
const ПУСТО: СчётЗикров = { версия: 1, счёт: {}, избранное: [] };
const МАКС = 1e9;

export function цельЗикра(запись: ЗаписьСчёта | undefined, раз: number): number {
  return запись?.цель ?? раз;
}

/** Сегодняшняя дата по Алматы (UTC+5) — сутки счёта зикров. */
export function деньСейчас(): string {
  return деньРК(Date.now());
}

/** Счёт за сегодня: запись другого дня — 0. */
export function сегодняЗикра(запись: ЗаписьСчёта | undefined, день: string = деньСейчас()): number {
  return запись && запись.день === день ? запись.текущий : 0;
}

/** +1 за сегодня (в новые сутки — с 1) и к «всего»; после цели счёт идёт дальше. готово — ровно дошли до цели. */
export function нажать(запись: ЗаписьСчёта | undefined, раз: number, день: string = деньСейчас()): { запись: ЗаписьСчёта; готово: boolean } {
  const цель = цельЗикра(запись, раз);
  const текущий = Math.min(МАКС, сегодняЗикра(запись, день) + 1);
  const всего = Math.min(МАКС, (запись?.всего ?? 0) + 1);
  const новая: ЗаписьСчёта = { текущий, день, всего, ...(запись?.цель !== undefined ? { цель: запись.цель } : null) };
  return { запись: новая, готово: текущий === цель };
}

function разобратьСчёт(с: unknown): СчётЗикров {
  if (!с || typeof с !== 'object') return ПУСТО;
  const о = с as Record<string, unknown>;
  const счёт: Record<string, ЗаписьСчёта> = {};
  if (о.счёт && typeof о.счёт === 'object') {
    for (const [id, з] of Object.entries(о.счёт as Record<string, unknown>)) {
      const з2 = з as Record<string, unknown> | null;
      if (!з2 || !целое(з2.текущий, 0, МАКС) || !целое(з2.всего, 0, МАКС)) continue;
      const цель = целое(з2.цель, 1, 1000) ? з2.цель : undefined;
      // Записи до 27.11.2026 без «дня» (круг) — считаем сегодняшними, чтобы счёт на экране не пропал.
      const день = typeof з2.день === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(з2.день) ? з2.день : деньСейчас();
      счёт[id] = { текущий: з2.текущий, день, всего: з2.всего, ...(цель !== undefined ? { цель } : null) };
    }
  }
  const избранное = Array.isArray(о.избранное) ? (о.избранное as unknown[]).filter(строка) : [];
  return { версия: 1, счёт, избранное };
}

let счётСейчас: СчётЗикров | null = null;
const слушатели = new Set<(с: СчётЗикров) => void>();

export async function прочитатьСчёт(): Promise<СчётЗикров> {
  if (!счётСейчас) счётСейчас = разобратьСчёт(await прочитатьJSON<unknown>(КЛЮЧ_СЧЁТА, null));
  return счётСейчас;
}

function сохранить(с: СчётЗикров) {
  счётСейчас = с;
  void записатьJSON(КЛЮЧ_СЧЁТА, с);
  for (const ф of [...слушатели]) ф(с);
}

function текущийСчёт(): СчётЗикров {
  return счётСейчас ?? ПУСТО;
}

/** +1 к зикру; возвращает, дошёл ли счёт за сегодня ровно до цели (для вибрации и отметки «готово»). */
export function добавить(id: string, раз: number): boolean {
  const с = текущийСчёт();
  const { запись, готово } = нажать(с.счёт[id], раз);
  сохранить({ ...с, счёт: { ...с.счёт, [id]: запись } });
  return готово;
}

/** Сбросить счёт за сегодня (всё — и «всего» тоже; цель остаётся). */
export function сбросить(id: string, всё = false): void {
  const с = текущийСчёт();
  const з = с.счёт[id];
  if (!з) return;
  сохранить({ ...с, счёт: { ...с.счёт, [id]: { текущий: 0, день: деньСейчас(), всего: всё ? 0 : з.всего, ...(з.цель !== undefined ? { цель: з.цель } : null) } } });
}

/** Своя цель зикра (null — по умолчанию из набора). Счёт за сегодня не сбрасывается. */
export function задатьЦель(id: string, цель: number | null): void {
  const с = текущийСчёт();
  const з = с.счёт[id] ?? { текущий: 0, всего: 0 };
  const { цель: _прежняя, ...безЦели } = з;
  сохранить({ ...с, счёт: { ...с.счёт, [id]: цель === null ? безЦели : { ...безЦели, цель } } });
}

export function переключитьИзбранное(id: string): void {
  const с = текущийСчёт();
  const есть = с.избранное.includes(id);
  сохранить({ ...с, избранное: есть ? с.избранное.filter((и) => и !== id) : [...с.избранное, id] });
}

/** Счёт для экранов: сначала из памяти (или пустой), после чтения хранилища — сохранённый; меняется сразу. */
export function useСчётЗикров(): СчётЗикров {
  const [с, установить] = useState<СчётЗикров>(текущийСчёт());
  useEffect(() => {
    let живой = true;
    void прочитатьСчёт().then((з) => {
      if (живой) установить(з);
    });
    слушатели.add(установить);
    return () => {
      живой = false;
      слушатели.delete(установить);
    };
  }, []);
  return с;
}
