/**
 * Зикры: загрузка набора (статический файл сборки) и личный счёт на этом устройстве.
 *
 * Решение владельца 26.11.2026: «Добавь все эти зикры с переводом и с счётчиком, чтобы можно было нажать и считать как
 * второй скрин»; «Арабский, произношение на нашем языке и перевод также как здесь». Экраны — screens/DhikrScreen.tsx
 * (список) и screens/DhikrCounterScreen.tsx (счётчик).
 *
 * Откуда данные: content/dhikr/dhikr.json → tools/dhikr/build_dhikr.py → app/public/dhikr/dhikr.<хэш>.json (dist/dhikr).
 * Текста зикров в JS нет — только манифест (manifest.generated.ts: имя файла, sha256, количество). Загрузка — общим
 * загрузчиком Корана (src/quran/data.ts: сверка sha256, кэш, «нет связи»), ключ кэша «зикры».
 * Арабский текст выводится как есть (Коран — дословно из Tanzil по ссылке «сура:аят», хадисы — из HadeethEnc).
 *
 * Счёт — только на устройстве (localStorage «aiustaz:dhikr.v1»), никуда не отправляется:
 *   { версия: 1, счёт: { [id]: { текущий, день?, всего, цель? } }, избранное: id[] }.
 *   текущий — счёт за сутки «день» (YYYY-MM-DD по Алматы, UTC+5; CLAUDE.md: сутки — по Алматы); в новые сутки — с 0.
 *   всего — за всё время. После цели счёт НЕ сбрасывается — идёт дальше (владелец 27.11.2026: «после 33 обнуляется — не
 *   нужно, пусть продолжает; крупно — за сегодня, ниже — за весь период»).
 * Общего счёта всех пользователей нет (правило 9: без публичных счётчиков поклонения и наград).
 *
 * Контракт:
 *   проверитьЗикры(сырые) → НаборЗикров | null — строгая проверка формы (4 языка, номера 1…N подряд, id уникальны);
 *   загрузитьЗикры(), useЗикры() → состояние как у Корана ({ 'загрузка' } | { 'нет', нетСвязи, причина } | { 'есть', данные });
 *   нажать(запись, цельПоУмолчанию, день) → { запись, готово } — чистая функция: +1 за сегодня (в новые сутки — с 1),
 *     без сброса после цели; готово — счёт за сегодня только что стал равен цели;
 *   сегодняЗикра(запись, день?) — счёт за сегодня (другие сутки — 0); деньСейчас() — сегодняшняя дата по Алматы;
 *   цельЗикра(запись, раз); ЦЕЛИ — варианты цели в меню;
 *   прочитатьСчёт(), useСчётЗикров() → СчётЗикров; добавить(id, раз), сбросить(id, всё?), задатьЦель(id, цель | null),
 *   переключитьИзбранное(id) — меняют состояние, пишут в хранилище и сразу сообщают подписчикам.
 */
