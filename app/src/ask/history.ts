/**
 * История чата AI Ustaz — только на этом телефоне (localStorage через engine/storage), «Очистить» стирает её.
 * Владелец 27.11.2026: чат «как у Айалема». На сервере о человеке ничего не хранится (CLAUDE.md, «Данные и приватность»).
 * Храним последние МАКС_ЗАПИСЕЙ сообщений: вопрос (текст), ответ (как пришёл, уже проверенный api.разобратьОтвет).
 * Контракт: прочитатьИсторию() → Promise<ЗаписьЧата[]>; записатьИсторию(з[]) ; очиститьИсторию().
 */
import { записатьJSON, прочитатьJSON } from '../engine/storage';
import { разобратьОтвет } from './api';
import { МАКС_ЗАПИСЕЙ, новыйИд, проверитьИсторию, type ЗаписьЧата } from './historyCore';

export { новыйИд, type ЗаписьЧата };
export const КЛЮЧ_ИСТОРИИ = 'ask-chat.v1';

export async function прочитатьИсторию(): Promise<ЗаписьЧата[]> {
  return проверитьИсторию(await прочитатьJSON<unknown>(КЛЮЧ_ИСТОРИИ, []), разобратьОтвет);
}

export async function записатьИсторию(записи: readonly ЗаписьЧата[]): Promise<void> {
  await записатьJSON(КЛЮЧ_ИСТОРИИ, записи.slice(-МАКС_ЗАПИСЕЙ));
}

export async function очиститьИсторию(): Promise<void> {
  await записатьJSON(КЛЮЧ_ИСТОРИИ, []);
}
