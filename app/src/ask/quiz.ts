/**
 * «Проверьте меня» в чате AI Ustaz: мини-вопрос ТОЛЬКО из нашей базы и ТОЛЬКО по пройденным урокам.
 * Владелец 27.11.2026 (чат «как у Айалема», чипы «Проверьте меня»). Ничего не придумываем: берём готовое задание
 * «выбор» (вопрос, варианты, верный, пояснение из утверждённой базы правил) из урока, который человек уже прошёл
 * (engine/progress: уроки[n].пройден). Неверные варианты — только буквы и слоги (правило 8), аяты — никогда.
 * Не прошёл ни одного урока — null: чат честно предлагает начать с урока («Не ругать за правило, которое ещё не
 * проходили», правило 7).
 * Контракт: взятьВопрос(прогресс, случай?) → Promise<ВопросПроверки | null>.
 */
import { загрузитьУрок } from '../engine/lessonEngine';
import type { ЗаданиеВыбор } from '../content/types';
import type { Прогресс } from '../engine/progress';

export type ВопросПроверки = { урок: number; задание: ЗаданиеВыбор };

export function пройденныеУроки(прогресс: Прогресс): number[] {
  return Object.entries(прогресс.уроки)
    .filter(([н, и]) => и.пройден && Number(н) >= 1 && Number(н) <= 100)
    .map(([н]) => Number(н))
    .sort((а, б) => а - б);
}

export async function взятьВопрос(прогресс: Прогресс, случай: () => number = Math.random): Promise<ВопросПроверки | null> {
  const уроки = пройденныеУроки(прогресс);
  for (let попытка = 0; попытка < 3 && уроки.length; попытка++) {
    const номер = уроки[Math.floor(случай() * уроки.length)];
    const урок = await загрузитьУрок(номер).catch(() => null);
    const выборы = (урок?.задания ?? []).filter((з): з is ЗаданиеВыбор => з.тип === 'выбор' && з.варианты.length >= 2);
    if (выборы.length) return { урок: номер, задание: выборы[Math.floor(случай() * выборы.length)] };
  }
  return null;
}
