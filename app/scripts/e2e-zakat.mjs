async function новаяСтраница(браузер, база, { ширина = 360, высота = 780, язык = 'ru', доп = {}, ошибкиСети = false } = {}) {
  const контекст = await браузер.newContext({ ...ТЕЛЕФОН(ширина, высота), locale: 'ru-RU', timezoneId: 'Asia/Almaty' });
  await контекст.addInitScript(
    ({ прогресс, доп }) => {
      if (location.protocol.startsWith('http') && !sessionStorage.getItem('__доп')) {
        sessionStorage.setItem('__доп', '1');
        for (const [к, з] of Object.entries(доп)) localStorage.setItem(к, з);
      }
      window.__csp = [];
      document.addEventListener('securitypolicyviolation', (е) => window.__csp.push(е.blockedURI + ' ' + е.violatedDirective));
      if (location.protocol.startsWith('http') && !localStorage.getItem('aiustaz:progress.v1')) localStorage.setItem('aiustaz:progress.v1', JSON.stringify(прогресс));
      try {
        localStorage.setItem('aiustaz:quran-reciter-asked.v1', '1');
      } catch {}
    },
    { прогресс: ПРОГРЕСС(язык), доп },
  );
  const стр = await контекст.newPage();
  await стр.clock.setFixedTime(new Date(ВРЕМЯ));
  const проблемы = [];
  const чанки = [];
  стр.on('request', (з) => {
    const u = з.url();
    if (/\/ZakatScreen-[0-9a-f]+\.js$/.test(u)) чанки.push(u);
    if (!u.startsWith(база + '/') && !u.startsWith('data:') && !u.startsWith('blob:')) проблемы.push('запрос на другой адрес: ' + u);
  });
  стр.on('console', (с) => {
    // 503 и обрыв сети у /api/zakat/prices — сценарий теста (браузер пишет «Failed to load resource»), остальное — ошибка.
    if (ошибкиСети && /Failed to load resource/.test(с.text()) && /\/api\/zakat\/(prices|rates)/.test(с.location()?.url ?? '')) return;
    if (с.type() === 'error') проблемы.push('ошибка в консоли: ' + с.text());
  });
  стр.on('pageerror', (о) => проблемы.push('исключение на странице: ' + о.message));
  return { контекст, стр, проблемы, чанки };
}

function помощники(стр, проблемы, имя) {
  const э = (id) => стр.getByTestId(id).first();
  const есть = async (id) => (await стр.getByTestId(id).count()) > 0;
  const сырой = async (id) => норм(await стр.evaluate((id) => document.querySelector(`[data-testid="${id}"]`)?.textContent ?? null, id));
  const значение = (id) => э(id).inputValue();
  const атр = (id, а) => э(id).getAttribute(а);
  const проверить = (условие, что) => {
    проверок += 1;
    if (!условие) throw new Error(`[закят: ${имя}] НЕ ВЫПОЛНЕНО: ${что}`);
    console.log(`  ✓ ${что}`);
  };
  const экран = async (id, адрес) => {
    await э(id).waitFor({ timeout: 15000 });
    if (адрес) await стр.waitForFunction((а) => location.hash === а, адрес, { timeout: 5000 });
  };
  const ждатьТекст = (id, текст) =>
    стр
      .waitForFunction(
        ([id, т]) => (document.querySelector(`[data-testid="${id}"]`)?.textContent ?? '').replace(/[  ]/g, ' ').trim() === т,
        [id, текст],
        { timeout: 5000 },
      )
      .then(
        () => true,
        () => false,
      );
  const ввести = async (поле, текст) => {
    await э('закят-поле-' + поле).fill(текст);
  };
  const безПроблем = async (что) => {
    const csp = await стр.evaluate(() => window.__csp ?? []);
    for (const н of csp) проблемы.push('нарушение CSP: ' + н);
    const ключи = await стр.evaluate(() => Object.keys(localStorage));
    for (const к of ключи) if (!к.startsWith('aiustaz:')) проблемы.push('чужой ключ в localStorage: ' + к);
    проверить(проблемы.length === 0, что + (проблемы.length ? ':\n      ' + проблемы.join('\n      ') : ''));
  };
  const безГоризонтальнойПрокрутки = async (где) => {
    const лишнее = await стр.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    проверить(лишнее <= 1, `${где}: нет горизонтальной прокрутки (лишние ${лишнее} px)`);
  };
  /** Снимок окна (SCREENSHOTS): к элементу id — прокрутить, чтобы он был вверху окна. */
  const снимок = async (файл, id) => {
    if (!process.env.SCREENSHOTS) return;
    if (id) await стр.evaluate((id) => document.querySelector(`[data-testid="${id}"]`)?.scrollIntoView({ block: 'start' }), id);
    await стр.waitForTimeout(300);
    await стр.screenshot({ path: path.join(path.resolve(process.env.SCREENSHOTS), файл + '.png') });
  };
  return { э, есть, сырой, значение, атр, проверить, экран, ждатьТекст, ввести, безПроблем, безГоризонтальнойПрокрутки, снимок };
}

