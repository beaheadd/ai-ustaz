    await стр.clock.setFixedTime(new Date(ВРЕМЯ));
    const ключи = await стр.evaluate(() => Object.keys(localStorage).filter((к) => к.includes('dhikr')));
    п.проверить(JSON.stringify(ключи.sort()) === JSON.stringify(['aiustaz:dhikr-filter.v1', 'aiustaz:dhikr.v1']), `ключи хранения — aiustaz:dhikr.v1 и aiustaz:dhikr-filter.v1 (${ключи.join(', ')})`);

    // ── Дуа по темам (владелец 27.11.2026: «дуа для входа в мечеть, путника, повседневные») ──
    await стр.goto(адрес('#/dua'));
    await п.экран('экран-дуа', '#/dua');
    await п.э('зикры-список').waitFor({ timeout: 15000 });
    const дуа = набор.зикры.filter((з) => з.дуа);
    п.проверить(дуа.length >= 30 && (await п.карточек()) === дуа.length, `«Дуа» — все мольбы: ${дуа.length}`);
    for (const тема of ['утро-вечер', 'мечеть', 'путь', 'еда', 'сон']) п.проверить(await п.есть('дуа-группа-' + тема), `группа «${тема}» на экране «Дуа»`);
    await п.э('дуа-тема-мечеть').click();
    const мечеть = дуа.filter((з) => з.тема === 'мечеть').map((з) => з.id).sort();
    const вМечети = await стр.evaluate(() => [...document.querySelectorAll('[data-testid^="зикры-строка-"]')].map((е) => е.getAttribute('data-testid')).filter((т) => /^зикры-строка-[a-z0-9-]+$/.test(т)).map((т) => т.slice('зикры-строка-'.length)).sort());
    п.проверить(JSON.stringify(вМечети) === JSON.stringify(мечеть) && мечеть.includes('mosque-enter'), `тема «Мечеть и азан»: ${вМечети.join(', ')}`);
    const вход = набор.зикры.find((з) => з.id === 'mosque-enter');
    await п.э('зикры-строка-mosque-enter').click();
    await п.экран('экран-зикр', `#/dhikr/item?n=${вход.номер}`);
    await п.э('зикр-арабский').waitFor({ timeout: 15000 });
    const arВход = await стр.evaluate(() => [...document.querySelectorAll('[data-testid="зикр-арабский"] [lang="ar"]')].map((е) => е.textContent));
    п.проверить(JSON.stringify(arВход) === JSON.stringify(вход.ar) && вход.источник.hadeethenc === 65092, 'дуа входа в мечеть: арабский = данным побайтно, HadeethEnc № 65092');

    // «Сбросить всё».
    await стр.goto(адрес('#/dhikr/item?n=1'));
    await п.экран('экран-зикр', '#/dhikr/item?n=1');
    await п.э('зикр-арабский').waitFor({ timeout: 15000 });
    await п.э('зикр-меню-кнопка').click();
    await п.э('зикр-сбросить-всё').click();
    п.проверить((await п.ждатьТекст('зикр-текущий', '0')) && (await п.текстЭ('зикр-всего')) === 'За всё время: 0', '«Сбросить всё» → 0 и «За всё время: 0»');

    // ── 4. глубокая ссылка и несуществующий номер ──
    await стр.goto('about:blank');
    await стр.goto(адрес('#/dhikr/item?n=2'));
    await п.экран('экран-зикр', '#/dhikr/item?n=2');
    await п.э('кнопка-назад').click();
    await п.экран('экран-зикры', '#/dhikr');
    await п.э('кнопка-назад').click();
    await п.экран('экран-ещё', '#/more');
    п.проверить(true, 'глубокая ссылка: счётчик → «Назад» → список → «Назад» → «Ещё»');
