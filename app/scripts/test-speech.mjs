тест('покрывают все слова по порядку; ≤ предела сервиса (вынужденные — ≤ ЦЕЛЬ_СЕК); токены подсветки — ровно слова части; не идут через ۘ', () => {
  assert.equal(ВСЕ_АЯТЫ.length, 6236);
  let всего = 0;
  let вынужденных = 0;
  for (const а of ВСЕ_АЯТЫ) {
    const ток = разборАята(а.текст);
    const ч = части(а.сура, а.аят);
    const слов = ток.filter((т) => т.вид === 'слово').length;
    assert.ok(ч.length >= 1);
    assert.equal(ч[0].словоС, 1);
    assert.equal(ч[0].токенС, 0);
    assert.equal(ч.at(-1).словоС + ч.at(-1).слов - 1, слов);
    assert.equal(ч.at(-1).токенПо, ток.length - 1);
    ч.forEach((п, i) => {
      const где = `${а.сура}:${а.аят} p${п.номер}`;
      assert.equal(п.номер, i + 1);
      assert.ok(п.оценкаСек <= ПРЕДЕЛ_СЕРВИСА_СЕК || п.слов <= 2, где);
      if (п.конец === 'вынужденная' || п.сВозвратом) assert.ok(п.оценкаСек <= ЦЕЛЬ_СЕК || п.слов <= 2, где);
      const слова = ток.slice(п.токенС, п.токенПо + 1).filter((т) => т.вид === 'слово').map((т) => т.номерСлова);
      assert.deepEqual(слова, Array.from({ length: п.слов }, (_, к) => п.словоС + к), где);
      for (let к = п.токенС; к < п.токенПо; к++) assert.ok(!(ток[к].вид === 'знак' && ток[к].знак === 'лязим'), где + ' через ۘ');
      if (i > 0) {
        const пред = ч[i - 1];
        assert.equal(п.сВозвратом, пред.конец === 'вынужденная', где);
        assert.equal(п.словоС, пред.словоС + пред.слов - (п.сВозвратом ? 1 : 0), где);
        if (!п.сВозвратом) assert.equal(п.токенС, пред.токенПо + 1, где);
      }
      if (п.конец === 'остановка') assert.ok(п.знакВКонце && ['лязим', 'кыля', 'сыля', 'джаиз'].includes(п.знакВКонце), где);
      if (п.конец !== 'остановка') assert.equal(п.знакВКонце, null, где);
      if (п.конец === 'вынужденная') вынужденных += 1;
      всего += 1;
    });
  }
  console.log(`    частей ${всего}, вынужденных остановок ${вынужденных}, аятов с частями ${ВСЕ_АЯТЫ.filter((а) => части(а.сура, а.аят).length > 1).length}`);
});
