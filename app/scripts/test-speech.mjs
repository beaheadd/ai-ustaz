#!/usr/bin/env node
/**
 * Тест чистых функций проверки голосом (без браузера и без сервиса): node scripts/test-speech.mjs
 *   speech/wavEncode.ts — WAV PCM16 16 кГц моно (заголовок, отсчёты, обрезка, смешение каналов);
 *   speech/flag.ts      — проверкаРазрешенаДля: на batr.kz и поддоменах всегда false, без флага false;
 *   speech/answer.ts    — разобратьОтвет: уровни только «проверьте»/«подсказка», фрагмент только из текста на экране,
 *                         фонемы не проходят, плохой звук, мусор → «недоступно»;
 *   speech/hints.ts     — шаблоны: без «Ошибка/неправильно/неверно/верно», мадд со счётами, S5 для мунфасиля.
 * Модули — TypeScript без импортов (кроме `import type`): node ≥ 22.18 снимает типы сам
 * (на 22.6–22.17 — запуск с --experimental-strip-types).
 */
import assert from 'node:assert/strict';

const { закодироватьWav, смешатьВМоно, ЧАСТОТА_ПРОВЕРКИ } = await import('../src/speech/wavEncode.ts');
const { проверкаРазрешенаДля } = await import('../src/speech/flag.ts');
const { разобратьОтвет, МАКС_ЗАМЕЧАНИЙ } = await import('../src/speech/answer.ts');
const { текстЗамечания, текстБезЗамечаний, текстПлохогоЗвука, текстОшибкиПроверки, счётаRu } = await import('../src/speech/hints.ts');

let проверок = 0;
function тест(имя, ф) {
  ф();
  проверок += 1;
  console.log('  ✓ ' + имя);
}

console.log('wavEncode');
тест('заголовок RIFF/WAVE, PCM, 1 канал, 16 кГц, 16 бит', () => {
  const б = закодироватьWav(new Float32Array([0, 0.5, -0.5, 1, -1]), ЧАСТОТА_ПРОВЕРКИ);
  const в = new DataView(б);
  const стр = (с, н) => String.fromCharCode(...new Uint8Array(б, с, н));
  assert.equal(б.byteLength, 44 + 5 * 2);
  assert.equal(стр(0, 4), 'RIFF');
  assert.equal(в.getUint32(4, true), 36 + 10);
  assert.equal(стр(8, 4), 'WAVE');
  assert.equal(стр(12, 4), 'fmt ');
  assert.equal(в.getUint16(20, true), 1);
  assert.equal(в.getUint16(22, true), 1);
  assert.equal(в.getUint32(24, true), 16000);
  assert.equal(в.getUint32(28, true), 32000);
  assert.equal(в.getUint16(32, true), 2);
  assert.equal(в.getUint16(34, true), 16);
  assert.equal(стр(36, 4), 'data');
  assert.equal(в.getUint32(40, true), 10);
  assert.deepEqual([0, 1, 2, 3, 4].map((i) => в.getInt16(44 + i * 2, true)), [0, 16384, -16384, 32767, -32768]);
});
тест('обрезка за [-1, 1] и NaN/∞ → 0', () => {
  const в = new DataView(закодироватьWav(new Float32Array([2, -3, NaN, Infinity]), 16000));
  assert.deepEqual([0, 1, 2, 3].map((i) => в.getInt16(44 + i * 2, true)), [32767, -32768, 0, 0]);
});
тест('пустая запись — только заголовок; неверная частота — исключение', () => {
  assert.equal(закодироватьWav(new Float32Array(0), 16000).byteLength, 44);
  assert.throws(() => закодироватьWav(new Float32Array(1), 0));
});
тест('смешатьВМоно: среднее каналов, по короткому; один канал — копия', () => {
  assert.deepEqual([...смешатьВМоно([new Float32Array([1, 0, 1]), new Float32Array([0, 0])])], [0.5, 0]);
  const один = new Float32Array([0.25, -0.25]);
  const копия = смешатьВМоно([один]);
  assert.deepEqual([...копия], [0.25, -0.25]);
  assert.notEqual(копия, один);
  assert.equal(смешатьВМоно([]).length, 0);
});

console.log('flag');
тест('без флага — выключено везде', () => {
  for (const х of ['localhost', '127.0.0.1', 'aiustaz.kz']) {
    assert.equal(проверкаРазрешенаДля(х, undefined), false);
    assert.equal(проверкаРазрешенаДля(х, '0'), false);
    assert.equal(проверкаРазрешенаДля(х, 'true'), false);
  }
});
тест('с флагом: batr.kz, www.batr.kz, поддомены, регистр и точка в конце — всегда выключено', () => {
  for (const х of ['batr.kz', 'www.batr.kz', 'WWW.BATR.KZ', 'batr.kz.', 'analytics.batr.kz', '', '  ']) assert.equal(проверкаРазрешенаДля(х, '1'), false, х);
});
тест('с флагом: свой домен и localhost/127.0.0.1 — включено; похожие на batr имена — не batr', () => {
  for (const х of ['localhost', '127.0.0.1', 'aiustaz.kz', 'www.aiustaz.kz', 'notbatr.kz', 'batr.kz.example.org']) assert.equal(проверкаРазрешенаДля(х, '1'), true, х);
});
тест('aiustaz.pro и www — включено и без флага (та же сборка, что batr.kz/aiustaz); похожие имена — нет', () => {
  for (const х of ['aiustaz.pro', 'www.aiustaz.pro', 'AIUSTAZ.PRO', 'aiustaz.pro.']) {
    assert.equal(проверкаРазрешенаДля(х, undefined), true, х);
    assert.equal(проверкаРазрешенаДля(х, '1'), true, х);
  }
  for (const х of ['aiustaz.pro.batr.kz', 'evil-aiustaz.pro', 'aiustaz.pro.example.org', 'm.aiustaz.pro']) assert.equal(проверкаРазрешенаДля(х, undefined), false, х);
  assert.equal(проверкаРазрешенаДля('aiustaz.pro.batr.kz', '1'), false, 'поддомен batr.kz — никогда');
});

console.log('answer');
const ТЕКСТ = 'خَلَقَ، مِثْلُ، صَبْرْ';
const ЭТАЛОН = 'خَلَقَ مِثْلُ صَبْرْ';
const фр = (ф) => [ЭТАЛОН.indexOf(ф), ЭТАЛОН.indexOf(ф) + ф.length];
const замечание = (доп) => ({ код: 'B1', вид: 'огласовка', уровень: 'проверьте', позиция: фр('مِثْلُ'), фрагмент: 'مِثْلُ', ожидалось: 'mi', услышано: 'ma', счёт_ожидался: null, счёт_услышан: null, правила: [], уверенность: 3.1, ...доп });
const ответ = (замечания) => ({ статус: 'ок', эталон: { текст: ЭТАЛОН, фонемы: 'xalaqa' }, услышано: { фонемы: 'xalaqa', уверенность_ср: 0.9 }, замечания });
тест('замечание: фрагмент из текста на экране, фонемы не проходят', () => {
  const и = разобратьОтвет(ответ([замечание()]), ТЕКСТ);
  assert.equal(и.вид, 'ответ');
  assert.deepEqual(и.замечания, [{ код: 'B1', вид: 'огласовка', уровень: 'проверьте', фрагмент: 'مِثْلُ', счётОжидался: null, счётУслышан: null }]);
});
тест('уровень «ошибка»/незнакомый → «проверьте»; «подсказка» остаётся', () => {
  const и = разобратьОтвет(ответ([замечание({ уровень: 'ошибка' }), замечание({ уровень: 'подсказка', позиция: фр('صَبْرْ'), фрагмент: 'صَبْرْ' })]), ТЕКСТ);
  assert.deepEqual(и.замечания.map((з) => з.уровень), ['проверьте', 'подсказка']);
});
тест('фрагмент не совпал с позицией, не входит в текст на экране или текста нет — null', () => {
  assert.equal(разобратьОтвет(ответ([замечание({ позиция: [0, 3] })]), ТЕКСТ).замечания[0].фрагмент, null);
  const чужой = 'مِثْلُ';
  assert.equal(разобратьОтвет(ответ([замечание()]), 'أَ إِ أُ').замечания[0].фрагмент, null);
  assert.equal(разобратьОтвет(ответ([замечание()]), null).замечания[0].фрагмент, null);
  assert.equal(разобратьОтвет(ответ([замечание({ фрагмент: чужой + 'x' })]), ТЕКСТ).замечания[0].фрагмент, null);
});
тест('счёта: целые 0..99, мусор → null; не больше МАКС_ЗАМЕЧАНИЙ, по порядку в тексте', () => {
  const и = разобратьОтвет(ответ([замечание({ счёт_ожидался: 4.4, счёт_услышан: 'два' }), замечание({ позиция: фр('خَلَقَ'), фрагмент: 'خَلَقَ' }), замечание(), замечание()]), ТЕКСТ);
  assert.equal(и.замечания.length, МАКС_ЗАМЕЧАНИЙ);
  assert.equal(и.замечания[0].фрагмент, 'خَلَقَ');
  assert.equal(и.замечания[1].счётОжидался, 4);
  assert.equal(и.замечания[1].счётУслышан, null);
});
тест('плохой звук — с причиной; незнакомая причина — «другое»', () => {
  assert.deepEqual(разобратьОтвет({ статус: 'плохой_звук', причина: 'тихо' }, ТЕКСТ), { вид: 'плохой-звук', причина: 'тихо' });
  assert.deepEqual(разобратьОтвет({ статус: 'плохой_звук', причина: 'шум?' }, ТЕКСТ), { вид: 'плохой-звук', причина: 'другое' });
});
тест('мусор и HTML вместо JSON-объекта — «недоступно»; пустые замечания — ответ без замечаний', () => {
  for (const д of [null, 'html', 42, {}, { статус: 'ок' }, { статус: 'что-то' }]) assert.deepEqual(разобратьОтвет(д, ТЕКСТ), { вид: 'ошибка', ошибка: 'недоступно' });
  assert.deepEqual(разобратьОтвет(ответ([]), ТЕКСТ), { вид: 'ответ', замечания: [] });
});

console.log('hints');
// \b в JS не работает с кириллицей — границы слова пишем явно.
const ЗАПРЕТНОЕ = /[Оо]шибк|[Нн]еправильн|[Нн]еверн|(^|[^а-яё])[Вв]ерно([^а-яё]|$)|Отлично|грех|харам|недействител|[Ққ]ате/;
const базовое = { код: 'C1.табии', вид: 'мадд', уровень: 'проверьте', фрагмент: 'قَالَ', счётОжидался: 2, счётУслышан: 1 };
тест('мадд: «Проверьте себя: в «…» мадд — тяните на N счёта, у вас прозвучало около M»', () => {
  assert.equal(текстЗамечания(базовое, 'ru'), 'Проверьте себя: в «قَالَ» мадд — тяните на 2 счёта, у вас прозвучало около 1.');
  assert.match(текстЗамечания({ ...базовое, код: 'C1.лязим', счётОжидался: 6, счётУслышан: 2 }, 'ru'), /на 6 счётов, у вас прозвучало около 2/);
  assert.match(текстЗамечания({ ...базовое, фрагмент: null }, 'ru'), /^Проверьте себя: в одном месте мадд/);
  assert.match(текстЗамечания(базовое, 'kk'), /^Өзіңізді тексеріңіз: «قَالَ» тұсында мәд бар — 2 харакатқа созыңыз/);
});
тест('мунфасиль на 2 — «Подсказка» по S5 (Тайиба), без штрафа', () => {
  const т = текстЗамечания({ ...базовое, код: 'C1.мунфасиль', уровень: 'подсказка', счётУслышан: 2, счётОжидался: 4 }, 'ru');
  assert.match(т, /^Подсказка: вы читаете мунфасиль на 2 счёта\. Так читают по некоторым путям «Тайибат ан-нашр»/);
  assert.match(т, /Шатибийя/);
  assert.match(текстЗамечания({ ...базовое, код: 'C1.мунфасиль', уровень: 'подсказка' }, 'kk'), /^Кеңес: сіз мунфасил/);
});
тест('все виды и коды, оба языка: без запретных слов, не длиннее 240 символов', () => {
  const коды = [['A1', 'буква'], ['A2', 'буква'], ['A3', 'буква'], ['B1', 'огласовка'], ['C1.табии', 'мадд'], ['C1.муттасиль', 'мадд'], ['C2', 'мадд'], ['D2', 'гунна'], ['E1', 'идгам'], ['F1', 'калькаля'], ['F3', 'калькаля'], ['T', 'таджвид'], ['Z9', 'новый']];
  for (const [код, вид] of коды)
    for (const уровень of ['проверьте', 'подсказка'])
      for (const фрагмент of ['مِثْلُ', null])
        for (const язык of ['ru', 'kk']) {
          const т = текстЗамечания({ код, вид, уровень, фрагмент, счётОжидался: 4, счётУслышан: 2 }, язык);
          assert.ok(!ЗАПРЕТНОЕ.test(т), т);
          assert.ok(т.length <= 240, т);
          assert.match(т, язык === 'ru' ? /^(Проверьте себя|Подсказка): / : /^(Өзіңізді тексеріңіз|Кеңес): /, т);
        }
});
тест('нет замечаний, плохой звук, сбой сервиса — без «Ошибка» и похвалы «верно»', () => {
  assert.equal(текстБезЗамечаний('ru'), 'Мы не услышали расхождений. Проверка ИИ может ошибаться.');
  for (const язык of ['ru', 'kk']) {
    for (const п of ['коротко', 'длинно', 'тихо', 'перегруз', 'испорчено', 'другое']) {
      const т = текстПлохогоЗвука(п, язык);
      assert.ok(!/Ошибк|неправильн|Қате/.test(т), т);
      assert.match(т, язык === 'ru' ? /это не ошибка/i : /бұл қате емес/i, т);
    }
    for (const о of ['нет-сети', 'занят', 'таймаут', 'запись', 'большая', 'недоступно']) assert.ok(текстОшибкиПроверки(о, язык).length > 10);
  }
  assert.match(текстПлохогоЗвука('тихо', 'ru'), /^Плохо слышно: .*запишите ещё раз/);
});
тест('счётаRu: 1 счёт, 2 счёта, 5 счётов, 11 счётов, 21 счёт', () => {
  assert.deepEqual([1, 2, 4, 5, 6, 11, 12, 21, 22].map(счётаRu), ['1 счёт', '2 счёта', '4 счёта', '5 счётов', '6 счётов', '11 счётов', '12 счётов', '21 счёт', '22 счёта']);
});

