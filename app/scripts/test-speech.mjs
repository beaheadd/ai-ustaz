тест('заголовок RIFF/WAVE, PCM, 1 канал, 16 кГц, 16 бит', () => {
  const б = закодироватьWav(new Float32Array([0, 0.5, -0.5, 1, -1]), ЧАСТОТА_ПРОВЕРКИ);
  const в = new DataView(б);
  const стр = (с, н) => String.fromCharCode(...new Uint8Array(б, с, н));
  assert.equal(б.byteLength, 44 + 5 * 2);
  assert.equal(стр(0, 4), 'RIFF');
  assert.equal(в.getUint32(4, true), 36 + 10);
  assert.equal(стр(8, 4), 'WAVE');
  assert.equal(стр(12, 4), 'fmt ');
  assert.equal(в.getUint16(20, true), 1);
  assert.equal(в.getUint16(22, true), 1);
  assert.equal(в.getUint32(24, true), 16000);
  assert.equal(в.getUint32(28, true), 32000);
  assert.equal(в.getUint16(32, true), 2);
  assert.equal(в.getUint16(34, true), 16);
  assert.equal(стр(36, 4), 'data');
  assert.equal(в.getUint32(40, true), 10);
  assert.deepEqual([0, 1, 2, 3, 4].map((i) => в.getInt16(44 + i * 2, true)), [0, 16384, -16384, 32767, -32768]);
});
