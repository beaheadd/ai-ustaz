    await п.э('урок-после-намаза-скрыть').click();
    п.проверить(!(await п.есть('урок-после-намаза')), '«Не сейчас» скрывает приглашение');
    await стр.reload();
    await п.э('карточка-намаза').waitFor();
    п.проверить(!(await п.есть('урок-после-намаза')), 'после перезагрузки приглашение до следующего намаза не возвращается');

    await п.э('намаз-кибла').click();
    await стр.waitForFunction(() => location.hash === '#/qibla');
    п.проверить(true, '«Кибла» → #/qibla');
    await стр.goBack();
    await п.э('карточка-намаза').waitFor();

