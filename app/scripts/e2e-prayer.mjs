    await п.э('город-поиск').fill('xyzq');
    await п.э('город-ничего').waitFor();
    п.проверить(await п.есть('город-ничего'), 'поиск без результата (и в своих списках, и по миру) — «Ничего не нашли»');
    await п.э('город-поиск').fill('');
