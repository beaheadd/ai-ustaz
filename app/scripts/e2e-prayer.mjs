    п.проверить(!/хиджр|недействит/i.test(весь), 'нет хиджры и слов о действительности намаза');
    п.проверить((await стр.getByTestId(/^неделя-\d{4}-\d\d-\d\d$/).count()) === 8, 'таблица: сегодня и ещё 7 дней');
    п.проверить((await п.текстЭ(`неделя-${сдвигДня(ДЕНЬ, 1)}-maghrib`)) === чч_мм(завтра.maghrib), 'таблица: магриб завтра = расчёт');
    await п.безГоризонтальнойПрокрутки('#/prayer');
    await п.снимок('01-время-намаза-ru-светлая');
    await п.снимокВесь('02-время-намаза-ru-светлая-весь');

    п.проверить(await п.есть('урок-после-намаза'), '«5 минут урока?» — 35 мин после зухра');
    await п.э('урок-после-намаза-перейти').click();
    await стр.waitForFunction(() => /^#\/lesson/.test(location.hash));
    п.проверить(true, `«К уроку» → ${await стр.evaluate(() => location.hash)}`);
    await стр.goBack();
