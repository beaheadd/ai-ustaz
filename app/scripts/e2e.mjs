/** multipart → { поле: Buffer } (только для теста подмены сервиса). */
function разобратьMultipart(тело, contentType) {
  const граница = contentType.match(/boundary=(?:"([^"]+)"|([^;]+))/i);
  const разделитель = Buffer.from('--' + (граница[1] ?? граница[2]));
  const поля = {};
  let начало = тело.indexOf(разделитель);
  while (начало >= 0) {
    const следующее = тело.indexOf(разделитель, начало + разделитель.length);
    if (следующее < 0) break;
    const часть = тело.subarray(начало + разделитель.length + 2, следующее - 2);
    const конецЗаголовков = часть.indexOf('\r\n\r\n');
    const заголовки = часть.subarray(0, конецЗаголовков).toString('utf8');
    const имя = заголовки.match(/name="([^"]+)"/)?.[1];
    if (имя) поля[имя] = часть.subarray(конецЗаголовков + 4);
    начало = следующее;
  }
  return поля;
}

