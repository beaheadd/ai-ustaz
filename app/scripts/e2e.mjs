function тихийWav() {
  const частота = 8000;
  const отсчётов = частота / 5;
  const б = Buffer.alloc(44 + отсчётов * 2);
  б.write('RIFF', 0); б.writeUInt32LE(36 + отсчётов * 2, 4); б.write('WAVE', 8); б.write('fmt ', 12);
  б.writeUInt32LE(16, 16); б.writeUInt16LE(1, 20); б.writeUInt16LE(1, 22); б.writeUInt32LE(частота, 24);
  б.writeUInt32LE(частота * 2, 28); б.writeUInt16LE(2, 32); б.writeUInt16LE(16, 34); б.write('data', 36); б.writeUInt32LE(отсчётов * 2, 40);
  return б;
}

/** Подменить чанк content/media.json в ответе сервера: клип для урока 2 и/или «разрешено» у всех авторов. */
async function подменитьМедиа(контекст, { клип = null, разрешить = false } = {}) {
  const счёт = { чанков: 0, клипов: 0, разрешений: 0, звуков: 0 };
  await контекст.route(/\/_expo\/static\/js\/web\/media-[0-9a-f]+\.js$/, async (маршрут) => {
    const ответ = await маршрут.fetch();
    let тело = await ответ.text();
    счёт.чанков += 1;
    if (клип) {
      // Минификатор снимает кавычки с ключей (id:"L02"); с ecma 2020 (metro.config.js) — и с кириллических
      // (аудио:[]); прежние сборки оставляли их в кавычках ("аудио":[]) — принимаем оба вида.
      const урок = тело.search(/"?id"?:"L02"/);
      const после = урок < 0 ? null : /(?<=[{,])"?аудио"?:\[\]/.exec(тело.slice(урок));
      if (!после) счёт.ошибка = 'чанк media: не найден урок L02 с аудио:[] — изменился формат сборки?';
      else {
        const пусто = урок + после.index;
        тело = тело.slice(0, пусто) + '"аудио":[' + JSON.stringify(клип) + ']' + тело.slice(пусто + после[0].length);
        счёт.клипов += 1;
      }
    }
    if (разрешить) {
      тело = тело.replace(/(?<=[{,])"?(разрешено|показывать)"?:(?:!1|false)/g, (_, к) => {
        счёт.разрешений += 1;
        return `"${к}":!0`;
      });
    }
    await маршрут.fulfill({ response: ответ, body: тело });
  });
  await контекст.route('**/aiustaz/media/test/**', async (маршрут) => {
    счёт.звуков += 1;
    await маршрут.fulfill({ status: 200, contentType: 'audio/wav', body: тихийWav() });
  });
  return счёт;
}

