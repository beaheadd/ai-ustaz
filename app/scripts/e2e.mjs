/** Записать себя в открытой <ПанельЗаписи>: пояснение (если ещё не было) → запись → стоп → послушать. */
async function записатьСебя(стр, п, где, { проверкаЕсть = false } = {}) {
  await п.э('запись-начать').click();
  try {
    await п.э('пояснение-микрофона').waitFor({ timeout: 1500 });
    п.проверить((await п.э('пояснение-микрофона').innerText()).length > 20, `${где}: перед первым запросом микрофона — пояснение`);
    await п.снимок('пояснение-микрофона');
    await п.э('микрофон-разрешить').click();
  } catch {
    /* пояснение уже было показано раньше */
  }
  await п.э('запись-идёт').waitFor({ timeout: 10000 });
  await стр.waitForTimeout(1200);
  await п.э('запись-стоп').click();
  await п.э('запись-готово').waitFor({ timeout: 10000 });
  п.проверить((await п.э('запись-готово').innerText()).includes('Записали!'), `${где}: «Записали! Послушайте себя.»`);
  п.проверить(await п.микрофонСвободен(), `${где}: после «Стоп» микрофон освобождён`);
  await п.э('запись-слушать').click();
  await стр.waitForTimeout(400);
  п.проверить(!ВЕРДИКТ.test(await п.текст()), `${где}: нет вердикта по голосу`);
  if (!проверкаЕсть) п.проверить(!(await п.есть('проверить-запись')), `${где}: кнопки «Проверить» нет (проверка голосом выключена)`);
}

/** Задание с выбором без оценки (урок 0): нажимать варианты по порядку, пока кнопка дальше не откроется. */
async function ответитьКакУгодно(стр, п, кнопка) {
  for (let i = 0; i < 6 && (await п.есть('вариант-' + i)); i++) {
    const в = п.э('вариант-' + i);
    if ((await в.getAttribute('aria-disabled')) === 'true') continue;
    await в.click();
    if (await п.открыто(кнопка, 800)) return;
  }
}

/** Низ элемента выше верха нижней панели (элемент не спрятан под ней). */
async function надПанелью(стр, id) {
  return стр.evaluate((т) => {
    const э = document.querySelector(`[data-testid="${т}"]`);
    const далее = document.querySelector('[data-testid="урок-далее"]') ?? document.querySelector('[data-testid="лестница-следующая"]');
    if (!э || !далее) return { ок: false, что: 'нет элемента' };
    const панель = далее.parentElement?.getBoundingClientRect() ?? далее.getBoundingClientRect();
    const р = э.getBoundingClientRect();
    return { ок: р.bottom <= панель.top + 1 && р.top >= 0, что: `низ ${Math.round(р.bottom)}, верх панели ${Math.round(панель.top)}` };
  }, id);
}

/**
 * Пройти задания открытого урока (после «Начать урок») верными ответами из JSON урока.
 * записывать — записывать себя в заданиях «запись»; снимки — префикс имён снимков (первое задание каждого вида).
 * Возвращает число заданий «выбор». На каждом задании: плашка на месте, нет горизонтальной прокрутки.
 */
async function пройтиЗадания(стр, п, урок, { записывать = false, снимки = null } = {}) {
  const { э, проверить } = п;
  const задания = урок.задания;
  const сняты = new Set();
  let выборов = 0;
  for (let i = 0; i < задания.length; i++) {
    const з = задания[i];
    const где = `урок ${урок.номер}, задание ${i + 1}/${задания.length} (${з.тип}${з.вид ? ', ' + з.вид : ''})`;
    await э('задание-' + (i + 1)).waitFor({ timeout: 8000 });
    await стр.waitForTimeout(60);
    проверить(await п.виден('плашка-прототипа'), `${где}: плашка на месте`);
    await п.безГоризонтальнойПрокрутки(где);
    const имяСнимка = снимки ? снимки + з.тип + (з.вид ? '-' + з.вид : '') : null;
    const снять = async () => {
      if (имяСнимка && !сняты.has(имяСнимка)) {
        сняты.add(имяСнимка);
        await п.снимок(имяСнимка);
      }
    };
    switch (з.тип) {
      case 'теория':
      case 'знакомство':
        await снять();
        await э('урок-далее').click();
        break;
      case 'выбор': {
        выборов += 1;
        проверить((await э('урок-далее').getAttribute('aria-disabled')) === 'true', '  «Далее» закрыто до ответа');
        if (з.вид === 'собери' && (await п.есть('знак-0'))) {
          await э('знак-' + з.верный).click();
          await э('собери-проверить').click();
        } else {
          await э('вариант-' + з.верный).click();
        }
        await э('ответ-верно').waitFor({ timeout: 4000 });
        await п.безГоризонтальнойПрокрутки(где + ' после ответа');
        await стр.waitForFunction(() => {
          const э = document.querySelector('[data-testid="ответ-верно"]');
          const д = document.querySelector('[data-testid="урок-далее"]');
          return э && д && э.getBoundingClientRect().bottom <= (д.parentElement ?? д).getBoundingClientRect().top + 1;
        }, null, { timeout: 3000 }).catch(() => {});
        const над = await надПанелью(стр, 'ответ-верно');
        проверить(над.ок, '  «Верно!» видно над нижней панелью (' + над.что + ')');
        await снять();
        await э('урок-далее').click();
        break;
      }
      case 'прочитай': {
        проверить(await п.открыто('урок-далее', 1500), '  «Прочитай»: нижняя кнопка открыта сразу');
        const надпись = await э('урок-далее').innerText();
        проверить(i === задания.length - 1 || /Прочитал/.test(надпись), `  «Прочитай»: нижняя кнопка «${надпись.trim()}»`);
        if (await п.есть('подсказка')) {
          await э('подсказка').click();
          await э('транскрипция-0').waitFor({ timeout: 3000 });
        }
        await п.безГоризонтальнойПрокрутки(где + ' с подсказкой');
        await снять();
        await э('урок-далее').click();
        break;
      }
      case 'запись':
        проверить(await п.открыто('урок-далее'), '  запись: «Далее» открыто и без записи (вердикта нет)');
        if (записывать) await записатьСебя(стр, п, где);
        await снять();
        await э('урок-далее').click();
        break;
      case 'лестница':
        for (let к = 1; к < з.ступени.length; к++) {
          проверить(await п.виден('лестница-следующая'), `  лестница, ступень ${к}: нижняя кнопка — «Следующая ступень»`);
          await э('лестница-следующая').click();
          await п.безГоризонтальнойПрокрутки(где + ', ступень ' + (к + 1));
        }
        проверить(await п.открыто('урок-далее', 1500), '  лестница: на последней ступени нижняя кнопка ведёт дальше');
        await снять();
        await э('урок-далее').click();
        break;
      default:
        throw new Error('неизвестный тип задания: ' + з.тип);
    }
  }
  return выборов;
}

