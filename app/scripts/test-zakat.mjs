#!/usr/bin/env node
/**
 * Тест калькулятора закята (без браузера): node scripts/test-zakat.mjs  (npm run test:zakat)
 *   zakat/calc.ts — нисаб по серебру (по умолчанию) и по золоту, вычет долгов, ниже нисаба, без хауля, нет цены
 *   металла, округление вверх до тенге, большие суммы (точно, без ошибок дробей), разбор и очистка ввода, формат «1 234 567 ₸».
 * Владелец 28.11.2026: «Нужно добавить калькулятор закята. Назвать нужно „Закят“». Правила счёта — черновик для устаза.
 * Модуль — TypeScript: node ≥ 22.18 снимает типы сам.
 */
import assert from 'node:assert/strict';

const з = await import('../src/zakat/calc.ts');
const { посчитатьЗакят, разобратьСумму, очиститьВвод, форматТенге, ПУСТОЙ_ВВОД, НИСАБ_ЗОЛОТО_Г, НИСАБ_СЕРЕБРО_Г } = з;

let проверок = 0;
function тест(имя, ф) {
  ф();
  проверок += 1;
  console.log('  ✓ ' + имя);
}
const ввод = (ч) => ({ ...ПУСТОЙ_ВВОД, ...ч });
// Цены в тестах — условные (в приложении цен нет: их вводит человек).
const ЗОЛОТО = 40_000;
const СЕРЕБРО = 500;

console.log('закят: нисаб');
тест('нисаб в граммах: 85 г золота и 595 г серебра; по умолчанию — серебро, хауль не отмечен', () => {
  assert.equal(НИСАБ_ЗОЛОТО_Г, 85);
  assert.equal(НИСАБ_СЕРЕБРО_Г, 595);
  assert.equal(ПУСТОЙ_ВВОД.нисабПо, 'серебро');
  assert.equal(ПУСТОЙ_ВВОД.хауль, false);
});
тест('по серебру: 595 × 500 = 297 500 ₸; 1 000 000 ₸ наличными → закят 25 000 ₸', () => {
  const и = посчитатьЗакят(ввод({ наличные: 1_000_000, ценаСеребра: СЕРЕБРО, ценаЗолота: ЗОЛОТО, хауль: true }));
  assert.equal(и.нисабСереброТг, 297_500);
  assert.equal(и.нисабЗолотоТг, 3_400_000);
  assert.equal(и.нисабТг, 297_500);
  assert.equal(и.нисабДостигнут, true);
  assert.equal(и.причина, 'закят');
  assert.equal(и.закят, 25_000);
});
тест('по золоту: та же сумма 1 000 000 ₸ ниже нисаба 85 × 40 000 = 3 400 000 ₸ → не обязателен', () => {
  const и = посчитатьЗакят(ввод({ наличные: 1_000_000, ценаСеребра: СЕРЕБРО, ценаЗолота: ЗОЛОТО, нисабПо: 'золото', хауль: true }));
  assert.equal(и.нисабТг, 3_400_000);
  assert.equal(и.нисабДостигнут, false);
  assert.equal(и.причина, 'ниже-нисаба');
  assert.equal(и.закят, 0);
});
тест('ровно нисаб — достигнут (≥): 297 500 ₸ → закят 7 438 ₸ (7 437,5 вверх)', () => {
  const и = посчитатьЗакят(ввод({ счета: 297_500, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.нисабДостигнут, true);
  assert.equal(и.закят, 7_438);
});
тест('на тиын ниже нисаба — не достигнут', () => {
  const и = посчитатьЗакят(ввод({ счета: 297_499.99, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.причина, 'ниже-нисаба');
  assert.equal(и.закят, 0);
});
тест('нет цены грамма металла выбранного нисаба → «нет-цены», закята нет; цена другого металла не подменяет', () => {
  assert.equal(посчитатьЗакят(ввод({ наличные: 5_000_000, хауль: true })).причина, 'нет-цены');
  const и = посчитатьЗакят(ввод({ наличные: 5_000_000, ценаЗолота: ЗОЛОТО, хауль: true }));
  assert.equal(и.причина, 'нет-цены');
  assert.equal(и.нисабТг, null);
  assert.equal(и.нисабЗолотоТг, 3_400_000);
  assert.equal(и.закят, 0);
});

console.log('закят: имущество и долги');
тест('все статьи складываются: наличные, счета, золото г × цена, серебро г × цена, товары, долги вам', () => {
  const и = посчитатьЗакят(
    ввод({ наличные: 100_000, счета: 200_000, золотоГ: 10, ценаЗолота: ЗОЛОТО, сереброГ: 100, ценаСеребра: СЕРЕБРО, товары: 300_000, долгиВам: 50_000, хауль: true }),
  );
  assert.equal(и.золотоТг, 400_000);
  assert.equal(и.сереброТг, 50_000);
  assert.equal(и.имущество, 1_100_000);
  assert.equal(и.чистое, 1_100_000);
  assert.equal(и.закят, 27_500);
});
тест('ваши долги вычитаются: 1 000 000 − 400 000 = 600 000 → 15 000 ₸', () => {
  const и = посчитатьЗакят(ввод({ наличные: 1_000_000, вашиДолги: 400_000, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.вычет, 400_000);
  assert.equal(и.чистое, 600_000);
  assert.equal(и.закят, 15_000);
});
тест('долги опускают ниже нисаба: 400 000 − 200 000 = 200 000 < 297 500 → не обязателен', () => {
  const и = посчитатьЗакят(ввод({ наличные: 400_000, вашиДолги: 200_000, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.причина, 'ниже-нисаба');
  assert.equal(и.закят, 0);
});
тест('долги больше имущества → чистое 0 (не отрицательное), «пусто»', () => {
  const и = посчитатьЗакят(ввод({ наличные: 100_000, вашиДолги: 900_000, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.чистое, 0);
  assert.equal(и.вычет, 100_000);
  assert.equal(и.причина, 'пусто');
});
тест('граммы без цены — металл не посчитан и отмечен (нетЦеныЗолота / нетЦеныСеребра)', () => {
  const и = посчитатьЗакят(ввод({ золотоГ: 50, сереброГ: 700, ценаСеребра: СЕРЕБРО }));
  assert.equal(и.золотоТг, 0);
  assert.equal(и.нетЦеныЗолота, true);
  assert.equal(и.нетЦеныСеребра, false);
  assert.equal(и.сереброТг, 350_000);
});
тест('отрицательные и не числа считаются нулём', () => {
  const и = посчитатьЗакят(ввод({ наличные: -500, счета: Number.NaN, товары: Infinity, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.имущество, 0);
});

console.log('закят: хауль и округление');
тест('нисаб достигнут, но хауль не отмечен → «нет-хауля», закят 0', () => {
  const и = посчитатьЗакят(ввод({ наличные: 1_000_000, ценаСеребра: СЕРЕБРО }));
  assert.equal(и.нисабДостигнут, true);
  assert.equal(и.причина, 'нет-хауля');
  assert.equal(и.закят, 0);
});
тест('округление вверх до тенге: 300 001 / 40 = 7 500,025 → 7 501; 300 000 / 40 = 7 500 ровно', () => {
  assert.equal(посчитатьЗакят(ввод({ наличные: 300_001, ценаСеребра: СЕРЕБРО, хауль: true })).закят, 7_501);
  assert.equal(посчитатьЗакят(ввод({ наличные: 300_000, ценаСеребра: СЕРЕБРО, хауль: true })).закят, 7_500);
});
тест('дробные граммы и цены без ошибок дробей: 0,1 г серебра × 512,35 = 51,24 ₸; нисаб 595 × 512,35 = 304 848,25 → 304 849', () => {
  const и = посчитатьЗакят(ввод({ сереброГ: 0.1, ценаСеребра: 512.35, наличные: 304_848.25, хауль: true }));
  assert.equal(и.нисабСереброТг, 304_849);
  assert.equal(и.сереброТг, 51.24);
  assert.equal(и.нисабДостигнут, true);
  assert.equal(и.закят, Math.ceil((30_484_825 + 5_124) / 4000));
});
тест('большие суммы точно: 999 999 999 999 ₸ → 25 000 000 000 ₸ (999 999 999 999 / 40 = 24 999 999 999,975 вверх)', () => {
  const и = посчитатьЗакят(ввод({ счета: 999_999_999_999, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и.закят, 25_000_000_000);
  const и2 = посчитатьЗакят(ввод({ наличные: 1e12, счета: 1e12, товары: 1e12, долгиВам: 1e12, ценаСеребра: СЕРЕБРО, хауль: true }));
  assert.equal(и2.чистое, 4e12);
  assert.equal(и2.закят, 1e11);
});

console.log('закят: ввод и формат');
тест('разобратьСумму: пробелы любых видов, запятая, пусто → 0, мусор/минус/слишком много → null', () => {
  assert.equal(разобратьСумму(''), 0);
  assert.equal(разобратьСумму('   '), 0);
  assert.equal(разобратьСумму('1 234 567'), 1_234_567);
  assert.equal(разобратьСумму('1 234 567,5'), 1_234_567.5);
  assert.equal(разобратьСумму('12.75'), 12.75);
  assert.equal(разобратьСумму(',5'), 0.5);
  assert.equal(разобратьСумму('.5'), 0.5);
  assert.equal(разобратьСумму('-5'), null);
  assert.equal(разобратьСумму('12a'), null);
  assert.equal(разобратьСумму('1,2,3'), null);
  assert.equal(разобратьСумму('1000000000001'), null);
});
тест('очиститьВвод: цифры и одна дробная часть, разряды пробелом, ведущие нули убраны', () => {
  assert.equal(очиститьВвод('1234567', 2), '1 234 567');
  assert.equal(очиститьВвод('1234567,891', 2), '1 234 567,89');
  assert.equal(очиститьВвод('12.5', 3), '12,5');
  assert.equal(очиститьВвод('007', 2), '7');
  assert.equal(очиститьВвод('abc', 2), '');
  assert.equal(очиститьВвод(',5', 2), '0,5');
  assert.equal(очиститьВвод('1,2,3', 2), '1,23');
  assert.equal(очиститьВвод('5,', 2), '5,');
  assert.equal(очиститьВвод('99,9', 0), '99');
  assert.equal(очиститьВвод('12345678901234567', 2), '1 234 567 890 123');
  assert.equal(разобратьСумму(очиститьВвод('1234567,891', 2)), 1_234_567.89);
});
тест('форматТенге: «1 234 567 ₸» с неразрывными пробелами; дробь — «12,50 ₸»; 0 → «0 ₸»', () => {
  assert.equal(форматТенге(1_234_567), '1 234 567 ₸');
  assert.equal(форматТенге(0), '0 ₸');
  assert.equal(форматТенге(999), '999 ₸');
  assert.equal(форматТенге(12.5), '12,50 ₸');
  assert.equal(форматТенге(25_000_000_000), '25 000 000 000 ₸');
});

console.log(`\nOK: калькулятор закята — ${проверок} проверок`);
