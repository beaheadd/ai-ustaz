function память(начальное = {}) {
  const м = new Map(Object.entries(начальное));
  return { getItem: (к) => (м.has(к) ? м.get(к) : null), setItem: (к, з) => м.set(к, String(з)), м };
}
const ответ = (код, тело) => async (адрес, параметры) => {
  assert.equal(адрес, '/api/zakat/prices');
  assert.equal(параметры.credentials, 'omit');
  return { ok: код === 200, json: async () => тело };
};
