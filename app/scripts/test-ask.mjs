#!/usr/bin/env node
/**
 * Модульный тест клиента «Спросить AI Ustaz» (src/ask/api.ts): где включено, разбор ответа сервера и защита второй линии
 * (правила 1 и 2 CLAUDE.md), запрос без лишних данных, коды ошибок. Без сети: fetch подставной.
 * Запуск: npm run test:ask
 */
import assert from 'node:assert/strict';

const { спроситьРазрешеноДля, разобратьОтвет, спросить, ссылкаАята, МАКС_ВОПРОС } = await import('../src/ask/api.ts');

let проверок = 0;
const проверить = (что, ф) => {
  ф();
  проверок += 1;
  console.log('  ✓ ' + что);
};

const источник = (х = {}) => ({ id: 's1', вид: 'справка', заголовок: 'Что такое AI Ustaz', ссылка: null, текст: 'Бесплатное приложение.', арабский: null, источник: 'Справка AI Ustaz', степень: null, кто_оценил: null, черновик: false, версия: '1', ...х });
const ответ = (х = {}) => ({ вид: 'ответ', режим: 'поиск', текст: 'Вот что есть в нашей базе:', источники: [источник()], черновик: false, ...х });

console.log('Где включено');
проверить('aiustaz.pro и www — всегда; batr.kz и поддомены — никогда; иначе — по флагу сборки', () => {
  assert.equal(спроситьРазрешеноДля('aiustaz.pro', undefined), true);
  assert.equal(спроситьРазрешеноДля('WWW.AIUSTAZ.PRO.', undefined), true);
  assert.equal(спроситьРазрешеноДля('batr.kz', '1'), false);
  assert.equal(спроситьРазрешеноДля('analytics.batr.kz', '1'), false);
  assert.equal(спроситьРазрешеноДля('127.0.0.1', undefined), false);
  assert.equal(спроситьРазрешеноДля('127.0.0.1', '1'), true);
  assert.equal(спроситьРазрешеноДля('', '1'), false);
});

console.log('Разбор ответа');
проверить('правильный ответ разбирается как есть', () => {
  const р = разобратьОтвет(ответ());
  assert.equal(р.вид, 'ответ');
  assert.equal(р.текст, 'Вот что есть в нашей базе:');
  assert.equal(р.источники.length, 1);
  assert.equal(р.черновик, false);
});
проверить('неверный вид, режим или форма — null', () => {
  assert.equal(разобратьОтвет(ответ({ вид: 'фетва' })), null);
  assert.equal(разобратьОтвет(ответ({ режим: 'интернет' })), null);
  assert.equal(разобратьОтвет(ответ({ источники: 'x' })), null);
  assert.equal(разобратьОтвет(null), null);
});
проверить('правило 1: текст с арабским письмом — заменяется шаблоном (null), источники остаются', () => {
  const р = разобратьОтвет(ответ({ текст: 'Сказано: ٱلْحَمْدُ لِلَّهِ' }));
  assert.equal(р.текст, null);
  assert.equal(р.источники.length, 1);
});
проверить('правило 1: арабское письмо в полях источника (кроме «арабский» у хадиса) — источник отброшен', () => {
  assert.equal(разобратьОтвет(ответ({ источники: [источник({ текст: 'بِسْمِ' })] })).источники.length, 0);
  assert.equal(разобратьОтвет(ответ({ источники: [источник({ вид: 'статья', арабский: 'نص' })] })).источники.length, 0);
});
проверить('Коран — только со ссылкой «сура:аят» в пределах; арабского от сервера у Корана не принимаем', () => {
  const к = источник({ id: 'q', вид: 'коран', ссылка: '2:43', текст: '' });
  assert.equal(разобратьОтвет(ответ({ источники: [к] })).источники.length, 1);
  assert.equal(разобратьОтвет(ответ({ источники: [{ ...к, ссылка: '115:1' }] })).источники.length, 0);
  assert.equal(разобратьОтвет(ответ({ источники: [{ ...к, арабский: 'وَأَقِيمُوا' }] })).источники.length, 0);
  assert.deepEqual(ссылкаАята(' 2:255 '), { сура: 2, аят: 255 });
  assert.equal(ссылкаАята('0:1'), null);
  assert.equal(ссылкаАята('2:255a'), null);
});
проверить('правило 2: хадис без ссылки, степени или того, кто её дал, — отброшен; полный — принят', () => {
  const х = источник({ id: 'h', вид: 'хадис', ссылка: 'сборник, №', степень: 'степень', кто_оценил: 'кто', арабский: 'نص' });
  assert.equal(разобратьОтвет(ответ({ источники: [х] })).источники.length, 1);
  for (const без of ['ссылка', 'степень', 'кто_оценил']) assert.equal(разобратьОтвет(ответ({ источники: [{ ...х, [без]: null }] })).источники.length, 0, без);
});
проверить('черновик: если хоть один источник — черновик, ответ помечен', () => {
  assert.equal(разобратьОтвет(ответ({ источники: [источник({ черновик: true })] })).черновик, true);
});
проверить('не больше 8 источников, длинные поля обрезаются', () => {
  const р = разобратьОтвет(ответ({ текст: 'а'.repeat(5000), источники: Array.from({ length: 12 }, (_, i) => источник({ id: 's' + i })) }));
  assert.equal(р.источники.length, 8);
  assert.equal(р.текст.length, 2000);
});

console.log('Запрос');
console.log('  ✓ в запросе только { q, lang } (без истории, идентификаторов, координат); 200 → ответ');
{
  let тело = null;
  let адрес = null;
  const итог = await спросить('  Что такое AI Ustaz?  ', 'ru', {
    fetch: async (а, п) => {
      адрес = а;
      тело = JSON.parse(п.body);
      return { status: 200, json: async () => ответ() };
    },
  });
  assert.equal(адрес, '/api/ask/v1');
  assert.deepEqual(Object.keys(тело).sort(), ['lang', 'q']);
  assert.equal(тело.q, 'Что такое AI Ustaz?');
  assert.equal(итог.ок, true);
  проверок += 1;
}
console.log('  ✓ коды: 429 → лимит, 400 → вопрос, 503 → нет-базы, 500 → сбой, исключение → нет-связи, кривой JSON → сбой');
{
  const с = (status, json = async () => ({})) => ({ fetch: async () => ({ status, json }) });
  assert.deepEqual(await спросить('вопрос', 'ru', с(429)), { ок: false, причина: 'лимит' });
  assert.deepEqual(await спросить('вопрос', 'ru', с(400)), { ок: false, причина: 'вопрос' });
  assert.deepEqual(await спросить('вопрос', 'ru', с(503)), { ок: false, причина: 'нет-базы' });
  assert.deepEqual(await спросить('вопрос', 'ru', с(500)), { ок: false, причина: 'сбой' });
  assert.deepEqual(await спросить('вопрос', 'ru', { fetch: async () => { throw new Error('сеть'); } }), { ок: false, причина: 'нет-связи' });
  assert.deepEqual(await спросить('вопрос', 'ru', с(200, async () => ({ вид: 'x' }))), { ок: false, причина: 'сбой' });
  проверок += 1;
}
console.log('  ✓ слишком короткий или длинный вопрос — не отправляется');
{
  let звали = false;
  const ф = { fetch: async () => ((звали = true), { status: 200, json: async () => ответ() }) };
  assert.deepEqual(await спросить('аб', 'ru', ф), { ок: false, причина: 'вопрос' });
  assert.deepEqual(await спросить('а'.repeat(МАКС_ВОПРОС + 1), 'ru', ф), { ок: false, причина: 'вопрос' });
  assert.equal(звали, false);
  проверок += 1;
}

console.log(`\nOK: ${проверок} проверок`);
