/** Рамки (px от верха окна): плашка прототипа, карточка намаза, кнопка урока, меню; низ подписи «AI Ustaz · …». */
function геометрия(стр) {
  return стр.evaluate(() => {
    const р = (id) => {
      const б = document.querySelector(`[data-testid="${id}"]`)?.getBoundingClientRect();
      return б ? { верх: б.top, низ: б.bottom, высота: б.height } : null;
    };
    const подписьИИ = document.querySelector('[data-testid="главная-реплика"] div[dir="ltr"]');
    return {
      плашка: р('плашка-прототипа'),
      карточка: р('карточка-намаза'),
      кнопка: р('главная-начать'),
      меню: р('нижнее-меню'),
      подписьИИ: подписьИИ?.getBoundingClientRect().bottom ?? null,
      текстИИ: подписьИИ?.textContent ?? null,
      текстКнопки: document.querySelector('[data-testid="главная-начать"]')?.textContent ?? '',
    };
  });
}

/**
 * Подписи плиток: название и время — текст внутри плитки (не шире её содержимого), число строк; ярлык — внутри плитки,
 * не наезжает на название, строк. разрывСлова — строк названия больше, чем слов (слово разорвано посередине).
 */
function подписиПлиток(стр) {
  return стр.evaluate(() =>
    [...document.querySelectorAll('[data-testid="карточка-намаза"] [data-testid^="намаз-блок-"]')].map((б) => {
      const рб = б.getBoundingClientRect();
      const рамка = parseFloat(getComputedStyle(б).borderLeftWidth);
      const [назв, время] = б.querySelector(':scope > div[aria-hidden]:last-child').children;
      const текст = (е) => {
        const r = document.createRange();
        r.selectNodeContents(е);
        return r.getBoundingClientRect();
      };
      const строк = (е) => Math.round(е.getBoundingClientRect().height / parseFloat(getComputedStyle(е).lineHeight));
      const вне = (е) => {
        const т = текст(е);
        return т.left < рб.left + рамка - 0.5 || т.right > рб.right - рамка + 0.5 || е.scrollWidth > е.clientWidth + 1;
      };
      const я = б.querySelector('[data-testid^="намаз-метка-"]');
      const ря = я?.getBoundingClientRect();
      return {
        ключ: б.getAttribute('data-testid').slice('намаз-блок-'.length),
        название: назв.textContent,
        ширина: рб.width,
        обрезано: вне(назв) || вне(время),
        строкНазвания: строк(назв),
        строкВремени: строк(время),
        разрывСлова: строк(назв) > назв.textContent.trim().split(/\s+/).length || строк(время) > 1,
        ярлык: я
          ? {
              текст: я.textContent,
              внутри: ря.left >= рб.left - 0.5 && ря.right <= рб.right + 0.5 && !вне(я.firstElementChild ?? я),
              наезд: ря.bottom > назв.getBoundingClientRect().top + 1,
              строк: строк(я.firstElementChild ?? я),
            }
          : null,
      };
    }),
  );
}

