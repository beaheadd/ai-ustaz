async function новаяСтраница(браузер, база, { профиль = devices['iPhone 13'], язык = 'ru', схема = 'light', время, гео, разрешитьГео = false, ios = null, снимки = false } = {}) {
  const контекст = await браузер.newContext({
    ...профиль,
    deviceScaleFactor: снимки ? 2 : 1,
    colorScheme: схема,
    locale: 'ru-RU',
    timezoneId: 'Asia/Almaty',
    ...(гео ? { geolocation: гео } : {}),
    permissions: разрешитьГео ? ['geolocation'] : [],
  });
  await контекст.addInitScript(
    ({ прогресс, ios }) => {
      window.__csp = [];
      document.addEventListener('securitypolicyviolation', (е) => window.__csp.push(е.blockedURI + ' ' + е.violatedDirective));
      if (!localStorage.getItem('aiustaz:progress.v1')) localStorage.setItem('aiustaz:progress.v1', JSON.stringify(прогресс));
      if (ios && window.DeviceOrientationEvent) {
        window.__запросовРазрешения = 0;
        window.DeviceOrientationEvent.requestPermission = async () => {
          window.__запросовРазрешения += 1;
          return ios;
        };
      }
    },
    { прогресс: ПРОГРЕСС(язык), ios },
  );
  const стр = await контекст.newPage();
  if (время) await стр.clock.setFixedTime(new Date(время));
  const проблемы = [];
  стр.on('request', (з) => {
    const u = з.url();
    if (!u.startsWith(база + '/') && !u.startsWith('data:') && !u.startsWith('blob:')) проблемы.push('запрос на другой адрес: ' + u);
  });
  стр.on('console', (с) => {
    if (с.type() === 'error') проблемы.push('ошибка в консоли: ' + с.text());
  });
  стр.on('pageerror', (о) => проблемы.push('исключение на странице: ' + о.message));
  return { контекст, стр, проблемы };
}

function помощники(стр, проблемы, имя, папкаСнимков) {
  const э = (id) => стр.getByTestId(id).first();
  const есть = async (id) => (await стр.getByTestId(id).count()) > 0;
  const текстЭ = async (id) => (await э(id).innerText()).trim();
  const хэш = () => стр.evaluate(() => location.hash);
  const проверить = (условие, что) => {
    проверок += 1;
    if (!условие) throw new Error(`[главная: ${имя}] НЕ ВЫПОЛНЕНО: ${что}`);
    console.log(`  ✓ ${что}`);
  };
  const безПроблем = async (что) => {
    const csp = await стр.evaluate(() => window.__csp ?? []);
    for (const н of csp) проблемы.push('нарушение CSP: ' + н);
    const ключи = await стр.evaluate(() => Object.keys(localStorage));
    for (const к of ключи) if (!к.startsWith('aiustaz:')) проблемы.push('чужой ключ в localStorage: ' + к);
    const звук = await стр.evaluate(() => document.querySelectorAll('audio, video').length);
    if (звук) проблемы.push(`есть <audio>/<video>: ${звук}`);
    проверить(проблемы.length === 0, что + (проблемы.length ? ':\n      ' + проблемы.join('\n      ') : ''));
  };
  const безГоризонтальнойПрокрутки = async (где) => {
    const лишнее = await стр.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    проверить(лишнее <= 1, `${где}: нет горизонтальной прокрутки (лишние ${лишнее} px)`);
  };
  /** Снимок окна или (весь) всей прокручиваемой высоты: окно временно вытягивается до высоты содержимого. */
  const снимок = async (файл, весь = false) => {
    if (!папкаСнимков) return;
    await стр.waitForTimeout(250);
    const окно = стр.viewportSize();
    if (весь && окно) {
      const высота = await стр.evaluate(() =>
        Math.max(
          window.innerHeight,
          ...[...document.querySelectorAll('*')]
            .filter((е) => е.scrollHeight > е.clientHeight + 1 && getComputedStyle(е).overflowY !== 'visible')
            .map((е) => е.scrollHeight + (window.innerHeight - е.clientHeight)),
        ),
      );
      await стр.setViewportSize({ width: окно.width, height: Math.min(высота, 7000) });
      await стр.waitForTimeout(300);
    }
    await стр.screenshot({ path: path.join(папкаСнимков, файл + '.png') });
    if (весь && окно) await стр.setViewportSize(окно);
  };
  return { э, есть, текстЭ, хэш, проверить, безПроблем, безГоризонтальнойПрокрутки, снимок };
}

const вРК = (день, чм) => new Date(`${день}T${чм}:00+05:00`).toISOString();

/** Проверка шести блоков: порядок дня (восход — 2-й) и времена = расчёт. */
async function шестьБлоков(стр, п, времена, где) {
  const порядок = await стр.evaluate(() =>
    [...document.querySelectorAll('[data-testid="карточка-намаза"] [data-testid^="намаз-блок-"]')].map((е) => е.getAttribute('data-testid').slice('намаз-блок-'.length)),
  );
  п.проверить(JSON.stringify(порядок) === JSON.stringify(КЛЮЧИ_ВРЕМЁН) && порядок[1] === 'sunrise', `${где}: шесть блоков по порядку дня, восход — 2-й (${порядок.join(', ')})`);
  const расхождения = [];
  for (const к of КЛЮЧИ_ВРЕМЁН) {
    const т = await п.текстЭ('намаз-время-' + к);
    if (т !== чч_мм(времена[к])) расхождения.push(`${к}: ${т} ≠ ${чч_мм(времена[к])}`);
  }
  п.проверить(расхождения.length === 0, `${где}: все 6 времён = расчёт (${КЛЮЧИ_ВРЕМЁН.map((к) => чч_мм(времена[к])).join(' ')})` + (расхождения.length ? ': ' + расхождения.join('; ') : ''));
}

