/** Карточка намаза — зелёная арка (владелец 27.11.2026): у карточки поверхность «герой», заливка арки тёмная. */
async function зелёнаяАрка(стр) {
  return стр.evaluate(() => {
    const к = document.querySelector('[data-testid="карточка-намаза"]');
    const герой = !!к && (к.getAttribute('data-surface') === 'hero' || !!к.querySelector('[data-surface="hero"]') || !!к.closest('[data-surface="hero"]'));
    const заливка = к?.querySelector('svg path[fill]')?.getAttribute('fill') ?? '';
    const м = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(заливка);
    const я = м ? (0.2126 * parseInt(м[1], 16) + 0.7152 * parseInt(м[2], 16) + 0.0722 * parseInt(м[3], 16)) / 255 : 1;
    return { герой, заливка, тёмная: я < 0.35 };
  });
}

