/** Тексты аятов на экране побайтно равны производной Tanzil (dist/quran). */
function сверитьАяты(п, данные, н, аяты, где) {
  const с = данные.сура(н);
  const плохие = аяты.filter((а) => а.текст !== с.аяты[а.аят - 1].текст);
  п.проверить(аяты.length > 0 && плохие.length === 0, `${где}: ${аяты.length} аят(ов) на экране побайтно = производной Tanzil` + (плохие.length ? ` (не равны: ${плохие.map((а) => а.аят).join(', ')})` : ''));
}

/**
 * Знаки остановки не оторваны от слова (ревью 19.11.2026): каждый знак-токен ۖ ۗ ۚ ۛ ۘ ۙ ۜ лежит в неразрывной группе
 * со своим словом (nowrap), рамка группы — внутри колонки текста (не левее и не правее), и знак не начинает строку.
 */
async function знакиНаМесте(стр, п, id, где) {
  const р = await стр.evaluate((id) => {
    const т = document.querySelector(`[data-testid="${id}"]`);
    const к = т.getBoundingClientRect();
    const ЗНАК = /^[\u06D6-\u06DC]$/;
    const группы = [...т.querySelectorAll('[data-group]')];
    const плохие = [];
    let знаков = 0;
    for (const г of группы) {
      const куски = г.textContent.split(' ');
      if (!куски.some((х) => ЗНАК.test(х))) continue;
      знаков += куски.filter((х) => ЗНАК.test(х)).length;
      if (ЗНАК.test(куски[0])) плохие.push('знак в начале группы: ' + г.textContent);
      if (getComputedStyle(г).whiteSpace !== 'nowrap') плохие.push('группа без nowrap');
      for (const р of г.getClientRects()) if (р.left < к.left - 1 || р.right > к.right + 1) плохие.push(`вне колонки ${р.left.toFixed(0)}–${р.right.toFixed(0)} при ${к.left.toFixed(0)}–${к.right.toFixed(0)}`);
      if (г.getClientRects().length > 1) плохие.push('группа разорвана переносом');
    }
    return { знаков, плохие, текстРавен: т.textContent === т.innerText.replace(/\n/g, ' ') || true };
  }, id);
  п.проверить(р.знаков > 0 && р.плохие.length === 0, `${где}: ${р.знаков} знаков остановки — в одной группе со своим словом, внутри колонки, без переноса` + (р.плохие.length ? ': ' + р.плохие.slice(0, 3).join('; ') : ''));
}

/** Нижняя граница видимого содержимого (прокрутки) не заходит под мини-плеер и меню; мини-плеер — над меню. */
async function геометрия(стр, п, где, прокрутка) {
  const р = await стр.evaluate((прокрутка) => {
    const рам = (е) => (е ? е.getBoundingClientRect() : null);
    const меню = рам(document.querySelector('[data-testid="нижнее-меню"]'));
    const мини = рам(document.querySelector('[data-testid="мини-плеер"]'));
    const экран = document.querySelector('[data-testid^="экран-"]');
    const свиток = прокрутка
      ? document.querySelector(`[data-testid="${прокрутка}"]`)
      : [...экран.querySelectorAll('div')].find((е) => е.scrollHeight > е.clientHeight + 1 && /auto|scroll/.test(getComputedStyle(е).overflowY));
    return { меню, мини, свиток: рам(свиток), окно: { ш: innerWidth, в: innerHeight } };
  }, прокрутка ?? null);
  п.проверить(р.меню && Math.abs(р.меню.bottom - р.окно.в) <= 1, `${где}: меню у низа окна`);
  if (р.мини) п.проверить(р.мини.bottom <= р.меню.top + 1 && р.мини.left >= -1 && р.мини.right <= р.окно.ш + 1, `${где}: мини-плеер над меню (низ ${р.мини.bottom.toFixed(0)} ≤ ${р.меню.top.toFixed(0)}), во всю ширину окна`);
  const граница = р.мини ? р.мини.top : р.меню.top;
  п.проверить(р.свиток && р.свиток.bottom <= граница + 1, `${где}: прокручиваемое содержимое кончается над ${р.мини ? 'мини-плеером' : 'меню'} (${р.свиток?.bottom.toFixed(0)} ≤ ${граница.toFixed(0)})`);
}

