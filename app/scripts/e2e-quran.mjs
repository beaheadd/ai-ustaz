/**
 * Сборка с проверкой голосом (EXPO_PUBLIC_SPEECH_CHECK=1), 127.0.0.1: на экране аята есть «Проверить»; в запросе —
 * sura, aya, uthmani_from/uthmani_words части и kinds; ответ сервиса подменён: слово замечания подсвечено в аяте,
 * подсказка — «Проверьте себя: <слово из копии для показа>», без «Ошибка».
 */
export async function коранПроверкаГолосом(браузер, папка) {
  console.log('\n══ Коран: проверка голосом на экране аята (сборка с флагом) ══');
  const сервер = await запуститьСервер({ порт: 0, папка });
  const база = сервер.адрес;
  проверок = 0;
  try {
    const данные = данныеКорана(папка);
    const { контекст, стр, проблемы } = await новаяСтраница(браузер, база);
    const п = помощники(стр, проблемы, 'проверка голосом', null);
    const запросы = [];
    let ответ = null;
    await стр.route('**/api/speech/v1/proverka', async (маршрут) => {
      const з = маршрут.request();
      const тело = з.postDataBuffer() ?? Buffer.alloc(0);
      const тип = з.headers()['content-type'] ?? '';
      const граница = тип.match(/boundary=(?:"([^"]+)"|([^;]+))/i);
      const поля = {};
      for (const кусок of тело.toString('latin1').split('--' + (граница[1] ?? граница[2]))) {
        const м = /name="([^"]+)"[^]*?\r\n\r\n([^]*)\r\n$/.exec(кусок);
        if (м && м[1] !== 'audio') поля[м[1]] = Buffer.from(м[2], 'latin1').toString('utf8');
      }
      запросы.push(поля);
      await маршрут.fulfill(ответ);
    });
    await стр.goto(база + '/aiustaz/index.html#/quran/check?n=2&a=255&p=2');
    await п.э('часть-аята').waitFor({ timeout: 10000 });
    const [, с, по] = /слова (\d+)–(\d+)/.exec(await п.текстЭ('часть-аята')).map(Number);
    await п.э('запись-начать').click();
    await п.э('запись-идёт').waitFor({ timeout: 10000 });
    await стр.waitForTimeout(1200);
    await п.э('запись-стоп').click();
    await п.э('проверить-запись').waitFor({ timeout: 10000 });
    п.проверить(true, 'сборка своего домена: после записи аята есть «Проверить»');
    const слово = с + 1;
    const словаПоказа = данные.сура(2).аяты[254].текст.split(' ').filter((т) => !(т.length === 1 && /[ۖ-ۜ۞۩]/.test(т)));
    ответ = {
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({
        статус: 'ок',
        эталон: { текст: 'фонетика', фонемы: '', слово_с: с, слов: по - с + 1 },
        услышано: { фонемы: '', уверенность_ср: 0.8 },
        замечания: [{ код: 'B1', вид: 'огласовка', уровень: 'ошибка', позиция: [0, 1], фрагмент: 'x', слово, ожидалось: 'ءِ', услышано: 'ءَ', счёт_ожидался: null, счёт_услышан: null, правила: [], уверенность: 4.2 }],
        длительность_сек: 2,
        время_мс: 300,
      }),
    };
    await п.э('проверить-запись').click();
    await п.э('согласие-проверки-да').click();
    await п.э('итог-проверки').waitFor({ timeout: 15000 });
    const з = запросы[0] ?? {};
    п.проверить(
      з.sura === '2' && з.aya === '255' && з.uthmani_from === String(с) && з.uthmani_words === String(по - с + 1) && /\S/.test(з.kinds ?? '') && !з.text && !з.word_from,
      `запрос: sura=2, aya=255, uthmani_from=${з.uthmani_from}, uthmani_words=${з.uthmani_words}, kinds=${з.kinds}`,
    );
    const подсказка = await п.текстЭ('подсказка-проверки');
    п.проверить(подсказка.startsWith('Проверьте себя') && подсказка.includes(словаПоказа[слово - 1]) && !/Ошибка/.test(подсказка), `подсказка «Проверьте себя» со словом ${слово} из копии для показа (уровень «ошибка» сервиса не показан как «Ошибка»)`);
    п.проверить(await п.есть('аят-слово-' + слово), `слово ${слово} подсвечено в аяте (аят-слово-${слово})`);
    await п.безПроблем('проверка голосом на экране аята: без ошибок');
    await контекст.close();
  } finally {
    await сервер.закрыть();
  }
  console.log(`Коран, проверка голосом: ${проверок} проверок пройдено.`);
  return проверок;
}

