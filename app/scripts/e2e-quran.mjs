    п.проверить(/Tanzil Uthmani v1\.1, сверен по контрольной сумме/.test(await п.текстЭ('сура-источник')), 'меню вида: источник текста — Tanzil, сверка');
    await п.э('таджвид-урок-l').click();
    await п.экран('экран-карта', '#/course');
    п.проверить(true, '«Урок 31, 40» → карта курса');
    await стр.goBack();
    await стр.waitForFunction(() => document.querySelector('[data-ayah="2:1"]'), null, { timeout: 10000 });

