    for (let i = 0; i < 30 && !(await стр.evaluate(() => !!document.querySelector('[data-ayah="2:286"]'))); i++) {
      await п.прокрутитьСуру('конец');
      await стр.waitForTimeout(250);
    }
    await сверитьПоток(стр, п, 2, 1, 'аль-Бакара прокруткой до 2:286');
    п.проверить((await текстыСтраницы(стр)).length === 286, 'вся аль-Бакара (286 аятов) — одной прокруткой, без «следующей страницы»');

    // Владелец 27.11.2026 не нашёл закладку: при чтении панели уехали — нажатие на аят возвращает кнопку закладки.
    await п.прокрутитьСуру(2000);
    await стр.waitForTimeout(150);
    await п.прокрутитьСуру(4000);
    await стр.waitForFunction(() => document.querySelector('[data-testid="сура-кнопки"]')?.getAttribute('aria-hidden') === 'true', null, { timeout: 3000 });
    const видимый = await стр.evaluate(() => {
      const а = [...document.querySelectorAll('[data-ayah]')].find((э) => {
        const р = э.getBoundingClientRect();
        return р.top > 150 && р.bottom < innerHeight - 200;
      });
      а?.click();
      return а?.getAttribute('data-ayah') ?? null;
    });
    // Нажатие на аят мусхафа — лист действий (владелец 27.11.2026); закрыли — выбор и кнопки остаются.
    await п.э('сура-действия').waitFor({ timeout: 3000 });
    п.проверить((await п.текстЭ('действия-заголовок')) === 'Аят ' + видимый, `мусхаф: нажатие на аят ${видимый} → лист действий «Аят ${видимый}»`);
