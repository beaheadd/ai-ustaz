/** WAV PCM 16 бит, моно: синус частоты гц длительностью сек, тихо, с плавными краями. */
function тон(сек, гц, дискр = 8000) {
  const n = Math.round(сек * дискр);
  const б = Buffer.alloc(44 + n * 2);
  б.write('RIFF', 0);
  б.writeUInt32LE(36 + n * 2, 4);
  б.write('WAVEfmt ', 8);
  б.writeUInt32LE(16, 16);
  б.writeUInt16LE(1, 20);
  б.writeUInt16LE(1, 22);
  б.writeUInt32LE(дискр, 24);
  б.writeUInt32LE(дискр * 2, 28);
  б.writeUInt16LE(2, 32);
  б.writeUInt16LE(16, 34);
  б.write('data', 36);
  б.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) {
    const край = Math.min(1, i / 200, (n - i) / 200);
    б.writeInt16LE(Math.round(Math.sin((2 * Math.PI * гц * i) / дискр) * 3000 * край), 44 + i * 2);
  }
  return б;
}

/**
 * Подмена записи источника в чанке приложения: «разрешено: true», дата и условия, база /aiustaz-audio/test, имя
 * «Тестовый тон» — только в этом тесте (настоящий content/audio-sources.json не меняется: там «разрешено: false»).
 */
const ЗАПИСЬ_ИСТОЧНИКА = /кари:\{ru:"[^"]*",kk:"[^"]*",ar:"[^"]*"\},база:"",шаблон:"\{sura3\}\{aya3\}\.mp3",бисмилла:null,разрешено:!1,дата_разрешения:null,условия:null/g;
const ТЕСТОВАЯ_ЗАПИСЬ =
  'кари:{ru:"Тестовый тон",kk:"Тест үні",ar:null},база:"/aiustaz-audio/test",шаблон:"{sura3}{aya3}.mp3",бисмилла:null,разрешено:!0,дата_разрешения:"2026-11-19",условия:"тест e2e: тоны, не Коран"';

async function тестовыйИсточник(контекст, сек = 0.6) {
  const счёт = { чанков: 0, файлов: 0 };
  await контекст.route(/\/_expo\/static\/js\/web\/index-[0-9a-f]+\.js$/, async (маршрут) => {
    const ответ = await маршрут.fetch();
    const тело = (await ответ.text()).replace(ЗАПИСЬ_ИСТОЧНИКА, () => {
      счёт.чанков += 1;
      return ТЕСТОВАЯ_ЗАПИСЬ;
    });
    await маршрут.fulfill({ response: ответ, body: тело });
  });
  await контекст.route(/\/aiustaz-audio\/test\/(\d{3})(\d{3})\.mp3$/, async (маршрут) => {
    const [, с, а] = /(\d{3})(\d{3})\.mp3$/.exec(маршрут.request().url());
    счёт.файлов += 1;
    await маршрут.fulfill({ status: 200, contentType: 'audio/wav', body: тон(сек, 300 + Number(с) + Number(а) * 40) });
  });
  return счёт;
}

