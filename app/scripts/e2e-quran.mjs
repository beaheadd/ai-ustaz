// ───────────────────────── Данные: производные Tanzil из сборки ─────────────────────────

function данныеКорана(папка) {
  const dq = path.join(папка, 'quran');
  const индексФайл = fs.readdirSync(dq).find((ф) => /^index\.[0-9a-f]{20}\.json$/.test(ф));
  const индекс = JSON.parse(fs.readFileSync(path.join(dq, индексФайл), 'utf8'));
  const кэш = new Map();
  const сура = (н) => {
    if (!кэш.has(н)) кэш.set(н, JSON.parse(fs.readFileSync(path.join(папка, индекс.суры[н - 1].файл), 'utf8')));
    return кэш.get(н);
  };
  return { индекс, сура };
}

