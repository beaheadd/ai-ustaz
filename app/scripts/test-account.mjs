тест('нажатия на двух телефонах между синхронизациями не теряются и не удваиваются', () => {
  const с = новыйСервер();
  const а = устройство('aaaaaaaaaaaaaaaaaaaaaaaa', { dhikr: зикры() });
  const б = устройство('bbbbbbbbbbbbbbbbbbbbbbbb', { dhikr: зикры() });
  const нажать = (у, раз) => {
    const з = у.локальное.dhikr.счёт.allah ?? { текущий: 0, всего: 0, день: '2026-11-28' };
    у.локальное.dhikr.счёт.allah = { ...з, текущий: (з.день === '2026-11-28' ? з.текущий : 0) + раз, день: '2026-11-28', всего: з.всего + раз };
  };
  нажать(а, 5);
  синх(а, с, 'dhikr', { сейчас: 1000 });
  синх(б, с, 'dhikr', { сейчас: 1100 });
  assert.equal(сегодня(б.локальное, 'allah'), 5);
  нажать(а, 3);
  нажать(б, 4);
  синх(б, с, 'dhikr', { сейчас: 2000 });
  синх(а, с, 'dhikr', { сейчас: 2100 }); // конфликт версии → повтор со свежей
  синх(б, с, 'dhikr', { сейчас: 2200 });
  for (const у of [а, б]) {
    assert.equal(сегодня(у.локальное, 'allah'), 12);
    assert.equal(у.локальное.dhikr.счёт.allah.всего, 12);
  }
  // Повторы ничего не меняют.
  for (let и = 0; и < 3; и += 1) {
    синх(а, с, 'dhikr', { сейчас: 3000 + и });
    синх(б, с, 'dhikr', { сейчас: 3000 + и });
  }
  assert.equal(сегодня(а.локальное, 'allah'), 12);
  assert.equal(а.локальное.dhikr.счёт.allah.всего, 12);
});
