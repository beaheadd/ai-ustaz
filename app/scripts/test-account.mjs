тест('телефон А прошёл урок 1, телефон Б — урок 2: на обоих оба; лучший — максимум, дни — объединение', () => {
  const с = новыйСервер();
  const а = устройство('aaaaaaaaaaaaaaaaaaaaaaaa', { progress: { ...пустоПрогресс(), уроки: { 1: урок(true, 0.8, 2, '2026-11-27') }, дниЗанятий: ['2026-11-27'], предупреждениеПоказано: true } });
  const б = устройство('bbbbbbbbbbbbbbbbbbbbbbbb', { progress: { ...пустоПрогресс(), уроки: { 1: урок(false, 0.9, 1, '2026-11-28'), 2: урок(true, 1, 1, '2026-11-28') }, дниЗанятий: ['2026-11-28'] } });
  синх(а, с, 'progress', { сейчас: 1000 });
  синх(б, с, 'progress', { сейчас: 2000 });
  синх(а, с, 'progress', { сейчас: 3000 });
  for (const у of [а, б]) {
    const п = у.локальное.progress;
    assert.deepEqual(п.уроки['1'], урок(true, 0.9, 2, '2026-11-28'));
    assert.deepEqual(п.уроки['2'], урок(true, 1, 1, '2026-11-28'));
    assert.deepEqual(п.дниЗанятий, ['2026-11-27', '2026-11-28']);
    assert.equal(п.предупреждениеПоказано, true);
  }
  // Повторная синхронизация без изменений ничего не пишет.
  assert.equal(синх(а, с, 'progress', { сейчас: 4000 }), false);
  assert.equal(синх(б, с, 'progress', { сейчас: 4000 }), false);
});
тест('сброс прогресса на одном телефоне — новая эпоха: другой телефон тоже начинает заново', () => {
  const с = новыйСервер();
  const а = устройство('aaaaaaaaaaaaaaaaaaaaaaaa', { progress: { ...пустоПрогресс(), уроки: { 1: урок(true, 1, 1, '2026-11-27') }, дниЗанятий: ['2026-11-27'] } });
  const б = устройство('bbbbbbbbbbbbbbbbbbbbbbbb', { progress: пустоПрогресс() });
  синх(а, с, 'progress', { сейчас: 1000 });
  синх(б, с, 'progress', { сейчас: 2000 });
  assert.ok(б.локальное.progress.уроки['1']);
  а.локальное.progress = пустоПрогресс(); // «Сбросить прогресс»
  синх(а, с, 'progress', { сейчас: 3000 });
  assert.equal(с.доки.progress.data.эпоха, 3000);
  синх(б, с, 'progress', { сейчас: 4000 });
  assert.deepEqual(б.локальное.progress.уроки, {});
  // После сброса новые уроки снова сливаются.
  б.локальное.progress.уроки['3'] = урок(true, 1, 1, '2026-11-28');
  синх(б, с, 'progress', { сейчас: 5000 });
  синх(а, с, 'progress', { сейчас: 6000 });
  assert.ok(а.локальное.progress.уроки['3']);
});
