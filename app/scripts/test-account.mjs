// ───────────── модель: сервер и устройства ─────────────
function новыйСервер() {
  return { доки: {} }; // ключ → { v, data }
}
function устройство(id, локальное) {
  return { id, локальное: structuredClone(локальное), базы: {} };
}
/** Один проход синхронизации ключа, как в account/sync.ts (с повтором при конфликте). */
function синх(у, сервер, ключ, { сейчас, день = '2026-11-28', изСервера = null } = {}) {
  const к = { сейчас, день, устройство: у.id };
  const там = изСервера ?? сервер.доки[ключ];
  const документТам = там ? м.разобратьДокумент(ключ, structuredClone(там.data)) : null;
  const база = у.базы[ключ] ? м.разобратьДокумент(ключ, structuredClone(у.базы[ключ].data)) : null;
  const л = у.локальное[ключ];
  const здесь =
    ключ === 'progress' ? м.вДокументПрогресса(л, база, сейчас) : ключ === 'dhikr' ? м.вДокументЗикров(л, база, к) : м.вДокументПолей(л, база, сейчас);
  const итог = м.слить(ключ, здесь, документТам);
  у.локальное[ключ] =
    ключ === 'progress' ? м.изДокументаПрогресса(итог) : ключ === 'dhikr' ? м.изДокументаЗикров(итог, л, день) : { ...л, ...м.изДокументаПолей(итог) };
  const записали = !документТам || !м.одинаково(итог, документТам);
  if (записали) {
    // Сравнение версии, как на сервере: запись только поверх той версии, что видели.
    const сейчасНаСервере = сервер.доки[ключ];
    if ((сейчасНаСервере?.v ?? 0) !== (там?.v ?? 0)) return синх(у, сервер, ключ, { сейчас, день, изСервера: сейчасНаСервере });
    сервер.доки[ключ] = { v: (там?.v ?? 0) + 1, data: structuredClone(итог) };
  }
  у.базы[ключ] = { v: сервер.доки[ключ].v, data: structuredClone(итог) };
  return записали;
}

const пустоПрогресс = () => ({ уроки: {}, дниЗанятий: [], онбордингПройден: false, предупреждениеПоказано: false });
const урок = (пройден, лучший, попыток, последний) => ({ пройден, лучший, попыток, последний });
const зикры = (счёт = {}, избранное = []) => ({ счёт, избранное });
const сегодня = (локальное, id, день = '2026-11-28') => (локальное.dhikr.счёт[id]?.день === день ? локальное.dhikr.счёт[id].текущий : 0);

