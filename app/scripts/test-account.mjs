  синх(б, с, 'dhikr', { сейчас: 40 });
  а.локальное.dhikr.счёт.x = { ...(а.локальное.dhikr.счёт.x ?? { текущий: 0, всего: 0, день: '2026-11-28' }), цель: 33 };
